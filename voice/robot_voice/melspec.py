"""Лог-мел спектрограмма — ровно та, которую ждёт энкодер whisper.

Зачем она здесь. Определитель конца реплики (turn_end) построен на энкодере
whisper, и его вход — не звук, а картинка звука:

    вход:  input_features ['s6', 80, 800]

Восемьдесят мел-фильтров на восемьсот кадров. Восемьсот кадров при шаге 160
отсчётов — это ровно восемь секунд на шестнадцати килогерцах.

Подать сюда сырую волну можно, форма даже сойдётся при неудачном стечении
обстоятельств — и сеть будет уверенно отвечать на вопрос о шуме. Это худший
вид поломки: без сообщения об ошибке, с правдоподобными числами.

Считаем сами, без librosa и без torch. Не из гордости: на плате робота лишняя
сотня мегабайт зависимостей ради сорока строк математики — плохая сделка, а
собирается это добро под aarch64 не всегда. Формулы взяты те же, что у
whisper (он берёт фильтры у librosa с настройками по умолчанию), и разложены
здесь явно, чтобы их можно было сверить глазами, а не «доверять пакету».

Точность тут не роскошь. Мел-шкала бывает двух видов — Slaney и HTK, — они
расходятся уже на середине диапазона, и взять не ту значит подать сети
знакомую по форме, но чужую по содержанию картинку. Whisper использует
Slaney, поэтому и здесь Slaney.
"""

from __future__ import annotations

import numpy as np

# Параметры whisper. Менять их нельзя: сеть училась ровно на этих.
ОКНО_БПФ = 400          # 25 мс при 16 кГц
ШАГ = 160               # 10 мс — отсюда «кадр» и берётся
ФИЛЬТРОВ = 80

# Граница, за которой мел-шкала Slaney переходит из линейной в логарифмическую.
_ЛИНЕЙНО_ДО_ГЦ = 1000.0
_ГЦ_НА_МЕЛ = 200.0 / 3.0
_МЕЛ_НА_ГРАНИЦЕ = _ЛИНЕЙНО_ДО_ГЦ / _ГЦ_НА_МЕЛ          # ровно 15.0
_ШАГ_ЛОГА = np.log(6.4) / 27.0


def в_мелы(герцы: np.ndarray) -> np.ndarray:
    """Герцы в мелы по Slaney: до килогерца линейно, дальше логарифмически."""
    герцы = np.asarray(герцы, dtype=np.float64)
    мелы = герцы / _ГЦ_НА_МЕЛ
    высоко = герцы >= _ЛИНЕЙНО_ДО_ГЦ
    if np.any(высоко):
        мелы = np.where(
            высоко,
            _МЕЛ_НА_ГРАНИЦЕ + np.log(np.maximum(герцы, 1e-9) / _ЛИНЕЙНО_ДО_ГЦ)
            / _ШАГ_ЛОГА,
            мелы)
    return мелы


def в_герцы(мелы: np.ndarray) -> np.ndarray:
    """Обратное преобразование. Обязано в точности обращать в_мелы."""
    мелы = np.asarray(мелы, dtype=np.float64)
    герцы = мелы * _ГЦ_НА_МЕЛ
    высоко = мелы >= _МЕЛ_НА_ГРАНИЦЕ
    if np.any(высоко):
        герцы = np.where(
            высоко,
            _ЛИНЕЙНО_ДО_ГЦ * np.exp(_ШАГ_ЛОГА * (мелы - _МЕЛ_НА_ГРАНИЦЕ)),
            герцы)
    return герцы


def фильтры(частота: int = 16000, окно: int = ОКНО_БПФ,
            сколько: int = ФИЛЬТРОВ) -> np.ndarray:
    """Треугольные мел-фильтры, (сколько, окно//2 + 1).

    Каждый фильтр — треугольник, поднимающийся от предыдущей мел-точки к
    своей и спадающий к следующей. Нормировка Slaney: площадь треугольника
    приводится к единице, иначе высокие фильтры, широкие по герцам, дали бы
    вклад во много раз больший низких.
    """
    частоты_бпф = np.fft.rfftfreq(окно, 1.0 / частота)
    точки = в_герцы(np.linspace(в_мелы(0.0), в_мелы(частота / 2.0), сколько + 2))
    ширины = np.diff(точки)
    склоны = точки[:, None] - частоты_бпф[None, :]

    вес = np.zeros((сколько, len(частоты_бпф)), dtype=np.float64)
    for i in range(сколько):
        вверх = -склоны[i] / ширины[i]
        вниз = склоны[i + 2] / ширины[i + 1]
        вес[i] = np.maximum(0.0, np.minimum(вверх, вниз))

    площадь = 2.0 / (точки[2:сколько + 2] - точки[:сколько])
    return (вес * площадь[:, None]).astype(np.float32)


def _окно_ханна(длина: int) -> np.ndarray:
    """Периодическое окно Ханна — такое же, как torch.hann_window по умолчанию.

    Именно ПЕРИОДИЧЕСКОЕ, а не симметричное. Разница в одном отсчёте и в
    делителе, на слух и на глаз незаметна, а спектр смещает — и сеть получит
    не ту картинку, на которой училась.
    """
    n = np.arange(длина, dtype=np.float64)
    return 0.5 - 0.5 * np.cos(2.0 * np.pi * n / длина)


class Спектрограмма:
    """Считает лог-мел один и тот же способ, храня фильтры и окно.

    Класс, а не функция: фильтры считаются заметно дольше самой спектрограммы,
    а меняться им не с чего. Пересчитывать их по десять раз в секунду на
    Cortex-A55 — это отдать процессор ровно тому, ради ускорения чего всё и
    затевалось.
    """

    def __init__(self, частота: int = 16000, фильтров: int = ФИЛЬТРОВ) -> None:
        self.частота = частота
        self.фильтры = фильтры(частота, ОКНО_БПФ, фильтров)
        self.окно = _окно_ханна(ОКНО_БПФ)

    def кадров_для(self, отсчётов: int) -> int:
        return отсчётов // ШАГ

    def отсчётов_для(self, кадров: int) -> int:
        return кадров * ШАГ

    def посчитать(self, звук: np.ndarray, кадров: int) -> np.ndarray:
        """Лог-мел (фильтров, кадров) из звука в отрезке [-1, 1].

        Звук берётся ХВОСТОМ и дополняется тишиной СЛЕВА до нужной длины:
        конец реплики слышен по её концу, и он должен остаться у правого края
        картинки — там же, где был у примеров при обучении.
        """
        надо = self.отсчётов_для(кадров)
        звук = np.asarray(звук, dtype=np.float32).ravel()
        if len(звук) >= надо:
            звук = звук[-надо:]
        else:
            звук = np.pad(звук, (надо - len(звук), 0))

        # Отражающее дополнение по половине окна с каждой стороны — так делает
        # torch.stft с center=True, а whisper зовёт его именно так.
        полу = ОКНО_БПФ // 2
        расширенный = np.pad(звук.astype(np.float64), (полу, полу), mode="reflect")

        нарезка = np.lib.stride_tricks.sliding_window_view(расширенный, ОКНО_БПФ)
        нарезка = нарезка[::ШАГ]
        # Последний кадр whisper отбрасывает: он наполовину состоит из
        # дополнения и настоящего звука почти не содержит.
        нарезка = нарезка[:кадров]
        спектр = np.fft.rfft(нарезка * self.окно, axis=-1)
        мощность = (спектр.real ** 2 + спектр.imag ** 2).T.astype(np.float32)

        мел = self.фильтры @ мощность
        лог = np.log10(np.maximum(мел, 1e-10))
        # Отсекаем всё тише восьмидесяти децибел от самого громкого места и
        # приводим к отрезку около [-1, 1]. Обе строки — из whisper дословно:
        # без них числа уедут на порядки, и сеть увидит другой мир.
        лог = np.maximum(лог, лог.max() - 8.0)
        return ((лог + 4.0) / 4.0).astype(np.float32)
