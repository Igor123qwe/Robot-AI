"""Постоянная карта квартиры: то, что робот знает о доме, а не о минуте.

ЗАЧЕМ ОТДЕЛЬНАЯ КАРТА, когда есть mapping. Разные вопросы — разные карты, и
смешивать их нельзя.

  mapping отвечает «проеду ли я СЕЙЧАС». Шесть метров вокруг робота, и она
  ЗАБЫВАЕТ: половина уверенности уходит за тридцать пять секунд. Так и надо —
  стул унесли, кот ушёл, человек прошёл, и держаться за увиденное минуту назад
  значит объезжать призраков.

  atlas отвечает «как устроена квартира». Стены за сутки не двигаются, и
  забывать их через полминуты — значит каждый раз открывать дом заново. Здесь
  карта копится месяцами и живёт в файле.

Так же устроены и роботы-пылесосы: быстрый слой для объезда прямо сейчас и
постоянный план квартиры, который дорабатывается от уборки к уборке.

ЧТО ДЕЛАЕТ ЭТУ КАРТУ ВОЗМОЖНОЙ. Привязка к ориентирам (landmarks.привязаться).
Без неё карту копить НЕЛЬЗЯ, и это не осторожность, а арифметика: робот
включается носом куда попало, его нынешний ноль не имеет отношения к
вчерашнему, и слитая вслепую карта наложится со сдвигом и поворотом. Две-три
такие поездки — и вместо плана квартиры выйдет каша, из которой уже ничего не
достать. Поэтому вливаем только после того, как робот узнал знакомую мебель и
понял, где стоит.

ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Это не SLAM. Настоящий SLAM правит накопленную ошибку
одометрии по ходу движения и умеет замыкать петли; ему нужен лидар, которого у
нас нет. Здесь ошибка одометрии правится только в момент привязки — когда
робот видит знакомый предмет. Между привязками карта плывёт вместе с
одометрией, и чем дольше поездка, тем сильнее. Поэтому клетка здесь крупнее,
чем у mapping: мельче было бы враньём о точности.
"""

from __future__ import annotations

import json
import logging
import math
import os
import time

import numpy as np

from pathlib import Path

from . import planner

log = logging.getLogger(__name__)

# Сторона клетки. Десять сантиметров, вдвое крупнее, чем у карты объезда, и
# это про честность, а не про экономию. Между привязками карта плывёт вместе с
# одометрией — на метрах пути это сантиметры, — и рисовать её клетками по пять
# сантиметров значило бы обещать точность, которой нет.
КЛЕТКА = 0.10
# Сторона карты в метрах. Двадцать: обычная квартира целиком, с запасом на
# коридор. Двести на двести клеток — это сорок тысяч чисел, меньше двухсот
# килобайт, и такое можно писать на карточку хоть каждую минуту.
СТОРОНА = 20.0
КЛЕТОК = int(СТОРОНА / КЛЕТКА)

# Пределы уверенности в клетке. Копим в логарифмах шансов, как и карта
# объезда: складывать наблюдения тогда можно простым сложением.
ПРЕДЕЛ = 4.0
# Насколько сильно одно наблюдение двигает клетку. Меньше, чем у быстрой
# карты: сюда попадает уже усреднённое, и дёргаться от одного взгляда незачем.
ЗА_ЗАНЯТО = 0.5
ЗА_СВОБОДНО = 0.3
# Выше этого считаем клетку занятой, ниже — свободной.
ПОРОГ = 1.5

# --- поиск неизведанного ----------------------------------------------------
# Сколько неизвестных клеток должно лежать по направлению, чтобы туда стоило
# ехать. Пять, то есть полметра глубины.
#
# Число взято у того же explore_lite: там это min_frontier_size, и стоит он на
# 0.6-0.75 м. Смысл один — не гонять робота через комнату ради щели, которую
# он всё равно закроет одним взглядом с того места, где стоит. Без такого
# порога обход не кончается никогда: неизвестное всегда где-нибудь остаётся,
# хотя бы под диваном.
НОВОГО_ХВАТИТ = 5

# Во сколько неизвестных клеток обходится поворот на радиан.
#
# Шесть. Считается так: луч длиной четыре метра — это сорок клеток, то есть
# потолок находки. Разворот на полкруга (π радиан) должен стоить примерно
# половины этого потолка, иначе робот будет вертеться на месте ради каждой
# лишней клетки: 20 / π ≈ 6.
#
# Отношение получается близким к тому, что стоит у explore_lite (вес дороги
# втрое-впятеро выше веса размера), и это не совпадение — довод тот же.
КЛЕТОК_ЗА_РАДИАН = 6.0

# Насколько широк «плохой» сектор вокруг направления, в котором не проехали.
# Полрадиана, то есть по 30° в каждую сторону: уже — и робот попробует
# соседний луч и упрётся в то же самое; шире — и он выбросит из рассмотрения
# целую четверть круга из-за одного стула.
ЗАБЫТЬ_НАПРАВЛЕНИЕ = 0.5

# Как часто пишем карту на диск. Раз в две минуты: карта большая, карточка не
# бесконечная, а терять при выключении можно самое большее две минуты езды.
ПИСАТЬ_РАЗ_В = 120.0

# Как часто выкладывать план для пульта. Пять секунд: карта квартиры меняется
# медленно, чаще смотреть не на что, а файл на сорок тысяч клеток писать в
# tmpfs десять раз в секунду незачем.
ПОКАЗЫВАТЬ_РАЗ_В = 5.0

# Куда выкладывать план для пульта. /run — память: постоянная карта живёт на
# карточке, а её КАРТИНКА нужна ровно пока открыт пульт.
ФАЙЛ_ПОКАЗА = os.environ.get("ROBOT_FLAT_FILE", "/run/robot-ai/flat.json")
ЗАПАСНОЙ_ФАЙЛ_ПОКАЗА = "~/.robot-ai/flat.json"

# Знаки сжатия — те же три, что у быстрой карты, и читает их тот же код в
# пульте. Своя азбука здесь означала бы вторую реализацию разжатия в браузере.
ЗНАКИ = {0: " ", 1: "#", -1: "."}

# Отсюда следует, сколько раз клетку надо увидеть, чтобы поверить: порог,
# делённый на вес одного наблюдения, — три взгляда на занятое и пять на
# свободное. А чтобы СТЕРЕТЬ с карты убранный шкаф, надо проехать сквозь него
# девять раз: столько набирается от предела уверенности до порога. Это долго
# нарочно — стена, мимо которой робот просто давно не ездил, стираться не
# должна. Одного взгляда мало намеренно: дальномер промахивается, а
# ошибка, попавшая в ПОСТОЯННУЮ карту, останется там навсегда — в отличие от
# быстрой, где она растает за полминуты.
#
# Свободное подтверждается дольше занятого, и это не описка. Ошибиться,
# записав стену там, где её нет, — значит объезжать пустоту; ошибиться,
# записав пустоту там, где стена, — значит в неё поехать.


class Атлас:
    """План квартиры, который копится месяцами.

    Не забывает по времени вовсе. Забывание здесь было бы вредно: стена,
    которую робот не видел неделю, никуда не делась — он просто туда не
    заезжал. А то, что действительно изменилось (переставили шкаф), исправится
    само: новые наблюдения сдвинут клетки в другую сторону, потому что
    свободное пространство тоже записывается.
    """

    def __init__(self, файл=None, клеток: int = КЛЕТОК,
                 клетка: float = КЛЕТКА, часы=time.monotonic) -> None:
        self.файл = файл
        self.клеток = клеток
        self.клетка = клетка
        self._часы = часы
        self.сетка = np.zeros((клеток, клеток), dtype=np.float32)
        # Ноль карты — в её середине. Карта НЕ едет за роботом, в отличие от
        # быстрой: она про квартиру, а не про робота, и середина у неё там,
        # где робот впервые привязался.
        self.середина = клеток // 2
        self.влито = 0
        self.поездок = 0
        self._писали = 0.0
        self._показано = 0.0
        self._не_выложил = False
        if файл:
            self.загрузить()

    # --- служебное -------------------------------------------------------
    def _в_клетки(self, x: float, y: float):
        return (int(round(x / self.клетка)) + self.середина,
                int(round(y / self.клетка)) + self.середина)

    def _в_метры(self, кx: int, кy: int):
        return ((кx - self.середина) * self.клетка,
                (кy - self.середина) * self.клетка)

    def _внутри(self, кx: int, кy: int) -> bool:
        return 0 <= кx < self.клеток and 0 <= кy < self.клеток

    # --- накопление ------------------------------------------------------
    def отметить(self, x: float, y: float, занято: bool) -> None:
        """Одна клетка: тут стена или тут проехали."""
        кx, кy = self._в_клетки(x, y)
        if not self._внутри(кx, кy):
            return
        шаг = ЗА_ЗАНЯТО if занято else -ЗА_СВОБОДНО
        self.сетка[кy, кx] = float(
            np.clip(self.сетка[кy, кx] + шаг, -ПРЕДЕЛ, ПРЕДЕЛ))

    def влить(self, быстрая, привязан: bool = True) -> int:
        """Перенести накопленное быстрой картой. Отдаёт число клеток.

        `привязан` — знает ли робот, где он относительно этой карты. Ложь —
        не вливаем ВОВСЕ и молчим об этом только в журнале. Слитая вслепую
        карта наложится со сдвигом и поворотом, и две-три поездки превратят
        план квартиры в кашу, из которой уже ничего не достать. Отказ копить
        обратим, испорченная карта — нет.
        """
        if not привязан:
            log.debug("атлас: не привязан — не вливаю")
            return 0
        занятые = getattr(быстрая, "занятые_вокруг", None)
        if занятые is None:
            return 0
        поза = getattr(быстрая, "поза", None)
        if поза_плоха(поза):
            return 0
        рx, рy, курс = поза
        cos, sin = math.cos(курс), math.sin(курс)
        сколько = 0
        try:
            точки = list(занятые(быстрая.клеток * быстрая.клетка / 2))
        except Exception:                       # noqa: BLE001
            log.debug("атлас: быстрая карта не отдала занятые", exc_info=True)
            return 0
        for вперёд, вбок in точки:
            # Точки приходят в системе робота — переводим в мировую.
            x = рx + cos * вперёд - sin * вбок
            y = рy + sin * вперёд + cos * вбок
            self.отметить(x, y, True)
            сколько += 1
        # Под самим роботом заведомо свободно: он там стоит. Это важнее, чем
        # кажется, — без записи свободного карта умеет только зарастать, и
        # унесённый шкаф остался бы на ней навсегда.
        self.отметить(рx, рy, False)
        self.влито += сколько
        return сколько

    def проехали(self, x: float, y: float) -> None:
        """Робот тут проехал — значит тут свободно."""
        self.отметить(x, y, False)

    # --- чтение ----------------------------------------------------------
    def занято(self, x: float, y: float) -> bool:
        кx, кy = self._в_клетки(x, y)
        if not self._внутри(кx, кy):
            return False
        return bool(self.сетка[кy, кx] >= ПОРОГ)

    def занятые_вокруг(self, x: float, y: float, курс: float,
                       дальше: float = 2.0):
        """Занятые клетки рядом — в системе робота, как у быстрой карты.

        Отдаём в том же виде, что и mapping.занятые_вокруг: (вперёд, вбок).
        Так планировщику всё равно, откуда пришло препятствие, и не нужно
        учить его второму способу читать карту.
        """
        готово = []
        радиус = int(дальше / self.клетка)
        цx, цy = self._в_клетки(x, y)
        cos, sin = math.cos(-курс), math.sin(-курс)
        for кy in range(max(0, цy - радиус), min(self.клеток, цy + радиус + 1)):
            for кx in range(max(0, цx - радиус),
                            min(self.клеток, цx + радиус + 1)):
                if self.сетка[кy, кx] < ПОРОГ:
                    continue
                мx, мy = self._в_метры(кx, кy)
                дx, дy = мx - x, мy - y
                if math.hypot(дx, дy) > дальше:
                    continue
                готово.append((дx * cos - дy * sin, дx * sin + дy * cos))
        return готово

    def куда_неизвестно(self, поза, дальше: float = 4.0,
                        лучей: int = 24,
                        избегать=()) -> tuple[float, int] | None:
        """Куда ехать, чтобы увидеть новое: (курс в мире, сколько клеток).

        None — вокруг всё известно или позы нет.

        ЧТО ЭТО ТАКОЕ. Настоящие обследователи строят границу известного
        («фронтир») и планируют путь к ближайшей её точке. Планировать путь
        нам нечем: без лидара и SLAM глобального планировщика в этом роботе
        нет и не будет, а reactive-объезд по дороге всё равно уведёт с любой
        нарисованной линии.

        Поэтому выбираем НЕ ПУТЬ, А НАПРАВЛЕНИЕ — единственное, что робот
        способен честно выдержать. Из своей клетки пускаем лучи по кругу и
        считаем вдоль каждого неизвестные клетки, обрывая луч о первую
        занятую: за стену робот не поедет, и обещать себе тамошнюю новизну
        нечестно.

        Ничью решаем в пользу нынешнего курса. На пустой карте неизвестно
        одинаково во все стороны, и без этого правила робот выбирал бы первый
        луч по списку — то есть всегда одну и ту же сторону света, независимо
        от того, куда смотрит.
        """
        if поза_плоха(поза):
            return None
        рx, рy, курс = поза
        шаг = self.клетка
        шагов = max(1, int(дальше / шаг))
        лучшее = None
        for i in range(лучей):
            угол = курс + (i / лучей) * 2 * math.pi
            # НАПРАВЛЕНИЯ, В КОТОРЫХ УЖЕ НЕ ВЫШЛО, НЕ ПРЕДЛАГАЕМ СНОВА.
            #
            # Без этого получается вот что: карта говорит «неизвестного
            # больше всего вон там», робот доворачивается, упирается в то,
            # чего карта не знает (стул, порог, косяк), возвращается ни с чем
            # — и карта, ничего не узнав, советует ТО ЖЕ САМОЕ. Робот ходит по
            # кругу, пока не кончится время.
            #
            # У explore_lite для этого чёрный список фронтиров, до которых не
            # доехали за progress_timeout. Здесь то же самое, только в углах.
            if any(abs((угол - плохой + math.pi) % (2 * math.pi) - math.pi)
                   < ЗАБЫТЬ_НАПРАВЛЕНИЕ for плохой in избегать):
                continue
            cos, sin = math.cos(угол), math.sin(угол)
            новых = self._вдоль(рx, рy, cos, sin, шаг, шагов)
            if новых < НОВОГО_ХВАТИТ:
                continue
            # ЦЕНА ДОРОГИ ВАЖНЕЕ РАЗМЕРА НАХОДКИ — так считают все, и это
            # видно по их числам. У explore_lite, самой ходовой реализации
            # фронтира в ROS, вес расстояния 3-5, а вес размера 1.0: робот
            # предпочтёт близкий маленький фронтир далёкому большому.
            #
            # Довод не в экономии, а в том, что ошибка накапливается по пути.
            # Дорога до дальнего фронтира — это метры одометрии без привязки,
            # и приехав, робот уже не вполне знает, где он. Ближний фронтир
            # даёт то же знание дешевле и точнее.
            #
            # У нас «расстояние» — это отворот: пути мы не планируем, а
            # платим поворотом на месте и трясём им ту самую одометрию.
            отворот = abs((угол - курс + math.pi) % (2 * math.pi) - math.pi)
            оценка = новых - отворот * КЛЕТОК_ЗА_РАДИАН
            if лучшее is None or оценка > лучшее[0]:
                лучшее = (оценка, угол, новых)
        if лучшее is None:
            return None
        _, угол, новых = лучшее
        return (угол + math.pi) % (2 * math.pi) - math.pi, новых

    def _вдоль(self, рx, рy, cos, sin, шаг, шагов) -> int:
        """Сколько неизвестных клеток по этому направлению. Ноль — некуда.

        Смотрим ТРЕМЯ параллельными лучами по ширине корпуса, а не одним, и
        это не украшение. Луч в одну клетку — линия нулевой толщины: он
        проскакивает между двумя стульями там, где робот не пролезет, и
        одинаково легко находит «новое» в щели за шкафом. Робот поедет туда,
        упрётся и объявит тупик — а на карте место так и останется
        неизвестным, потому что заглянуть в него было нечем.

        Три луча по полуширине корпуса дают ровно тот вопрос, который нужен:
        «влезу ли я туда целиком». Первая занятая клетка ЛЮБОГО из трёх
        обрывает направление целиком, а не свой луч: занятая клетка сбоку —
        это стена, в которую упрётся плечо.
        """
        # Перпендикуляр к направлению — вдоль него и разносим лучи.
        пx, пy = -sin, cos
        # Полуширину берём у планировщика, а не заводим свою: габарит робота
        # обязан жить в одном месте, иначе однажды разъедутся тот, по
        # которому робот проверяет дугу, и тот, по которому выбирает, куда
        # ехать вообще, — и он поедет туда, куда сам себя потом не пустит.
        полуширина = planner.ПОЛУШИРИНА + planner.ЗАПАС
        новых = 0
        живы = [True, True, True]
        for н in range(1, шагов + 1):
            вперёд = н * шаг
            for л, отступ in enumerate((0.0, полуширина, -полуширина)):
                if not живы[л]:
                    continue
                кx, кy = self._в_клетки(рx + cos * вперёд + пx * отступ,
                                        рy + sin * вперёд + пy * отступ)
                if not self._внутри(кx, кy):
                    живы[л] = False
                    continue
                значение = self.сетка[кy, кx]
                if значение >= ПОРОГ:
                    # Стена по любому из лучей — дальше корпус не пройдёт.
                    return новых
                if abs(значение) < ПОРОГ and not л:
                    # Считаем новизну только по среднему лучу: боковые нужны
                    # для «влезу ли», и складывать их значило бы втрое
                    # завышать награду за широкие коридоры.
                    новых += 1
            if not any(живы):
                break
        return новых

    def сколько_знаю(self) -> dict:
        """Насколько карта заполнена. Для человека и для журнала."""
        занято = int((self.сетка >= ПОРОГ).sum())
        свободно = int((self.сетка <= -ПОРОГ).sum())
        клеток = self.клеток * self.клеток
        return {"занято": занято, "свободно": свободно,
                "известно": занято + свободно,
                "доля": round((занято + свободно) / клеток, 4),
                "метров": round((занято + свободно) * self.клетка ** 2, 1),
                "поездок": self.поездок}

    # --- хранение --------------------------------------------------------
    def сохранить(self, принудительно: bool = False) -> bool:
        """Записать карту. Раз в две минуты, если не просят иначе.

        Пишем через временный файл и переименование: выдернутое посреди
        записи питание оставит на месте целую прошлую карту, а не половину
        новой. Для карты, которая копится месяцами, это не мелочь.
        """
        if not self.файл:
            return False
        сейчас = self._часы()
        if not принудительно and сейчас - self._писали < ПИСАТЬ_РАЗ_В:
            return False
        self._писали = сейчас
        try:
            os.makedirs(os.path.dirname(str(self.файл)) or ".", exist_ok=True)
            врем = f"{self.файл}.новый"
            # Пишем только ненулевые клетки. Карта квартиры заполнена на
            # проценты, и хранить сорок тысяч нулей ради двух тысяч чисел
            # незачем — да и читается такой файл глазами.
            клетки = np.nonzero(self.сетка)
            данные = {
                "клетка": self.клетка, "клеток": self.клеток,
                "середина": self.середина, "поездок": self.поездок,
                "когда": time.time(),
                "точки": [[int(кx), int(кy), round(float(self.сетка[кy, кx]), 2)]
                          for кy, кx in zip(*клетки)],
            }
            with open(врем, "w", encoding="utf-8") as f:
                json.dump(данные, f, ensure_ascii=False)
            os.replace(врем, self.файл)
            return True
        except OSError:
            log.debug("атлас: не смог сохранить", exc_info=True)
            return False

    def загрузить(self) -> bool:
        try:
            with open(self.файл, encoding="utf-8") as f:
                данные = json.load(f)
        except (OSError, ValueError):
            return False
        if not isinstance(данные, dict):
            return False
        # Размер клетки мог поменяться между версиями. Пересчитывать старую
        # карту под новую сетку — это размазать её по соседям и испортить;
        # честнее начать заново и сказать об этом.
        if abs(float(данные.get("клетка") or 0) - self.клетка) > 1e-6:
            log.info("атлас: карта записана другой клеткой — начинаю заново")
            return False
        if int(данные.get("клеток") or 0) != self.клеток:
            log.info("атлас: карта другого размера — начинаю заново")
            return False
        self.середина = int(данные.get("середина") or self.клеток // 2)
        self.поездок = int(данные.get("поездок") or 0)
        for точка in данные.get("точки") or []:
            try:
                кx, кy, вес = int(точка[0]), int(точка[1]), float(точка[2])
            except (TypeError, ValueError, IndexError):
                continue
            if self._внутри(кx, кy):
                self.сетка[кy, кx] = вес
        сколько = self.сколько_знаю()
        log.info("атлас: помню %d клеток квартиры (%.1f м²) за %d поездок",
                 сколько["известно"], сколько["метров"], self.поездок)
        return True

    def для_пульта(self) -> dict:
        """Карта для показа. Только известное, строками «x y вес»."""
        клетки = np.nonzero(np.abs(self.сетка) >= ПОРОГ)
        return {
            "клетка": self.клетка, "клеток": self.клеток,
            "середина": self.середина,
            "точки": [[int(кx), int(кy),
                       1 if self.сетка[кy, кx] >= ПОРОГ else 0]
                      for кy, кx in zip(*клетки)],
        }

    def выложить(self, файл, не_чаще: float = ПОКАЗЫВАТЬ_РАЗ_В,
                 поза=None, почему: str = "") -> bool:
        """План квартиры — в файл, чтобы его видел пульт. True — записали.

        ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, если карта и так лежит на диске. Затем, что на
        диске она лежит в своём формате и вперемешку со служебным, а пульт
        живёт в другом процессе, и знание формата в нём — это вторая копия
        формата. Такая копия у нас уже была (порог стопа) и разошлась при
        первой же правке.

        И ЗАЧЕМ ВООБЩЕ. До сих пор постоянная карта не показывалась нигде.
        Игорь смотрел на панель «карта вокруг» — а та ЗАБЫВЧИВА по замыслу,
        половина стирается за тридцать пять секунд, — и видел ровно то, на что
        пожаловался: «карту не сохраняет, каждый раз заново рисует». Карта,
        которую нельзя увидеть, неотличима от несуществующей.

        `почему` — если не копим, то по какой причине; пульт покажет это
        словами. Молча пустая панель хуже: она читается как поломка.
        """
        сейчас = self._часы()
        if сейчас - self._показано < не_чаще:
            return False
        self._показано = сейчас
        # Сжимаем так же, как быстрая карта: три знака со счётчиками повторов.
        # Двести на двести — сорок тысяч клеток, списком чисел это сотня
        # килобайт на кадр; пустая карта укладывается в один кусок.
        знаки = np.zeros_like(self.сетка, dtype=np.int8)
        знаки[self.сетка >= ПОРОГ] = 1
        знаки[self.сетка <= -ПОРОГ] = -1
        плоско = знаки.ravel()
        границы = np.flatnonzero(np.diff(плоско)) + 1
        начала = np.concatenate(([0], границы))
        длины = np.diff(np.concatenate((начала, [плоско.size])))
        строка = "".join(f"{д}{ЗНАКИ[int(плоско[н])]}"
                         for н, д in zip(начала, длины))
        сколько = self.сколько_знаю()
        try:
            файл = Path(файл)
            файл.parent.mkdir(parents=True, exist_ok=True)
            врем = файл.with_name(файл.name + ".tmp")
            врем.write_text(json.dumps({
                "когда": time.time(),
                "клетка": self.клетка,
                "клеток": self.клеток,
                "середина": self.середина,
                "клетки": строка,
                "поза": list(поза) if поза else None,
                "влито": self.влито,
                "поездок": self.поездок,
                "известно": сколько["известно"],
                "метров": round(сколько["метров"], 1),
                "копим": not почему,
                "почему": почему,
            }, ensure_ascii=False))
            врем.replace(файл)
            return True
        except OSError as e:
            if not self._не_выложил:
                self._не_выложил = True
                log.warning("атлас: план не пишется в %s (%s) — "
                            "пульт его не увидит", файл, e)
            return False


def поза_плоха(поза) -> bool:
    """Годится ли поза для счёта. То же имя, что в landmarks, тот же смысл."""
    if поза is None:
        return True
    try:
        return len(поза) < 3
    except TypeError:
        return True
