# Сторона клетки. Десять сантиметров, вдвое крупнее, чем у карты объезда, и
# это про честность, а не про экономию. Между привязками карта плывёт вместе с
# одометрией — на метрах пути это сантиметры, — и рисовать её клетками по пять
# сантиметров значило бы обещать точность, которой нет.
КЛЕТКА = 0.10
# Сторона карты в метрах. Двадцать: обычная квартира целиком, с запасом на
# коридор. Двести на двести клеток — это сорок тысяч чисел, меньше двухсот
# килобайт, и такое можно писать на карточку хоть каждую минуту.
СТОРОНА = 20.0
КЛЕТОК = int(СТОРОНА / КЛЕТКА)

# Пределы уверенности в клетке. Копим в логарифмах шансов, как и карта
# объезда: складывать наблюдения тогда можно простым сложением.
ПРЕДЕЛ = 4.0
# Насколько сильно одно наблюдение двигает клетку. Меньше, чем у быстрой
# карты: сюда попадает уже усреднённое, и дёргаться от одного взгляда незачем.
ЗА_ЗАНЯТО = 0.5
ЗА_СВОБОДНО = 0.3
# Выше этого считаем клетку занятой, ниже — свободной.
ПОРОГ = 1.5

# --- схема: стены прямыми, а не крапом --------------------------------------
# Игорь, посмотрев на план: «карта лучше не стала, зелёная зона появилась, но
# нечитаемо — пусть он прям схему рисует, он же видит».
#
# И он прав про причину. Занятые клетки — это КРАП: каждая стена рисуется
# ломаной ниткой из точек, сбитой шумом дальномера и дрожанием курса, а между
# нитками висят одиночные выбросы. Тысяча таких точек в кадре 200×200 не
# складывается глазом в квартиру, сколько на неё ни смотри. Человек узнаёт
# своё жильё по ЛИНИЯМ: вот стена четыре метра, вот проём, вот угол.
#
# ЧТО ДЕЛАЮТ ДРУГИЕ. Извлечение отрезков из занятой сетки — классика (split
# and merge, RANSAC по точкам, преобразование Хафа). Все три ищут прямые в
# произвольном направлении и потому тратят силы на то, чего у нас нет.
#
# У НАС ЕСТЬ БОЛЬШЕЕ, и грех этим не воспользоваться: компас уже посчитал, НА
# СКОЛЬКО ПОВЁРНУТ ДОМ. В жилом доме стены сходятся под прямым углом, значит в
# повороте дома они ОСЕВЫЕ — и вместо поиска произвольных прямых достаточно
# посчитать сплошные ряды занятых клеток по строкам и по столбцам. Это точнее
# (направление не выводится из шумных точек, а известно), в разы дешевле и
# гораздо устойчивее на коротких кусках, где Хафу не за что зацепиться.
#
# Дом не известен — рисуем в осях карты. Хуже, но не отказ: квартиры чаще
# всего и так стоят почти по осям.
#
# Короче этого — не стена, а мебель или выброс. Шестьдесят сантиметров: стена
# короче не бывает, а тумбочка бывает.
СТЕНА_ОТ_МЕТРОВ = 0.6
# Пропуск, который сшиваем. Двадцать сантиметров: столько дальномер теряет на
# тёмном плинтусе или на косом луче. Дверной проём — восемьдесят, и он
# уцелеет: проёмы на схеме нужны, без них квартира выйдет глухой коробкой.
ДЫРА_В_СТЕНЕ = 0.2
# Насколько толстой бывает нарисованная стена. Настоящая — двенадцать
# сантиметров, но пеленг гуляет, и одна и та же стена ложится в две-три
# соседние строки. Их надо слить в один отрезок, иначе схема выйдет из
# двойных линий — это ничем не лучше крапа.
СТЕНА_ТОЛЩЕ_НЕ_БЫВАЕТ = 0.4


def _полосы(значения, минимум: int, дыра: int):
    """Сплошные куски в списке индексов. [(от, до), ...] по возрастанию."""
    подряд = sorted(set(значения))
    if not подряд:
        return []
    куски = []
    начало = прошлое = подряд[0]
    for з in подряд[1:]:
        if з - прошлое > дыра + 1:
            if прошлое - начало + 1 >= минимум:
                куски.append((начало, прошлое))
            начало = з
        прошлое = з
    if прошлое - начало + 1 >= минимум:
        куски.append((начало, прошлое))
    return куски


def _слить(куски, толщина: int):
    """Слить куски из соседних рядов в один: стена одна, а рядов у неё три.

    Соседними считаем те, что и лежат рядом (ближе `толщина` рядов), и
    ПЕРЕКРЫВАЮТСЯ вдоль. Без второго условия схема сшила бы в одну линию
    противоположные стены узкого коридора.
    """
    вышло = []
    for ряд, от, до in sorted(куски):
        for номер, (р, о, д) in enumerate(вышло):
            if abs(ряд - р) <= толщина and от <= д and о <= до:
                вышло[номер] = ((р * (д - о + 1) + ряд * (до - от + 1))
                                / max(1, (д - о + 1) + (до - от + 1)),
                                min(о, от), max(д, до))
                break
        else:
            вышло.append((float(ряд), от, до))
    return вышло


def стены(сетка, клетка: float = КЛЕТКА, середина: int = 0,
          поворот: float = 0.0, порог: float = ПОРОГ):
    """Занятые клетки → отрезки стен в метрах: [[x1, y1, x2, y2], ...].

    Считается в повороте дома (см. шапку выше), отдаётся в осях карты — там
    же, где живут поза и пометки, чтобы пульту не пришлось знать про компас.
    """
    занято = np.nonzero(сетка >= порог)
    if len(занято[0]) < 2:
        return []
    x = (занято[1].astype(float) - середина) * клетка
    y = (занято[0].astype(float) - середина) * клетка
    в_дом, из_дома = math.cos(поворот), math.sin(поворот)
    # В дом — поворотом на минус угол, обратно — на плюс.
    хд = x * в_дом + y * из_дома
    уд = -x * из_дома + y * в_дом
    иx = np.round(хд / клетка).astype(int).tolist()
    иy = np.round(уд / клетка).astype(int).tolist()

    минимум = max(2, int(round(СТЕНА_ОТ_МЕТРОВ / клетка)))
    дыра = max(0, int(round(ДЫРА_В_СТЕНЕ / клетка)))
    толщина = max(1, int(round(СТЕНА_ТОЛЩЕ_НЕ_БЫВАЕТ / клетка)))

    по_рядам: dict[int, list[int]] = {}
    по_столбцам: dict[int, list[int]] = {}
    for а, б in zip(иx, иy):
        по_рядам.setdefault(б, []).append(а)
        по_столбцам.setdefault(а, []).append(б)

    вдоль_x = [(ряд, от, до) for ряд, где in по_рядам.items()
               for от, до in _полосы(где, минимум, дыра)]
    вдоль_y = [(стб, от, до) for стб, где in по_столбцам.items()
               for от, до in _полосы(где, минимум, дыра)]

    отрезки = []
    for ряд, от, до in _слить(вдоль_x, толщина):
        отрезки.append(((от * клетка, ряд * клетка),
                        (до * клетка, ряд * клетка)))
    for стб, от, до in _слить(вдоль_y, толщина):
        отрезки.append(((стб * клетка, от * клетка),
                        (стб * клетка, до * клетка)))

    наружу = []
    for (х1, у1), (х2, у2) in отрезки:
        наружу.append([round(х1 * в_дом - у1 * из_дома, 3),
                       round(х1 * из_дома + у1 * в_дом, 3),
                       round(х2 * в_дом - у2 * из_дома, 3),
                       round(х2 * из_дома + у2 * в_дом, 3)])
    return наружу

# --- поиск неизведанного ----------------------------------------------------
# Сколько неизвестных клеток должно лежать по направлению, чтобы туда стоило
# ехать. Пять, то есть полметра глубины.
#
# Число взято у того же explore_lite: там это min_frontier_size, и стоит он на
# 0.6-0.75 м. Смысл один — не гонять робота через комнату ради щели, которую
# он всё равно закроет одним взглядом с того места, где стоит. Без такого
# порога обход не кончается никогда: неизвестное всегда где-нибудь остаётся,
# хотя бы под диваном.
НОВОГО_ХВАТИТ = 5

# Во сколько неизвестных клеток обходится поворот на радиан.
#
# Двенадцать, и было шесть. Считается так: луч длиной восемь метров — это
# восемьдесят клеток, то есть потолок находки. Разворот на полкруга (π радиан)
# должен стоить примерно половины этого потолка, иначе робот будет вертеться
# на месте ради каждой лишней клетки: 40 / π ≈ 12.
#
# Число привязано к ГОРИЗОНТУ (см. ГОРИЗОНТ ниже) и меняется вместе с ним: это
# доля потолка находки, а не самостоятельная величина. Когда горизонт был
# четыре метра, здесь стояло шесть — по той же формуле.
#
# Отношение получается близким к тому, что стоит у explore_lite (вес дороги
# втрое-впятеро выше веса размера), и это не совпадение — довод тот же.
КЛЕТОК_ЗА_РАДИАН = 12.0

# Насколько далеко заглядываем, выбирая направление.
#
# ВОСЕМЬ МЕТРОВ, И ЭТО ГЛАВНОЕ ЧИСЛО ОБХОДА. Было четыре, и четырёх не хватало
# по устройству, а не по невезению.
#
# Считается так. Быстрая карта вокруг робота — шесть метров стороной
# (mapping.СТОРОНА), и `влить` переливает в план ВСЮ её свободу разом, кругом
# радиусом три метра (mapping.свободные_вокруг). Заливка идёт с каждым кадром
# дальномера, десять раз в секунду: через полсекунды после приезда всё в трёх
# метрах вокруг робота на плане уже ИЗВЕСТНО.
#
# Значит луч длиной четыре метра мог найти неизвестное только на последнем
# метре — десять клеток, из которых стена съедала половину. А порог, ниже
# которого направление не рассматривается вовсе, стоит на пяти клетках
# (НОВОГО_ХВАТИТ). Робот оказывался в положении, где почти каждое направление
# «уже известно»: в живом журнале это и вышло — «неизвестного больше всего в
# 0° (6 клеток)», а тремя остановками позже «карта полна» посреди
# необследованной квартиры.
#
# Восемь метров дают пять метров запаса за краем залитой области — комнату
# средней руки целиком. Дальше восьми смысла нет: план держит двадцать метров
# стороной, и луч длиннее половины стороны начнёт упираться в край карты.
ГОРИЗОНТ = 8.0

# --- фронтир: граница известного --------------------------------------------
# Клетка фронтира — СВОБОДНАЯ клетка, у которой есть неизвестный сосед. Это и
# есть край изведанного: доехать туда можно (клетка свободна), а за ней
# начинается то, чего робот не видел.
#
# ЧЕМ ЭТО ЛУЧШЕ ЛУЧЕЙ ИЗ-ПОД РОБОТА, которыми мы искали новое раньше. Лучи
# отвечают на вопрос «что мне отсюда ВИДНО», а фронтир — на вопрос «где вообще
# осталось неизведанное». Разница решает судьбу дверного проёма.
#
# Проём в девяносто сантиметров с трёх метров занимает градусов двадцать пять.
# Лучей мы пускали двадцать четыре, то есть через пятнадцать градусов, и в
# проём попадал один, много два. А направление считается проезжим, только если
# СВОБОДНЫ ВСЕ ТРИ параллельных луча по ширине корпуса, — стоило лучу пройти
# наискось, боковой цеплял косяк и убивал направление целиком.
#
# Выходило, что робот находил дверь, только если стоял к ней почти носом.
# В остальных случаях соседняя комната для него не существовала: неизвестное
# там было, а увидеть его было нечем. Ровно это Игорь и увидел на живом
# роботе — «обошёл он пол комнаты».
#
# Фронтир этой беды не знает: клетки у проёма становятся свободными, как
# только робот один раз мазнул по ним дальномером с любого угла, и дальше они
# лежат на карте и ждут. Так ищут все — Yamauchi (1997), explore_lite, m-explore
# и всё, что выросло из них.
#
# Сколько клеток должно быть в скоплении, чтобы за ним стоило ехать. Шесть при
# клетке в десять сантиметров — это шестьдесят сантиметров границы, то есть
# ровно min_frontier_size у explore_lite (0.6-0.75 м). Смысл тот же: не гонять
# робота через квартиру ради щели под диваном, которую он всё равно не
# откроет. Без такого порога обход не кончается никогда.
ФРОНТИР_ОТ = 6


# Цена шага волны: прямо десять, наискось четырнадцать.
#
# НЕ ЕДИНИЦА НА ЛЮБОЙ ШАГ, и это не украшение. Первая редакция ходила по
# четырём соседям с ценой единица — то есть мерила путь ПО-МАНХЭТТЕНСКИ,
# кварталами. У такого поля вся «лесенка» между двумя точками равноценна, и
# направление на ближайшее неизведанное выходило кратным сорока пяти
# градусам: робот в углу комнаты, которому до двери шестнадцать градусов,
# получал сорок пять и ехал в стену.
#
# Четырнадцать — это десять на корень из двух, округлённое. Тем же приёмом
# считает hector_exploration_planner (у него 100 и 141). Поле после этого
# приближает настоящее расстояние, и направление получается честным.
#
# Сами смещения живут в теле волны: она ходит по ПЛОСКОМУ списку, и шаг там
# — это сдвиг индекса, зависящий от стороны карты. Держать его снаружи
# значило бы считать сторону дважды.
ЦЕНА_КЛЕТКИ = 10

# Чем помечена клетка, до которой волна не дошла: за стеной, в щели, куда не
# влезет корпус, или в отрезанной части квартиры. Большое число, а не минус
# единица, потому что волна сравнивает «стало < было» и ищет минимум.
НЕДОСТУПНО = np.iinfo(np.int32).max

# Насколько далеко вперёд по полю смотрим, выбирая курс, — «морковка».
#
# Метр. Это меньше дальности дальномера (два метра), и в этом весь смысл:
# точка, на которую робот правит, обязана лежать в пределах того, что он
# ВИДИТ. Тогда объезжающий планировщик работает внутри морковки, а не поперёк
# всего пути, и сойти с маршрута не может: на следующем шаге морковка
# пересчитается из новой позы и снова потянет туда же.
#
# Ближе брать нельзя: у клетки восемь соседей, то есть шаг поля задаёт курс с
# точностью до сорока пяти градусов и дёргается от клетки к клетке.
МОРКОВКА = 1.0

# Насколько далеко искать своё место на поле, если под роботом значения нет.
# Полметра: пол под ним мог не набрать шести наблюдений, или он подъехал к
# стене ближе полуширины корпуса. Дальше искать незачем — это уже не «я тут».
ОГЛЯДЕТЬСЯ = 0.5

# Сколько соседей неизвестной клетки должны быть тоже неизвестны, чтобы счесть
# её неизведанной землёй, а не дыркой в измерениях. Три из четырёх — разбор
# в фронтиры().
СОСЕДЕЙ_У_НЕИЗВЕДАННОГО = 3

# Насколько широк «плохой» сектор вокруг направления, в котором не проехали.
# Полрадиана, то есть по 30° в каждую сторону: уже — и робот попробует
# соседний луч и упрётся в то же самое; шире — и он выбросит из рассмотрения
# целую четверть круга из-за одного стула.
ЗАБЫТЬ_НАПРАВЛЕНИЕ = 0.5

# Как часто пишем карту на диск. Раз в две минуты: карта большая, карточка не
# бесконечная, а терять при выключении можно самое большее две минуты езды.
ПИСАТЬ_РАЗ_В = 120.0

# Как часто жалуемся в журнал на то, что копить нечего, потому что не
# привязаны. Раз в минуту: заливка идёт десять раз в секунду, и жалоба на
# каждый кадр утопила бы собой весь остальной разбор — ровно то, от чего уже
# страдает журнал шасси.
ЖАЛУЕМСЯ_РАЗ_В = 60.0

# Как часто выкладывать план для пульта. Пять секунд: карта квартиры меняется
# медленно, чаще смотреть не на что, а файл на сорок тысяч клеток писать в
# tmpfs десять раз в секунду незачем.
ПОКАЗЫВАТЬ_РАЗ_В = 5.0

# Куда выкладывать план для пульта. /run — память: постоянная карта живёт на
# карточке, а её КАРТИНКА нужна ровно пока открыт пульт.
ФАЙЛ_ПОКАЗА = os.environ.get("ROBOT_FLAT_FILE", "/run/robot-ai/flat.json")
ЗАПАСНОЙ_ФАЙЛ_ПОКАЗА = "~/.robot-ai/flat.json"

# Знаки сжатия — те же три, что у быстрой карты, и читает их тот же код в
# пульте. Своя азбука здесь означала бы вторую реализацию разжатия в браузере.
ЗНАКИ = {0: " ", 1: "#", -1: "."}

# Отсюда следует, сколько раз клетку надо увидеть, чтобы поверить: порог,
# делённый на вес одного наблюдения, — три взгляда на занятое и пять на
# свободное. А чтобы СТЕРЕТЬ с карты убранный шкаф, надо проехать сквозь него
# девять раз: столько набирается от предела уверенности до порога. Это долго
# нарочно — стена, мимо которой робот просто давно не ездил, стираться не
# должна. Одного взгляда мало намеренно: дальномер промахивается, а
# ошибка, попавшая в ПОСТОЯННУЮ карту, останется там навсегда — в отличие от
# быстрой, где она растает за полминуты.
#
# Свободное подтверждается дольше занятого, и это не описка. Ошибиться,
# записав стену там, где её нет, — значит объезжать пустоту; ошибиться,
# записав пустоту там, где стена, — значит в неё поехать.


class Атлас:
    """План квартиры, который копится месяцами.

    Не забывает по времени вовсе. Забывание здесь было бы вредно: стена,
    которую робот не видел неделю, никуда не делась — он просто туда не
    заезжал. А то, что действительно изменилось (переставили шкаф), исправится
    само: новые наблюдения сдвинут клетки в другую сторону, потому что
    свободное пространство тоже записывается.
    """

    def __init__(self, файл=None, клеток: int = КЛЕТОК,
                 клетка: float = КЛЕТКА, часы=time.monotonic) -> None:
        self.файл = файл
        self.клеток = клеток
        self.клетка = клетка
        self._часы = часы
        self.сетка = np.zeros((клеток, клеток), dtype=np.float32)
        # Ноль карты — в её середине. Карта НЕ едет за роботом, в отличие от
        # быстрой: она про квартиру, а не про робота, и середина у неё там,
        # где робот впервые привязался.
        self.середина = клеток // 2
        self.влито = 0
        self.поездок = 0
        # Сколько раз отказались вливать из-за непривязки и когда сказали об
        # этом вслух в журнал. Отказ — не мелочь: пока он длится, постоянная
        # карта НЕ РАСТЁТ ВОВСЕ, сколько бы робот ни ездил.
        self.не_влито = 0
        self._жаловались = 0.0
        self._писали = 0.0
        self._показано = 0.0
        self._не_выложил = False
        if файл:
            self.загрузить()

    # --- служебное -------------------------------------------------------
    def _в_клетки(self, x: float, y: float):
        return (int(round(x / self.клетка)) + self.середина,
                int(round(y / self.клетка)) + self.середина)

    def _в_метры(self, кx: int, кy: int):
        return ((кx - self.середина) * self.клетка,
                (кy - self.середина) * self.клетка)

    def _внутри(self, кx: int, кy: int) -> bool:
        return 0 <= кx < self.клеток and 0 <= кy < self.клеток

    # --- накопление ------------------------------------------------------
    def отметить(self, x: float, y: float, занято: bool) -> None:
        """Одна клетка: тут стена или тут проехали."""
        кx, кy = self._в_клетки(x, y)
        if not self._внутри(кx, кy):
            return
        шаг = ЗА_ЗАНЯТО if занято else -ЗА_СВОБОДНО
        self.сетка[кy, кx] = float(
            np.clip(self.сетка[кy, кx] + шаг, -ПРЕДЕЛ, ПРЕДЕЛ))

    def влить(self, быстрая, привязан: bool = True) -> int:
        """Перенести накопленное быстрой картой. Отдаёт число клеток.

        `привязан` — знает ли робот, где он относительно этой карты. Ложь —
        не вливаем ВОВСЕ и молчим об этом только в журнале. Слитая вслепую
        карта наложится со сдвигом и поворотом, и две-три поездки превратят
        план квартиры в кашу, из которой уже ничего не достать. Отказ копить
        обратим, испорченная карта — нет.
        """
        if not привязан:
            # ГОВОРИМ ОБ ЭТОМ ГРОМКО, а стояло `log.debug`, то есть молча.
            #
            # Отказ вливать — не заминка, а полная остановка накопления: пока
            # робот не узнал квартиру, постоянная карта не растёт НИ НА ОДНУ
            # КЛЕТКУ, сколько бы он ни ездил. Обход при этом идёт как ни в чём
            # не бывало, отчитывается о пройденных метрах и заканчивается
            # словами «обошёл квартиру» — а записать было некуда.
            #
            # Отличить это снаружи было нельзя ничем: в журнале на уровне info
            # пусто, в пульте карта просто не меняется. Первое, что надо
            # проверять, когда «карта не строится», — вот эта строка.
            #
            # Раз в минуту, а не каждый кадр: заливка идёт десять раз в
            # секунду, и честная жалоба на каждый кадр утопила бы журнал.
            self.не_влито += 1
            сейчас = self._часы()
            if сейчас - self._жаловались > ЖАЛУЕМСЯ_РАЗ_В:
                self._жаловались = сейчас
                log.warning(
                    "атлас: НЕ ЗАПИСЫВАЮ НИЧЕГО — не узнал квартиру (отказов "
                    "%d). Постоянная карта не растёт, пока не привяжусь: для "
                    "привязки нужно %d однозначно узнанных предмета из "
                    "запомненных. Проверь узнавание предметов (DOSOD).",
                    self.не_влито, landmarks.ПАР_ДЛЯ_ПРИВЯЗКИ)
            return 0
        занятые = getattr(быстрая, "занятые_вокруг", None)
        if занятые is None:
            return 0
        поза = getattr(быстрая, "поза", None)
        if поза_плоха(поза):
            return 0
        рx, рy, курс = поза
        cos, sin = math.cos(курс), math.sin(курс)
        сколько = 0
        try:
            точки = list(занятые(быстрая.клеток * быстрая.клетка / 2))
        except Exception:                       # noqa: BLE001
            log.debug("атлас: быстрая карта не отдала занятые", exc_info=True)
            return 0
        for вперёд, вбок in точки:
            # Точки приходят в системе робота — переводим в мировую.
            x = рx + cos * вперёд - sin * вбок
            y = рy + sin * вперёд + cos * вбок
            self.отметить(x, y, True)
            сколько += 1
        # А ТЕПЕРЬ СВОБОДНОЕ, и без него всё это не карта, а облако точек.
        #
        # Здесь стояла одна строка: «под роботом свободно, он там стоит». То
        # есть постоянная карта копила ТОЛЬКО СТЕНЫ, а пустое место
        # появлялось на ней ровно там, где проехали колёса, — ниточкой в одну
        # клетку. В пульте это выглядело как россыпь красных точек без комнат,
        # и Игорь сказал прямо: «карта не строится... пусть нормальную карту
        # рисует».
        #
        # Знание при этом было посчитано и выброшено. Быстрая карта пускает
        # лучи от дальномера и честно помечает конус до препятствия свободным
        # (mapping._луч); нам оставалось только взять это, а не считать заново.
        #
        # Свободное весит меньше занятого (ЗА_СВОБОДНО против ЗА_ЗАНЯТО) — по
        # тому же доводу, что и всюду: записать пустоту там, где стена,
        # опаснее, чем наоборот.
        пусто = getattr(быстрая, "свободные_вокруг", None)
        if пусто is not None:
            try:
                for вперёд, вбок in пусто(быстрая.клеток * быстрая.клетка / 2):
                    x = рx + cos * вперёд - sin * вбок
                    y = рy + sin * вперёд + cos * вбок
                    self.отметить(x, y, False)
                    сколько += 1
            except Exception:                   # noqa: BLE001
                log.debug("атлас: быстрая карта не отдала свободные",
                          exc_info=True)
        self.отметить(рx, рy, False)
        self.влито += сколько
        return сколько

    def проехали(self, x: float, y: float) -> None:
        """Робот тут проехал — значит тут свободно."""
        self.отметить(x, y, False)

    # --- чтение ----------------------------------------------------------
    def занято(self, x: float, y: float) -> bool:
        кx, кy = self._в_клетки(x, y)
        if not self._внутри(кx, кy):
            return False
        return bool(self.сетка[кy, кx] >= ПОРОГ)

    def занятые_вокруг(self, x: float, y: float, курс: float,
                       дальше: float = 2.0):
        """Занятые клетки рядом — в системе робота, как у быстрой карты.

        ВОЗВРАЩАЕМ то же, что `mapping.занятые_вокруг`: точки (вперёд, вбок).
        А вот ЗОВУТ иначе, и путать эти две вещи дорого. Быстрой карте хватает
        одного довода «дальше», потому что она сама живёт в системе робота;
        атлас — мировой, и без позы ему нечего пересчитывать, поэтому здесь
        три довода впереди.

        Значит, `planner.из_карты` этот метод НЕ ПРОЧТЁТ: он зовёт `точки(дальше)`
        одним доводом, и довод сядет на `x`. Раньше в этой строке было написано
        обратное — «планировщику всё равно, откуда пришло препятствие», — и
        обещание держалось только на том, что подставить сюда атлас никто не
        пробовал: в бою планировщик получает `mapping.Карта`, а этот метод
        зовут из одной лишь самопроверки. Понадобится атлас как источник
        препятствий — учить надо планировщик передавать позу, а не надеяться,
        что подойдёт само.
        """
        готово = []
        радиус = int(дальше / self.клетка)
        цx, цy = self._в_клетки(x, y)
        cos, sin = math.cos(-курс), math.sin(-курс)
        for кy in range(max(0, цy - радиус), min(self.клеток, цy + радиус + 1)):
            for кx in range(max(0, цx - радиус),
                            min(self.клеток, цx + радиус + 1)):
                if self.сетка[кy, кx] < ПОРОГ:
                    continue
                мx, мy = self._в_метры(кx, кy)
                дx, дy = мx - x, мy - y
                if math.hypot(дx, дy) > дальше:
                    continue
                готово.append((дx * cos - дy * sin, дx * sin + дy * cos))
        return готово

    def фронтиры(self, годные=None) -> list[tuple[float, float, int]]:
        """Скопления клеток на границе известного: (x, y, сколько клеток).

        Клетка фронтира — свободная клетка с неизвестным соседом. Скопления
        собираем обходом в ширину по восьми соседям.

        ТОЧКА СКОПЛЕНИЯ — ЕГО СЕРЕДИНА, и нужна она только для отчёта: куда
        ехать, решает не она, а волна (поле_до_неизведанного). Раньше здесь
        выбиралась ближайшая к роботу клетка, потому что по ней и строился
        курс, — от этого способа мы ушли, когда замер показал, что выбор
        точки проигрывает полю.

        Мелочь отбрасываем здесь же: скопление меньше ФРОНТИР_ОТ клеток — это
        щель за шкафом или дрожь на краю конуса дальномера, а не комната.

        `годные` — если передать список, в него сложатся КЛЕТКИ уцелевших
        скоплений. Из них потом пускается волна (поле_до_неизведанного), и
        отбор по размеру достаётся ей даром: волна не побежит от крапины.
        """
        if годные is None:
            годные = []
        свободно = self.сетка < -ПОРОГ
        неизвестно = np.abs(self.сетка) <= ПОРОГ
        # ДЫРКА В ПОЛУ — НЕ НЕИЗВЕДАННАЯ ЗЕМЛЯ, и без этого правила фронтир
        # бесполезен.
        #
        # Клетка становится свободной не сразу: ЗА_СВОБОДНО — три десятых при
        # ПОРОГЕ в полтора, то есть нужно ШЕСТЬ наблюдений подряд. Робот едет,
        # и большая часть пола попадает под луч раз или два — этого мало.
        # Получается пол, СПЛОШЬ ИСПЕЩРЁННЫЙ «неизвестными» клетками, по
        # которым робот только что проехал.
        #
        # Каждая такая крапина — свободные соседи с неизвестной серединой, то
        # есть фронтир по букве определения. Их сотни, и все они у робота под
        # колёсами: он выбирал ближайшую, ехал полметра, ничего нового не
        # видел, находил следующую и так до конца отпущенного времени. В
        # прогоне по двухкомнатной квартире это выглядело как тридцать метров
        # пути, не покинувших первой комнаты.
        #
        # Отличить настоящее неизведанное от крапины просто: настоящее лежит
        # СПЛОШНЫМ КУСКОМ. Считаем, сколько соседей клетки тоже неизвестны, и
        # требуем хотя бы трёх из четырёх.
        #
        # Именно СЧИТАЕМ, а не требуем все четыре. Кромка большого куска —
        # та самая, что смотрит на свободное, — одним соседом всегда упирается
        # в свободную клетку, и правило «все четыре» вычёркивало ровно её. То
        # есть вычёркивало единственный слой, который и образует границу: на
        # проверке с дверным проёмом фронтиров не находилось вовсе.
        #
        # Три из четырёх разделяют как надо: у крапины в открытом полу
        # неизвестных соседей нет совсем, у кромки комнаты за дверью — три.
        соседей = np.zeros(self.сетка.shape, dtype=np.int8)
        соседей[:, :-1] += неизвестно[:, 1:]
        соседей[:, 1:] += неизвестно[:, :-1]
        соседей[:-1, :] += неизвестно[1:, :]
        соседей[1:, :] += неизвестно[:-1, :]
        сплошная = неизвестно & (соседей >= СОСЕДЕЙ_У_НЕИЗВЕДАННОГО)
        # Сосед-невидимка с любой из четырёх сторон. Сдвигаем маску целиком, а
        # не бегаем по клеткам: карта — сорок тысяч клеток, и питонов цикл по
        # ней шёл бы дольше, чем едет робот.
        край = np.zeros_like(свободно)
        край[:, :-1] |= сплошная[:, 1:]
        край[:, 1:] |= сплошная[:, :-1]
        край[:-1, :] |= сплошная[1:, :]
        край[1:, :] |= сплошная[:-1, :]
        клетки = свободно & край
        осталось = {(int(кx), int(кy))
                    for кy, кx in zip(*np.nonzero(клетки))}
        скопления = []
        while осталось:
            начало = осталось.pop()
            свои = [начало]
            очередь = [начало]
            while очередь:
                кx, кy = очередь.pop()
                for дx in (-1, 0, 1):
                    for дy in (-1, 0, 1):
                        сосед = (кx + дx, кy + дy)
                        if сосед in осталось:
                            осталось.discard(сосед)
                            свои.append(сосед)
                            очередь.append(сосед)
            if len(свои) < ФРОНТИР_ОТ:
                continue
            годные.extend(свои)
            сx = sum(к[0] for к in свои) / len(свои)
            сy = sum(к[1] for к in свои) / len(свои)
            мx, мy = self._в_метры(сx, сy)
            скопления.append((мx, мy, len(свои)))
        return скопления

    def _проезжие(self) -> np.ndarray:
        """Клетки, по которым робот и вправду пролезет.

        Свободного мало: свободная клетка вплотную к стене роботу не годится,
        он шириной сорок сантиметров. Раздуваем занятое на полуширину корпуса
        с запасом — тем же числом, которым планировщик проверяет дуги, а не
        своим: габарит обязан жить в одном месте.

        Без этого волна с чистой совестью проложит поле сквозь щель в десять
        сантиметров, робот поедет туда и застрянет — а поле будет и дальше
        звать его в ту же щель, потому что через неё «ближе всего».
        """
        занято = self.сетка > ПОРОГ
        радиус = max(1, int((planner.ПОЛУШИРИНА + planner.ЗАПАС) / self.клетка))
        толстое = занято.copy()
        for _ in range(радиус):
            шире = толстое.copy()
            шире[:, :-1] |= толстое[:, 1:]
            шире[:, 1:] |= толстое[:, :-1]
            шире[:-1, :] |= толстое[1:, :]
            шире[1:, :] |= толстое[:-1, :]
            толстое = шире
        return (self.сетка < -ПОРОГ) & ~толстое

    def поле_до_неизведанного(self):
        """Сколько клеток ехать до ближайшего неизведанного. None — некуда.

        ЭТО ГЛАВНАЯ ФУНКЦИЯ ОБХОДА, и она заменила собой выбор цели.

        Раньше здесь выбиралась ЛУЧШАЯ ТОЧКА и считалось расстояние до неё —
        `math.hypot`, то есть ПО ПРЯМОЙ, СКВОЗЬ СТЕНЫ. Фронтир в соседней
        комнате за перегородкой числился «в двух метрах», хотя ехать до него
        девять вокруг; робот доворачивался прямо на него и упирался в стену.
        Замер на квартире из четырёх помещений это и показал: выбор цели по
        прямой проиграл простому перебору лучей из-под робота, потому что лучи
        хотя бы честны про геометрию — сквозь стены они не видят.

        Правильно считать не расстояние до точки, а ПОЛЕ. Пускаем волну в
        ширину по проезжим клеткам, начиная СРАЗУ ОТ ВСЕХ фронтиров, и каждая
        клетка получает число: сколько шагов до ближайшего неизведанного в
        обход стен. Дальше робот не выбирает цель вовсе — он идёт туда, где
        поле падает. Это exploration transform (Wirth и Pellenz, 2007), тем же
        живёт hector_exploration_planner.

        Что уходит вместе с выбором цели:

          • расстояние сквозь стены — теперь геодезическое;
          • недостижимые фронтиры — им просто не достаётся значения, и чёрный
            список направлений («тут не проехали») становится не нужен;
          • «довернулся и поехал вслепую два метра» — курс пересчитывается на
            каждом шаге из нынешней позы.

        ЦЕНА. Замерено, а не прикинуто: волна по всему плану квартиры
        (200×200 клеток) занимает двенадцать миллисекунд на обычной машине,
        то есть около пятидесяти на плате робота — двадцать раз в секунду.
        Обходу она нужна два-три раза. Запас есть, и потому это бесплатно.

        ПОЧЕМУ ВНУТРИ ПЛОСКИЙ СПИСОК, А НЕ NUMPY. Первая редакция считала
        прямо по массиву numpy и выходила в шестьдесят миллисекунд, то есть
        четверть секунды на плате. Виноват не алгоритм: numpy быстр на целых
        массивах и МЕДЛЕНЕН на обращении по одной клетке — каждое `поле[y, x]`
        это создание объекта-скаляра. Волна же только тем и занята, что ходит
        по клеткам поодиночке, пятьдесят тысяч раз.
        Обычный питонов список плоским индексом `y * сторона + x` оказался
        ВПЯТЕРО быстрее. Массив собираем в конце, одним вызовом.
        """
        годные: list[tuple[int, int]] = []
        self.фронтиры(годные=годные)
        if not годные:
            return None
        сторона = self.клеток
        всего = сторона * сторона
        проезжие = self._проезжие().ravel().tolist()
        поле = [НЕДОСТУПНО] * всего
        очередь = deque()
        for кx, кy in годные:
            # Сам фронтир может стоять вплотную к стене — он ведь на кромке.
            # Пускаем волну и из него: иначе у комнаты за узкой дверью не
            # окажется ни одной стартовой клетки, и она пропадёт.
            и = кy * сторона + кx
            if поле[и]:
                поле[и] = 0
                очередь.append(и)
        # Смещения в плоском списке. Диагонали идут вместе с двумя своими
        # прямыми соседями: наискось между двух занятых клеток не пролезть,
        # там косяк двери или ножка стола, и срезать угол нельзя.
        шаги = ((-сторона, 10, None), (сторона, 10, None),
                (-1, 10, None), (1, 10, None),
                (-сторона - 1, 14, (-сторона, -1)),
                (-сторона + 1, 14, (-сторона, 1)),
                (сторона - 1, 14, (сторона, -1)),
                (сторона + 1, 14, (сторона, 1)))
        while очередь:
            и = очередь.popleft()
            сюда = поле[и]
            for сдвиг, цена, углы in шаги:
                j = и + сдвиг
                if j < 0 or j >= всего or not проезжие[j]:
                    continue
                if углы is not None and not (проезжие[и + углы[0]]
                                             and проезжие[и + углы[1]]):
                    continue
                стало = сюда + цена
                if стало < поле[j]:
                    поле[j] = стало
                    очередь.append(j)
        return np.array(поле, dtype=np.int32).reshape(сторона, сторона)

    def куда_неизвестно(self, поза, дальше: float = ГОРИЗОНТ,
                        лучей: int = 24,
                        избегать=()) -> tuple[float, int] | None:
        """Куда ехать за новым: (курс в мире, сколько клеток). None — некуда.

        СНАЧАЛА ЛУЧИ, ПОТОМ ВОЛНА, И ПОРЯДОК ИМЕННО ТАКОЙ — ЭТО ЗАМЕРЕНО.

        Соблазн поставить волну первой большой: она умнее, она считает дорогу
        в обход стен, она видит комнату за дверью. Замер этот соблазн
        забраковал. Квартира из четырёх помещений, десять минут, покрытие:

            лучи (как было)          51, 48, 50, 29 %   комнат 2, 2, 2, 1
            волна вместо лучей                   50 %   комнат 2
            фронтир вместо лучей         46, 32 %       комнат 2, 2
            ЛУЧИ + ВОЛНА В ЗАПАС         70, 59 %       комнат 3, 3

        Гибрид выигрывает, и выигрывает объяснимо. Лучи отвечают на вопрос
        «куда я могу доехать ПРЯМО СЕЙЧАС»: они пущены из-под робота, они
        коротки, и всё, что они находят, лежит в пределах ближайших метров —
        то есть там, где реактивный объезд ещё способен привести. Пока лучи
        отвечают, слушать надо их.

        А вот когда лучи молчат — вот это и есть тот самый миг, в который
        прежний код объявлял «карта полна» и вставал на восемнадцатом метре
        посреди необойдённой квартиры. Лучи молчат не потому, что квартира
        кончилась, а потому, что всё видимое отсюда уже известно. Именно
        здесь волна и нужна: она одна знает, что за дверью, в которую робот
        сейчас не смотрит, лежит целая комната, и знает, как туда ехать в
        обход стен.

        То есть волна тут не «умнее лучей», а отвечает на ДРУГОЙ вопрос — не
        «куда шагнуть», а «куда идти, когда шагать некуда». Ставить её первой
        значит спрашивать про дальнее там, где решается ближнее.

        Курс от волны берём СПУСКОМ ПО ПОЛЮ, и не на шаг, а на МОРКОВКУ —
        точку в метре впереди, в пределах дальности дальномера. Соседняя
        клетка дала бы курс с точностью до сорока пяти градусов (соседей
        восемь) и дёргалась бы от клетки к клетке; точка в метре даёт гладкое
        направление, и объезжающий планировщик работает внутри неё, а не
        поперёк всего пути.
        """
        if поза_плоха(поза):
            return None
        рядом = self._куда_по_лучам(поза, дальше, лучей, избегать)
        if рядом is not None:
            return рядом
        return self._куда_по_волне(поза)

    def _куда_по_волне(self, поза) -> tuple[float, int] | None:
        """Куда идти по полю до неизведанного. None — идти некуда."""
        рx, рy, _курс = поза
        поле = self.поле_до_неизведанного()
        if поле is None:
            return None
        откуда = self._встать_на_поле(поле, рx, рy)
        if откуда is None:
            return None
        цель = self._морковка(поле, откуда)
        мx, мy = self._в_метры(цель[1], цель[0])
        if math.hypot(мx - рx, мy - рy) < self.клетка:
            return None
        угол = math.atan2(мy - рy, мx - рx)
        return ((угол + math.pi) % (2 * math.pi) - math.pi,
                int(поле[откуда]) // ЦЕНА_КЛЕТКИ)

    def _встать_на_поле(self, поле, рx: float, рy: float):
        """Клетка робота на поле. Своя может быть без значения — ищем рядом.

        Робот стоит там, где стоит, а поле построено только по проезжим
        клеткам. Его собственная клетка легко окажется без значения: пол под
        ним ещё не набрал шести наблюдений, или он подъехал к стене ближе
        полуширины корпуса. Отказываться из-за этого нельзя — ехать-то надо.
        """
        кx, кy = self._в_клетки(рx, рy)
        лучшее = None
        радиус = max(2, int(ОГЛЯДЕТЬСЯ / self.клетка))
        for дy in range(-радиус, радиус + 1):
            for дx in range(-радиус, радиус + 1):
                ny, nx = кy + дy, кx + дx
                if not (0 <= ny < self.клеток and 0 <= nx < self.клеток):
                    continue
                if поле[ny, nx] >= НЕДОСТУПНО:
                    continue
                далеко = дy * дy + дx * дx
                if лучшее is None or далеко < лучшее[0]:
                    лучшее = (далеко, (ny, nx))
        return лучшее[1] if лучшее else None

    def _морковка(self, поле, откуда):
        """Куда править: клетка в круге радиусом МОРКОВКА с наименьшим полем.

        ПОЧЕМУ КРУГОМ, А НЕ ШАГ ЗА ШАГОМ ВНИЗ ПО ГРАДИЕНТУ. Пошаговый спуск
        сюда и был написан первым, и он повёл робота не туда: у клетки восемь
        соседей, значения поля целые, и соседей с ОДИНАКОВЫМ значением обычно
        несколько. Выбор между ними достаётся порядку перебора, шаг косит на
        диагональ, следующий косит снова — за десять шагов набегает лесенка.
        На проверке робот стоял в полутора метрах от двери прямо напротив
        неё, а спуск давал курс минус двадцать семь градусов, то есть в стену.

        Минимум по кругу лесенки не знает вовсе: он смотрит на итог, а не на
        дорогу к нему. Из всех клеток, до которых робот дотянется за метр,
        берём ту, от которой до неизведанного ближе всего, — и правим прямо
        на неё.

        Ничью решаем в пользу БЛИЖНЕЙ клетки: если полем одинаково хороши
        несколько, ехать надо в ту, что требует меньшего отклонения.
        """
        кy, кx = откуда
        радиус = max(1, int(МОРКОВКА / self.клетка))
        лучшее = None
        for дy in range(-радиус, радиус + 1):
            for дx in range(-радиус, радиус + 1):
                далеко = дy * дy + дx * дx
                if далеко > радиус * радиус:
                    continue
                ny, nx = кy + дy, кx + дx
                if not (0 <= ny < self.клеток and 0 <= nx < self.клеток):
                    continue
                з = поле[ny, nx]
                if з >= НЕДОСТУПНО:
                    continue
                ключ = (int(з), далеко)
                if лучшее is None or ключ < лучшее[0]:
                    лучшее = (ключ, (ny, nx))
        return лучшее[1] if лучшее else откуда

    def куда_поглядеть(self, поза, шаг_метров: float = 1.5,
                       не_ближе: float = 1.0,
                       сколько: int = 12) -> list[tuple[float, float]]:
        """Знакомые проезжие места — куда съездить и посмотреть.

        ЭТО НЕ ФРОНТИР, И СПРАШИВАЮТ ОТСЮДА ДРУГОЕ. `куда_неизвестно` отвечает
        «где я НЕ БЫЛ» — вопрос обхода, у которого цель покрытие. У поиска
        цель другая: посмотреть, и посмотреть надо как раз там, где робот
        БЫЛ, — собака лежит на знакомом диване, а не в неизведанном углу.

        Понадобилось это по живому случаю, и случай ровно обратный тому, для
        которого писался обход. Робот с ПОЛНОЙ картой:

            атлас: помню 4557 клеток квартиры (45.6 м²) за 0 поездок
            поиск: еду смотреть точку -2.5, -2.4 (туда ещё не смотрел)
            поиск: не нашёл dog — обошёл всё, что помню (точек 1)

        Неизведанного не осталось — карта полная, — и единственный источник
        точек у свежего робота выдал ОДНУ штуку и замолчал. Свежей встречи
        нет, привязки к вчерашним любимым местам нет, описи мебели нет. Итог:
        «Не нашёл. Смотрел в 1 местах» по квартире в сорок пять метров.
        Полная карта делала поиск БЕСПОЛЕЗНЕЕ пустой — то есть чем дольше
        робот живёт в доме, тем хуже ищет.

        Берём проезжие клетки — те же, по которым волна прокладывает путь, и
        по той же полуширине корпуса, чтобы не звать себя в щель. Прореживаем
        на `шаг_метров`: два взгляда с расстояния в полметра показывают одно и
        то же, а поиск платит за каждый переезд. Ближние `не_ближе` метров
        выбрасываем — оттуда уже посмотрели, стоя здесь.

        Порядок — от ближнего к дальнему: искать надо начиная с того, что под
        боком, а не гнать через квартиру к дальней стене.
        """
        if поза_плоха(поза):
            return []
        проезжие = self._проезжие()
        кy, кx = np.nonzero(проезжие)
        if len(кx) == 0:
            return []
        рx, рy = float(поза[0]), float(поза[1])
        точки = []
        for кx_, кy_ in zip(кx.tolist(), кy.tolist()):
            x, y = self._в_метры(кx_, кy_)
            далеко = math.hypot(x - рx, y - рy)
            if далеко >= не_ближе:
                точки.append((далеко, x, y))
        точки.sort()
        # Прореживаем жадно, по возрастанию расстояния: ближняя точка своего
        # угла всегда побеждает дальнюю в том же углу.
        взяли: list[tuple[float, float]] = []
        for _, x, y in точки:
            if any(math.hypot(x - вx, y - вy) < шаг_метров for вx, вy in взяли):
                continue
            взяли.append((x, y))
            if len(взяли) >= сколько:
                break
        return взяли

    def _куда_по_лучам(self, поза, дальше: float = ГОРИЗОНТ,
                       лучей: int = 24,
                       избегать=()) -> tuple[float, int] | None:
        """Куда ехать, чтобы увидеть новое: (курс в мире, сколько клеток).

        None — вокруг всё известно или позы нет.

        ЧТО ЭТО ТАКОЕ. Настоящие обследователи строят границу известного
        («фронтир») и планируют путь к ближайшей её точке. Планировать путь
        нам нечем: без лидара и SLAM глобального планировщика в этом роботе
        нет и не будет, а reactive-объезд по дороге всё равно уведёт с любой
        нарисованной линии.

        Поэтому выбираем НЕ ПУТЬ, А НАПРАВЛЕНИЕ — единственное, что робот
        способен честно выдержать. Из своей клетки пускаем лучи по кругу и
        считаем вдоль каждого неизвестные клетки, обрывая луч о первую
        занятую: за стену робот не поедет, и обещать себе тамошнюю новизну
        нечестно.

        Ничью решаем в пользу нынешнего курса. На пустой карте неизвестно
        одинаково во все стороны, и без этого правила робот выбирал бы первый
        луч по списку — то есть всегда одну и ту же сторону света, независимо
        от того, куда смотрит.
        """
        if поза_плоха(поза):
            return None
        рx, рy, курс = поза
        шаг = self.клетка
        шагов = max(1, int(дальше / шаг))
        лучшее = None
        for i in range(лучей):
            угол = курс + (i / лучей) * 2 * math.pi
            # НАПРАВЛЕНИЯ, В КОТОРЫХ УЖЕ НЕ ВЫШЛО, НЕ ПРЕДЛАГАЕМ СНОВА.
            #
            # Без этого получается вот что: карта говорит «неизвестного
            # больше всего вон там», робот доворачивается, упирается в то,
            # чего карта не знает (стул, порог, косяк), возвращается ни с чем
            # — и карта, ничего не узнав, советует ТО ЖЕ САМОЕ. Робот ходит по
            # кругу, пока не кончится время.
            #
            # У explore_lite для этого чёрный список фронтиров, до которых не
            # доехали за progress_timeout. Здесь то же самое, только в углах.
            if any(abs((угол - плохой + math.pi) % (2 * math.pi) - math.pi)
                   < ЗАБЫТЬ_НАПРАВЛЕНИЕ for плохой in избегать):
                continue
            cos, sin = math.cos(угол), math.sin(угол)
            новых = self._вдоль(рx, рy, cos, sin, шаг, шагов)
            if новых < НОВОГО_ХВАТИТ:
                continue
            # ЦЕНА ДОРОГИ ВАЖНЕЕ РАЗМЕРА НАХОДКИ — так считают все, и это
            # видно по их числам. У explore_lite, самой ходовой реализации
            # фронтира в ROS, вес расстояния 3-5, а вес размера 1.0: робот
            # предпочтёт близкий маленький фронтир далёкому большому.
            #
            # Довод не в экономии, а в том, что ошибка накапливается по пути.
            # Дорога до дальнего фронтира — это метры одометрии без привязки,
            # и приехав, робот уже не вполне знает, где он. Ближний фронтир
            # даёт то же знание дешевле и точнее.
            #
            # У нас «расстояние» — это отворот: пути мы не планируем, а
            # платим поворотом на месте и трясём им ту самую одометрию.
            отворот = abs((угол - курс + math.pi) % (2 * math.pi) - math.pi)
            оценка = новых - отворот * КЛЕТОК_ЗА_РАДИАН
            if лучшее is None or оценка > лучшее[0]:
                лучшее = (оценка, угол, новых)
        if лучшее is None:
            return None
        _, угол, новых = лучшее
        return (угол + math.pi) % (2 * math.pi) - math.pi, новых

    def _вдоль(self, рx, рy, cos, sin, шаг, шагов) -> int:
        """Сколько неизвестных клеток по этому направлению. Ноль — некуда.

        Смотрим ТРЕМЯ параллельными лучами по ширине корпуса, а не одним, и
        это не украшение. Луч в одну клетку — линия нулевой толщины: он
        проскакивает между двумя стульями там, где робот не пролезет, и
        одинаково легко находит «новое» в щели за шкафом. Робот поедет туда,
        упрётся и объявит тупик — а на карте место так и останется
        неизвестным, потому что заглянуть в него было нечем.

        Три луча по полуширине корпуса дают ровно тот вопрос, который нужен:
        «влезу ли я туда целиком». Первая занятая клетка ЛЮБОГО из трёх
        обрывает направление целиком, а не свой луч: занятая клетка сбоку —
        это стена, в которую упрётся плечо.
        """
        # Перпендикуляр к направлению — вдоль него и разносим лучи.
        пx, пy = -sin, cos
        # Полуширину берём у планировщика, а не заводим свою: габарит робота
        # обязан жить в одном месте, иначе однажды разъедутся тот, по
        # которому робот проверяет дугу, и тот, по которому выбирает, куда
        # ехать вообще, — и он поедет туда, куда сам себя потом не пустит.
        полуширина = planner.ПОЛУШИРИНА + planner.ЗАПАС
        новых = 0
        живы = [True, True, True]
        for н in range(1, шагов + 1):
            вперёд = н * шаг
            for л, отступ in enumerate((0.0, полуширина, -полуширина)):
                if not живы[л]:
                    continue
                кx, кy = self._в_клетки(рx + cos * вперёд + пx * отступ,
                                        рy + sin * вперёд + пy * отступ)
                if not self._внутри(кx, кy):
                    живы[л] = False
                    continue
                значение = self.сетка[кy, кx]
                if значение >= ПОРОГ:
                    # Стена по любому из лучей — дальше корпус не пройдёт.
                    return новых
                if abs(значение) < ПОРОГ and not л:
                    # Считаем новизну только по среднему лучу: боковые нужны
                    # для «влезу ли», и складывать их значило бы втрое
                    # завышать награду за широкие коридоры.
                    новых += 1
            if not any(живы):
                break
        return новых

    def сколько_знаю(self) -> dict:
        """Насколько карта заполнена. Для человека и для журнала."""
        занято = int((self.сетка >= ПОРОГ).sum())
        свободно = int((self.сетка <= -ПОРОГ).sum())
        клеток = self.клеток * self.клеток
        return {"занято": занято, "свободно": свободно,
                "известно": занято + свободно,
                "доля": round((занято + свободно) / клеток, 4),
                "метров": round((занято + свободно) * self.клетка ** 2, 1),
                "поездок": self.поездок}

    # --- хранение --------------------------------------------------------
    def сохранить(self, принудительно: bool = False) -> bool:
        """Записать карту. Раз в две минуты, если не просят иначе.

        Пишем через временный файл и переименование: выдернутое посреди
        записи питание оставит на месте целую прошлую карту, а не половину
        новой. Для карты, которая копится месяцами, это не мелочь.
        """
        if not self.файл:
            return False
        сейчас = self._часы()
        if not принудительно and сейчас - self._писали < ПИСАТЬ_РАЗ_В:
            return False
        self._писали = сейчас
        try:
            os.makedirs(os.path.dirname(str(self.файл)) or ".", exist_ok=True)
            врем = f"{self.файл}.новый"
            # Пишем только ненулевые клетки. Карта квартиры заполнена на
            # проценты, и хранить сорок тысяч нулей ради двух тысяч чисел
            # незачем — да и читается такой файл глазами.
            клетки = np.nonzero(self.сетка)
            данные = {
                "клетка": self.клетка, "клеток": self.клеток,
                "середина": self.середина, "поездок": self.поездок,
                "когда": time.time(),
                "точки": [[int(кx), int(кy), round(float(self.сетка[кy, кx]), 2)]
                          for кy, кx in zip(*клетки)],
            }
            with open(врем, "w", encoding="utf-8") as f:
                json.dump(данные, f, ensure_ascii=False)
            os.replace(врем, self.файл)
            return True
        except OSError:
            log.debug("атлас: не смог сохранить", exc_info=True)
            return False

    def загрузить(self) -> bool:
        try:
            with open(self.файл, encoding="utf-8") as f:
                данные = json.load(f)
        except (OSError, ValueError):
            return False
        if not isinstance(данные, dict):
            return False
        # Размер клетки мог поменяться между версиями. Пересчитывать старую
        # карту под новую сетку — это размазать её по соседям и испортить;
        # честнее начать заново и сказать об этом.
        if abs(float(данные.get("клетка") or 0) - self.клетка) > 1e-6:
            log.info("атлас: карта записана другой клеткой — начинаю заново")
            return False
        if int(данные.get("клеток") or 0) != self.клеток:
            log.info("атлас: карта другого размера — начинаю заново")
            return False
        self.середина = int(данные.get("середина") or self.клеток // 2)
        self.поездок = int(данные.get("поездок") or 0)
        for точка in данные.get("точки") or []:
            try:
                кx, кy, вес = int(точка[0]), int(точка[1]), float(точка[2])
            except (TypeError, ValueError, IndexError):
                continue
            if self._внутри(кx, кy):
                self.сетка[кy, кx] = вес
        сколько = self.сколько_знаю()
        log.info("атлас: помню %d клеток квартиры (%.1f м²) за %d поездок",
                 сколько["известно"], сколько["метров"], self.поездок)
        return True

    def для_пульта(self) -> dict:
        """Карта для показа. Только известное, строками «x y вес»."""
        клетки = np.nonzero(np.abs(self.сетка) >= ПОРОГ)
        return {
            "клетка": self.клетка, "клеток": self.клеток,
            "середина": self.середина,
            "точки": [[int(кx), int(кy),
                       1 if self.сетка[кy, кx] >= ПОРОГ else 0]
                      for кy, кx in zip(*клетки)],
        }

    def выложить(self, файл, не_чаще: float = ПОКАЗЫВАТЬ_РАЗ_В,
                 поза=None, почему: str = "", пометки=None,
                 поворот: float = 0.0) -> bool:
        """План квартиры — в файл, чтобы его видел пульт. True — записали.

        ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, если карта и так лежит на диске. Затем, что на
        диске она лежит в своём формате и вперемешку со служебным, а пульт
        живёт в другом процессе, и знание формата в нём — это вторая копия
        формата. Такая копия у нас уже была (порог стопа) и разошлась при
        первой же правке.

        И ЗАЧЕМ ВООБЩЕ. До сих пор постоянная карта не показывалась нигде.
        Игорь смотрел на панель «карта вокруг» — а та ЗАБЫВЧИВА по замыслу,
        половина стирается за тридцать пять секунд, — и видел ровно то, на что
        пожаловался: «карту не сохраняет, каждый раз заново рисует». Карта,
        которую нельзя увидеть, неотличима от несуществующей.

        `почему` — если не копим, то по какой причине; пульт покажет это
        словами. Молча пустая панель хуже: она читается как поломка.
        """
        сейчас = self._часы()
        if сейчас - self._показано < не_чаще:
            return False
        self._показано = сейчас
        # Сжимаем так же, как быстрая карта: три знака со счётчиками повторов.
        # Двести на двести — сорок тысяч клеток, списком чисел это сотня
        # килобайт на кадр; пустая карта укладывается в один кусок.
        знаки = np.zeros_like(self.сетка, dtype=np.int8)
        знаки[self.сетка >= ПОРОГ] = 1
        знаки[self.сетка <= -ПОРОГ] = -1
        плоско = знаки.ravel()
        границы = np.flatnonzero(np.diff(плоско)) + 1
        начала = np.concatenate(([0], границы))
        длины = np.diff(np.concatenate((начала, [плоско.size])))
        строка = "".join(f"{д}{ЗНАКИ[int(плоско[н])]}"
                         for н, д in zip(начала, длины))
        сколько = self.сколько_знаю()
        # Мебель кладём сюда же — довод в самом поле «пометки» ниже.
        вещи = []
        if пометки is not None:
            try:
                вещи = list(пометки.для_пульта())
            except Exception:                   # noqa: BLE001
                log.debug("пометки не отдались для пульта", exc_info=True)
        try:
            файл = Path(файл)
            файл.parent.mkdir(parents=True, exist_ok=True)
            врем = файл.with_name(файл.name + ".tmp")
            врем.write_text(json.dumps({
                "когда": time.time(),
                "клетка": self.клетка,
                "клеток": self.клеток,
                "середина": self.середина,
                "клетки": строка,
                "поза": list(поза) if поза else None,
                "влито": self.влито,
                "поездок": self.поездок,
                "известно": сколько["известно"],
                "метров": round(сколько["метров"], 1),
                "копим": not почему,
                "почему": почему,
                # МЕБЕЛЬ КЛАДЁМ СЮДА ЖЕ. План квартиры без мебели — это
                # контур стен, по которому человек своё жильё не узнаёт. А
                # «стол вот тут, диван вон там» превращает его в план,
                # который читается с одного взгляда. Пометки живут в другом
                # модуле (landmarks), но человеку они нужны на этой же
                # картинке, а не рядом списком.
                "пометки": вещи,
                # СХЕМА СТЕН — то, ради чего план вообще смотрят. Крап из
                # тысячи занятых клеток человек своей квартирой не признает;
                # прямые линии он читает с одного взгляда. Считаем здесь, а
                # не в пульте: направление стен даёт компас, и знание про
                # компас в браузере было бы второй копией того же.
                "стены": стены(self.сетка, self.клетка, self.середина,
                               поворот),
            }, ensure_ascii=False))
            врем.replace(файл)
            return True
        except OSError as e:
            if not self._не_выложил:
                self._не_выложил = True
                log.warning("атлас: план не пишется в %s (%s) — "
                            "пульт его не увидит", файл, e)
            return False


def поза_плоха(поза) -> bool:
    """Годится ли поза для счёта. То же имя, что в landmarks, тот же смысл."""
    if поза is None:
        return True
    try:
        return len(поза) < 3
    except TypeError:
        return True
