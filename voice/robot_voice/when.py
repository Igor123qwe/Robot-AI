"""Разбор времени: «в семь утра», «через двадцать минут», «завтра в восемь».

Отдельно от intents.py, потому что это самостоятельная задача со своими
углами: часть суток, переход через полночь, «завтра», двузначные минуты
без двоеточия (Whisper пишет «7 30», а не «7:30»).

Текст сюда приходит уже после numerals_to_digits — числительные заменены
цифрами, поэтому «в семь утра» выглядит как «в 7 утра».
"""

from __future__ import annotations

import re
from datetime import datetime, timedelta

_PART = {
    "утра": "am", "утром": "am",
    "дня": "pm", "вечера": "pm", "вечером": "pm",
    "ночи": "night", "ночью": "night",
}

# «в 7», «на 7 30», «к 19:45», «в 8 часов вечера».
_CLOCK = re.compile(
    r"(?:^|\s)(?:в|на|к|во)\s+(\d{1,2})(?:[ .:-]+(\d{2}))?\s*"
    r"(?:час\w*\s*)?(утра|утром|дня|вечера|вечером|ночи|ночью)?(?=\s|$)"
)

# «в час дня» — единственное время, которое говорят словом, а не числом:
# «час» для numerals_to_digits не числительное, а единица измерения.
_ONE = re.compile(r"(?:^|\s)(?:в|к|во)\s+час\s+(дня|ночи)(?=\s|$)")
_NOON = re.compile(r"(?:^|\s)(?:в|к|во)\s+(полдень|полночь)(?=\s|$)")

# Половины говорят по-русски через СЛЕДУЮЩИЙ час: «полвосьмого» — это 7:30, а
# не 8:30. Порядковые числительные numerals_to_digits не трогает, они доезжают
# сюда словами. Шаблон не знал их вовсе, и «разбуди меня в полвосьмого» уходило
# модели, а та ставила будильник наугад.
_ПОРЯДКОВЫЕ = {
    "первого": 1, "второго": 2, "третьего": 3, "четвертого": 4, "пятого": 5,
    "шестого": 6, "седьмого": 7, "восьмого": 8, "девятого": 9, "десятого": 10,
    "одиннадцатого": 11, "двенадцатого": 12,
}
_ЧАСТЬ = r"(утра|утром|дня|вечера|вечером|ночи|ночью)"
_ПОРЯДКОВОЕ = "|".join(_ПОРЯДКОВЫЕ)
#
# Предлоги здесь не для красоты. «Помыть пол второго этажа» и «съешь половину
# второго пирога» — не время, и без предлога напоминание встало бы на 1:30.
# Поэтому: «в половине», «к половине», «на половину» — да; голое «пол второго»
# — только после «в» или «к» (а «на пол» — это пол, на который кладут);
# слитное «полвосьмого» однозначно и узнаётся где угодно.
_HALF = re.compile(
    rf"(?:^|\s)(?:"
    rf"(?:(?:в|во|к)\s+половине|на\s+половину)\s+"
    rf"(?:({_ПОРЯДКОВОЕ})|(\d{{1,2}})(?:-?го)?)"
    rf"|(?:(?:в|во|к|на)\s+)?пол-?({_ПОРЯДКОВОЕ})"
    rf"|(?:в|во|к)\s+пол\s+({_ПОРЯДКОВОЕ})"
    rf")\s*{_ЧАСТЬ}?(?=\s|$)")
# «Без пятнадцати семь» — 6:45. Словами до сюда оно не доезжает: числа
# «пятнадцати семь» сложились бы в 22, поэтому intents.normalize заранее
# пишет его цифрами раздельно — «без 15 7».
_BEZ = re.compile(
    rf"(?:^|\s)(?:(?:в|на|к|во)\s+)?без\s+(\d{{1,2}})\s+(?:минут\w*\s+)?"
    rf"(\d{{1,2}})(?:\s*час\w*)?\s*{_ЧАСТЬ}?(?=\s|$)")


def _по_части(hour: int, слово: str) -> int:
    """Час с учётом «утра», «вечера», «ночи»."""
    part = _PART.get(слово or "")
    if part == "am":
        # Ничего не меняем намеренно. По-английски 12 AM — это полночь, и
        # раньше так считалось и здесь; по-русски «двенадцать утра» — полдень,
        # а полночь говорят «двенадцать ночи», и её разбирает ветка ниже.
        pass
    elif part == "pm":
        hour = hour if hour >= 12 else hour + 12
    elif part == "night":
        # «в двенадцать ночи» — полночь, «в час ночи» — час, «в десять ночи» — 22.
        hour = 0 if hour == 12 else (hour if hour <= 5 else (hour + 12) % 24)
    return hour


def _найти(text: str) -> tuple[int, int, re.Match] | None:
    """Час, минута и то место фразы, где они сказаны. None — времени нет.

    Место нужно напоминанию: время из его текста вырезают, и вырезать надо
    ровно то, что здесь прочитано, а не первое похожее на время.
    """
    special = _NOON.search(text)
    if special:
        return (12 if special.group(1) == "полдень" else 0), 0, special
    special = _ONE.search(text)
    if special:
        return (13 if special.group(1) == "дня" else 1), 0, special

    m = _HALF.search(text)
    if m:
        словом = m.group(1) or m.group(3) or m.group(4) or ""
        следующий = _ПОРЯДКОВЫЕ.get(словом) or int(m.group(2) or 0)
        if 1 <= следующий <= 12:
            # «Половина первого» — 12:30: час до первого — двенадцатый.
            return _по_части(следующий - 1 or 12, m.group(5)), 30, m

    m = _BEZ.search(text)
    if m:
        без, следующий = int(m.group(1)), int(m.group(2))
        if 1 <= без <= 30 and 1 <= следующий <= 12:
            return _по_части(следующий - 1 or 12, m.group(3)), 60 - без, m

    m = _CLOCK.search(text)
    if not m:
        return None

    hour, minute = int(m.group(1)), int(m.group(2) or 0)
    if hour > 23 or minute > 59:
        return None
    return _по_части(hour, m.group(3)), minute, m


def at_time(text: str, now: datetime | None = None) -> datetime | None:
    """Ближайший момент, когда наступит названное время. None — времени нет.

    Без уточнения части суток берётся ближайшее наступление: «разбуди в семь»,
    сказанное вечером, — это семь утра завтра, а не семь вечера сегодня.
    """
    now = now or datetime.now()
    найдено = _найти(text)
    if найдено is None:
        return None
    hour, minute, _ = найдено
    return _next(now, hour, minute, text)


def отрезок(text: str) -> tuple[int, int] | None:
    """Где во фразе сказано время суток — чтобы вырезать его из текста."""
    найдено = _найти(text)
    return найдено[2].span() if найдено else None


def _next(now: datetime, hour: int, minute: int, text: str) -> datetime:
    target = now.replace(hour=hour, minute=minute, second=0, microsecond=0)
    if re.search(r"\bзавтра\b", text):
        target += timedelta(days=1)
    elif target <= now:
        target += timedelta(days=1)
    return target


def minutes_until(when: datetime, now: datetime | None = None) -> float:
    return round(((when or datetime.now()) - (now or datetime.now())).total_seconds() / 60, 3)


def moment(text: str, now: datetime | None = None) -> datetime | None:
    """Момент из строки: сначала как готовая дата, потом как живая фраза.

    Правила уже разобрали фразу целиком и знают точный момент — вместе с
    «завтра». Но в инструмент едет строка, и раньше там оставалось одно
    время суток: «напомни завтра в девять» превращалось в «в 9:00», а
    инструмент разбирал это заново и брал БЛИЖАЙШИЕ девять часов, то есть
    сегодняшние. Напоминание срабатывало на сутки раньше, молча.

    Поэтому правила отдают дату целиком, а модель по-прежнему говорит
    по-человечески — принимаем оба вида.
    """
    t = (text or "").strip()
    if not t:
        return None
    try:
        return datetime.fromisoformat(t)
    except ValueError:
        pass
    # Числительные словами — тоже наш случай: модель пишет «семь утра», а
    # разбор ждёт цифр. Импорт внутри функции, потому что intents сам зовёт
    # этот модуль, и наверху получилось бы кольцо.
    from .intents import normalize
    return at_time(f"в {normalize(t)}", now)
