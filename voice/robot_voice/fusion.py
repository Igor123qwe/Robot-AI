"""Сплав камеры и дальномера: плотная картина глубины в честных метрах.

Замысел. Нейросеть, оценивающая глубину по одной картинке, выдаёт ОТНОСИТЕЛЬНУЮ
глубину: она уверенно видит, что стена дальше стула, но не знает, метр до неё
или три. Масштаба у неё нет и взяться ему неоткуда — это врождённое свойство
одного глаза, а не недоработка. Именно поэтому монокулярное зрение плохо
годится для «не врезаться»: красивая карта без единого настоящего размера.

Дальномер даёт обратное: всего 64 точки, зато настоящие метры.

Сложить их — и получится то, чего нет ни у одного по отдельности: плотная
картина, как с камеры, и честная в метрах, как с дальномера. В работах это
зовут depth completion, а приём с опорными точками — sparse metric anchoring
(DELTAR, ECCV 2022, и CFPNet — оба ровно на этом датчике).

Тяжёлый способ — обучить сеть, которая сама сливает то и другое. Здесь
сделан лёгкий: подгонка двух чисел. Он даёт большую часть пользы и умещается
в полсотни строк без единой новой зависимости.

ПОЧЕМУ ПОДГОНКА ИДЁТ В ОБРАТНЫХ ВЕЛИЧИНАХ. Модели глубины обучают на потерях,
инвариантных к сдвигу и масштабу, и связь с настоящим расстоянием у них
линейна не в метрах, а в обратных метрах: 1/метры = a·отклик + b. Подгонять
прямо в метрах — распространённая ошибка: близкие точки тогда тянут подгонку
на себя, а дальняя половина кадра уезжает в бессмыслицу.
"""

from __future__ import annotations

import logging
import math

import numpy as np

from . import rig

log = logging.getLogger(__name__)

# Поля зрения. Камера AR0234 с объективом на 130 градусов по горизонтали,
# дальномер VL53L7CX — 60 на 60. То есть сетка дальномера накрывает примерно
# среднюю треть кадра, а не весь кадр: края картинки опорных точек не имеют.
КАМЕРА_ГОР = rig.КАМЕРА_ПОЛЕ_ГОР
ТОФ_ГОР = rig.ТОФ_ПОЛЕ_ГОР
ТОФ_ВЕРТ = rig.ТОФ_ПОЛЕ_ВЕРТ

# Насколько далеко замер может отстоять от подогнанной прямой, чтобы считаться
# своим. Доля, а не метры: на трёх метрах промах в десять сантиметров — норма,
# на тридцати сантиметрах — уже беда.
ПРОМАХ = 0.25

# Сколько опорных точек нужно, чтобы вообще браться. Двух хватает для двух
# неизвестных, но на двух любая помеха становится законом. Восемь — это
# восьмая часть сетки, ниже уже гадание.
ХВАТИТ_ТОЧЕК = 8


def зоны_в_пиксели(ширина: int, высота: int,
                   камера_гор: float = КАМЕРА_ГОР,
                   тоф_гор: float = ТОФ_ГОР,
                   тоф_верт: float = ТОФ_ВЕРТ) -> list[list[tuple[int, int]]]:
    """Куда в кадре смотрит каждая из 64 зон. Сетка 8×8 точек (x, y).

    Считается по углам, а не по калибровочной доске, и это осознанно: доска
    нужна, когда требуется сантиметровая точность привязки. Здесь опорные
    точки идут в подгонку двух чисел по всему кадру, и смещение на пару
    пикселей растворяется в шестидесяти четырёх замерах.

    Оба поля считаем от общего центра — датчик и камера стоят рядом и смотрят
    в одну сторону. Разнос между ними в несколько сантиметров даёт заметный
    сдвиг только вплотную, а вплотную нас интересует не картинка, а стоп.

    Соотношение сторон камеры учитывается: вертикальное поле выводится из
    горизонтального, а не берётся равным ему. Ошибка тут перекашивает всю
    сетку по вертикали, и нижние зоны начинают «смотреть» в потолок.
    """
    # Угол → пиксель по модели дырочной камеры. Для широких объективов она
    # врёт на краях, но зоны дальномера сидят в середине кадра, где врать ей
    # почти негде: 31 градус против 65.
    фокус_x = (ширина / 2.0) / math.tan(math.radians(камера_гор / 2.0))
    # Тот же фокус по вертикали: пиксели квадратные, значит фокус общий.
    фокус_y = фокус_x

    сетка: list[list[tuple[int, int]]] = []
    for ряд in range(8):
        строка: list[tuple[int, int]] = []
        # Ряд 0 — верх сетки, значит угол вверх, значит пиксель выше центра.
        угол_в = math.radians(тоф_верт * ((ряд + 0.5) / 8.0 - 0.5))
        for кол in range(8):
            угол_г = math.radians(тоф_гор * ((кол + 0.5) / 8.0 - 0.5))
            x = int(round(ширина / 2.0 + фокус_x * math.tan(угол_г)))
            y = int(round(высота / 2.0 + фокус_y * math.tan(угол_в)))
            строка.append((min(max(x, 0), ширина - 1),
                           min(max(y, 0), высота - 1)))
        сетка.append(строка)
    return сетка


def подогнать(отклик: list[float], метры: list[float]) -> tuple[float, float, int]:
    """Найти a и b в 1/метры = a·отклик + b, отбросив промахи.

    Возвращает (a, b, сколько точек приняли). Ноль точек — подгонка не вышла.

    Отбраковка нужна не для красоты. Часть зон смотрит в пол, часть ловит
    отражение от стекла, часть меряет край предмета, попадая между двумя
    глубинами. Обычный метод наименьших квадратов такие точки не отбрасывает,
    а честно тянет к ним всю прямую — и портит остальные шестьдесят.
    """
    if len(отклик) < 2:
        return 0.0, 0.0, 0
    x = np.asarray(отклик, dtype=float)
    y = 1.0 / np.asarray(метры, dtype=float)

    беру = np.ones(len(x), dtype=bool)
    a = b = 0.0
    # Два прохода: подогнали по всем, отбросили выпавших, подогнали снова.
    # Третий проход ничего не меняет — проверено на живых данных в работах по
    # depth completion, и здесь мы не умнее.
    for _ in range(2):
        if беру.sum() < 2:
            return 0.0, 0.0, 0
        a, b = np.polyfit(x[беру], y[беру], 1)
        предсказано = a * x + b
        # Промах меряем по самой величине: доля, а не абсолют.
        с_чем_сравнить = np.maximum(np.abs(y), 1e-6)
        беру = np.abs(предсказано - y) / с_чем_сравнить <= ПРОМАХ
    return float(a), float(b), int(беру.sum())


def в_метры(глубина: np.ndarray, сетка_тоф: list[list[float]],
            соответствие: list[list[tuple[int, int]]] | None = None,
            ) -> tuple[np.ndarray | None, str]:
    """Плотная относительная глубина + сетка дальномера → метры.

    Возвращает (карта в метрах, объяснение). Карта None — привязать не вышло,
    и объяснение говорит почему. Молча возвращать неметрическую карту нельзя:
    её примут за метры и поедут по ней.
    """
    высота, ширина = глубина.shape[:2]
    точки = соответствие or зоны_в_пиксели(ширина, высота)

    отклик: list[float] = []
    метры: list[float] = []
    for ряд in range(8):
        for кол in range(8):
            расстояние = сетка_тоф[ряд][кол]
            if расстояние <= 0.0:
                continue          # зона не измерила — опорой быть не может
            x, y = точки[ряд][кол]
            отклик.append(float(глубина[y, x]))
            метры.append(расстояние)

    if len(отклик) < ХВАТИТ_ТОЧЕК:
        return None, f"опорных точек всего {len(отклик)}, нужно {ХВАТИТ_ТОЧЕК}"

    a, b, принято = подогнать(отклик, метры)
    if принято < ХВАТИТ_ТОЧЕК:
        return None, f"подгонка не сошлась, приняла {принято} точек из {len(отклик)}"

    обратные = a * глубина.astype(float) + b
    # Ноль и отрицательные обратные величины означают «бесконечно далеко» и
    # «за спиной» — оба ответа для карты занятости бессмысленны. Отмечаем их
    # нулём, то есть «не знаю», а не огромным числом: пустота на карте
    # честнее выдуманного простора.
    годные = обратные > 1e-6
    карта = np.zeros_like(обратные)
    карта[годные] = 1.0 / обратные[годные]
    return карта, f"привязано по {принято} точкам из {len(отклик)}"


def занятость(карта: np.ndarray, порог: float = 1.5) -> list[float]:
    """Свернуть карту глубины в профиль «как далеко свободно» по колонкам.

    Восемь чисел слева направо — заготовка для карты занятости и для ответа
    «свободен ли путь». Берём НИЖНЮЮ половину кадра: верх — это стены выше
    робота и потолок, ехать он туда не собирается.

    Ноль означает «не знаю», и в занятости он должен остаться нулём: принять
    незнание за свободу — это и есть тот случай, когда робот уезжает в
    стеклянную дверь.
    """
    высота, ширина = карта.shape[:2]
    низ = карта[высота // 2:, :]
    профиль: list[float] = []
    for i in range(8):
        полоса = низ[:, i * ширина // 8:(i + 1) * ширина // 8]
        живое = полоса[полоса > 0.0]        # ноль — «не знаю», не «свободно»
        профиль.append(float(min(живое.min(), порог)) if живое.size else 0.0)
    return профиль
