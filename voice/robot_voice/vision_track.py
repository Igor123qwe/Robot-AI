"""Где человек в кадре — по детектору тела, считающему на BPU.

Зачем понадобилось. Следование до сих пор велось ОДНИМ дальномером: восемь
колонок на шестьдесят градусов. Шаг человека вбок — и он вне поля зрения,
шесть секунд, «Больше не иду». Ровно это и было в живом журнале.

У камеры сто тридцать градусов, и она удержит человека там, где дальномер уже
потерял. Плюс дальномер не знает, ЧТО перед ним: стул на пути и человек для
него одинаковые восемь чисел. Детектор знает.

Считает это не облачная модель, а свёрточная сеть на BPU — та самая, что уже
лежит в TogetheROS (`mono2d_body_detection`). Разница принципиальна: облако
отвечает две-четыре секунды, а следование требует решения десять раз в
секунду. В тридцать раз мимо — это не «медленнее», это негодный инструмент.
Свёрточная сеть на плате даёт десятки кадров в секунду локально и бесплатно.

РАЗБОР СООБЩЕНИЯ НАМЕРЕННО ТЕРПИМЫЙ. Форму `ai_msgs/PerceptionTargets` я
живьём не видел, а версии таких пакетов расходятся в мелочах: где-то рамка
зовётся `rect`, где-то `bbox`, координаты бывают углами и бывают центром с
размером. Прибитый разбор означал бы, что обновление пакета молча ломает
следование — а молча оно и так выглядит как «робот перестал ходить». Поэтому
берём то, что найдём, и ПЕРВОЕ пришедшее сообщение печатаем в журнал целиком:
подогнать разбор по одной строке лога — минута, гадать по молчащему роботу —
вечер.
"""

from __future__ import annotations

import json
import logging
import math
import time

log = logging.getLogger(__name__)

# Топик детектора тела в TogetheROS. Меняется настройкой: у разных сборок и
# разных запусков имя может отличаться, а пересобирать робота из-за строки
# незачем.
ТОПИК = "/hobot_mono2d_body_detection"
ТИП = "ai_msgs/msg/PerceptionTargets"

# Что считаем человеком. Детектор отдаёт тело, голову, лицо и руки; нам нужно
# тело, а при его отсутствии сойдёт голова — по ней пеленг не хуже.
ЧЕЛОВЕК = ("body", "person", "head")

# Сколько живёт последняя отметка. Полсекунды: детектор идёт десятки кадров в
# секунду, и если он замолчал дольше, значит человек вышел из кадра или узел
# упал. Держаться за отметку старше — это вести робота по памяти туда, где
# человека уже нет.
ЖИВЁТ = 0.5

# Через сколько отпустить пропавшую цель. Номера детектор выдаёт по порядку и
# рано или поздно повторяет; держаться за номер, которого не видели полминуты,
# значит однажды пойти за чужим человеком со случайно совпавшим номером.
ОТПУСКАЕМ_ЧЕРЕЗ = 30.0

# Поле зрения камеры по горизонтали, градусов. DECXIN AR0234 — 130°.
ПОЛЕ_КАМЕРЫ = 130.0

# Ширина кадра, который разбирает детектор. Знать её ОБЯЗАТЕЛЬНО и взять
# неоткуда: в PerceptionTargets размеров кадра нет вовсе — ни ширины, ни
# высоты, проверено по определению сообщения. А без ширины рамка в пикселях
# ничего не говорит о направлении.
#
# Шестьсот сорок — то, что публикует hobot_usb_cam в запуске по умолчанию
# («Recved img encoding: nv12, h: 480, w: 640»), хотя сама камера умеет
# 1920x1200. Ошибиться здесь втрое — значит втрое ошибиться в пеленге и
# уверенно ехать мимо человека.
ШИРИНА_КАДРА = 640.0


def _числа(узел, ключи) -> float | None:
    """Достать число из словаря по любому из синонимов."""
    if not isinstance(узел, dict):
        return None
    for ключ in ключи:
        if ключ in узел:
            try:
                return float(узел[ключ])
            except (TypeError, ValueError):
                return None
    return None


def середина_рамки(рамка) -> tuple[float, float] | None:
    """Центр рамки и её ширина в пикселях. None — рамку не разобрали.

    Три вида записи, и все три встречаются у пакетов этого семейства:
    углы (x_offset/y_offset + width/height), две точки (x1,y1,x2,y2) и центр
    с размером. Разбираем все — стоит это десять строк, а угадывание стоит
    вечера отладки на роботе.
    """
    if not isinstance(рамка, dict):
        return None
    лево = _числа(рамка, ("x_offset", "x1", "left", "x"))
    ширина = _числа(рамка, ("width", "w"))
    право = _числа(рамка, ("x2", "right"))

    if лево is not None and ширина is not None:
        return лево + ширина / 2.0, ширина
    if лево is not None and право is not None:
        return (лево + право) / 2.0, abs(право - лево)
    центр = _числа(рамка, ("center_x", "cx"))
    if центр is not None and ширина is not None:
        return центр, ширина
    return None


def высота_рамки(рамка) -> tuple[float, float] | None:
    """Высота рамки в пикселях и её нижний край. None — не разобрали.

    Нужна для расстояния по размеру человека — способа, которым это делают
    все. Нижний край отдаём отдельно: рамка, упирающаяся в край кадра,
    обрезана, и её высота уже не про рост, а про то, где кончился кадр.
    """
    if not isinstance(рамка, dict):
        return None
    верх = _числа(рамка, ("y_offset", "y1", "top", "y"))
    высота = _числа(рамка, ("height", "h"))
    низ = _числа(рамка, ("y2", "bottom"))
    if верх is not None and высота is not None:
        return высота, верх + высота
    if верх is not None and низ is not None:
        return abs(низ - верх), max(верх, низ)
    return None


def найти_человека(сообщение, держим: int = 0):
    """Центр рамки, ширина, номер цели и пиксель ног. None — человека нет.

    `держим` — за кем идём сейчас. Детектор сам ведёт нумерацию целей
    (`track_id`) между кадрами, и это лучше любой нашей эвристики: пока номер
    тот же, человек тот же, даже если он присел, отвернулся или мимо прошёл
    кто-то ближе.

    Своего не нашли — берём САМОГО ШИРОКОГО: он ближе всех, а начинать
    следование надо за тем, кто рядом, а не за прохожим в глубине кадра.
    """
    цели = сообщение.get("targets") or сообщение.get("perceptions") or []
    if not isinstance(цели, list):
        return None
    лучшее = None
    свой = None
    for цель in цели:
        if not isinstance(цель, dict):
            continue
        вид = str(цель.get("type") or цель.get("class_name") or "").lower()
        номер = int(цель.get("track_id") or 0)
        рамки = цель.get("rois") or цель.get("rois_") or []
        if not isinstance(рамки, list):
            continue
        # Тело предпочитаем голове: по нему пеленг устойчивее, голова
        # мотается. Поэтому сортируем рамки так, чтобы тело шло первым.
        for roi in sorted(рамки, key=_сначала_тело):
            имя = str((roi or {}).get("type") or вид).lower()
            if not any(с in имя for с in ЧЕЛОВЕК):
                continue
            разбор = середина_рамки((roi or {}).get("rect")
                                    or (roi or {}).get("bbox") or roi)
            if разбор is None:
                continue
            прямоугольник = ((roi or {}).get("rect")
                             or (roi or {}).get("bbox") or roi)
            по_высоте = высота_рамки(прямоугольник)
            найдено = (разбор[0], разбор[1], номер, ноги(цель),
                       по_высоте[0] if по_высоте else 0.0,
                       по_высоте[1] if по_высоте else 0.0)
            if держим and номер == держим:
                свой = найдено
            if лучшее is None or разбор[1] > лучшее[1]:
                лучшее = найдено
            break               # с этой цели хватит одной рамки
    return свой or лучшее


def _сначала_тело(roi) -> int:
    имя = str((roi or {}).get("type") or "").lower()
    return 0 if "body" in имя else 1


def ноги(цель) -> float | None:
    """Пиксель, на котором человек касается пола. None — скелета нет.

    Берём САМУЮ НИЖНЮЮ точку скелета, а не «щиколотку номер такой-то». Номера
    точек у разных выпусков детектора разные, а «ниже всех» — это ноги при
    любом соглашении. Приём стоит одной строки и переживает обновление модели.

    Зачем это нужно. Точка касания с полом — единственное место человека,
    расстояние до которого можно узнать по одной картинке: всё остальное
    висит в воздухе и зависит от роста. Человек может быть худым, толстым,
    ребёнком или в шубе — ноги у всех стоят на полу.
    """
    точки = (цель or {}).get("points") or []
    if not isinstance(точки, list):
        return None
    ниже_всех = None
    for набор in точки:
        если_список = (набор or {}).get("point") or []
        if not isinstance(если_список, list):
            continue
        for т in если_список:
            y = _числа(т, ("y",))
            if y is None:
                continue
            # Ноль-ноль детектор ставит там, где точку не нашёл. Считать её
            # ногой — значит померить расстояние до верхнего края кадра.
            if y <= 0:
                continue
            if ниже_всех is None or y > ниже_всех:
                ниже_всех = y
    return ниже_всех


class Дальномер_по_ногам:
    """Расстояние до человека по одной камере. Учится сам, пока может.

    Геометрию камеры относительно дальномера мы не знаем и знать не хотим:
    её пришлось бы мерить линейкой, записывать в настройку и переписывать
    после каждого раза, когда камеру задели. Вместо этого робот ВЫУЧИВАЕТ
    связь сам — пока оба датчика видят человека одновременно.

    Связь эта простая и следует из устройства камеры. Человек стоит на полу;
    чем он дальше, тем выше в кадре точка касания. Для камеры с обычной
    оптикой расстояние обратно пропорционально тому, насколько ноги ниже
    линии горизонта:

        d = k / (y - y0)

    Два неизвестных: k (высота камеры, делённая на угловой масштаб) и y0
    (где в кадре горизонт). Оба находятся по нескольким парам «пиксель ног —
    расстояние с дальномера», которые робот собирает сам, идя за человеком.

    Ради чего. Дальномер видит шестьдесят градусов, камера — сто тридцать.
    Человек, шагнувший вбок, для дальномера пропал, и робот до сих пор мог
    только доворачиваться вслепую. С выученной связью он знает и НАПРАВЛЕНИЕ,
    и РАССТОЯНИЕ по одной камере — то есть продолжает идти за человеком там,
    где дальномер уже ничего не говорит.
    """

    # Сколько пар нужно, чтобы поверить. Меньше пяти — это подгонка прямой
    # по двум точкам, где любая ошибка замера становится законом.
    ПАР_ХВАТИТ = 8
    # Насколько далеко друг от друга должны стоять пары по расстоянию. Пары,
    # снятые с одного места, задают прямую с любым наклоном.
    РАЗБЕГ = 0.5
    # Сколько пар помним. Старые выбрасываем: камеру могли задеть, и связь
    # обязана переучиваться, а не держаться за вчерашнее.
    ПОМНИМ = 60
    # Насколько в среднем можно промахиваться, чтобы всё ещё считать связь
    # найденной. Пятнадцать процентов — это двадцать сантиметров на полутора
    # метрах: терпимо для следования и заведомо мало для случайного набора,
    # где промах уходит за сотню.
    ПРОМАХ_ПРЕДЕЛ = 0.15

    def __init__(self) -> None:
        self.пары: list[tuple[float, float]] = []
        self.k = 0.0
        self.y0 = 0.0
        self._сказал = False

    @property
    def выучен(self) -> bool:
        return self.k > 0.0

    def запомнить(self, пиксель: float, расстояние: float) -> None:
        """Пара «ноги в кадре — метры с дальномера». Зовётся, когда видят оба."""
        if пиксель <= 0 or not (0.3 <= расстояние <= 3.0):
            # Ближе тридцати сантиметров дальномер врёт засветкой, дальше
            # трёх метров — почти не отвечает. Учиться на этом нельзя.
            return
        self.пары.append((пиксель, расстояние))
        if len(self.пары) > self.ПОМНИМ:
            self.пары.pop(0)
        self._пересчитать()

    def _пересчитать(self) -> None:
        if len(self.пары) < self.ПАР_ХВАТИТ:
            return
        дальности = [д for _п, д in self.пары]
        if max(дальности) - min(дальности) < self.РАЗБЕГ:
            return
        # d = k/(y - y0)  ⇔  1/d = y/k - y0/k — то есть обратное расстояние
        # линейно по пикселю. Подгоняем прямую наименьшими квадратами: так
        # задача из нелинейной становится школьной.
        n = float(len(self.пары))
        sy = sum(п for п, _д in self.пары)
        sq = sum(1.0 / д for _п, д in self.пары)
        syy = sum(п * п for п, _д in self.пары)
        syq = sum(п / д for п, д in self.пары)
        низ = n * syy - sy * sy
        if abs(низ) < 1e-9:
            return
        a = (n * syq - sy * sq) / низ           # наклон, 1/(м·пиксель)
        b = (sq - a * sy) / n                   # свободный член
        if a <= 1e-9:
            # Обратное расстояние обязано РАСТИ с пикселем: ниже в кадре —
            # ближе. Иначе это не пол, а что-то другое, и учиться нечему.
            return

        k, y0 = 1.0 / a, -b / a

        # А ТЕПЕРЬ САМОЕ ВАЖНОЕ: проверить, что прямая вообще описывает эти
        # точки. Наименьшие квадраты проведут прямую через что угодно, включая
        # случайный набор, и вернут красивые числа — без единого признака
        # того, что связи нет.
        #
        # Поймано своей же проверкой: на выдуманном мусоре, где расстояние
        # прыгало между метром и полутора независимо от пикселя, эта штука
        # объявила себя выученной. Робот, поверивший такому расстоянию, поехал
        # бы на человека уверенно и молча — худшее из возможного.
        промах = 0.0
        for пиксель, правда in self.пары:
            если_ниже = пиксель - y0
            сказали = k / если_ниже if если_ниже > 1e-6 else 0.0
            промах += abs(сказали - правда) / max(правда, 0.1)
        промах /= len(self.пары)
        if промах > self.ПРОМАХ_ПРЕДЕЛ:
            if self.выучен:
                log.info("расстояние по ногам разъехалось (промах %.0f%%) — "
                         "забываю и учусь заново", промах * 100)
            self.k = self.y0 = 0.0
            self._сказал = False
            return

        self.k, self.y0 = k, y0
        if not self._сказал:
            self._сказал = True
            log.info("расстояние по ногам выучено: горизонт на %.0f-м "
                     "пикселе, промах %.0f%%, по %d парам",
                     y0, промах * 100, len(self.пары))

    def сколько(self, пиксель: float) -> float:
        """Метры до человека по пикселю его ног. Ноль — не знаю."""
        if not self.выучен or пиксель <= self.y0:
            return 0.0
        д = self.k / (пиксель - self.y0)
        # За пределами, на которых учились, не отвечаем: прямая, продолженная
        # вдаль, даёт красивые числа и никакого отношения к правде.
        return д if 0.3 <= д <= 4.0 else 0.0


class Дальномер_по_росту:
    """Расстояние до человека по ВЫСОТЕ его рамки в кадре.

    Так это делают все, и не зря. Из простой оптики: предмет известной
    высоты H на расстоянии d занимает в кадре h = f·H/d пикселей, где f —
    фокусное расстояние в пикселях. Значит d = f·H/h.

    ЧЕМ ЭТО ЛУЧШЕ РАССТОЯНИЯ ПО НОГАМ, которое здесь уже есть. Тот способ
    хитрее и точнее в теории, но требует, чтобы дальномер и камера сперва
    договорились: пары «пиксель ног — метры» собираются, только когда оба
    видят одного человека. На живом роботе они не договорились ни разу — в
    журнале за одну минуту четыре переучивания подряд, «промах 15%», и
    «горизонт на -946-м пикселе», то есть заведомая чушь.

    Рамка же есть в КАЖДОМ кадре, где детектор нашёл человека, и не зависит
    ни от дальномера, ни от того, попал ли человек в его шестьдесят
    градусов. Способ работает сразу, с первого кадра.

    Фокусное берём из поля зрения камеры — считать нечего, это геометрия:
    f = (ширина кадра / 2) / tg(поле / 2). Рост по умолчанию человеческий; он
    и есть единственная неточность способа, и она честная — люди отличаются
    ростом на десяток процентов, а не в разы.

    А когда дальномер всё-таки подтверждает расстояние, рост уточняется под
    ЭТОГО человека. Тогда способ становится точным, но и без уточнения он
    остаётся рабочим — в отличие от расстояния по ногам.
    """

    # Рост человека по умолчанию. Не «средний по стране», а такой, чтобы
    # ошибка была симметричной: и ребёнок, и высокий взрослый отстоят от него
    # примерно одинаково.
    РОСТ = 1.7
    # Сколько пар нужно, чтобы поверить уточнённому росту.
    ПАР_ХВАТИТ = 12
    # Сколько пар помним.
    ПОМНИМ = 60
    # Насколько уточнённый рост может отличаться от обычного человеческого.
    # Вдвое — это уже не человек, а ошибка разбора, и верить ей нельзя.
    РОСТ_ОТ, РОСТ_ДО = 1.0, 2.2

    def __init__(self, ширина_кадра: float = ШИРИНА_КАДРА,
                 поле: float = ПОЛЕ_КАМЕРЫ) -> None:
        self.фокус = (ширина_кадра / 2.0) / math.tan(math.radians(поле / 2.0))
        self.рост = self.РОСТ
        self.пары: list[tuple[float, float]] = []
        self._сказал = False

    def сколько(self, высота_пикселей: float) -> float:
        """Метры до человека. Ноль — рамки нет или она нелепая."""
        if высота_пикселей <= 1.0:
            return 0.0
        д = self.фокус * self.рост / высота_пикселей
        # За пределами разумного не отвечаем: рамка в два пикселя даст
        # сто метров, и робот поверит.
        return д if 0.3 <= д <= 6.0 else 0.0

    def запомнить(self, высота_пикселей: float, расстояние: float) -> None:
        """Дальномер подтвердил метры — уточняем рост ЭТОГО человека."""
        if высота_пикселей <= 1.0 or not (0.4 <= расстояние <= 3.0):
            return
        self.пары.append((высота_пикселей, расстояние))
        if len(self.пары) > self.ПОМНИМ:
            self.пары.pop(0)
        if len(self.пары) < self.ПАР_ХВАТИТ:
            return
        # H = d·h/f для каждой пары; берём медиану, а не среднее: один
        # промах дальномера по мебели не должен утащить рост.
        ростки = sorted(д * h / self.фокус for h, д in self.пары)
        рост = ростки[len(ростки) // 2]
        if not (self.РОСТ_ОТ <= рост <= self.РОСТ_ДО):
            return
        self.рост = рост
        if not self._сказал:
            self._сказал = True
            log.info("расстояние по росту уточнено: %.2f м по %d парам",
                     рост, len(self.пары))


class Глазомер:
    """Последнее, что видел детектор: где человек и когда это было."""

    def __init__(self, ширина_кадра: float = ШИРИНА_КАДРА,
                 поле: float = ПОЛЕ_КАМЕРЫ) -> None:
        self.ширина_кадра = ширина_кадра
        self.поле = поле
        self._угол = 0.0
        self._доля = 0.0
        self._когда = 0.0
        self._кадров = 0
        self._показал = False
        # За кем идём. Ноль — ещё ни за кем; ставится по первой детекции и
        # держится, пока цель не пропала надолго. Без этого робот на кухне
        # переключался бы с человека на человека, стоило кому-то пройти ближе.
        self.держим = 0
        # Пиксель, на котором человек касается пола, и выученная связь
        # «пиксель — метры». Вместе они дают расстояние по одной камере там,
        # где дальномера не хватает.
        self.ноги_пиксель = 0.0
        self.по_ногам = Дальномер_по_ногам()
        # Высота рамки человека и её нижний край. Отсюда расстояние по
        # размеру — способ, который работает с первого кадра и не зависит
        # от дальномера.
        self.высота_рамки = 0.0
        self.низ_рамки = 0.0
        self.по_росту = Дальномер_по_росту(ширина_кадра, поле)

    # --- со стороны ROS ---------------------------------------------------
    def принять(self, сообщение) -> None:
        if not self._показал:
            self._показал = True
            log.info("детектор тела: первое сообщение выглядит так: %s",
                     json.dumps(сообщение, ensure_ascii=False)[:700])
        # Ширину кадра в сообщении ищем на всякий случай — вдруг соседний
        # детектор её всё же кладёт, — но рассчитывать на неё нельзя: в
        # PerceptionTargets её нет. Значит настройка обязана быть верной.
        ширина = _числа(сообщение, ("image_width", "width")) or self.ширина_кадра
        # Цель, пропавшую надолго, отпускаем. Номера детектор выдаёт по
        # порядку и рано или поздно повторяет; держаться за номер, которого
        # не видели минуту, значит однажды пойти за чужим человеком, у
        # которого случайно совпал номер.
        if self.держим and self._когда and not self.свежий:
            if time.monotonic() - self._когда > ОТПУСКАЕМ_ЧЕРЕЗ:
                log.info("детектор тела: цель %d пропала — отпускаю", self.держим)
                self.держим = 0

        найдено = найти_человека(сообщение, self.держим)
        if найдено is None:
            return
        центр, _, номер, ноги_y, высота, низ = найдено
        if номер and номер != self.держим:
            if self.держим and self.свежий:
                # Своего видим — чужого не берём. Сюда попадаем, только когда
                # своего в кадре нет.
                return
            log.info("детектор тела: веду цель %d", номер)
            self.держим = номер
        # Пиксель → угол. Левее центра кадра — положительный угол (влево),
        # как и у дальномера: две системы отсчёта в одной задаче однажды
        # сложатся с разными знаками, и робот поедет от человека.
        доля = (ширина / 2.0 - центр) / max(1.0, ширина / 2.0)
        self._доля = доля
        self._угол = доля * math.radians(self.поле) / 2.0
        self.ноги_пиксель = ноги_y or 0.0
        # Рамка, упирающаяся в нижний край кадра, ОБРЕЗАНА: её высота говорит
        # не о росте человека, а о том, где кончился кадр. Это не мелочь —
        # ближе метра человек в кадр не влезает целиком, и без этой проверки
        # робот считал бы его далёким ровно тогда, когда тот ближе всего.
        высота_кадра = ширина / 4.0 * 3.0        # кадр 4:3, как у нас
        self.высота_рамки = (высота if высота > 1.0
                             and низ < высота_кадра - 4.0 else 0.0)
        self.низ_рамки = низ
        self._когда = time.monotonic()
        self._кадров += 1

    # --- со стороны следования -------------------------------------------
    @property
    def свежий(self) -> bool:
        return bool(self._когда) and time.monotonic() - self._когда < ЖИВЁТ

    @property
    def угол(self) -> float:
        """Куда повернуться, радианы. Положительно — влево."""
        return self._угол

    @property
    def кадров(self) -> int:
        return self._кадров

    # --- расстояние по одной камере --------------------------------------
    def сверить(self, метры: float) -> None:
        """Дальномер сказал, сколько до человека, — запоминаем пару.

        Зовётся из следования, когда ОБА датчика видят одного и того же
        человека. Из этих пар и складывается связь «пиксель ног — метры».

        Учиться на ходу, а не по разметке линейкой, здесь не роскошь: высота и
        наклон камеры меняются от того, что её задели или переставили, и
        записанные однажды числа устареют молча. Пары же собираются заново
        каждый раз, когда робот идёт за человеком.
        """
        if not self.свежий:
            return
        if self.ноги_пиксель > 0:
            self.по_ногам.запомнить(self.ноги_пиксель, метры)
        if self.высота_рамки > 0:
            self.по_росту.запомнить(self.высота_рамки, метры)

    @property
    def далеко_ли(self) -> float:
        """Метры до человека по одной камере. Ноль — не знаю.

        Ради этого всё и делалось. Дальномер видит шестьдесят градусов, камера
        — сто тридцать. Человек, шагнувший вбок, для дальномера пропал, и до
        сих пор робот мог только доворачиваться вслепую, не зная, догонять его
        или притормозить. Теперь знает.
        """
        if not self.свежий:
            return 0.0
        # СНАЧАЛА ПО РОСТУ. Он работает с первого кадра и не требует, чтобы
        # дальномер с камерой договорились; по ногам — точнее, но на живом
        # роботе он не выучился ни разу: четыре переучивания за минуту и
        # «горизонт на -946-м пикселе». Точный способ, который не работает,
        # хуже приблизительного, который работает.
        if self.высота_рамки > 0:
            по_росту = self.по_росту.сколько(self.высота_рамки)
            if по_росту:
                return по_росту
        if self.ноги_пиксель > 0:
            return self.по_ногам.сколько(self.ноги_пиксель)
        return 0.0

    def забыть(self) -> None:
        """Отпустить цель — следование кончилось или человек потерян насовсем."""
        self.держим = 0
        self._когда = 0.0

    def подписка(self) -> dict:
        """Что послать rosbridge, чтобы получать детекции."""
        return {"op": "subscribe", "topic": ТОПИК, "type": ТИП,
                "throttle_rate": 50}
