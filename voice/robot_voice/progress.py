"""Едем ли мы на самом деле. Сторож застревания.

ЧЕГО НЕ ХВАТАЛО. У обычной поездки («проедь два метра») такая проверка есть
давно: ros.ехать смотрит одометрию каждый круг и через полторы секунды
неподвижности объявляет «кажется, я во что-то упёрся». У СЛЕДОВАНИЯ её не
было вовсе — а следование как раз и есть то, что робот делает подолгу и в
тесноте.

Из-за этого любая беда с ходовой частью во время следования выглядела
одинаково: робот стоит и молчит. Человек видит неподвижного робота, который
перед этим бодро сказал «Иду за тобой», и решает, что тот сломался или врёт.
Так и было: разбираться приходилось по журналу, вручную, задним числом.

Почему не позвать ту же проверку из ros.ехать. Она устроена под ОДНУ
поездку с заранее известным путём и судит по соседним замерам: сдвинулся ли
робот хоть на полсантиметра за кадр. Для следования этого мало — там команда
меняется пятнадцать раз в секунду, робот законно и часто стоит (человек
близко, сторож не пускает, доворачиваемся на месте), и «не сдвинулся за
кадр» там не значит ничего. Судить надо по ОКНУ: сколько всего велели за
последние секунды против того, сколько всего вышло.

Причин у «командую, а не еду» ровно три, и все три настоящие:
  • колесо во что-то упёрлось — ножка стула, порог, провод, ковёр;
  • контроллер не принял команду (или её не довёз rosbridge);
  • одометрия встала, и тогда врёт ещё и карта.
Различить их отсюда нельзя, а СООБЩИТЬ о том, что что-то из этого случилось,
можно и нужно.

ПОЧЕМУ НЕ ПЯТИМСЯ. У настоящих роботов на этом месте стоят «поведения
восстановления»: сдать назад, крутнуться, попробовать иначе. Нам нельзя:
дальномер смотрит вперёд, сзади слепая зона, а застревание чаще всего
случается ровно там, где тесно. Робот, который на застревании начинает
пятиться вслепую, опаснее робота, который встал и сказал.

Поэтому здесь только одно действие: остановиться и объяснить. Остальное —
дело человека, и он справится за две секунды, если ему сказать.

КАК СУДИМ. Копим окно последних секунд: что командовали и где были по
одометрии. Дальше два независимых сравнения.

  Ход:     сколько метров велели проехать против того, на сколько метров
           сместились от начала окна до конца.
  Поворот: сколько радиан велели повернуть против накопленной суммы
           поворотов между соседними замерами.

Смещение берём ОТ КРАЯ ДО КРАЯ, а не суммой шагов, нарочно: шум одометрии в
сумме шагов накапливается (тридцать замеров по миллиметру — это уже три
сантиметра «хода» у совершенно неподвижного робота) и замаскировал бы ровно
то, что мы ищем. От края до края шум не копится.

А вот повороты складываем ПО ШАГАМ и СО ЗНАКОМ. Разность курсов пришлось бы
разворачивать через ±π, и робот, крутящийся быстро, показал бы почти ноль —
то есть выглядел бы застрявшим именно тогда, когда он заведомо не застрял.
Знак у суммы малых шагов гасит шум не хуже, а через π ничего не переносится.
"""

from __future__ import annotations

import logging
import math
import time

log = logging.getLogger(__name__)

# За какое окно судим. Две с половиной секунды: короче — попадём на разгон
# (робот честно трогается и за первые полсекунды проезжает сантиметры),
# длиннее — человек успеет уйти, пока робот думает.
ЗА_СКОЛЬКО = 2.5

# С какой скорости шасси ОБЯЗАНО тронуться. Ниже неё молчим, что бы ни
# показала одометрия: тележка на ковре при десяти сантиметрах в секунду может
# и не поехать, и это не поломка, а нижняя граница здравого смысла.
#
# Первая редакция этого файла считала иначе — складывала команду за окно и
# сравнивала сумму с порогом. Так «полсекунды ехали, две стояли» давало те же
# шестнадцать сантиметров, что и «две с половиной секунды ползли», и на живом
# роботе сторож дважды объявил застревание там, где робот просто держал
# дистанцию до человека:
#
#   велел проехать 0.16 м, а сдвинулся на 0.00 м
#
# Шестнадцать сантиметров за две с половиной секунды — это шесть сантиметров
# в секунду средних, то есть команда, от которой шасси и не должно поехать.
# Улика оказалась не уликой.
ТРОГАЕТСЯ_ОТ = 0.10

# То же для поворота на месте — и здесь порог НЕ УГАДАН, а посчитан, потому
# что угаданный уже соврал.
#
# Стояло 0.30 рад/с, и на живом роботе сторож объявил застревание на команде
# 0.35 рад/с. Считаем, что это значит для колёс. При развороте на месте
# колесо едет со скоростью w · плечо, где плечо — расстояние от центра
# платформы до колеса. У WD550 колёсная база 19.5 см, то есть плечо от 0.0975
# (только вдоль) до 0.14 м (по диагонали, если колея примерно такая же).
#
# Значит при 0.35 рад/с колесо идёт 3.4–4.9 см/с. Это ВТРОЕ МЕДЛЕННЕЕ той
# скорости, с которой мы вообще готовы утверждать, что шасси обязано
# тронуться. Меканум с его роликами на ковре при четырёх сантиметрах в
# секунду может честно стоять.
#
# Отсюда порог: 0.10 м/с на плече 0.11–0.14 м — это 0.7–1.0 рад/с. Берём
# осторожный край. Сторож останавливает поездку и говорит человеку вслух;
# промолчать зря дешевле, чем зря обвинить.
#
# Следствие, и его надо знать: проверка поворота теперь срабатывает только на
# командах, близких к предельной (ПОВОРОТ_МАКС = 1.0). На спокойных
# доворотах робот про застревание молчит — не потому, что не смотрит, а
# потому, что на такой скорости отличить «упёрся» от «слишком медленно, чтобы
# сдвинуться» нечем, и делать вид, что есть, нельзя.
КРУТИТСЯ_ОТ = 0.9

# Сколько секунд подряд команда должна БЫТЬ ВЫШЕ этого порога, прежде чем
# молчание колёс станет уликой. Полторы секунды: разгон занимает доли
# секунды, а полторы секунды непрерывной команды — это уже не заминка.
ВЕЛЕЛИ_ДОЛЬШЕ = 1.5

# Насколько мало надо сместиться, чтобы это считалось «не поехал». Пять
# сантиметров — заведомо больше шума одометрии и заведомо меньше того, что
# получается при живых колёсах за полторы секунды хода.
ПРОЕХАЛИ_МЕНЬШЕ = 0.05
# То же по углу: меньше шести градусов за полторы секунды команды — это не
# поворот.
ПОВЕРНУЛИ_МЕНЬШЕ = 0.1

# Как часто повторять жалобу. Десять секунд: за меньшее человек не успеет
# подойти, а робот забормочет одно и то же.
МОЛЧИМ = 10.0

# Замеры старше этого выбрасываем как разрыв, а не как часть окна. Полсекунды
# без единого кадра — это уже не «цикл", а пауза, и склеивать через неё
# «велели» с «получилось» нельзя.
РАЗРЫВ = 0.5


class Ход:
    """Сравнивает команду с одометрией и говорит, когда они разошлись.

    Заводится на одну поездку. `отметить` зовут каждый круг цикла, `беда` —
    сразу после; пустая строка значит «всё в порядке или судить не по чему».
    """

    def __init__(self, *, часы=time.monotonic) -> None:
        self._часы = часы
        self._замеры: list[tuple[float, float, float, float, float, float]] = []
        self._сказали = 0.0
        self._поворот_накоплен = 0.0

    # --- сбор ------------------------------------------------------------
    def забыть(self) -> None:
        """Начать копить заново. Зовут после жалобы и после остановки."""
        self._замеры.clear()
        self._поворот_накоплен = 0.0

    def отметить(self, вперёд: float, поворот: float, поза) -> None:
        """Что скомандовали и где оказались. `поза` — (x, y, курс) или None.

        Нет позы — нет и суда: без одометрии сравнивать команду не с чем.
        Копить при этом тоже нельзя, иначе после её возвращения окно склеится
        через дыру и покажет «не ехал» там, где робот ехал вслепую.
        """
        if поза is None:
            self.забыть()
            return
        try:
            x, y, курс = (float(поза[0]), float(поза[1]), float(поза[2]))
        except (TypeError, ValueError, IndexError):
            self.забыть()
            return
        сейчас = self._часы()
        if self._замеры and сейчас - self._замеры[-1][0] > РАЗРЫВ:
            self.забыть()
        self._замеры.append((сейчас, abs(float(вперёд)), abs(float(поворот)),
                             x, y, курс))
        self._подрезать()

    def _подрезать(self) -> None:
        край = self._часы() - ЗА_СКОЛЬКО
        лишние = 0
        for замер in self._замеры:
            if замер[0] >= край:
                break
            лишние += 1
        if лишние:
            del self._замеры[:лишние]
        # Сумму поворотов пересчитываем по окну целиком, а не правим при
        # каждом добавлении и выбрасывании. Замеров в окне четыре десятка,
        # цена этого — ничто, а вычитание выброшенного вручную — тот самый
        # вид кода, в котором однажды теряется знак и никто не замечает.
        накоплено = 0.0
        for номер in range(1, len(self._замеры)):
            было = self._замеры[номер - 1][5]
            стало = self._замеры[номер][5]
            накоплено += (стало - было + math.pi) % (2 * math.pi) - math.pi
        self._поворот_накоплен = накоплено

    # --- суд -------------------------------------------------------------
    def велели(self) -> tuple[float, float]:
        """Сколько СЕКУНД за окно велели всерьёз ехать и всерьёз крутиться.

        Секунды, а не метры, и это разница между уликой и совпадением. Сумма
        метров не различает «полсекунды ехали, две стояли» и «две с половиной
        секунды ползли»: числа выходят одинаковые, а смысл противоположный. В
        первом случае колёса просто не успели, во втором им действительно
        велели ехать и они не поехали.

        Считаем только то время, когда команда была ВЫШЕ порога, с которого
        шасси обязано тронуться. Всё, что ниже, — не команда, а дрожание.
        """
        едем = крутимся = 0.0
        for номер in range(1, len(self._замеры)):
            дt = self._замеры[номер][0] - self._замеры[номер - 1][0]
            if дt <= 0:
                continue
            # Команду берём ПРЕДЫДУЩУЮ: именно она действовала в этот промежуток.
            if self._замеры[номер - 1][1] >= ТРОГАЕТСЯ_ОТ:
                едем += дt
            if self._замеры[номер - 1][2] >= КРУТИТСЯ_ОТ:
                крутимся += дt
        return едем, крутимся

    def вышло(self) -> tuple[float, float]:
        """Сколько метров и радиан получилось на самом деле."""
        if len(self._замеры) < 2:
            return 0.0, 0.0
        первый, последний = self._замеры[0], self._замеры[-1]
        сдвиг = math.hypot(последний[3] - первый[3], последний[4] - первый[4])
        return сдвиг, abs(self._поворот_накоплен)

    def беда(self) -> str:
        """Пустая строка — всё в порядке. Иначе фраза для человека и журнала.

        Жалуемся не чаще раза в МОЛЧИМ секунд и каждый раз начинаем копить
        заново: одна и та же неподвижность не должна выдаваться за две.
        """
        if len(self._замеры) < 3:
            return ""
        если_окно = self._замеры[-1][0] - self._замеры[0][0]
        if если_окно < ЗА_СКОЛЬКО * 0.8:
            return ""
        сейчас = self._часы()
        if сейчас - self._сказали < МОЛЧИМ:
            return ""
        едем, крутимся = self.велели()
        проехали, повернули = self.вышло()
        причина = ""
        if едем >= ВЕЛЕЛИ_ДОЛЬШЕ and проехали < ПРОЕХАЛИ_МЕНЬШЕ:
            причина = (f"{едем:.1f} с подряд велел ехать, "
                       f"а сдвинулся на {проехали:.2f} м")
        elif крутимся >= ВЕЛЕЛИ_ДОЛЬШЕ and повернули < ПОВЕРНУЛИ_МЕНЬШЕ:
            причина = (f"{крутимся:.1f} с подряд велел крутиться, "
                       f"а повернулся на {math.degrees(повернули):.0f}°")
        if not причина:
            return ""
        self._сказали = сейчас
        self.забыть()
        log.warning("ход: застряли — %s", причина)
        return причина
