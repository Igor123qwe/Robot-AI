"""Числа, время и даты словами.

Всё, что говорит робот, уходит в Piper, а тот читает написанное буквально.
«14:35» он произносит как «четырнадцать двоеточие тридцать пять», «1.5 мин» —
как «один точка пять мин». Поэтому числа в репликах пишутся словами.

Модель это делает сама (так сказано в системном промпте), но правила и
инструменты отвечают в обход модели — им нужен такой же перевод.
"""

from __future__ import annotations

import re
from datetime import datetime

_UNITS = ("ноль", "один", "два", "три", "четыре", "пять", "шесть", "семь",
          "восемь", "девять", "десять", "одиннадцать", "двенадцать",
          "тринадцать", "четырнадцать", "пятнадцать", "шестнадцать",
          "семнадцать", "восемнадцать", "девятнадцать")
_TENS = {2: "двадцать", 3: "тридцать", 4: "сорок", 5: "пятьдесят",
         6: "шестьдесят", 7: "семьдесят", 8: "восемьдесят", 9: "девяносто"}
_HUNDREDS = ("", "сто", "двести", "триста", "четыреста", "пятьсот",
             "шестьсот", "семьсот", "восемьсот", "девятьсот")
# Женский род нужен минутам и секундам: «одна минута», «двадцать две секунды».
_FEMALE = {"один": "одна", "два": "две"}
# Винительный падеж — для «поставь таймер на одну минуту».
_FEMALE_ACC = {"один": "одну", "два": "две"}

_MONTHS = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля",
           "августа", "сентября", "октября", "ноября", "декабря")
_WEEKDAYS = ("понедельник", "вторник", "среда", "четверг", "пятница",
             "суббота", "воскресенье")
_ORDINALS = ("", "первое", "второе", "третье", "четвёртое", "пятое", "шестое",
             "седьмое", "восьмое", "девятое", "десятое", "одиннадцатое",
             "двенадцатое", "тринадцатое", "четырнадцатое", "пятнадцатое",
             "шестнадцатое", "семнадцатое", "восемнадцатое", "девятнадцатое",
             "двадцатое")


def cardinal(n: int, *, female: bool = False, accusative: bool = False) -> str:
    """Число словами, 0–999. Больше роботу не нужно: дальше идут метры и минуты."""
    n = int(n)
    if n < 0 or n > 999:
        return str(n)

    words = []
    hundreds, rest = divmod(n, 100)
    if hundreds:
        words.append(_HUNDREDS[hundreds])
    if rest or not hundreds:
        if rest < 20:
            words.append(_UNITS[rest])
        else:
            tens, unit = divmod(rest, 10)
            words.append(_TENS[tens])
            if unit:
                words.append(_UNITS[unit])

    if female:
        forms = _FEMALE_ACC if accusative else _FEMALE
        words[-1] = forms.get(words[-1], words[-1])
    return " ".join(words)


def plural(n: float, one: str, few: str, many: str) -> str:
    """Согласование существительного с числом: 1 минута, 2 минуты, 5 минут."""
    n = abs(int(n)) % 100
    if 11 <= n <= 14:
        return many
    n %= 10
    if n == 1:
        return one
    if 2 <= n <= 4:
        return few
    return many


def count(n: int, one: str, few: str, many: str, *,
          female: bool = False, accusative: bool = False) -> str:
    """Число с существительным: «пять минут», «двадцать два градуса»."""
    return (f"{cardinal(n, female=female, accusative=accusative)} "
            f"{plural(n, one, few, many)}")


def volts(v: float) -> str:
    """«двенадцать и четыре вольта» — десятичную точку вслух не читают."""
    whole = int(v)
    tenth = int(round((v - whole) * 10))
    if tenth == 10:
        whole, tenth = whole + 1, 0
    if not tenth:
        return count(whole, "вольт", "вольта", "вольт")
    return f"{cardinal(whole)} и {cardinal(tenth)} вольта"


def duration(seconds: float, *, accusative: bool = False) -> str:
    """Длительность словами: «девять минут», «час двадцать минут».

    accusative — для «поставил таймер на одну минуту».
    """
    total = max(0, int(round(seconds)))
    sec_forms = ("секунду" if accusative else "секунда", "секунды", "секунд")
    min_forms = ("минуту" if accusative else "минута", "минуты", "минут")
    if total < 60:
        return count(total, *sec_forms, female=True, accusative=accusative)

    minutes, sec = divmod(total, 60)
    hours, minutes = divmod(minutes, 60)
    parts = []
    if hours:
        parts.append(count(hours, "час", "часа", "часов"))
    if minutes:
        parts.append(count(minutes, *min_forms, female=True, accusative=accusative))
    # Секунды при часах — лишняя точность для разговора.
    if sec and not hours:
        parts.append(count(sec, *sec_forms, female=True, accusative=accusative))
    return " ".join(parts)


def clock(when: datetime | None = None) -> str:
    """Время словами: «четырнадцать часов тридцать пять минут»."""
    when = when or datetime.now()
    if not when.minute:
        return f"{_bare_clock(when)} ровно"
    return _bare_clock(when)


def _bare_clock(when: datetime) -> str:
    """То же без «ровно»: «в семь часов ровно» звучит по-канцелярски."""
    hours = count(when.hour, "час", "часа", "часов")
    if not when.minute:
        return hours
    return f"{hours} {count(when.minute, 'минута', 'минуты', 'минут', female=True)}"


def _ordinal(day: int) -> str:
    if day <= 20:
        return _ORDINALS[day]
    if day == 30:
        return "тридцатое"
    tens, unit = divmod(day, 10)
    return f"{_TENS[tens]} {_ORDINALS[unit]}"


def when_phrase(target: datetime, now: datetime | None = None) -> str:
    """«сегодня в семь часов», «завтра в семь часов тридцать минут»."""
    now = now or datetime.now()
    days = (target.date() - now.date()).days
    day = {0: "сегодня", 1: "завтра", 2: "послезавтра"}.get(days)
    if day is None:
        day = f"{_ordinal(target.day)} {_MONTHS[target.month - 1]}"
    return f"{day} в {_bare_clock(target)}"


def date(when: datetime | None = None) -> str:
    """Дата словами: «пятница, первое августа»."""
    when = when or datetime.now()
    return (f"{_WEEKDAYS[when.weekday()]}, "
            f"{_ordinal(when.day)} {_MONTHS[when.month - 1]}")


# --- цифры вслух ------------------------------------------------------------
# Инструменты проговаривают числа словами сами: погода отдаёт «шестнадцать
# градусов», батарея — «двенадцать и четыре вольта». Но между инструментом и
# динамиком стоит МОДЕЛЬ, и она пересказывает результат своими словами:
#
#     вызываю weather({'day': 'сейчас'})
#     робот: В Калининграде сейчас 16 градусов, ясно, ветер 11 м/с.
#
# Аккуратный текст инструмента превратился в цифры и сокращения, а синтез на
# них спотыкается — человек слышит пропущенную цифру. То же самое во всяком
# свободном тексте модели: «около 0,2–0,4 метра от камеры».
#
# Уговаривать модель промптом бесполезно: она пишет как пишет, и проверять
# каждое её слово нечем. Поэтому чиним на последней остановке перед синтезом,
# где мимо не пройдёт ничего.
# Единицы, которые нельзя просто заменить строкой: они обязаны согласоваться с
# числом. «23 °C» — это «двадцать три градусА», а не «градусОВ», и слышно это
# сразу. Поэтому число и единица разбираются ОДНИМ куском.
_ЕДИНИЦЫ_СО_СЧЁТОМ = (
    (r"°\s*[CСc]|°|º", ("градус", "градуса", "градусов")),
    (r"%", ("процент", "процента", "процентов")),
    (r"км/ч", ("километр в час", "километра в час", "километров в час")),
    (r"м/с(?:ек)?", ("метр в секунду", "метра в секунду", "метров в секунду")),
)

# А эти замены от числа не зависят: единица стоит сама по себе.
_ЕДИНИЦЫ_ПРОСТО = (
    ("км/ч", "километров в час"),
    ("м/с", "метров в секунду"),
    ("°C", " градусов"),
    ("°С", " градусов"),   # русская «С» — её ставят по ошибке, и часто
    ("º", " градусов"),
    ("°", " градусов"),
    ("%", " процентов"),
)

_ЧИСЛО = re.compile(r"(?<![\w.,])(-?)(\d+)(?:[.,](\d+))?")


def _дробь_вслух(целое: str, дробное: str) -> str:
    """«ноль и два» — так же, как робот произносит вольты.

    Не «ноль целых две десятых»: вслух это звучит как урок арифметики, а
    робот отвечает на бытовой вопрос.
    """
    хвост = дробное.rstrip("0") or "0"
    if len(хвост) == 1:
        return f"{cardinal(int(целое))} и {cardinal(int(хвост))}"
    # Двузначная дробь читается как число: «двенадцать и двадцать пять».
    return f"{cardinal(int(целое))} и {cardinal(int(хвост[:2]))}"


def _слово_числа(минус: str, целое: str, дробное: str | None) -> str | None:
    """Число словами. None — не берёмся (слишком велико)."""
    # Числа длиннее трёх цифр cardinal не умеет и честно вернёт цифры. Год,
    # номер дома, большая сумма — пусть остаются как были: сказать «две тысячи
    # двадцать шестой» мы всё равно не сможем, а испортить можем.
    if len(целое) > 3:
        return None
    слова = (_дробь_вслух(целое, дробное) if дробное else cardinal(int(целое)))
    return f"минус {слова}" if минус else слова


# Часы. Разбираются ПЕРВЫМИ и отдельно: двоеточие между двумя числами — это
# не разделитель, а время, и «19:12» вслух превращалось в «девятнадцать
# двоеточие двенадцать». Пропустив этот случай в общий разбор, мы бы сломали
# ровно тот ответ, который робот даёт чаще всего.
_ЧАСЫ = re.compile(r"(?<![\d:])([01]?\d|2[0-3]):([0-5]\d)(?![\d:])")


def числа_вслух(text: str) -> str:
    """Цифры и сокращения — словами. Что не по зубам, оставляем как есть."""
    def часы(m: "re.Match[str]") -> str:
        ч, мин = int(m.group(1)), int(m.group(2))
        сказано = count(ч, "час", "часа", "часов")
        if мин:
            сказано += " " + count(мин, "минута", "минуты", "минут", female=True)
        return сказано

    text = _ЧАСЫ.sub(часы, text)

    # Сперва число вместе с единицей — ради согласования.
    for знак, формы in _ЕДИНИЦЫ_СО_СЧЁТОМ:
        образец = re.compile(
            r"(?<![\w.,])(-?)(\d+)(?:[.,](\d+))?\s*(?:" + знак + r")")

        def замена(m: "re.Match[str]", формы=формы) -> str:
            слова = _слово_числа(m.group(1), m.group(2), m.group(3))
            if слова is None:
                return m.group(0)
            # Согласуем по ЦЕЛОЙ части: «двенадцать и пять градуса» — так и
            # говорят, дробь на форму существительного не влияет.
            return f"{слова} {plural(int(m.group(2)), *формы)}"

        text = образец.sub(замена, text)

    # Потом одинокие единицы без числа («ветер в м/с»).
    for знак, словами in _ЕДИНИЦЫ_ПРОСТО:
        text = text.replace(знак, словами)

    def просто(m: "re.Match[str]") -> str:
        слова = _слово_числа(m.group(1), m.group(2), m.group(3))
        return m.group(0) if слова is None else слова

    text = _ЧИСЛО.sub(просто, text)
    # Тире между числами склеивается с ними и читается слитно: разводим.
    text = re.sub(r"(?<=[а-яё])([–—-])(?=[а-яё])", r" \1 ", text)
    return re.sub(r"\s{2,}", " ", text).strip()


# --- болтовня ---------------------------------------------------------------
# Что робот отвечает на «привет», «как дела», «спасибо» и «пока».
#
# ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ У МОДЕЛИ. Ответ известен заранее, а поход к модели
# стоит четырёх тысяч токенов системного промпта ДО первого слова человека
# (pc/kuzya_pc.py, DEFAULT_CTX). На односложной реплике это и медленно, и
# плохо: зацепиться модели не за что, кроме самого промпта, и в ответ
# прилетают его обрывки.
#
# ПОЧЕМУ ВАРИАНТОВ ПО НЕСКОЛЬКУ. Один заученный ответ на каждый случай
# превращает робота в говорящую игрушку: человек здоровается второй раз за
# вечер и слышит слово в слово то же самое. Несколько равноправных вариантов
# стоят ровно ничего, а разница слышна сразу.
#
# ПОЧЕМУ КОРОТКО. Это ответ голосом на дежурную фразу. Длинный тут не нужен
# никому: человек сказал «привет», а не «расскажи о себе».
БОЛТОВНЯ = {
    "привет": ("Привет!", "Привет-привет.", "О, привет.", "Здравствуй.",
               "Привет. Я тут."),
    "как дела": ("Хорошо, катаюсь потихоньку.", "Нормально, а у тебя?",
                 "Всё в порядке. Чем помочь?", "Да неплохо. Стою, слушаю."),
    "спасибо": ("Пожалуйста.", "Не за что.", "Обращайся.", "Всегда рад."),
    "пока": ("Пока!", "До встречи.", "Давай, я тут буду.", "Пока-пока."),
}

# Приветствие по времени суток: если человек сказал «доброе утро», отвечать
# «добрый вечер» нельзя, а «привет» на это звучит холодно.
ПО_ВРЕМЕНИ = ((5, 12, ("Доброе утро!", "Утро доброе.")),
              (12, 18, ("Добрый день!", "День добрый.")),
              (18, 23, ("Добрый вечер!", "Вечер добрый.")))


def поболтать(вид: str = "привет", *, выбрать=None, when=None) -> str:
    """Дежурный ответ на дежурную фразу. Неизвестный вид — просто «Привет!».

    `выбрать` — чем брать из вариантов; по умолчанию случайно. Подменяется в
    проверках: случайность в них означала бы проверку, которая иногда падает.
    """
    import random

    выбрать = выбрать or random.choice
    варианты = БОЛТОВНЯ.get(вид)
    if not варианты:
        return "Привет!"
    if вид == "привет":
        час = (when or datetime.now()).hour
        для_часа = [ф for от, до, ф in ПО_ВРЕМЕНИ if от <= час < до]
        if для_часа:
            # Половина на половину: и время суток называем, и не долбим одним
            # и тем же «доброе утро» всё утро подряд.
            варианты = варианты + tuple(для_часа[0])
    return выбрать(list(варианты))
