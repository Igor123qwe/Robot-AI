"""Движение в кадре камеры — не только человек, а всё, что шевелится.

ЗАЧЕМ. Детектор тела на BPU ведёт ЧЕЛОВЕКА, и по нему лицо уже умеет
смотреть на того, кто вошёл. Но живой персонаж должен оглядываться и на
кошку, на штору, на включённый свет — на любое движение. Для этого не нужна
нейросеть: разница двух соседних кадров, ужатых до 32×24, говорит «что-то
сдвинулось» и «где — левее или правее».

ОТКУДА КАДРЫ. Камерой владеет один хозяин (детектор на BPU, а до него —
веб-сервер), остальные берут у него поток MJPEG по HTTP. Здесь тот же поток
читает ffmpeg с ключом -lowres: MJPEG умеет распаковываться сразу в
четверть размера, и это стоит доли процента процессора, а не десятки, как
полная распаковка 1280×1024. Наружу — 32×24 серых пикселя, четыре раза в
секунду, сырыми байтами в трубу. Ни PIL, ни OpenCV на роботе для этого не
нужно: разница и центр тяжести считаются на голом Python — 768 чисел.

ЧЕГО НЕ СЧИТАЕМ ДВИЖЕНИЕМ. Когда едет сам робот, движется весь кадр — это
не движение в комнате, и на время поездки разница не смотрится. Мелкий шум
сенсора отсекается порогом по пикселю; вспышка автоэкспозиции (весь кадр
разом посветлел) — долей изменившихся пикселей: если сдвинулось больше
половины кадра, это свет, а не кошка.

`разница()` — чистая функция от двух кадров: проверяется на байтах.
"""

from __future__ import annotations

import logging
import os
import shutil
import subprocess
import threading
import time

log = logging.getLogger(__name__)

ШИРИНА, ВЫСОТА = 32, 24
КАДРОВ_В_СЕКУНДУ = 4
ПОРОГ_ПИКСЕЛЯ = 28          # из 255 — ниже это шум сенсора
ДОЛЯ_ДВИЖЕНИЯ = 0.012       # доля пикселей, которые должны измениться (≈9 из 768)
ДОЛЯ_СВЕТА = 0.5            # изменилось больше половины кадра — это свет, не движение
ДЕРЖАТЬ = 1.5               # секунд «движение есть» после последнего кадра с ним
ПОВТОР = 15.0               # секунд между попытками поднять ffmpeg заново


def разница(было: bytes, стало: bytes, ширина: int = ШИРИНА) -> tuple[float, float]:
    """(сила 0..1, где −1..1) по двум серым кадрам одинакового размера.

    Сила — доля изменившихся пикселей (порог ПОРОГ_ПИКСЕЛЯ), где — центр
    тяжести изменений по горизонтали: −1 левый край кадра, +1 правый. Пусто
    или размеры не сошлись — (0, 0). Больше ДОЛЯ_СВЕТА кадра — свет: (0, 0).
    """
    if not было or not стало or len(было) != len(стало):
        return 0.0, 0.0
    всего = len(стало)
    сдвинулось = 0
    сумма_x = 0
    for i in range(всего):
        if abs(стало[i] - было[i]) >= ПОРОГ_ПИКСЕЛЯ:
            сдвинулось += 1
            сумма_x += i % ширина
    if not сдвинулось:
        return 0.0, 0.0
    доля = сдвинулось / всего
    if доля >= ДОЛЯ_СВЕТА:
        return 0.0, 0.0
    где = (сумма_x / сдвинулось) / max(1, ширина - 1) * 2.0 - 1.0
    return min(1.0, доля / 0.15), max(-1.0, min(1.0, где))


class Движение:
    """Следит за потоком камеры и держит последний вердикт для лица."""

    def __init__(self, источник: str = "", *, едет=None, часы=time.monotonic) -> None:
        # Откуда поток: тот же адрес, что и у веб-сервера, иначе — его же
        # раздача (она поднимет камеру сама и будет держать, пока читаем).
        порт = os.environ.get("ROBOT_WEB_PORT", "8000")
        self.источник = (источник or os.environ.get("ROBOT_CAMERA_URL", "").strip()
                         or f"http://127.0.0.1:{порт}/camera/stream")
        self.включено = os.environ.get("ROBOT_MOTION", "1") != "0"
        self._едет = едет                     # () -> bool
        self._часы = часы
        self._lock = threading.Lock()
        self._сила = 0.0
        self._где = 0.0
        self._когда = float("-inf")
        self._кадров = 0
        self.почему = "не запускалось"

    # --- наружу -----------------------------------------------------------
    def состояние(self) -> dict:
        """{есть, сила, где} — для face.json. «Есть» держится ДЕРЖАТЬ секунд."""
        with self._lock:
            свежо = self._часы() - self._когда <= ДЕРЖАТЬ
            return {"есть": bool(свежо and self._сила > 0),
                    "сила": round(self._сила, 2) if свежо else 0.0,
                    "где": round(self._где, 2) if свежо else 0.0}

    def кадр(self, было: bytes, стало: bytes) -> None:
        """Один шаг: два кадра → вердикт. Отдельно от чтения — для проверок."""
        self._кадров += 1
        try:
            едет = bool(self._едет()) if self._едет is not None else False
        except Exception:                       # noqa: BLE001
            едет = False
        if едет:
            return                              # движется весь кадр — это мы сами
        сила, где = разница(было, стало)
        if сила >= ДОЛЯ_ДВИЖЕНИЯ / 0.15:
            with self._lock:
                self._сила, self._где, self._когда = сила, где, self._часы()

    # --- чтение потока --------------------------------------------------------
    def start(self) -> None:
        if not self.включено:
            self.почему = "выключено (ROBOT_MOTION=0)"
            log.info("движение: %s", self.почему)
            return
        if shutil.which("ffmpeg") is None:
            self.почему = "нет ffmpeg"
            log.warning("движение: нет ffmpeg — оглядываться на движение не буду")
            return
        threading.Thread(target=self._крутиться, name="движение", daemon=True).start()

    def _команда(self) -> list[str]:
        return ["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin",
                # Распаковать MJPEG сразу в четверть размера: дёшево.
                "-lowres", "2", "-i", self.источник,
                "-vf", f"fps={КАДРОВ_В_СЕКУНДУ},scale={ШИРИНА}:{ВЫСОТА},format=gray",
                "-f", "rawvideo", "-"]

    def _крутиться(self) -> None:
        размер = ШИРИНА * ВЫСОТА
        while True:
            try:
                proc = subprocess.Popen(self._команда(), stdout=subprocess.PIPE,
                                        stderr=subprocess.PIPE)
            except OSError as e:
                self.почему = f"ffmpeg не запустился: {e}"
                log.warning("движение: %s", self.почему)
                time.sleep(ПОВТОР)
                continue
            self.почему = "смотрю"
            log.info("движение: смотрю поток %s", self.источник)
            было = b""
            try:
                while True:
                    стало = proc.stdout.read(размер)
                    if len(стало) < размер:
                        break
                    if было:
                        self.кадр(было, стало)
                    было = стало
            finally:
                беда = b""
                try:
                    proc.kill()
                    беда = (proc.stderr.read() or b"")[-300:]
                except Exception:               # noqa: BLE001
                    pass
            self.почему = "поток оборвался" + (f": {беда.decode('utf-8', 'replace').strip()}"
                                               if беда else "")
            log.warning("движение: %s — попробую через %.0f с", self.почему, ПОВТОР)
            time.sleep(ПОВТОР)
