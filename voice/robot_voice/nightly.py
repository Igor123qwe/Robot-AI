"""Ночной разбор: что робот узнал о своей квартире, прожив в ней день.

ЗАЧЕМ. Дневник копит факты, но факт сам по себе бесполезен. «Застрял в 18:34
в точке (1.2, -0.4)» не говорит ничего; «пятый вечер подряд застреваю в одном
и том же углу возле кухни» — говорит всё. Разница между первым и вторым — это
и есть разбор: сложить одиночные события в повторяющиеся.

ЧТО ЗДЕСЬ СЧИТАЕТСЯ БЕЗ МОДЕЛИ, и это важно. Кластеризация мест, счёт
повторов, доля срывов — обычная арифметика. Она проверяема, воспроизводима и
не стоит ни копейки. Модель нужна ровно для одного: превратить готовые числа в
фразу, которую человек поймёт с первого раза.

Такое разделение не изящество, а необходимость. Модель на этом роботе врёт в
арифметике — она и людям-то её путает, — зато хорошо формулирует. Дай ей
сырой дневник и попроси «найди закономерности» — получишь правдоподобный
пересказ, в котором числа выдуманы, и проверить его будет нечем. Дай готовые
числа и попроси сказать одной фразой — получишь то, что нужно.

ЧТО РОБОТ ДЕЛАЕТ С ВЫВОДАМИ. Пока — рассказывает. Это меньше, чем хотелось
бы, и честнее, чем притворяться. Чтобы «объезжать плохое место», нужна
глобальная карта квартиры и своё место в ней, а у нас карта локальная и
забывчивая: координаты живут от включения до включения и после перезагрузки
означают уже другое. Поэтому выводы привязаны ко времени и обстоятельствам
(«вечером», «когда иду за тобой»), а не к точкам на плане квартиры.

Одометрия за поездку уходит на проценты, и внутри ОДНОГО запуска точки
сравнимы — на этом кластеризация и держится. Между запусками — нет, и
объединять их нельзя: разбор считает «повторяется» только по числу дней, в
которые событие случалось, а не по совпадению координат.
"""

from __future__ import annotations

import json
import logging
import math
import os
import time

from . import ru

log = logging.getLogger(__name__)

# На каком расстоянии два тупика считаются ОДНИМ местом. Полметра: это
# примерно полторы длины робота — тот же угол, в который он въезжает то чуть
# левее, то чуть правее. Меньше — и один угол рассыплется на пять «мест»;
# больше — кухня сольётся с коридором.
ОДНО_МЕСТО = 0.5

# Сколько раз событие должно повториться, чтобы стать выводом. Три: два раза
# бывает совпадением, а из трёх уже складывается привычка — и робота, и
# квартиры.
ХВАТИТ_ПОВТОРОВ = 3

# В скольких РАЗНЫХ днях событие должно встретиться, чтобы счесть его
# свойством квартиры, а не одного неудачного вечера. Два: мебель за сутки
# обычно не переставляют, но кот на коврике живёт один вечер.
ДНЕЙ_ПОДРЯД = 2

# Сколько выводов держим. Двадцать: больше человек всё равно не выслушает, а
# копить их вечно значит однажды сказать про квартиру, в которой уже сделали
# ремонт.
ВЫВОДОВ_ПРЕДЕЛ = 20

# Сколько дней вывод живёт без подтверждения. Две недели — тот же срок, что у
# дневника: наблюдение, которое не повторилось за две недели, описывает уже
# не эту квартиру.
ВЫВОД_ЖИВЁТ_ДНЕЙ = 14


def _день(когда: float) -> str:
    """Какой это день. Строкой, чтобы попадало в JSON без потерь."""
    return time.strftime("%Y-%m-%d", time.localtime(когда))


def места(записи, порог: float = ОДНО_МЕСТО):
    """Сложить точки в места. Список: {где, сколько, дней, что, когда}.

    Кластеризуем жадно и в один проход: первая точка задаёт место, каждая
    следующая либо попадает в готовое, либо заводит своё. Это не k-средних и
    не должно им быть — мест единицы, точность нужна до полуметра, а всё
    сложное здесь обернулось бы зависимостью от numpy и невозможностью
    объяснить результат.

    Порядок обхода влияет на разбиение, и это осознанная плата. Для «угол
    возле кухни» она не значит ничего: две-три точки в полуметре друг от
    друга соберутся в одно место при любом порядке.
    """
    собрано: list[dict] = []
    for запись in записи:
        x, y = запись.get("x"), запись.get("y")
        if x is None or y is None:
            continue
        try:
            x, y = float(x), float(y)
        except (TypeError, ValueError):
            continue
        когда = float(запись.get("когда") or 0)
        свой = None
        for место in собрано:
            if math.hypot(x - место["где"][0], y - место["где"][1]) <= порог:
                свой = место
                break
        if свой is None:
            свой = {"где": (x, y), "сколько": 0, "дни": set(),
                    "что": {}, "первый": когда, "последний": когда}
            собрано.append(свой)
        свой["сколько"] += 1
        свой["дни"].add(_день(когда))
        свой["последний"] = max(свой["последний"], когда)
        повод = str(запись.get("занятие") or запись.get("итог") or "?")
        свой["что"][повод] = свой["что"].get(повод, 0) + 1
        # Середину места подтягиваем к среднему: место — это не первая точка,
        # а середина всех, иначе оно уползает к краю кластера.
        сколько = свой["сколько"]
        сx = свой["где"][0] + (x - свой["где"][0]) / сколько
        сy = свой["где"][1] + (y - свой["где"][1]) / сколько
        свой["где"] = (сx, сy)
    for место in собрано:
        место["дней"] = len(место["дни"])
        место.pop("дни")
    собрано.sort(key=lambda м: м["сколько"], reverse=True)
    return собрано


def трудные_места(дневник, часов: float = 24 * 7):
    """Где робот застревает не случайно. Только повторяющееся."""
    тупики = [з for з in дневник.за(часов) if з.get("что") == "тупик"]
    найдено = []
    for место in места(тупики):
        if место["сколько"] < ХВАТИТ_ПОВТОРОВ:
            continue
        if место["дней"] < ДНЕЙ_ПОДРЯД:
            continue
        найдено.append(место)
    return найдено


def срывы_следования(дневник, часов: float = 24 * 7):
    """Чем чаще всего кончается следование и как часто оно срывается."""
    записи = [з for з in дневник.за(часов) if з.get("что") == "следование"]
    если_нет = {"всего": 0, "сорвалось": 0, "доля": 0.0, "по_итогам": {}}
    if not записи:
        return если_нет
    по_итогам: dict[str, int] = {}
    сорвалось = 0
    for з in записи:
        итог = str(з.get("итог") or "?")
        по_итогам[итог] = по_итогам.get(итог, 0) + 1
        if з.get("сорвалось"):
            сорвалось += 1
    return {"всего": len(записи), "сорвалось": сорвалось,
            "доля": round(сорвалось / len(записи), 2),
            "по_итогам": по_итогам}


def факты(дневник, часов: float = 24 * 7) -> dict:
    """Всё, что посчиталось арифметикой. Это и пойдёт модели.

    Отдаём именно ЧИСЛА, а не сырой дневник, и в этом весь замысел. Сырой
    дневник модель пересказала бы правдоподобно и с выдуманными цифрами, а
    проверить её было бы нечем. Из готовых чисел выдумать нельзя — можно
    только сформулировать.
    """
    свод = дневник.свод(часов)
    return {
        "часов": часов,
        "всего_событий": свод["всего"],
        "по_видам": свод["по_видам"],
        "следование": срывы_следования(дневник, часов),
        "трудные_места": [
            {"сколько": м["сколько"], "дней": м["дней"],
             "что": м["что"],
             "где": [round(м["где"][0], 1), round(м["где"][1], 1)]}
            for м in трудные_места(дневник, часов)
        ],
        "повторы": дневник.повторы(часов),
    }


def есть_о_чём_говорить(факты_: dict) -> bool:
    """Стоит ли вообще звать модель.

    Разбор, которому нечего сказать, должен молчать, а не сочинять. Робот,
    каждый вечер объявляющий «сегодня я ничего нового не заметил», — это
    робот, которого выключают на третий вечер.
    """
    if факты_.get("трудные_места"):
        return True
    if факты_.get("повторы"):
        return True
    следование = факты_.get("следование") or {}
    хватает = следование.get("всего", 0) >= ХВАТИТ_ПОВТОРОВ
    return bool(хватает and следование.get("сорвалось"))


ЗАДАНИЕ = (
    "Ты робот Кузя. Ниже — числа о твоём дне, посчитанные тобой самим. "
    "Скажи одной-двумя фразами, что из этого стоит знать хозяину. "
    "Говори как о себе и своей квартире, просто, без списков и без цифр в "
    "скобках. Не выдумывай того, чего в числах нет. Если числа ни о чём "
    "не говорят — ответь одним словом: нечего."
)


class Разбор:
    """Хранит выводы и умеет их обновлять. Один на робота.

    Файл рядом с дневником: выводы — такая же память робота о себе, и терять
    их при перезапуске значит начинать учиться заново каждое утро.
    """

    def __init__(self, файл, дневник, часы=time.time) -> None:
        self.файл = файл
        self.дневник = дневник
        self._часы = часы
        self.выводы: list[dict] = self._прочитать()

    # --- хранение --------------------------------------------------------
    def _прочитать(self) -> list[dict]:
        try:
            with open(self.файл, encoding="utf-8") as f:
                данные = json.load(f)
        except (OSError, ValueError):
            return []
        return [з for з in данные if isinstance(з, dict)] \
            if isinstance(данные, list) else []

    def _сохранить(self) -> None:
        край = self._часы() - ВЫВОД_ЖИВЁТ_ДНЕЙ * 24 * 3600
        живые = [в for в in self.выводы if float(в.get("когда") or 0) >= край]
        живые = живые[-ВЫВОДОВ_ПРЕДЕЛ:]
        self.выводы = живые
        try:
            os.makedirs(os.path.dirname(str(self.файл)) or ".", exist_ok=True)
            врем = f"{self.файл}.новый"
            with open(врем, "w", encoding="utf-8") as f:
                json.dump(живые, f, ensure_ascii=False, indent=1)
            os.replace(врем, self.файл)
        except OSError:
            log.debug("разбор: не смог сохранить выводы", exc_info=True)

    # --- сам разбор ------------------------------------------------------
    def разобрать(self, спросить=None, часов: float = 24 * 7) -> str:
        """Посчитать факты и, если есть о чём, попросить модель их назвать.

        `спросить(задание, текст) -> str` — как обратиться к модели. Нет её
        или молчит — вывод всё равно сохранится, только своими словами: числа
        посчитаны нами, и без модели они не пропадают.
        """
        числа = факты(self.дневник, часов)
        if not есть_о_чём_говорить(числа):
            log.info("разбор: за %.0f ч ничего примечательного", часов)
            return ""
        сказано = ""
        if спросить is not None:
            try:
                сказано = (спросить(
                    ЗАДАНИЕ,
                    json.dumps(числа, ensure_ascii=False)) or "").strip()
            except Exception:                   # noqa: BLE001
                log.warning("разбор: модель не ответила", exc_info=True)
        if сказано.lower().strip(" .!") == "нечего":
            сказано = ""
        if not сказано:
            сказано = своими_словами(числа)
        if not сказано:
            return ""
        self.выводы.append({"когда": round(self._часы(), 1),
                            "вывод": сказано, "числа": числа})
        self._сохранить()
        log.info("разбор: %s", сказано)
        return сказано

    def последнее(self, сколько: int = 3) -> list[str]:
        return [str(в.get("вывод") or "") for в in self.выводы[-сколько:]]


def своими_словами(числа: dict) -> str:
    """Вывод без модели. На случай, если её нет или она молчит.

    Числа посчитаны нами и никуда не денутся оттого, что модель недоступна.
    Фраза выйдет суше, но правдой она быть не перестанет — а именно правда
    здесь и ценна.
    """
    куски = []
    трудные = числа.get("трудные_места") or []
    if трудные:
        худшее = трудные[0]
        куски.append(
            "Есть место, где я застреваю: "
            + ru.count(худшее["сколько"], "раз", "раза", "раз")
            + " за " + ru.count(худшее["дней"], "день", "дня", "дней"))
    следование = числа.get("следование") or {}
    if следование.get("всего") and следование.get("сорвалось"):
        куски.append(
            f"из {следование['всего']} раз, что я шёл следом, "
            f"{следование['сорвалось']} сорвалось")
    повторы = числа.get("повторы") or []
    if повторы:
        первый = повторы[0]
        куски.append(
            "ты " + ru.count(первый["раз"], "раз", "раза", "раз")
            + f" просил «{первый['повод']}» около {первый['час']} часов")
    return ". ".join(куски) + "." if куски else ""
