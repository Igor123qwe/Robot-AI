def итог_по_причине(почему: str, иначе: str = "доехал") -> str:
    """Причину остановки словами — в вид итога для лица (см. ИТОГИ).

    Причины у движителей человеческие и у каждого свои: «сказали стоп»,
    «кнопка стоп», «показали ладонь», «потерял», «обыскал квартиру и не
    нашёл». Сводить их в один словарь в шести местах значило бы однажды
    разойтись, и тогда «кнопка» у одного превратится в «приехал» у другого —
    ровно та ложь, ради которой итог и заведён. Всё, что не похоже ни на
    остановку человеком, ни на беду, — `иначе`: движитель кончил сам.
    """
    низ = (почему or "").strip().lower()
    if низ in ИТОГИ:
        return низ
    if "кнопк" in низ:
        return "кнопка"
    if "ладон" in низ:
        return "ладонь"
    if "упал" in низ:
        return "упал"
    if "батаре" in низ:
        return "батарея"
    if "потерял" in низ or "не нашёл" in низ or "уходил" in низ:
        # «Три раза уходила — больше не хожу»: собака ушла, спутник сдался.
        return "потерял"
    if "застр" in низ or "не выбрал" in низ or "не проехать" in низ:
        return "застрял"
    if "сбой" in низ or "не так" in низ or "сорвал" in низ:
        return "сбой"
    if any(с in низ for с in ("стоп", "перебили", "голос", "попросили",
                              "остановили", "другую команду")):
        return "голос"
    return иначе


def сторона_по_причине(причина: str, как: str = "") -> int | None:
    """Где было препятствие: +1 слева, −1 справа, 0 — прямо, None — не про то.

    Сторожа говорят сторону словами («впереди что-то справа»), и шар
    отшатывается от неё. Знак — как у поворота: плюс — левая сторона робота.
    """
    низ = (причина or "").lower()
    if "слева" in низ or "левее" in низ:
        return 1
    if "справа" in низ or "правее" in низ:
        return -1
    return 0 if как in _ИТОГИ_СО_СТОРОНОЙ else None


def сказать_итог(ros, почему: str, иначе: str = "доехал") -> None:
    """Движитель кончил — лицу итог по словам его причины.

    Одна строка в finally каждого движителя. Через getattr: движители ездят и
    на поддельном шасси в проверках, и итог там бывает не нужен вовсе.
    Сбой здесь не смеет помешать колёсам — они к этому мигу уже стоят.
    """
    отметить = getattr(ros, "отметить_итог", None)
    if отметить is None:
        return
    try:
        отметить(итог_по_причине(почему, иначе), почему)
    except Exception:                           # noqa: BLE001
        log.exception("не смог отметить, чем кончилось движение")


def _класс_хода(x: float, y: float, wz: float) -> tuple[int, int, int]:
    """Куда едем, без величины: знаки с мёртвыми зонами. Смена — это край."""
    def знак(v: float, ноль: float) -> int:
        return 0 if abs(v) < ноль else (1 if v > 0 else -1)
    return (знак(x, ХОД_ПОЧТИ_НОЛЬ), знак(y, ХОД_ПОЧТИ_НОЛЬ),
            знак(wz, ПОВОРОТ_ПОЧТИ_НОЛЬ))


def _нулевая(x: float, y: float, wz: float) -> bool:
    """Тот же порог, что у publish_twist: ниже него колёса не крутятся."""
    return abs(x) + abs(y) + abs(wz) <= 1e-3


def _до_сотых(v: float, ноль: float) -> float:
    """Округлить для лица, с мёртвой зоной: мелочь — ровно ноль."""
    return 0.0 if abs(v) < ноль else round(float(v), 2)


class Движитель(NamedTuple):
    """Кто ещё умеет крутить колёса, кроме drive().

    Заведено потому, что колёса перестали быть собственностью одного потока.
    Следование за человеком крутится своим циклом и публикует /cmd_vel
    напрямую, а Ros про него не знал ничего — и из этого выросли две дыры
    сразу, обе тихие:

      • `moving` отвечал «стою», пока робот ехал за человеком. Кнопка СТОП в
        пульте проверяет именно `moving`, прежде чем счесть чужой ноль
        требованием остановиться, — значит ВО ВРЕМЯ СЛЕДОВАНИЯ КНОПКА НЕ
        РАБОТАЛА ВОВСЕ. Единственная страховка на то время, когда робот
        говорит и не слышит голоса, молча отсутствовала;
      • команда «проедь метр» во время следования запускала второй поток на
        те же колёса. Два источника скорости на один топик пятнадцать раз в
        секунду каждый — это не «кто-то победит», это дёрганый робот,
        едущий в среднее направление.

    Лечится тем, чем такое лечится у всех, кто ездит: у колёс один хозяин в
    один момент. Здесь роль арбитра берёт Ros — не потому, что ему хочется,
    а потому, что он единственный, через кого проходят все команды.

    `идёт` — крутит ли этот движитель колёса прямо сейчас.
    `остановить` — прекратить, НЕ ДОЖИДАЯСЬ. Зовётся в том числе из потока
    websocket, а он в это время не читает сообщения: заблокировать его на
    секунду значит на секунду ослепнуть — ровно в тот миг, когда человек жмёт
    аварийную кнопку.
    """

    имя: str
    идёт: Callable[[], bool]
    остановить: Callable[[str], None]


class Ros:
    def __init__(self, url: str) -> None:
        self.url = url
        self._ws: websocket.WebSocketApp | None = None
        self._connected = threading.Event()
        self._voltage: float | None = None
        self._voltage_at = 0.0
        self._odom: tuple[float, float, float] | None = None
        self._odom_at = 0.0
        self._lock = threading.Lock()
        self._stop = False
        # Переподключение: пауза растёт, жалоба в лог — одна на поломку
        # (см. _пауза_и_жалоба). None в «_молчит_с» значит «связь была».
        self._пауза = 0.0
        self._молчит_с: float | None = None
        self._жаловался = 0.0
        # Движение крутится в отдельном потоке, иначе робот не услышит «стоп»,
        # пока едет: главный цикл стоял бы в sleep, а микрофон был бы заглушён.
        self._motion_cancel = threading.Event()
        self._motion: threading.Thread | None = None
        # Когда в /cmd_vel последний раз видели ненулевую скорость. Слушаем сам
        # топик, а не только себя: гнать робота может и веб-пульт напрямую.
        self._last_move = 0.0
        # Сколько наших собственных нулей ещё не вернулось эхом.
        #
        # Считаем штуки, а не смотрим на часы, и это исправление настоящей
        # дыры. Раньше здесь стояла отметка времени: «ноль моложе полусекунды
        # — наш». Пока робот ездил по команде, это работало: во время поездки
        # он публикует НЕнулевые скорости, и окно не обновлялось. А следование
        # публикует нули постоянно — стоит человеку остановиться, робот
        # пятнадцать раз в секунду сообщает шасси «стою». Окно при этом не
        # закрывается никогда, и кнопка СТОП тонула в нём целиком.
        #
        # Счётчик от этого свободен: rosbridge возвращает подписчику ровно то,
        # что опубликовано, штука за штуку. Сколько нулей мы послали, столько
        # эхо и съедим; всё сверх того послал кто-то другой, и это требование
        # остановиться. Чей именно ноль оказался «нашим», значения не имеет —
        # важно, что арифметика сходится.
        #
        # Хранится не число, а ОТМЕТКИ ВРЕМЕНИ каждого неотвеченного нуля, и
        # это третья правка одного и того же места. Чистый счётчик не сходился
        # в одном случае: эхо потерялось — пакет выбросил rosbridge, сокет
        # моргнул без закрытия, — и долг в одну штуку жил вечно. Следующий
        # чужой ноль, то есть кнопка СТОП, съедался как «свой». Отметка
        # старше ЭХО_ЖИВЁТ списывается: ждать её дальше бессмысленно.
        self._свои_нули_когда: deque[float] = deque()
        # То же для НЕнулевых команд, но с самой скоростью: (x, y, wz, когда).
        # Эхо своей последней команды иногда приходит, когда поток движения
        # уже кончился и `moving` отвечает «стою», — и без сверки по значению
        # оно читалось бы как пульт: лишнее «поехали» и второе «приехали».
        self._свои_ходы: deque[tuple] = deque(maxlen=64)
        # Когда последний раз видели ЧУЖОЙ ноль в /cmd_vel. См.
        # ЧУЖОЙ_СТОП_ДЕРЖИТСЯ: на стыке двух движений `moving` врёт, и ноль,
        # пришедший в этот зазор, иначе пропадал бы.
        self._чужой_ноль_когда = 0.0
        # Последние замеры напряжения и вердикт по ним — см. УСРЕДНЯЕМ_ЗАМЕРОВ.
        self._вольты: deque[float] = deque(maxlen=УСРЕДНЯЕМ_ЗАМЕРОВ)
        self._села = False
        # Сторож пути: спрашивается пятнадцать раз в секунду ВО ВРЕМЯ
        # движения вперёд и может его оборвать. Ставится снаружи (app.py) и
        # смотрит в дальномер.
        #
        # Разница с проверкой перед командой принципиальная. Проверка перед
        # командой отвечает на вопрос «свободно ли сейчас», а поездка длится
        # до пятнадцати секунд, и человек за это время успевает встать на
        # пути. Робот, проверивший дорогу один раз и дальше едущий вслепую,
        # опаснее робота без датчика: тот хотя бы не обещал.
        self.сторож: Callable[[], tuple[bool, str]] | None = None
        # Второй сторож — на то, куда датчик не смотрит: задний ход, боковой,
        # разворот на месте. Спрашивается с задуманными скоростями и отвечает
        # по КАРТЕ ПАМЯТИ, а не по датчику: сзади дальномера нет и не будет,
        # но стул, стоявший там минуту назад, никуда не делся.
        #
        # Раньше этого не проверялось ничем: сторож судил только «x > 0»,
        # честно объясняя, что про заднее полушарие не знает. Задний ход без
        # датчиков — единственный юридически доказанный механизм травмы среди
        # тротуарных роботов, и «не знаю» тут не оправдание, а описание дыры.
        self.сторож_вслепую: Callable[
            [float, float, float], tuple[bool, str]] | None = None
        # Куда сообщать скорость, которую сейчас подадут на колёса. Ставится
        # снаружи (app.py) и ведёт в дальномер: он считает от неё порог стопа,
        # потому что тормозной путь растёт квадратом скорости. None — некому
        # сообщать, и дальномер судит по прежней осторожности.
        self.скорость_дальномеру: Callable[[float], None] | None = None
        # Куда отдавать детекции людей с камеры. Ставится снаружи (app.py);
        # None — детектор не запущен, и следование идёт по одному дальномеру,
        # как раньше. Подписка при этом всё равно оформляется: узел могут
        # поднять и после робота, и тогда детекции просто начнут приходить.
        self.людей_видно: Callable[[dict], None] | None = None
        # СТОРОЖ МОЛЧАЩЕЙ ПОДПИСКИ. Считаем детекции и помним, когда
        # подписались. Ровно на этом месте робот пятнадцать месяцев был слеп:
        # детектор исправно считал людей на BPU, мост писал «Subscribed to
        # /hobot_mono2d_body_detection», ошибок не было нигде — а сообщения не
        # доходили, потому что не сошлись QoS (узел отдаёт «best effort», мост
        # слушал «reliable», и ROS 2 такую пару молча не соединяет).
        #
        # Снаружи это выглядело как «человечек скучный»: без человека в кадре
        # не могут сыграть 129 сценок из 295, молчит всё расписание, экран
        # гаснет через три минуты и не будится. И ни одной строки в журнале.
        #
        # Сторож стоит именно здесь, у ПОДПИСКИ. В самом детекторе (см.
        # vision_track._считать_диагностику) счётчик по построению зовётся
        # только на пришедшем сообщении — «сообщений нет вовсе» им не
        # различить никогда.
        self._детекций = 0
        self._подписались_в: float | None = None
        self._жаловался_на_тишину = float("-inf")
        # Куда отдавать жесты. None — узлы распознавания кисти не подняты.
        self.жесты_видно: Callable[[dict], None] | None = None
        # Куда отдавать распознанные вещи. None — узел поиска вещей не поднят.
        self.вещи_видно: Callable[[dict], None] | None = None
        # Все, кто умеет крутить колёса помимо drive(). См. класс Движитель.
        self._движители: list[Движитель] = []
        # Сколько команд ХОДА подряд не ушло в шасси и кричали ли мы об этом.
        # См. _связь_держится: порванная посреди поездки связь оставляет
        # шасси с последней дошедшей скоростью, и «стоп» тем же путём тоже
        # не дойдёт.
        self._не_ушло = 0
        self._кричали_про_связь = False
        # Чем сказать человеку, что поездка оборвалась. Молча встать посреди
        # комнаты — это выглядит как поломка: человек попросил проехать метр,
        # робот сказал «еду», проехал двадцать сантиметров и замер.
        self.объявить: Callable[..., object] | None = None
        # Почему оборвалось последнее движение. Пусто — само доехало.
        self.прервано = ""
        # --- ход для лица (см. ХОД_ЖИВЁТ и ход()) ---
        # Последняя поданная на колёса скорость: (x, y, wz, когда, откуда),
        # «откуда» — «свой» или «пульт». Часы — свои, подменяемые: проверке
        # незачем ждать по-настоящему, пока команда протухнет.
        self._часы = time.monotonic
        self._команда: tuple | None = None
        # Сколько раз колёса трогались с места — кем угодно. Номер, а не
        # флаг: короткий старт между двумя снимками иначе пропадал бы, а
        # счётчик доедет и после потерянного кадра.
        self._старт = 0
        # Когда последний раз подавали ненулевую скорость.
        self._ненулевая_когда: float | None = None
        # С какого мига команда «заметная» и с какого мига при ней стоим.
        self._сильно_с: float | None = None
        self._упор_с: float | None = None
        # Что докладывает одометрия о скорости: (vx, vy, w, когда).
        self._факт: tuple | None = None
        self._поза_была: tuple | None = None
        # Ехал ли пульт: его конец — тоже итог.
        self._пульт_ехал = False
        # Тронулась ли поездка ПО-НАСТОЯЩЕМУ — см. кто_едет().
        self._поездка_тронулась = False
        # Сказан ли уже итог этой поездки — см. _закрыть_поездку.
        self._итог_сказан = False
        self._маршрут = False
        # Чем кончилось последнее движение — см. отметить_итог.
        self._итог: dict | None = None
        # Будильник лица: ход сменился (тронулись, встали, повернули в другую
        # сторону, новый итог). Зовётся ТОЛЬКО на смене, не на каждом такте.
        self.ход_сменился: Callable[[], None] | None = None
        # Тревога лицу — независимо от дальномера и от того, умеет ли робот
        # говорить. Раньше единственным проводом тревоги была фраза «Стою:
        # …», а `объявить` ставился только когда дальномер поднялся: без него
        # упор и потеря связи с колёсами проходили беззвучно и невидимо.
        self.тревога_хода: Callable[[str], None] | None = None

    # Значения по умолчанию КЛАССА для хода — по той же причине, что у сторожа
    # детекций ниже: проверки собирают мост в обход __init__, а publish_twist
    # и _motion_loop теперь трогают эти поля на каждом шаге.
    _часы = staticmethod(time.monotonic)
    _команда = None
    _старт = 0
    _ненулевая_когда = None
    _сильно_с = None
    _упор_с = None
    _факт = None
    _поза_была = None
    _пульт_ехал = False
    _поездка_тронулась = False
    _итог_сказан = False
    _маршрут = False
    _итог = None
    _не_ушло = 0
    ход_сменился = None
    тревога_хода = None

    # --- жизненный цикл -------------------------------------------------
    def start(self) -> None:
        threading.Thread(target=self._run_forever, daemon=True).start()
        threading.Thread(target=self._сторож_детекций, daemon=True).start()

    # --- сторож молчащей подписки ---------------------------------------------
    ДЕТЕКЦИЙ_ЖДЁМ = 30.0          # секунд после подписки — и хватит ждать
    ТИШИНА_НАПОМИНАТЬ = 300.0     # как часто повторять, пока не починят
    # Значения по умолчанию КЛАССА, а не только экземпляра: самопроверки
    # поднимают мост в обход конструктора (им нужен один метод, а не связь), и
    # счётчик, живущий лишь в __init__, ронял бы разбор сообщений на ровном
    # месте. Сторож обязан быть незаметен для всех, кто о нём не знает.
    _детекций = 0
    _подписались_в = None
    _жаловался_на_тишину = float("-inf")

    def молчит_ли_детектор(self, сейчас: float) -> float | None:
        """Сколько секунд подписка молчит; None — всё в порядке или рано судить.

        Вынесено отдельным методом, чтобы это можно было проверить без потока
        и без моста: сторож, который нельзя проверить, — половина сторожа.
        """
        подписались = self._подписались_в
        if подписались is None or self._детекций:
            return None
        молчит = сейчас - подписались
        return молчит if молчит >= self.ДЕТЕКЦИЙ_ЖДЁМ else None

    def _сторож_детекций(self) -> None:
        """Подписались — и тишина. Сказать вслух, пока никто не заметил сам.

        Пятнадцать месяцев на живом роботе: детектор считал людей на BPU
        тридцать раз в секунду, мост писал «Subscribed to …», ошибок не было
        нигде — а до робота не доходило ни одно сообщение. Снаружи это
        выглядело как «человечек скучный», и искали в лице.

        Поэтому строка не просто жалуется, а говорит, ЧТО ПРОВЕРИТЬ. Человек
        у робота не обязан помнить про QoS.
        """
        while not self._stop:
            time.sleep(5.0)
            молчит = self.молчит_ли_детектор(time.monotonic())
            if молчит is None:
                continue
            сейчас = time.monotonic()
            if сейчас - self._жаловался_на_тишину < self.ТИШИНА_НАПОМИНАТЬ:
                continue
            self._жаловался_на_тишину = сейчас
            log.error(
                "детектор тела: подписка оформлена %.0f с назад, не пришло НИ "
                "ОДНОГО сообщения. Робот не видит человека в кадре: персонаж "
                "не смотрит на вас, не здоровается первым, экран гаснет при "
                "живом хозяине. Проверь: systemctl status robot-body, а потом "
                "ros2 topic echo %s --qos-reliability best_effort --once",
                молчит, ЛЮДИ)

    def stop(self) -> None:
        self._stop = True
        if self._ws:
            self._ws.close()

    def _run_forever(self) -> None:
        while not self._stop:
            try:
                self._ws = websocket.WebSocketApp(
                    self.url,
                    on_open=self._on_open,
                    on_message=self._on_message,
                    on_close=self._on_close,
                )
                self._ws.run_forever(ping_interval=20, ping_timeout=10)
            except Exception:
                log.exception("rosbridge: сбой соединения")
            self._connected.clear()
            if not self._stop:
                time.sleep(self._пауза_и_жалоба())

    # Сколько ждать перед следующей попыткой: сначала быстро (моргнул
    # вебсокет — вернулись через две секунды), потом всё реже, до полуминуты.
    ПАУЗА_СНАЧАЛА = 2.0
    ПАУЗА_ПРЕДЕЛ = 30.0
    ЖАЛОВАТЬСЯ_РАЗ_В = 300.0          # секунд — как часто напоминать, что связи нет

    def _пауза_и_жалоба(self) -> float:
        """Пауза до следующей попытки. Заодно решает, жаловаться ли в лог.

        РОВНО ОДНА СТРОКА НА ПОЛОМКУ, А НЕ ТРИДЦАТЬ В МИНУТУ. Когда rosbridge
        не поднят, попытка раз в две секунды писала в журнал две строки —
        свою и чужую (websocket: Connection refused). За ночь это десятки
        тысяч строк, в которых тонет всё остальное; на живом роботе именно
        так и вышло. Теперь: первая потеря — подробно и с последствиями,
        дальше молча, и раз в пять минут напоминание, что связи всё ещё нет.
        """
        сейчас = time.monotonic()
        if self._молчит_с is None:
            self._молчит_с = сейчас
            self._жаловался = сейчас
            # ЧЕМ ЭТО ПАХНЕТ — СПИСКОМ, А НЕ ОДНИМ ПУНКТОМ. Раньше про
            # rosbridge говорилось только «команды движения не пройдут», и
            # никому не приходило в голову, что через тот же мост идёт
            # ДЕТЕКТОР ЛЮДЕЙ: персонаж на экране переставал видеть человека,
            # не смотрел на него и не звал — а в журнале про это ни слова.
            log.warning(
                "rosbridge (%s) не отвечает. Пока его нет: не поедет ни одна "
                "команда движения, нет одометрии и заряда, и — что не видно "
                "сразу — робот НЕ ВИДИТ ЧЕЛОВЕКА В КАДРЕ (детектор людей идёт "
                "тем же мостом): персонаж на экране не будет смотреть на вас, "
                "здороваться и звать. Проверь, поднят ли rosbridge на роботе.",
                self.url)
        elif сейчас - self._жаловался >= self.ЖАЛОВАТЬСЯ_РАЗ_В:
            self._жаловался = сейчас
            log.warning("rosbridge молчит уже %d мин — человека в кадре робот "
                        "по-прежнему не видит", int((сейчас - self._молчит_с) / 60))
        self._пауза = min(self.ПАУЗА_ПРЕДЕЛ,
                          (self._пауза or self.ПАУЗА_СНАЧАЛА) * 2)
        return self._пауза

    def _on_open(self, ws) -> None:
        if self._молчит_с is not None:
            log.info("rosbridge: связь вернулась после %d с — человека в кадре "
                     "снова видно", int(time.monotonic() - self._молчит_с))
        # Связь есть — счётчики молчания и пауза сбрасываются: следующая
        # потеря опять начнётся с двух секунд и своей подробной строки.
        self._молчит_с = None
        self._пауза = 0.0
        log.info("rosbridge: подключён к %s", self.url)
        # Долг по эхо обнуляем: пока связи не было, наши нули до подписчика не
        # дошли и уже не дойдут. Оставленный «в долг» счёт съел бы ровно
        # столько же нажатий кнопки СТОП — молча и навсегда.
        with self._lock:
            self._эхо().clear()
        # И счёт неушедших команд — с нуля: мост вернулся, команды снова
        # уходят. Без этого лицо держало бы «связи с колёсами нет» до первой
        # новой поездки, хотя связь давно есть.
        self._не_ушло = 0
        self._connected.set()
        self._send({"op": "advertise", "topic": CMD_VEL, "type": "geometry_msgs/msg/Twist"})
        self._send({"op": "subscribe", "topic": ODOM,
                    "type": "nav_msgs/msg/Odometry", "throttle_rate": 50})
        self._send({"op": "subscribe", "topic": POWER, "type": "std_msgs/msg/Float32",
                    "throttle_rate": 1000})
        # Без throttle намеренно. Это единственный канал, по которому работает
        # кнопка СТОП: rosbridge при throttle не ставит сообщения в очередь, а
        # выбрасывает пришедшие раньше окна, и нули от кнопки терялись целиком
        # — их перекрывало эхо собственной поездки, идущее каждые 66 мс.
        # Разбор трёх десятков json в секунду ничего не стоит.
        self._send({"op": "subscribe", "topic": CMD_VEL, "type": "geometry_msgs/msg/Twist"})
        # Детектор людей на BPU. Тридцать кадров в секунду — это много для
        # разбора json, поэтому просим не чаще двадцати: следованию хватает
        # с запасом (человек за пятьдесят миллисекунд никуда не денется), а
        # процессор нужен дальномеру и звуку.
        self._send({"op": "subscribe", "topic": ЛЮДИ,
                    "type": "ai_msgs/msg/PerceptionTargets",
                    "throttle_rate": 50, "qos": ДЕТЕКТОРЫ_QOS})
        # С этой секунды ждём детекции. Не пришли — скажем вслух (сторожить).
        self._подписались_в = time.monotonic()
        self._детекций = 0
        # Жесты. Подписываемся всегда, даже если узлы не подняты: подписка на
        # молчащий топик ничего не стоит, а узлы могут поднять и после робота.
        # Через жест работает остановка, и она обязана быть готова заранее.
        self._send({"op": "subscribe", "topic": ЖЕСТЫ,
                    "type": "ai_msgs/msg/PerceptionTargets",
                    "throttle_rate": 50, "qos": ДЕТЕКТОРЫ_QOS})
        # Вещи. Без throttle: сообщения приходят только в ответ на наш запрос,
        # то есть несколько штук в минуту, и выбрасывать из них нечего.
        self._send({"op": "subscribe", "topic": ВЕЩИ,
                    "type": "ai_msgs/msg/PerceptionTargets",
                    "qos": ДЕТЕКТОРЫ_QOS})
        self._send({"op": "advertise", "topic": ВЗГЛЯД,
                    "type": "std_msgs/msg/Empty"})
        self._send({"op": "advertise", "topic": ВЗГЛЯД_ОДИН,
                    "type": "std_msgs/msg/Empty"})

    def _on_close(self, ws, *_a) -> None:
        # Тихо: про потерю связи скажет _пауза_и_жалоба — один раз и по делу.
        # Здесь была строка на КАЖДУЮ попытку, и вместе с чужой строкой
        # websocket-библиотеки они и составляли тот самый поток в журнале.
        log.debug("rosbridge: соединение закрыто")
        self._connected.clear()
        with self._lock:
            self._эхо().clear()

    def _on_message(self, ws, raw: str) -> None:
        try:
            msg = json.loads(raw)
        except ValueError:
            return
        if msg.get("op") != "publish":
            return

        if msg.get("topic") == ЛЮДИ:
            self._детекций += 1
            если_есть = self.людей_видно
            if если_есть is not None:
                try:
                    если_есть(msg.get("msg") or {})
                except Exception:               # noqa: BLE001
                    # Детектор — ускоритель, а не опора: сбой в разборе его
                    # сообщений не должен ронять связь с шасси, по которой
                    # ходит «стоп».
                    log.exception("не разобрал детекцию людей")
            return

        if msg.get("topic") == ЖЕСТЫ:
            если_есть = self.жесты_видно
            if если_есть is not None:
                try:
                    если_есть(msg.get("msg") or {})
                except Exception:               # noqa: BLE001
                    log.exception("не разобрал жест")
            return

        if msg.get("topic") == ВЕЩИ:
            если_есть = self.вещи_видно
            if если_есть is not None:
                try:
                    если_есть(msg.get("msg") or {})
                except Exception:               # noqa: BLE001
                    log.exception("не разобрал вещи")
            return

        if msg.get("topic") == ODOM:
            self._запомнить_одометрию(msg.get("msg") or {})
            return
        if msg.get("topic") == POWER:
            try:
                self._запомнить_напряжение(float(msg["msg"]["data"]))
            except (KeyError, TypeError, ValueError):
                return

        elif msg.get("topic") == CMD_VEL:
            try:
                body = msg["msg"]
                x = float(body["linear"]["x"])
                y = float(body["linear"]["y"])
                wz = float(body["angular"]["z"])
            except (KeyError, TypeError, ValueError):
                return
            speed = abs(x) + abs(y) + abs(wz)
            if speed > 1e-3:
                with self._lock:
                    self._last_move = time.monotonic()
                # ПУЛЬТ ВИДЕН ЛИЦУ. Он публикует /cmd_vel мимо publish_twist,
                # и раньше робот, которого гоняли с телефона, на экране стоял:
                # ни «еду», ни наклона, а камера принимала собственный ход за
                # движение в комнате. Эхо своей же команды узнаём по значению
                # (см. _свои_ходы): по одному `moving` нельзя — последнее эхо
                # поездки приходит и тогда, когда её поток уже кончился.
                if not self._наш_ход(x, y, wz) and not self.moving:
                    self._пульт_едет(x, y, wz)
            elif self._наш_ноль():
                return
            # Чужой ноль запоминаем ВСЕГДА, а не только на ходу: на стыке
            # двух движений `moving` отвечает «стою», и без отметки кнопка,
            # нажатая в этот зазор, пропадала бы. См. ЧУЖОЙ_СТОП_ДЕРЖИТСЯ.
            elif not self._запомнить_чужой_ноль():
                return
            elif self.moving:
                # Ноль в топике, пока мы едем, — это кто-то другой требует
                # остановиться: кнопка СТОП в пульте или отпущенный джойстик.
                # Без этого поток движения через 66 мс снова подаёт скорость,
                # и кнопка не работает — а она единственная страховка, пока
                # робот говорит и не слышит «стоп».
                log.info("в /cmd_vel пришёл ноль — прекращаю движение")
                self._чужой_стоп("кнопка стоп")
            else:
                # Чужой ноль, а сами мы не едем: так пульт отпускает колёса.
                self._пульт_встал()

    def _send(self, obj: dict) -> bool:
        """Отправить. False — не ушло, и звать эхо на него не надо."""
        ws = self._ws
        if ws is None or not self._connected.is_set():
            return False
        try:
            ws.send(json.dumps(obj))
        except Exception:
            log.warning("rosbridge: не удалось отправить %s", obj.get("op"))
            return False
        return True

    def wait_connected(self, timeout: float = 10.0) -> bool:
        return self._connected.wait(timeout)

    # --- телеметрия -----------------------------------------------------
    @property
    def connected(self) -> bool:
        return self._connected.is_set()

    @property
    def voltage(self) -> float | None:
        """Напряжение батареи или None, если свежих данных нет.

        Шасси шлёт его раз в секунду. Если данные протухли — связи с шасси
        нет, и старое значение врёт: иначе робот через сутки после отключения
        уверенно сообщит «батарея двенадцать вольт».
        """
        with self._lock:
            if self._voltage_at and time.monotonic() - self._voltage_at > VOLTAGE_TTL:
                return None
            return self._voltage

    @property
    def телеметрия_протухла(self) -> bool:
        """Напряжение приходило, но замолчало дольше VOLTAGE_TTL.

        Отдельно от `voltage is None`, и это важно для того, кто решает,
        ехать ли. None значит два разных положения: «шасси ещё не успело
        сказать» (первая секунда после подключения — ехать можно) и «шасси
        МОЛЧИТ уже десять секунд при живом rosbridge» — то есть узел шасси
        упал или USB отвалился, и команда хода уйдёт в никуда. Раньше оба
        читались как «телеметрия ещё не пришла — не блокируем», и робот на
        мёртвом шасси бодро отвечал «Еду вперёд».
        """
        with self._lock:
            когда = getattr(self, "_voltage_at", 0.0)
            return bool(когда) and time.monotonic() - когда > VOLTAGE_TTL

    def _запомнить_напряжение(self, вольт: float) -> None:
        """Новый замер — в окно, вердикт «села» — с гистерезисом."""
        with self._lock:
            self._voltage = вольт
            self._voltage_at = time.monotonic()
            окно = getattr(self, "_вольты", None)
            if окно is None:
                окно = self._вольты = deque(maxlen=УСРЕДНЯЕМ_ЗАМЕРОВ)
            окно.append(вольт)
            среднее = sum(окно) / len(окно)
            if среднее < rig.БАТАРЕЯ_ПУСТА:
                self._села = True
            elif среднее >= rig.БАТАРЕЯ_ОТПУСКАЕТ:
                self._села = False
            # Между порогами вердикт не меняется — в этом и гистерезис.

    @property
    def батарея_села(self) -> bool:
        """Нельзя ли ехать из-за батареи — по среднему и с гистерезисом.

        Один ответ на всех, кто ездит: поездка по команде, следование,
        обход. Мгновенный замер под просадкой от моторов тут не судья — см.
        УСРЕДНЯЕМ_ЗАМЕРОВ. Протухшая телеметрия вердикта не меняет: про неё
        спрашивают отдельно (телеметрия_протухла), и это другая беда.
        """
        with self._lock:
            return bool(getattr(self, "_села", False))

    # --- управление -----------------------------------------------------
    def _эхо(self) -> deque:
        """Отметки неотвеченных своих нулей. Через getattr: Ros собирают и в
        обход __init__ — в проверках, где ни сокета, ни узла нет."""
        эхо = getattr(self, "_свои_нули_когда", None)
        if эхо is None:
            эхо = self._свои_нули_когда = deque()
        return эхо

    def _наш_ноль(self) -> bool:
        """Наш ли это ноль вернулся эхом. True — съели, разбираться не о чем.

        Зовётся на КАЖДЫЙ нулевой /cmd_vel, даже когда робот стоит и отменять
        нечего: счётчик обязан сходиться всегда. Пропустить эхо «потому что и
        так стоим» значит оставить долг, который потом проглотит настоящую
        кнопку.

        Долг старше ЭХО_ЖИВЁТ списывается ДО ответа: потерянное эхо не
        вернётся, а оставленное в долгу оно съело бы следующую кнопку.
        """
        with self._lock:
            эхо = self._эхо()
            край = time.monotonic() - ЭХО_ЖИВЁТ
            while эхо and эхо[0] < край:
                эхо.popleft()
            if not эхо:
                return False
            эхо.popleft()
            return True

    def _ходы(self) -> deque:
        """Свои ненулевые команды без эха. Через getattr — как _эхо."""
        ходы = getattr(self, "_свои_ходы", None)
        if ходы is None:
            ходы = self._свои_ходы = deque(maxlen=64)
        return ходы

    def _наш_ход(self, x: float, y: float, wz: float) -> bool:
        """Эхо ли это своей ненулевой команды. True — съели.

        Сверяем по значению: rosbridge возвращает ровно те числа, что мы
        послали. Эхо приходит по порядку, поэтому всё, что старше найденного,
        уже не вернётся (пакет потерялся) и списывается вместе с ним.
        """
        with self._lock:
            ходы = self._ходы()
            край = time.monotonic() - ЭХО_ЖИВЁТ
            while ходы and ходы[0][3] < край:
                ходы.popleft()
            for i, (хx, хy, хw, _) in enumerate(ходы):
                if abs(хx - x) < 1e-6 and abs(хy - y) < 1e-6 and abs(хw - wz) < 1e-6:
                    for _ in range(i + 1):
                        ходы.popleft()
                    return True
            return False

    def _запомнить_чужой_ноль(self) -> bool:
        """Отметить чужой ноль. Всегда True — чтобы встать в цепочку разбора."""
        with self._lock:
            self._чужой_ноль_когда = time.monotonic()
        return True

    def _чужой_стоп_свежий(self) -> bool:
        """Нажимали ли кнопку только что — моложе ЧУЖОЙ_СТОП_ДЕРЖИТСЯ."""
        with self._lock:
            когда = getattr(self, "_чужой_ноль_когда", 0.0)
        return bool(когда) and time.monotonic() - когда < ЧУЖОЙ_СТОП_ДЕРЖИТСЯ

    def _запомнить_одометрию(self, сообщение: dict) -> None:
        """Где шасси считает себя сейчас: координаты и поворот."""
        try:
            поза = сообщение["pose"]["pose"]
            точка = поза["position"]
            кватернион = поза["orientation"]
            x, y = float(точка["x"]), float(точка["y"])
            qz, qw = float(кватернион["z"]), float(кватернион["w"])
            qx, qy = float(кватернион.get("x", 0.0)), float(кватернион.get("y", 0.0))
        except (KeyError, TypeError, ValueError):
            return
        # Плоский робот: из кватерниона нужен только поворот вокруг вертикали.
        поворот = math.atan2(2.0 * (qw * qz + qx * qy),
                             1.0 - 2.0 * (qy * qy + qz * qz))
        with self._lock:
            self._odom = (x, y, поворот)
            self._odom_at = time.monotonic()
        self._запомнить_факт(сообщение, x, y, поворот)

    def _запомнить_факт(self, сообщение: dict, x: float, y: float,
                        поворот: float) -> None:
        """С какой скоростью шасси едет НА САМОМ ДЕЛЕ — для лица («упор»).

        Берём twist из того же сообщения: шасси докладывает его в системе
        робота (scripts/measure_braking.py читает это же поле). Нет его — или
        он нулевой, а поза при этом сдвинулась, — считаем по разнице поз: узел
        WHEELTEC может и не заполнять twist, и тогда честный ноль в нём
        означал бы «стоим» при едущем роботе. Решения о стопе по этому
        числу не принимаются — оно только для показа.
        """
        сейчас = self._часы()
        было = self._поза_была
        self._поза_была = (x, y, поворот, сейчас)
        по_позе = None
        if было is not None and сейчас - было[3] > 1e-3:
            прошло = сейчас - было[3]
            dx, dy = x - было[0], y - было[1]
            # Из мировых осей в оси робота: вперёд — его нос, влево — плюс.
            c, s = math.cos(поворот), math.sin(поворот)
            шаг = (поворот - было[2] + math.pi) % (2 * math.pi) - math.pi
            по_позе = ((dx * c + dy * s) / прошло, (-dx * s + dy * c) / прошло,
                       шаг / прошло)
        try:
            тв = сообщение["twist"]["twist"]
            по_шасси = (float(тв["linear"]["x"]), float(тв["linear"].get("y", 0.0)),
                        float(тв["angular"]["z"]))
        except (KeyError, TypeError, ValueError, AttributeError):
            по_шасси = None
        факт = по_шасси
        if по_позе is not None and (факт is None or (
                _нулевая(*факт) and not _нулевая(*по_позе))):
            факт = по_позе
        if факт is None:
            return
        with self._lock:
            self._факт = (*факт, сейчас)

    @property
    def odom(self) -> tuple[float, float, float] | None:
        """Координаты и поворот. None — шасси про это молчит.

        Молчит оно в двух случаях: узел не запущен или подписка не доехала.
        Оба означают одно — ехать придётся по секундомеру, как раньше.
        """
        with self._lock:
            if not self._odom_at or time.monotonic() - self._odom_at > ODOM_TTL:
                return None
            return self._odom

    def посмотреть(self) -> bool:
        """Попросить затвор отдать кадр в сеть поиска вещей.

        Пустое сообщение: единственное, что нужно сказать, — «посмотри
        сейчас». Возвращает, ушёл ли запрос; ответ придёт отдельно, в ВЕЩИ.
        """
        return self._send({"op": "publish", "topic": ВЗГЛЯД, "msg": {}})

    def посмотреть_разок(self) -> bool:
        """То же, но один кадр вместо трёх. Для того, кто просит часто."""
        return self._send({"op": "publish", "topic": ВЗГЛЯД_ОДИН, "msg": {}})

    def publish_twist(self, x: float = 0.0, y: float = 0.0, wz: float = 0.0) -> None:
        ноль = abs(x) + abs(y) + abs(wz) <= 1e-3
        # ДАЛЬНОМЕРУ — ДО ПОДАЧИ. Порог стопа у него считается от скорости
        # (тормозной путь растёт квадратом), а знает скорость только тот, кто
        # командует колёсами. Место выбрано единственное на всех: и следование,
        # и поездка по команде, и остановка идут через publish_twist, и
        # пропустить кого-то из них здесь нельзя по построению.
        # Через getattr: Ros собирают и в обход __init__ — в проверках, где ни
        # сокета, ни узла нет.
        сказать = getattr(self, "скорость_дальномеру", None)
        if сказать is not None:
            try:
                сказать(x, wz)
            except Exception:              # noqa: BLE001
                log.exception("не смог сказать дальномеру про скорость")
        ушло = self._send({
            "op": "publish",
            "topic": CMD_VEL,
            "msg": {
                "linear": {"x": x, "y": y, "z": 0.0},
                "angular": {"x": 0.0, "y": 0.0, "z": wz},
            },
        })
        # Считаем ТОЛЬКО то, что правда ушло. Ноль, не пролезший в закрытый
        # сокет, эхом не вернётся, а записанный в долг — съест чужой.
        if ноль and ушло:
            with self._lock:
                self._эхо().append(time.monotonic())
        elif ушло:
            with self._lock:
                self._ходы().append((x, y, wz, time.monotonic()))
        # Лицу — что подали. Здесь, а не в каждом движителе: через
        # publish_twist идут все, кто крутит колёса, и мимо не пройдёт никто.
        if self._запомнить_команду(x, y, wz, "свой"):
            self._край()
        if not ноль:
            self._связь_держится(ушло)

    # --- ход для лица -----------------------------------------------------
    def _запомнить_команду(self, x: float, y: float, wz: float,
                           откуда: str) -> bool:
        """Запомнить поданную скорость. True — это край: тронулись, встали
        или поехали в другую сторону; на каждом такте лицо не будят."""
        сейчас = self._часы()
        класс = _класс_хода(x, y, wz)
        ненулевая = not _нулевая(x, y, wz)
        with self._lock:
            было = self._команда
            крутились = self._крутятся(было, сейчас)
            был_класс = _класс_хода(*было[:3]) if крутились else (0, 0, 0)
            self._команда = (x, y, wz, сейчас, откуда)
            if ненулевая:
                self._ненулевая_когда = сейчас
                if not крутились:
                    # С места — или после того, как команда замолчала: для
                    # глаза это и есть «тронулись».
                    self._старт += 1
            сильно = (math.hypot(x, y) >= УПОР_ХОД_ОТ
                      or abs(wz) >= УПОР_ПОВОРОТ_ОТ)
            if not сильно:
                self._сильно_с = self._упор_с = None
            elif self._сильно_с is None:
                self._сильно_с = сейчас
            if откуда == "свой":
                # Свои колёса — свой хозяин: пульт, если и ехал, отпущен.
                self._пульт_ехал = False
        return ненулевая != крутились or класс != был_класс

    @staticmethod
    def _крутятся(команда, сейчас: float) -> bool:
        """Подана ли этой командой ненулевая скорость, и не замолчала ли она."""
        if команда is None or _нулевая(*команда[:3]):
            return False
        if сейчас - команда[3] > ХОД_ЖИВЁТ:
            # Замолчавшая команда — не ход. Издатель, переставший слать, это
            # не «едем», даже если последнее его слово было «вперёд».
            return False
        return True

    def крутятся(self) -> bool:
        """Подана ли сейчас на колёса ненулевая скорость — кем угодно.

        Не то же, что `moving`: тот отвечает, есть ли у колёс хозяин, и на нём
        держится разбор аварийной кнопки. Спутник, стоящий в «наблюдаю», —
        хозяин колёс, но колёса у него не крутятся.
        """
        with self._lock:
            команда = self._команда
        return self._крутятся(команда, self._часы())

    def _край(self) -> None:
        """Разбудить лицо — ВНЕ замка: будильник чужой, и ждать его нельзя."""
        будильник = self.ход_сменился
        if будильник is None:
            return
        try:
            будильник()
        except Exception:                       # noqa: BLE001
            log.exception("лицо не проснулось на смену хода")

    def _пульт_едет(self, x: float, y: float, wz: float) -> None:
        """Ненулевая скорость с пульта — запомнить как поданную."""
        край = self._запомнить_команду(x, y, wz, "пульт")
        with self._lock:
            self._пульт_ехал = True
        if край:
            self._край()

    def _пульт_встал(self) -> None:
        """Пульт отпустил колёса — нулём или молчанием. Один итог на поездку."""
        with self._lock:
            ехал, self._пульт_ехал = self._пульт_ехал, False
            команда = self._команда
        if not ехал:
            return
        if команда is not None and команда[4] == "пульт":
            self._запомнить_команду(0.0, 0.0, 0.0, "пульт")
        self.отметить_итог("пульт", "отпустили пульт")

    def _пульт_молчит(self, сейчас: float) -> None:
        """Пульт замолчал без нуля — это тоже конец его поездки."""
        with self._lock:
            команда = self._команда
            ехал = self._пульт_ехал
        if (ехал and команда is not None and команда[4] == "пульт"
                and сейчас - команда[3] > ХОД_ЖИВЁТ):
            self._пульт_встал()

    def кто_едет(self) -> str:
        """Кто владеет колёсами — одним словом для лица, или пусто.

        Поездка считается ТРОНУВШЕЙСЯ, а не просто начатой. Поток движения
        живёт и тогда, когда память слепых направлений отказала на первом
        же круге, и пока он произносит «Не поеду: сзади человек»: живое
        `moving` в этот миг и давало на экране «поехали!» роботу, который не
        двинулся, и «приехали» — роботу, которого остановил сторож.
        """
        поток = getattr(self, "_motion", None)
        if (поток is not None and поток.is_alive()
                and self._поездка_тронулась):
            return "маршрут" if self._маршрут else "поездка"
        for д in getattr(self, "_движители", ()):
            try:
                if д.идёт():
                    return КТО_КОРОТКО.get(д.имя, д.имя.split()[0])
            except Exception:                   # noqa: BLE001
                log.exception("«%s» не сказал, едет ли он", д.имя)
        with self._lock:
            команда = self._команда
        if (команда is not None and команда[4] == "пульт"
                and self._крутятся(команда, self._часы())):
            return "пульт"
        return ""

    def ход(self) -> dict:
        """Что делают колёса прямо сейчас — для лица (face.json, итог_хода).

        Поля и единицы — договор с шаром на ПК (face/orb_rules.ход_шара):
        вперёд и вбок — м/с, поворот — рад/с против часовой (влево), факт —
        [v, w] по одометрии или None, упор — 0..1, старт — счётчик троганий,
        возраст — секунды с последней ненулевой команды по НАШИМ часам (ПК
        прибавит своё время в пути), связь — уходят ли команды в шасси.
        """
        сейчас = self._часы()
        self._пульт_молчит(сейчас)
        with self._lock:
            команда = self._команда
            факт = self._факт
            старт = self._старт
            когда = self._ненулевая_когда
            сильно_с = self._сильно_с
        крутятся = self._крутятся(команда, сейчас)
        x, y, wz = команда[:3] if крутятся else (0.0, 0.0, 0.0)
        if факт is not None and сейчас - факт[3] > ODOM_TTL:
            факт = None
        упор = self._упор(x, y, wz, факт, сильно_с, сейчас) if крутятся else 0.0
        if not крутятся:
            with self._lock:
                self._упор_с = None
        возраст = (ВОЗРАСТ_ПРЕДЕЛ if когда is None
                   else min(ВОЗРАСТ_ПРЕДЕЛ, max(0.0, сейчас - когда)))
        return {
            "крутятся": крутятся,
            "вперёд": _до_сотых(x, ХОД_ПОЧТИ_НОЛЬ),
            "вбок": _до_сотых(y, ХОД_ПОЧТИ_НОЛЬ),
            "поворот": _до_сотых(wz, ПОВОРОТ_ПОЧТИ_НОЛЬ),
            "факт": ([round(факт[0], 2), round(факт[2], 2)]
                     if факт is not None else None),
            "упор": round(упор, 2),
            "старт": старт,
            "возраст": round(возраст, 2),
            "связь": self._не_ушло < СВЯЗИ_НЕТ_ПОСЛЕ,
        }

    def _упор(self, x: float, y: float, wz: float, факт, сильно_с,
              сейчас: float) -> float:
        """0..1: велим ехать, а одометрия говорит «стоим». Только для показа.

        Растёт за УПЁРЛИСЬ_ЧЕРЕЗ — столько же, сколько _motion_loop ждёт,
        прежде чем объявить упор: шар начинает дрожать до вердикта, а не
        после, и к вердикту дрожит в полную силу.
        """
        if факт is None or сильно_с is None or сейчас - сильно_с < УПОР_ЖДЁМ:
            with self._lock:
                self._упор_с = None
            return 0.0
        стоим = True
        if math.hypot(x, y) >= УПОР_ХОД_ОТ:
            стоим = math.hypot(факт[0], факт[1]) < УПОР_ДОЛЯ * math.hypot(x, y)
        if стоим and abs(wz) >= УПОР_ПОВОРОТ_ОТ:
            стоим = abs(факт[2]) < УПОР_ДОЛЯ * abs(wz)
        with self._lock:
            if not стоим:
                self._упор_с = None
                return 0.0
            if self._упор_с is None:
                self._упор_с = сейчас
            return min(1.0, (сейчас - self._упор_с) / УПЁРЛИСЬ_ЧЕРЕЗ)

    @property
    def итог(self) -> dict:
        """Чем кончилось последнее движение: {номер, как, причина, сторона}."""
        with self._lock:
            итог = self._итог
        if итог is None:
            return {"номер": 0, "как": "", "причина": "", "сторона": None}
        return dict(итог)

    def отметить_итог(self, как: str, причина: str = "",
                      сторона: int | None = None) -> None:
        """Движение кончилось — так-то и потому-то. Номер растёт каждый раз.

        Номер, а не текст, по той же причине, что у «делает»: два одинаковых
        итога подряд — это две остановки, и шар обязан кивнуть дважды.

        Заведено против самой обидной лжи лица: ЛЮБАЯ остановка выглядела
        прибытием. Аварийная кнопка, голосовой «стоп», ладонь, сторож у стены,
        падение человека — всё давало один и тот же кивок «приехали», а
        потеря связи с колёсами — и вовсе спокойное лицо.
        """
        if сторона is None:
            сторона = сторона_по_причине(причина, как)
        with self._lock:
            номер = (self._итог or {}).get("номер", 0) + 1
            self._итог = {"номер": номер, "как": как,
                          "причина": str(причина or ""), "сторона": сторона}
        self._край()

    def _закрыть_поездку(self, как: str | None, причина: str = "", *,
                         тронувшуюся: bool = True) -> bool:
        """Итог СВОЕЙ поездки (drive/run_route) — ровно один, первым сказавшим.

        Сказать его могут четверо из разных потоков: кнопка из потока
        websocket, «стоп» голосом, сторож и конец цикла из потока движения.
        Раньше каждый проверял «едет ли ещё» и говорил сам, и две кнопки
        подряд (пульт шлёт пять нулей) давали два «кнопка», а кнопка в миг
        прибытия — «кнопка» и следом «доехал» с кивком «приехали». Проверка
        и отметка теперь под одним замком.

        `тронувшуюся` — закрывать, только если поездка правда тронулась
        (кнопка и голос по стоящей поездке итога не дают). `как` None —
        закрыть молча: итог уже сказан иначе (потеря связи с колёсами).
        """
        with self._lock:
            if self._итог_сказан or (тронувшуюся and not self._поездка_тронулась):
                return False
            self._итог_сказан = True
            self._поездка_тронулась = False
        if как:
            self.отметить_итог(как, причина)
        return True

    def _связи_нет(self) -> bool:
        """Не уходят ли команды в шасси — значит, и нули остановки не дошли."""
        return self._не_ушло >= СВЯЗИ_НЕТ_ПОСЛЕ

    def _тревога(self, причина: str) -> None:
        """Тревогу — лицу, мимо речи. См. тревога_хода."""
        тревога = self.тревога_хода
        if тревога is None:
            return
        try:
            тревога(причина)
        except Exception:                       # noqa: BLE001
            log.exception("лицо не встревожилось")

    def _встать(self) -> None:
        """Три нуля в колёса — столько же, сколько шлёт всякая остановка.

        Три, а не один: пакет может потеряться, а шасси держит последнюю
        скорость, пока ему не скажут иначе (см. _motion_loop).
        """
        for _ in range(3):
            self.publish_twist()
            time.sleep(0.02)

    def _оборвать(self, почему: str, фраза: str, как: str = "сторож") -> None:
        """Прекратить поездку: СНАЧАЛА колёса, ПОТОМ слова.

        Порядок — это и есть исправление. Раньше сторож, увидев препятствие,
        звал `объявить(...)` прямо из цикла движения, а нули уходили в finally
        — то есть ПОСЛЕ фразы. `объявить` — это voice.say: он ждёт замок речи
        и конец реплики, секунду-две. Последней командой в топике всё это
        время оставалась НЕнулевая скорость, и робот, говоря «Стою: впереди
        что-то», проезжал на 0.3 м/с ещё полметра — в то самое «что-то».
        docs/movement.md обещает, что колёса встают раньше, чем робот
        договорит; теперь это правда.

        `как` — вид итога для лица (ИТОГИ): «сторож», «вслепую», «упёрся»,
        «не_тронулся». Итог и тревога — тоже ДО фразы. Поток движения живёт,
        пока робот договаривает, и раньше лицо всё это время считало его
        едущим, а когда фраза кончалась — радостно кивало «приехали» роботу,
        которого только что остановили у стены.
        """
        self.прервано = почему
        self._оборвано_когда = time.monotonic()
        self._встать()
        # Колёса свободны, поездки больше нет — осталась только речь. Итог —
        # если его не сказала кнопка, нажатая, пока шли нули.
        self._закрыть_поездку(как, почему, тронувшуюся=False)
        self._тревога(почему)
        сказать = self.объявить
        if сказать is None:
            return
        # Говорим ОТДЕЛЬНЫМ ПОТОКОМ, как и про потерю связи, — поток движения
        # кончается сразу после нулей. Иначе он ждал замок речи: ход модели
        # держит голос весь ход, а второй drive того же хода ждал этот поток
        # в _пустить до двадцати пяти секунд. Двадцать семь секунд робот был
        # глух и нем — и потом всё равно ехал вторым коленом.
        threading.Thread(target=self._сказать_тихо, args=(сказать, фраза),
                         daemon=True, name="стою").start()

    def _связь_держится(self, ушло: bool) -> None:
        """Считаем неушедшие команды хода. Молча терять их нельзя.

        Пока робот стоит, порванная связь — это просто неработающие колёса, и
        узнаётся она по любой следующей команде. А вот порванная посреди хода
        — это другое: последняя дошедшая скорость на шасси ОСТАЁТСЯ, своего
        таймаута у драйвера нет, и «стоп» тем же путём тоже не дойдёт. Робот
        едет, а мы об этом не знаем и сказать не можем.

        Сделать отсюда мы можем ровно одно — сказать вслух. Человек рядом и
        есть последний сторож: он дотянется до выключателя. Молчание в этот
        момент — худшее из возможного.
        """
        if ушло:
            self._не_ушло = 0
            self._кричали_про_связь = False
            return
        self._не_ушло += 1
        # Пять подряд — это треть секунды на пятнадцати герцах. Одиночный
        # промах бывает при переподключении и сам себя чинит.
        if self._не_ушло < СВЯЗИ_НЕТ_ПОСЛЕ or self._кричали_про_связь:
            return
        self._кричали_про_связь = True
        log.error("команда хода не уходит в шасси уже %d раз подряд — "
                  "остановить робота отсюда НЕЧЕМ", self._не_ушло)
        # Лицу — ДО речи и НЕЗАВИСИМО от неё. Самое опасное положение робота
        # раньше показывалось самым спокойным лицом: фраза про связь не
        # похожа на «Стою: …», по которой лицо узнаёт тревогу, а без
        # дальномера её и сказать было нечем.
        self.отметить_итог("связь", "потерял связь с колёсами")
        self._тревога("потерял связь с колёсами")
        сказать = self.объявить
        if сказать is None:
            return
        # Отдельным потоком: говорит робот секундами, а поток движения должен
        # продолжать пытаться достучаться до шасси, а не ждать конца фразы.
        threading.Thread(
            target=lambda: self._сказать_тихо(
                сказать, "Потерял связь с колёсами. Выключи меня рукой."),
            daemon=True).start()

    @staticmethod
    def _сказать_тихо(сказать, фраза: str) -> None:
        try:
            сказать(фраза)
        except Exception:                       # noqa: BLE001
            log.exception("не смог сказать: %s", фраза)

    # --- кто крутит колёса ----------------------------------------------
    def завести_движитель(self, имя: str, идёт: Callable[[], bool],
                          остановить: Callable[[str], None]) -> None:
        """Заявить о ещё одном источнике движения. См. класс Движитель.

        Заявляться обязаны все, кто публикует /cmd_vel мимо drive(). Не
        заявившийся не выключается ни кнопкой СТОП, ни голосом, ни выходом
        из программы — и узнаётся об этом только тем, что робот не встал.
        """
        self._движители.append(Движитель(имя, идёт, остановить))
        log.info("колёса теперь умеет крутить ещё и «%s»", имя)

    def _чужой_стоп(self, почему: str) -> None:
        """Остановиться по требованию снаружи. НЕ ЖДЁТ и ждать не должен.

        Зовётся из потока websocket, который в это время не читает
        сообщения. Дождаться здесь чьего-нибудь потока — значит на это время
        оглохнуть, в том числе к следующим нулям той же кнопки.
        """
        # Итог — за свою поездку. Движители скажут свой сами, из своего
        # finally: причина «кнопка стоп» доедет до них через остановить().
        if self._своя_поездка_идёт():
            self._закрыть_поездку("кнопка", почему)
        self._motion_cancel.set()
        for д in self._движители:
            try:
                д.остановить(почему)
            except Exception:                   # noqa: BLE001
                log.exception("«%s» не остановился по требованию", д.имя)

    def stop_motion(self, почему: str = "голос") -> None:
        """Немедленно прекратить движение, чем бы оно ни было вызвано.

        `почему` — кто остановил, словами («сказали стоп», «показали
        ладонь»): уходит движителям как причина и лицу как итог (см.
        итог_по_причине). Раньше причины не было вовсе, и лицо не отличало
        «стоп» голосом от прибытия.
        """
        self.cancel_motion(почему=почему)
        self._встать()          # три раза — на случай потери пакета

    def _своя_поездка_идёт(self) -> bool:
        """Едет ли drive/run_route — тронувшись и ещё не кончившись.

        Не просто «жив ли поток»: оборванная сторожем поездка ещё живёт, пока
        робот договаривает «Стою: …», и «стоп» в эту секунду дал бы второй
        итог той же остановке.
        """
        motion = getattr(self, "_motion", None)
        return (motion is not None and motion.is_alive()
                and motion is not threading.current_thread()
                and self._поездка_тронулась)

    def cancel_motion(self, timeout: float = 2.0, почему: str = "остановили") -> None:
        motion = self._motion
        if self._своя_поездка_идёт():
            self._закрыть_поездку(итог_по_причине(почему, иначе="голос"), почему)
        self._motion_cancel.set()
        # Следование и всё прочее, что крутит колёса само, — тоже движение.
        # Без этой строки «стоп» останавливал поездку по команде и не трогал
        # следование: колёса замирали на десятую долю секунды, а следующий
        # круг чужого цикла трогал их снова.
        for д in self._движители:
            try:
                д.остановить(почему)
            except Exception:                   # noqa: BLE001
                log.exception("«%s» не остановился", д.имя)
        if motion is not None and motion.is_alive() and motion is not threading.current_thread():
            motion.join(timeout=timeout)

    @property
    def moving(self) -> bool:
        """Едем ли по своей команде — по любой, а не только по drive().

        Следование считается движением наравне с поездкой. Раньше не
        считалось, и из этого росла тихая беда: `moving` отвечал «стою», пока
        робот ехал за человеком, а на этом ответе держится разбор чужого нуля
        в /cmd_vel — то есть аварийная кнопка.
        """
        if self._motion is not None and self._motion.is_alive():
            return True
        for д in self._движители:
            try:
                if д.идёт():
                    return True
            except Exception:                   # noqa: BLE001
                log.exception("«%s» не сказал, едет ли он", д.имя)
        return False

    @property
    def busy(self) -> bool:
        """Движется ли робот вообще — хоть по голосу, хоть с веб-пульта.

        Пульт публикует /cmd_vel напрямую через rosbridge, минуя этот класс,
        поэтому смотрим на сам топик. Полторы секунды — с запасом к 15 Гц,
        с которыми пульт шлёт команды.
        """
        if self.moving:
            return True
        with self._lock:
            last = self._last_move
        return last > 0 and (time.monotonic() - last) < 1.5

    def drive(self, x: float, y: float, wz: float, duration: float,
              *, путь: float = 0.0, угол: float = 0.0) -> None:
        """Запускает движение в отдельном потоке.

        Возврат управления сразу — чтобы робот продолжал слушать и мог
        принять «стоп» на ходу.

        Путь и угол — сколько проехать и на сколько повернуться по правде,
        в метрах и радианах. Если шасси докладывает одометрию, движение
        кончается по ней, а duration остаётся предохранителем на случай, когда
        одометрия врёт или молчит. Без неё всё как раньше — по секундомеру.

        Если робот уже едет — ДОЖИДАЕМСЯ. Раньше новая команда отменяла
        прежнюю, и «проедь вперёд, а потом назад» кончалось одним движением
        назад: модель звала оба инструмента в одну секунду, второй убивал
        первый. Человек видел, что робот дёрнулся и уехал не туда.

        Отмена осталась ровно там, где нужна, — в stop_motion по слову «стоп».
        """
        self._пустить(self._motion_loop, (x, y, wz, duration),
                      {"путь": путь, "угол": угол})

    def run_route(self, шаги: list[dict]) -> None:
        """Несколько движений подряд — одной программой, одним потоком.

        Зачем отдельно от drive. Фигуру вроде зигзага или круга нельзя собрать
        из отдельных вызовов drive: каждый ждёт предыдущий в ОЧЕРЕДЬ_ЖДЁМ, и
        двенадцать шагов заняли бы главный цикл на всё время поездки — робот
        перестал бы слышать «стоп» ровно тогда, когда он нужнее всего.

        Здесь наоборот: управление возвращается сразу, а шаги отсчитывает
        отдельный поток. Поток этот — тот же самый self._motion, поэтому
        снаружи маршрут неотличим от обычной поездки: moving и busy правдивы,
        а stop_motion обрывает не текущий шаг, а всю программу целиком.

        Каждый шаг — словарь аргументов _motion_loop: x, y, wz, duration и,
        если есть одометрия, путь с углом.
        """
        self._пустить(self._route_loop, (list(шаги),), {})

    def _пустить(self, цель, args: tuple, kwargs: dict) -> None:
        """Общее начало любого движения: дождаться прежнего и завести поток."""
        if time.monotonic() - getattr(self, "_оборвано_когда", float("-inf")) \
                < ПОСЛЕ_ОБРЫВА_НЕ_ЕДЕМ:
            log.info("сторож только что остановил (%s) — следующее колено не "
                     "начинаю", self.прервано or "?")
            return
        # Сперва освобождаем колёса от всех прочих. Команда «проедь метр»,
        # отданная во время следования, раньше заводила второй поток на те же
        # колёса: два источника скорости по пятнадцать раз в секунду каждый,
        # и шасси выполняет тот, чей пакет пришёл последним. Робот от этого не
        # «выбирает» — он дёргается и едет в среднее место.
        #
        # Побеждает новая команда, а не старая: человек, сказавший «проедь
        # вперёд», отменил тем самым прежнее намерение, а не поставил его в
        # очередь.
        for д in self._движители:
            try:
                if д.идёт():
                    log.info("новая команда на колёса — прекращаю «%s»", д.имя)
                    д.остановить("дали другую команду")
            except Exception:                   # noqa: BLE001
                log.exception("«%s» не уступил колёса", д.имя)
        предыдущее = self._motion
        if (предыдущее is not None and предыдущее.is_alive()
                and предыдущее is not threading.current_thread()):
            # Ждём не бесконечно: если прежнее движение зависло, новое всё
            # равно должно случиться, иначе робот замрёт навсегда.
            предыдущее.join(timeout=ОЧЕРЕДЬ_ЖДЁМ)
        self.cancel_motion()
        self._motion_cancel.clear()
        # КНОПКА, НАЖАТАЯ В ЭТОТ ЗАЗОР, НЕ ПРОПАДАЕТ. Между cancel_motion выше
        # и стартом потока ниже `moving` отвечает «стою», и чужой ноль из
        # /cmd_vel разбор пропускал как «никто не едет». Человек жал СТОП,
        # видел, что робот встал, — и тот трогался следующей командой,
        # которая уже лежала в очереди. Свежий чужой стоп отменяет и её.
        if self._чужой_стоп_свежий():
            log.info("кнопка стоп только что нажималась — новое движение "
                     "не начинаю")
            self.прервано = "кнопка стоп"
            self.отметить_итог("кнопка", self.прервано)
            return
        # Долг по эхо здесь НЕ обнуляется, и это не забывчивость. Предыдущая
        # поездка только что доложила о себе тремя нулями; они ещё летят
        # обратно по подписке и обязаны быть съедены как свои. Прежний код
        # обнулял тут отметку времени — потому что окно в полсекунды иначе
        # накрыло бы начало новой поездки. Счётчику такое лечение не нужно:
        # он съест ровно три и ни одним больше.
        # Причина прошлого обрыва к новой поездке отношения не имеет.
        self.прервано = ""
        with self._lock:
            self._поездка_тронулась = False
            self._итог_сказан = False
        self._motion = threading.Thread(target=цель, args=args, kwargs=kwargs,
                                        daemon=True)
        self._motion.start()

    def _route_loop(self, шаги: list[dict]) -> None:
        """Шаги маршрута по очереди, с оглядкой на «стоп» между ними.

        Отмену проверяем и здесь, а не только внутри шага: _motion_loop от
        неё выходит молча, и без этой проверки маршрут после «стоп» просто
        поехал бы дальше со следующего колена.
        """
        всего = len(шаги)
        # Лицу маршрут — одна поездка: «доехал» колен не объявляется, иначе
        # шар кивал бы «приехали» на каждом углу квадрата.
        self._маршрут = True
        # Кончалось ли хоть одно колено по предохранителю. Тогда и весь
        # маршрут — не прибытие: иначе B10 жил бы в маршрутах дальше.
        предохранитель = False
        try:
            for номер, шаг in enumerate(шаги, 1):
                if self._motion_cancel.is_set():
                    log.info("маршрут прерван на шаге %d из %d", номер, всего)
                    return
                log.info("маршрут: шаг %d из %d", номер, всего)
                if self._motion_loop(**шаг) == "предохранитель":
                    предохранитель = True
                if self.прервано:
                    # Сторож остановил колено — вся программа отменяется, а
                    # не только оно. Маршрут задуман целиком: продолжить его
                    # со следующего шага значит поехать по фигуре, которой уже
                    # нет, мимо препятствия, которого робот не объезжал.
                    log.info("маршрут отменён на шаге %d из %d: %s",
                             номер, всего, self.прервано)
                    return
            log.info("маршрут пройден, шагов %d", всего)
            if self._motion_cancel.is_set():
                pass                            # итог сказал тот, кто отменил
            elif self._связи_нет():
                # Нули остановки не дошли — «доехал» был бы ложью. Итог
                # «связь» уже сказан тем, кто её потерял.
                self._закрыть_поездку(None, тронувшуюся=False)
            elif предохранитель:
                self._закрыть_поездку("предохранитель", "предохранитель",
                                      тронувшуюся=False)
            else:
                self._закрыть_поездку("доехал", "маршрут пройден",
                                      тронувшуюся=False)
        finally:
            self._маршрут = False

    def _motion_loop(self, x: float, y: float, wz: float, duration: float,
                     *, путь: float = 0.0, угол: float = 0.0) -> str:
        """Одна поездка (или колено маршрута). Вернёт её итог: «доехал»,
        «предохранитель» или пусто — итог сказал тот, кто оборвал."""
        # Команду повторяем пятнадцать раз в секунду. Раньше здесь стояло
        # объяснение «шасси при паузе само тормозит», и оно НЕВЕРНО.
        #
        # В драйвере WHEELTEC (turn_on_wheeltec_robot) Cmd_Vel_Callback просто
        # пакует пришедший Twist в кадр для STM32. Ни таймера, ни отметки
        # времени, ни повторной посылки нуля; единственное обнуление — в
        # деструкторе, который при kill -9 или segfault не зовётся. То есть
        # последняя посланная скорость действует, ПОКА НЕ ПРИДЁТ СЛЕДУЮЩАЯ.
        #
        # Повторять всё равно надо — по другой причине: свежая команда каждые
        # 66 мс это единственное, по чему сторож мёртвой руки отличает живого
        # издателя от умершего (scripts/cmd_vel_watchdog.py). А проверить,
        # есть ли таймаут в самой прошивке STM32, можно только на роботе:
        # scripts/check_deadman.py, колёса в воздухе.
        начало = self.odom if (путь or угол) else None

        def предохранитель() -> float:
            """Докуда ехать по секундомеру, если одометрия не остановит.

            Втрое дольше заказанного — с запасом: разгон съедает время, и
            робот доезжает позже, чем обещал секундомер.
            """
            return time.monotonic() + max(duration * 3.0, duration + 2.0)

        if начало is not None:
            deadline = предохранитель()
        else:
            deadline = time.monotonic() + duration
        пройдено = повёрнуто = 0.0
        прошлый = начало
        # Замолчала ли одометрия посреди поездки.
        потеряли = False
        # Когда робот перестал шевелиться, хотя команда идёт.
        стоим_с = 0.0
        прошлая_отметка = -1.0
        # Сторож судит только движение ВПЕРЁД: дальномер смотрит вперёд и про
        # то, что сзади и по бокам, не знает ничего. Запрещать по его данным
        # задний ход значило бы выдавать незнание за опасность.
        сторожим = x > 0 and self.сторож is not None
        # Слепое направление — всё, кроме чистого хода вперёд. Спрашиваем
        # каждый круг, а не один раз перед стартом: поездка длится секунды, и
        # человек за спиной успевает и подойти, и уйти.
        вслепую = self.сторож_вслепую is not None and (
            x < 0 or abs(y) > 1e-3
            or (abs(wz) > 1e-3 and abs(x) <= 1e-3 and abs(y) <= 1e-3))
        # Чем кончилась поездка — для лица. Пусто — сказали другие: тот, кто
        # отменил (stop_motion, кнопка), или _оборвать.
        итог = ""
        # Подали ли хоть одну ненулевую команду. Отказ на первом же круге —
        # это «не тронулся», а не «отпрянул от стены»: робот не двигался.
        тронулись = False
        try:
            while time.monotonic() < deadline and not self._motion_cancel.is_set():
                # Обрыв по любому из сторожей — через _оборвать: нули в
                # колёса идут ТАМ и ДО фразы. Здесь их нет намеренно, чтобы
                # порядок «встать, потом сказать» жил в одном месте.
                if вслепую:
                    можно, почему = self.сторож_вслепую(x, y, wz)
                    if not можно:
                        log.info("память не пускает вслепую: %s", почему)
                        # «Не тронулся» — только если не двигалась вся
                        # поездка: на колене маршрута робот уже ехал.
                        self._оборвать(почему, f"Не поеду: {почему}.",
                                       как="вслепую"
                                       if тронулись or self._поездка_тронулась
                                       else "не_тронулся")
                        break
                if сторожим:
                    можно, почему = self.сторож()
                    if not можно:
                        log.info("сторож оборвал поездку: %s", почему)
                        self._оборвать(почему, f"Стою: {почему}.", как="сторож")
                        break
                self.publish_twist(x, y, wz)
                if not тронулись and not _нулевая(x, y, wz):
                    тронулись = True
                    with self._lock:
                        # Кнопка, успевшая закрыть поездку до этого круга, —
                        # последнее слово: поездка снова «не тронется».
                        if not self._итог_сказан:
                            self._поездка_тронулась = True
                self._motion_cancel.wait(1 / 15)
                if начало is None:
                    continue
                сейчас = self.odom
                if сейчас is None:
                    # Одометрия замолчала ПОСРЕДИ поездки, и это отдельная
                    # беда, а не мелочь. Раньше цикл просто шёл дальше и
                    # публиковал ту же скорость до тройного предохранителя:
                    # команда «три метра» превращалась в сорок пять секунд
                    # хода — и молча, потому что выход по предохранителю
                    # ничего не объявляет.
                    #
                    # Считаем остаток по ПУТИ, а не по duration: секундомер
                    # врёт в меньшую сторону (разгон никто не считает), и
                    # остаток по нему систематически недоезжал бы. Тот же
                    # тройной запас, но от того, сколько осталось.
                    if not потеряли:
                        потеряли = True
                        осталось = max(0.0, (путь or 0.0) - пройдено)
                        по_времени = (осталось / max(1e-3, abs(x) + abs(y))
                                      if осталось else duration)
                        deadline = min(deadline,
                                       time.monotonic()
                                       + max(по_времени * 3.0, 1.0))
                        log.warning("одометрия замолчала на %.2f м из %.2f — "
                                    "доезжаю по секундомеру", пройдено,
                                    путь or 0.0)
                    continue
                if потеряли:
                    # Вернулась — снимаем укорочение. Кратковременный провал
                    # приёма не должен навсегда обрезать поездку.
                    потеряли = False
                    deadline = предохранитель()
                    log.info("одометрия вернулась")
                # Едем ли мы вообще. Колёса крутятся, команда уходит, а
                # робот стоит — значит упёрся: задом в стену, которую
                # дальномер не видит по построению, колесом в порожек,
                # шнуром за ножку стула.
                #
                # Раньше этого не замечал никто. Одометрия читалась ровно для
                # двух вопросов — сколько проехали и на сколько повернулись, —
                # а «заказано против фактического» не сравнивалось нигде.
                # Робот сорок пять секунд толкал стену, потом молча вставал
                # там, где обещал быть через три метра, и ничего не говорил:
                # выход по предохранителю ничего не объявляет.
                #
                # Меряем ДВИЖЕНИЕ, а не путь к цели: разворот на месте пути не
                # набирает вовсе, и судить его пройденным расстоянием значило
                # бы объявлять застрявшим каждый поворот.
                # Судим ТОЛЬКО по свежим замерам. Цикл крутится пятнадцать
                # раз в секунду, одометрия приходит двадцать, и один и тот же
                # замер иногда читается дважды — это не «робот стоит». А если
                # шасси замолчало совсем, но двух секунд ещё не прошло и
                # одометрия не считается протухшей, повторы шли бы полторы
                # секунды подряд, и робот объявлял бы упор там, где на самом
                # деле замолчал датчик. Сказать неправду о причине хуже, чем
                # промолчать.
                with self._lock:
                    отметка = self._odom_at
                if отметка == прошлая_отметка:
                    continue
                прошлая_отметка = отметка
                сдвиг = math.hypot(сейчас[0] - (прошлый or сейчас)[0],
                                   сейчас[1] - (прошлый or сейчас)[1])
                поворот_шаг = abs((сейчас[2] - (прошлый or сейчас)[2]
                                   + math.pi) % (2 * math.pi) - math.pi)
                if сдвиг > ШЕВЕЛИТСЯ or поворот_шаг > ШЕВЕЛИТСЯ_УГЛОМ:
                    стоим_с = 0.0
                elif not стоим_с:
                    стоим_с = time.monotonic()
                elif time.monotonic() - стоим_с > УПЁРЛИСЬ_ЧЕРЕЗ:
                    log.warning("колёса крутятся, а робот не двигается %.1f с "
                                "— прекращаю: кажется, я во что-то упёрся",
                                УПЁРЛИСЬ_ЧЕРЕЗ)
                    self._оборвать("кажется, я во что-то упёрся",
                                   "Стою: кажется, я во что-то упёрся. "
                                   "Посмотри, что там.", как="упёрся")
                    break

                if путь:
                    пройдено = math.hypot(сейчас[0] - начало[0],
                                          сейчас[1] - начало[1])
                    if пройдено >= путь:
                        log.info("проехал %.2f м из %.2f — останавливаюсь",
                                 пройдено, путь)
                        итог = "доехал"
                        break
                if угол and прошлый is not None:
                    # Складываем приращения, а не считаем разницу с началом:
                    # поворот идёт по кругу, и на трёхстах шестидесяти градусах
                    # разница вернулась бы к нулю.
                    шаг = сейчас[2] - прошлый[2]
                    шаг = (шаг + math.pi) % (2 * math.pi) - math.pi
                    повёрнуто += abs(шаг)
                    if повёрнуто >= угол:
                        log.info("повернулся на %.0f° из %.0f — останавливаюсь",
                                 math.degrees(повёрнуто), math.degrees(угол))
                        итог = "доехал"
                        break
                прошлый = сейчас
            else:
                # Вышли не по break: отменили — или кончился срок.
                if self._motion_cancel.is_set():
                    pass                        # итог сказал тот, кто отменил
                elif начало is None:
                    # Без одометрии срок и есть мера пути: доехали.
                    итог = "доехал"
                else:
                    # А вот с одометрией срок — это ПРЕДОХРАНИТЕЛЬ, и выход
                    # по нему раньше не говорил ничего. Втрое дольше
                    # заказанного робот ехал и не доехал: одометрия врёт,
                    # колесо буксует на ковре, задание кривое. Снаружи это
                    # выглядело обычным прибытием — и в журнале, и на лице.
                    log.warning("поездка кончилась по предохранителю (%s): "
                                "проехал %.2f м из %.2f, повернулся на %.0f° "
                                "из %.0f",
                                "одометрия замолчала" if потеряли
                                else "втрое дольше заказанного, одометрия "
                                     "так и не остановила",
                                пройдено, путь or 0.0, math.degrees(повёрнуто),
                                math.degrees(угол or 0.0))
                    итог = "предохранитель"
        finally:
            # Нули и здесь, даже если _оборвать их уже послал: finally —
            # единственное место, через которое проходит КАЖДЫЙ выход из
            # цикла, включая исключение, и три лишних нуля дешевле одного
            # недостающего.
            self._встать()
            # Итог — ПОСЛЕ нулей: «доехал» на лице значит «колёса стоят».
            # Колено маршрута не прибытие — итог скажет сам маршрут, по всем
            # коленам сразу (см. _route_loop).
            if итог and not self._маршрут:
                if self._связи_нет():
                    # Команды в шасси не уходят — значит, не ушли и нули: на
                    # колёсах, может быть, всё ещё последняя скорость. Ни
                    # «доехал», ни «предохранитель» — правдой был бы только
                    # итог «связь», и он уже сказан.
                    self._закрыть_поездку(None, тронувшуюся=False)
                else:
                    self._закрыть_поездку(итог, итог if итог != "доехал" else "",
                                          тронувшуюся=False)
        return итог
