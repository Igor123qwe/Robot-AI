"""Пол как ПЛОСКОСТЬ, а не как «нижние два ряда».

Зачем это понадобилось. Дальномер отдаёт 64 расстояния, и до сих пор робот
разбирался в них правилами: «ряды 2–5 — препятствие ближе 35 см», «ряды 6–7 —
пол, сравни с нормой». Правила держались на трёх допущениях, и все три
ломались на живом роботе:

  1. Что известно, какой ряд верхний. Не известно: «пола не вижу, где верх —
     не понял» — обычная строка в журнале, после которой защита от обрыва
     выключалась совсем.
  2. Что норма пола, снятая при запуске, верна и дальше. Неверна: включился у
     ступеньки — запомнил нормой пустоту; задели датчик — норма от другой
     геометрии.
  3. Что пол не попадает в ряды 2–5. Попадает. При наклоне датчика вниз на
     10–15°, как было записано в docs/hardware.md, ряд 5 упирается в пол на
     33 см — ближе порога стопа. Робот, собранный строго по инструкции,
     упирался в собственный пол и не ехал вперёд НИКОГДА.

Все три допущения не нужны, если считать пол тем, чем он и является, —
плоскостью. Расстояние плюс известный угол зоны дают точку в пространстве;
64 точки задают плоскость с большим запасом. Дальше всё выводится, а не
предполагается:

    точка на плоскости           — пол, ехать можно
    точка над плоскостью на 5 см — предмет: нога, кошка, порог, ножка стула
    пола нет там, где он должен быть — обрыв ИЛИ чёрный ковёр (см. ниже)
    наклон плоскости             — куда смотрит датчик, сам, без галок

И пересчитывается это каждый кадр: задели датчик — через десятую долю секунды
робот уже знает новую геометрию. Ни нормы, ни калибровки, ни отвёртки.

ЧЕГО ГЕОМЕТРИЯ НЕ МОЖЕТ. Отличить обрыв от чёрного ковра. Лазер не
возвращается ни от того, ни от другого, и данных для различения нет в
принципе — это не недостаток метода, а отсутствие сигнала. Здесь мы честно
говорим «дыра», а решать, ступенька это или коврик, должен тот, у кого есть
другой источник: камера. Отсюда `дыры()` — их отдают наружу отдельно.
"""

from __future__ import annotations

import logging
import math

import numpy as np

log = logging.getLogger(__name__)

# Поле зрения платы, градусов. Квадратное: 60 на 60 при сетке 8×8.
ПОЛЕ = 60.0
СТОРОНА = 8

# Ближе этого точка над плоскостью считается самой плоскостью. Пять
# сантиметров: ToF врёт на сантиметр-полтора, ковёр и порожек дают ещё
# столько же, а нога человека выше семи. Меньше — начнём тормозить о стыки
# плитки, больше — перестанем видеть тапок.
ТОЛЩИНА_ПОЛА = 0.05

# Насколько плоскость должна быть похожа на пол, чтобы мы ей поверили.
# Нормаль пола смотрит вверх; косинус с вертикалью ниже этого — значит
# нашлась стена или столешница сбоку, а не пол под колёсами.
ПОХОЖА_НА_ПОЛ = 0.80

# Сколько точек обязано лечь в плоскость, чтобы считать её найденной. Меньше
# трети — это не пол, а случайное совпадение трёх замеров.
ТОЧЕК_ХВАТИТ = 0.30

# Сколько попыток отбора. Тридцать хватает: доля точек пола в кадре редко
# ниже трети, и вероятность ни разу не попасть в три «половых» точки за
# тридцать заходов меньше сотой доли процента.
ПОПЫТОК = 30

# Разброс, в пределах которого точка считается лежащей в плоскости при отборе.
ДОПУСК = 0.03


def направления(поле: float = ПОЛЕ, сторона: int = СТОРОНА) -> np.ndarray:
    """Единичные векторы взгляда каждой зоны, (сторона, сторона, 3).

    Оси робота: x вперёд, y влево, z вверх.

    Ряд 0 — верхний, колонка 0 — левая. Это соглашение сетки, а не свойство
    платы: какой ряд физически верхний, мы больше не выясняем и не обязаны —
    плоскость найдётся при любом развороте, а её нормаль и скажет, где верх.
    """
    середина = (сторона - 1) / 2.0
    шаг = math.radians(поле / сторона)
    вверх = (середина - np.arange(сторона)) * шаг          # ряд → угол вверх
    влево = (середина - np.arange(сторона)) * шаг          # колонка → влево

    тангаж = вверх[:, None]
    рыскание = влево[None, :]
    x = np.cos(тангаж) * np.cos(рыскание)
    y = np.cos(тангаж) * np.sin(рыскание)
    z = np.sin(тангаж) * np.ones_like(рыскание)
    оси = np.stack([x, y, z], axis=-1)
    return оси / np.linalg.norm(оси, axis=-1, keepdims=True)


_НАПРАВЛЕНИЯ = направления()


def точки(сетка) -> tuple[np.ndarray, np.ndarray]:
    """Замеры → точки в пространстве. Возвращает (точки, маска живых).

    Мёртвые зоны (плата вернула ноль — не измерила) в точки не превращаются:
    ноль расстояния означает «не знаю», а не «упёрлись носом». Спутать эти два
    смысла — старая беда этого проекта, и здесь она отсекается на входе.
    """
    д = np.asarray(сетка, dtype=np.float64)
    живые = д > 0.0
    return _НАПРАВЛЕНИЯ * д[:, :, None], живые


def _плоскость_по_трём(а, б, в) -> tuple[np.ndarray, float] | None:
    нормаль = np.cross(б - а, в - а)
    длина = np.linalg.norm(нормаль)
    if длина < 1e-9:
        return None                     # три точки на одной прямой
    нормаль = нормаль / длина
    return нормаль, float(нормаль @ а)


class Плоскость:
    """Найденный пол: нормаль, отступ и всё, что из них следует."""

    def __init__(self, нормаль: np.ndarray, отступ: float,
                 своих: int, всего: int) -> None:
        # Нормаль всегда смотрит ВВЕРХ (в сторону робота). Иначе знак высоты
        # переворачивается, и предмет на полу становится ямой — ошибка,
        # которую в цифрах не видно, а в поведении видно сразу.
        if нормаль[2] < 0:
            нормаль, отступ = -нормаль, -отступ
        self.нормаль = нормаль
        self.отступ = отступ
        self.своих = своих
        self.всего = всего

    @property
    def высота(self) -> float:
        """Высота датчика над полом, метры."""
        return float(-self.отступ) if self.нормаль[2] > 0 else 0.0

    @property
    def наклон(self) -> float:
        """На сколько градусов датчик смотрит вниз. Отрицательно — вверх.

        Выводится из нормали, а не задаётся настройкой. Значит наклон датчика
        перестал быть тем, что человек обязан выставить правильно: любой
        сгодится, лишь бы пол попадал в кадр.
        """
        # Нормаль пола в осях робота: у идеально ровно стоящего датчика она
        # равна (0, 0, 1). Наклон датчика вниз откидывает её назад, поэтому
        # знак берём обратный — чтобы «наклон 10°» значило «смотрит вниз на
        # десять градусов», как это и понимает человек с отвёрткой.
        return -math.degrees(math.atan2(self.нормаль[0], self.нормаль[2]))

    @property
    def похожа_на_пол(self) -> bool:
        return abs(float(self.нормаль[2])) >= ПОХОЖА_НА_ПОЛ

    def высоты(self, точки_: np.ndarray) -> np.ndarray:
        """Высота каждой точки над плоскостью, метры. Отрицательная — под ней."""
        return точки_ @ self.нормаль - self.отступ


def найти(сетка, ряды: range | None = None) -> Плоскость | None:
    """Найти пол в кадре. None — не нашёлся, решать придётся старыми правилами.

    Отбор случайными тройками с подсчётом согласных (RANSAC), а не подгонка по
    всем точкам сразу. Причина простая: в кадре кроме пола есть стены, мебель
    и человек, и средняя плоскость по всему подряд не будет ни полом, ни
    стеной. Отбор ищет ту плоскость, с которой согласно БОЛЬШИНСТВО, а
    несогласных отбрасывает — они и есть препятствия.
    """
    все_точки, живые = точки(сетка)
    if ряды is not None:
        маска = np.zeros_like(живые)
        маска[ряды, :] = True
        живые = живые & маска

    набор = все_точки[живые]
    if len(набор) < 3:
        return None

    порог = max(3, int(len(набор) * ТОЧЕК_ХВАТИТ))
    лучшая: tuple[np.ndarray, float] | None = None
    лучших = 0
    # Перебор детерминированный, без случайности: одинаковый кадр обязан
    # давать одинаковый ответ. Робот, который на том же месте то едет, то не
    # едет, неотлаживаем.
    шаг = max(1, len(набор) // 8)
    for i in range(0, len(набор), шаг):
        for j in range(i + 1, len(набор), шаг):
            for k in range(j + 1, len(набор), шаг):
                кандидат = _плоскость_по_трём(набор[i], набор[j], набор[k])
                if кандидат is None:
                    continue
                нормаль, отступ = кандидат
                свои = int(np.sum(np.abs(набор @ нормаль - отступ) <= ДОПУСК))
                if свои > лучших:
                    лучших, лучшая = свои, кандидат

    if лучшая is None or лучших < порог:
        return None

    # Уточняем по всем согласным сразу: тройка задаёт плоскость грубо, а
    # среднее по тридцати точкам — точно.
    нормаль, отступ = лучшая
    свои = набор[np.abs(набор @ нормаль - отступ) <= ДОПУСК]
    центр = свои.mean(axis=0)
    _, _, оси = np.linalg.svd(свои - центр)
    нормаль = оси[-1]
    отступ = float(нормаль @ центр)
    return Плоскость(нормаль, отступ, len(свои), len(набор))
