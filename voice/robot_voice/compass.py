"""Компас по стенам: абсолютный курс там, где гироскоп уплывает.

ЗАЧЕМ. Курс робота считается интегрированием угловой скорости, а интеграл
шума — это дрейф. У шасси на гироскопе он идёт градус-другой в минуту, и это
не мелочь: за двадцать минут обхода набегает до полукруга. На карте квартиры
двадцать метров стороной такой поворот превращает прямой коридор в веер, стены
расходятся на метры, и НИКАКАЯ навигация этого не исправит — она работает на
данных, которые уже неверны.

Хуже всего, что дрейф не виден изнутри. Робот уверен в своём курсе ровно так
же, как в первую минуту; ошибка накапливается молча и обнаруживается только
тем, что карта перестала походить на квартиру.

ЧТО С ЭТИМ ДЕЛАЮТ. Нужен АБСОЛЮТНЫЙ ориентир — что-то, что не уплывает.
В квартире он есть, и он бесплатный: стены. Жильё строят по прямоугольнику,
и все стены в нём смотрят в одну из четырёх сторон, отличающихся на девяносто
градусов. Это называется гипотезой манхэттенского мира, и в помещении она
верна почти всегда.

Значит так: смотрим на стену дальномером, считаем, под каким углом она стоит
относительно робота, прибавляем нынешний курс — получаем направление стены в
мире. Оно обязано быть кратно девяноста градусам плюс постоянная (как повёрнут
дом относительно нашего нуля). Постоянная неизвестна, но она ПОСТОЯННА, и в
этом весь фокус: если она поехала, поехал не дом, а наш курс. Разница и есть
накопленный дрейф.

ПОЧЕМУ ЭТО РАБОТАЕТ НА НАШЕМ ЖЕЛЕЗЕ. Замерено на модели: восемь колонок
дальномера, поставленные на плоскую стену в метре, дают её угол с разбросом
около одного градуса. Мы боремся с дрейфом в один-три градуса за минуту —
запас достаточный, чтобы поправка была осмысленной.

ЧЕГО ЭТОТ КОМПАС НЕ УМЕЕТ, и врать про это нельзя:

  • он не знает, где север. Он знает только, что дом стоит ровно, и держит
    курс относительно дома. Этого достаточно: карта тоже относительно дома;
  • он неоднозначен с точностью до девяноста градусов. Стена перед носом
    может быть любой из четырёх. Поэтому поправка вносится ТОЛЬКО МАЛЫМИ
    ДОЛЯМИ и только когда расхождение невелико: мы правим дрейф, а не ищем
    ориентацию заново. Робот, повернувшийся на настоящие девяносто градусов,
    компас не обманет — он просто увидит следующую стену;
  • он молчит в круглой комнате, посреди зала и перед шкафом, стоящим косо.
    Это нормально: молчание лучше выдумки, а стены рано или поздно найдутся.
"""

from __future__ import annotations

import logging
import math

from . import rig

log = logging.getLogger(__name__)

# Сколько колонок дальномера должны видеть стену, чтобы считать по ним угол.
# Пять из восьми: по четырём точкам прямая проводится ещё уверенно, но одна
# промахнувшаяся зона уводит её заметно, а пятая точка это лечит.
ТОЧЕК_НА_СТЕНУ = 5

# Насколько широко должны стоять крайние точки, чтобы углу можно было верить.
# Полметра: угол считается тем точнее, чем длиннее отрезок, а на коротком
# кусочке стены сантиметровый шум даёт градусы.
ШИРИНА_СТЕНЫ = 0.5

# Насколько точки могут отходить от прямой, чтобы счесть это одной плоскостью.
#
# ДОЛЯ ОТ ДАЛЬНОСТИ, А НЕ ПОСТОЯННАЯ ВЕЛИЧИНА. Сперва тут стояли три
# сантиметра на любом расстоянии, и компас на живом роботе молчал: «стен пока
# не видел» посреди комнаты.
#
# Причина в физике датчика. Шум дальномера растёт с дистанцией — паспорт задаёт
# его долей от измеряемого, а не абсолютом. Замерено на модели: у ровной стены
# в восьмидесяти сантиметрах остаток около восьми миллиметров, а в полутора
# метрах — уже двадцать четыре, и постоянный порог отсекал ПОЛОВИНУ честных
# замеров именно там, где стены чаще всего и оказываются.
#
# Полтора процента от средней дальности плюс сантиметр на всякий случай. При
# этом излом — стена со стулом, угол комнаты — даёт остаток в десятки
# сантиметров, то есть на порядок больше, и отсеивается как отсеивался.
ОСТАТОК_ДОЛЯ = 0.015
ОСТАТОК_ХОТЬ_БЫ = 0.01

# Ближе и дальше этого стене не верим. Ближе тридцати сантиметров дальномер
# врёт сам, дальше двух метров кончается его паспортная дальность, а на пределе
# шум растёт быстрее, чем польза.
СТЕНА_ОТ = 0.3
СТЕНА_ДО = 2.0

# Какие ряды сетки давать компасу. НЕ СПИСОК, А ВЫВОД ИЗ ГЕОМЕТРИИ — довод
# целиком в rig.ряды_видящие_стену. Коротко: `лучи` берёт по колонке минимум
# из рядов, поэтому один ряд, смотрящий в пол, побеждает в колонке всю стену,
# и компас меряет угол горизонтальной плоскости вместо вертикальной.
#
# Здесь, а не в mapping, потому что окно стены (СТЕНА_ДО) знает компас. В
# mapping это число называется ВЕРИМ_ДО и означает другое — докуда верим
# замеру, — и связывать их значило бы связать две разные осторожности.
РЯДЫ_СТЕН = rig.ряды_видящие_стену(СТЕНА_ДО)

# Насколько медленно подтягиваем курс к показаниям стен.
#
# Два процента на замер. Это сознательно ОЧЕНЬ медленно, и вот почему:
# ошибиться в компасе опаснее, чем не поправиться. Стена, принятая за другую
# (их четыре, и они на девяносто градусов), рванула бы карту на четверть
# круга. При двух процентах даже подряд идущая ошибка успевает быть замеченной
# и погашенной следующими правильными замерами, а настоящий дрейф — величина
# медленная, и его двух процентов на десять замеров в секунду хватает с лихвой.
ДОВЕРИЕ_ЗАМЕРУ = 0.02

# Больше этого расхождения считаем, что видим ДРУГУЮ стену, а не свою дрейфом
# уехавшую. Пятнадцать градусов: дрейф столько набирает за пять-десять минут,
# и мы успеем его выбрать задолго до; а вот перескок на соседнюю стену даёт
# сразу девяносто, и путать эти два случая нельзя.
ЧУЖАЯ_СТЕНА = math.radians(15)

# Сколько последних промахов мимо плоскости помним, чтобы назвать в журнале
# типичный остаток. Полсотни: больше не нужно для медианы, а память не резиновая.
ПОМНИМ_ОТКАЗОВ = 50


def угол_стены(лучи, почему=None) -> tuple[float, float] | None:
    """Под каким углом стоит стена перед роботом: (угол, остаток).

    `лучи` — [(угол зоны в радианах, расстояние в метрах), ...], то же, что
    отдаёт mapping.лучи. None — стены не видно или это не стена.

    Угол отсчитывается от направления «прямо перед роботом» и означает
    направление НОРМАЛИ к стене: ноль — стена стоит поперёк, робот смотрит ей
    в лицо.

    Считаем главную ось облака точек, а не наклон y(x). Наклон y(x) уходит в
    бесконечность у стены, стоящей вдоль взгляда, — а такие как раз и
    встречаются, когда робот едет по коридору.
    """
    def отказ(причина):
        if почему is not None:
            почему.append((причина, 0.0, 0.0))
        return None

    точки = [(d * math.cos(θ), d * math.sin(θ)) for θ, d in лучи
             if СТЕНА_ОТ <= d <= СТЕНА_ДО]
    if len(точки) < ТОЧЕК_НА_СТЕНУ:
        return отказ("мало точек в дальности")
    ширина = math.hypot(точки[0][0] - точки[-1][0],
                        точки[0][1] - точки[-1][1])
    if ширина < ШИРИНА_СТЕНЫ:
        return отказ("узкий кусок")
    сx = sum(т[0] for т in точки) / len(точки)
    сy = sum(т[1] for т in точки) / len(точки)
    xx = yy = xy = 0.0
    for x, y in точки:
        дx, дy = x - сx, y - сy
        xx += дx * дx
        yy += дy * дy
        xy += дx * дy
    if abs(xx) < 1e-12 and abs(yy) < 1e-12:
        return отказ("точки слиплись")
    вдоль = 0.5 * math.atan2(2 * xy, xx - yy)
    # Остаток — среднее расстояние точек до найденной прямой. Настоящая стена
    # даёт шум датчика, излом (стена плюс стул, угол комнаты) — в разы больше.
    нx, нy = -math.sin(вдоль), math.cos(вдоль)
    остаток = sum(abs((x - сx) * нx + (y - сy) * нy)
                  for x, y in точки) / len(точки)
    подальше = sum(math.hypot(x, y) for x, y in точки) / len(точки)
    if остаток > max(ОСТАТОК_ХОТЬ_БЫ, ОСТАТОК_ДОЛЯ * подальше):
        if почему is not None:
            # Числа кладём ОТДЕЛЬНО от названия причины. Первая редакция
            # вписывала их в саму строку, и каждый отказ становился
            # уникальным: счётчик разлетался на сотню строк по одной штуке
            # вместо одной строки со ста.
            почему.append(("не плоскость", остаток, подальше))
            return None
        return отказ("не плоскость")
    return вдоль + math.pi / 2, остаток


def в_клетку(угол: float) -> float:
    """Свести угол к диапазону четверти оборота: стены неотличимы через 90°."""
    четверть = math.pi / 2
    return (угол + четверть / 2) % четверть - четверть / 2


class Компас:
    """Держит курс по стенам квартиры. Отдаёт поправку к одометрии.

    Пользоваться так: на каждом кадре дальномера позвать `заметить`, а курс
    брать не сырой, а через `поправить`.
    """

    def __init__(self) -> None:
        # Как повёрнут дом относительно нашего нуля, в пределах четверти
        # оборота. None — ещё ни одной стены не видели.
        self.дом: float | None = None
        # Накопленная поправка к курсу одометрии.
        self.поправка = 0.0
        self.замеров = 0
        self.принято = 0
        # ПОЧЕМУ НЕ ВЫШЛО — ПО ПРИЧИНАМ. Без этого «стен пока не видел»
        # неотличимо от «стен вокруг нет», и разбираться приходится гаданием.
        # На живом роботе именно так и вышло: компас молчал, а какое из четырёх
        # сит его глушит — по журналу было не понять.
        self.отказы: dict[str, int] = {}
        # Последние промахи мимо плоскости: (остаток, дальность). Нужны, чтобы
        # сказать в журнале не только «не плоскость», но и НАСКОЛЬКО не — по
        # этому числу сразу видно, шумит ли датчик сильнее ожидаемого или
        # перед роботом и правда не стена.
        self._мимо: list[tuple[float, float]] = []

    def заметить(self, курс: float, лучи) -> bool:
        """Учесть стену, если она видна. True — замер принят."""
        причины: list = []
        найдено = угол_стены(лучи, причины)
        if найдено is None:
            за_что, остаток, дальше = (причины[0] if причины
                                       else ("нет лучей", 0.0, 0.0))
            self.отказы[за_что] = self.отказы.get(за_что, 0) + 1
            if остаток:
                self._мимо.append((остаток, дальше))
                del self._мимо[:-ПОМНИМ_ОТКАЗОВ]
            return False
        self.замеров += 1
        отн, _остаток = найдено
        видно = в_клетку(курс + self.поправка + отн)
        if self.дом is None:
            # Первая стена и задаёт, как повёрнут дом. Спорить не с чем.
            self.дом = видно
            self.принято += 1
            return True
        расхождение = в_клетку(видно - self.дом)
        if abs(расхождение) > ЧУЖАЯ_СТЕНА:
            # Стена не та, за которую мы её приняли, или это вовсе не стена.
            # Молчим: правка по ней увела бы курс на десятки градусов.
            return False
        # Дом стоять не мог — значит уехали мы. Гасим расхождение малой долей.
        self.поправка -= расхождение * ДОВЕРИЕ_ЗАМЕРУ
        self.принято += 1
        return True

    def поправить(self, курс: float) -> float:
        """Курс одометрии с учётом накопленного дрейфа."""
        return (курс + self.поправка + math.pi) % (2 * math.pi) - math.pi

    def поза(self, поза):
        """То же для целой позы (x, y, курс). None остаётся None."""
        if поза_плоха(поза):
            return поза
        x, y, курс = поза
        return (x, y, self.поправить(курс))

    def как_дела(self) -> str:
        """Строка для журнала: сколько набрали и на сколько поправляем."""
        if self.дом is None:
            return ("компас: стен пока не видел" + self._отчёт_об_отказах()
                    + _про_ряды())
        return (f"компас: дом повёрнут на {math.degrees(self.дом):+.1f}°, "
                f"поправка к курсу {math.degrees(self.поправка):+.2f}°, "
                f"принято {self.принято} замеров из {self.замеров}"
                + self._отчёт_об_отказах() + _про_ряды())

    def _отчёт_об_отказах(self) -> str:
        """Почему стена не засчиталась — по видам, с числами."""
        if not self.отказы:
            return ""
        куски = []
        for вид, сколько in sorted(self.отказы.items(), key=lambda т: -т[1]):
            если = f"{вид} — {сколько}"
            if вид == "не плоскость" and self._мимо:
                остатки = sorted(о for о, _ in self._мимо)
                дальше = sorted(д for _, д in self._мимо)
                сред_о = остатки[len(остатки) // 2]
                сред_д = дальше[len(дальше) // 2]
                порог = max(ОСТАТОК_ХОТЬ_БЫ, ОСТАТОК_ДОЛЯ * сред_д)
                если += (f" (обычно {сред_о * 1000:.0f} мм на {сред_д:.1f} м, "
                         f"пускаю до {порог * 1000:.0f})")
            куски.append(если)
        return " | не вышло: " + ", ".join(куски)


def _про_ряды() -> str:
    """Сказать, если кронштейн оставил компасу слишком мало рядов.

    Молчим, пока рядов хватает: журнал не место для строки, которая всегда
    одна и та же. А когда их один — говорим, и говорим ПРИЧИНУ, потому что
    иначе это выглядит как «компас плохой», а на деле это наклон.

    Один ряд компас получает начиная примерно с 25° вниз, а с 31° не получил
    бы ни одного — там его спасает запасной ряд из rig, и без этой строки
    спасение было бы неотличимо от исправной работы.
    """
    if len(РЯДЫ_СТЕН) > 1:
        return ""
    ряд = РЯДЫ_СТЕН[0]
    return (f" | стены смотрю одним рядом ({ряд}) из восьми: при наклоне "
            f"{rig.ТОФ_НАКЛОН:.0f}° остальные упираются в пол ближе "
            f"{СТЕНА_ДО:.0f} м. Подними датчик — рядов станет больше")


def поза_плоха(поза) -> bool:
    if поза is None:
        return True
    try:
        return len(поза) < 3
    except TypeError:
        return True
