# Нарезка на фразы
# --- конец реплики по громкости ---------------------------------------------
# Сколько подряд тихих кадров считаем концом реплики. Шестьсот миллисекунд —
# то самое число, на котором сходятся все, кто делает голосовых собеседников:
# меньше — режем человека на вдохе посреди фразы, больше — он ждёт зря.
ТИШИНЫ_ХВАТИТ_МС = 600
# И сколько речи должно накопиться, чтобы вообще начать искать конец. Триста
# миллисекунд: короче не бывает даже «стоп», а щелчок или хлопок двери
# набирал бы конец реплики мгновенно и слал в распознавание пустоту.
РЕЧИ_ХВАТИТ_МС = 300
# Ниже какой доли размаха «речь минус фон» считаем, что человек замолчал.
# Четверть: голос говорящего в метре от микрофона громче фона в несколько раз,
# и падение до четверти размаха — это уже не пауза между словами, а конец.
ТИХО_НИЖЕ_ДОЛИ = 0.25
# Насколько быстро подстраивается оценка фона. Половина за секунду: комната
# меняется медленно, а подстраиваться под самого говорящего нельзя — иначе
# фон «догонит» его голос и речь окажется тишиной.
ФОН_ЗА_СЕКУНДУ = 0.5


class КонецПоГромкости:
    """Договорил ли человек — по тому, что стало тихо ОТНОСИТЕЛЬНО фона.

    ЗАЧЕМ, если есть VAD. Затем, что VAD отвечает на другой вопрос. Он говорит
    «здесь есть речь», и в комнате, где работает телевизор и играет ребёнок,
    честно отвечает «есть» ВСЕГДА — речь там и правда есть, просто не наша.
    Правило «полтысячи миллисекунд тишины» в такой комнате не срабатывает ни
    разу, запись каждый раз доезжает до потолка окна, и человек ждёт лишние
    четыре секунды, уже всё сказав. В живом журнале это половина всех команд:

        аудио: имя услышано — слушаю команду
        аудио: окно команды кончилось, а тишины так и не было — пишу 5.0 с

    ЧТО СЧИТАЕМ ВМЕСТО ЭТОГО. Не «есть ли речь», а «стало ли тихо по сравнению
    с тем, как громко было». Человек, отдающий команду роботу, стоит в шаге от
    микрофона и звучит в разы громче фона; когда он замолкает, громкость
    падает обратно к фону — и это видно, даже если фон сам по себе шумный.
    Порог берём не абсолютный, а долей размаха «речь минус фон»: так он
    подстраивается и под тихую ночную кухню, и под комнату с телевизором.

    ГЛАВНОЕ СВОЙСТВО — то же, что у turn_end: РЕЖЕМ ТОЛЬКО РАНЬШЕ, никогда не
    позже. Старые правила (тишина по VAD и потолок окна) остаются нетронутыми,
    значит худший случай равен вчерашнему поведению.
    """

    def __init__(self, *, частота: int = 16000, кадр_мс: int = FRAME_MS,
                 тишины_мс: int = ТИШИНЫ_ХВАТИТ_МС,
                 речи_мс: int = РЕЧИ_ХВАТИТ_МС) -> None:
        self.кадр_мс = кадр_мс
        self.тихих_надо = max(1, тишины_мс // кадр_мс)
        self.речи_надо = max(1, речи_мс // кадр_мс)
        self.фон: float | None = None
        # Насколько сдвигается оценка фона за один кадр.
        доля_в_секунду = ФОН_ЗА_СЕКУНДУ
        кадров_в_секунду = 1000.0 / кадр_мс
        self.шаг_фона = 1.0 - (1.0 - доля_в_секунду) ** (1.0 / кадров_в_секунду)
        self.начать()

    def начать(self) -> None:
        """Новая реплика: забыть накопленное про громкость, но не про фон."""
        self.громче_всего = 0.0
        self.тихих = 0
        self.кадров = 0

    def слушать_фон(self, кадр) -> None:
        """Кадр из тишины между репликами — им и уточняем фон.

        Кормить сюда надо только то, что звучит ДО имени: пока человек
        говорит, фон обновлять нельзя, иначе он догонит голос и речь окажется
        тишиной. Ровно на этом ломаются наивные автопороги.
        """
        уровень = _громкость(кадр)
        if self.фон is None:
            self.фон = уровень
        else:
            self.фон += (уровень - self.фон) * self.шаг_фона

    def договорил(self, кадр) -> bool:
        """Скормить кадр речи. True — человек, похоже, закончил."""
        уровень = _громкость(кадр)
        фон = self.фон if self.фон is not None else 0.0
        self.кадров += 1
        self.громче_всего = max(self.громче_всего, уровень)
        размах = self.громче_всего - фон
        if размах <= 1e-6:
            # Ничего громче фона так и не прозвучало — судить не по чему.
            self.тихих = 0
            return False
        порог = фон + размах * ТИХО_НИЖЕ_ДОЛИ
        if уровень <= порог:
            self.тихих += 1
        else:
            self.тихих = 0
        return (self.кадров >= self.речи_надо
                and self.тихих >= self.тихих_надо)


def _громкость(кадр) -> float:
    """Средняя громкость кадра. Не пик: одиночный щелчок не должен решать."""
    массив = np.asarray(кадр, dtype=np.float32)
    if not массив.size:
        return 0.0
    return float(np.sqrt(np.mean(массив * массив)))


