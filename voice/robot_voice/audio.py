"""Захват звука и нарезка на фразы по детектору речи.

Три источника:
  local   — микрофон, воткнутый в RDK X5 (после приезда ReSpeaker Lite);
  phone   — старый Android с приложением IP Webcam, отдаёт /audio.wav;
  browser — микрофон компьютера: вкладка пульта шлёт звук на веб-сервер
            робота, а мы забираем его оттуда потоком. Удобно для отладки:
            наушники на голове, эха нет, телефон не нужен.

Пока робот говорит, микрофон заглушён: аппаратного эхоподавления нет, и на
полном словаре робот распознаёт собственный голос — проверено, он отвечал сам
себе. Программный AEC поверх Wi-Fi с плавающей задержкой этого не лечит.

Но ОДНО ухо всё же оставлено открытым: пока робот говорит, отдельный
распознаватель слушает десяток слов вроде «хватит» и «замолчи», чтобы человек
мог перебить длинную реплику. Это работает без эхоподавления по трём причинам,
и все три обязательны: словарь из десяти слов вместо тысяч, запрет на слова,
которые робот произносит прямо сейчас (иначе рассказ про умения остановит сам
себя — в нём есть «по слову стоп»), и низкая цена ошибки: ложное срабатывание
всего лишь обрывает реплику робота. Подробности — в _начать_перебивание.
"""

from __future__ import annotations

import io
import logging
import struct
import subprocess
import threading
import time
import wave
from collections import deque
from typing import Callable, Iterator

import numpy as np
import webrtcvad

from .wake import ПЕРЕБИВАНИЕ, clean_token as _чистое

log = logging.getLogger(__name__)

FRAME_MS = 20  # webrtcvad принимает только 10, 20 или 30 мс

# Сколько «микрофон считается живым» после последнего настоящего звука.
# Пять секунд: человек молчит между фразами дольше, чем можно подумать,
# а вот закрытая вкладка молчит навсегда.
REAL_AUDIO_TTL = 5.0

# Через сколько молчания считать arecord зависшим и убивать. Пятнадцать секунд:
# исправный отдаёт кадры непрерывно, а столько тишины подряд бывает только у
# мёртвого процесса.
ЗАВИС_ЧЕРЕЗ = 15.0


# Сколько первых букв должны совпасть, чтобы счесть, что распознаватель
# принял слово робота за слово из словаря перебиваний.
#
# ТРИ. Число вынужденное, и цену за него надо назвать честно.
#
# Считать по числу правок не выходит: «стою» и «стоять» отличаются на ТРИ
# правки — то есть ровно на том случае, ради которого всё и делается, порог
# пришлось бы задрать так высоко, что под него попало бы полсловаря. А путается
# звук как раз началом слова, не концом.
#
# ЦЕНА. Пока робот произносит слово на «сто» — «стол», «стоит», «сто», — его
# нельзя перебить словами «стоп», «стой», «стоять». Это плохо, но заметно
# меньшее зло, и вот почему:
#
#   пропущенное перебивание откладывает остановку на длину реплики, секунду-
#   две: сказанное человеком никуда не девается, оно разберётся обычным путём,
#   как только робот замолчит. А сторож дальномера работает всё это время и от
#   голоса не зависит вовсе;
#
#   само-перебивание же убивает дело целиком и сразу. В живом журнале обход,
#   только что запущенный человеком, умер через секунду от голоса самого
#   робота.
СОВПАЛО_НАЧАЛО = 3


def _чем_услышит_себя(фраза: str | None) -> set[str]:
    """Слова словаря, в которые распознаватель превратит речь самого робота.

    ЗАЧЕМ НЕ ПРОСТО СРАВНИТЬ СЛОВА. Распознаватель перебиваний работает по
    ЗАКРЫТОЙ ГРАММАТИКЕ из двенадцати слов: всё, что он слышит, обязано стать
    одним из них. Робот сказал «Стою, жду» — «стою» превратилось в «стоять», и
    робот сам себя остановил.

    Поймано на живом роботе, в журнале это одна секунда:

        12:30:42 робот: Стою, жду.
        12:30:43 аудио: перебили словом «стоять» — стою и молчу
        12:30:43 обход кончился: остановили

    Обход, который человек только что запустил, умер от голоса самого робота.
    Прежняя защита сравнивала слова буквально: «стоять» среди сказанного
    («стою», «жду») не нашлось, и она пропустила.

    Поэтому глушим не сказанное, а то, ВО ЧТО ЕГО МОГУТ ПРЕВРАТИТЬ.
    """
    слова = {_чистое(с) for с in (фраза or "").lower().split()}
    слова.discard("")
    глушим = set(слова)
    for своё in слова:
        for чужое in ПЕРЕБИВАНИЕ:
            коротко = min(len(своё), len(чужое))
            if коротко >= СОВПАЛО_НАЧАЛО and своё[:СОВПАЛО_НАЧАЛО] == чужое[:СОВПАЛО_НАЧАЛО]:
                глушим.add(чужое)
    return глушим


