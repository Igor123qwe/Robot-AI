class Listener:
    """Выдаёт по одной законченной фразе (WAV-байты) за раз."""

    def __init__(self, source, *, sample_rate: int, vad_level: int,
                 silence_ms: int, min_speech_ms: int, max_speech_ms: int = 20000,
                 start_frames: int = 2, spotter=None,
                 command_ms: int = 10000,
                 спешим: Callable[[], bool] | None = None,
                 конец_реплики=None) -> None:
        self.pump = Pump(source)
        # Определитель конца реплики по звуку. Нет — режем по тишине, как
        # раньше. Он умеет обрывать запись только РАНЬШЕ прежних правил, так
        # что худший случай с ним равен сегодняшнему поведению.
        self.конец_реплики = конец_реплики
        # Второй определитель конца — по громкости относительно фона. В
        # отличие от `конец_реплики`, ему не нужен файл модели: он считает
        # арифметику по самому звуку и работает всегда. Довод целиком — в
        # КонецПоГромкости.
        self.по_громкости = КонецПоГромкости(частота=sample_rate)
        # Детектор имени на потоке. Есть — слушаем по имени и режем только
        # команду; нет — откатываемся на нарезку по паузам, см. utterances().
        self.spotter = spotter
        self.command_frames = max(1, command_ms // FRAME_MS)
        # Имя прозвучало в ЗВУКЕ, а не в тексте. Читается сразу после фразы —
        # как confidence у распознавания. Верх по этому признаку понимает, что
        # искать имя в расшифровке уже не надо: оно точно было.
        self.wake_heard = False
        # Кого дёрнуть, как только имя услышано. Нужно, чтобы приглушить
        # музыку ПРЯМО СЕЙЧАС, а не после распознавания: человек уже начал
        # говорить, и перекрикивать песню он не должен.
        self.on_wake: Callable[[], None] | None = None
        # Короткая команда, услышанная прямо здесь: «стоп», «дальше», «тише».
        # Пусто — обычная фраза, её надо распознавать. Не пусто — распознавать
        # нечего, слово уже известно, и это экономит две секунды на «стоп».
        self.instant = ""
        # Есть ли сейчас что прерывать. Мгновенный слой затевался ради одного:
        # «стоп» едущему роботу за доли секунды вместо двух с половиной. Когда
        # робот стоит, спешить некуда — и держать этот слой открытым значит
        # только собирать ложные срабатывания на обычной речи. Пусто — считаем,
        # что спешим всегда (так ведут себя проверки и старая сборка).
        self.спешим = спешим
        self.sample_rate = sample_rate
        self.vad = webrtcvad.Vad(vad_level)
        self.silence_frames = max(1, silence_ms // FRAME_MS)
        self._min_speech = max(1, min_speech_ms // FRAME_MS)
        self.max_speech_frames = max(1, max_speech_ms // FRAME_MS)
        # Начинаем запись только после нескольких подряд речевых кадров:
        # одиночный щелчок или стук посуды VAD принимает за речь.
        self._start = max(1, start_frames)
        # Играет ли рядом музыка. Детектор речи её за речь и принимает: на
        # живом роботе под включённое радио каждая пауза уезжала в
        # распознавание отдельным куском, тот возвращался пустым, и полсекунды
        # ПК уходило в никуда — по нескольку раз в минуту.
        self._noisy = False
        # Небольшой предбуфер, чтобы не отрезать начало слова.
        self.preroll = deque(maxlen=max(1, 300 // FRAME_MS))
        self._muted = threading.Event()
        # Что робот произносит прямо сейчас, и кого дёрнуть, если его
        # перебили. Пусто — перебивание выключено (нет детектора или некому
        # сообщать), и робот договаривает, как договаривал раньше.
        self.говорю = ""
        # Зовётся при перебивании и получает ЧТО просят прекратить: «молчи»
        # или «колёса». Разница существенная: «ясно» просит замолчать, а
        # «стоп» едущему роботу просит остановить колёса, и это важнее.
        self.on_barge: Callable[[str], None] | None = None
        self._барж: threading.Thread | None = None
        self._барж_стоп = threading.Event()
        # Последний кусок пришлось резать по длине, а не по паузе. Читается
        # сразу после получения фразы — как confidence у распознавания.
        # Такой кусок — это срез комнаты, а не реплика: имя в нём может стоять
        # где угодно, и разбирать его надо иначе.
        self.long_chunk = False

    # Сколько кадров после имени слушаем короткий приказ. Полторы секунды:
    # «стоп» и «дальше» звучат меньше секунды, а дальше начинается обычная
    # фраза, и ловить в ней отдельные слова опасно.
    МГНОВЕННЫХ_КАДРОВ = 1500 // FRAME_MS

    # Во сколько раз дольше должен звучать звук, чтобы под музыку считаться
    # началом фразы. Двух хватает: 40 мс подряд речевых кадров превращаются в
    # 80, а предбуфер в 300 мс всё равно донесёт начало слова целиком.
    NOISY = 2

    def background(self, шумно: bool) -> None:
        """Стало шумно или снова тихо. Зовётся, когда включают музыку."""
        if шумно != self._noisy:
            log.info("фон: %s", "играет музыка" if шумно else "тихо")
        self._noisy = шумно

    @property
    def start_frames(self) -> int:
        return self._start * self.NOISY if self._noisy else self._start

    @property
    def min_speech_frames(self) -> int:
        """Минимальная длина фразы. Под музыку НЕ поднимается — намеренно.

        Соблазн был: поднять оба порога и отсечь музыкальный мусор разом. Но
        этот порог отбраковывает уже записанный кусок по длине, а мусор под
        музыку был длинный — в логе куски по 2.6–3.6 секунды. То есть пользы
        никакой, а вред прямой: «стоп» — это меньше полусекунды речи, и
        удвоенный порог выбросил бы ровно ту команду, ради которой всё
        останавливается.
        """
        return self._min_speech

    # Пока робот говорит — не слушаем: иначе он расслышит сам себя.
    def mute(self, говорю: str = "") -> None:
        """Заглушить микрофон на время реплики и начать слушать перебивание.

        `говорю` — текст, который робот сейчас произносит. Он не для красоты:
        без него перебивание невозможно, см. _слушать_перебивание.
        """
        self.говорю = говорю
        self._muted.set()
        self._начать_перебивание()

    # --- перебивание ------------------------------------------------------
    def _начать_перебивание(self) -> None:
        """Слушать «хватит», пока робот говорит.

        Раньше этого не было, и в шапке модуля стояло, что barge-in появится
        только с аппаратным эхоподавлением. Это оказалось неверно — но верно
        было ОПАСЕНИЕ за ним: без эхоподавления робот слышит сам себя, а свою
        речь он произносит громче, чем человек из комнаты. Распознаватель на
        полном словаре тут же начал бы находить в собственном голосе что
        угодно.

        Отсюда три ограничения, и все три обязательны:

        1. Словарь ровно из слов перебивания плюс «[unk]». Десяток слов вместо
           тысяч — и возможность честно сказать «это не из моего словаря».
        2. Слово, которое робот СЕЙЧАС произносит, к перебиванию не годится.
           Без этой проверки рассказ про умения останавливал бы сам себя: в
           нём есть строка «могу остановиться по слову стоп». Проверено на
           живом тексте, он в selftest.
        3. Слушаем только пока говорим, и только по звуку, накопленному ПОСЛЕ
           начала реплики. Иначе перебиванием станет то, что человек сказал
           до неё.

        Цена ошибки здесь низкая, и это тоже часть решения: ложное срабатывание
        обрывает реплику робота — досадно, но безобидно. Ради этого можно
        позволить себе слышать нечётко.
        """
        if self.spotter is None or self.on_barge is None:
            return
        if self._барж is not None and self._барж.is_alive():
            return
        self._барж_стоп.clear()
        self._барж = threading.Thread(target=self._слушать_перебивание,
                                      daemon=True)
        self._барж.start()

    def _слушать_перебивание(self) -> None:
        import json as _json

        try:
            слух = self.spotter.слух_для_перебивания()
        except Exception:                       # noqa: BLE001
            log.exception("перебивание не поднялось — слушать не буду")
            return

        # Свои же слова к перебиванию не годятся: робот произносит их сам, и
        # услышит себя раньше человека.
        своё = _чем_услышит_себя(self.говорю)
        курсор = self.pump.сколько_было()
        while not self._барж_стоп.is_set() and self._muted.is_set():
            кадры, курсор = self.pump.свежие(курсор)
            if not кадры:
                self._барж_стоп.wait(0.05)
                continue
            for кадр in кадры:
                if слух.AcceptWaveform(кадр.tobytes()):
                    текст = _json.loads(слух.Result()).get("text", "")
                else:
                    текст = _json.loads(слух.PartialResult()).get("partial", "")
                for слово in текст.split():
                    голое = _чистое(слово)
                    if голое not in ПЕРЕБИВАНИЕ or голое in своё:
                        continue
                    что = ПЕРЕБИВАНИЕ[голое]
                    log.info("аудио: перебили словом «%s» — %s", голое,
                             "стою и молчу" if что == "колёса" else "замолкаю")
                    try:
                        self.on_barge(что)
                    except Exception:           # noqa: BLE001
                        log.exception("не смог замолчать по перебиванию")
                    return

    def unheard(self) -> bytes:
        """Звук, который накопился, пока его никто не разбирал — как WAV.

        Отдаётся именно копия: разбор на фразы этот же звук ещё получит.
        Пусто — значит и слушать нечего.
        """
        raw = self.pump.peek()
        if not raw:
            return b""
        return to_wav(np.frombuffer(raw, dtype=np.int16), self.sample_rate)

    def unmute(self) -> None:
        self._барж_стоп.set()
        self.говорю = ""
        self._muted.clear()
        self.preroll.clear()
        # Выбрасываем всё, что накопилось, пока робот говорил и думал.
        self.pump.drop_pending()

    def utterances(self) -> Iterator[bytes]:
        """Фразы для разбора. Как именно — решает наличие детектора имени."""
        if self.spotter is not None:
            yield from self._по_имени()
        else:
            yield from self._по_паузам()

    def _громкость(self) -> "КонецПоГромкости":
        """Определитель конца реплики по громкости, заводя его при нужде.

        Через метод, а не только через __init__: Listener собирают и в обход
        конструктора — в проверках, где ни микрофона, ни детектора имени нет,
        — и обращение к признаку, заведённому только в __init__, роняет там
        весь цикл нарезки.
        """
        готовый = getattr(self, "по_громкости", None)
        if готовый is None:
            готовый = КонецПоГромкости(
                частота=getattr(self, "sample_rate", 16000))
            self.по_громкости = готовый
        return готовый

    def _по_имени(self) -> Iterator[bytes]:
        """Слушаем имя на потоке, пишем только команду за ним.

        Пауз до имени не ждём вовсе — поэтому шумная комната и играющая музыка
        перестают мешать: детектор слушает поток как есть. Пауза нужна ровно
        для одного — понять, где команда кончилась.

        Имя в запись попадает не всегда: предбуфер короче слова, и начало
        может срезаться. Это не беда, а замысел — верх и не ищет имя в тексте,
        ему сказано звуком, что робота позвали.
        """
        self.pump.start()
        speech: list[np.ndarray] = []
        silence = 0
        пишем = False
        слушаем_приказ = 0
        молчим = False

        for frame in self.pump.frames():
            if self._muted.is_set():
                # Робот говорит сам. Копить его собственную речь в детекторе
                # нельзя: своё имя он произносит и сам, и позвал бы себя.
                #
                # Сбрасываем один раз на входе в молчание, а не на каждом
                # кадре: кадр — это двадцать миллисекунд, то есть Reset у
                # Kaldi звался полсотни раз в секунду всё время, пока робот
                # говорит. Работе это не мешало, но жгло процессор там, где
                # делать нечего.
                if not молчим:
                    self.spotter.сбросить()
                    молчим = True
                speech, silence, пишем = [], 0, False
                self.preroll.clear()
                continue
            молчим = False

            if not пишем:
                self.preroll.append(frame)
                # Фон уточняем ровно здесь — ДО имени. Пока человек говорит,
                # трогать оценку фона нельзя: она догонит его голос, и речь
                # окажется тишиной.
                self._громкость().слушать_фон(frame)
                if self.spotter.услышал(frame.tobytes()):
                    log.info("аудио: имя услышано — слушаю команду")
                    if self.on_wake is not None:
                        try:
                            self.on_wake()
                        except Exception:       # noqa: BLE001 — музыка не повод глохнуть
                            log.exception("не смог приглушить музыку")
                    speech = list(self.preroll)
                    silence, пишем = 0, True
                    self._громкость().начать()
                    # Спрашиваем ровно здесь, в миг имени: дальше человек уже
                    # говорит, и менять решение поздно.
                    слушаем_приказ = (self.МГНОВЕННЫХ_КАДРОВ
                                      if self.спешим is None or self.спешим()
                                      else 0)
                continue

            speech.append(frame)
            if слушаем_приказ:
                # Первые полторы секунды после имени слушаем короткий приказ.
                # Дальше не слушаем намеренно: «стоп» в середине длинной фразы
                # («да не надо, стоп-кран это не про нас») сработать не должен.
                слушаем_приказ -= 1
                приказ = self.spotter.команда(frame.tobytes())
                if приказ:
                    log.info("аудио: сразу услышал «%s» — не распознаю", приказ)
                    payload, speech = speech, []
                    silence, пишем, слушаем_приказ = 0, False, 0
                    self.preroll.clear()
                    self.wake_heard = True
                    self.instant = приказ
                    yield to_wav(np.concatenate(payload), self.sample_rate)
                    continue
            if self.vad.is_speech(frame.tobytes(), self.sample_rate):
                silence = 0
            else:
                silence += 1

            # Спрашиваем сеть, договорил ли человек, — и делаем это ВО ВРЕМЯ
            # РЕЧИ, а не в паузе. В этом весь смысл: в комнате, где не
            # смолкают, паузы не случается вовсе, и правило «полтысячи
            # миллисекунд тишины» не срабатывает НИ РАЗУ. Запись каждый раз
            # доезжает до потолка окна, и человек ждёт лишние секунды, уже
            # всё сказав. В журнале ПК это видно как «на 5.0 с звука» подряд.
            #
            # Сеть смотрит на саму реплику — интонацию, темп, грамматику, — и
            # фоновая болтовня ей не мешает так, как мешает VAD.
            договорил = False
            if self.конец_реплики is not None:
                накоплено = len(speech) * FRAME_MS / 1000.0
                if self.конец_реплики.пора_спросить(накоплено):
                    договорил = bool(self.конец_реплики.договорил(
                        np.concatenate(speech)))
            # А это работает всегда и без файла модели: стало тихо по
            # сравнению с тем, как громко было, — значит человек замолчал.
            # Считается на каждом кадре, потому что стоит копейки.
            стало_тихо = self._громкость().договорил(frame)

            # Либо человек договорил, либо говорит слишком долго. Предел здесь
            # щедрый: это длина ОДНОЙ команды, а не потолок задержки ответа,
            # как было у нарезки по паузам.
            if (договорил or стало_тихо or silence >= self.silence_frames
                    or len(speech) >= self.command_frames):
                payload, speech = speech, []
                silence, пишем, слушаем_приказ = 0, False, 0
                self.preroll.clear()
                self.wake_heard = True
                self.instant = ""
                # Чем именно кончилась запись — в журнал. Без этого нельзя
                # отличить работающий определитель от молчащего: и тот и
                # другой снаружи выглядят как «робот записал и отправил».
                if договорил:
                    log.info("аудио: слышу, что договорил — не жду тишины "
                             "(записано %.1f с из %.1f)",
                             len(payload) * FRAME_MS / 1000.0,
                             self.command_frames * FRAME_MS / 1000.0)
                elif стало_тихо:
                    log.info("аудио: стало тихо относительно фона — режу "
                             "(записано %.1f с из %.1f, фон %.4f, "
                             "громче всего %.4f)",
                             len(payload) * FRAME_MS / 1000.0,
                             self.command_frames * FRAME_MS / 1000.0,
                             self._громкость().фон or 0.0,
                             self._громкость().громче_всего)
                elif len(payload) >= self.command_frames:
                    log.info("аудио: окно команды кончилось, а тишины так и "
                             "не было — пишу %.1f с как есть",
                             len(payload) * FRAME_MS / 1000.0)
                # Обрывки этой команды остались в частичном результате: первые
                # полторы секунды её скармливали детектору, ища короткий
                # приказ, и совпадения не нашлось — а значит и сброса не было.
                # Без явного сброса первый же следующий кадр читает залежавшийся
                # партиал и объявляет имя во второй раз: робот сам себя
                # перебивает, приглушает музыку и записывает тишину.
                self.spotter.сбросить()
                yield to_wav(np.concatenate(payload), self.sample_rate)

    def _по_паузам(self) -> Iterator[bytes]:
        """Запасной способ: резать по паузам, имя искать в тексте.

        Работает без модели для ловли имени — хуже, но работает. Всё, что
        связано с «срезом комнаты», живёт только здесь: при живом детекторе
        куски приезжают размером с команду, и резать по длине незачем.
        """
        self.pump.start()
        speech: list[np.ndarray] = []
        silence = 0
        voiced_run = 0
        # Речевых кадров в куске — именно речевых, а не «всего минус хвост
        # тишины». Раньше считалось вторым способом, и в счёт попадали
        # предбуфер и семьсот миллисекунд тишины на конце: одиночный щелчок
        # набирал ровно порог и уезжал в распознавание как секунда почти
        # тишины. Порог при этом не работал вообще ни на чём.
        voiced_total = 0
        talking = False

        for frame in self.pump.frames():
            if self._muted.is_set():
                speech.clear()
                silence = voiced_run = voiced_total = 0
                talking = False
                continue

            is_speech = self.vad.is_speech(frame.tobytes(), self.sample_rate)

            if not talking:
                self.preroll.append(frame)
                voiced_run = voiced_run + 1 if is_speech else 0
                if voiced_run >= self.start_frames:
                    talking = True
                    speech = list(self.preroll)
                    silence = 0
                    voiced_total = voiced_run
                continue

            speech.append(frame)
            if is_speech:
                voiced_total += 1
            silence = 0 if is_speech else silence + 1

            # Либо человек замолчал, либо говорит слишком долго — режем.
            too_long = len(speech) >= self.max_speech_frames
            if too_long:
                # Раньше такой кусок выбрасывался целиком — считалось, что
                # столько подряд длится только шум. В живой квартире это
                # оказалось неверно: люди разговаривают непрерывно, паузы в
                # полсекунды не случается по двадцать секунд кряду, и вместе с
                # чужим разговором выбрасывалось обращение к роботу, если оно
                # прозвучало внутри. Человек звал — робот молчал.
                #
                # Теперь кусок уходит в разбор, но помечается: это срез
                # комнаты, а не реплика. Решать, по карману ли его разбирать,
                # будет верх — у него одного есть право знать, ПК сейчас
                # распознаёт или сам робот.
                log.info("аудио: %d с без паузы — режу и отдаю как есть",
                         self.max_speech_frames * FRAME_MS // 1000)
                payload, speech = speech, []
                voiced_total = silence = voiced_run = 0
                talking = False
                self.preroll.clear()
                self.long_chunk = True
                yield to_wav(np.concatenate(payload), self.sample_rate)
                continue

            if silence >= self.silence_frames:
                talking = False
                voiced_run = 0
                payload, speech = speech, []
                voiced, voiced_total = voiced_total, 0
                self.preroll.clear()
                if voiced >= self.min_speech_frames:
                    self.long_chunk = False
                    yield to_wav(np.concatenate(payload), self.sample_rate)
                else:
                    log.debug("аудио: слишком короткий фрагмент (%d кадров речи), "
                              "пропускаю", voiced)


def to_wav(samples: np.ndarray, sample_rate: int) -> bytes:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sample_rate)
        w.writeframes(samples.tobytes())
    return buf.getvalue()
