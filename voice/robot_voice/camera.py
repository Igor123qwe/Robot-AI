"""Глаза робота: взять кадр и понять, что на нём.

Кадр робот у себя не добывает. Камерой владеет веб-сервер (web/camera.py), и
на то есть причина: устройство /dev/video* захватывается монопольно, а
желающих двое — пульт и голос. Поэтому здесь обычный запрос к соседнему порту,
без единой строчки про ffmpeg и v4l2.

Смотрит за робота не он сам. На плате нет ничего, что разглядело бы комнату:
BPU занят, а зрячая модель — это гигабайты. Значит кадр едет туда же, куда
едут речь и разговор, — на домашний ПК, и только туда: робот работает в паре
с ПК (решение хозяина, октябрь 2026). ПК не разглядел — робот молчит, без
облака и без объявлений.

Отдельная ручка /see на ПК нужна не из любви к симметрии. Мост переводит
переписку в Ollama и разбирает только текст и вызовы инструментов: картинка,
вложенная в обычный запрос, вылетала бы молча, без единой ошибки, — а модель,
не увидев ничего, уверенно рассказала бы, что перед роботом. Врать с полной
убеждённостью хуже, чем честно молчать, поэтому зрение ходит своей дорогой.
"""

from __future__ import annotations

import base64
import logging
import os
import urllib.error
import urllib.request

log = logging.getLogger(__name__)

# Сколько ждать кадр от своего же веб-сервера. Он рядом, через локальную
# петлю, но камеру ему может понадобиться разбудить: ffmpeg стартует, UVC
# договаривается о формате, автоэкспозиция подбирает выдержку.
КАДР_ЖДЁМ = 8.0

# Сколько ждать ответа от того, кто смотрит. Всё это время робот молчит с
# заглушённым микрофоном, поэтому предел жёсткий: лучше честное «не успел»,
# чем полминуты немоты, в которую человек успевает спросить трижды.
ОТВЕТ_ЖДЁМ = 20.0

ВОПРОС_ПО_УМОЛЧАНИЮ = (
    "Ты — глаза домашнего робота. Опиши коротко и по-русски, что перед тобой: "
    "люди, предметы, обстановка. Две-три фразы, без предисловий. "
    "Не выдумывай того, чего не видно."
)

# Заданный вопрос обрамляем, а не шлём голым. Зрячая модель — чужая, про
# робота она ничего не знает: без этого «сколько пальцев» она может ответить
# по-английски, развёрнутым абзацем или рассуждением о том, чьи это пальцы.
# Ответ идёт человеку ДОСЛОВНО, пересказывать его некому, поэтому он обязан
# быть сразу пригодным для произнесения вслух.
ОБРАМЛЕНИЕ = (
    "Ты — глаза домашнего робота, камера смотрит вперёд. Глядя на картинку, "
    "ответь коротко и по-русски на вопрос человека — одной-двумя фразами, без "
    "предисловий. Не выдумывай того, чего не видно.\n\nВопрос: {}"
)


# Куда в кадре смотрит сетка дальномера. Файл общий с веб-сервером, он же его
# и пишет: сводит поля зрения человек глазами в пульте, потому что
# калибровочной доски у нас нет, а точность до пикселя тут и не нужна — зона
# дальномера это конус шириной с ладонь на метре.
# Имя файла держать в согласии с web/server.py (ФАЙЛ_ПРИЦЕЛА).
ФАЙЛ_ПРИЦЕЛА = "tof_aim.json"
ПРИЦЕЛ_ПО_УМОЛЧАНИЮ = {"x": 0.5, "y": 0.5, "ш": 0.538, "в": 0.862,
                       "зеркало": False, "вверхногами": False,
                       "поперёк": False}


def прицел() -> dict:
    """Доли кадра, которые накрывает сетка: центр и размер."""
    try:
        import json
        from pathlib import Path

        данные = json.loads((Path.home() / ".robot-ai" / ФАЙЛ_ПРИЦЕЛА).read_text())
        готово = {к: float(данные[к]) for к in ("x", "y", "ш", "в")}
        готово["зеркало"] = bool(данные.get("зеркало"))
        готово["вверхногами"] = bool(данные.get("вверхногами"))
        готово["поперёк"] = bool(данные.get("поперёк"))
    except Exception:                     # noqa: BLE001 — нет файла, кривой файл
        return dict(ПРИЦЕЛ_ПО_УМОЛЧАНИЮ)
    if all(0.0 <= float(готово[к]) <= 1.0 for к in ("x", "y", "ш", "в")):
        return готово
    return dict(ПРИЦЕЛ_ПО_УМОЛЧАНИЮ)


def подсказка_дальномера(сетка: list[list[float]], где: dict | None = None) -> str:
    """Расстояния словами — для зрячей модели. Пусто, если мерить нечего.

    Зачем это нужно. Модель по одной картинке видит, что стул ближе стены, но
    метров не знает и знать не может: масштаба у одного глаза нет. Спросишь
    «далеко ли стул» — ответит уверенно и наугад. А дальномер метры знает, но
    не знает, что перед ним стул.

    Сложить их можно двумя способами. Тяжёлый — обучить сеть, которая сольёт
    плотную картинку с редкими опорными точками (depth completion). Лёгкий —
    просто СКАЗАТЬ модели, в каких местах кадра сколько метров, и пусть она
    сама соотнесёт числа с тем, что видит. Второй способ не требует ни
    обучения, ни видеокарты на роботе, и на вопрос «сколько до стула»
    отвечает не хуже.

    Отдельно говорим, какую часть кадра сетка накрывает: у камеры 130
    градусов, у дальномера 60, то есть числа есть только про середину. Без
    этой оговорки модель приписывает расстояние предметам с краю — тем
    увереннее, чем меньше знает.
    """
    живые = [м for ряд in сетка for м in ряд if м > 0]
    if len(живые) < 4:
        return ""
    где = где or прицел()
    слева = max(0.0, где["x"] - где["ш"] / 2) * 100
    справа = min(1.0, где["x"] + где["ш"] / 2) * 100
    сверху = max(0.0, где["y"] - где["в"] / 2) * 100
    снизу = min(1.0, где["y"] + где["в"] / 2) * 100
    строки = "\n".join(
        "  " + " ".join("  -  " if м <= 0 else f"{м:5.2f}" for м in ряд)
        for ряд in сетка)
    return (
        "\n\nДАЛЬНОМЕР. У робота есть лазерный дальномер: он меряет расстояние "
        "в 64 точках, разложенных сеткой восемь на восемь. На этой картинке "
        f"сетка накрывает область от {слева:.0f}% до {справа:.0f}% по ширине "
        f"и от {сверху:.0f}% до {снизу:.0f}% по высоте, считая от левого "
        "верхнего угла. Восемь строк по восемь чисел, сверху вниз и слева "
        "направо, в метрах; прочерк — не измерено.\n"
        f"{строки}\n"
        "Пользуйся этим, когда спрашивают про расстояние: называй его для "
        "предметов, попавших в эту область. Числа не перечисляй — скажи "
        "по-человечески. Про предметы вне области расстояние не выдумывай: "
        "скажи, что не мерил.")


class Глаза:
    """Кадр с камеры робота плюс тот, кто его разглядит."""

    def __init__(self, web_url: str = "", pc_url: str = "", tof=None) -> None:
        порт = os.environ.get("ROBOT_WEB_PORT", "8000")
        self.web_url = (web_url or f"http://127.0.0.1:{порт}").rstrip("/")
        self.pc_url = pc_url.rstrip("/")
        # Дальномер. Он даёт зрению то, чего у одного глаза нет и взяться ему
        # неоткуда: настоящие метры.
        self.tof = tof
        # Зрячей модели на ПК может не быть вовсе. Ходить к нему за каждым
        # взглядом, зная, что он откажет, — это секунда немоты на ровном
        # месте, и человек её слышит.
        self._пк_без_зрения = False

    # --- кадр -----------------------------------------------------------
    def снимок(self) -> bytes:
        """Один кадр с камеры робота. Пусто — значит не вышло."""
        try:
            with urllib.request.urlopen(self.web_url + "/camera/snapshot",
                                        timeout=КАДР_ЖДЁМ) as ответ:
                тип = ответ.headers.get("Content-Type", "")
                тело = ответ.read()
        except (urllib.error.URLError, OSError) as e:
            log.warning("камера: не забрал кадр (%s)", e)
            return b""
        if not тип.startswith("image/"):
            # Сервер отвечает отказом в JSON — там и написано, что случилось.
            log.warning("камера: вместо кадра пришло %s (%s)",
                        тип or "непонятно что", тело[:200].decode("utf-8", "replace"))
            return b""
        return тело

    # --- взгляд ---------------------------------------------------------
    def посмотреть(self, вопрос: str = "") -> str:
        """Что перед роботом, словами. Готовый текст для человека."""
        кадр = self.снимок()
        if not кадр:
            return ("Не вижу: камера не отдала кадр. "
                    "Загляни в журнал робота, там причина.")
        вопрос = (вопрос or "").strip()
        вопрос = ОБРАМЛЕНИЕ.format(вопрос) if вопрос else ВОПРОС_ПО_УМОЛЧАНИЮ
        вопрос += self._про_расстояния()

        if self.pc_url and not self._пк_без_зрения:
            текст = self._спросить_пк(кадр, вопрос)
            if текст:
                return текст
        # ПК не разглядел — молчим. Придумывать нельзя (ради этого зрение и
        # ходит отдельной дорогой), а объявлять, что ПК пропал, — не нужно:
        # робот работает только в паре с ним.
        return ""

    def _про_расстояния(self) -> str:
        """Что добавить к вопросу от дальномера. Пусто — добавлять нечего."""
        if self.tof is None:
            return ""
        try:
            взгляд = self.tof.взгляд()
            if not взгляд.свежий:
                return ""
            return подсказка_дальномера(взгляд.сетка)
        except Exception:                 # noqa: BLE001 — зрение важнее
            log.exception("не смог приложить расстояния к взгляду")
            return ""

    def _спросить_пк(self, кадр: bytes, вопрос: str) -> str:
        import requests

        try:
            ответ = requests.post(
                self.pc_url + "/see",
                json={"вопрос": вопрос,
                      "кадр": base64.b64encode(кадр).decode("ascii")},
                timeout=ОТВЕТ_ЖДЁМ,
            )
        except Exception as e:                  # noqa: BLE001 — сон ПК не беда
            log.info("зрение: ПК не ответил (%s)", e)
            return ""
        if ответ.status_code != 200:
            # Отдельно и громко: «нет зрячей модели» человек иначе не узнает
            # никогда, а починка — одна команда на ПК.
            log.warning("зрение: ПК отказал (%s) %s",
                        ответ.status_code, ответ.text[:200])
            # Отсутствие модели — это не сбой связи, а положение дел: до
            # перезапуска оно не изменится. Спрашивать снова каждый раз
            # значит дарить человеку секунду тишины за уже известный ответ.
            # Прочие отказы (перегружен, оборвалось) запоминать нельзя — они
            # проходят сами, и робот остался бы без домашнего зрения зря.
            if ответ.status_code == 502 and "не ответила" in ответ.text:
                self._пк_без_зрения = True
                log.warning("зрение: на ПК зрячей модели нет — больше не "
                            "спрашиваю до перезапуска")
            return ""
        return (ответ.json().get("текст") or "").strip()

