"""Глаза робота: взять кадр и понять, что на нём.

Кадр робот у себя не добывает. Камерой владеет веб-сервер (web/camera.py), и
на то есть причина: устройство /dev/video* захватывается монопольно, а
желающих двое — пульт и голос. Поэтому здесь обычный запрос к соседнему порту,
без единой строчки про ffmpeg и v4l2.

Смотрит за робота не он сам. На плате нет ничего, что разглядело бы комнату:
BPU занят, а зрячая модель — это гигабайты. Значит кадр едет туда же, куда
едут речь и разговор: на домашний ПК, а если тот спит — в облако. Порядок тот
же, что у мозга и распознавания, и по той же причине: дома даром и быстро,
облако — чтобы робот не слеп, пока компьютер выключен.

Отдельная ручка /see на ПК нужна не из любви к симметрии. Мост переводит
переписку в Ollama и разбирает только текст и вызовы инструментов: картинка,
вложенная в обычный запрос, вылетала бы молча, без единой ошибки, — а модель,
не увидев ничего, уверенно рассказала бы, что перед роботом. Врать с полной
убеждённостью хуже, чем честно молчать, поэтому зрение ходит своей дорогой.
"""

from __future__ import annotations

import base64
import logging
import os
import urllib.error
import urllib.request

log = logging.getLogger(__name__)

# Сколько ждать кадр от своего же веб-сервера. Он рядом, через локальную
# петлю, но камеру ему может понадобиться разбудить: ffmpeg стартует, UVC
# договаривается о формате, автоэкспозиция подбирает выдержку.
КАДР_ЖДЁМ = 8.0

# Сколько ждать ответа от того, кто смотрит. Всё это время робот молчит с
# заглушённым микрофоном, поэтому предел жёсткий: лучше честное «не успел»,
# чем полминуты немоты, в которую человек успевает спросить трижды.
ОТВЕТ_ЖДЁМ = 20.0

ВОПРОС_ПО_УМОЛЧАНИЮ = (
    "Ты — глаза домашнего робота. Опиши коротко и по-русски, что перед тобой: "
    "люди, предметы, обстановка. Две-три фразы, без предисловий. "
    "Не выдумывай того, чего не видно."
)


class Глаза:
    """Кадр с камеры робота плюс тот, кто его разглядит."""

    def __init__(self, web_url: str = "", pc_url: str = "",
                 api_key: str = "", api_base: str = "", model: str = "",
                 vision_model: str = "", учёт=None) -> None:
        порт = os.environ.get("ROBOT_WEB_PORT", "8000")
        self.web_url = (web_url or f"http://127.0.0.1:{порт}").rstrip("/")
        self.pc_url = pc_url.rstrip("/")
        self.api_key = api_key
        self.api_base = api_base
        self.model = model
        # Смотрит младшая и быстрая; старшая — только если младшей нет.
        self.vision_model = vision_model or model
        # Куда сообщить, во что обошёлся взгляд. Кадр стоит примерно как
        # полторы тысячи слов, и без этого он не попадал ни в один счётчик:
        # расход за сеанс не двигался, хотя деньги тратились.
        self.учёт = учёт
        # Пускать ли картинку в облако, когда ПК не отвечает. По умолчанию да:
        # робот, ослепший вместе с выключенным компьютером, — это не то, чего
        # ждёшь от «посмотри». Но кадр стоит примерно как полторы тысячи
        # слов, и тот, кому это дорого, выключает одной настройкой.
        self.в_облако = os.environ.get("ROBOT_VISION_CLOUD", "1") != "0"

    # --- кадр -----------------------------------------------------------
    def снимок(self) -> bytes:
        """Один кадр с камеры робота. Пусто — значит не вышло."""
        try:
            with urllib.request.urlopen(self.web_url + "/camera/snapshot",
                                        timeout=КАДР_ЖДЁМ) as ответ:
                тип = ответ.headers.get("Content-Type", "")
                тело = ответ.read()
        except (urllib.error.URLError, OSError) as e:
            log.warning("камера: не забрал кадр (%s)", e)
            return b""
        if not тип.startswith("image/"):
            # Сервер отвечает отказом в JSON — там и написано, что случилось.
            log.warning("камера: вместо кадра пришло %s (%s)",
                        тип or "непонятно что", тело[:200].decode("utf-8", "replace"))
            return b""
        return тело

    # --- взгляд ---------------------------------------------------------
    def посмотреть(self, вопрос: str = "") -> str:
        """Что перед роботом, словами. Готовый текст для человека."""
        кадр = self.снимок()
        if not кадр:
            return ("Не вижу: камера не отдала кадр. "
                    "Загляни в журнал робота, там причина.")
        вопрос = (вопрос or "").strip() or ВОПРОС_ПО_УМОЛЧАНИЮ

        if self.pc_url:
            текст = self._спросить_пк(кадр, вопрос)
            if текст:
                return текст
        if self.в_облако and self.api_key:
            текст = self._спросить_облако(кадр, вопрос)
            if текст:
                return текст
        # Молчать нельзя: человек спросил и ждёт. Но и придумывать нельзя —
        # это ровно тот случай, ради которого зрение ходит отдельной дорогой.
        if not self.pc_url and not self.api_key:
            return "Посмотреть некому: ни компьютер, ни облако не настроены."
        return ("Кадр есть, а разглядеть его некому: компьютер не ответил"
                + (", в облако не пускают." if not self.в_облако else "."))

    def _спросить_пк(self, кадр: bytes, вопрос: str) -> str:
        import requests

        try:
            ответ = requests.post(
                self.pc_url + "/see",
                json={"вопрос": вопрос,
                      "кадр": base64.b64encode(кадр).decode("ascii")},
                timeout=ОТВЕТ_ЖДЁМ,
            )
        except Exception as e:                  # noqa: BLE001 — сон ПК не беда
            log.info("зрение: ПК не ответил (%s)", e)
            return ""
        if ответ.status_code != 200:
            # Отдельно и громко: «нет зрячей модели» человек иначе не узнает
            # никогда, а починка — одна команда на ПК.
            log.warning("зрение: ПК отказал (%s) %s",
                        ответ.status_code, ответ.text[:200])
            return ""
        return (ответ.json().get("текст") or "").strip()

    def _спросить_облако(self, кадр: bytes, вопрос: str) -> str:
        текст = self._облаком(кадр, вопрос, self.vision_model)
        if текст or self.vision_model == self.model:
            return текст
        # Младшей модели может не быть у этого ключа. Молчать об этом нельзя:
        # человек спросил и ждёт, а починка — одна строчка в настройках.
        log.warning("зрение: %s не ответила — смотрю моделью разговора (%s)",
                    self.vision_model, self.model)
        return self._облаком(кадр, вопрос, self.model)

    def _облаком(self, кадр: bytes, вопрос: str, модель: str) -> str:
        try:
            import anthropic

            клиент = anthropic.Anthropic(api_key=self.api_key,
                                         base_url=self.api_base or None,
                                         timeout=ОТВЕТ_ЖДЁМ)
            ответ = клиент.messages.create(
                model=модель,
                max_tokens=300,
                messages=[{
                    "role": "user",
                    "content": [
                        {"type": "image",
                         "source": {"type": "base64", "media_type": "image/jpeg",
                                    "data": base64.b64encode(кадр).decode("ascii")}},
                        {"type": "text", "text": вопрос},
                    ],
                }],
            )
        except Exception as e:                  # noqa: BLE001
            log.warning("зрение: облако отказало (%s)", e)
            return ""
        if self.учёт is not None:
            расход = getattr(ответ, "usage", None)
            try:
                self.учёт(модель, getattr(расход, "input_tokens", 0) or 0,
                          getattr(расход, "output_tokens", 0) or 0)
            except Exception:               # noqa: BLE001 — счёт не повод молчать
                log.exception("не смог записать расход на взгляд")
        куски = [блок.text for блок in ответ.content
                 if getattr(блок, "type", "") == "text"]
        return "".join(куски).strip()
