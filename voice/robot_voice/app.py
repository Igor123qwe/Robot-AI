def уверенно_расслышали(sure: float | None) -> bool:
    """Достаточно ли уверенно распознана фраза, чтобы по ней ЕХАТЬ.

    Отдельной функцией, а не строкой в цикле, потому что проверить строку в
    середине `_listen_loop` нечем — и это выяснилось мутацией: заменил
    вычисление на `True`, и ни одна из двух тысяч проверок не заметила.
    Сторож в tools при этом проверен хорошо — но он читает то, что сюда
    записали, и если сюда всегда писать «уверенно», сторож становится
    украшением.

    Живая беда, ради которой признак заведён: whisper услышал «Кузяка идла»,
    модель домыслила из этого «влево», и робот поехал. Имя совпало — одного
    имени не хватило.

    `None` значит «распознаватель уверенности не сообщает», и это не повод
    отказывать: так работают все пути, кроме основного.
    """
    return sure is None or sure >= UNSURE_BELOW


def окно_держит_комната(имя_слышно: bool, окно_открыто: bool,
                        было: int) -> tuple[int, bool]:
    """Считает ответы без обращения. Возвращает (стало, пора ли закрыть окно).

    Окно продлевалось на каждой обработанной фразе, включая пришедшую БЕЗ
    имени. Комната говорит чаще, чем окно закрывается, — значит оно держит
    само себя и не закрывается никогда. См. ОТВЕТОВ_БЕЗ_ИМЕНИ.

    Считаем только пока окно открыто: вне окна фразы и так уходят в «не мне»,
    и накручивать на них счётчик значило бы закрыть окно ещё до того, как оно
    откроется.
    """
    if имя_слышно:
        return 0, False
    if not окно_открыто:
        return было, False
    стало = было + 1
    return стало, стало > ОТВЕТОВ_БЕЗ_ИМЕНИ


def зовут_другого(фраза: str) -> bool:
    """Обращаются по имени, и имя не робота.

    «Виктор, как дела у тебя» и «Иди уже, Рома» — живые строки из журнала, на
    которые робот вступал в чужой разговор. Проверять надо только в открытом
    окне: там имя не требуется, и любое обращение звучит как обращение к нему.

    Список _NOT_A_NAME отсекает слова, которыми фразу НАЧИНАЮТ, а не зовут:
    без него «Ладно, поедем» считалось бы обращением к некоему Ладно.
    """
    зовут = _VOCATIVE.match(фраза or "")
    return bool(зовут) and _clean_token(зовут.group(1)) not in _NOT_A_NAME


def зовут_помощника(фраза: str) -> bool:
    """Фраза начата с имени другого помощника: «Алиса, включи свет»."""
    слова = (фраза or "").split()
    return bool(слова) and _clean_token(слова[0]) in ЧУЖИЕ_ПОМОЩНИКИ


def детектор_ошибся(text: str, имя_в_тексте: bool, голос_знаком: bool = True) -> bool:
    """Детектор на потоке услышал имя, а расшифровка говорит иное.

    Имя в расшифровке снимает вопрос: два свидетеля сошлись. Без имени —
    три признака, каждого достаточно: фраза обращена к другому помощнику;
    она длинна (ДЕТЕКТОР_ВРЁТ_ОТ_СЛОВ); голос НЕЗНАКОМ.

    Про незнакомый голос — по журналу за три с половиной часа с музыкой и
    телевизором рядом, уже с длинным предбуфером. Настоящих обращений
    четыре, и во всех четырёх имя в расшифровке есть. Без имени пришло
    одиннадцать фраз — «Не прибрался», «Chickson», «Да», обрывки песен, — и
    ни одна не была обращением, а «Не прибрался» робот ещё и исполнил:
    «поеду и посмотрю, где что стоит». Все одиннадцать — голос, которого
    робот не знает. Домашних он знает по голосу, и им послабление остаётся:
    детектор услышал имя, расшифровка проглотила — верим детектору. Чужой
    голос, который хочет внимания робота, назовёт его по имени, и теперь имя
    попадает в запись целиком.
    """
    if имя_в_тексте:
        return False
    return (зовут_помощника(text) or len(text.split()) >= ДЕТЕКТОР_ВРЁТ_ОТ_СЛОВ
            or not голос_знаком)


def _канон(cfg) -> tuple[str, ...]:
    """Настоящие имена робота — те, с которыми можно сравнивать нестрого.

    Отбрасываем всё, чего нет в самом списке имён: настройки правят порознь, и
    канон, разошедшийся со списком, сделал бы робота глухим молча. Не осталось
    ничего — отдаём пустоту, а она значит «сравнивай со всем списком», как
    было до этой правки. Оглохнуть от невнимательности робот не должен.
    """
    свои = tuple(и for и in getattr(cfg, "wake_canon", ()) if и in cfg.wake_words)
    return свои


def _strip_wake_word(text: str, wake_words: tuple[str, ...],
                     ratio: float = 0.8, anywhere: bool = False,
                     канон: tuple[str, ...] = ()) -> str | None:
    """Возвращает текст без имени, либо None, если робота не звали.

    Имя ищется не только в начале: «Кузя, вперёд» и «а ну-ка Кузя вперёд»
    одинаково законны. Дальше первых трёх слов не смотрим — иначе случайное
    упоминание в середине разговора будет принято за обращение.

    anywhere меняет правило и включается только для куска, нарезанного по
    длине, а не по паузе. Такой кусок — это двадцать секунд комнаты, где
    обращение может стоять на четырнадцатой секунде и оказаться сороковым
    словом. Правило трёх слов писалось для реплик и здесь просто не работает:
    человек звал, а робот молчал.

    Берётся ПОСЛЕДНЕЕ вхождение и всё, что после него. Прозвучало имя дважды —
    обращение то, что свежее; а слова до него принадлежат чужому разговору, и
    тащить их в команду нельзя.
    """
    if not wake_words:
        return text

    # По предложениям и с конца. Первых трёх слов КУСКА не хватало: в живой
    # комнате в одно распознавание слипается по два-три предложения, и
    # «Сойдите, пожалуйста, с кровати, Арина. Кузя, привет.» уходило в «не
    # мне» — имя оказалось шестым словом. Внутри предложения правило трёх слов
    # остаётся: оно и отделяет обращение от случайного упоминания.
    #
    # С конца — потому что человек часто зовёт несколько раз подряд, не
    # дождавшись ответа: «Кузя, сделай звук на пять. Кузя, включи музыку.»
    # Свежее обращение и есть настоящее, а первое робот уже проспал.
    предложения = _SENTENCE.split(text)
    for н in range(len(предложения) - 1, -1, -1):
        tokens = предложения[н].split()
        for i, token in enumerate(tokens[:3]):
            if _sounds_like_wake(_clean_token(token), wake_words, ratio, канон):
                rest = tokens[:i] + tokens[i + 1:]
                # Слова перед именем — обращение («эй», «слушай»), а не команда.
                if all(_clean_token(t) in _FILLERS for t in tokens[:i]):
                    rest = tokens[i + 1:]
                команда = " ".join(rest).strip(" ,.!?…—-")
                # ВСЁ, ЧТО СКАЗАНО ПОСЛЕ, — ТОЖЕ КОМАНДА, а не чужой разговор.
                #
                # Здесь бралось только предложение с именем, а хвост
                # выбрасывался, и это стоило живой команды:
                #
                #   услышано: «Кузя, поехали. Иди за мной.»
                #   ушло в разбор: «поехали»
                #
                # Правило «иду за тобой» ждало ровно «иди за мной» и не
                # сработало; «поехали» правилами не разобралось, ушло к
                # модели, та ответила текстом вместо инструмента — и робот
                # сказал «Не понял, куда ехать» через десять с половиной
                # секунд. Со второй попытки, когда Игорь сказал то же самое
                # одним предложением, правило сработало за 1.1 с.
                #
                # Голое «Кузя!» отдельным предложением лечилось этим же
                # приёмом и раньше — просто в отдельной ветке. Двух правил для
                # одного вопроса быть не должно: хвост принадлежит обращению
                # независимо от того, осталось ли что-то в самом предложении с
                # именем.
                хвост = " ".join(предложения[н + 1:]).strip(" ,.!?…—-")
                if хвост:
                    команда = f"{команда}. {хвост}".strip(" ,.!?…—-") \
                        if команда else хвост
                return команда

    # Срез комнаты: двадцать секунд без пауз, распознавание точек не
    # расставило, и предложений тут может не быть вовсе. Тогда ищем имя где
    # угодно — терять обращение из-за отсутствующей точки глупо.
    if anywhere:
        tokens = text.split()
        for i in range(len(tokens) - 1, -1, -1):
            if _sounds_like_wake(_clean_token(tokens[i]), wake_words, ratio,
                                 канон):
                return " ".join(tokens[i + 1:]).strip(" ,.!?…—-")
    return None


def _вернуть_музыку(player) -> None:
    """Снять приглушение, когда ход кончился, не начавшись.

    Музыку приглушает сам детектор имени, ещё до распознавания, — иначе
    человеку пришлось бы перекрикивать песню. Но ход умеет обрываться сразу
    после этого: имя послышалось в самой музыке, распознавание вернуло пустоту.
    Без явного возврата громкость ждала бы страховки по времени, и музыка сама
    по себе гуляла бы то тише, то громче.
    """
    if player is not None:
        player.приглушить(False)


def _без_обращения(text: str) -> str:
    """Убрать искажённое имя из начала команды.

    Зовётся только когда имя услышано ЗВУКОМ, а в расшифровке не нашлось.
    Запись начинается на самом имени, значит первое слово — это оно и есть,
    просто распознавание написало его неузнаваемо. С живого робота: «Кузя,
    включи музыку» приехало как «Друзья, включи музыку» — робот проснулся
    правильно, но правило про музыку из-за лишнего слова не сработало, фраза
    ушла модели, и та ответила «Включаю музыку на твой вкус», не позвав ни
    одного инструмента. Музыка не заиграла, а человек услышал, что заиграла.

    Признак — запятая: обращение от команды отделяют именно ею. Без запятой не
    трогаем, иначе «вперёд на метр» осталось бы без «вперёд».
    """
    слова = text.strip().split()
    if len(слова) > 1 and слова[0].endswith(","):
        return " ".join(слова[1:]).strip(" ,.!?…—-")
    return text.strip()


def _is_looped(text: str) -> bool:
    """Зациклился ли Whisper: «сантиметров, сантиметров, сантиметров…».

    Живая речь так не выглядит: даже «да да да» — это три слова, а не сорок.
    Страховка на случай, если параметры против повторов не сработают.
    """
    words = re.findall(r"\w+", text.lower())
    if len(words) < 8:
        return False
    top = max(collections.Counter(words).values())
    return top / len(words) > 0.4


def _is_junk(text: str) -> bool:
    stripped = text.strip()
    if _JUNK.match(stripped) or not re.search(r"[а-яa-z]", stripped, re.I):
        return True
    if _is_looped(stripped):
        log.info("whisper зациклился, отбрасываю")
        return True
    # Титры переводчиков осмысленны по форме, но появляются только на тишине.
    return bool(_HALLUCINATION.search(stripped)) and len(stripped) < 120


class Watchdog:
    """Присматривает за тем, о чём человек узнаёт последним.

    Заряд: полоску в пульте видно, только если пульт открыт и на него смотрят.
    Робот ездит по квартире, а садится всегда не вовремя, поэтому о разряде он
    сообщает голосом — но ровно по одному разу на порог, иначе это нытьё.

    Микрофон: если телефон уснул или Wi-Fi моргнул, робот молчит, и снаружи
    это неотличимо от «обиделся». Состояние уходит в пульт строкой.

    Про ПК сторож НЕ говорит ничего: робот работает только в паре с ним, и
    пропавший ПК — это просто тишина, а не новость вслух (раньше сторож здесь
    объявлял, что ПК пропал и робот справляется своими силами).
    """

    LEVELS = ((11.1, "Батарея меньше половины."),
              (10.8, "Батарея садится, пора на зарядку."),
              (CUTOFF_VOLT, "Батарея почти пустая, ехать я больше не буду."))

    def __init__(self, ros, voice: Voice, listener: Listener,
                 period: float = 30.0) -> None:
        self.ros = ros
        self.voice = voice
        self.listener = listener
        self.period = period
        self._said: set[float] = set()
        self._mic_was: bool | None = None
        self._stop = threading.Event()

    def start(self) -> None:
        threading.Thread(target=self._run, daemon=True).start()

    def stop(self) -> None:
        self._stop.set()

    def _run(self) -> None:
        while not self._stop.wait(self.period):
            try:
                self._battery()
                self._mic()
            except Exception:
                log.exception("наблюдатель споткнулся")

    def _battery(self) -> None:
        volt = self.ros.voltage
        if volt is None:
            return
        # Зарядили — снова можно предупреждать.
        self._said = {v for v in self._said if volt <= v}
        for level, phrase in self.LEVELS:
            if volt <= level and level not in self._said:
                # Порог считаем сказанным, только если его УСЛЫШАЛИ: без ПК
                # робот молчит, и предупреждение прозвучит, когда ПК вернётся,
                # а не пропадёт насовсем.
                # Повторяем только «говорить было нечем» (−1, ПК нет). «Никто
                # не слушал» (0, вкладка пульта закрыта) — сказано: иначе
                # предупреждение синтезировалось бы каждые полминуты, глуша
                # микрофон, пока не зарядят.
                if self.voice.say(phrase) >= 0:
                    self._said.add(level)
                    log.info("батарея %.1f В — предупредил", volt)
                break

    def _mic(self) -> None:
        online = self.listener.pump.alive
        if online == self._mic_was:
            return
        self._mic_was = online
        log.info("микрофон %s", "на связи" if online else "не отвечает")
        self.voice.status("микрофон на связи" if online
                          else "микрофон не отвечает — проверь телефон")


def _post_heard(speak_endpoint: str, kind: str, text: str) -> None:
    """Показать в пульте, что робот расслышал. Ошибку глушим: это подсказка."""
    req = urllib.request.Request(
        f"{speak_endpoint}/{kind}", data=text.encode(), method="POST",
        headers={"Content-Type": "text/plain; charset=utf-8"})
    try:
        urllib.request.urlopen(req, timeout=3).close()
    except (urllib.error.URLError, OSError):
        pass


def _собрать_проигрыватель(cfg, state, listener) -> Player:
    """Проигрыватель один на радио и на Яндекс — и он есть ВСЕГДА.

    «Выключи музыку» и «сделай тише» человек говорит одинаково, что бы под
    ними ни играло, поэтому проигрыватель один.

    Раньше он собирался только при audio_out == "browser", и это условие
    путало две разные вещи: куда идёт ГОЛОС робота и где играет МУЗЫКА. Музыка
    играет в пульте, а пульт — отдельная служба robot-web, она работает
    независимо от голоса. Стоило перевести голос на свой динамик — и вместе с
    ним пропадали все инструменты музыки: на «включи музыку» робот отвечал «у
    меня нет такой функции», имея под рукой работающее радио, а правило
    громкости звало инструмент, которого нет, — робот говорил «громкость
    уменьшена», не изменив ничего. Вслух это неотличимо от исправной работы.

    Функция отдельная не для красоты: условие жило в середине main(), где его
    нельзя проверить, и потому оно спокойно прожило до живого робота.
    """
    # Про Яндекс говорим честно и сразу: без библиотеки токен бесполезен, а
    # узнавать об этом в момент «Кузя, включи Грота» — потерянный вечер.
    музыка = None
    if cfg.yandex_token and not Music.installed():
        log.warning("токен Яндекса есть, а библиотеки нет — играет только "
                    "радио. Поставь: pip3 install --user yandex-music")
    elif cfg.yandex_token:
        музыка = Music(cfg.yandex_token)
    # Куда играть. Пока голос шёл во вкладку, музыка там же и играла — это
    # было естественно. С колонкой на роботе вкладка становится лишним звеном:
    # робот честно ставит песню, рапортует «включаю» — и человек не слышит
    # ничего, потому что вкладка закрыта. Ровно так и вышло на живом роботе.
    куда = Pult(cfg.web_endpoint.rsplit("/", 1)[0])
    где = "в пульте"
    if cfg.audio_out == "local":
        игрок = Колонка.живой()
        if игрок:
            # Музыке можно свою карту. ReSpeaker Lite умеет ровно 16 кГц: речи
            # хватает, а музыке это потолок в восемь килогерц по полосе —
            # телефонное качество, которое не лечится ни усилителем, ни
            # пересчётом частоты.
            карта = cfg.music_device or cfg.spk_device
            куда = Колонка(карта, игрок=игрок)
            где = f"в колонку робота через {игрок}"
            if cfg.music_device and cfg.music_device != cfg.spk_device:
                где += f", карта {cfg.music_device}"
        else:
            где = ("в пульте — в колонку играть нечем. Поставить: "
                   "sudo apt install ffmpeg (или mpg123)")
    log.info("музыка: %s, %s",
             "Яндекс и радио" if музыка is not None
             else "интернет-радио (Яндекс не подключён)", где)
    return Player(
        куда, музыка,
        громкость=float(state.get("громкость музыки", MUSIC_LOUD)),
        on_volume=lambda доля: state.set("громкость музыки", доля),
        # Под музыку детектор речи глохнет: ровный фон он принимает за речь и
        # режет паузы на куски, а куски возвращаются пустыми. Поэтому
        # проигрыватель сообщает микрофону, что стало шумно.
        on_playing=listener.background)


