_СТОП_С_ПРИЧИНОЙ = re.compile(r"^\s*(?:Стою|Не поеду)\s*:\s*(.+?)\s*(?:[.!…]|$)")


def _причина_стопа(text: str) -> str:
    """Из «Стою: причина.» — «причина»; из любой другой реплики — пусто."""
    m = _СТОП_С_ПРИЧИНОЙ.match(text or "")
    return m.group(1) if m else ""


def _объявить(voice: Voice, text: str, **kw) -> int:
    """Объявление колёс — вслух и лицу.

    Лицо умеет «встревожен(причина)» и рисует «стою: причина» вместо глаз —
    и до сих пор этого не звал никто: сторож пути живёт в ros.py, а тот про
    экран не знает и знать не должен. Единственное, что сторож делает
    наружу, — объявляет причину вслух через ros.объявить. Вот на этом
    проводе и стоим: реплика вида «Стою: …» — это и есть тревога, и лицо
    узнаёт о ней из тех же слов, что слышит человек. Экран не имеет права
    врать — а тут он и не может: слова одни и те же.

    Снимается тревога в сторож() из main: первый же круг сторожа, на
    котором путь свободен, зовёт лицу «путь_свободен».
    """
    причина = _причина_стопа(text)
    if причина:
        _лицо(voice, "встревожен", причина)
    return voice.say(text, **kw)


class Voice:
    """Речь робота: одна реплика за раз, и микрофон молчит, пока она звучит.

    Микрофон глушится не «на всякий случай»: аппаратного эхоподавления нет,
    робот слышит сам себя и отвечает сам себе — проверено на живом роботе.
    Замок нужен потому, что таймер срабатывает в своём потоке и может
    заговорить посреди ответа: в режиме local это два piper на одну звуковую
    карту, в режиме browser — две реплики в очереди пульта.
    """

    def __init__(self, speaker: Speaker, listener: Listener) -> None:
        self.speaker = speaker
        self.listener = listener
        self._lock = threading.RLock()
        # Куда показать услышанное. Пульт рисует это субтитрами: без экрана и
        # без SSH иначе не понять, расслышал робот или нет.
        self.on_heard: Callable[[str, str], None] | None = None
        # Лицо на экране. None — экрана нет; все обращения через _лицо().
        self.лицо = None
        # Что прозвучало за этот ход — для истории разговора модели (см.
        # _в_историю). Главный цикл чистит список в начале каждого хода.
        self.сказано_за_ход: list[str] = []

    @contextlib.contextmanager
    def quiet(self, говорю: str = ""):
        """Заглушает микрофон на время звучания реплики.

        `говорю` — текст реплики. Он уходит вниз не для журнала: перебивание
        обязано знать, что робот произносит прямо сейчас, иначе робот
        остановит сам себя собственным словом. Рассказ про умения содержит
        «могу остановиться по слову стоп» — без этой проверки он обрывался бы
        на первой же фразе.
        """
        self.listener.mute(говорю)
        try:
            yield
        finally:
            self.listener.unmute()

    @contextlib.contextmanager
    def hold(self):
        """Занимает голос, не трогая микрофон.

        Пока модель думает, робот молчит, и сказанное в этот момент копится в
        буфере звука. Мгновенно он на «стоп» не среагирует — главный цикл в
        это время висит в разговоре с моделью, — но и не потеряет: хвост
        разбирается сразу после ответа, см. _caught_stop.
        """
        with self._lock:
            yield

    def say(self, text: str, *, loud: bool = False, on_sound=None) -> int:
        """Говорит и возвращает, сколько слушателей реально услышали.

        −1 — говорить было нечем: ПК нет, а голос робота — это голос ПК.

        on_sound зовётся в миг, когда пошёл ПЕРВЫЙ звук, а не когда реплика
        отзвучала. Разница между этими моментами — вся длина реплики, и
        секундомер, меряющий второе вместо первого, показывает не задержку, а
        многословность: «Сейчас двадцать три часа двадцать одна минута» давала
        2759 мс «синтеза» при настоящем синтезе в четверть секунды.
        """
        if not text:
            return 0
        может = getattr(self.speaker, "может_говорить", None)
        if может is not None and not может():
            # Голос робота — это голос ПК, а его сейчас нет: робот молчит.
            # Микрофон не глушим и «говорю» на лицо не пишем — звука не
            # будет, а глухота на время несказанной фразы — это пропущенный
            # «стоп». −1 — «говорить было нечем» (не путать с 0, «никто не
            # слушал»): таймер по нему ждёт ПК и прозвонит, когда тот вернётся.
            log.info("робот (молча, ПК нет): %s", text)
            return -1
        with self._lock, self.quiet(text):
            # Лицу — что произносим: строка «говорю» и текст под ней. И
            # обязательно снять по выходу, иначе на экране повиснет реплика,
            # которая давно отзвучала, — а это и есть замершее лицо.
            _лицо(self, "говорю", text)
            try:
                слышали = self.speaker.say(text, loud=loud, on_sound=on_sound)
            finally:
                _лицо(self, "сказал")
        # ПК мог пропасть прямо на этой фразе: до неё голос считался живым, а
        # /tts не ответил. Это тоже «говорить было нечем», а не «никто не
        # слушал»: иначе будильник с выключенным ПК сгорал за три звонка.
        if слышали <= 0 and может is not None and not может():
            return -1
        # Хвост, а не всё подряд: таймеры и сторож говорят и между ходами, и
        # без хода список рос бы сутками. getattr — Voice собирают и в обход
        # __init__ (проверки), и падать из-за журнала реплик незачем.
        сказано = getattr(self, "сказано_за_ход", None)
        if сказано is not None:
            сказано.append(text)
            del сказано[:-16]
        return слышали

    def heard(self, text: str) -> None:
        self._show("heard", text)
        _лицо(self, "услышал", text)

    def status(self, text: str) -> None:
        """Состояние робота, а не реплика человека: рисуется иначе."""
        self._show("status", text)

    def _show(self, kind: str, text: str) -> None:
        if self.on_heard is not None and text:
            try:
                self.on_heard(kind, text)
            except Exception:
                log.debug("не смог показать %s в пульте", kind, exc_info=True)


# Насколько часы могут разойтись, прежде чем это станет бедой. Полминуты —
# сетевая задержка и округление, а вот минута и больше уже сдвигает будильник.
CLOCK_SLACK = 60.0


def _check_clock(cfg) -> None:
    """Сверяет часы робота с часами ПК и кричит, если они разъехались.

    У SBC робота нет батарейки часов: после выключения питания время берётся
    из сети, а если сети в этот момент не было — остаётся каким попало. На
    живом роботе разница с ПК дошла до пяти часов, и «поставь будильник на
    восемнадцать» уехало на сутки вперёд. По поведению такое не диагностируется
    вовсе: робот уверенно называет неверное время, а человек ему верит.

    Сверяем СЕКУНДЫ, а не то, что показывают стрелки. Первая версия сравнивала
    настенное время — и на живом доме сразу ошиблась: робот в Калининграде, ПК
    по Москве, час разницы, а часы при этом идеально синхронны. Число секунд от
    пояса не зависит, и только оно говорит о настоящем расхождении.

    Часовой пояс — отдельная беда, и её эта проверка не ловит вовсе: часы могут
    сойтись до секунды, а робот всё равно будет считать, что сейчас другой час.
    Поэтому пояс печатаем рядом, чтобы человек увидел его глазами.
    """
    if not cfg.pc_url:
        return
    try:
        with urllib.request.urlopen(cfg.pc_url.rstrip("/") + "/health",
                                    timeout=3) as resp:
            import json as _json
            здоровье = _json.loads(resp.read() or b"{}") or {}
    except Exception:
        return          # ПК выключен — это не про часы, и молчать тут правильно
    там = здоровье.get("секунд")
    if not там:
        return          # старая сборка на ПК: секунд не сообщает
    разница = time.time() - float(там)
    if abs(разница) < CLOCK_SLACK:
        log.info("часы робота и ПК сходятся (пояс робота %s)",
                 datetime.now().astimezone().tzname() or "не задан")
        return
    log.warning("ЧАСЫ РАЗОШЛИСЬ НА %+.0f МИНУТ — не поясом, а по-настоящему. "
                "Будильники и напоминания уедут ровно на неё. "
                "Проверить: timedatectl. Включить синхронизацию: "
                "sudo timedatectl set-ntp true", разница / 60)


def _setup_logging() -> None:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)-7s %(name)s: %(message)s",
        datefmt="%H:%M:%S",
        stream=sys.stdout,
    )
    # websocket-библиотека пишет своё «[Errno 111] Connection refused —
    # goodbye» уровнем ERROR на КАЖДУЮ попытку подключения. Пока rosbridge не
    # поднят, попытки идут вечно, и журнал робота состоял из них целиком —
    # за ночь десятки тысяч строк, в которых не найти ничего. Про состояние
    # связи теперь говорим сами (ros.py, _пауза_и_жалоба): один раз и с
    # последствиями, включая «человека в кадре не вижу». Поэтому её ERROR
    # глушим до CRITICAL — не теряя своей диагностики, а заменяя чужую.
    logging.getLogger("websocket").setLevel(logging.CRITICAL)
    logging.getLogger("httpx").setLevel(logging.WARNING)


