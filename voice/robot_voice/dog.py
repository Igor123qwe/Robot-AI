"""Спутник: робот ходит за собакой и не навязывается.

    «Кузя, походи за собакой» — идёт следом примерно в метре.
    Собака залезла на кровать  — отъехал, заглушил моторы, ждёт.
    Собака уходит от робота    — отступил и перестал преследовать.
    Собака потерялась          — поехал искать по квартире.

ГЛАВНОЕ ТРЕБОВАНИЕ ЗДЕСЬ — НЕ ТОЧНОСТЬ, А НЕНАВЯЗЧИВОСТЬ. Робот, который
идеально держит метр, но дёргается и разворачивается на собаку, задачу не
решает: собака уйдёт в другую комнату, и на этом всё кончится. Поэтому
половина правил ниже — про то, чего робот НЕ делает.

──────────────────────────────────────────────────────────────────────────────
ТРИ ПРАВИЛА НЕНАВЯЗЧИВОСТИ, и они не косметика.

МЁРТВАЯ ЗОНА. В метре с небольшим и почти по курсу — в шасси уходит ТОЧНЫЙ
НОЛЬ, а не 0.06 м/с. Постоянное подруливание собака читает как приставание, а
меканум на малой команде вдобавок гудит и не едет. Ноль — это ноль.

БОКОМ, А НЕ РАЗВОРОТОМ. Шасси голономное, и это здесь не оптимизация, а
поведение: разворот корпуса на собаку — сигнал ориентирования, который она
читает; боковое смещение таким сигналом не является. Доворачиваемся корпусом
только когда она ушла из поля вбок сильнее тридцати градусов.

МОЛЧА. Вслух ровно две фразы: «пошёл» и одна в конце. Ни «она на кровати», ни
«она уходит». Довод тот же, что записан в шапке обхода со слов хозяина: робот,
комментирующий каждый шаг, заглушает сам себя.

──────────────────────────────────────────────────────────────────────────────
ПОЧЕМУ РЕШЕНИЕ ОТДЕЛЕНО ОТ ЕЗДЫ

`решить` и `как_ехать` — чистые функции: состояние плюс факты на входе,
состояние и команда на выходе. Ни колёс, ни времени, ни сети внутри.

Так сделано, чтобы таблицу переходов можно было прогнать целиком, не поднимая
ни одного узла ROS, — и чтобы инварианты вроде «ни в одном состоянии вперёд не
даётся ближе шестидесяти сантиметров» проверялись перебором, а не надеждой.

──────────────────────────────────────────────────────────────────────────────
ЧЕГО ЗДЕСЬ НЕТ, честно.

Опознавания особи. Двух собак и кошку робот перепутает: у сети нет номеров,
которым можно верить.

Гарантии отъехать ровно на два метра. Робот пятится только по полу, который
сам занимал секунды назад, и только пока память не возражает. Смог 1.4 м —
останется на 1.4 м. Двухметровый задний ход вслепую рядом с животным и,
возможно, ребёнком — это не осторожность, это её противоположность.
"""

from __future__ import annotations

import logging
import math
import threading
import time
from typing import NamedTuple

from . import dogsight, planner, ride, search

log = logging.getLogger(__name__)

# --- дистанции (числа ТЗ) -----------------------------------------------------
ДЕРЖАТЬ = 1.0
ЗОНА_ОТ, ЗОНА_ДО = 0.8, 1.6
ЗОНА_УГОЛ = math.radians(15.0)
# Наблюдательная позиция у мебели. Два с половиной, а не два из ТЗ: с двух
# метров дальномер не видит собаку на диване (0.80 м) — расчёт в docs/dog.md.
НАБЛЮДАЮ_С = 2.5
БЛИЖЕ_НЕЛЬЗЯ = 0.6
# Насколько отъехали — уже достаточно. Отъезд назад идёт по своему следу и
# может кончиться раньше; требовать ровно два с половиной значило бы стоять и
# буксовать у стены.
ОТОШЛИ_ХВАТИТ = 1.5

# --- скорости (числа ТЗ) ------------------------------------------------------
V_МАКС = 0.25
V_БЛИЗКО = 0.15
W_МАКС = 0.5
БОКОМ_ОТ = math.radians(30.0)
# Быстрее этого вбок не ходим. Меканум вбок слабее, чем вперёд, а робот в эту
# сторону не смотрит вовсе.
БОКОМ_МАКС = 0.10
# Отъезжаем вдвое медленнее ходового: назад робот не видит, и весь его запас
# безопасности здесь — короткий путь и малая скорость.
ОТСТУПАЕМ_НЕ_БЫСТРЕЕ = 0.12

# --- уход собаки (числа ТЗ) ---------------------------------------------------
УХОДИТ_БЫСТРЕЕ = 0.6
УХОДОВ_ХВАТИТ = 2
УХОДОВ_ЗА = 10.0
ОТСТУП_ПАУЗА = 60.0
ОТСТУПОВ_ПОДРЯД = 3
ОТСТУПЫ_ПОМНИМ = 600.0
# На сколько отодвигаемся после каждого отступа. ТЗ говорит «отступает и
# перестаёт преследовать»; обрыв на третьем разе — это утёс. Растущая
# дистанция делает «перестаёт» постепенным: 1.0 → 1.5 → 2.0 → конец, и правило
# «три подряд» перестаёт быть произволом — это конец градиента.
ДОБАВКА_ПОСЛЕ_ОТСТУПА = 0.5

# --- время ---------------------------------------------------------------------
ШАГ = ride.ШАГ
# Сколько живёт подтверждение сети. Сеть отвечает полтора раза в секунду, и
# требовать свежести чаще значило бы считать собаку потерянной между кадрами.
ДЕРЖИМ_БЕЗ_СЕТИ = 2.0
ПОТЕРЯЛИ_ЧЕРЕЗ = 5.0
СТОИТ_К_ОТДЫХУ = 5.0
ХВАТИТ_ЧЕРЕЗ = 1800.0

ЖДУ, ВЕДУ, СТОЮ, НАБЛЮДАЮ, ОТСТУПАЮ, ИЩУ, ХВАТИТ = (
    "жду", "веду", "стою", "наблюдаю", "отступаю", "ищу", "хватит")


class Факты(NamedTuple):
    """Всё, что решателю нужно знать. Ни колёс, ни времени внутри."""

    видим: bool = False
    расстояние: float = 0.0
    пеленг: float = 0.0
    поднята: bool = False
    уходит: bool = False
    отступов: int = 0
    потерян: float = 0.0
    в_состоянии: float = 0.0
    отошли: float = 0.0
    держать: float = ДЕРЖАТЬ
    батарея_села: bool = False


def в_зоне(ф: Факты) -> bool:
    """Робот там, где надо, и смотрит куда надо."""
    return (ф.видим and ЗОНА_ОТ <= ф.расстояние <= ЗОНА_ДО
            and abs(ф.пеленг) < ЗОНА_УГОЛ)


def решить(состояние: str, ф: Факты) -> tuple[str, str]:
    """Что делать дальше. (новое состояние, почему).

    Явной таблицей, а не вложенными if: переходов больше десятка, и в
    лестнице из условий однажды теряется ветка, которую никто не заметит.
    """
    if ф.батарея_села:
        return ХВАТИТ, "батарея села"

    if состояние in (ЖДУ,):
        return (ВЕДУ, "вижу собаку") if ф.видим else (ИЩУ, "не вижу — поищу")

    if состояние in (ВЕДУ, СТОЮ):
        if ф.поднята:
            return НАБЛЮДАЮ, "забралась на мебель"
        if ф.уходит:
            return ОТСТУПАЮ, "уходит от меня"
        if ф.потерян > ПОТЕРЯЛИ_ЧЕРЕЗ:
            return ИЩУ, "потерял"
        if состояние == ВЕДУ and в_зоне(ф):
            return СТОЮ, "на месте"
        if состояние == СТОЮ and not в_зоне(ф):
            return ВЕДУ, "ушла из зоны"
        return состояние, ""

    if состояние == НАБЛЮДАЮ:
        if not ф.поднята:
            return ВЕДУ, "спрыгнула"
        if ф.потерян > 3 * ПОТЕРЯЛИ_ЧЕРЕЗ:
            return ИЩУ, "не вижу её на мебели"
        return НАБЛЮДАЮ, ""

    if состояние == ОТСТУПАЮ:
        if ф.в_состоянии < ОТСТУП_ПАУЗА:
            return ОТСТУПАЮ, ""
        if ф.отступов >= ОТСТУПОВ_ПОДРЯД:
            return ХВАТИТ, "три раза уходила — больше не хожу"
        return (ВЕДУ, "пауза кончилась") if ф.видим else (ИЩУ, "поищу заново")

    if состояние == ИЩУ:
        return (ВЕДУ, "нашлась") if ф.видим else (ИЩУ, "")

    return ХВАТИТ, ""


def как_ехать(состояние: str, ф: Факты, *, можно_боком: bool = True,
              можно_назад: bool = True) -> tuple[float, float, float, str]:
    """Команда колёсам: (вперёд, вбок, поворот, почему).

    ВБОК — ВТОРАЯ ОСЬ, и она здесь не ради красоты. Разворот корпуса собака
    читает как ориентирование на неё; боковое смещение таким сигналом не
    является. Поэтому пока она в тридцати градусах, доворачиваем БОКОМ.

    `можно_боком` и `можно_назад` спрашиваются у памяти на КАЖДОМ круге:
    дальномер смотрит вперёд и только вперёд, а бок и корма — слепые.
    Нет памяти — нет бокового хода; доворачиваемся корпусом, это видно.
    """
    стоим = (0.0, 0.0, 0.0)

    if состояние in (ЖДУ, ХВАТИТ):
        return (*стоим, "стою")

    if состояние in (НАБЛЮДАЮ, ОТСТУПАЮ):
        # Отъехали достаточно — ПОЛНЫЙ НОЛЬ. Робот, который «немножко
        # подъезжает посмотреть», — это ровно то, чего вся затея избегает.
        if ф.отошли >= ОТОШЛИ_ХВАТИТ or not можно_назад:
            return (*стоим, "жду не двигаясь")
        return (-ОТСТУПАЕМ_НЕ_БЫСТРЕЕ, 0.0, 0.0, "отхожу")

    if состояние == СТОЮ:
        # ТОЧНЫЙ НОЛЬ, а не «почти ноль». Микрокоррекции собака читает как
        # приставание, а меканум на 0.06 м/с гудит и не едет.
        return (*стоим, "на месте, не дёргаюсь")

    if состояние == ИЩУ:
        # Поиском рулит search.Поиск — здесь колёсам ничего не говорим.
        return (*стоим, "ищу")

    # --- ВЕДУ -----------------------------------------------------------
    if not ф.видим:
        return (*стоим, "не вижу")
    if ф.расстояние <= БЛИЖЕ_НЕЛЬЗЯ:
        # Ближе жёсткого минимума вперёд не даём НИКОГДА и ни в каком
        # состоянии. Это единственное правило, которое не обсуждается.
        return (*стоим, "и так близко")

    промах = ф.расстояние - ф.держать
    потолок = V_БЛИЗКО if ф.расстояние < 1.5 else V_МАКС
    вперёд = max(0.0, min(потолок, промах * 0.8)) if промах > 0 else 0.0

    вбок = поворот = 0.0
    if abs(ф.пеленг) >= ЗОНА_УГОЛ:
        if abs(ф.пеленг) < БОКОМ_ОТ and можно_боком:
            # Влево у нас плюс, и вбок тоже плюс — знак один.
            вбок = max(-БОКОМ_МАКС, min(БОКОМ_МАКС, ф.пеленг * 0.3))
        else:
            поворот = max(-W_МАКС, min(W_МАКС, ф.пеленг * 1.2))
    почему = ("иду боком" if вбок else
              "доворачиваюсь" if поворот else
              "иду прямо" if вперёд else "стою")
    return (вперёд, вбок, поворот, почему)


class Уходы:
    """Считает, сколько раз собака от робота уходила.

    Событие — не «расстояние выросло», а «выросло БЫСТРО и не один кадр».
    Робот, едущий за стоящей собакой, расстояние тоже меняет; поэтому
    радиальную скорость берём с вычетом собственной, а событие засчитываем
    только после нескольких кадров подряд.
    """

    ПОДРЯД = 3

    def __init__(self, часы=time.monotonic) -> None:
        self._часы = часы
        self._подряд = 0
        self.события: list[float] = []
        self.отступы: list[float] = []

    def кадр(self, радиальная: float) -> None:
        if радиальная > УХОДИТ_БЫСТРЕЕ:
            self._подряд += 1
            if self._подряд >= self.ПОДРЯД:
                self._подряд = 0
                self.события.append(self._часы())
        else:
            self._подряд = 0

    def уходит(self) -> bool:
        край = self._часы() - УХОДОВ_ЗА
        self.события = [к for к in self.события if к >= край]
        return len(self.события) >= УХОДОВ_ХВАТИТ

    def отступили(self) -> None:
        self.события.clear()
        self.отступы.append(self._часы())

    def отступов(self) -> int:
        край = self._часы() - ОТСТУПЫ_ПОМНИМ
        self.отступы = [к for к in self.отступы if к >= край]
        return len(self.отступы)


class Спутник(ride.Переезд):
    """Ходит за собакой. Источник движения — заявляется как следование."""

    def __init__(self, ros, tof, *, план=None, карта=None, пометки=None,
                 вещи=None, компас=None, места=None, говорить=None) -> None:
        self.ros = ros
        self.tof = tof
        self.план = план
        self.карта = карта
        self.пометки = пометки
        self.вещи = вещи
        self.компас = компас
        self.места = места
        self.говорить = говорить or (lambda фраза: None)
        self.выбираюсь = planner.Выбираюсь()
        self._поток: threading.Thread | None = None
        self._стоп = threading.Event()
        self._велели = (0.0, 0.0)
        self.проехали = 0.0
        self.едем_не_быстрее = V_МАКС
        self.поворот_на_ходу = W_МАКС
        self.поворот_на_месте = search.ПОВОРОТ_ОСМОТРА
        self.переезд_метров = 2.0
        self.забываем_неудачу = search.ЗАБЫВАЕМ_НЕУДАЧУ
        self.состояние = ЖДУ
        self.держать = ДЕРЖАТЬ
        self.пульс = dogsight.Пульс()
        self.поднялась = dogsight.Поднялась()
        self.уходы = Уходы()
        self.почему_кончилось = ""

    @property
    def идёт(self) -> bool:
        return self._поток is not None and self._поток.is_alive()

    def начать(self) -> str:
        if self.идёт:
            return "Уже хожу за ней."
        if self.ros is None or self.tof is None:
            return "Не могу ехать: колёса или дальномер не отвечают."
        self.состояние = ЖДУ
        self.держать = ДЕРЖАТЬ
        self.почему_кончилось = ""
        self.поднялась.забыть()
        self.уходы = Уходы()
        self._стоп.clear()
        self.выбираюсь.сбросить()
        self._поток = threading.Thread(target=self._ходить, daemon=True)
        self._поток.start()
        return "Пошёл за собакой. Скажи стоп, когда хватит."

    def хватит(self, почему: str = "", *, ждать: bool = True) -> bool:
        if not self.идёт:
            return False
        self.почему_кончилось = почему or "сказали стоп"
        self._стоп.set()
        if ждать and self._поток is not None:
            self._поток.join(timeout=3.0)
        return True

    # --- сам цикл --------------------------------------------------------
    def _ходить(self) -> None:
        начали = вошли = time.monotonic()
        видели = 0.0
        отошли = 0.0
        try:
            while not self._стоп.is_set():
                if time.monotonic() - начали > ХВАТИТ_ЧЕРЕЗ:
                    self.почему_кончилось = "хожу уже полчаса"
                    break
                факты, видели = self._осмотреться(видели, вошли, отошли)
                новое, почему = решить(self.состояние, факты)
                if новое != self.состояние:
                    log.info("спутник: %s → %s (%s)",
                             self.состояние, новое, почему or "по обстановке")
                    if новое == ОТСТУПАЮ:
                        self.уходы.отступили()
                        self.держать += ДОБАВКА_ПОСЛЕ_ОТСТУПА
                    if новое in (НАБЛЮДАЮ, ОТСТУПАЮ):
                        отошли = 0.0
                    self.состояние, вошли = новое, time.monotonic()
                if self.состояние == ХВАТИТ:
                    self.почему_кончилось = почему or "закончил"
                    break
                if self.состояние == ИЩУ:
                    self._стоп.wait(ШАГ)
                    continue
                отошли += self._поехать(факты)
        except Exception:                       # noqa: BLE001
            log.exception("спутник: сорвался")
            self.почему_кончилось = "что-то пошло не так"
        finally:
            self._встать()
            self._доложить()

    def _осмотреться(self, видели: float, вошли: float,
                     отошли: float) -> tuple[Факты, float]:
        """Собрать факты. Сеть спрашиваем по пульсу, дальномер — каждый круг."""
        сейчас = time.monotonic()
        if self.пульс.пора(self.состояние.upper()) and self.ros is not None:
            try:
                self.ros.посмотреть_разок()
            except Exception:                   # noqa: BLE001
                log.debug("спутник: кадр не попросился", exc_info=True)
        собака = self.вещи.найти("dog") if self.вещи else None
        свежая = (собака is not None
                  and time.time() - getattr(собака, "когда", 0.0)
                  < ДЕРЖИМ_БЕЗ_СЕТИ)
        пеленг = float(getattr(собака, "угол", 0.0) or 0.0) if свежая else 0.0

        взгляд = self.tof.взгляд() if self.tof is not None else None
        сетка = getattr(взгляд, "сетка_без_пола", None) if взгляд else None
        пятно = (dogsight.пятно_в_секторе(сетка, пеленг)
                 if свежая and сетка else None)
        видим = bool(свежая and пятно)
        расстояние = пятно[0] if пятно else 0.0
        if видим:
            видели = сейчас

        # Признаки «на мебели»: главные камерные, дальномер подтверждает.
        мебель = next((self.вещи.найти(к) for к in dogsight.ЛЕЖБИЩА
                       if self.вещи and self.вещи.найти(к)), None) \
            if свежая else None
        поднята = self.поднялась.кадр({
            "рамки": dogsight.над_мебелью(собака, мебель) if свежая else False,
            "низ выше пола": (
                dogsight.низ_выше_пола(getattr(собака, "низ", 0.0),
                                       расстояние, 0.25, 65.0)
                if видим else False),
        })
        self.уходы.кадр(self._радиальная(расстояние))
        return Факты(
            видим=видим, расстояние=расстояние, пеленг=пеленг,
            поднята=поднята, уходит=self.уходы.уходит(),
            отступов=self.уходы.отступов(), потерян=сейчас - видели,
            в_состоянии=сейчас - вошли, отошли=отошли,
            держать=self.держать), видели

    _прошлое_расстояние = 0.0

    def _радиальная(self, расстояние: float) -> float:
        """Как быстро собака удаляется, за вычетом собственного хода."""
        если_нет = 0.0
        if not расстояние or not self._прошлое_расстояние:
            self._прошлое_расстояние = расстояние
            return если_нет
        своя = self._велели[0]
        скорость = (расстояние - self._прошлое_расстояние) / ШАГ + своя
        self._прошлое_расстояние = расстояние
        return скорость

    def _поехать(self, ф: Факты) -> float:
        """Подать команду. Отдаёт, сколько метров отъехали назад."""
        вперёд, вбок, поворот, _ = как_ехать(
            self.состояние, ф,
            можно_боком=self._память_пускает(0.0, 0.1, 0.0),
            можно_назад=self._память_пускает(-0.1, 0.0, 0.0))
        if self.ros is not None:
            self._велели = (вперёд, поворот)
            self.ros.publish_twist(вперёд, вбок, поворот)
        self._стоп.wait(ШАГ)
        return abs(вперёд) * ШАГ if вперёд < 0 else 0.0

    def _память_пускает(self, x: float, y: float, wz: float) -> bool:
        """Слепые направления спрашиваем у карты. Нет карты — не едем вслепую."""
        if self.карта is None:
            return False
        try:
            можно, _ = self.карта.можно_ехать(x, y, wz)
            return bool(можно)
        except Exception:                       # noqa: BLE001
            return False

    def _доложить(self) -> None:
        """Одна фраза, и только в конце."""
        if self.почему_кончилось == "три раза уходила — больше не хожу":
            self.говорить("Она от меня уходит. Больше не хожу за ней.")
            return
        if self.почему_кончилось == "сказали стоп":
            self.говорить("Больше не хожу.")
            return
        self.говорить("Закончил ходить за собакой.")
