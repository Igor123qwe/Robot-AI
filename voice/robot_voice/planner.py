def препятствия(сетка, поле_градусов: float = 60.0,
                ряды=range(2, 6)) -> list[tuple[float, float]]:
    """Сетка дальномера → точки (вперёд, вбок) в метрах, в системе робота.

    Берём средние ряды: верхние смотрят выше робота — люстра и притолока ему
    не мешают, — нижние упираются в пол, и считать пол препятствием значит не
    поехать никогда.
    """
    точки: list[tuple[float, float]] = []
    if not сетка:
        return точки
    колонок = len(сетка[0])
    for р in ряды:
        if р >= len(сетка):
            continue
        for к, д in enumerate(сетка[р]):
            if not д or д <= 0.0:
                continue
            # Колонка 0 — слева, колонка 7 — справа; влево угол положительный,
            # как у пеленга и у ROS.
            угол = math.radians(((колонок - 1) / 2.0 - к)
                                * (поле_градусов / колонок))
            точки.append((д * math.cos(угол), д * math.sin(угол)))
    return точки


def из_карты(карта, дальше: float = 1.2) -> list[tuple[float, float]]:
    """Занятые клетки карты памяти вокруг робота — тоже препятствия.

    Нужны для того, чего дальномер не видит физически: разъезжаясь со стулом,
    робот перестаёт его видеть ровно тогда, когда стул оказывается у него под
    боком. Карта помнит.
    """
    если_нет = []
    if карта is None:
        return если_нет
    точки = getattr(карта, "занятые_вокруг", None)
    if точки is None:
        return если_нет
    try:
        return [(x, y) for x, y in точки(дальше)]
    except Exception:                            # noqa: BLE001
        return если_нет


def проехать(v: float, w: float, t: float) -> tuple[float, float, float]:
    """Где окажется робот через t секунд, если ехать так. (вперёд, вбок, курс).

    Дуга, а не отрезок: робот с ненулевым поворотом едет по окружности, и
    прямая вместо неё — это ошибка ровно там, где она дороже всего, то есть
    на крутых объездах.
    """
    if abs(w) < 1e-6:
        return v * t, 0.0, 0.0
    радиус = v / w
    курс = w * t
    return радиус * math.sin(курс), радиус * (1.0 - math.cos(курс)), курс


def придержать(было: float, стало: float, за_сколько: float,
               разгон: float, замедление: float) -> float:
    """Не дать скорости прыгнуть ступенькой.

    Без этого команда меняется мгновенно: колёса срываются в
    проскальзывание — у меканума ролики к этому особенно склонны, — одометрия
    начинает врать, а человеку кажется, что робот дёргается.

    Тормозить разрешаем быстрее, чем разгоняться. Ограничивать торможение
    ради плавности значит продлевать тормозной путь: цена комфорта не может
    быть такой.

    Живёт ЗДЕСЬ, а не в follow, по одной причине: этой же функцией
    планировщик прокатывает пробные дуги. Если бы их было две, они однажды
    разошлись бы, и робот поехал бы не по той дуге, которую проверил.
    """
    if за_сколько <= 0:
        return стало
    вверх = разгон * за_сколько
    вниз = замедление * за_сколько
    if стало > было:
        return min(стало, было + вверх)
    return max(стало, было - вниз)


def по_кривизне(v: float, w: float,
                радиус_не_меньше: float = РАДИУС_НЕ_МЕНЬШЕ,
                не_ниже: float = СБАВЛЯЕМ_НЕ_НИЖЕ) -> float:
    """Сбавить ход на крутом повороте. Формула Nav2, довод наш.

    Радиус дуги r = v/w. Круче порога — умножаем скорость на r/r_min, то есть
    чем круче, тем медленнее; ровно на пороге множитель единица, и разрыва
    нет. (В Nav2 это записано как v·(1 − |r − r_min|/r_min); при r < r_min
    это то же самое число, просто длиннее.)

    Зачем это роботу, который и так тихоходный: он видит шестьдесят градусов
    вперёд и ничего по бокам. Крутой поворот на полном ходу — это въезд в
    непроверенное со скоростью, с которой оттуда уже не остановиться.
    """
    if v <= 0.0 or abs(w) < 1e-6:
        return v
    радиус = abs(v / w)
    if радиус >= радиус_не_меньше:
        return v
    сбавили = v * (радиус / радиус_не_меньше)
    # Ниже порога не опускаем — но и не ПОДНИМАЕМ то, что и так было ниже.
    return min(v, max(сбавили, не_ниже))


def прокатить(v_цель: float, w_цель: float,
              v0: float = 0.0, w0: float = 0.0, *,
              шагов: int = ШАГОВ, горизонт: float = ГОРИЗОНТ,
              разгон: float = РАЗГОН, сброс: float = СБРОС,
              разгон_поворота: float = РАЗГОН_ПОВОРОТА,
              торможение: float = ТОРМОЖЕНИЕ):
    """Где робот окажется, если СКОМАНДОВАТЬ (v_цель, w_цель) из (v0, w0).

    Выдаёт позы по одной, от ближней к дальней: (вперёд, вбок, курс, хвост).
    Последнее — признак того, что этот кусок уже тормозной.

    Выдаёт, а не отдаёт списком, нарочно. Проверка почти всегда обрывается
    досрочно — либо корпус во что-то вошёл, либо стало ясно, что хвост
    считать незачем, — и считать позы, которых никто не спросит, значит
    тратить круг цикла впустую.

    Две вещи, которых не делала прежняя прямая прокатка с постоянной
    скоростью.

    РАЗГОН. Колёса не прыгают на заданную скорость: между командой и ней
    стоит `придержать`. Прокатывая дугу постоянной скоростью, планировщик
    проверял траекторию, по которой робот НЕ ПОЕДЕТ, и ошибался в самую
    опасную сторону: от неподвижности поворот набирается за треть секунды, а
    ход — за секунду с лишним, то есть первый миг робот почти крутится на
    месте там, где ему обещали пологую дугу.

    ТОРМОЗНОЙ ХВОСТ. После горизонта скорость гасится настоящим замедлением,
    а поворот держится. Это и есть условие допустимости из DWA — «оставляем
    только те скорости, на которых робот способен остановиться», — записанное
    прокаткой вместо арифметики: так в него сам собой попадает поворот,
    которого в формуле v ≤ sqrt(2·d·a) нет.
    """
    шаг = горизонт / max(1, шагов)
    x = y = курс = 0.0
    v, w = v0, w0
    for _ in range(max(1, шагов)):
        v = придержать(v, v_цель, шаг, разгон, сброс)
        w = придержать(w, w_цель, шаг, разгон_поворота, разгон_поворота)
        x, y, курс = _шагнуть(x, y, курс, v, w, шаг)
        yield x, y, курс, False
    for _ in range(ХВОСТ_ШАГОВ):
        if v <= ПОЧТИ_СТОИМ:
            return
        v = max(0.0, v - торможение * шаг)
        x, y, курс = _шагнуть(x, y, курс, v, w, шаг)
        yield x, y, курс, True


def тормозной_путь(v: float, торможение: float = ТОРМОЖЕНИЕ) -> float:
    """Сколько метров робот проедет, если прямо сейчас начать тормозить."""
    if v <= 0:
        return 0.0
    return v * v / (2.0 * max(0.01, торможение))


def _шагнуть(x: float, y: float, курс: float,
             v: float, w: float, шаг: float) -> tuple[float, float, float]:
    """Один кусок дуги, приложенный к текущей позе."""
    дx, дy, дкурс = проехать(v, w, шаг)
    cos, sin = math.cos(курс), math.sin(курс)
    return x + дx * cos - дy * sin, y + дx * sin + дy * cos, курс + дкурс


def влезаем(x: float, y: float, курс: float,
            точки, полуширина: float, полудлина: float) -> float:
    """Насколько тесно в этой позе. Ноль и меньше — корпус во что-то вошёл.

    Отдаём не «да/нет», а ЗАПАС в метрах: планировщику мало знать, что
    проедет, — из двух проезжих дуг надо выбрать ту, что идёт просторнее.

    Корпус — прямоугольник, а не круг. Круг радиуса тридцать сантиметров
    (описанная окружность тележки) не пролезает в щель, в которую она
    проходит спокойно, и робот отказывался бы ехать по собственному коридору.
    """
    зазор = float("inf")
    cos, sin = math.cos(-курс), math.sin(-курс)
    for тx, тy in точки:
        # Точка в системе координат этой позы.
        дx, дy = тx - x, тy - y
        мx = дx * cos - дy * sin
        мy = дx * sin + дy * cos
        # Расстояние от точки до прямоугольника корпуса.
        вбок = abs(мy) - полуширина
        вдоль = abs(мx) - полудлина
        если_снаружи = math.hypot(max(вбок, 0.0), max(вдоль, 0.0))
        внутри = max(вбок, вдоль)
        зазор = min(зазор, если_снаружи if внутри > 0 else внутри)
    return зазор


def штраф_за_тесноту(зазор: float) -> float:
    """Насколько плоха дуга по близости к предметам. Формула инфляции Nav2.

    Убывает по экспоненте и НИКОГДА не обращается в ноль: препятствие в метре
    впереди должно чуть-чуть влиять на выбор уже сейчас, иначе робот поедет
    прямо на него и спохватится тогда, когда объезжать станет нечем.
    """
    return math.exp(-ТЕСНОТА_КРУЧЕ * max(0.0, зазор))


def без_цели(точки, до_цели: float, угол: float,
             радиус: float = ЦЕЛЬ_НЕ_ПРЕПЯТСТВИЕ):
    """Убрать из препятствий то, что стоит на месте цели.

    Дальномер не знает, что перед ним, и человек для него — обычное пятно.
    Оставить его в препятствиях значит велеть роботу от него уворачиваться:
    чем ближе подходит, тем теснее, тем сильнее хочется отвернуть. Робот
    кружил бы вокруг человека, не подходя.
    """
    if до_цели <= 0:
        return list(точки)
    цx, цy = до_цели * math.cos(угол), до_цели * math.sin(угол)
    return [(x, y) for x, y in точки
            if math.hypot(x - цx, y - цy) > радиус]


def выбрать(цель_дальше: float, цель_угол: float, точки,
            скорость_потолок: float, поворот_потолок: float,
            было_вперёд: float = 0.0, было_поворот: float = 0.0,
            запас: float = ЗАПАС):
    """Лучшая пара (вперёд, поворот) из перебора. И почему выбрана именно она.

    `цель_дальше` — сколько метров надо ПРОЕХАТЬ к цели (уже за вычетом
    желаемой дистанции). Ноль или меньше — ехать вперёд незачем, остаётся
    доворот.

    Возвращает (вперёд, поворот, объяснение). Все дуги упираются — вернём
    нули и скажем об этом: остановка с причиной лучше молчаливого ступора.
    """
    # Куда хотим попасть — точка в системе робота.
    цx = max(0.0, цель_дальше) * math.cos(цель_угол)
    цy = max(0.0, цель_дальше) * math.sin(цель_угол)
    до_цели_сейчас = math.hypot(цx, цy)

    # Точки, до которых за горизонт с тормозным хвостом всё равно не
    # дотянуться, в переборе не участвуют. Это не хитрость ради скорости, а
    # единственный способ уложиться в круг цикла: перебор идёт по всем дугам,
    # каждая по всем шагам, каждый шаг по всем точкам — и лишняя четверть
    # точек стоит лишней четверти времени на каждом кадре.
    дотуда = (max(скорость_потолок, abs(было_вперёд)) * (ГОРИЗОНТ + 1.0)
              + ПОЛУДЛИНА + ТЕСНО_ОТ + запас)
    точки = [(x, y) for x, y in точки if math.hypot(x, y) <= дотуда]

    лучшее = None
    лучший_счёт = -1e9
    уперлись = 0
    всего = 0
    for доля in ДОЛИ_СКОРОСТИ:
        for w in ПОВОРОТЫ:
            if abs(w) > поворот_потолок + 1e-9:
                continue
            всего += 1
            # Сбавляем на крутом ДО проверки, а не после. Проверить одну
            # скорость, а поехать с другой — это ровно та ошибка, из-за
            # которой затевалась прокатка с разгоном.
            v_кр = по_кривизне(скорость_потолок * доля, w)
            # Прокатываем дугу — с разгоном и с тормозным хвостом — и смотрим
            # самый тесный её кусок. Хвост означает: до полной остановки
            # корпус не должен задеть ничего. Дуга, на которой робот успевает
            # проехать полторы секунды и только потом упирается, теперь
            # отбрасывается, а не выбирается.
            теснее_всего = float("inf")
            конец = (0.0, 0.0, 0.0)
            # Насколько робот способен сдвинуться за весь тормозной хвост.
            # Больше чем на столько зазор при торможении не убавится, значит
            # хвост, начинающийся в просторном месте, считать незачем — и это
            # не приближение, а точная оценка сверху.
            хватит_простора = тормозной_путь(v_кр) + запас
            for x, y, курс, хвост in прокатить(v_кр, w, было_вперёд,
                                               было_поворот):
                if хвост and теснее_всего >= хватит_простора:
                    break
                if not хвост:
                    # Цель считаем по концу ХОДОВОЙ части: тормозной хвост —
                    # это не «куда я хочу приехать», а «где я встану, если
                    # сейчас же начну тормозить».
                    конец = (x, y, курс)
                зазор = влезаем(x, y, курс, точки, ПОЛУШИРИНА, ПОЛУДЛИНА)
                теснее_всего = min(теснее_всего, зазор)
                if теснее_всего < запас:
                    break
            if теснее_всего < запас:
                уперлись += 1
                continue

            x, y, _курс = конец
            до_цели_потом = math.hypot(цx - x, цy - y)
            приблизились = до_цели_сейчас - до_цели_потом
            теснота = штраф_за_тесноту(теснее_всего)
            # Плавность считаем ТОЛЬКО по повороту. Скорость и без того
            # сглаживается разгоном — теперь прямо внутри прокатки, — а
            # складывать метры в секунду с радианами в секунду одним весом —
            # это сравнивать несравнимое.
            дёрганье = abs(w - было_поворот)
            # Путь по дуге, а не скорость: награда обязана быть в тех же
            # метрах, что и близость к цели, иначе она однажды окажется
            # дороже её. Один раз уже оказалась.
            ход = math.hypot(x, y)
            счёт = (ЗА_БЛИЗОСТЬ * приблизились
                    + ЗА_ХОД * ход
                    - ЗА_ТЕСНОТУ * теснота
                    - ЗА_ПЛАВНОСТЬ * дёрганье)
            if счёт > лучший_счёт:
                лучший_счёт, лучшее = счёт, (v_кр, w, теснее_всего)

    if лучшее is None:
        return 0.0, 0.0, f"все {всего} дуг упираются"
    v, w, зазор = лучшее
    почему = f"зазор {зазор:.2f} м, отброшено {уперлись} из {всего}"
    if v <= 0.0:
        # Ноль вперёд при живых дугах — это не «нечего делать», а «ехать
        # незачем или некуда». Без этой приписки в журнале остаётся бодрое
        # «зазор 0.37 м» рядом с неподвижным роботом, и человек ищет поломку
        # там, где её нет.
        почему += "; вперёд не еду"
    return v, w, почему


def радиус_корпуса() -> float:
    """Описанная окружность тележки — для вращения на месте.

    Отдельно от полуширины: при развороте на месте углы корпуса заметают
    круг, и там нужна именно диагональ. Берём из mapping, чтобы число жило в
    одном месте.
    """
    return mapping.РАДИУС_КОРПУСА
