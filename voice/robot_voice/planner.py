"""Куда ехать: перебор дуг вместо «прямо или стоять».

ЧЕГО НЕ ХВАТАЛО. До сих пор робот считал скорость и поворот простой
пропорцией — «человек правее, значит крути вправо; человек дальше, значит
езжай» — и отдельно проверял, не мешает ли что-то впереди. Мешает — скорость
в ноль. Обойти он не умел вовсе: только ехать или стоять.

Для комнаты это приговор. Стул на пути, косяк, угол дивана — всё это не
«стой», а «прими на полметра левее и езжай дальше». Настоящие роботы так и
делают: строят десятки пробных траекторий, отбрасывают те, что упрутся, и из
оставшихся берут ту, что ближе всего подводит к цели. В Nav2 это зовётся
локальным планировщиком (DWA, TEB), и без него ездить по жилью нельзя.

ЧТО ЗДЕСЬ И ЧЕГО ЗДЕСЬ НЕТ. Это не Nav2 и не его замена. Nav2 строит путь по
карте всей квартиры и требует лидара; у нас лидара нет, и дальномер видит
шестьдесят градусов вперёд — по бокам робот слеп. Значит планировать маршрут
через комнату нечем и незачем.

А вот выбрать ближайшие полторы секунды — можно, и этого хватает, чтобы
объезжать. Перебираем пары «скорость, поворот», прокатываем каждую вперёд по
дуге, выбрасываем те, на которых корпус во что-нибудь войдёт, и берём из
оставшихся лучшую по близости к цели.

ОТКУДА БЕРУТСЯ ПРЕПЯТСТВИЯ. Из двух мест сразу:
  • живая сетка дальномера — то, что видно прямо сейчас впереди;
  • карта памяти — то, что робот видел раньше и что уже вышло из поля зрения.
Второе важнее, чем кажется: разъезжаясь со стулом, робот перестаёт его
видеть ровно в тот момент, когда стул оказывается у него под боком.

ЧЕГО ЭТОТ ПЛАНИРОВЩИК НЕ УМЕЕТ, и врать про это не надо. Он не выведет из
тупика: заехав в угол, робот увидит, что все дуги упираются, и остановится —
пятиться назад вслепую ему нельзя, там слепая зона. Он не объедет предмет,
которого не видел (тонкая ножка стула на границе разрешения). И он не
планирует дальше полутора секунд: за поворот коридора он не заглядывает.
"""

from __future__ import annotations

import logging
import math

from . import mapping

log = logging.getLogger(__name__)

# Насколько далеко прокатываем каждую пробную дугу. Полторы секунды: на нашей
# скорости это метр с небольшим — дальше загадывать нечем, потому что дальше
# дальномер уже почти ничего не возвращает.
ГОРИЗОНТ = 1.5
# На сколько кусков режем дугу при проверке. Восемь: шаг выходит около
# пятнадцати сантиметров, вчетверо мельче корпуса — проскочить препятствие
# между двумя пробами нельзя.
ШАГОВ = 8

# Полуширина корпуса и полудлина. Робот проверяется ПРЯМОУГОЛЬНИКОМ, а не
# кругом, и это принципиально: круг радиуса 0.30 (описанная окружность) не
# пролезает в щель, в которую тележка проходит боком спокойно. Мерить надо
# рулеткой — числа по чертежу WD550.
ПОЛУШИРИНА = 0.20
ПОЛУДЛИНА = 0.25
# Запас поверх корпуса. Не «на всякий случай», а на то, что колёса
# проскальзывают, одометрия врёт, а кромку предмета датчик видит не в самой
# её точке.
ЗАПАС = 0.06

# Какие скорости перебираем, доли от разрешённой. Ноль обязателен: иногда
# правильный ответ — «повернуться на месте, не двигаясь».
ДОЛИ_СКОРОСТИ = (0.0, 0.35, 0.7, 1.0)
# Какие повороты перебираем, рад/с. Плотнее у нуля: разница между «прямо» и
# «чуть левее» решает, а между «круто» и «очень круто» — уже нет.
ПОВОРОТЫ = (-1.0, -0.6, -0.35, -0.18, -0.08, 0.0,
            0.08, 0.18, 0.35, 0.6, 1.0)

# Веса в оценке. Подобраны так, чтобы приближение к цели решало, а остальное
# только разнимало ничьи.
ЗА_БЛИЗОСТЬ = 1.0        # насколько конец дуги ближе к цели, метры
# Штраф за тесноту. Не награда за простор, а именно штраф, и растёт он по мере
# приближения к корпусу — так дуга, проходящая впритирку, проигрывает
# заведомо, а две просторные не спорят между собой попусту.
ЗА_ТЕСНОТУ = 2.0
# Ближе этого начинаем считать тесно. Дальше — всё равно просторно, и
# разбирать там нечего.
ТЕСНО_ОТ = 0.35
# Штраф за резкую смену поворота. Маленький нарочно.
#
# Сначала он был втрое больше и сравнивал метры в секунду с радианами в
# секунду одним весом. Выходило, что от неподвижности ЛЮБОЙ поворот выглядит
# резким, и робот, увидев стул точно по курсу, предпочитал «прямо, но
# медленно»: так он тоже приближается к цели. Кончалось это тем, что он
# подползал к стулу на полметра и вставал — объехать оттуда уже нельзя,
# тележке шириной сорок сантиметров нужно место для дуги.
#
# Проверено прогонами: со старым весом робот вставал в 0.5 м от стула, с
# новым обходит его и едет дальше.
ЗА_ПЛАВНОСТЬ = 0.05

ЦЕЛЬ_НЕ_ПРЕПЯТСТВИЕ = 0.45


def препятствия(сетка, поле_градусов: float = 60.0,
                ряды=range(2, 6)) -> list[tuple[float, float]]:
    """Сетка дальномера → точки (вперёд, вбок) в метрах, в системе робота.

    Берём средние ряды: верхние смотрят выше робота — люстра и притолока ему
    не мешают, — нижние упираются в пол, и считать пол препятствием значит не
    поехать никогда.
    """
    точки: list[tuple[float, float]] = []
    if not сетка:
        return точки
    колонок = len(сетка[0])
    for р in ряды:
        if р >= len(сетка):
            continue
        for к, д in enumerate(сетка[р]):
            if not д or д <= 0.0:
                continue
            # Колонка 0 — слева, колонка 7 — справа; влево угол положительный,
            # как у пеленга и у ROS.
            угол = math.radians(((колонок - 1) / 2.0 - к)
                                * (поле_градусов / колонок))
            точки.append((д * math.cos(угол), д * math.sin(угол)))
    return точки


def из_карты(карта, дальше: float = 1.2) -> list[tuple[float, float]]:
    """Занятые клетки карты памяти вокруг робота — тоже препятствия.

    Нужны для того, чего дальномер не видит физически: разъезжаясь со стулом,
    робот перестаёт его видеть ровно тогда, когда стул оказывается у него под
    боком. Карта помнит.
    """
    если_нет = []
    if карта is None:
        return если_нет
    точки = getattr(карта, "занятые_вокруг", None)
    if точки is None:
        return если_нет
    try:
        return [(x, y) for x, y in точки(дальше)]
    except Exception:                            # noqa: BLE001
        return если_нет


def проехать(v: float, w: float, t: float) -> tuple[float, float, float]:
    """Где окажется робот через t секунд, если ехать так. (вперёд, вбок, курс).

    Дуга, а не отрезок: робот с ненулевым поворотом едет по окружности, и
    прямая вместо неё — это ошибка ровно там, где она дороже всего, то есть
    на крутых объездах.
    """
    if abs(w) < 1e-6:
        return v * t, 0.0, 0.0
    радиус = v / w
    курс = w * t
    return радиус * math.sin(курс), радиус * (1.0 - math.cos(курс)), курс


def влезаем(x: float, y: float, курс: float,
            точки, полуширина: float, полудлина: float) -> float:
    """Насколько тесно в этой позе. Ноль и меньше — корпус во что-то вошёл.

    Отдаём не «да/нет», а ЗАПАС в метрах: планировщику мало знать, что
    проедет, — из двух проезжих дуг надо выбрать ту, что идёт просторнее.

    Корпус — прямоугольник, а не круг. Круг радиуса тридцать сантиметров
    (описанная окружность тележки) не пролезает в щель, в которую она
    проходит спокойно, и робот отказывался бы ехать по собственному коридору.
    """
    зазор = float("inf")
    cos, sin = math.cos(-курс), math.sin(-курс)
    for тx, тy in точки:
        # Точка в системе координат этой позы.
        дx, дy = тx - x, тy - y
        мx = дx * cos - дy * sin
        мy = дx * sin + дy * cos
        # Расстояние от точки до прямоугольника корпуса.
        вбок = abs(мy) - полуширина
        вдоль = abs(мx) - полудлина
        если_снаружи = math.hypot(max(вбок, 0.0), max(вдоль, 0.0))
        внутри = max(вбок, вдоль)
        зазор = min(зазор, если_снаружи if внутри > 0 else внутри)
    return зазор


def без_цели(точки, до_цели: float, угол: float,
             радиус: float = ЦЕЛЬ_НЕ_ПРЕПЯТСТВИЕ):
    """Убрать из препятствий то, что стоит на месте цели.

    Дальномер не знает, что перед ним, и человек для него — обычное пятно.
    Оставить его в препятствиях значит велеть роботу от него уворачиваться:
    чем ближе подходит, тем теснее, тем сильнее хочется отвернуть. Робот
    кружил бы вокруг человека, не подходя.
    """
    if до_цели <= 0:
        return list(точки)
    цx, цy = до_цели * math.cos(угол), до_цели * math.sin(угол)
    return [(x, y) for x, y in точки
            if math.hypot(x - цx, y - цy) > радиус]


def выбрать(цель_дальше: float, цель_угол: float, точки,
            скорость_потолок: float, поворот_потолок: float,
            было_вперёд: float = 0.0, было_поворот: float = 0.0,
            запас: float = ЗАПАС):
    """Лучшая пара (вперёд, поворот) из перебора. И почему выбрана именно она.

    `цель_дальше` — сколько метров надо ПРОЕХАТЬ к цели (уже за вычетом
    желаемой дистанции). Ноль или меньше — ехать вперёд незачем, остаётся
    доворот.

    Возвращает (вперёд, поворот, объяснение). Все дуги упираются — вернём
    нули и скажем об этом: остановка с причиной лучше молчаливого ступора.
    """
    # Куда хотим попасть — точка в системе робота.
    цx = max(0.0, цель_дальше) * math.cos(цель_угол)
    цy = max(0.0, цель_дальше) * math.sin(цель_угол)
    до_цели_сейчас = math.hypot(цx, цy)

    лучшее = None
    лучший_счёт = -1e9
    уперлись = 0
    всего = 0
    for доля in ДОЛИ_СКОРОСТИ:
        v = скорость_потолок * доля
        for w in ПОВОРОТЫ:
            if abs(w) > поворот_потолок + 1e-9:
                continue
            всего += 1
            # Прокатываем дугу и смотрим самый тесный её кусок.
            теснее_всего = float("inf")
            конец = (0.0, 0.0, 0.0)
            for шаг in range(1, ШАГОВ + 1):
                t = ГОРИЗОНТ * шаг / ШАГОВ
                x, y, курс = проехать(v, w, t)
                конец = (x, y, курс)
                зазор = влезаем(x, y, курс, точки, ПОЛУШИРИНА, ПОЛУДЛИНА)
                теснее_всего = min(теснее_всего, зазор)
                if теснее_всего < запас:
                    break
            if теснее_всего < запас:
                уперлись += 1
                continue

            x, y, _курс = конец
            до_цели_потом = math.hypot(цx - x, цy - y)
            приблизились = до_цели_сейчас - до_цели_потом
            теснота = max(0.0, ТЕСНО_ОТ - min(теснее_всего, ТЕСНО_ОТ))
            # Плавность считаем ТОЛЬКО по повороту. Скорость и без того
            # сглаживается ниже по течению (см. придержать в follow), а
            # складывать метры в секунду с радианами в секунду одним весом —
            # это сравнивать несравнимое.
            дёрганье = abs(w - было_поворот)
            счёт = (ЗА_БЛИЗОСТЬ * приблизились
                    - ЗА_ТЕСНОТУ * теснота
                    - ЗА_ПЛАВНОСТЬ * дёрганье)
            _ = было_вперёд
            if счёт > лучший_счёт:
                лучший_счёт, лучшее = счёт, (v, w, теснее_всего)

    if лучшее is None:
        return 0.0, 0.0, f"все {всего} дуг упираются"
    v, w, зазор = лучшее
    return v, w, f"зазор {зазор:.2f} м, отброшено {уперлись} из {всего}"


def радиус_корпуса() -> float:
    """Описанная окружность тележки — для вращения на месте.

    Отдельно от полуширины: при развороте на месте углы корпуса заметают
    круг, и там нужна именно диагональ. Берём из mapping, чтобы число жило в
    одном месте.
    """
    return mapping.РАДИУС_КОРПУСА
