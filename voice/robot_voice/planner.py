"""Куда ехать: перебор дуг вместо «прямо или стоять».

ЧЕГО НЕ ХВАТАЛО. До сих пор робот считал скорость и поворот простой
пропорцией — «человек правее, значит крути вправо; человек дальше, значит
езжай» — и отдельно проверял, не мешает ли что-то впереди. Мешает — скорость
в ноль. Обойти он не умел вовсе: только ехать или стоять.

Для комнаты это приговор. Стул на пути, косяк, угол дивана — всё это не
«стой», а «прими на полметра левее и езжай дальше». Настоящие роботы так и
делают: строят десятки пробных траекторий, отбрасывают те, что упрутся, и из
оставшихся берут ту, что ближе всего подводит к цели. В Nav2 это зовётся
локальным планировщиком (DWA, TEB), и без него ездить по жилью нельзя.

ЧТО ЗДЕСЬ И ЧЕГО ЗДЕСЬ НЕТ. Это не Nav2 и не его замена. Nav2 строит путь по
карте всей квартиры и требует лидара; у нас лидара нет, и дальномер видит
шестьдесят градусов вперёд — по бокам робот слеп. Значит планировать маршрут
через комнату нечем и незачем.

А вот выбрать ближайшие полторы секунды — можно, и этого хватает, чтобы
объезжать. Перебираем пары «скорость, поворот», прокатываем каждую вперёд по
дуге, выбрасываем те, на которых корпус во что-нибудь войдёт, и берём из
оставшихся лучшую по близости к цели.

ОТКУДА БЕРУТСЯ ПРЕПЯТСТВИЯ. Из двух мест сразу:
  • живая сетка дальномера — то, что видно прямо сейчас впереди;
  • карта памяти — то, что робот видел раньше и что уже вышло из поля зрения.
Второе важнее, чем кажется: разъезжаясь со стулом, робот перестаёт его
видеть ровно в тот момент, когда стул оказывается у него под боком.

ЧЕГО ЭТОТ ПЛАНИРОВЩИК НЕ УМЕЕТ, и врать про это не надо. Он не выведет из
тупика: заехав в угол, робот увидит, что все дуги упираются, и остановится —
пятиться назад вслепую ему нельзя, там слепая зона. Он не объедет предмет,
которого не видел (тонкая ножка стула на границе разрешения). И он не
планирует дальше полутора секунд: за поворот коридора он не заглядывает.

ЧТО ДОБАВЛЕНО ПОСЛЕ СВЕРКИ С ЧУЖИМИ ФОРМУЛАМИ. Первая редакция этого файла
была «DWA по мотивам»: дуги перебирались, но три вещи, из-за которых DWA
вообще называется ДИНАМИЧЕСКИМ, отсутствовали.

  1. ДИНАМИЧЕСКОЕ ОКНО. Дуга прокатывалась с постоянной скоростью, а колёса
     разгоняются не мгновенно (за это отвечает `придержать`). Планировщик
     проверял одну дугу, а ехал робот по другой — и промах был не мелкий: от
     неподвижности при v=0.55 и w=0.6 проверялся радиус 0.9 м, а первый миг
     робот шёл по радиусу 0.05 м, то есть почти крутился на месте. Проверено
     было просторно, поехали — в стену. Теперь дуга прокатывается ТЕМ ЖЕ
     разгоном, каким потом поедет.

  2. ДОПУСТИМОСТЬ ПО ТОРМОЗНОМУ ПУТИ. У Фокса, Бургарда и Труна в наборе
     остаются только те скорости, на которых робот СПОСОБЕН ОСТАНОВИТЬСЯ до
     препятствия (v ≤ sqrt(2·d·a)). У нас проверялись полторы секунды хода —
     и всё; что будет на полутора-с-половиной, никого не занимало. Теперь к
     каждой дуге пристроен ТОРМОЗНОЙ ХВОСТ: после горизонта скорость гасится
     с настоящим замедлением, и корпус обязан не задеть ничего до полной
     остановки. Это та же формула, только без арифметики: вместо «сравним
     число с корнем» — «прокатим и посмотрим», а поворот при этом учитывается
     сам собой.

  3. СБАВЛЯТЬ НА КРУТОМ. В Nav2 это зовётся regulated pure pursuit:
     v ← v·(r/r_min) при r < r_min. Для нашего робота довод даже сильнее, чем
     для складского: он видит шестьдесят градусов вперёд и НИЧЕГО по бокам,
     то есть крутой поворот — это въезд в невидимое. Крутить туда на полном
     ходу нельзя.

ЧЕГО НЕТ И ПОСЛЕ ЭТОГО. Обхода всей квартиры «змейкой» (boustrophedon — то,
чем пылесосы покрывают комнату) и следования вдоль стены. Обе вещи требуют
карты ВСЕЙ комнаты и позы в ней, а у нас карта локальная и забывчивая, и без
лидара другой не будет. Врать, что робот «объедет квартиру», нечем.
"""

from __future__ import annotations

import logging
import math

log = logging.getLogger(__name__)

# Насколько далеко прокатываем каждую пробную дугу. Полторы секунды: на нашей
# скорости это метр с небольшим — дальше загадывать нечем, потому что дальше
# дальномер уже почти ничего не возвращает.
ГОРИЗОНТ = 1.5
# На сколько кусков режем дугу при проверке. Восемь: шаг выходит около
# пятнадцати сантиметров, вчетверо мельче корпуса — проскочить препятствие
# между двумя пробами нельзя.
ШАГОВ = 8

# Полуширина корпуса и полудлина. Робот проверяется ПРЯМОУГОЛЬНИКОМ, а не
# кругом, и это принципиально: круг радиуса 0.30 (описанная окружность) не
# пролезает в щель, в которую тележка проходит боком спокойно. Мерить надо
# рулеткой — числа по чертежу WD550.
ПОЛУШИРИНА = 0.20
ПОЛУДЛИНА = 0.25
# Запас поверх корпуса. Не «на всякий случай», а на то, что колёса
# проскальзывают, одометрия врёт, а кромку предмета датчик видит не в самой
# её точке.
ЗАПАС = 0.06

# --- как разгоняется и тормозит эта тележка ----------------------------------
# Эти числа жили в follow.py, потому что ими ограничивали команду перед
# отправкой на колёса. Теперь они нужны и здесь: планировщик, который считает
# дугу без разгона, считает дугу, по которой робот не поедет. Держим их в
# одном месте — follow берёт их отсюда.
#
# Разгон медленнее сброса намеренно: тормозить надо так быстро, как умеем, а
# трогаться — плавно, иначе ролики меканума срываются в проскальзывание и
# одометрия начинает врать.
РАЗГОН = 0.5                 # м/с², как быстро прибавляем ход
СБРОС = 1.2                  # м/с², как быстро убавляем команду
РАЗГОН_ПОВОРОТА = 3.0        # рад/с², в обе стороны

# Настоящее замедление при торможении, м/с². Взято с запасом ВНИЗ: никто его
# не мерил, а ошибиться тут можно только в одну сторону. Померить —
# scripts/measure_braking.py, три метра свободного пола: разогнать до
# известной скорости, скомандовать ноль и посмотреть по одометрии, сколько
# проехал дальше; a = v²/(2·путь). Когда померим — правим ЗДЕСЬ.
ТОРМОЖЕНИЕ = 0.8

# Докуда докатываем тормозной хвост. Ограничение нужно только чтобы цикл
# гарантированно кончился: при 0.55 м/с и замедлении 0.8 хвост это 0.7 с,
# то есть четыре шага. Десять — с запасом на вдвое более медленное торможение.
ХВОСТ_ШАГОВ = 10
# Ниже этой скорости считаем, что уже стоим.
ПОЧТИ_СТОИМ = 0.02

# Радиус, круче которого сбавляем ход. Nav2 держит здесь 0.9 м для складской
# тележки; у нас довод свой и он жёстче: дальномер видит ±30°, по бокам робот
# слеп, и крутой поворот — это въезд в невидимое.
#
# Считается так. Остановка занимает время реакции плюс само торможение, у нас
# это около секунды. За секунду при повороте w курс уходит на w радиан, и
# уходить дальше половины поля зрения (30° ≈ 0.52 рад) значит ехать туда, где
# ничего не мерили. Отсюда w ≤ 0.5 рад/с на полном ходу, то есть радиус не
# меньше 0.55/0.5 ≈ 1.1 м. Берём 0.8 — середину между этой строгостью и тем,
# что в квартире дуги радиусом метр просто некуда вписать.
#
# Действует так: при v=0.55 и w=1.0 радиус выходит 0.55 м, и скорость падает
# до 0.55·(0.55/0.8) = 0.38 м/с. Круто повернуть робот по-прежнему может —
# но не с разбегу.
РАДИУС_НЕ_МЕНЬШЕ = 0.8

# С какого зазора до корпуса начинаем сбавлять ход, метры. Второе правило
# regulated pure pursuit, которого у нас не было: скорость режется не только
# крутизной поворота, но и близостью препятствия.
#
# Полметра. Считается так же, как всё остальное здесь, — от тормозного пути.
# На полном ходу 0.55 м/с при замедлении 0.8 м/с² робот проезжает 0.19 м,
# плюс задержка реакции цепочки (кадр дальномера, круг цикла, разгон колёс)
# — ещё около 0.2 м. Итого треть метра до полной остановки; полметра даёт к
# этому запас, а не впритык.
СБАВЛЯТЬ_БЛИЖЕ = 0.5

# Сколько ходовых дуг должно остаться, чтобы считать, что ехать ещё есть куда.
# Меньше — робот упёрся и должен искать обход, а не стоять столбом. Пять из
# пятидесяти пяти: это уже не выбор, а последние крохи у самой стены.
ХОДОВЫХ_ХВАТИТ = 5
# С какой скоростью разворачиваться, ища обход, рад/с. То же осторожное
# число, что у поездки вслепую: вращение на месте кажется безобидным и
# таковым не является — робот слеп сзади и по бокам, а углы корпуса
# описывают окружность.
ИЩЕМ_ОБХОД = 0.4

# Насколько широко оглядываемся, ища выход, градусов в каждую сторону. Сто
# восемьдесят: карта помнит и то, что уже за спиной, — робот туда только что
# приехал. Дальномер столько не видит, но карта видела.
ОГЛЯДЫВАЕМСЯ_НА = 180.0
# Ширина сектора при выборе свободного направления, градусов. Тридцать: уже
# — начинаем ловить шум одиночных замеров, шире — теряется разница между
# дверным проёмом и стеной рядом с ним.
СЕКТОР = 30.0
# Сколько рад/с даём на радиан отклонения от свободного направления. Единица:
# поворот затухает по мере доворота и на месте гаснет сам, без отдельного
# условия «хватит крутиться».
ПО_УГЛУ_ОБХОДА = 1.0
# С какого поворота считаем, что робот УЖЕ крутится и менять сторону поздно.
# Половина от той скорости, с которой ищем обход: меньше — это остаток
# затухания, а не намерение.
КРУТИМСЯ_ОТ = ИЩЕМ_ОБХОД / 2

# Ниже этой скорости регулировка по кривизне больше не сбавляет. Порог не
# для красоты, без него формула сама себя загоняет в угол.
#
# Радиус r = v/w, то есть чем МЕДЛЕННЕЕ едешь, тем круче выглядит один и тот
# же поворот, тем сильнее сбавляет регулировка — и тем круче он выглядит на
# следующем кадре. Петля. Замерено на нашей же тележке: при v=0.16 и w=0.6
# регулировка отдаёт 0.053 м/с, то есть пять сантиметров в секунду, а это уже
# не «осторожно», а «стоим».
#
# В Nav2 на этом месте стоит regulated_linear_scaling_min_speed со значением
# 0.25 м/с. У нас 0.15: довод, ради которого сбавляют («не въезжай на ходу
# туда, куда не смотрел»), на пятнадцати сантиметрах в секунду попросту не
# работает — робот на такой скорости останавливается за ладонь.
СБАВЛЯЕМ_НЕ_НИЖЕ = 0.15

# Какие скорости перебираем, доли от разрешённой. Ноль обязателен: иногда
# правильный ответ — «повернуться на месте, не двигаясь».
#
# Долей стало больше после того, как появился отбор по тормозному пути: он
# ОТБРАСЫВАЕТ слишком быстрые дуги вместо того, чтобы их придерживать, и с
# четырьмя долями робот в тесноте проваливался с 0.38 сразу в ноль. Между
# «идти шагом» и «стоять» должно быть что-то ещё.
#
# Пятая, а не шестая: перебор идёт на каждом кадре, и каждая доля стоит
# примерно миллисекунды на этой плате. Круг цикла 67 мс, и отдавать половину
# его планировщику нельзя — робот начнёт запаздывать за человеком, а это та
# самая беда, ради которой всё и делалось.
ДОЛИ_СКОРОСТИ = (0.0, 0.15, 0.4, 0.7, 1.0)
# Какие повороты перебираем, рад/с. Плотнее у нуля: разница между «прямо» и
# «чуть левее» решает, а между «круто» и «очень круто» — уже нет.
ПОВОРОТЫ = (-1.0, -0.6, -0.35, -0.18, -0.08, 0.0,
            0.08, 0.18, 0.35, 0.6, 1.0)

# Веса в оценке. Подобраны так, чтобы приближение к цели решало, а остальное
# только разнимало ничьи.
ЗА_БЛИЗОСТЬ = 1.0        # насколько конец дуги ближе к цели, метры
# Штраф за тесноту. Не награда за простор, а именно штраф, и растёт он по мере
# приближения к корпусу — так дуга, проходящая впритирку, проигрывает
# заведомо, а две просторные не спорят между собой попусту.
ЗА_ТЕСНОТУ = 0.6
# Насколько круто штраф растёт при приближении к корпусу, 1/м.
#
# ШТРАФ ЭКСПОНЕНЦИАЛЬНЫЙ, и это не украшение. Раньше он был линейным с
# обрывом: ближе 0.35 м растём, дальше — ровный ноль. У такого штрафа есть
# слепая зона, и она оказалась там, где всё решается.
#
# На прогоне со стулом по осевой это выглядело так. Робот подходит: зазор
# 0.47 — штрафа нет, едем прямо на полной. Зазор 0.35 — штрафа всё ещё нет.
# Зазор 0.30 — штраф появился, но объезжать уже НЕЧЕМ: до стула 0.7 м, а
# тележке шириной сорок сантиметров, чтобы разъехаться, нужно уйти вбок на
# 0.38 м, и за оставшиеся полторы секунды на такой скорости она столько не
# уйдёт. Робот подползал и вставал.
#
# Отворачивать надо начинать РАНЬШЕ, чем стало тесно, — а для этого штраф
# обязан быть отличным от нуля и на просторе. Ровно это и делает инфляция
# костмапы в Nav2: cost = exp(-k·(d - r)), никакого обрыва, влияние
# препятствия убывает, но не исчезает.
#
# k = 3 подобрано прогонами: при нём стул на 1.2 м уже виден оценке (0.24
# против 0.19 у дуги, которая от него отворачивает), и этой разницы хватает,
# чтобы начать обходить с самого начала, а не в упор.
#
# Вес 0.6 подобран там же, перебором по восьми сценам и двум потолкам
# скорости. Он не на острие: и 0.45, и 0.75 дают то же поведение — меняется
# только величина крюка. Единственная сцена, чувствительная к весу, — стул
# ТОЧНО по осевой, где влево и вправо одинаково хороши; там тяжёлый штраф
# заставляет робота предпочесть остановку выбору стороны.
ТЕСНОТА_КРУЧЕ = 3.0
# Прежнее имя. Больше не порог, а только то расстояние, на котором штраф
# считается «заметным»; нужно проверкам и объяснениям.
ТЕСНО_ОТ = 0.35
# Награда за то, что вообще едем. Метров награды на метр проеханного пути.
#
# ЭТОГО СЛАГАЕМОГО НЕ БЫЛО, и это была не мелочь. В исходной формуле DWA
# (Фокс, Бургард, Трун) их три: близость к цели, простор и СКОРОСТЬ. Третье
# кажется лишним — «раз приближаемся, значит и едем», — и не является им.
#
# Ползти вперёд на пяти сантиметрах в секунду совершенно безопасно: простора
# полно (за полторы секунды никуда не доедешь), к цели всё-таки приближаешься,
# штрафовать не за что. А любая дуга, которая всерьёз обходит препятствие,
# ОБЯЗАНА подойти к нему ближе, чем ползанье на месте, — и проигрывает по
# простору. Робот выбирал ползти и вставал в полуметре от стула: оттуда
# объехать уже нельзя, тележке шириной сорок сантиметров нужно место для дуги.
#
# Ровно эта беда однажды уже чинилась весом за плавность, и вернулась с
# другой стороны, когда появился тормозной хвост. Лечится она не подкруткой
# штрафов, а тем, чего не хватало: наградой за ход.
#
# СЧИТАЕТСЯ В МЕТРАХ ПУТИ, и это не мелочь. Сперва здесь стояла доля от
# разрешённой скорости — v/потолок, — и на живом роботе это вышло боком в
# тот же вечер. Потолок ведь не постоянный: когда ехать вперёд незачем, он
# падает, и награда, делённая на маленький потолок, начинает стоить ДОРОЖЕ
# метра приближения. В журнале это выглядело так:
#
#   до_человека 0.65 м … близко ДА … вперёд 0.28
#
# То есть робот поехал НА человека, стоящего ближе, чем разрешено подходить.
# Никакое препятствие его не гнало: цель была нулевая, а награда за ход при
# потолке 0.275 стоила 1.21 за метр против 1.00 у близости к цели.
#
# В метрах пути такого не бывает по устройству: вес меньше единицы, значит
# уехать ОТ цели всегда дороже, чем стоять, — сколько бы ни было потолка.
# А ползанье по-прежнему проигрывает объезду: путь у него короткий, значит
# и награда маленькая.
ЗА_ХОД = 0.4
# Штраф за резкую смену поворота. Маленький нарочно.
#
# Сначала он был втрое больше и сравнивал метры в секунду с радианами в
# секунду одним весом. Выходило, что от неподвижности ЛЮБОЙ поворот выглядит
# резким, и робот, увидев стул точно по курсу, предпочитал «прямо, но
# медленно»: так он тоже приближается к цели. Кончалось это тем, что он
# подползал к стулу на полметра и вставал — объехать оттуда уже нельзя,
# тележке шириной сорок сантиметров нужно место для дуги.
#
# Проверено прогонами: со старым весом робот вставал в 0.5 м от стула, с
# новым обходит его и едет дальше.
ЗА_ПЛАВНОСТЬ = 0.05

ЦЕЛЬ_НЕ_ПРЕПЯТСТВИЕ = 0.45


def препятствия(сетка, поле_градусов: float = 60.0,
                ряды=range(2, 6)) -> list[tuple[float, float]]:
    """Сетка дальномера → точки (вперёд, вбок) в метрах, в системе робота.

    Берём средние ряды: верхние смотрят выше робота — люстра и притолока ему
    не мешают, — нижние упираются в пол, и считать пол препятствием значит не
    поехать никогда.
    """
    точки: list[tuple[float, float]] = []
    if not сетка:
        return точки
    колонок = len(сетка[0])
    for р in ряды:
        if р >= len(сетка):
            continue
        for к, д in enumerate(сетка[р]):
            if not д or д <= 0.0:
                continue
            # Колонка 0 — слева, колонка 7 — справа; влево угол положительный,
            # как у пеленга и у ROS.
            угол = math.radians(((колонок - 1) / 2.0 - к)
                                * (поле_градусов / колонок))
            точки.append((д * math.cos(угол), д * math.sin(угол)))
    return точки


def из_карты(карта, дальше: float = 1.2) -> list[tuple[float, float]]:
    """Занятые клетки карты памяти вокруг робота — тоже препятствия.

    Нужны для того, чего дальномер не видит физически: разъезжаясь со стулом,
    робот перестаёт его видеть ровно тогда, когда стул оказывается у него под
    боком. Карта помнит.
    """
    если_нет = []
    if карта is None:
        return если_нет
    точки = getattr(карта, "занятые_вокруг", None)
    if точки is None:
        return если_нет
    try:
        return [(x, y) for x, y in точки(дальше)]
    except Exception:                            # noqa: BLE001
        return если_нет


def проехать(v: float, w: float, t: float) -> tuple[float, float, float]:
    """Где окажется робот через t секунд, если ехать так. (вперёд, вбок, курс).

    Дуга, а не отрезок: робот с ненулевым поворотом едет по окружности, и
    прямая вместо неё — это ошибка ровно там, где она дороже всего, то есть
    на крутых объездах.
    """
    if abs(w) < 1e-6:
        return v * t, 0.0, 0.0
    радиус = v / w
    курс = w * t
    return радиус * math.sin(курс), радиус * (1.0 - math.cos(курс)), курс


def придержать(было: float, стало: float, за_сколько: float,
               разгон: float, замедление: float) -> float:
    """Не дать скорости прыгнуть ступенькой.

    Без этого команда меняется мгновенно: колёса срываются в
    проскальзывание — у меканума ролики к этому особенно склонны, — одометрия
    начинает врать, а человеку кажется, что робот дёргается.

    Тормозить разрешаем быстрее, чем разгоняться. Ограничивать торможение
    ради плавности значит продлевать тормозной путь: цена комфорта не может
    быть такой.

    Живёт ЗДЕСЬ, а не в follow, по одной причине: этой же функцией
    планировщик прокатывает пробные дуги. Если бы их было две, они однажды
    разошлись бы, и робот поехал бы не по той дуге, которую проверил.
    """
    if за_сколько <= 0:
        return стало
    вверх = разгон * за_сколько
    вниз = замедление * за_сколько
    if стало > было:
        return min(стало, было + вверх)
    return max(стало, было - вниз)


def по_кривизне(v: float, w: float,
                радиус_не_меньше: float = РАДИУС_НЕ_МЕНЬШЕ,
                не_ниже: float = СБАВЛЯЕМ_НЕ_НИЖЕ) -> float:
    """Сбавить ход на крутом повороте. Формула Nav2, довод наш.

    Радиус дуги r = v/w. Круче порога — умножаем скорость на r/r_min, то есть
    чем круче, тем медленнее; ровно на пороге множитель единица, и разрыва
    нет. (В Nav2 это записано как v·(1 − |r − r_min|/r_min); при r < r_min
    это то же самое число, просто длиннее.)

    Зачем это роботу, который и так тихоходный: он видит шестьдесят градусов
    вперёд и ничего по бокам. Крутой поворот на полном ходу — это въезд в
    непроверенное со скоростью, с которой оттуда уже не остановиться.
    """
    if v <= 0.0 or abs(w) < 1e-6:
        return v
    радиус = abs(v / w)
    if радиус >= радиус_не_меньше:
        return v
    сбавили = v * (радиус / радиус_не_меньше)
    # Ниже порога не опускаем — но и не ПОДНИМАЕМ то, что и так было ниже.
    return min(v, max(сбавили, не_ниже))


def по_близости(v: float, зазор: float,
                сбавлять_от: float = СБАВЛЯТЬ_БЛИЖЕ,
                не_ниже: float = СБАВЛЯЕМ_НЕ_НИЖЕ) -> float:
    """Сбавить ход рядом с препятствием. Вторая половина той же формулы Nav2.

    В regulated pure pursuit скорость режут ДВА независимых правила, и мы до
    сих пор взяли только одно. Первое — по крутизне поворота (по_кривизне),
    оно уже есть. Второе — по близости к препятствию: чем ближе стоит что-то
    к корпусу, тем ниже потолок скорости, линейно.

    Разница между этим и штрафом за тесноту в оценке — та же, что между
    потолком и советом. Штраф СРАВНИВАЕТ дуги между собой: он выберет самую
    просторную из имеющихся. Но если все они одинаково тесные — а в коридоре
    шириной в метр так и есть, — то лучшая из них поедет на полной скорости,
    потому что сравнивать не с чем. Потолок же не сравнивает ни с чем: тесно
    — значит медленно, и точка.

    Для нашего робота довод сильнее, чем для складской тележки. Он видит
    шестьдесят градусов вперёд, по бокам слеп, а всё, что ближе двадцати
    сантиметров от корпуса, дальномер уже не разрешает. Ехать быстро в
    полуметре от стены значит ехать быстро туда, где поправить курс негде.
    """
    if v <= 0.0 or зазор >= сбавлять_от:
        return v
    доля = max(0.0, зазор) / сбавлять_от
    return min(v, max(v * доля, не_ниже))


def прокатить(v_цель: float, w_цель: float,
              v0: float = 0.0, w0: float = 0.0, *,
              шагов: int = ШАГОВ, горизонт: float = ГОРИЗОНТ,
              разгон: float = РАЗГОН, сброс: float = СБРОС,
              разгон_поворота: float = РАЗГОН_ПОВОРОТА,
              торможение: float = ТОРМОЖЕНИЕ):
    """Где робот окажется, если СКОМАНДОВАТЬ (v_цель, w_цель) из (v0, w0).

    Выдаёт позы по одной, от ближней к дальней: (вперёд, вбок, курс, хвост).
    Последнее — признак того, что этот кусок уже тормозной.

    Выдаёт, а не отдаёт списком, нарочно. Проверка почти всегда обрывается
    досрочно — либо корпус во что-то вошёл, либо стало ясно, что хвост
    считать незачем, — и считать позы, которых никто не спросит, значит
    тратить круг цикла впустую.

    Две вещи, которых не делала прежняя прямая прокатка с постоянной
    скоростью.

    РАЗГОН. Колёса не прыгают на заданную скорость: между командой и ней
    стоит `придержать`. Прокатывая дугу постоянной скоростью, планировщик
    проверял траекторию, по которой робот НЕ ПОЕДЕТ, и ошибался в самую
    опасную сторону: от неподвижности поворот набирается за треть секунды, а
    ход — за секунду с лишним, то есть первый миг робот почти крутится на
    месте там, где ему обещали пологую дугу.

    ТОРМОЗНОЙ ХВОСТ. После горизонта скорость гасится настоящим замедлением,
    а поворот держится. Это и есть условие допустимости из DWA — «оставляем
    только те скорости, на которых робот способен остановиться», — записанное
    прокаткой вместо арифметики: так в него сам собой попадает поворот,
    которого в формуле v ≤ sqrt(2·d·a) нет.
    """
    шаг = горизонт / max(1, шагов)
    x = y = курс = 0.0
    v, w = v0, w0
    for _ in range(max(1, шагов)):
        v = придержать(v, v_цель, шаг, разгон, сброс)
        w = придержать(w, w_цель, шаг, разгон_поворота, разгон_поворота)
        x, y, курс = _шагнуть(x, y, курс, v, w, шаг)
        yield x, y, курс, False
    for _ in range(ХВОСТ_ШАГОВ):
        if v <= ПОЧТИ_СТОИМ:
            return
        v = max(0.0, v - торможение * шаг)
        x, y, курс = _шагнуть(x, y, курс, v, w, шаг)
        yield x, y, курс, True


def тормозной_путь(v: float, торможение: float = ТОРМОЖЕНИЕ) -> float:
    """Сколько метров робот проедет, если прямо сейчас начать тормозить."""
    if v <= 0:
        return 0.0
    return v * v / (2.0 * max(0.01, торможение))


def _шагнуть(x: float, y: float, курс: float,
             v: float, w: float, шаг: float) -> tuple[float, float, float]:
    """Один кусок дуги, приложенный к текущей позе."""
    дx, дy, дкурс = проехать(v, w, шаг)
    cos, sin = math.cos(курс), math.sin(курс)
    return x + дx * cos - дy * sin, y + дx * sin + дy * cos, курс + дкурс


def влезаем(x: float, y: float, курс: float,
            точки, полуширина: float, полудлина: float) -> float:
    """Насколько тесно в этой позе. Ноль и меньше — корпус во что-то вошёл.

    Отдаём не «да/нет», а ЗАПАС в метрах: планировщику мало знать, что
    проедет, — из двух проезжих дуг надо выбрать ту, что идёт просторнее.

    Корпус — прямоугольник, а не круг. Круг радиуса тридцать сантиметров
    (описанная окружность тележки) не пролезает в щель, в которую она
    проходит спокойно, и робот отказывался бы ехать по собственному коридору.
    """
    зазор = float("inf")
    cos, sin = math.cos(-курс), math.sin(-курс)
    for тx, тy in точки:
        # Точка в системе координат этой позы.
        дx, дy = тx - x, тy - y
        мx = дx * cos - дy * sin
        мy = дx * sin + дy * cos
        # Расстояние от точки до прямоугольника корпуса.
        вбок = abs(мy) - полуширина
        вдоль = abs(мx) - полудлина
        если_снаружи = math.hypot(max(вбок, 0.0), max(вдоль, 0.0))
        внутри = max(вбок, вдоль)
        зазор = min(зазор, если_снаружи if внутри > 0 else внутри)
    return зазор


def штраф_за_тесноту(зазор: float) -> float:
    """Насколько плоха дуга по близости к предметам. Формула инфляции Nav2.

    Убывает по экспоненте и НИКОГДА не обращается в ноль: препятствие в метре
    впереди должно чуть-чуть влиять на выбор уже сейчас, иначе робот поедет
    прямо на него и спохватится тогда, когда объезжать станет нечем.
    """
    return math.exp(-ТЕСНОТА_КРУЧЕ * max(0.0, зазор))


def без_цели(точки, до_цели: float, угол: float,
             радиус: float = ЦЕЛЬ_НЕ_ПРЕПЯТСТВИЕ):
    """Убрать из препятствий то, что стоит на месте цели.

    Дальномер не знает, что перед ним, и человек для него — обычное пятно.
    Оставить его в препятствиях значит велеть роботу от него уворачиваться:
    чем ближе подходит, тем теснее, тем сильнее хочется отвернуть. Робот
    кружил бы вокруг человека, не подходя.
    """
    if до_цели <= 0:
        return list(точки)
    цx, цy = до_цели * math.cos(угол), до_цели * math.sin(угол)
    return [(x, y) for x, y in точки
            if math.hypot(x - цx, y - цy) > радиус]


def выбрать(цель_дальше: float, цель_угол: float, точки,
            скорость_потолок: float, поворот_потолок: float,
            было_вперёд: float = 0.0, было_поворот: float = 0.0,
            запас: float = ЗАПАС):
    """Лучшая пара (вперёд, поворот) из перебора. И почему выбрана именно она.

    `цель_дальше` — сколько метров надо ПРОЕХАТЬ к цели (уже за вычетом
    желаемой дистанции). Ноль или меньше — ехать вперёд незачем, остаётся
    доворот.

    Возвращает (вперёд, поворот, объяснение). Все дуги упираются — вернём
    нули и скажем об этом: остановка с причиной лучше молчаливого ступора.
    """
    # Куда хотим попасть — точка в системе робота.
    цx = max(0.0, цель_дальше) * math.cos(цель_угол)
    цy = max(0.0, цель_дальше) * math.sin(цель_угол)
    до_цели_сейчас = math.hypot(цx, цy)

    # Точки, до которых за горизонт с тормозным хвостом всё равно не
    # дотянуться, в переборе не участвуют. Это не хитрость ради скорости, а
    # единственный способ уложиться в круг цикла: перебор идёт по всем дугам,
    # каждая по всем шагам, каждый шаг по всем точкам — и лишняя четверть
    # точек стоит лишней четверти времени на каждом кадре.
    дотуда = (max(скорость_потолок, abs(было_вперёд)) * (ГОРИЗОНТ + 1.0)
              + ПОЛУДЛИНА + ТЕСНО_ОТ + запас)
    точки = [(x, y) for x, y in точки if math.hypot(x, y) <= дотуда]

    лучшее = None
    лучший_счёт = -1e9
    уперлись = 0
    всего = 0
    for доля in ДОЛИ_СКОРОСТИ:
        for w in ПОВОРОТЫ:
            if abs(w) > поворот_потолок + 1e-9:
                continue
            всего += 1
            # Сбавляем на крутом ДО проверки, а не после. Проверить одну
            # скорость, а поехать с другой — это ровно та ошибка, из-за
            # которой затевалась прокатка с разгоном.
            v_кр = по_кривизне(скорость_потолок * доля, w)
            # Прокатываем дугу — с разгоном и с тормозным хвостом — и смотрим
            # самый тесный её кусок. Хвост означает: до полной остановки
            # корпус не должен задеть ничего. Дуга, на которой робот успевает
            # проехать полторы секунды и только потом упирается, теперь
            # отбрасывается, а не выбирается.
            теснее_всего = float("inf")
            конец = (0.0, 0.0, 0.0)
            # Насколько робот способен сдвинуться за весь тормозной хвост.
            # Больше чем на столько зазор при торможении не убавится, значит
            # хвост, начинающийся в просторном месте, считать незачем — и это
            # не приближение, а точная оценка сверху.
            хватит_простора = тормозной_путь(v_кр) + запас
            for x, y, курс, хвост in прокатить(v_кр, w, было_вперёд,
                                               было_поворот):
                if хвост and теснее_всего >= хватит_простора:
                    break
                if not хвост:
                    # Цель считаем по концу ХОДОВОЙ части: тормозной хвост —
                    # это не «куда я хочу приехать», а «где я встану, если
                    # сейчас же начну тормозить».
                    конец = (x, y, курс)
                зазор = влезаем(x, y, курс, точки, ПОЛУШИРИНА, ПОЛУДЛИНА)
                теснее_всего = min(теснее_всего, зазор)
                if теснее_всего < запас:
                    break
            if теснее_всего < запас:
                уперлись += 1
                continue

            x, y, _курс = конец
            до_цели_потом = math.hypot(цx - x, цy - y)
            приблизились = до_цели_сейчас - до_цели_потом
            теснота = штраф_за_тесноту(теснее_всего)
            # Плавность считаем ТОЛЬКО по повороту. Скорость и без того
            # сглаживается разгоном — теперь прямо внутри прокатки, — а
            # складывать метры в секунду с радианами в секунду одним весом —
            # это сравнивать несравнимое.
            дёрганье = abs(w - было_поворот)
            # Путь по дуге, а не скорость: награда обязана быть в тех же
            # метрах, что и близость к цели, иначе она однажды окажется
            # дороже её. Один раз уже оказалась.
            ход = math.hypot(x, y)
            счёт = (ЗА_БЛИЗОСТЬ * приблизились
                    + ЗА_ХОД * ход
                    - ЗА_ТЕСНОТУ * теснота
                    - ЗА_ПЛАВНОСТЬ * дёрганье)
            if счёт > лучший_счёт:
                # Потолок по близости накладываем ЗДЕСЬ, на уже выбранную
                # дугу, а не при переборе. Иначе сбавленная скорость
                # уменьшила бы и путь, и приближение к цели, и тесная дуга
                # проиграла бы просторной ещё и по счёту — то есть один и тот
                # же довод сработал бы дважды. Сравниваем дуги на равных, а
                # медленнее едем по той, что выбрали.
                лучший_счёт = счёт
                лучшее = (по_близости(v_кр, теснее_всего), w, теснее_всего)

    if лучшее is None:
        # Не осталось НИ ОДНОЙ проезжей дуги — даже неподвижной. Это значит,
        # что корпус уже задевает что-то или стоит к нему вплотную: робот
        # въехал носом.
        #
        # Раньше здесь возвращались нули, и на этом всё кончалось. Но нули —
        # худший из возможных ответов: положение само не исправится, а
        # пятиться нельзя, сзади слепая зона. Разворот же уводит углы корпуса
        # ВБОК от того, во что уперся нос, и это единственное движение,
        # которое тут вообще осталось.
        return (0.0, обход(точки, цель_угол, было_поворот),
                f"все {всего} дуг упираются; разворачиваюсь")
    v, w, зазор = лучшее
    почему = f"зазор {зазор:.2f} м, отброшено {уперлись} из {всего}"
    if v <= 0.0 and уперлись >= всего - ХОДОВЫХ_ХВАТИТ:
        # УПЁРСЯ — ИЩЕМ ОБХОД, а не сообщаем о неудаче. Ходовых дуг почти не
        # осталось: впереди стена, косяк или угол.
        #
        # Раньше здесь возвращались нули, и робот вставал столбом. Со стороны
        # это «сломался»: он видит препятствие, знает про него, говорит о нём
        # вслух — и не делает ровно того единственного, что мог бы сделать.
        #
        # А сделать он может: развернуться. Вращение на месте не требует
        # места впереди, ему нужен только круг, который заметает корпус, и
        # этот круг проверяется отдельно. Повернувшись, робот увидит другое —
        # шестьдесят градусов дальномера это узкая щёлка, и выход чаще всего
        # просто вне её.
        #
        # Куда крутиться, решаем по тому, где просторнее: считаем сумму
        # зазоров слева и справа от осевой. Это грубо и этого достаточно —
        # выбрать надо не лучший угол, а сторону.
        return 0.0, обход(точки, цель_угол, было_поворот), почему + "; ищу обход"
    if v <= 0.0:
        # Ноль вперёд при живых дугах — это не «нечего делать», а «ехать
        # незачем или некуда». Без этой приписки в журнале остаётся бодрое
        # «зазор 0.37 м» рядом с неподвижным роботом, и человек ищет поломку
        # там, где её нет.
        почему += "; вперёд не еду"
    return v, w, почему


def обход(точки, цель_угол: float, было_поворот: float = 0.0) -> float:
    """С какой скоростью доворачиваться, выбираясь из тупика. Рад/с.

    Не «крутись, пока не станет лучше», а поворот К НАЙДЕННОМУ свободному
    направлению — и потому затухающий: чем ближе робот к нему, тем медленнее
    крутится, а на месте останавливается сам. В патентах iRobot это записано
    как «повернуть на минимальный угол, попадающий в допустимый диапазон».

    Ничего свободного не видно вовсе (коробка со всех сторон) — крутимся в
    сторону цели. Стоять из-за того, что все стороны одинаково плохи, — это
    ровно тот случай, когда робот застревает навсегда.
    """
    куда = куда_свободнее(точки)
    if abs(куда) < 1e-6:
        куда = цель_угол if abs(цель_угол) > 1e-6 else math.radians(СЕКТОР)
    # СТОРОНУ ВЫБИРАЕМ ОДИН РАЗ И ДЕРЖИМСЯ ЕЁ, пока крутимся. В патентах
    # iRobot режим поворота так и описан: «выполняет поворот по часовой или
    # против часовой стрелки», сторона одна на весь манёвр.
    #
    # Без этого выходило метание. Робот довернулся к свободному сектору,
    # увидел проезжую дугу, поехал, снова упёрся — и свободным теперь
    # оказался сектор с ДРУГОЙ стороны, потому что картина сменилась. В
    # прогоне «носом в стену» он накрутил 184 градуса и остался на прежнем
    # курсе: ровно туда и обратно.
    #
    # Дожать начатый разворот всегда лучше, чем передумать на полпути:
    # выбранная сторона хотя бы куда-то ведёт, а метание не ведёт никуда.
    if abs(было_поворот) > КРУТИМСЯ_ОТ and куда * было_поворот < 0:
        куда = math.copysign(куда, было_поворот)
    сколько = ПО_УГЛУ_ОБХОДА * куда
    return max(-ИЩЕМ_ОБХОД, min(ИЩЕМ_ОБХОД, сколько))


def куда_свободнее(точки) -> float:
    """На какой угол довернуть, чтобы смотреть в самое свободное место.

    Радианы, положительное — влево. Ноль — разницы не видно.

    ЗАЧЕМ ЭТО ВМЕСТО ПРОСТОГО «КРУТИСЬ ВЛЕВО». В патентах iRobot режим
    поворота описан так: вычислить допустимый диапазон новых направлений и
    повернуть на МИНИМАЛЬНЫЙ угол, попадающий в него. Разница с «крутись,
    пока не станет лучше» не в изяществе, а в двух вещах.

    Первая: минимальный поворот — это минимальное время, когда робот слеп в
    ту сторону, куда поворачивается. Второе: поворот, у которого есть цель,
    сам собой затухает по мере приближения к ней, и робот не проскакивает
    свободное направление, чтобы потом возвращаться. В прогоне по углу
    комнаты «крутись в сторону, где просторнее» давало разворот на двести
    градусов там, где хватило бы восьмидесяти.

    Считаем по секторам в тридцать градусов: для каждого берём самую БЛИЗКУЮ
    точку в нём (сектор хорош ровно настолько, насколько плох его худший
    участок) и выбираем сектор, где эта близкая точка дальше всех. Пустой
    сектор — лучший из возможных: там не видно ничего.
    """
    ЛУЧШЕЕ_ПУСТО = 99.0
    сектора: dict[int, float] = {}
    for x, y in точки:
        угол = math.degrees(math.atan2(y, x))
        if abs(угол) > ОГЛЯДЫВАЕМСЯ_НА:
            continue
        номер = int(round(угол / СЕКТОР))
        далеко = math.hypot(x, y)
        сектора[номер] = min(сектора.get(номер, ЛУЧШЕЕ_ПУСТО), далеко)
    сколько = int(ОГЛЯДЫВАЕМСЯ_НА / СЕКТОР)
    лучший, лучше_всего = None, -1.0
    # Идём от середины наружу, чтобы при равенстве побеждал БЛИЖНИЙ к курсу
    # сектор: это и есть «минимальный поворот».
    for шаг in range(сколько + 1):
        for номер in ((0,) if шаг == 0 else (-шаг, шаг)):
            место = сектора.get(номер, ЛУЧШЕЕ_ПУСТО)
            if место > лучше_всего:
                лучший, лучше_всего = номер, место
    if лучший is None:
        return 0.0
    return math.radians(лучший * СЕКТОР)


def куда_просторнее(точки) -> float:
    """+1 налево, -1 направо, 0 — не видно разницы.

    Считаем не «где ближайшее дальше», а СКОЛЬКО МЕСТА с каждой стороны:
    берём точки левее и правее осевой и складываем их удалённость. Одна
    близкая точка слева при пустоте за ней не должна перевешивать плотную
    стену справа — а по минимуму перевесила бы.

    Точки прямо по курсу в счёт не идут: они мешают одинаково обеим сторонам
    и только размывают разницу.
    """
    слева = справа = 0.0
    for x, y in точки:
        если_прямо = abs(y) < ПОЛУШИРИНА
        if если_прямо:
            continue
        далеко = math.hypot(x, y)
        if y > 0:
            слева += далеко
        else:
            справа += далеко
    if abs(слева - справа) < 1e-6:
        return 0.0
    return 1.0 if слева > справа else -1.0


# --- движение вдоль края (Edge mode у iRobot) --------------------------------
# На каком расстоянии от корпуса ведём стену. Тридцать сантиметров: ближе —
# любая неровность обоев цепляет угол, дальше — робот теряет стену из виду,
# потому что дальномер смотрит вперёд, а не вбок, и край поля зрения ловит
# стену лишь пока она рядом.
ВЕДЁМ_СТЕНУ = 0.30
# Докуда впереди считаем точку частью «нашей» стены. Полтора метра: дальше
# это уже не стена, вдоль которой едем, а что-то, до чего ещё доехать надо.
СТЕНУ_ВИДИМ_ДО = 1.5
# И насколько вбок. Метр: дальше вести нечего — робот всё равно не удержит
# на таком отдалении стену в поле зрения, дальномер смотрит вперёд.
СТЕНА_НЕ_ДАЛЬШЕ = 1.0
# Сколько рад/с на метр ошибки по расстоянию до стены.
К_СТЕНЕ = 2.0
# Быстрее этого вдоль стены не едем. Медленно нарочно: робот идёт боком к
# тому, чего почти не видит.
ВДОЛЬ_СТЕНЫ_НЕ_БЫСТРЕЕ = 0.20


def найти_стену(точки, сторона: float):
    """Ближайшая точка стены с этой стороны: (вбок, вперёд). None — нет стены.

    `сторона`: +1 слева, -1 справа.

    Берём не «что ровно сбоку», а сектор впереди-сбоку. Точка ровно сбоку
    говорит, где стена БЫЛА, когда робот с ней поравнялся; точка впереди-сбоку
    говорит, куда стена поворачивает. Второе и нужно, чтобы вписаться в угол,
    а не срезать его корпусом.
    """
    ближе, откуда = None, None
    for x, y in точки:
        если_с_той_стороны = y * сторона > 0
        if not если_с_той_стороны:
            continue
        # Ни сзади (там слепая зона, вести оттуда нечего), ни слишком далеко
        # впереди: стена в двух метрах — это ещё не та стена, вдоль которой
        # мы едем.
        if not (-ПОЛУДЛИНА < x < СТЕНУ_ВИДИМ_ДО):
            continue
        if abs(y) > СТЕНА_НЕ_ДАЛЬШЕ:
            continue
        if ближе is None or abs(y) < ближе:
            ближе, откуда = abs(y), x
    if ближе is None:
        return None
    return ближе, откуда


def вдоль_стены(точки, сторона: float, потолок: float = ВДОЛЬ_СТЕНЫ_НЕ_БЫСТРЕЕ,
                держать: float = ВЕДЁМ_СТЕНУ):
    """Ехать вдоль края препятствия. (вперёд, поворот, объяснение).

    ЗАЧЕМ. Разворот выводит робота из угла, но не из-за длинной стены: он
    отворачивается, находит просвет, едет, снова упирается в ту же стену и
    снова отворачивается. В прогоне «носом в стену» это давало 223 градуса
    накрученных при смене курса на 47 — робот метался и никуда не приезжал.

    У iRobot на этот случай отдельный режим (Edge): двигаться вдоль края
    препятствия, что «позволяет пройти в наименьшее возможное отверстие и
    выбраться из замкнутого пространства». Стена рано или поздно кончается —
    дверью, проходом или углом, — и это единственный способ её обойти, не
    видя всей комнаты.

    Держим постоянное расстояние простым пропорциональным законом: ближе
    нужного — отворачиваем от стены, дальше — подворачиваем к ней. ПИД тут
    незачем, скорость мала и инерция тележки тоже.

    Стену потеряли — значит она кончилась. Это УСПЕХ, а не сбой: ради этого
    вдоль неё и ехали. Отвечаем нулями, и вызывающий сам решит, что дальше.
    """
    найдено = найти_стену(точки, сторона)
    if найдено is None:
        return 0.0, 0.0, "стена кончилась"
    вбок, вперёд_до = найдено
    ошибка = вбок - держать
    # Знак: слева (сторона +1) стена далеко — подворачиваем ВЛЕВО, то есть
    # положительный поворот. Справа всё зеркально.
    поворот = сторона * К_СТЕНЕ * ошибка
    поворот = max(-ИЩЕМ_ОБХОД * 2, min(ИЩЕМ_ОБХОД * 2, поворот))
    # Скорость — обычным потолком по близости: впереди-сбоку стена, и лететь
    # вдоль неё незачем.
    v = по_близости(потолок, max(0.0, вперёд_до - ПОЛУДЛИНА))
    v = по_кривизне(v, поворот)
    сторона_словом = "слева" if сторона > 0 else "справа"
    return (v, поворот,
            f"иду вдоль стены {сторона_словом}, до неё {вбок:.2f} м")


# --- кто решает, что делать в тупике -----------------------------------------
# Сколько секунд разворачиваемся, прежде чем признать, что разворот не помог.
# Три: за это время робот при осторожном повороте проходит больше семидесяти
# градусов, то есть успевает заглянуть за край поля зрения дальномера в обе
# стороны. Не помогло за три секунды — не поможет и за десять.
КРУТИМСЯ_НЕ_ДОЛЬШЕ = 3.0
# Сколько ведём стену, прежде чем сдаться. Двадцать секунд: на скорости
# 0.15 м/с это три метра стены — длина обычной комнаты. Не нашли выход за
# длину комнаты — значит его нет там, где мы искали.
ВДОЛЬ_СТЕНЫ_НЕ_ДОЛЬШЕ = 20.0
# Сколько стоим и ждём, прежде чем что-то предпринимать. Секунда: помехой мог
# оказаться человек, кот или дверь, и все трое уходят сами. Nav2 держит в
# своём наборе такое же «подождать» именно поэтому. Дольше секунды ждать
# нельзя — тот, за кем идём, уйдёт.
ЖДЁМ_СЕКУНДУ = 1.0
# Сколько кадров подряд надо ехать, чтобы счесть, что выбрались. Восемь — это
# полсекунды на нашем цикле: меньше бывает и просто просветом, мелькнувшим
# краем поля зрения при развороте.
ПОДТВЕРДИТЬ_ВЫХОД = 8

# --- отъезд по своему следу ---------------------------------------------
# ПЯТИТЬСЯ ВСЛЕПУЮ РОБОТУ НЕЛЬЗЯ — сзади у него слепая зона, и об этом
# написано в шапке файла. Но «назад по следу, который сам же проехал минуту
# назад» — это не вслепую: тот метр пола робот только что физически занимал
# собственным корпусом, и если он там проехал, то проедет и обратно.
#
# ЗАЧЕМ ЭТО ПОНАДОБИЛОСЬ. В живом обходе робот упёрся носом в стену — вся
# сетка дальномера, все шестьдесят четыре зоны, читалась 0.13-0.16 м — и
# ПЯТНАДЦАТЬ СЕКУНД честно вёл «стену слева», давя на колёса, которые не
# крутились. Ни одно из четырёх прежних средств тут не работает: забывать
# нечего (стена настоящая), ждать нечего (стена не уйдёт), развернуться
# нельзя (упёршись носом, робот цепляет углом корпуса), вдоль стены не
# поедешь (чтобы ехать вдоль, надо сперва от неё отлипнуть).
#
# Отъезд стоит ПЕРВЫМ, потому что он единственный, кто возвращает роботу
# место для манёвра. Остальные три без него бессильны.
#
# Скорость нарочно вдвое ниже ходовой: назад робот не видит, и весь его
# запас безопасности здесь — короткий путь и малая скорость.
ОТЪЕЗЖАЮ_НЕ_БЫСТРЕЕ = 0.08
# Дальше этого не пятимся ни при каком запасе следа. Двадцать сантиметров —
# это ровно «отлипнуть от стены и получить место, чтобы развернуться».
ОТСТУП_НЕ_ДАЛЬШЕ = 0.20
# Ближе этого отъезд не стоит манёвра: пять сантиметров ничего не меняют, а
# движение назад — самое рискованное, что робот умеет.
ОТСТУП_СТОИТ_ТОГО = 0.05


class Выбираюсь:
    """Что делать, когда ехать некуда. Робот решает сам, по обстановке.

    ЗАЧЕМ ОТДЕЛЬНЫЙ РЕШАТЕЛЬ, а не одно зашитое действие. Тупики разные, и
    лечатся они разным:

      • померещилось — предмет есть только в памяти. Лечится забыванием, и
        никакое движение тут не нужно вовсе;
      • кто-то встал на дороге — человек, кот, приоткрытая дверь. Лечится
        ожиданием: помеха уходит сама;
      • въехал в угол — выход есть, просто не по курсу. Лечится разворотом;
      • упёрся в длинную стену — разворот НЕ ЛЕЧИТ. Робот отвернётся, найдёт
        просвет, поедет, снова упрётся в ту же стену и снова отвернётся. В
        прогоне это давало 223 градуса накрученных при смене курса на 47.
        Лечится движением вдоль края, пока стена не кончится.

    Одного средства на все четыре беды нет, поэтому здесь их четыре, и робот
    перебирает их сам, от дешёвого к дорогому: забыть → подождать →
    развернуться → идти вдоль стены. Порядок тот же, что у Nav2, с одной
    заменой: вместо «попятиться», которое нам запрещено слепой зоной, стоит
    «идти вдоль стены», которое у iRobot зовётся Edge mode.

    ПОЧЕМУ ЭТО РЕШАЕТ НЕ МОДЕЛЬ. Соблазн отдать выбор языковой модели большой
    и ошибочный: она отвечает секунды, а решение нужно пятнадцать раз в
    секунду, причём в тот самый миг, когда робот уже упёрся. Модель здесь
    опоздала бы ровно настолько, чтобы её совет стал бесполезен. Разделение
    то же, что во всём остальном роботе: правила решают быстрое, модель —
    медленное и редкое. Зато решатель ГОВОРИТ, что делает, и человеку слышно,
    почему робот ведёт себя именно так.
    """

    ЗАБЫЛ = "забыл"
    ОТЪЕХАТЬ = "отъезжаю"
    ЖДУ = "жду"
    КРУЧУСЬ = "кручусь"
    ВДОЛЬ = "вдоль стены"
    СДАЛСЯ = "сдался"

    def __init__(self, часы=None) -> None:
        self._часы = часы or (lambda: __import__("time").monotonic())
        self.начал = 0.0
        self.что = ""
        self.сторона = 0.0
        self._отъезд_до = 0.0
        self._отъезжали = False

    def сбросить(self) -> None:
        """Выехали — забываем, что выбирались."""
        self.начал = 0.0
        self.что = ""
        self.сторона = 0.0
        self._проехали = 0
        self._отъезд_до = 0.0
        self._отъезжали = False

    def едем(self) -> None:
        """Планировщик нашёл проезжую дугу. Может быть, выбрались.

        «Может быть» — не осторожность, а вывод из прогона. Разворачиваясь,
        робот то и дело видит проезжую дугу: повернулся на десять градусов,
        краем поля зрения поймал просвет — дуга есть. Бросить манёвр в этот
        миг значит поехать в просвет, тут же снова упереться и начать
        выбираться заново. В прогоне это выглядело как «жду → кручусь → жду →
        кручусь» без конца: робот не выбирался, а топтался.

        Поэтому выход надо ПОДТВЕРДИТЬ несколькими кадрами подряд. Полсекунды
        уверенной езды — это уже не блик в просвете.
        """
        if not self.что:
            return
        self._проехали += 1
        if self._проехали >= ПОДТВЕРДИТЬ_ВЫХОД:
            self.сбросить()

    @property
    def выбираюсь(self) -> bool:
        return bool(self.что)

    def сколько_уже(self) -> float:
        return self._часы() - self.начал if self.начал else 0.0

    def решить(self, точки, цель_угол: float, было_поворот: float = 0.0,
               отступ: float = 0.0):
        """Что делать сейчас: (вперёд, поворот, что_делаю, вслух).

        `отступ` — сколько метров назад роботу МОЖНО отъехать: длина следа,
        который он только что проехал сам. Ноль (и это по умолчанию) значит
        «нельзя», и тогда лестница ведёт себя ровно как прежде. Считает его
        тот, у кого есть одометрия, — здесь её нет и не должно быть.

        `вслух` — пусто, если говорить нечего. И почти всегда нечего: ВСЛУХ
        ГОВОРИМ ТОЛЬКО КОГДА СДАЛИСЬ.

        Раньше говорилось на каждой смене занятия — «осмотрюсь», «пойду вдоль
        стены», «стена кончилась». Смены занятия идут по кругу, и в живом
        журнале за одну минуту вышло вот что:

            Мне некуда ехать, осмотрюсь.        ×6
            Не могу развернуться, вокруг тесно. ×6
            Развернуться не вышло, пойду вдоль стены. ×4
            Стена кончилась, иду дальше.        ×2

        Восемнадцать реплик за минуту про одно и то же застревание. Игорь на
        это и сказал: «не нужно ему ещё озвучивать каждое действие, пусть как
        финиш только». И он прав не только про раздражение: робот, который
        комментирует каждый свой шаг, заглушает сам себя — за этим потоком не
        слышно того единственного раза, когда он правда просит помощи.

        Занятия при этом идут в журнал как шли: разбирать поведение по
        записям надо, а вот озвучивать промежуточные состояния — нет.
        """
        сейчас = self._часы()
        сказать = ""
        self._проехали = 0
        if not self.что:
            self.начал = сейчас
            self.что = self.ЗАБЫЛ

        прошло = сейчас - self.начал

        # ОТЪЕЗД ВКЛИНИВАЕТСЯ В ЛЮБОЙ МОМЕНТ, а не только в начале, и это не
        # вольность. Упереться носом можно и на пятнадцатой секунде «иду вдоль
        # стены» — именно так и было в живом обходе. Остальные три средства
        # тогда бессильны: пока робот прижат, ему негде повернуть.
        #
        # Один раз за попытку. Если отъезд не помог, второй отъезд не поможет
        # тоже, а вот выпятиться из комнаты задом он вполне способен.
        if (отступ >= ОТСТУП_СТОИТ_ТОГО and not self._отъезжали
                and self.что != self.ОТЪЕХАТЬ and self.что != self.СДАЛСЯ):
            метров = min(отступ, ОТСТУП_НЕ_ДАЛЬШЕ)
            self._отъезжали = True
            self.что = self.ОТЪЕХАТЬ
            self.начал = сейчас
            self._отъезд_до = сейчас + метров / ОТЪЕЗЖАЮ_НЕ_БЫСТРЕЕ
            log.info("выбираюсь: упёрся и не еду — отъезжаю на %.2f м "
                     "по своему следу", метров)

        if self.что == self.ОТЪЕХАТЬ:
            if сейчас < self._отъезд_до:
                # Строго прямо. Поворачивая на ходу назад, робот выносит корму
                # вбок — туда, куда он не смотрел ни разу.
                return -ОТЪЕЗЖАЮ_НЕ_БЫСТРЕЕ, 0.0, self.ОТЪЕХАТЬ, сказать
            # Отъехали. Дальше — обычная лестница с самого начала: место для
            # манёвра появилось, и разворот теперь может и сработать.
            self.что = self.ЖДУ
            self.начал = сейчас
            прошло = 0.0

        if self.что == self.ЗАБЫЛ:
            # Забывание мгновенно — оно уже случилось у вызывающего. Сразу
            # переходим к ожиданию: если предмета не было, следующий круг
            # найдёт проезжую дугу и всё это кончится само.
            self.что = self.ЖДУ
            self.начал = сейчас
            прошло = 0.0

        if self.что == self.ЖДУ:
            if прошло < ЖДЁМ_СЕКУНДУ:
                return 0.0, 0.0, self.ЖДУ, сказать
            self.что = self.КРУЧУСЬ
            self.начал = сейчас
            прошло = 0.0
            log.info("выбираюсь: некуда ехать — осматриваюсь")

        if self.что == self.КРУЧУСЬ:
            if прошло < КРУТИМСЯ_НЕ_ДОЛЬШЕ:
                return (0.0, обход(точки, цель_угол, было_поворот),
                        self.КРУЧУСЬ, сказать)
            # Разворот не помог. Значит дело не в курсе, а в стене.
            self.что = self.ВДОЛЬ
            self.начал = сейчас
            прошло = 0.0
            # Сторону выбираем ОДИН раз: ту, с которой стена ближе. Вести
            # надо ту стену, в которую упёрлись, а не противоположную.
            слева = найти_стену(точки, 1.0)
            справа = найти_стену(точки, -1.0)
            if слева and справа:
                self.сторона = 1.0 if слева[0] <= справа[0] else -1.0
            elif слева:
                self.сторона = 1.0
            elif справа:
                self.сторона = -1.0
            else:
                self.сторона = 1.0 if цель_угол >= 0 else -1.0
            log.info("выбираюсь: разворот не помог — иду вдоль стены %s",
                     "слева" if self.сторона > 0 else "справа")

        if self.что == self.ВДОЛЬ:
            if прошло >= ВДОЛЬ_СТЕНЫ_НЕ_ДОЛЬШЕ:
                self.что = self.СДАЛСЯ
                return 0.0, 0.0, self.СДАЛСЯ, "Не могу выбраться, помоги."
            v, w, _почему = вдоль_стены(точки, self.сторона)
            if v <= 0.0 and abs(w) < 1e-6:
                # Стена кончилась — ради этого и шли. Начинаем заново: пусть
                # обычный перебор дуг попробует ехать к цели.
                self.сбросить()
                log.info("выбираюсь: стена кончилась — пробую ехать к цели")
                return 0.0, 0.0, "", ""
            return v, w, self.ВДОЛЬ, сказать

        return 0.0, 0.0, self.СДАЛСЯ, сказать
