def время_в(город: str, сейчас=None) -> str:
    """Который час в городе. None вместо города — значит, города нет в списке."""
    import datetime as _dt

    ключ = (город or "").strip().lower().replace("ё", "е")
    смещение = ПОЯСА.get(ключ)
    if смещение is None:
        return ""
    сейчас = сейчас or _dt.datetime.now(_dt.timezone.utc)
    там = сейчас.astimezone(_dt.timezone(_dt.timedelta(hours=смещение)))
    return f"{_в(город)} {город.capitalize()} сейчас {ru.clock(там)}."


# Перед стечением согласных предлог удлиняется: «во Владивостоке», а не «в
# Владивостоке». Робот это произносит вслух, и разница слышна сразу.
_ВО = ("вл", "вр", "вс", "вт", "вн", "вз", "вш", "вб", "вк", "вп", "вф", "вц",
       "вч", "фр", "фл", "мн", "льв")


def _в(город: str) -> str:
    начало = (город or "").strip().lower().replace("ё", "е")[:2]
    return "Во" if начало in _ВО else "В"


# --- жребий ----------------------------------------------------------------

СТОРОНЫ = ("Орёл", "Решка")


def монетка(бросок=None) -> str:
    выбор = (бросок or random.choice)(list(СТОРОНЫ))
    return f"{выбор}."


def кубик(граней: int = 6, бросок=None) -> str:
    граней = max(2, min(100, int(граней or 6)))
    выпало = (бросок or random.randint)(1, граней)
    return f"{выпало}." if граней == 6 else f"{выпало} из {граней}."


def число(снизу: int = 1, сверху: int = 10, бросок=None) -> str:
    снизу, сверху = int(снизу), int(сверху)
    if снизу > сверху:
        снизу, сверху = сверху, снизу
    выпало = (бросок or random.randint)(снизу, сверху)
    return f"{выпало}."


# --- меры ------------------------------------------------------------------
#
# «Сколько сантиметров в метре» модель знает и так, но на «переведи двести
# граммов в фунты» начинает считать в уме — и промахивается там же, где всегда:
# в делении. Здесь таблица, а не память.

# Всё сводим к базовой единице своего рода: метру, килограмму, литру, градусу.
_МЕРЫ: dict[str, tuple[str, float, tuple[str, str, str]]] = {}


def _мера(род: str, сколько: float, формы: tuple[str, str, str],
          *ещё: str) -> None:
    """Формы — «метр, метра, метров»: числа робот произносит вслух."""
    for имя in (*формы, *ещё):
        _МЕРЫ[имя.replace("ё", "е")] = (род, сколько, формы)


_мера("длина", 0.001, ("миллиметр", "миллиметра", "миллиметров"), "мм")
_мера("длина", 0.01, ("сантиметр", "сантиметра", "сантиметров"), "см")
_мера("длина", 1.0, ("метр", "метра", "метров"), "м")
_мера("длина", 1000.0, ("километр", "километра", "километров"), "км")
_мера("длина", 0.0254, ("дюйм", "дюйма", "дюймов"))
_мера("длина", 0.3048, ("фут", "фута", "футов"))
_мера("длина", 1609.34, ("миля", "мили", "миль"))
_мера("вес", 0.001, ("грамм", "грамма", "граммов"), "г")
_мера("вес", 1.0, ("килограмм", "килограмма", "килограммов"), "кг")
_мера("вес", 1000.0, ("тонна", "тонны", "тонн"))
_мера("вес", 0.4536, ("фунт", "фунта", "фунтов"))
_мера("объем", 0.001, ("миллилитр", "миллилитра", "миллилитров"), "мл")
_мера("объем", 1.0, ("литр", "литра", "литров"), "л")
_мера("время", 1.0, ("секунда", "секунды", "секунд"))
_мера("время", 60.0, ("минута", "минуты", "минут"))
_мера("время", 3600.0, ("час", "часа", "часов"))
_мера("время", 86400.0, ("день", "дня", "дней"), "сутки", "суток")


def _основа(формы: tuple[str, str, str]) -> str:
    """Общее начало трёх форм: «метр», «мил», «минут». По нему и ищем."""
    первая = формы[0]
    for длина in range(len(первая), 2, -1):
        начало = первая[:длина]
        if all(ф.startswith(начало) for ф in формы):
            return начало
    return первая[:3]


# Падежей у мер много («в метре», «в минутах», «пять футов»), перечислять их
# все — верный способ забыть один. Ищем по общему началу форм, от длинного к
# короткому: «миллиметр» найдётся раньше, чем «метр».
_ОСНОВЫ = sorted(
    {_основа(значение[2]): значение for значение in _МЕРЫ.values()}.items(),
    key=lambda пара: len(пара[0]), reverse=True)


def _найти(имя: str):
    точно = _МЕРЫ.get(имя)
    if точно is not None:
        return точно
    for основа, значение in _ОСНОВЫ:
        if имя.startswith(основа):
            return значение
    return None


def перевести(сколько: float, из_чего: str, во_что: str) -> str:
    """«Двести граммов в фунтах». Разные рода мер не смешиваем."""
    из_чего = (из_чего or "").strip().lower().replace("ё", "е")
    во_что = (во_что or "").strip().lower().replace("ё", "е")
    первая, вторая = _найти(из_чего), _найти(во_что)
    if первая is None or вторая is None:
        какая = из_чего if первая is None else во_что
        return f"Не знаю такой меры — {какая}."
    if первая[0] != вторая[0]:
        return f"{первая[0].capitalize()} в {вторая[0]} не перевести."
    ответ = float(сколько) * первая[1] / вторая[1]
    # Вслух четыре знака после запятой не нужны: «три и одна десятая мили»
    # человек поймёт, «три целых одна тысяча шестьдесят девять» — нет.
    ответ = round(ответ, 2) if abs(ответ) >= 0.01 else round(ответ, 5)
    # Дробное число по-русски требует родительного падежа единственного:
    # «одна целая шесть километрА», а не «километр» и не «километров».
    имя = (вторая[2][1] if ответ != int(ответ)
           else ru.plural(int(ответ), *вторая[2]))
    return f"{вслух(ответ)} {имя}."


def выбрать(из_чего: list[str], бросок=None) -> str:
    варианты = [с.strip() for с in из_чего if с and с.strip()]
    if not варианты:
        return "Не из чего выбирать."
    if len(варианты) == 1:
        return f"Выбирать не из чего, только {варианты[0]}."
    return f"{(бросок or random.choice)(варианты)}."
