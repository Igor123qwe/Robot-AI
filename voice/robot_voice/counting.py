def время_в(город: str, сейчас=None) -> str:
    """Который час в городе. Пусто — города нет в списке."""
    import datetime as _dt
    from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

    ключ = (город or "").strip().lower().replace("ё", "е")
    запись = ПОЯСА.get(ключ)
    if запись is None:
        return ""
    имя_пояса, вслух_город = запись
    try:
        пояс = ZoneInfo(имя_пояса)
    except (ZoneInfoNotFoundError, ValueError):
        # Базы поясов в системе нет. Соврать на час хуже, чем признаться.
        log.warning("нет часового пояса %s — не скажу время в городе", имя_пояса)
        return ""
    сейчас = сейчас or _dt.datetime.now(_dt.timezone.utc)
    # Город произносим в предложном падеже и берём его из таблицы, а не из
    # услышанного: модель зовёт инструмент именительным, и робот говорил
    # «в Москва сейчас». Падежи русских городов правилом не выводятся.
    return f"{_в(вслух_город)} {вслух_город} сейчас {ru.clock(сейчас.astimezone(пояс))}."


# Перед стечением согласных предлог удлиняется: «во Владивостоке», а не «в
# Владивостоке». Робот это произносит вслух, и разница слышна сразу.
_ВО = ("вл", "вр", "вс", "вт", "вн", "вз", "вш", "вб", "вк", "вп", "вф", "вц",
       "вч", "фр", "фл", "мн", "льв")


def _в(город: str) -> str:
    начало = (город or "").strip().lower().replace("ё", "е")[:2]
    return "Во" if начало in _ВО else "В"


# --- жребий ----------------------------------------------------------------

СТОРОНЫ = ("Орёл", "Решка")


def монетка(бросок=None) -> str:
    выбор = (бросок or random.choice)(list(СТОРОНЫ))
    return f"{выбор}."


def кубик(граней: int = 6, бросок=None) -> str:
    граней = max(2, min(100, int(граней or 6)))
    выпало = (бросок or random.randint)(1, граней)
    return f"{выпало}." if граней == 6 else f"{выпало} из {граней}."


def число(снизу: int = 1, сверху: int = 10, бросок=None) -> str:
    снизу, сверху = int(снизу), int(сверху)
    if снизу > сверху:
        снизу, сверху = сверху, снизу
    выпало = (бросок or random.randint)(снизу, сверху)
    return f"{выпало}."


# --- меры ------------------------------------------------------------------
#
# «Сколько сантиметров в метре» модель знает и так, но на «переведи двести
# граммов в фунты» начинает считать в уме — и промахивается там же, где всегда:
# в делении. Здесь таблица, а не память.

# Всё сводим к базовой единице своего рода: метру, килограмму, литру, градусу.
_МЕРЫ: dict[str, tuple[str, float, tuple[str, str, str]]] = {}


def _мера(род: str, сколько: float, формы: tuple[str, str, str],
          *ещё: str) -> None:
    """Формы — «метр, метра, метров»: числа робот произносит вслух."""
    for имя in (*формы, *ещё):
        _МЕРЫ[имя.replace("ё", "е")] = (род, сколько, формы)


