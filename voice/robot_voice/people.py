def _спрячь(глагол: str, второе: bool) -> str | None:
    """«люблю» → «любишь»/«любит». None — по окончанию не угадать."""
    if глагол in _ГЛАГОЛЫ:
        return _ГЛАГОЛЫ[глагол][0 if второе else 1]
    основа, ся = глагол, ""
    if глагол.endswith(("юсь", "усь")):
        основа, ся = глагол[:-2], "ся"
    if основа in _ГЛАГОЛЫ:
        return _ГЛАГОЛЫ[основа][0 if второе else 1] + ся
    if len(основа) < 3:
        return None
    if основа.endswith("ю") and основа[-2] in "аяеуюиоь":
        # «работаю», «гуляю», «болею», «рисую», «пью»: первое спряжение.
        return основа[:-1] + ("ешь" if второе else "ет") + ся
    if основа.endswith(("рю", "ню", "лю")):
        # «говорю», «звоню», «люблю», «сплю»: второе, с беглой «л» после
        # губных («люблю» → «любишь», «готовлю» → «готовишь»).
        корень = основа[:-2] if основа[-3] in "бпвмф" and основа.endswith("лю") \
            else основа[:-1]
        return корень + ("ишь" if второе else "ит") + ся
    if основа.endswith("у") and основа[-2] not in "жшчщкгаеёиоуыэюя":
        # «кладу», «плыву», «жму»: первое спряжение.
        return основа[:-1] + ("ешь" if второе else "ет") + ся
    return None


def _с_регистром(образец: str, слово: str) -> str:
    return слово[:1].upper() + слово[1:] if образец[:1].isupper() else слово


def _лицо(факт: str, второе: bool) -> str | None:
    """Факт от первого лица — во второе («ты») или в третье («он»).

    None — глагол после «я» незнакомый, и переделать честно не выйдет.
    Факт без первого лица («любит крепкий чай» — так пишет модель)
    возвращается как был.
    """
    куски = re.findall(r"\w+|\W+", факт)
    слова = [i for i, к in enumerate(куски) if re.match(r"\w", к)]
    ищем_глагол = 0
    for n, i in enumerate(слова):
        к = куски[i]
        н = к.lower()
        пред_i = слова[n - 1] if n else None
        пред = куски[пред_i].lower() if пред_i is not None else ""
        if ищем_глагол:
            ищем_глагол -= 1
            if н in _МЕЖДУ:
                continue
            ищем_глагол = 0
            if not н.endswith(("л", "ла", "ло", "ли", "лся", "лась", "лось", "лись")):
                спряжено = _спрячь(н, второе)
                if спряжено:
                    куски[i] = _с_регистром(к, спряжено)
                    continue
                if н in _ГЛАГОЛЫ or н.endswith(("у", "ю", "усь", "юсь")):
                    return None
        новое = None
        if н == "я":
            новое = "ты" if второе else "он"
            ищем_глагол = 3
        elif н in _МОЙ:
            новое = "тво" + н[2:] if второе else "его"
        elif н in ("меня", "мне", "мной", "мною"):
            if второе:
                новое = {"меня": "тебя", "мне": "тебе", "мной": "тобой",
                         "мною": "тобою"}[н]
            elif пред in _ПРЕДЛОГИ:
                новое = {"меня": "него",
                         "мне": "нём" if пред in _ПРЕДЛОЖНЫЙ else "нему",
                         "мной": "ним", "мною": "ним"}[н]
            else:
                новое = {"меня": "его", "мне": "ему", "мной": "им", "мною": "им"}[н]
            if пред in _БЕГЛЫЙ:
                куски[пред_i] = _с_регистром(куски[пред_i], _БЕГЛЫЙ[пред])
        if новое:
            куски[i] = _с_регистром(к, новое)
    return "".join(куски)


def про_тебя(факт: str) -> str:
    """Факт — для рассказа самому человеку: «я люблю» → «ты любишь»."""
    вышло = _лицо(факт, второе=True)
    return вышло if вышло is not None else f"с твоих слов — «{факт}»"


def о_нём(факт: str) -> str:
    """Факт — для справки модели: «я люблю» → «он любит»."""
    вышло = _лицо(факт, второе=False)
    return вышло if вышло is not None else f"о себе говорил: «{факт}»"


# --- о ком запись и с чьих слов --------------------------------------------
#
# «Запомни, что у мамы аллергия на орехи», сказанное Ромой, раньше ложилось в
# дело Ромы как факт о самом Роме, а справка подавала его модели как «что ты
# о нём знаешь». Класть в мамино дело тоже нельзя: мама этого не говорила, и
# голос её тут ни при чём. Запись остаётся в деле говорящего, с пометкой «о
# ком» — и звучит «со слов: у мамы…», чтобы модель не выдумала остального.

# Родня в любом падеже. Формы перечислены, а не «мам\w*»: «мамонт» и «папка»
# — не родня. Ключ — как пишется у нас (без «ё»), значение — кто это.
_РОДНЯ = {форма: кто for кто, формы in {
    "мама": "мама мамы маме маму мамой мамочка мамочки мамочке",
    "папа": "папа папы папе папу папой папочка папочки",
    "бабушка": "бабушка бабушки бабушке бабушку бабушкой бабуля бабули бабуле",
    "дедушка": "дедушка дедушки дедушке дедушку дедушкой дед деда деду дедом",
    "брат": "брат брата брату братом братик братика братику",
    "сестра": "сестра сестры сестре сестру сестрой сестренка сестренки",
    "сын": "сын сына сыну сыном сынок сынка",
    "дочь": "дочь дочери дочерью дочка дочки дочке дочку дочкой",
    "муж": "муж мужа мужу мужем",
    "жена": "жена жены жене жену женой",
    "тётя": "тетя тети тете тетю тетей",
    "дядя": "дядя дяди дяде дядю дядей",
}.items() for форма in формы.split()}
# Что может стоять перед роднёй в начале факта: «у МОЕЙ мамы», «НАШ папа».
# «Его» и «её» — так пишет подмеченное модель: «у его мамы аллергия».
_ЧЕЙ = _МОЙ | {"наш", "наша", "наше", "нашего", "нашей", "нашему", "нашим",
               "наши", "наших", "его", "ее"}


def _о_ком(факт: str) -> str:
    """Кто из родни — подлежащее факта. Пусто — факт о самом говорящем.

    Смотрим только НАЧАЛО: «у мамы аллергия», «моя мама любит розы», «папе
    нравится джаз». «Я люблю маму» — это о самом человеке, и мама тут
    дополнение, а не тот, о ком речь.
    """
    слова = re.findall(r"\w+", факт.lower().replace("ё", "е"))
    if слова[:1] == ["у"]:
        слова = слова[1:]
    if слова[:1] and слова[0] in _ЧЕЙ:
        слова = слова[1:]
    return _РОДНЯ.get(слова[0], "") if слова else ""


def _с_пометкой(запись: dict, текст: str) -> str:
    """Факт с пометкой, чьи это слова, если они не о самом человеке."""
    if запись.get("кто_сказал"):
        return f"со слов {в_падеже(запись['кто_сказал'], 'род')}: {текст}"
    if запись.get("о_ком"):
        return f"со слов: {текст}"
    return текст


# --- имя в падеже ---------------------------------------------------------
#
# Робот обращается к людям по имени и в косвенных падежах: «тебя я знаю как
# Рому», «сверю голос с Игорем», «со слов Ани». Имена в доме простые, и
# правила по окончанию хватает; что не склоняется (Нино, Ирэн) — так и
# остаётся. Женских на мягкий знак мало, они перечислены.

_ЖЕНСКИЕ_НА_Ь = {"любовь", "нинель", "адель", "ассоль", "рахиль", "юдифь",
                 "эсфирь", "изабель"}
# После этих букв в окончании пишется «и», а не «ы»: «Маши», «Ольги».
_ШИПЯЩИЕ_ЗАДНЕЯЗЫЧНЫЕ = "гкхжшчщ"


def в_падеже(имя: str, падеж: str) -> str:
    """Имя в родительном («род»), винительном («вин») или творительном
    («твор») падеже: Рома → Ромы / Рому / Ромой, Игорь → Игоря / Игоря /
    Игорем."""
    н = имя.lower()
    # «Голос 3» и имена латиницей не склоняем: «Igorа» хуже, чем «Igor».
    if not re.fullmatch(r"[а-яё-]{2,}", н):
        return имя
    основа, конец = имя[:-1], н[-1]
    if конец == "а":
        if падеж == "вин":
            return основа + "у"
        if падеж == "род":
            return основа + ("и" if н[-2:-1] in _ШИПЯЩИЕ_ЗАДНЕЯЗЫЧНЫЕ else "ы")
        return основа + ("ей" if н[-2:-1] in "жшчщц" else "ой")
    if конец == "я":
        return основа + {"вин": "ю", "род": "и"}.get(падеж, "ей")
    if конец == "й":
        return основа + {"вин": "я", "род": "я"}.get(падеж, "ем")
    if конец == "ь":
        if н in _ЖЕНСКИЕ_НА_Ь:
            return имя if падеж == "вин" else основа + (
                "и" if падеж == "род" else "ью")
        return основа + {"вин": "я", "род": "я"}.get(падеж, "ем")
    if конец not in "оеёиуыэю-":
        return имя + {"вин": "а", "род": "а"}.get(падеж, "ом")
    return имя


def _as_records(facts) -> list[dict]:
    """Приводит факты к единому виду.

    Раньше они лежали простыми строками. Читать старое дело мы обязаны: у
    человека там записи, которые он роботу диктовал, и терять их из-за смены
    формата нельзя.
    """
    out = []
    for f in facts or []:
        out.append(f if isinstance(f, dict) else {"что": str(f), "сам": False})
    return out


def _words(text: str) -> set[str]:
    """Значимые слова фразы. Пунктуация и мелочь вроде «и», «в» отброшены."""
    bare = re.sub(r"[^\w\s]", " ", text.lower().replace("ё", "е"))
    # Числа держим любой длины: «встреча в 10» и «встреча в 15» — это разные
    # записи, а по длине слова они обе отсеялись бы как мелочь.
    return {w for w in bare.split() if len(w) >= SHORT_WORD or w.isdigit()}


def _find_same(facts: list[dict], fact: str) -> dict | None:
    """Уже записанное про то же самое, если есть.

    Считаем повтором только два случая: слова совпали полностью (пусть и в
    другом порядке) или одна запись целиком содержится в другой — «любит чай»
    и «любит крепкий чай по утрам». Второе особенно нужно роботу, который
    подмечает сам: он возвращается к той же теме и дописывает подробности.

    По похожести букв не сравниваем намеренно. «Любит чай» и «любит кофе»
    отличаются на одно слово и совпадают на восемьдесят процентов букв — а
    слить их в одну запись значит потерять то, ради чего дело и заводилось.
    """
    mine = _words(fact)
    if not mine:
        return None
    for record in facts:
        known = _words(record.get("что", ""))
        if known and (known == mine or known <= mine or mine <= known):
            return record
    return None


def _trimmed(facts: list[dict]) -> list[dict]:
    """Оставляет все поручения и не больше FACTS_LIMIT подмеченных — свежих.

    Поручение «запомни, что я работаю по ночам» человек дал сознательно, и
    вытеснять его нельзя ничем — ни болтовнёй, ни другим поручением. Раньше
    при нехватке подмеченных резалось «старейшее, каким бы оно ни было», то
    есть тринадцатое «запомни» молча съедало первое. А подмеченное роботом —
    догадка: не сбылась, так и бог с ней. Уходят старейшие из них, и столько,
    чтобы и дело в целом не перерастало ДЕЛО_ВМЕЩАЕТ.
    """
    подмеченных = sum(1 for r in facts if r.get("сам"))
    лишних = max(подмеченных - FACTS_LIMIT, len(facts) - ДЕЛО_ВМЕЩАЕТ, 0)
    keep, dropped = [], 0
    for record in facts:
        if dropped < лишних and record.get("сам"):
            dropped += 1
            continue
        keep.append(record)
    return keep


def _самое_нужное(записи: list[dict], сколько: int) -> list[dict]:
    """Не больше `сколько` записей: сначала поручения, из них свежие, потом
    подмеченное, тоже свежее. Отданные — в том порядке, в каком записаны.

    Нужно потому, что поручения больше не вытесняются: дело может быть
    длиннее справки и длиннее того, что стоит читать вслух.
    """
    важность = sorted(range(len(записи)),
                      key=lambda i: (bool(записи[i].get("сам")), -i))
    return [записи[i] for i in sorted(важность[:сколько])]
