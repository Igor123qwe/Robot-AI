"""Личные дела: что робот знает о каждом, с кем разговаривает.

Разделение труда с ПК намеренное. Слепки голосов лежат там, где считаются, —
на компьютере: это двести чисел на человека и модель на восемьдесят мегабайт.
А личные дела живут здесь, на роботе, потому что нужны ему в каждом
разговоре и переживают переустановку ПК.

Что в деле. Имя, сколько раз разговаривали, когда виделись в последний раз и
факты: что человек любит, чем занят, о чём просил не забыть. Из них и
получается «помнит меня», а не «отвечает всем одинаково».

Факты двух сортов, и разница между ними важна.

Записанные по просьбе — «запомни, что я работаю по ночам». Это прямое
поручение, и вытеснять его нельзя.

Подмеченные — то, что робот услышал в разговоре сам, без просьбы. Так и
получается настоящий конспект: человек не диктует анкету, он просто
разговаривает. Но такие заметки и врут чаще, и накапливаются быстрее, поэтому
при нехватке места уходят только они, а поручения — никогда.

Дело ведётся бессрочно, как личное дело, а не как журнал разговоров: у
каждой записи есть дата и источник (по просьбе или подмечено, о ком, с чьих
слов). Всё хранится на роботе, в его же папке данных, и стирается голосом
только с подтверждением тем же голосом — «забудь про меня», «да, стирай».
"""

from __future__ import annotations

import json
import logging
import re
import threading
from datetime import datetime
from pathlib import Path

from .ru import count

log = logging.getLogger(__name__)

# Сколько записей кладём в справку модели и сколько ПОДМЕЧЕННЫХ держим на
# человека. Больше в справке — это уже не личное дело, а протокол
# наблюдения: и в промпт не влезет, и оплачивается в каждой реплике.
#
# Поручения («запомни, что…») этим пределом НЕ режутся. Раньше режущим был
# он же, и тринадцатое «запомни» молча выталкивало самое старое поручение:
# человек просил запомнить, робот сказал «Запомнил», а через месяц не помнил.
FACTS_LIMIT = 12

# Сколько записей вообще вмещает дело. Это не норма, а предохранитель от
# зацикленного «запомни» (телевизор, игра ребёнка): до него семья за годы не
# дойдёт. Упёрлись — робот говорит «дело переполнено» и пишет в журнал, а не
# теряет старое молча.
ДЕЛО_ВМЕЩАЕТ = 200

# Сколько записей робот читает вслух на «что ты обо мне знаешь». Остальное —
# одной фразой «и ещё столько-то»: пятьдесят пунктов подряд никто не слушает.
ВСЛУХ_ЗАПИСЕЙ = 8

# Сколько символов от факта берём. Модель иногда пишет абзац там, где нужна
# строка, а промпт уезжает в каждом запросе.
FACT_LENGTH = 160

# Короче этого — не факт, а обрывок: «да», «ага», «чай». Такое в деле только
# место занимает и путает модель в следующий раз.
FACT_MINIMUM = 8

# Слова короче этого при сравнении записей не учитываем: «и», «в», «не» —
# это не про смысл, а про грамматику.
SHORT_WORD = 3


class People:
    """Личные дела всех, кого робот знает."""

    def __init__(self, store: Path) -> None:
        self.store = store
        self._lock = threading.Lock()
        self.cards: dict[str, dict] = {}
        try:
            self.cards = json.loads(store.read_text("utf-8"))
        except (OSError, ValueError):
            self.cards = {}

    def _save(self) -> None:
        try:
            self.store.parent.mkdir(parents=True, exist_ok=True)
            tmp = self.store.with_suffix(".tmp")
            tmp.write_text(json.dumps(self.cards, ensure_ascii=False, indent=1),
                           "utf-8")
            tmp.replace(self.store)
        except OSError as e:
            log.warning("не сохранил личные дела (%s)", e)

    def card(self, name: str) -> dict:
        return self.cards.get(name) or {}

    def known(self) -> list[str]:
        return sorted(self.cards)

    def met(self, name: str) -> None:
        """Отмечает встречу. Зовётся на каждой узнанной фразе."""
        if not name:
            return
        with self._lock:
            card = self.cards.setdefault(name, {"факты": [], "разговоров": 0})
            card["разговоров"] = card.get("разговоров", 0) + 1
            card["виделись"] = datetime.now().isoformat(timespec="seconds")
            self._save()

    def remember(self, name: str, fact: str, *, asked: bool = True,
                 кто_сказал: str = "") -> str:
        """Записывает факт о человеке. Возвращает, что сказать вслух.

        asked=False — робот подметил это сам, без просьбы. Такие записи и
        врут чаще, и накапливаются быстрее, поэтому вытесняются первыми.

        Источник записи остаётся при ней. «Сам» — подмечено или по просьбе.
        «О ком» — факт явно про другого из родни: «у мамы аллергия на орехи»,
        сказанное Ромой, ложится в дело РОМЫ с пометкой, а не в мамино и не
        как факт о самом Роме. «Кто сказал» — запись в деле `name` сделана со
        слов другого узнанного человека.
        """
        fact = " ".join(fact.split())[:FACT_LENGTH]
        if not name:
            return ("Я пока не знаю, кто ты. Скажи «запомни мой голос»."
                    if asked else "Не знаю, кто говорит — записывать некуда.")
        if len(fact) < FACT_MINIMUM:
            return "А что запомнить?" if asked else "Слишком коротко, не записал."
        о_ком = _о_ком(fact)
        with self._lock:
            card = self.cards.setdefault(name, {"факты": [], "разговоров": 0})
            facts = _as_records(card.get("факты"))
            # Повтор ищем только среди записей о том же человеке: «аллергия на
            # орехи» самого Ромы и «у мамы аллергия на орехи» — разные записи,
            # хотя слова одной целиком лежат в другой.
            same = _find_same([r for r in facts if r.get("о_ком", "") == о_ком],
                              fact)
            if same is not None:
                changed = False
                # Подробнее прежнего — берём новую формулировку: «любит чай»
                # уступает «любит крепкий чай по утрам».
                if len(fact) > len(same.get("что", "")):
                    same["что"] = fact
                    changed = True
                # Раньше это было мимолётным наблюдением, а теперь человек
                # попросил запомнить — запись становится поручением, и
                # вытеснять её больше нельзя.
                if asked and same.get("сам"):
                    same["сам"] = False
                    changed = True
                if changed:
                    card["факты"] = facts
                    self._save()
                return "Это я уже знаю." if о_ком else "Это я уже про тебя знаю."
            # Поручения не вытесняются ничем, значит места под новое может и
            # не быть. Молча выбросить старое нельзя — это ровно та потеря, от
            # которой поручения и защищены, — поэтому отказ вслух и в журнал.
            if sum(1 for r in facts if not r.get("сам")) >= ДЕЛО_ВМЕЩАЕТ:
                log.warning("дело %s переполнено (%d записей) — не записал новое",
                            name, len(facts))
                return "Дело переполнено, не записал."
            запись = {"что": fact, "сам": not asked,
                      "когда": datetime.now().date().isoformat()}
            if о_ком:
                запись["о_ком"] = о_ком
            if кто_сказал and кто_сказал != name:
                запись["кто_сказал"] = кто_сказал
            facts.append(запись)
            card["факты"] = _trimmed(facts)
            self._save()
        log.info("про %s %s: %s", name,
                 "запомнил по просьбе" if asked else "подметил сам", fact)
        return "Запомнил." if asked else "Записал в память, вслух не говори."

    def set_birthday(self, name: str, day: int, month: int) -> str:
        """Записывает день рождения структурой (день, месяц) — не текстом.

        Отдельно от remember(): дату сравнивать с «сегодня» нужно каждый день,
        а рыться в вольном тексте факта («у меня день рождения 5 декабря» /
        «пятого декабря» / «5.12») — гадать, а не читать. Число приходит от
        модели уже разобранным, схемой инструмента, как у set_timer.
        """
        if not name:
            return "Не знаю, кто говорит — записывать некуда."
        try:
            datetime(2000, month, day)          # 2000 — високосный: 29 февраля тоже бывает
        except ValueError:
            return "Такого дня в этом месяце не бывает."
        with self._lock:
            card = self.cards.setdefault(name, {"факты": [], "разговоров": 0})
            card["день_рождения"] = f"{day:02d}-{month:02d}"
            self._save()
        log.info("день рождения %s: %02d-%02d", name, day, month)
        return "Запомнил."

    def отпраздновать(self, name: str, today: tuple[int, int]) -> str:
        """Сегодня у name день рождения и его ещё не поздравляли — текст
        поздравления; иначе — пусто.

        Поздравляем РОВНО один раз в день: `met()` зовётся на каждой узнанной
        фразе, а «С днём рождения!» на каждую реплику разговора — это не
        забота, а докучливость. Отметка — той же датой, что и день рождения
        сравнивается, а не часами: технически «сегодня» не изменится, сколько
        бы раз за день ни позвали.
        """
        if not name:
            return ""
        день_месяц = self.card(name).get("день_рождения")
        if день_месяц != f"{today[0]:02d}-{today[1]:02d}":
            return ""
        отметка = datetime.now().date().isoformat()
        with self._lock:
            card = self.cards.setdefault(name, {"факты": [], "разговоров": 0})
            if card.get("поздравлен_в") == отметка:
                return ""
            card["поздравлен_в"] = отметка
            self._save()
        return ("С днём рождения!" if self.nameless(name)
                else f"С днём рождения, {name}!")

    def rename(self, old: str, new: str) -> None:
        """Безымянный голос обрёл имя — архив переезжает вместе с ним.

        Без этого всё, что робот записал про «голос 1», пропадало ровно в тот
        момент, когда человек представился, — то есть терялось самое ценное:
        первый разговор, в котором о себе рассказывают больше всего.
        """
        if old == new or old not in self.cards:
            return
        with self._lock:
            card = self.cards.pop(old)
            было = self.cards.get(new)
            if было:
                # Под этим именем уже есть дело: сливаем, не теряя ни одного
                # поручения — по тем же правилам, что и remember: уступить
                # место могут только подмеченные. Предохранитель ДЕЛО_ВМЕЩАЕТ
                # здесь не режет: слияние — не новая запись, а переезд старых.
                # Дубликаты отсеет remember при следующем добавлении.
                факты = _as_records(было.get("факты")) + _as_records(card.get("факты"))
                было["факты"] = _trimmed(факты)
                было["разговоров"] = (было.get("разговоров", 0)
                                      + card.get("разговоров", 0))
                # День рождения записали, пока человек был «голосом N», —
                # он не должен потеряться в тот миг, когда человек назвался.
                if card.get("день_рождения") and not было.get("день_рождения"):
                    было["день_рождения"] = card["день_рождения"]
            else:
                self.cards[new] = card
            self._save()
        log.info("личное дело %r теперь %r", old, new)

    def forget(self, name: str) -> str:
        if not name or name not in self.cards:
            return "Я про тебя ничего и не помню."
        with self._lock:
            del self.cards[name]
            self._save()
        log.info("личное дело %s стёрто", name)
        return "Всё стёр."

    def facts(self, name: str) -> list[str]:
        """Что робот знает о человеке, по порядку записи."""
        return [r["что"] for r in _as_records(self.card(name).get("факты"))]

    def tell(self, name: str) -> str:
        """Что робот скажет вслух на «что ты обо мне знаешь».

        Не больше ВСЛУХ_ЗАПИСЕЙ — те же, что важнее и для справки модели:
        сначала поручения, из них свежие. Остальное — «и ещё столько-то»:
        поручения теперь не вытесняются, и дело в полсотни пунктов робот
        иначе читал бы минуты три подряд.
        """
        if not name:
            return "Пока не знаю, кто ты."
        записи = _as_records(self.card(name).get("факты"))
        вслух = _самое_нужное(записи, ВСЛУХ_ЗАПИСЕЙ)
        facts = [_с_пометкой(r, про_тебя(r["что"])) for r in вслух]
        ещё = len(записи) - len(вслух)
        хвост = (f" И ещё {count(ещё, 'запись', 'записи', 'записей', female=True)}."
                 if ещё > 0 else "")
        if self.nameless(name):
            начало = "Голос твой узнаю, а имени не знаю."
            if not facts:
                return начало + " И больше пока ничего."
            return начало + " Про тебя знаю вот что. " + " ".join(
                f[:1].upper() + f[1:].rstrip(".") + "." for f in facts) + хвост
        if not facts:
            return f"Знаю, что тебя зовут {name}. Больше пока ничего."
        return "Про тебя знаю вот что. " + " ".join(
            f[:1].upper() + f[1:].rstrip(".") + "." for f in facts) + хвост

    def nameless(self, name: str) -> bool:
        """Голос узнан, но как зовут человека — неизвестно."""
        return name.startswith("голос ")

    def brief(self, name: str, today: tuple[int, int] | None = None) -> str:
        """Короткая справка для модели. Уезжает в каждом запросе, поэтому сжато.

        Кладётся отдельным системным блоком, а не в основной промпт: тот байт
        в байт одинаков в каждом запросе и оплачивается по льготной цене как
        кэш. Справка меняется от человека к человеку и кэшу только помешала бы.

        `today` — (день, месяц): есть день рождения на эту дату — приписка в
        конце, каждый раз, пока разговор идёт в этот день. Не гейтится
        «уже поздравил» — это для отпраздновать(): там разговор и жест на
        экране, здесь только то, что модель ЗНАЕТ, а поздравит она сама,
        своими словами, и не обязана делать это в каждой реплике подряд.

        Записей — не больше FACTS_LIMIT: сначала поручения, из них свежие,
        потом подмеченное. Порядок в справке — как записано: так модели
        понятнее, что было раньше, а что позже.
        """
        if not name:
            return ""
        записи = _самое_нужное(_as_records(self.card(name).get("факты")),
                               FACTS_LIMIT)
        facts = [_с_пометкой(r, о_нём(r["что"])) for r in записи]
        who = ("Ты узнаёшь этот голос, но имени не знаешь."
               if self.nameless(name) else f"{ГОВОРИТ}{name}.")
        справка = who if not facts else who + " Что ты о нём знаешь: " + "; ".join(facts) + "."
        if today and self.card(name).get("день_рождения") == f"{today[0]:02d}-{today[1]:02d}":
            справка += " " + ДЕНЬ_РОЖДЕНИЯ_СЕГОДНЯ
        return справка


# Приписка к справке в день рождения. Не готовой фразой («Сегодня у него день
# рождения!»), а пометкой для модели: готовую фразу домашняя модель читала
# вслух как есть — на «Кузя, я ж встаю» человек слышал про себя «у него день
# рождения». Поздравить — её дело, своими словами и на «ты».
ДЕНЬ_РОЖДЕНИЯ_СЕГОДНЯ = "(У собеседника сегодня день рождения: поздравь его сам, на «ты», один раз.)"

# Начало справки об узнанном по имени. Отдельной строкой, потому что её же
# читает мозг: по ней он понимает, что сменился собеседник (кто_в_справке).
ГОВОРИТ = "Сейчас с тобой говорит "


def кто_в_справке(справка: str) -> str:
    """Имя узнанного из справки brief(). Пусто — не узнан или имени нет.

    Голоса без имени («голос 1», «голос 2») справка не различает — и это
    допустимо: мозг тогда просто не считает собеседника сменившимся.
    """
    if not (справка or "").startswith(ГОВОРИТ):
        return ""
    return справка[len(ГОВОРИТ):].split(".", 1)[0].strip()


