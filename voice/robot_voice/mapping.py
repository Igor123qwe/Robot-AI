"""Карта проходимости вокруг робота: дальномер + колёса + время.

ПОЧЕМУ ЭТО ВООБЩЕ ВОЗМОЖНО. Дальномер видит шестьдесят градусов и восемь
направлений — вчетверо меньше лучей, чем у самого дешёвого лидара, и вшестеро
уже по обзору. Первый вывод из этого был «карты не будет», и он неверен.
Неверен потому, что считает только ОДИН кадр.

Лидар получает триста шестьдесят градусов за оборот своего зеркала. Робот
получает те же триста шестьдесят за оборот СЕБЯ. Восемь колонок, десять кадров
в секунду, шесть секунд разворота — это около пятисот замеров по кругу, что
сравнимо с четырьмя с половиной сотнями точек за оборот у LD19. Разница не в
количестве, а во времени: лидар успевает за десятую долю секунды, мы за шесть.

Отсюда и область применения. Карта, которая строится шесть секунд, годится
для «что вокруг меня сейчас» и не годится для «план квартиры»: пока робот
объезжает комнату, человек в ней успевает переставить стул, а сам он —
накопить ошибку одометрии. Поэтому карта здесь ЛОКАЛЬНАЯ и ЗАБЫВЧИВАЯ:
несколько метров вокруг, несколько минут памяти. Это не урезанная версия
настоящей карты, а другая вещь, и именно она нужна, чтобы объехать стул.

ТРИ ИСТОЧНИКА И ЧТО ДАЁТ КАЖДЫЙ.
  • дальномер — метры и направление, но только вперёд и только сейчас;
  • колёса — где робот стоял, когда мерил. Без них замеры несводимы: восемь
    лучей так и останутся восемью лучами;
  • время — то, чего нет ни в одном датчике. Замер минутной давности хуже
    свежего не потому, что датчик ошибся, а потому, что мир с тех пор
    изменился, и робот успел уехать.

ЗАНЯТОСТЬ В ЛОГ-ШАНСАХ. Клетка хранит не «занято/свободно», а число: больше
нуля — скорее занято, меньше — скорее свободно, ноль — не знаю. Каждый новый
замер прибавляет или отнимает. Так десять кадров, говорящих «свободно»,
перевешивают один случайный «занято», и наоборот: стена, увиденная десять раз,
не стирается одним промахом. Приём канонический, из работы Моравеца и Элфеса
про сонары — а наш датчик и есть восемь сонаров с узким конусом.

ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ.
  • замыкания цикла. Робот не узнаёт места, где уже был, и не правит по нему
    накопленную ошибку. Для карты, живущей минуты, это и не нужно;
  • глобальных координат. Начало отсчёта — там, где робота включили;
  • третьего измерения. Всё сводится к плоскости пола: для «объехать» этого
    достаточно, а для «проехать под столом» нужен другой датчик.
"""

from __future__ import annotations

import json
import logging
import math
import os
import time
from pathlib import Path

import numpy as np

log = logging.getLogger(__name__)

# --- размер и разрешение -----------------------------------------------------
# Сторона клетки. Пять сантиметров: мельче — карта начинает хранить шум
# дальномера, крупнее — в клетку перестаёт помещаться ножка стула, а именно
# ножки робот и цепляет. Роботы-пылесосы работают на тех же пяти.
КЛЕТКА = 0.05
# Сторона карты в метрах. Шесть — это комната целиком и запас на коридор.
# Больше незачем: дальше двух метров дальномер всё равно ничего не скажет, а
# память карты нужна не для планирования маршрута через квартиру.
СТОРОНА = 6.0
КЛЕТОК = int(СТОРОНА / КЛЕТКА)

# --- лог-шансы ---------------------------------------------------------------
# Сколько прибавляет один замер. Числа взяты в каноническом соотношении: за
# «занято» прибавляем вдвое больше, чем отнимаем за «свободно». Перекос
# намеренный и в безопасную сторону — стену увидеть труднее, чем не увидеть,
# и одиночное «здесь пусто» не должно стирать препятствие.
ЗАНЯТО = 0.85
СВОБОДНО = -0.4
# Предел насыщения. Без него клетка, которую робот видит минуту, накапливает
# такую уверенность, что переубедить её потом невозможно: человек унёс стул, а
# на карте он ещё пять минут стоит.
ПРЕДЕЛ = 3.5
# Выше этого клетка считается занятой, ниже минус этого — свободной. Между —
# «не знаю», и это третье состояние обязано существовать отдельно: принять
# незнание за свободу и есть тот случай, когда робот уезжает в стеклянную дверь.
ПОРОГ = 1.0

# --- забывание ---------------------------------------------------------------
# Во сколько раз слабеет уверенность за секунду. 0.98 — это половина за
# тридцать пять секунд: стул, унесённый минуту назад, с карты уходит, а стена,
# которую робот видит постоянно, держится.
ЗАБЫВАТЬ_ЗА_СЕКУНДУ = 0.98

# --- что берём из сетки ------------------------------------------------------
# Ряды, которые смотрят вперёд, а не в пол и не в потолок. Те же, по которым
# принимается решение о стопе: ниже начинается пол, выше — стены над роботом.
# Это ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ, безопасное для сырой сетки.
РЯДЫ = (2, 3, 4, 5)
# А если сетку уже очистили от пола плоскостью (Взгляд.сетка_без_пола), то
# нижние ряды становятся самыми ценными: после вычитания пола в них остаётся
# только то, что НА полу и близко, — тапок, кошка, порожек, нога. Именно это
# робот и цепляет. Верхние два ряда при этом всё равно не берём: они смотрят
# выше робота, и мапить туда значило бы запретить проезд под столом, под
# который робот прекрасно въезжает.
РЯДЫ_БЕЗ_ПОЛА = (2, 3, 4, 5, 6, 7)
# Поле зрения дальномера по горизонтали и ширина одной зоны. Зона — КОНУС в
# семь с половиной градусов, а не линия, и это не тонкость.
#
# Восемь лучей на шестьдесят градусов расходятся на метре на тринадцать
# сантиметров. Отметь на карте только конец луча — и стена выйдет пунктиром из
# точек через две пустые клетки, причём точка ровно по курсу не отметится
# никогда: центрального луча в чётной сетке нет, ближайшие идут по ±3.75°.
# Робот в такой стене увидит проходы, которых нет.
#
# Поэтому конец луча размечается ДУГОЙ по ширине зоны. Так соседние зоны
# смыкаются, и стена остаётся стеной.
ПОЛЕ = 60.0
ЗОНА = ПОЛЕ / 8.0
# Дальше этого замерам не верим: паспортная точность VL53L7CX держится до двух
# метров, дальше ошибка растёт до одиннадцати процентов.
ВЕРИМ_ДО = 2.0
НЕ_ВЕРИМ_БЛИЖЕ = 0.15

# --- габарит робота ----------------------------------------------------------
# Радиус круга, который заметает корпус при вращении на месте: половина
# диагонали платформы плюс запас.
#
# Число ВЗЯТО С ЗАПАСОМ ВВЕРХ и намеренно. Точных габаритов WD550 у меня нет,
# а ошибиться здесь можно только в одну сторону: занизишь — робот при
# развороте цепляет углом то, чего «по расчёту» не касается, и цепляет он
# обычно ногу. Померить просто — рулеткой по диагонали платформы, — и когда
# померим, число надо поправить ЗДЕСЬ.
РАДИУС_КОРПУСА = 0.30
# Сколько оставляем сверх габарита, ЕДУЧИ туда, куда датчик не смотрит.
# Пятнадцать сантиметров: карта помнит, но не видит, и человек за спиной мог
# с тех пор шагнуть роботу навстречу. Это место, в котором стоит нога, а не
# запас на округление.
ЗАПАС_ВСЛЕПУЮ = 0.15
# А для разворота на месте запас меньше, и это не небрежность. Едущий назад
# робот СОКРАЩАЕТ расстояние до того, чего не видит, и запас должен покрывать
# ещё и чужой шаг навстречу. Вращаясь, он не приближается ни к чему: углы
# корпуса заметают окружность ровно радиуса РАДИУС_КОРПУСА, и всё, что дальше
# неё, остаётся нетронутым. Требовать тут те же пятнадцать сантиметров значило
# бы запретить роботу поворачиваться в углу комнаты — то есть сделать его
# беспомощным ровно там, где развернуться и надо.
ЗАПАС_ПОВОРОТА = 0.08

# --- наружу, для пульта ------------------------------------------------------
# Три знака на три состояния клетки. Больше состояний у карты и нет: «занято»,
# «свободно» и «не знаю» — и третье обязано быть отдельным, иначе незнание
# рисуется свободой, а это и есть тот случай, когда робот уезжает в стеклянную
# дверь.
ЗНАКИ = {1: "#", -1: ".", 0: " "}

# Куда выкладывать карту для пульта. /run — это tmpfs, то есть память: писать
# карту на карточку три раза в секунду значило бы стирать её ресурс ради того,
# что живёт полсекунды. Каталог заводит systemd (RuntimeDirectory) и убирает
# его при остановке службы.
#
# Запасной путь — рядом с сеткой дальномера. Он нужен не роботу, а разработке:
# на машине без systemd каталога /run/robot-ai просто нет.
ФАЙЛ_КАРТЫ = os.environ.get("ROBOT_MAP_FILE", "/run/robot-ai/map.json")
ЗАПАСНОЙ_ФАЙЛ_КАРТЫ = str(Path.home() / ".robot-ai" / "map.json")

# Как часто выкладывать. Три раза в секунду: карта меняется медленно — на
# полной скорости робот проезжает за треть секунды четыре клетки, — а чаще
# значит зря греть плату.
ПИСАТЬ_РАЗ_В = 0.33


# --- когда не копим ----------------------------------------------------------
# Насколько робот может провернуться между двумя кадрами, чтобы замер ещё
# засчитывался. На десяти герцах и разрешённой скорости поворота один рад/с
# это шесть градусов за кадр — почти колонка. Больше — значит робот крутится
# быстрее, чем мерит, и замеры размажутся дугой.
БЫСТРЕЕ_НЕ_ВЕРИМ = math.radians(8.0)
# То же по расстоянию: за кадр робот проезжает сантиметра три.
ДАЛЬШЕ_НЕ_ВЕРИМ = 0.10


class Карта:
    """Локальная карта занятости. Мир в клетках, робот в метрах."""

    def __init__(self, клеток: int = КЛЕТОК, клетка: float = КЛЕТКА) -> None:
        self.клеток = клеток
        self.клетка = клетка
        self.сетка = np.zeros((клеток, клеток), dtype=np.float32)
        # Где в мире находится левый нижний угол карты. Карта едет за роботом:
        # он всегда примерно в середине, а уехавшее за край забывается.
        self.угол_x = -клеток * клетка / 2
        self.угол_y = -клеток * клетка / 2
        self.когда = 0.0
        self.поза: tuple[float, float, float] | None = None
        self.замеров = 0
        self.пропущено = 0
        self._выложено = 0.0
        self._не_выложил = False

    # --- служебное ------------------------------------------------------
    def _в_клетки(self, x: float, y: float) -> tuple[int, int]:
        return (int((x - self.угол_x) / self.клетка),
                int((y - self.угол_y) / self.клетка))

    def _подвинуть(self, x: float, y: float) -> None:
        """Держать робота в середине карты, сдвигая её и забывая уехавшее.

        Сдвигаем целыми клетками, а не на точное смещение: дробный сдвиг
        потребовал бы перевыборки, а перевыборка размазывает стену по соседям
        и делает это на каждом кадре. За десяток метров стена превратилась бы
        в широкую полосу — карта, которая портится сама от езды.
        """
        мx, мy = self._в_клетки(x, y)
        край = self.клеток // 4
        сдвиг_x = сдвиг_y = 0
        if мx < край:
            сдвиг_x = край - мx
        elif мx > self.клеток - край:
            сдвиг_x = self.клеток - край - мx
        if мy < край:
            сдвиг_y = край - мy
        elif мy > self.клеток - край:
            сдвиг_y = self.клеток - край - мy
        if not сдвиг_x and not сдвиг_y:
            return
        новая = np.zeros_like(self.сетка)
        # Копируем пересечение старой и новой области; остальное — чистое
        # «не знаю», и это правда: туда робот ещё не смотрел.
        сx0, сx1 = max(0, сдвиг_x), min(self.клеток, self.клеток + сдвиг_x)
        сy0, сy1 = max(0, сдвиг_y), min(self.клеток, self.клеток + сдвиг_y)
        новая[сy0:сy1, сx0:сx1] = self.сетка[сy0 - сдвиг_y:сy1 - сдвиг_y,
                                             сx0 - сдвиг_x:сx1 - сдвиг_x]
        self.сетка = новая
        self.угол_x -= сдвиг_x * self.клетка
        self.угол_y -= сдвиг_y * self.клетка

    def _забыть(self, сколько_прошло: float) -> None:
        if сколько_прошло <= 0:
            return
        self.сетка *= ЗАБЫВАТЬ_ЗА_СЕКУНДУ ** сколько_прошло

    # --- накопление -----------------------------------------------------
    def лучи(self, сетка_тоф: list[list[float]],
             ряды: tuple[int, ...] = РЯДЫ) -> list[tuple[float, float]]:
        """Сетку 8×8 — в плоский скан: (угол, расстояние) на колонку.

        Берём МИНИМУМ по рядам, а не среднее. Робот объезжает препятствие
        целиком, а не его среднюю высоту: если в колонке есть хоть одна
        близкая зона, там что-то торчит, и ехать туда нельзя.

        Колонка без единого замера в скан не попадает вовсе. Это важно:
        отсутствие замера — не «свободно до бесконечности», а «не знаю».
        Записать туда свободу значит выдумать проход там, где стекло.
        """
        плоско: list[tuple[float, float]] = []
        for к in range(8):
            свои = [сетка_тоф[р][к] for р in ряды
                    if НЕ_ВЕРИМ_БЛИЖЕ < сетка_тоф[р][к] <= ВЕРИМ_ДО]
            if not свои:
                continue
            угол = math.radians(ПОЛЕ * (3.5 - к) / 8.0)
            плоско.append((угол, min(свои)))
        return плоско

    def добавить(self, сетка_тоф: list[list[float]],
                 поза: tuple[float, float, float],
                 когда: float | None = None,
                 ряды: tuple[int, ...] = РЯДЫ) -> bool:
        """Учесть кадр. False — кадр отброшен, и это тоже нормально.

        Отбрасываем, когда робот между кадрами провернулся или проехал
        слишком много: замер относится к позе, в которой он сделан, а если
        поза за кадр успела уехать, привязывать его не к чему. Лучше
        потерять кадр, чем размазать стену дугой — размазанная стена потом
        не стирается, она копится.
        """
        когда = time.monotonic() if когда is None else когда
        x, y, курс = поза

        if self.поза is not None:
            прошло = когда - self.когда
            дx = x - self.поза[0]
            дy = y - self.поза[1]
            дкурс = (курс - self.поза[2] + math.pi) % (2 * math.pi) - math.pi
            self._забыть(прошло)
            if abs(дкурс) > БЫСТРЕЕ_НЕ_ВЕРИМ or math.hypot(дx, дy) > ДАЛЬШЕ_НЕ_ВЕРИМ:
                self.поза = поза
                self.когда = когда
                self.пропущено += 1
                return False
        self.поза = поза
        self.когда = когда
        self._подвинуть(x, y)

        свои = self.лучи(сетка_тоф, ряды)
        if not свои:
            return False
        for угол, дальность in свои:
            self._луч(x, y, курс + угол, дальность)
        self.замеров += len(свои)
        return True

    def _пометить(self, x: float, y: float, сколько: float) -> None:
        кx, кy = self._в_клетки(x, y)
        if 0 <= кx < self.клеток and 0 <= кy < self.клеток:
            прежде = self.сетка[кy, кx]
            self.сетка[кy, кx] = max(-ПРЕДЕЛ, min(ПРЕДЕЛ, прежде + сколько))

    def _луч(self, x: float, y: float, курс: float, дальность: float) -> None:
        """Свободно внутри конуса, занято дугой на его конце.

        Конус, а не линия. Зона дальномера — семь с половиной градусов, и на
        двух метрах это уже двадцать шесть сантиметров: половина стула.
        Отмечать только осевую линию значило бы рисовать стену пунктиром, а
        робот в пунктире видит проходы, которых нет.
        """
        полширины = math.radians(ЗОНА) / 2
        # Сколько лучей внутри конуса. Шаг между ними берём ВДВОЕ мельче
        # клетки, а не вровень с ней. Вровень уже пробовали: на метре соседние
        # подлучи расходятся на шесть с половиной сантиметров при клетке в
        # пять, и между ними снова остаются дырки — тот же пунктир, только
        # мельче и незаметнее. Половина клетки гарантирует, что соседние
        # подлучи попадут либо в одну клетку, либо в соседние.
        шаг_дуги = self.клетка / 2
        поперёк = max(2, int(дальность * math.radians(ЗОНА) / шаг_дуги) + 1)
        for i in range(поперёк):
            доля = 0.5 if поперёк == 1 else i / (поперёк - 1)
            угол = курс - полширины + 2 * полширины * доля
            cos, sin = math.cos(угол), math.sin(угол)
            # Свободное пространство вдоль луча. Последнюю клетку не трогаем:
            # там уже препятствие, и «свободно» рядом с ним съедало бы край.
            шаг = self.клетка / 2
            путь = 0.0
            while дальность - путь > self.клетка:
                self._пометить(x + cos * путь, y + sin * путь, СВОБОДНО)
                путь += шаг
            # Занято — на конце каждого луча конуса. Уверенность делим на
            # число лучей: препятствие увидено один раз, а не десять, и
            # накачивать его вдесятеро быстрее стены значило бы делать
            # случайный блик неудалимым.
            self._пометить(x + cos * дальность, y + sin * дальность,
                           ЗАНЯТО * (2.0 if поперёк == 1 else 2.0 / поперёк))

    # --- наружу ---------------------------------------------------------
    def ближайшее(self, сектор: tuple[float, float] | None = None,
                  дальность: float = ВЕРИМ_ДО) -> float:
        """До ближайшего занятого места вокруг робота, метры. Ноль — не знаю.

        ЗАЧЕМ. Дальномер смотрит вперёд на шестьдесят градусов, а корпус при
        вращении заметает круг. Сзади и по бокам робот слеп ПОЛНОСТЬЮ, и до
        сих пор он с этим только мирился: поворот разрешался тем медленнее,
        чем ближе что-то ВПЕРЕДИ, — то есть по догадке «если впереди тесно,
        то и вокруг, наверное, тоже».

        Догадка не нужна, если помнить. Стул, который был перед роботом
        секунду назад, никуда не делся оттого, что робот отвернулся; он лежит
        в этой карте и отвечает на вопрос «что вокруг» настоящим числом.
        Именно так и делают те, у кого узкий датчик: память о вышедшем из
        поля зрения (в литературе — occupancy grid + барьерные функции)
        заменяет обзор, которого нет.

        `сектор` — (куда смотреть относительно курса, полуширина), радианы.
        None — весь круг. Задний ход спрашивает про свой сектор, поворот —
        про круг целиком.

        Ноль означает «не знаю»: карта пуста, робот только включился или
        одометрии нет. Незнание — повод для осторожности, а не для смелости,
        и наверху это так и понимается.
        """
        if self.поза is None:
            return 0.0
        # Пусто — не «свободно», а «ещё не смотрел». Разница видна ровно
        # тогда, когда робот включили посреди комнаты и сразу попросили
        # развернуться.
        занятые = np.argwhere(self.сетка > ПОРОГ)
        if not len(занятые):
            return 0.0
        x, y, курс = self.поза
        мир_y = self.угол_y + (занятые[:, 0] + 0.5) * self.клетка
        мир_x = self.угол_x + (занятые[:, 1] + 0.5) * self.клетка
        дx, дy = мир_x - x, мир_y - y
        расстояния = np.hypot(дx, дy)
        близкие = расстояния <= дальность
        if сектор is not None:
            куда, полуширина = сектор
            углы = np.arctan2(дy, дx) - курс - куда
            углы = (углы + np.pi) % (2 * np.pi) - np.pi
            близкие &= np.abs(углы) <= полуширина
        свои = расстояния[близкие]
        if not len(свои):
            return дальность
        return float(свои.min())

    def занято(self, x: float, y: float) -> bool:
        кx, кy = self._в_клетки(x, y)
        if not (0 <= кx < self.клеток and 0 <= кy < self.клеток):
            return False
        return bool(self.сетка[кy, кx] > ПОРОГ)

    def можно_ехать(self, x: float, y: float, wz: float) -> tuple[bool, str]:
        """Пустит ли память туда, куда датчик не смотрит. (можно, почему нет).

        Дальномер видит вперёд и только вперёд. Всё остальное движение —
        задний ход, боковое, разворот на месте — робот совершает ВСЛЕПУЮ, и
        до сих пор это ничем не проверялось: сторож пути судил только `x > 0`,
        честно объясняя, что про заднее полушарие он не знает ничего.

        Не знать — не то же самое, что не помнить. Задний ход без датчиков —
        это, между прочим, единственный юридически доказанный механизм травмы
        среди тротуарных роботов: машина поехала назад, сбила человека,
        который там стоял. У нас сзади может оказаться ребёнок, пришедший
        посмотреть, — и карта помнит его ровно столько, сколько он не
        двигался с тех пор, как робот в последний раз туда смотрел.

        Отвечаем «можно», когда карта пуста: незнание — не разрешение, но и
        не запрет, а робот, которому нельзя двигаться до первой карты, просто
        не работает. Осторожность в этом случае обеспечивается скоростью, а
        не запретом.
        """
        куда: list[tuple[float, float, float, str]] = []
        зазор = РАДИУС_КОРПУСА + ЗАПАС_ВСЛЕПУЮ
        if x < -1e-3:
            куда.append((math.pi, math.radians(70), зазор, "сзади"))
        if y > 1e-3:
            куда.append((math.pi / 2, math.radians(70), зазор, "слева"))
        if y < -1e-3:
            куда.append((-math.pi / 2, math.radians(70), зазор, "справа"))
        if abs(wz) > 1e-3 and abs(x) <= 1e-3 and abs(y) <= 1e-3:
            # Разворот на месте: корпус заметает круг целиком, и сектора тут
            # нет. Спрашиваем про всю окружность и с меньшим запасом — см.
            # ЗАПАС_ПОВОРОТА.
            куда.append((0.0, math.pi, РАДИУС_КОРПУСА + ЗАПАС_ПОВОРОТА,
                         "вплотную"))
        if not куда:
            return True, ""

        for центр, полуширина, зазор, словом in куда:
            рядом = self.ближайшее((центр, полуширина), ВЕРИМ_ДО)
            if рядом <= 0:
                continue                # карта молчит — не запрещаем
            if рядом < зазор:
                return False, f"{словом} что-то в {рядом:.1f} м, я помню"
        return True, ""

    def для_пульта(self) -> dict:
        """То же, что картинка(), но сжато — чтобы возить по сети постоянно.

        Клеток сто двадцать на сто двадцать, четырнадцать тысяч штук. Списком
        чисел это тридцать пять килобайт JSON на каждый кадр, и дело даже не в
        сети: плата тратила бы на сборку этой строки больше, чем на саму
        карту. А смысла в точности тут нет — состояний всего три.

        Поэтому три знака и счётчики повторов: `"200 45.12#"` читается как
        двести «не знаю», сорок пять «свободно», двенадцать «занято». Пустая
        карта укладывается в один кусок, обычная комната — в пару килобайт.
        Разжимается это в браузере тремя строками.
        """
        плоско = self._знаки().ravel()
        if not плоско.size:
            строка = ""
        else:
            границы = np.flatnonzero(np.diff(плоско)) + 1
            начала = np.concatenate(([0], границы))
            длины = np.diff(np.concatenate((начала, [плоско.size])))
            строка = "".join(f"{д}{ЗНАКИ[int(плоско[н])]}"
                             for н, д in zip(начала, длины))
        return {
            "клетка": self.клетка,
            "клеток": self.клеток,
            "угол": [self.угол_x, self.угол_y],
            "поза": list(self.поза) if self.поза else None,
            "замеров": self.замеров,
            "пропущено": self.пропущено,
            "радиус": РАДИУС_КОРПУСА,
            "клетки": строка,
        }

    def _знаки(self) -> np.ndarray:
        """Три состояния: 1 занято, -1 свободно, 0 не знаю."""
        знаки = np.zeros_like(self.сетка, dtype=np.int8)
        знаки[self.сетка > ПОРОГ] = 1
        знаки[self.сетка < -ПОРОГ] = -1
        return знаки

    def выложить(self, файл: Path, не_чаще: float = ПИСАТЬ_РАЗ_В) -> bool:
        """Карту — в файл, чтобы её видел пульт. True — записали.

        Через файл, а не через порт, и по той же причине, что и сетку
        дальномера: пульт живёт в другом процессе, лезть ему в память робота
        неоткуда, а заводить ради картинки ещё один сетевой канал — это ещё
        один способ всё сломать.

        Файл в /run — это tmpfs, то есть память. Писать карту на карточку
        три раза в секунду значило бы стирать её ресурс ради того, что живёт
        полсекунды: четырнадцать тысяч клеток даже сжатыми складываются в
        гигабайты записи за сутки. Плюс systemd сам убирает каталог при
        остановке службы, и застрявшая вчерашняя карта не переживёт падения.
        """
        сейчас = time.monotonic()
        if сейчас - self._выложено < не_чаще:
            return False
        self._выложено = сейчас
        try:
            файл.parent.mkdir(parents=True, exist_ok=True)
            данные = self.для_пульта()
            # time.time, а не monotonic: читать будет ДРУГОЙ процесс, и
            # сравнивать ему надо со своими часами, а не с моими.
            данные["когда"] = time.time()
            врем = файл.with_name(файл.name + ".tmp")
            врем.write_text(json.dumps(данные, ensure_ascii=False))
            врем.replace(файл)
            return True
        except OSError as e:
            if not self._не_выложил:
                self._не_выложил = True
                log.warning("карта не пишется в %s (%s) — пульт её не увидит",
                            файл, e)
            return False

    def картинка(self) -> dict:
        """Карта для пульта: три состояния и поза робота.

        Отдаём именно три состояния, а не число: человеку нужно видеть, где
        робот НЕ ЗНАЕТ, что там. Свести незнание и свободу в один цвет —
        значит нарисовать проход сквозь стеклянную дверь.
        """
        знаки = np.zeros_like(self.сетка, dtype=np.int8)
        знаки[self.сетка > ПОРОГ] = 1
        знаки[self.сетка < -ПОРОГ] = -1
        return {
            "клетка": self.клетка,
            "клеток": self.клеток,
            "угол": [self.угол_x, self.угол_y],
            "поза": list(self.поза) if self.поза else None,
            "замеров": self.замеров,
            "пропущено": self.пропущено,
            # Плоским списком: так вдвое короче вложенных списков, а браузеру
            # всё равно, чем резать на строки.
            "клетки": знаки.flatten().tolist(),
        }
