"""Обследование квартиры: объехать, заглянуть в каждый угол, составить опись.

ЗАЧЕМ. Всё, что робот знает о доме, он до сих пор узнавал ПОПУТНО: карта
копилась, пока он шёл за человеком, мебель попадала в пометки, если случайно
оказалась в кадре. Попутное знание неполно по построению — робот ходил там,
где ходил человек, и смотрел туда, куда смотрел человек. Углы, в которые
никто не заглядывал, оставались белым пятном.

Обход — это то же самое, но НАМЕРЕННО: робот сам объезжает квартиру, сам
останавливается и осматривается кругом, и в конце говорит, что где стоит.

ИЗ ЧЕГО ЭТО СОБРАНО. Ничего нового изобретать не пришлось, всё уже было
поодиночке:

  atlas      — постоянный план квартиры, копится месяцами;
  landmarks  — пометки: стол вот здесь, диван вон там;
  things     — узнавание предметов сетью DOSOD на BPU, восемьдесят классов;
  planner    — объезд препятствий дугами;
  tof        — сторож, который не даёт въехать.

Обход только водит робота и вовремя дёргает затвор камеры.

ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ, И СКАЗАТЬ ЭТО НАДО СРАЗУ.

Это не полное покрытие. Без лидара и SLAM глобального планировщика в роботе
нет, значит нет и маршрута «объехать все комнаты по кратчайшему пути». Робот
выбирает НАПРАВЛЕНИЕ — туда, где на карте больше неизвестного, — и едет туда,
пока пускает дальномер. Так обследуют территорию простые роботы-пылесосы
первых поколений, и с тем же результатом: за один проход покрывается не всё,
за несколько — почти всё.

Это не полная опись. DOSOD знает восемьдесят классов COCO, и шкафа, тумбочки,
двери, батареи среди них нет. Робот честно перечисляет то, что умеет назвать,
а не делает вид, что перечислил всё.

Это не измерение с точностью до сантиметра. Место предмета берётся
пересечением двух взглядов из разных точек (landmarks.свести) — это и есть
главная причина, по которой обход ЕЗДИТ, а не просто вертится: без переезда
нет базы, без базы нет пересечения. При шуме пеленга в три градуса и переезде
на метр с лишним предмет в двух метрах определяется с ошибкой около четверти
метра. Пометки нарочно схлопываются в одну, если ближе восьмидесяти
сантиметров, — этого запаса как раз хватает.

Это не различение одинаковых предметов. Четыре стула у стола дают четыре
пеленга одного класса, и пересечь можно любой с любым: часть пересечений
придётся на пустое место. Задача называется data association и в общем виде
не решена даже там, где есть лидар. Нас спасает только то, что пометка
принимается после двух совпавших наблюдений, а призрачные пересечения от
взгляда к взгляду не повторяются.

ПОЧЕМУ МОЛЧА. Первая же живая поездка кончилась просьбой «не нужно ему ещё
озвучивать каждое действие, пусть как финиш только». Обход идёт минутами и
делает по три-четыре движения в минуту; проговаривать их вслух — это
превратить полезное дело в бубнёж. Поэтому голосом ровно две фразы: «пошёл» и
опись в конце. Всё остальное — в журнал.
"""

from __future__ import annotations

import logging
import math
import threading
import time

from . import planner, ru
from .follow import скорость_по_виду

log = logging.getLogger(__name__)

# Круг цикла. Тот же, что у следования: пятнадцать раз в секунду — это чаще,
# чем отдаёт дальномер, и реже, чем нужно, чтобы греть процессор впустую.
ШАГ = 1.0 / 15.0

# На сколько частей делим полный оборот при осмотре с места.
#
# Шесть, то есть по шестьдесят градусов. Поле камеры — сто тридцать, значит
# соседние взгляды перекрываются вдвое, и предмет, попавший на самый край
# кадра (где рамка обрезана и расстояние по ней врёт), в следующем взгляде
# окажется посередине. Меньше шагов — дыры между кадрами на поворотах, где
# картинка смазана; больше — обход вдвое дольше без прибавки к делу.
ОСМОТРОВ_ЗА_КРУГ = 6

# Как быстро крутимся, осматриваясь. Медленно и нарочно: камера у робота
# роллинг-шаттерная только для людей, а кадр в сеть уходит с ходу, и смаз
# превращает стул в пятно. Ноль шесть радиан в секунду — это шестьдесят
# градусов за две секунды.
ПОВОРОТ_ОСМОТРА = 0.6

# Сколько стоим на каждой остановке, дав сети посмотреть.
#
# Две секунды. Затвор (scripts/look_relay.py) отдаёт три кадра подряд, модель
# считает каждый около ста тридцати миллисекунд, плюс дорога через rosbridge;
# things.ЖДЁМ_ОТВЕТА — полторы секунды на один запрос. Берём с запасом:
# лишние полсекунды на остановке стоят дёшево, а недосмотренный угол —
# дорого, за ним придётся ехать снова.
СМОТРИМ_СЕКУНД = 2.0

# Сколько проезжаем между осмотрами. Метр двадцать: дальше — и робот
# проскакивает мимо угла, не заглянув в него; ближе — обход превращается в
# топтание, а одометрия набирает ошибку на каждом старте и торможении.
ПЕРЕЕЗД_МЕТРОВ = 1.2

# Быстрее этого в обходе не едем. Восемнадцать сантиметров в секунду —
# половина обычной скорости следования, и это не осторожность ради
# осторожности: робот едет туда, где НИЧЕГО НЕ ЗНАЕТ, и тормозной путь должен
# укладываться в то, что дальномер успевает разглядеть.
ЕДЕМ_НЕ_БЫСТРЕЕ = 0.18

# Круче этого в переезде не заворачиваем. Полрадиана в секунду — столько же,
# сколько у следования в поиске: робот слеп сзади и по бокам, а углы корпуса
# при повороте описывают окружность.
ПОВОРОТ_ОБХОДА = 0.5

# Сколько всего длится обход, если не прервать. Пять минут: за это время
# робот проезжает метров сорок и осматривается в двадцати местах — для
# двухкомнатной квартиры этого хватает, а батареи хватает надолго.
ХВАТИТ_ЧЕРЕЗ = 300.0

# Сколько остановок подряд без единой новой пометки означают «обошёл».
#
# Три. Одна пустая остановка ничего не значит — робот мог встать носом в
# пустую стену. Три подряд, между которыми он проехал по метру с лишним,
# означают, что новое кончилось. Это то же правило «loop until dry», по
# которому останавливают любой перебор с неизвестным концом.
ПУСТЫХ_СТОЯНОК = 3

# Сколько раз подряд можно не суметь уехать, прежде чем признать, что
# приехали. Робот, запертый в углу, не должен молотить колёсами до конца
# отпущенных пяти минут.
ЗАСТРЯЛИ_РАЗ = 3

# Сколько раз пробуем доехать обратно к началу и с какого расстояния считаем,
# что приехали. Четыре захода по два переезда — это метров десять пути, то
# есть обычная квартира насквозь; полметра — точность, на которую вообще
# способна одометрия после нескольких минут езды.
ДОМОЙ_ПОПЫТОК = 4
ДОМА_ЕСЛИ_БЛИЖЕ = 0.5

# Чем обход может кончиться САМ. Вслух опись зачитывается только после этих
# трёх; всё остальное — «сказали стоп», «дали другую команду», «сорвался» —
# значит обход прервали, и читать опись поверх чужого «стоп» нельзя.
#
# Списком, а не проверкой «не попросили»: причин остановки со временем
# прибавится, и по умолчанию новая причина должна МОЛЧАТЬ, а не говорить.
САМ_ДОШЁЛ = ("новое кончилось", "время вышло", "дальше не проехать")

# Сколько ждём одометрию, прежде чем считать движение по секундомеру.
# Полсекунды: одометрия идёт двадцать раз в секунду, и её отсутствие за
# полсекунды — это не заминка, а отсутствие.
ОДОМЕТРИЯ_ЖДЁТ = 0.5


class Обход:
    """Ездит по квартире, осматривается и запоминает, что где стоит."""

    def __init__(self, ros, tof, *, план=None, карта=None, пометки=None,
                 вещи=None, говорить=None) -> None:
        self.ros = ros
        self.tof = tof
        # Постоянный план квартиры: по нему выбираем, куда ехать дальше.
        # None — плана нет, и тогда едем туда, где просторнее по дальномеру.
        # Обход обязан работать и без плана: это ухудшение, а не отказ.
        self.план = план
        # Быстрая карта вокруг робота — нужна планировщику и повороту.
        self.карта = карта
        self.пометки = пометки
        self.вещи = вещи
        self.говорить = говорить or (lambda фраза: None)
        self.выбираюсь = planner.Выбираюсь()
        self._поток: threading.Thread | None = None
        self._стоп = threading.Event()
        # Итоги последнего обхода — чтобы про них можно было спросить потом.
        self.осмотрено = 0
        self.проехали = 0.0
        self.началось = 0.0
        self.кончилось = 0.0
        # Где робот стоял, когда его послали. Туда же и вернём.
        self.начальная = None
        self.почему_кончилось = ""

    # --- снаружи ----------------------------------------------------------
    @property
    def идёт(self) -> bool:
        return self._поток is not None and self._поток.is_alive()

    def начать(self) -> str:
        """Пойти обследовать квартиру. Возвращает фразу человеку."""
        if self.ros is None:
            return "Не могу обойти квартиру: нет связи с колёсами."
        if self.tof is None:
            return ("Не могу обойти квартиру: дальномера нет, а ехать по "
                    "незнакомым комнатам вслепую я не буду.")
        взгляд = self.tof.взгляд()
        if not взгляд.свежий:
            return "Не могу обойти квартиру: дальномер молчит."
        if self.вещи is None:
            # Без узнавания предметов обход выродился бы в бессмысленную
            # поездку: карта и так копится сама, пока робот ездит по делам.
            # Отказ с названной причиной честнее исправной с виду работы.
            return ("Обойти могу, но опись не составлю: узнавание предметов "
                    "не запущено. Проверь затвор look_relay и узел DOSOD.")
        if self.идёт:
            return "Я и так обхожу квартиру."
        # Колёса у одного хозяина — тот же довод, что у следования: две
        # команды на один топик означают, что робот едет в среднее место.
        освободить = getattr(self.ros, "stop_motion", None)
        if освободить is not None:
            try:
                освободить()
            except Exception:                   # noqa: BLE001
                log.exception("не смог освободить колёса перед обходом")
        self._стоп.clear()
        self.осмотрено = 0
        self.проехали = 0.0
        self.началось = time.monotonic()
        self.кончилось = 0.0
        self.начальная = self._поза()
        self.почему_кончилось = ""
        self.выбираюсь.сбросить()
        self._поток = threading.Thread(target=self._обходить, daemon=True)
        self._поток.start()
        return ("Пошёл смотреть квартиру. Это на несколько минут, скажу, "
                "когда закончу. Скажи стоп, если надоест.")

    def хватит(self, почему: str = "", *, ждать: bool = True) -> bool:
        """Прекратить обход. True — он правда шёл."""
        шло = self.идёт
        self._стоп.set()
        if шло:
            self.почему_кончилось = почему or "попросили"
            поток = self._поток
            if (ждать and поток is not None
                    and поток is not threading.current_thread()):
                поток.join(timeout=1.0)
        return шло

    # --- опись ------------------------------------------------------------
    def опись(self, подробно: bool = False) -> str:
        """Что нашли. Коротко — для голоса, подробно — для журнала и пульта.

        Считаем по НАДЁЖНЫМ пометкам, то есть виденным не меньше двух раз.
        Одиночное срабатывание распознавания бывает и на отражении в стекле, а
        человек по этой описи пойдёт в комнату проверять.
        """
        from . import things

        if self.пометки is None:
            return "Опись вести некуда: пометки не заведены."
        метки = self.пометки.надёжные()
        if not метки:
            return ("Ничего знакомого не нашёл. Либо в кадр не попало, либо "
                    "мебель не из тех восьмидесяти видов, что я знаю.")
        по_классам: dict[str, list[dict]] = {}
        for метка in метки:
            по_классам.setdefault(метка["класс"], []).append(метка)
        части = []
        for класс, свои in sorted(по_классам.items(),
                                  key=lambda п: -len(п[1])):
            имя = things.назвать(класс)
            части.append(имя if len(свои) == 1 else f"{имя} — {len(свои)}")
        коротко = ", ".join(части)
        if not подробно:
            return коротко
        строки = [f"Опись: {коротко}.", ""]
        for класс, свои in sorted(по_классам.items()):
            for метка in sorted(свои, key=lambda м: -м["раз"]):
                строки.append(
                    f"  {things.назвать(класс):<14} "
                    f"x={метка['x']:+.2f} y={метка['y']:+.2f} "
                    f"видел {метка['раз']} раз")
        if self.план is not None:
            знаю = self.план.сколько_знаю()
            строки += ["", f"План квартиры: известно {знаю['метров']} м², "
                           f"занято {знаю['занято']} клеток, "
                           f"поездок {знаю['поездок']}."]
        return "\n".join(строки)

    def _итог(self) -> str:
        """Фраза, которой обход заканчивается вслух."""
        минут = max(1, int((self.кончилось - self.началось) / 60.0 + 0.5))
        начало = (
            f"Обошёл квартиру: "
            f"{ru.count(self.осмотрено, 'осмотр', 'осмотра', 'осмотров')}, "
            f"{ru.count(int(self.проехали + 0.5), 'метр', 'метра', 'метров')}, "
            f"{ru.count(минут, 'минута', 'минуты', 'минут', female=True)}.")
        return f"{начало} {self.опись()}."

    # --- сам обход --------------------------------------------------------
    def _обходить(self) -> None:
        """Круг за кругом: осмотрелся — переехал — осмотрелся."""
        пусто = застряли = 0
        try:
            while not self._стоп.is_set():
                if time.monotonic() - self.началось > ХВАТИТ_ЧЕРЕЗ:
                    self.почему_кончилось = "время вышло"
                    break
                было = self._сколько_меток()
                self._панорама()
                self.осмотрено += 1
                новых = self._сколько_меток() - было
                log.info("обход: осмотр %d — новых пометок %d, проехал "
                         "%.1f м", self.осмотрено, новых, self.проехали)
                пусто = 0 if новых else пусто + 1
                if пусто >= ПУСТЫХ_СТОЯНОК:
                    self.почему_кончилось = "новое кончилось"
                    break
                if self._стоп.is_set():
                    break
                if self._переезд():
                    застряли = 0
                else:
                    застряли += 1
                    if застряли >= ЗАСТРЯЛИ_РАЗ:
                        self.почему_кончилось = "дальше не проехать"
                        break
            if not self._стоп.is_set():
                self._вернуться()
        except Exception:                       # noqa: BLE001
            self.почему_кончилось = "сорвался"
            log.exception("обход сорвался")
        finally:
            self.кончилось = time.monotonic()
            self._встать()
            if not self.почему_кончилось:
                self.почему_кончилось = "попросили"
            log.info("обход кончился: %s. %s", self.почему_кончилось,
                     self.опись(подробно=True))
            # Вслух — только если дошли до конца сами. Прерванный обход
            # человек прервал сам, и зачитывать ему опись поверх его же
            # «стоп» — то самое озвучивание каждого действия, от которого он
            # и просил избавить.
            if self.почему_кончилось in САМ_ДОШЁЛ:
                try:
                    self.говорить(self._итог())
                except Exception:               # noqa: BLE001
                    log.exception("не смог рассказать опись")

    def _вернуться(self) -> None:
        """Приехать обратно туда, откуда начали. Не вышло — не беда.

        Так же поступает explore_lite (`return_to_init: true`), и довод у него
        бытовой, а не научный: человек оставил робота у себя под рукой и
        рассчитывает найти его там же. Робот, закончивший опись в углу за
        креслом, формально прав и практически неудобен.

        ПОПЫТКА, А НЕ ОБЯЗАТЕЛЬСТВО. Пути мы не планируем, поэтому «домой»
        здесь значит «несколько раз довернуться на дом и проехать, сколько
        пустит дальномер». Не доехали — молчим: обещать возвращение и не
        вернуться хуже, чем не обещать.
        """
        дом = self.начальная
        if дом is None:
            return
        for _ in range(ДОМОЙ_ПОПЫТОК):
            if self._стоп.is_set():
                return
            поза = self._поза()
            if поза is None:
                return
            дx, дy = дом[0] - поза[0], дом[1] - поза[1]
            осталось = math.hypot(дx, дy)
            if осталось <= ДОМА_ЕСЛИ_БЛИЖЕ:
                log.info("обход: вернулся к началу, осталось %.2f м", осталось)
                return
            доворот = (math.atan2(дy, дx) - поза[2] + math.pi) % (2 * math.pi) - math.pi
            self._повернуть(доворот)
            if not self._ехать(min(осталось, ПЕРЕЕЗД_МЕТРОВ * 2)):
                log.info("обход: домой не проехал, осталось %.1f м", осталось)
                return

    def _сколько_меток(self) -> int:
        if self.пометки is None:
            return 0
        try:
            return len(self.пометки.надёжные())
        except Exception:                       # noqa: BLE001
            log.exception("пометки не ответили")
            return 0

    def _панорама(self) -> None:
        """Осмотреться кругом с места, дав сети посмотреть на каждой четверти.

        Смотрим ПЕРЕД поворотом, а не после: робот только что приехал сюда и
        стоит носом туда, куда ехал, — то есть в самое интересное место. Начни
        мы с поворота, первый кадр пришёлся бы на смазанную картинку.
        """
        шаг = 2 * math.pi / ОСМОТРОВ_ЗА_КРУГ
        for _ in range(ОСМОТРОВ_ЗА_КРУГ):
            if self._стоп.is_set():
                return
            self._посмотреть()
            if self._стоп.is_set():
                return
            self._повернуть(шаг)

    def _посмотреть(self) -> None:
        """Дёрнуть затвор и постоять, пока сеть считает."""
        стоим = self.ros is not None
        if стоим:
            self._встать()
        попросили = False
        try:
            попросили = bool(self.ros.посмотреть())
        except Exception:                       # noqa: BLE001
            log.exception("обход: не смог попросить кадр")
        if not попросили:
            log.debug("обход: затвор не отозвался")
        self._стоп.wait(СМОТРИМ_СЕКУНД)

    # --- движение ---------------------------------------------------------
    def _повернуть(self, на_сколько: float) -> bool:
        """Повернуться на месте на столько радиан. False — не вышло.

        Считаем по одометрии приращениями, а не разницей с началом: поворот
        идёт по кругу, и на трёхстах шестидесяти градусах разница вернулась бы
        к нулю. Нет одометрии — считаем по секундомеру от заказанной скорости:
        обход без неё станет кривым, но не сорвётся.
        """
        сторона = 1.0 if на_сколько >= 0 else -1.0
        цель = abs(на_сколько)
        повёрнуто = 0.0
        прошлая = self._поза()
        начали = time.monotonic()
        # Предохранитель: заказанная скорость плюс половина. Робот, у которого
        # буксуют колёса, иначе крутился бы вечно.
        предел = цель / ПОВОРОТ_ОСМОТРА * 1.5 + 1.0
        while not self._стоп.is_set() and повёрнуто < цель:
            if time.monotonic() - начали > предел:
                log.info("обход: поворот не сошёлся за %.1f с — еду дальше",
                         предел)
                break
            if not self._скорость(0.0, ПОВОРОТ_ОСМОТРА * сторона):
                return False
            self._стоп.wait(ШАГ)
            сейчас = self._поза()
            if сейчас is not None and прошлая is not None:
                шаг = (сейчас[2] - прошлая[2] + math.pi) % (2 * math.pi) - math.pi
                повёрнуто += abs(шаг)
            elif сейчас is None:
                повёрнуто += ПОВОРОТ_ОСМОТРА * ШАГ
            прошлая = сейчас
        self._встать()
        return повёрнуто >= цель

    def _переезд(self) -> bool:
        """Доехать до следующего места осмотра. False — не сдвинулись.

        Куда ехать, спрашиваем у плана квартиры: он один знает, где осталось
        неизвестное. Плана нет или он всё уже знает — едем туда, где
        просторнее по дальномеру: осматриваться посреди свободного места
        полезнее, чем упершись носом в шкаф.
        """
        куда = None
        if self.план is not None:
            try:
                куда = self.план.куда_неизвестно(self._поза())
            except Exception:                   # noqa: BLE001
                log.exception("обход: план не ответил, куда ехать")
        поза = self._поза()
        if куда is not None and поза is not None:
            доворот = (куда[0] - поза[2] + math.pi) % (2 * math.pi) - math.pi
            log.info("обход: неизвестного больше всего в %.0f° (%d клеток) — "
                     "доворачиваю", math.degrees(доворот), куда[1])
            self._повернуть(доворот)
        else:
            # Ни плана, ни позы: судим по дальномеру. `куда_свободнее` даёт
            # угол в системе робота, ровно то, что нужно для доворота.
            точки = self._препятствия()
            if точки:
                self._повернуть(planner.куда_просторнее(точки))
        return self._ехать(ПЕРЕЕЗД_МЕТРОВ)

    def _ехать(self, метров: float) -> bool:
        """Проехать вперёд, объезжая. False — не проехали и метра из десяти.

        Дугу выбирает тот же планировщик, что и следование, и по тем же
        точкам: разница только в том, что цель здесь не человек, а «вперёд».
        Дальномер остаётся поверх всего — он и решает, ехать ли вообще.
        """
        начало = self._поза()
        проехали = 0.0
        прошлая = начало
        начали = time.monotonic()
        предел = метров / max(0.05, ЕДЕМ_НЕ_БЫСТРЕЕ) * 2.0 + 2.0
        было_вперёд = было_поворот = 0.0
        while not self._стоп.is_set() and проехали < метров:
            if time.monotonic() - начали > предел:
                break
            взгляд = self.tof.взгляд() if self.tof is not None else None
            мешает = self.tof.мешает() if self.tof is not None else ""
            if мешает:
                # Сторож сказал «нельзя» — это не повод бросать обход, это
                # повод свернуть. Пробуем выбраться тем же арбитром, что и
                # следование; не вышло — возвращаем «не проехали», и верхний
                # цикл сам решит, сколько раз это терпеть.
                if not self._обойти(взгляд):
                    break
                continue
            свободно = getattr(взгляд, "свободно_впереди", 0.0) if взгляд else 0.0
            точки = self._препятствия(взгляд)
            вперёд, поворот = self._дуга(точки, свободно)
            if вперёд <= 0.0 and abs(поворот) <= 1e-3:
                if not self._обойти(взгляд):
                    break
                continue
            было_вперёд = planner.придержать(было_вперёд, вперёд, ШАГ,
                                             planner.РАЗГОН,
                                             planner.СБРОС)
            было_поворот = planner.придержать(было_поворот, поворот, ШАГ,
                                              planner.РАЗГОН_ПОВОРОТА,
                                              planner.РАЗГОН_ПОВОРОТА)
            if not self._скорость(было_вперёд, было_поворот):
                return проехали > 0.1
            self._стоп.wait(ШАГ)
            сейчас = self._поза()
            if сейчас is not None and прошлая is not None:
                проехали += math.hypot(сейчас[0] - прошлая[0],
                                       сейчас[1] - прошлая[1])
            elif сейчас is None:
                проехали += было_вперёд * ШАГ
            прошлая = сейчас
        self._встать()
        self.проехали += проехали
        return проехали > 0.1

    def _дуга(self, точки, свободно: float) -> tuple[float, float]:
        """Куда и как быстро ехать вперёд. Ноль-ноль — некуда."""
        потолок = min(ЕДЕМ_НЕ_БЫСТРЕЕ, скорость_по_виду(свободно)
                      if свободно > 0 else ЕДЕМ_НЕ_БЫСТРЕЕ)
        if потолок <= 0:
            return 0.0, 0.0
        # Цель — «прямо и подальше»: обход никого не догоняет, ему нужно
        # просто проехать вперёд, обходя то, что мешает.
        вперёд, поворот, _ = planner.выбрать(ПЕРЕЕЗД_МЕТРОВ, 0.0, точки,
                                             потолок, ПОВОРОТ_ОБХОДА)
        return вперёд, поворот

    def _обойти(self, взгляд) -> bool:
        """Тупик: спросить арбитра, что делать. False — сдался."""
        точки = self._препятствия(взгляд)
        вперёд, поворот, чем_занят, вслух = self.выбираюсь.решить(точки, 0.0)
        if чем_занят == planner.Выбираюсь.СДАЛСЯ:
            log.info("обход: выбраться не смог — %s", вслух or "молча")
            return False
        if not self._скорость(вперёд, поворот):
            return False
        self._стоп.wait(ШАГ)
        return True

    # --- мелочь -----------------------------------------------------------
    def _препятствия(self, взгляд=None):
        """Точки препятствий для планировщика: дальномер плюс память."""
        if взгляд is None and self.tof is not None:
            взгляд = self.tof.взгляд()
        точки = []
        if взгляд is not None:
            try:
                точки = list(planner.препятствия(взгляд.сетка))
            except Exception:                   # noqa: BLE001
                log.exception("обход: не разобрал кадр дальномера")
        if self.карта is not None:
            try:
                точки += list(planner.из_карты(self.карта))
            except Exception:                   # noqa: BLE001
                log.exception("обход: карта не отдала препятствия")
        return точки

    def _поза(self):
        """Где робот по одометрии. None — одометрии нет."""
        if self.ros is None:
            return None
        try:
            return self.ros.odom
        except Exception:                       # noqa: BLE001
            log.exception("обход: одометрия не ответила")
            return None

    def _скорость(self, вперёд: float, поворот: float) -> bool:
        """Подать скорость, если обход не отменили. False — отменили.

        Проверка вплотную к публикации, а не только в условии цикла: тот же
        довод, что у следования, — «стоп», пришедший между началом круга и
        подачей, иначе стоил бы роботу ещё одного шага вперёд.
        """
        if self._стоп.is_set():
            return False
        self.ros.publish_twist(вперёд, 0.0, поворот)
        return True

    def _встать(self) -> None:
        try:
            self.ros.publish_twist()
        except Exception:                       # noqa: BLE001
            log.exception("обход: не смог остановить колёса")
