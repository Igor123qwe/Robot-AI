class Обход(ride.Переезд):
    """Ездит по квартире, осматривается и запоминает, что где стоит."""

    def __init__(self, ros, tof, *, план=None, карта=None, пометки=None,
                 вещи=None, компас=None, говорить=None) -> None:
        self.ros = ros
        self.tof = tof
        # Постоянный план квартиры: по нему выбираем, куда ехать дальше.
        # None — плана нет, и тогда едем туда, где просторнее по дальномеру.
        # Обход обязан работать и без плана: это ухудшение, а не отказ.
        self.план = план
        # Быстрая карта вокруг робота — нужна планировщику и повороту.
        self.карта = карта
        self.пометки = пометки
        self.вещи = вещи
        # Компас по стенам. Нужен не обходу самому по себе, а согласованности:
        # карта квартиры строится в исправленном им курсе, и спрашивать её,
        # держа сырой, — значит промахиваться на накопленную поправку. См.
        # долгий разбор в _поза.
        self.компас = компас
        self.говорить = говорить or (lambda фраза: None)
        self.выбираюсь = planner.Выбираюсь()
        # Числа политики отдаём общему механизму езды. Механика у обхода и
        # поиска одна, осторожность — своя: обход ползёт медленно, потому что
        # едет в неизвестность.
        self.едем_не_быстрее = ЕДЕМ_НЕ_БЫСТРЕЕ
        self.поворот_на_ходу = ПОВОРОТ_ОБХОДА
        self.поворот_на_месте = ПОВОРОТ_ОСМОТРА
        self.переезд_метров = ПЕРЕЕЗД_МЕТРОВ
        self.забываем_неудачу = ЗАБЫВАЕМ_НЕУДАЧУ
        self._поток: threading.Thread | None = None
        self._стоп = threading.Event()
        # Последняя поданная в шасси команда — по ней сторож судит, буксуем ли.
        self._велели = (0.0, 0.0)
        # Итоги последнего обхода — чтобы про них можно было спросить потом.
        self.осмотрено = 0
        self.проехали = 0.0
        self.началось = 0.0
        self.кончилось = 0.0
        # Где робот стоял, когда его послали. Туда же и вернём.
        self.начальная = None
        self.почему_кончилось = ""
        # Направления, в которых уже не проехали: (курс в мире, когда).
        self._не_вышло: list[tuple[float, float]] = []
        # Отвечает ли сеть узнавания. Ложь — ждать её на каждом взгляде
        # незачем, но обход из-за этого не прекращаем: карта важнее.
        self.сеть_молчит = False

    # --- снаружи ----------------------------------------------------------
    @property
    def идёт(self) -> bool:
        return self._поток is not None and self._поток.is_alive()

    def начать(self) -> str:
        """Пойти обследовать квартиру. Возвращает фразу человеку."""
        if self.ros is None:
            return "Не могу обойти квартиру: нет связи с колёсами."
        if self.tof is None:
            return ("Не могу обойти квартиру: дальномера нет, а ехать по "
                    "незнакомым комнатам вслепую я не буду.")
        взгляд = self.tof.взгляд()
        if not взгляд.свежий:
            return "Не могу обойти квартиру: дальномер молчит."
        if self.вещи is None:
            # Без узнавания предметов обход выродился бы в бессмысленную
            # поездку: карта и так копится сама, пока робот ездит по делам.
            # Отказ с названной причиной честнее исправной с виду работы.
            return ("Обойти могу, но опись не составлю: узнавание предметов "
                    "не запущено. Проверь затвор look_relay и узел DOSOD.")
        if self.идёт:
            return "Я и так обхожу квартиру."
        # Колёса у одного хозяина — тот же довод, что у следования: две
        # команды на один топик означают, что робот едет в среднее место.
        освободить = getattr(self.ros, "stop_motion", None)
        if освободить is not None:
            try:
                освободить()
            except Exception:                   # noqa: BLE001
                log.exception("не смог освободить колёса перед обходом")
        self._стоп.clear()
        self.осмотрено = 0
        self.проехали = 0.0
        self.началось = time.monotonic()
        self.кончилось = 0.0
        self.начальная = self._поза()
        self.почему_кончилось = ""
        self.выбираюсь.сбросить()
        self._не_вышло.clear()
        self.сеть_молчит = False
        self._поток = threading.Thread(target=self._обходить, daemon=True)
        self._поток.start()
        return ("Пошёл смотреть квартиру. Это на несколько минут, скажу, "
                "когда закончу. Скажи стоп, если надоест.")

    def хватит(self, почему: str = "", *, ждать: bool = True) -> bool:
        """Прекратить обход. True — он правда шёл."""
        шло = self.идёт
        self._стоп.set()
        if шло:
            self.почему_кончилось = почему or "попросили"
            поток = self._поток
            if (ждать and поток is not None
                    and поток is not threading.current_thread()):
                поток.join(timeout=1.0)
        return шло

    # --- опись ------------------------------------------------------------
    def опись(self, подробно: bool = False) -> str:
        """Что нашли. Коротко — для голоса, подробно — для журнала и пульта.

        Считаем по НАДЁЖНЫМ пометкам, то есть виденным не меньше двух раз.
        Одиночное срабатывание распознавания бывает и на отражении в стекле, а
        человек по этой описи пойдёт в комнату проверять.
        """
        from . import things

        if self.пометки is None:
            return "Опись вести некуда: пометки не заведены."
        метки = self.пометки.надёжные()
        if not метки:
            return ("Ничего знакомого не нашёл. Либо в кадр не попало, либо "
                    "мебель не из тех восьмидесяти видов, что я знаю.")
        по_классам: dict[str, list[dict]] = {}
        for метка in метки:
            по_классам.setdefault(метка["класс"], []).append(метка)
        части = []
        for класс, свои in sorted(по_классам.items(),
                                  key=lambda п: -len(п[1])):
            имя = things.назвать(класс)
            части.append(имя if len(свои) == 1 else f"{имя} — {len(свои)}")
        коротко = ", ".join(части)
        if not подробно:
            return коротко
        строки = [f"Опись: {коротко}.", ""]
        for класс, свои in sorted(по_классам.items()):
            for метка in sorted(свои, key=lambda м: -м["раз"]):
                строки.append(
                    f"  {things.назвать(класс):<14} "
                    f"x={метка['x']:+.2f} y={метка['y']:+.2f} "
                    f"видел {метка['раз']} раз")
        if self.план is not None:
            знаю = self.план.сколько_знаю()
            строки += ["", f"План квартиры: известно {знаю['метров']} м², "
                           f"занято {знаю['занято']} клеток, "
                           f"поездок {знаю['поездок']}."]
        return "\n".join(строки)

    def _итог(self) -> str:
        """Фраза, которой обход заканчивается вслух."""
        минут = max(1, int((self.кончилось - self.началось) / 60.0 + 0.5))
        начало = (
            f"Обошёл квартиру: "
            f"{ru.count(self.осмотрено, 'осмотр', 'осмотра', 'осмотров')}, "
            f"{ru.count(int(self.проехали + 0.5), 'метр', 'метра', 'метров')}, "
            f"{ru.count(минут, 'минута', 'минуты', 'минут', female=True)}.")
        # СНАЧАЛА КАРТА — она и есть цель обхода. Игорь: «цель, чтобы он
        # составил карту и сделал отметки на карте как базу данных, в первую
        # очередь для улучшения навигации».
        про_карту = ""
        if self.план is not None:
            try:
                знаю = self.план.сколько_знаю()
                про_карту = f" Знаю про квартиру {знаю['метров']:.0f} м²."
            except Exception:                   # noqa: BLE001
                log.exception("план не ответил, сколько знает")
            # А ЕСЛИ ЗАПИСЫВАТЬ БЫЛО НЕКУДА — СКАЗАТЬ ЭТО ПЕРВЫМ ДЕЛОМ.
            #
            # Постоянная карта не растёт, пока робот не узнал квартиру
            # (atlas.влить, привязан=False), и до сих пор об этом не было
            # сказано нигде: обход честно ездил, честно отчитывался
            # пройденными метрами и заканчивался словами «обошёл квартиру» —
            # а в карту не легло ни клетки. Со стороны это неотличимо от
            # удачного обхода, и человек ждёт карту, которой не будет.
            if getattr(self.план, "не_влито", 0) > 0:
                return (f"{начало} Но в карту я НИЧЕГО НЕ ЗАПИСАЛ: не узнал "
                        f"квартиру и боюсь испортить старую карту, наложив "
                        f"новую вкривь. Пока не починим узнавание предметов, "
                        f"карта не растёт.")
        if self.сеть_молчит:
            return (f"{начало}{про_карту} А опись составить не смог: "
                    f"узнавание предметов не отвечает. Проверь, поднят ли "
                    f"узел DOSOD и затвор.")
        return f"{начало}{про_карту} {self.опись().rstrip('.')}."

    # --- сам обход --------------------------------------------------------
    def _обходить(self) -> None:
        """Круг за кругом: осмотрелся — переехал — осмотрелся."""
        пусто = застряли = молчит = 0
        try:
            while not self._стоп.is_set():
                if time.monotonic() - self.началось > ХВАТИТ_ЧЕРЕЗ:
                    self.почему_кончилось = "время вышло"
                    break
                было = self._сколько_меток()
                отвечала = self._когда_отвечали()
                self._панорама()
                self.осмотрено += 1
                новых = self._сколько_меток() - было
                # СЕТЬ МОЛЧИТ — ЭТО ПОВОД НЕ ЖДАТЬ ЕЁ, А НЕ ПОВОД ВСТАТЬ.
                #
                # Здесь стоял выход из обхода: не ответила дважды — уходим. И
                # это было неверно понятой целью. Игорь сказал прямо: «цель,
                # чтобы он составил карту и сделал отметки на карте как базу
                # данных, в первую очередь для улучшения навигации; он должен
                # объехать всю квартиру, условно открыть все места».
                #
                # Значит главное — ПОКРЫТИЕ, а опись предметов идёт попутно.
                # Карта копится с каждого кадра дальномера, и от того, отвечает
                # ли сеть узнавания, не зависит вовсе. Уходить из-за неё —
                # значит бросать главное дело из-за неудавшегося побочного: в
                # живом журнале обход из-за этого кончился через две минуты и
                # два метра, не открыв ничего.
                #
                # Молчание всё равно замечаем — но чтобы ПЕРЕСТАТЬ ЖДАТЬ. Взгляд
                # ждёт ответа до СМОТРИМ_СЕКУНД, и на шести взглядах это
                # двенадцать секунд простоя на каждой остановке. Ждать того,
                # кого нет, незачем.
                if self.вещи is not None and self._когда_отвечали() == отвечала:
                    молчит += 1
                    if молчит == МОЛЧИТ_ОСМОТРОВ:
                        self.сеть_молчит = True
                        log.warning(
                            "обход: узнавание предметов не ответило ни разу за "
                            "%d осмотра — описи не будет, но карту составлю. "
                            "Ждать сеть перестаю.", молчит)
                else:
                    молчит = 0
                    self.сеть_молчит = False
                log.info("обход: осмотр %d — новых пометок %d, проехал "
                         "%.1f м", self.осмотрено, новых, self.проехали)
                if self._стоп.is_set():
                    break
                # КУДА ДАЛЬШЕ — СПРАШИВАЕМ У КАРТЫ, И ОНА ЖЕ РЕШАЕТ, ХВАТИТ ЛИ.
                #
                # Здесь стоял счёт «остановок без новых пометок», и он оказался
                # мерой не того. Пометки — это ВЕЩИ, а обход про ПОКРЫТИЕ:
                # пустая прихожая не даёт ни одной пометки и обойти её всё
                # равно надо. На живом роботе это и вышло: три пустые
                # остановки подряд — и «новое кончилось» посреди неосмотренной
                # квартиры.
                #
                # Правильная мера — карта: некуда ехать значит нечего смотреть.
                # Ровно так же решает explore_lite (кончились фронтиры) и ровно
                # это отвечает куда_неизвестно, возвращая None.
                куда, отчего = self._куда_дальше()
                if куда is None:
                    log.info("обход: карта не подсказала направление — %s",
                             отчего)
                # «ОБОШЁЛ» ОБЪЯВЛЯЕМ ТОЛЬКО ПО ОДНОЙ ПРИЧИНЕ ИЗ ЧЕТЫРЁХ.
                # Молчащая одометрия, отсутствующий план и упавший план — это
                # не «квартира обойдена», это «спросить не у кого». Ехать в
                # таком положении надо дальше, а не заканчивать обход и
                # зачитывать опись, будто всё получилось.
                if отчего == "всё известно":
                    пусто += 1
                    if пусто >= ПУСТЫХ_СТОЯНОК:
                        self.почему_кончилось = "карта полна"
                        break
                else:
                    пусто = 0
                if self._переезд(куда):
                    застряли = 0
                else:
                    # Не вышло — запоминаем НАПРАВЛЕНИЕ, а не только неудачу.
                    # Иначе карта посоветует то же самое, робот упрётся в тот
                    # же стул, и так до конца отпущенного времени.
                    if куда is not None:
                        self._не_вышло.append((куда[0], time.monotonic()))
                    застряли += 1
                    if застряли >= ЗАСТРЯЛИ_РАЗ:
                        self.почему_кончилось = "дальше не проехать"
                        break
            if not self._стоп.is_set():
                self._вернуться()
        except Exception:                       # noqa: BLE001
            self.почему_кончилось = "сорвался"
            log.exception("обход сорвался")
        finally:
            self.кончилось = time.monotonic()
            self._встать()
            if not self.почему_кончилось:
                self.почему_кончилось = "попросили"
            log.info("обход кончился: %s. %s", self.почему_кончилось,
                     self.опись(подробно=True))
            # Вслух — только если дошли до конца сами. Прерванный обход
            # человек прервал сам, и зачитывать ему опись поверх его же
            # «стоп» — то самое озвучивание каждого действия, от которого он
            # и просил избавить.
            if self.почему_кончилось in САМ_ДОШЁЛ:
                try:
                    self.говорить(self._итог())
                except Exception:               # noqa: BLE001
                    log.exception("не смог рассказать опись")

    def _вернуться(self) -> None:
        """Приехать обратно туда, откуда начали. Не вышло — не беда.

        Так же поступает explore_lite (`return_to_init: true`), и довод у него
        бытовой, а не научный: человек оставил робота у себя под рукой и
        рассчитывает найти его там же. Робот, закончивший опись в углу за
        креслом, формально прав и практически неудобен.

        ПОПЫТКА, А НЕ ОБЯЗАТЕЛЬСТВО. Пути мы не планируем, поэтому «домой»
        здесь значит «несколько раз довернуться на дом и проехать, сколько
        пустит дальномер». Не доехали — молчим: обещать возвращение и не
        вернуться хуже, чем не обещать.
        """
        дом = self.начальная
        if дом is None:
            return
        for _ in range(ДОМОЙ_ПОПЫТОК):
            if self._стоп.is_set():
                return
            поза = self._поза()
            if поза is None:
                return
            дx, дy = дом[0] - поза[0], дом[1] - поза[1]
            осталось = math.hypot(дx, дy)
            if осталось <= ДОМА_ЕСЛИ_БЛИЖЕ:
                log.info("обход: вернулся к началу, осталось %.2f м", осталось)
                return
            доворот = (math.atan2(дy, дx) - поза[2] + math.pi) % (2 * math.pi) - math.pi
            self._повернуть(доворот)
            if not self._ехать(min(осталось, ПЕРЕЕЗД_МЕТРОВ * 2)):
                log.info("обход: домой не проехал, осталось %.1f м", осталось)
                return

    def _сколько_меток(self) -> int:
        if self.пометки is None:
            return 0
        try:
            return len(self.пометки.надёжные())
        except Exception:                       # noqa: BLE001
            log.exception("пометки не ответили")
            return 0

    def _панорама(self) -> None:
        """Осмотреться кругом с места, дав сети посмотреть на каждой четверти.

        Смотрим ПЕРЕД поворотом, а не после: робот только что приехал сюда и
        стоит носом туда, куда ехал, — то есть в самое интересное место. Начни
        мы с поворота, первый кадр пришёлся бы на смазанную картинку.
        """
        шаг = 2 * math.pi / ОСМОТРОВ_ЗА_КРУГ
        for _ in range(ОСМОТРОВ_ЗА_КРУГ):
            if self._стоп.is_set():
                return
            self._посмотреть()
            if self._стоп.is_set():
                return
            self._повернуть(шаг)

    def _посмотреть(self) -> None:
        """Дёрнуть затвор и постоять, пока сеть считает.

        ЖДЁМ ОТВЕТА, А НЕ СЕКУНДОМЕР. Здесь стояло «подождать две секунды с
        запасом», и на живом роботе это вышло в сорок секунд на остановку:
        шесть взглядов по две секунды плюс повороты. За отпущенные пять минут
        робот успел ТРИ остановки и два метра — на квартиру этого не хватает
        близко.

        Две секунды были взяты с запасом на самый медленный случай, а платил
        за них каждый взгляд. Правильнее спросить у самой памяти вещей, когда
        ответ пришёл: `отвечали` — это отметка времени последнего ответа сети.
        Пришёл за триста миллисекунд — едем дальше, не дожидаясь остального.
        Потолок остаётся тот же, но теперь он потолок, а не такса.
        """
        if self.ros is not None:
            self._встать()
        было = self._когда_отвечали()
        try:
            if not self.ros.посмотреть():
                log.debug("обход: затвор не отозвался")
        except Exception:                       # noqa: BLE001
            log.exception("обход: не смог попросить кадр")
        # Молчащую сеть не ждём вовсе: кадр всё равно просим (вдруг ожила),
        # но простаивать по две секунды на каждом взгляде из-за неё не будем.
        ждём = time.monotonic() + (0.0 if self.сеть_молчит else СМОТРИМ_СЕКУНД)
        while time.monotonic() < ждём and not self._стоп.is_set():
            if self._когда_отвечали() != было:
                return
            self._стоп.wait(ШАГ)

    def _когда_отвечали(self) -> float:
        """Отметка времени последнего ответа сети. Ноль — не отвечала."""
        try:
            return float(getattr(self.вещи, "отвечали", 0.0) or 0.0)
        except Exception:                       # noqa: BLE001
            return 0.0

    # --- движение ---------------------------------------------------------
    def _куда_дальше(self):
        """Куда ехать за новым: ((курс, клеток) или None, почему).

        ПОЧЕМУ ВОЗВРАЩАЕМ ПРИЧИНУ, А НЕ ОДИН ТОЛЬКО None. Пустой ответ здесь
        значит четыре разные вещи, и лечатся они противоположно:

          «нет плана»    — обход идёт без карты квартиры. Ездить надо, решать
                           «обошёл» по карте нельзя: карты нет;
          «нет позы»     — одометрия молчит. Робот не знает, где стоит, и
                           карта тут ни при чём — надо просто подождать;
          «план упал»    — исключение. Поломка, а не вывод о квартире;
          «всё известно» — и ВОТ ЭТО единственное, что вправду означает
                           «обошёл».

        Раньше все четыре сливались в None, верхний цикл считал их одинаково,
        и три пустых ответа подряд объявляли «карта полна». То есть молчащая
        одометрия и упавший план заканчивали обход теми же словами, что и
        честно обойдённая квартира, — и в журнале было не отличить.
        """
        if self.план is None:
            return None, "нет плана"
        поза = self._поза()
        if поза is None:
            return None, "нет позы"
        сейчас = time.monotonic()
        self._не_вышло = [(курс, когда) for курс, когда in self._не_вышло
                          if сейчас - когда < ЗАБЫВАЕМ_НЕУДАЧУ]
        try:
            куда = self.план.куда_неизвестно(
                поза, избегать=[к for к, _ in self._не_вышло])
        except Exception:                       # noqa: BLE001
            log.exception("обход: план не ответил, куда ехать")
            return None, "план упал"
        if куда is None:
            # Неизвестного не нашлось — но, может быть, только потому, что все
            # стороны в чёрном списке. Это «пока некуда», а не «всё известно»:
            # список сам стухнет через полминуты.
            if self._не_вышло:
                return None, "всё в чёрном списке"
            return None, "всё известно"
        return куда, ""


    def _переезд(self, куда=None) -> bool:
        """Доехать до следующего места осмотра. False — не сдвинулись.

        Карта не подсказала — едем туда, где просторнее по дальномеру:
        осматриваться посреди свободного места полезнее, чем упершись носом
        в шкаф, а стоять на месте бесполезно совсем.
        """
        поза = self._поза()
        if куда is not None and поза is not None:
            доворот = (куда[0] - поза[2] + math.pi) % (2 * math.pi) - math.pi
            log.info("обход: неизвестного больше всего в %.0f° (%d клеток) — "
                     "доворачиваю", math.degrees(доворот), куда[1])
            self._повернуть(доворот)
        else:
            точки = self._препятствия()
            if точки:
                self._повернуть(planner.куда_просторнее(точки))
        return self._ехать(ПЕРЕЕЗД_МЕТРОВ)
