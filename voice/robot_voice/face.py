"""Лицо робота: что показывать на экране, решает голосовая служба.

ЧТО ЭТО. Экран рисует отдельная служба `robot-face` (каталог `face/`), и она
НИЧЕГО не знает про робота. Она умеет одно: прочитать файл и нарисовать то,
что в нём написано. Всё знание о том, что робот делает, живёт здесь — в
процессе, который этим и занят, — и раз в десятую секунды выкладывается в
`/run/robot-ai/face.json`.

Так сделано по двум причинам, и обе записаны в docs/screen.md:

  • лицо не должно замирать, пока модель думает. Голосовой цикл висит в
    разговоре с моделью секундами, и если бы он же и рисовал, глаза бы
    застывали ровно тогда, когда человек ждёт ответа;
  • экран не имеет права врать. Он показывает только то, что робот знает о
    себе сам, теми же словами, что уходят в журнал. Никакой «задумчивости»,
    которой нет в коде.

ПОЧЕМУ ФАЙЛ, А НЕ СОКЕТ. По той же причине, что сетка дальномера и карта:
второй процесс, ещё один сетевой канал — ещё один способ всё сломать. Файл в
/run живёт в памяти, systemd убирает его при остановке службы, и застывшее
вчерашнее лицо не переживёт падения. Метка времени в файле — НАСТЕННЫЕ часы:
читает другой процесс, и сравнивать ему надо со своими часами, а не с чужим
счётчиком от загрузки.

ЧТО В ФАЙЛЕ. Ровно то, что нужно нарисовать, и ничего сверх:

    эмоция     — одна из ЭМОЦИИ; форма глаз
    строка     — что робот делает, словами: «слушаю», «думаю», «говорю», «еду»
    услышал    — последняя распознанная фраза: половина вечера уходит на
                 «он меня не понял», а тут видно сразу, что именно он услышал
    говорит    — что произносит прямо сейчас
    батарея    — вольты или null, если шасси молчит
    взгляд     — куда смотреть, радианы влево+, или null: глаза следуют за
                 человеком по пеленгу с камеры
    человек    — видит ли камера человека сейчас (от этого зависит яркость)
    едет       — крутятся ли колёса
    музыка     — {играет, название, режим («поток» — радио, «треки»),
                 прошло, длина} — секунды; длина 0 у радио
    погода     — {t, код, макс, мин, описание} или null. ТОЛЬКО когда о ней
                 спросили — сорок секунд после «какая погода», как карточка
                 у колонок с экраном: виджет появляется по делу, а не висит
    таймеры    — [{имя, осталось}] по ближайшему; пусто — ничего не идёт
    подсказка  — «Скажи: „Кузя, включи радио“» — только в покое: ни музыки,
                 ни речи, ни движения. Фразы — те, что робот правда понимает
    рот        — 0..1 по громкости звука, пока говорит (face/lips.py), или
                 null, если звук прошёл мимо (piper напрямую в динамик)
    движение   — {есть, сила, где} — что-то шевельнулось в кадре камеры
                 (motion.py), где: −1 слева … +1 справа
    делает     — {номер, что} — какой инструмент мозг позвал последним;
                 персонаж на экране изображает действие (сценки)
    ночь       — тихие часы: лицо тускнеет и теплеет

И ОБРАТНО: `/run/robot-ai/touch.json` пишет экран, когда на нём нажали
кнопку (тач), — {номер, действие}; голосовая служба читает его тем же
тактом и делает то же, что сделала бы по голосу: «дальше», «стоп»,
«тише», «громче». Номер растёт на каждое нажатие — одно нажатие
исполняется один раз.

ЭМОЦИИ — НЕ УКРАШЕНИЕ, А СОСТОЯНИЕ КОДА. Каждая наступает от конкретного
события в цикле и держится ровно столько, сколько это событие длится:
«слушаю» — пока открыто окно разговора, «думаю» — пока ждём модель, «говорю»
— пока звучит реплика. Короткие («рад», «не понял», «огорчён») сами гаснут
через несколько секунд: настроение, которое держится, пока его не сменят, —
это застывшее лицо, только медленное.
"""

from __future__ import annotations

import json
import logging
import os
import threading
import time
import urllib.error
import urllib.request
from pathlib import Path

from . import weather as weather_api

# Рот по звуку — общий модуль с ПК (face/lips.py): одна огибающая на двоих,
# чтобы своё лицо и аватар на ПК открывали рот по одним и тем же правилам.
import sys as _sys  # noqa: E402
_sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "face"))
import lips  # noqa: E402

log = logging.getLogger(__name__)

ФАЙЛ = os.environ.get("ROBOT_FACE_FILE", "/run/robot-ai/face.json")
# На машине без systemd каталога /run/robot-ai нет — тогда рядом с остальным.
ЗАПАСНОЙ_ФАЙЛ = "~/.robot-ai/face.json"

# Десять раз в секунду. Требование из ТЗ — не больше 200 мс от смены состояния
# в коде до смены на экране; половина уходит здесь, половина на чтение.
ПИШЕМ_РАЗ_В = 0.1
# Погода меняется не быстрее. Чаще — это трафик и нагрузка на чужой сервис
# ради виджета, который никто не разглядывает.
ПОГОДА_РАЗ_В = 600.0
# Если погоду не удалось узнать — пробуем снова через минуту, а не через десять:
# интернета не было при старте, а появится он скоро.
ПОГОДА_СНОВА_ЧЕРЕЗ = 60.0

ЭМОЦИИ = ("спокоен", "рад", "слушаю", "думаю", "не_понял", "огорчён",
          "встревожен", "сплю")
# Настроения, которые гаснут сами. Секунды.
ГАСНУТ_ЧЕРЕЗ = {"рад": 3.0, "не_понял": 3.0, "огорчён": 4.0}

# Сколько держать карточку погоды после вопроса о ней. Дольше — это уже
# «висит всегда», и ради чего тогда спрашивать.
ПОГОДА_ПОКАЗЫВАТЬ = 40.0
# Подсказки «Скажи: …» — по одной, сменяются раз в столько секунд. Только
# фразы, которые робот разбирает правилами (intents.py) или навыками: экран
# не имеет права обещать то, чего робот не умеет.
ПОДСКАЗКА_РАЗ_В = 20.0
ПОДСКАЗКИ = (
    "«Кузя, включи радио»",
    "«Кузя, включи музыку»",
    "«Кузя, какая погода»",
    "«Кузя, поставь таймер на десять минут»",
    "«Кузя, разбуди в семь утра»",
    "«Кузя, поехали за мной»",
    "«Кузя, что играет»",
    "«Кузя, сделай тише»",
    "«Кузя, какой заряд»",
    "«Кузя, напомни завтра в восемь полить цветы»",
)
# Что можно нажать на экране и что это значит для проигрывателя.
НАЖАТИЯ = ("дальше", "стоп", "тише", "громче")


def описание_погоды(код: int) -> str:
    """Словами, как их произносит человек. Одна таблица — та, что у голоса."""
    return weather_api._SKY.get(int(код), "")


class Лицо:
    """Собирает состояние робота в одно и выкладывает его файлом.

    Всё, что меняет лицо, зовётся из голосового цикла: `слушаю`, `думаю`,
    `говорю`, `сказал`, `услышал`, `не_понял`, `рад`, `огорчён`,
    `встревожен`. Остальное — батарея, колёса, взгляд, музыка — лицо
    спрашивает само у тех, кто это знает.

    `состояние()` — чистая функция от того, что накоплено: её можно проверить
    без файла, без потоков и без робота. Поток только пишет.
    """

    def __init__(self, *, ros=None, глаза=None, player=None, где=None,
                 тихо=None, таймеры=None, часы=time.monotonic,
                 файл: str | None = None, погода=weather_api.fetch,
                 слушаю_секунд: float = 20.0, аватар_url: str = "") -> None:
        self.ros = ros
        self.таймеры = таймеры            # tools.Timers или None
        self._погода_показать_до = float("-inf")
        self._нажатие_было = 0            # номер последнего исполненного
        # Рот по звуку: то, что робот кладёт в динамик, приходит сюда через
        # speaker.on_pcm (app.py). Пока говорит — рот идёт по огибающей.
        self.губы = lips.Губы(часы)
        # Движение в кадре камеры (motion.Движение) — или None.
        self.движение = None
        # Последний позванный инструмент: {номер, что}.
        self._делает: dict = {"номер": 0, "что": ""}
        # Необязательная копия того же состояния — на ПК, если там поднят
        # аватар (pc/avatar). Экран робота в этом не нуждается: как рисовал
        # сам, так и рисует, ПК тут ДОБАВКА, а не замена.
        self.аватар_url = (аватар_url or "").rstrip("/")
        self._аватар_вниз_до = 0.0
        # «Слушаю» держится ровно столько, сколько открыто окно разговора, и
        # число это — то же, что у голосового цикла (cfg.session_seconds), а
        # не своё. Свои двадцать секунд разошлись бы с окном при первой же
        # правке настройки, и лицо слушало бы, когда робот уже нет.
        self.слушаю_секунд = float(слушаю_секунд)
        self.глаза = глаза
        self.player = player
        self.где = где                    # () -> (lat, lon) | None
        self.тихо = тихо                  # () -> bool, тихие ли часы
        self._часы = часы
        self._погода_из = погода
        self._файл = Path(файл or ФАЙЛ)
        self._lock = threading.RLock()
        self._стоп = threading.Event()

        self._эмоция = "спокоен"
        self._эмоция_с = 0.0
        self._услышал = ""
        self._говорит = ""
        self._строка = ""
        self._причина = ""               # чем встревожен
        self._погода: dict | None = None
        self._погода_когда = 0.0
        self._погода_пробовали = 0.0
        self._записей = 0
        self._не_смог_писать = False

    # --- то, что зовёт голосовой цикл -------------------------------------
    def _стать(self, эмоция: str) -> None:
        if эмоция not in ЭМОЦИИ:
            raise ValueError(f"нет такой эмоции: {эмоция!r}")
        with self._lock:
            self._эмоция = эмоция
            self._эмоция_с = self._часы()

    def слушаю(self) -> None:
        """Окно разговора открыто: робота позвали, он ждёт продолжения."""
        with self._lock:
            self._говорит = ""
            self._стать("слушаю")

    def думаю(self) -> None:
        """Ждём модель. Держится, пока не начнётся ответ."""
        with self._lock:
            self._говорит = ""
            self._стать("думаю")

    def говорю(self, фраза: str) -> None:
        """Звучит реплика. Лицо спокойное — эмоцию несёт текст, не глаза."""
        with self._lock:
            self._говорит = (фраза or "").strip()
            # Тревога и огорчение переживают реплику: робот, который говорит
            # «впереди стена» со спокойным лицом, врёт лицом.
            if self._эмоция not in ("встревожен", "огорчён"):
                self._стать("спокоен")

    def сказал(self) -> None:
        """Реплика отзвучала — или её оборвали. Огибающую не доигрываем."""
        with self._lock:
            self._говорит = ""
        self.губы.сбросить()

    def делает(self, что: str) -> None:
        """Мозг позвал инструмент — персонаж на экране «делает» это сам.

        Номер растёт на каждый вызов: сценки на ПК и у домовёнка ловят его
        смену, а не имя — два «drive» подряд должны дать два жеста.
        """
        with self._lock:
            self._делает = {"номер": self._делает.get("номер", 0) + 1,
                            "что": str(что or "")}

    def озвучил(self, pcm: bytes, rate: int) -> None:
        """Звук ушёл в динамик — рот пойдёт по нему (speaker.on_pcm)."""
        try:
            self.губы.добавить(pcm, int(rate))
        except Exception:                       # noqa: BLE001
            log.debug("лицо: не разобрал звук под рот", exc_info=True)

    def _рот(self, говорит: str) -> float | None:
        """0..1 по звуку, пока говорит; None — звука не видели, пусть синус."""
        if not говорит:
            return None
        return self.губы.рот()

    def _движение(self) -> dict:
        д = self.движение
        if д is None:
            return {"есть": False, "сила": 0.0, "где": 0.0}
        try:
            return д.состояние()
        except Exception:                       # noqa: BLE001
            return {"есть": False, "сила": 0.0, "где": 0.0}

    def услышал(self, текст: str) -> None:
        with self._lock:
            self._услышал = (текст or "").strip()
            # Спросили о погоде — карточка появляется на время. Именно по
            # услышанному, а не по вызову инструмента: погоду отвечают и
            # правилом, и моделью, и навыком, а услышанное общее для всех.
            if "погод" in self._услышал.lower():
                self._погода_показать_до = self._часы() + ПОГОДА_ПОКАЗЫВАТЬ

    def нажали(self, действие: str) -> str:
        """Кнопка на экране — то же, что голосом. Возвращает ответ проигрывателя."""
        p = self.player
        if p is None or действие not in НАЖАТИЯ:
            return ""
        try:
            if действие == "дальше":
                return str(p.дальше(вслух=False) or "")
            if действие == "стоп":
                return str(p.выключить() or "")
            if действие == "тише":
                return str(p.тише() or "")
            return str(p.громче() or "")
        except Exception as e:                       # noqa: BLE001
            log.warning("лицо: нажатие «%s» не вышло (%s)", действие, e)
            return ""

    def _прочитать_нажатие(self) -> None:
        """touch.json от экрана: новый номер — новое нажатие, исполнить раз."""
        файл = self._файл.with_name("touch.json")
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
            номер, действие = int(данные.get("номер") or 0), str(данные.get("действие") or "")
        except (OSError, ValueError, AttributeError):
            return
        if номер <= self._нажатие_было:
            return
        self._нажатие_было = номер
        ответ = self.нажали(действие)
        log.info("лицо: нажали «%s»%s", действие, f" — {ответ}" if ответ else "")

    def не_понял(self) -> None:
        self._стать("не_понял")

    def рад(self) -> None:
        self._стать("рад")

    def огорчён(self) -> None:
        self._стать("огорчён")

    def встревожен(self, почему: str = "") -> None:
        """Не пускаю вперёд. Держится, пока не позовут `спокоен`."""
        with self._lock:
            self._причина = (почему or "").strip()
            self._стать("встревожен")

    def спокоен(self) -> None:
        with self._lock:
            self._причина = ""
            self._стать("спокоен")

    # --- сборка -----------------------------------------------------------
    def _эмоция_сейчас(self) -> str:
        """Короткие настроения гаснут сами — иначе это застывшее лицо."""
        эмоция = self._эмоция
        держим = ГАСНУТ_ЧЕРЕЗ.get(эмоция)
        if эмоция == "слушаю":
            держим = self.слушаю_секунд
        if держим is not None and self._часы() - self._эмоция_с > держим:
            return "спокоен"
        return эмоция

    def _едет(self) -> bool:
        try:
            return bool(self.ros is not None and self.ros.moving)
        except Exception:                       # noqa: BLE001
            return False

    def _батарея(self) -> float | None:
        try:
            в = self.ros.voltage if self.ros is not None else None
        except Exception:                       # noqa: BLE001
            return None
        return round(float(в), 2) if в is not None else None

    def _взгляд(self) -> tuple[bool, float | None]:
        """(видит ли человека, куда смотреть). Взгляд только по свежему."""
        г = self.глаза
        if г is None:
            return False, None
        try:
            if not г.свежий:
                return False, None
            return True, round(float(г.угол), 3)
        except Exception:                       # noqa: BLE001
            return False, None

    def _музыка(self) -> dict:
        p = self.player
        тишина = {"играет": False, "название": "", "режим": "", "прошло": 0, "длина": 0}
        if p is None:
            return тишина
        try:
            играет = bool(p.играет)
            прошло, длина = (0.0, 0.0)
            позиция = getattr(p, "позиция", None)
            if играет and callable(позиция):
                прошло, длина = позиция()
            return {"играет": играет,
                    "название": str(getattr(p, "название", "") or ""),
                    "режим": str(getattr(p, "режим", "") or "") if играет else "",
                    "прошло": int(прошло), "длина": int(длина)}
        except Exception:                       # noqa: BLE001
            return тишина

    def _таймеры(self) -> list[dict]:
        """Идущие таймеры по ближайшему. Пауза — тоже таймер, с пометкой."""
        т = self.таймеры
        if т is None:
            return []
        try:
            идут = [{"имя": имя, "осталось": int(round(сек))}
                    for имя, сек in т.remaining().items()]
            идут.sort(key=lambda з: з["осталось"])
            стоят = [{"имя": имя, "осталось": int(round(сек)), "пауза": True}
                     for имя, сек in getattr(т, "paused", dict)().items()]
            return (идут + стоят)[:3]
        except Exception:                       # noqa: BLE001
            return []

    def _подсказка(self, эмоция: str, говорит: str, едет: bool, музыка: dict) -> str:
        """«Скажи: …» — только когда экрану больше нечего сказать.

        Пока играет музыка, идёт речь или робот едет — на экране есть дело
        важнее, и подсказка поверх него была бы рекламой, а не помощью.
        """
        if эмоция != "спокоен" or говорит or едет or музыка.get("играет"):
            return ""
        номер = int(self._часы() / ПОДСКАЗКА_РАЗ_В) % len(ПОДСКАЗКИ)
        return f"Скажи: {ПОДСКАЗКИ[номер]}"

    def _ночь(self) -> bool:
        try:
            return bool(self.тихо()) if self.тихо is not None else False
        except Exception:                       # noqa: BLE001
            return False

    def состояние(self) -> dict:
        """Всё, что нужно нарисовать. Чистая функция от накопленного."""
        with self._lock:
            эмоция = self._эмоция_сейчас()
            говорит = self._говорит
            услышал = self._услышал
            причина = self._причина
            # Погода — по делу: карточка живёт ПОГОДА_ПОКАЗЫВАТЬ после вопроса.
            погода = (self._погода
                      if self._часы() < self._погода_показать_до else None)
        едет = self._едет()
        человек, взгляд = self._взгляд()
        музыка = self._музыка()

        # Строка состояния — словами, что робот делает. Порядок важен: речь
        # главнее мысли, мысль главнее ожидания, а колёса — отдельная правда,
        # которая идёт рядом, а не вместо.
        if говорит:
            строка = "говорю"
        elif эмоция == "думаю":
            строка = "думаю"
        elif эмоция == "слушаю":
            строка = "слушаю"
        elif эмоция == "встревожен":
            строка = f"стою: {причина}" if причина else "стою"
        elif эмоция == "сплю":
            строка = ""
        else:
            строка = ""
        if едет and эмоция != "встревожен":
            строка = f"{строка}, еду" if строка else "еду"

        return {
            "когда": time.time(),
            "эмоция": эмоция,
            "строка": строка,
            "услышал": услышал,
            "говорит": говорит,
            "батарея": self._батарея(),
            "взгляд": взгляд,
            "человек": человек,
            "едет": едет,
            "музыка": музыка,
            "рот": self._рот(говорит),
            "движение": self._движение(),
            "делает": dict(self._делает),
            "погода": погода,
            "таймеры": self._таймеры(),
            "подсказка": self._подсказка(эмоция, говорит, едет, музыка),
            "ночь": self._ночь(),
        }

    # --- погода -----------------------------------------------------------
    def _обновить_погоду(self) -> None:
        """Раз в десять минут; неудача — повтор через минуту, не через десять."""
        сейчас = self._часы()
        with self._lock:
            если_свежа = (self._погода is not None
                          and сейчас - self._погода_когда < ПОГОДА_РАЗ_В)
            если_рано = сейчас - self._погода_пробовали < ПОГОДА_СНОВА_ЧЕРЕЗ
        if если_свежа or если_рано:
            return
        with self._lock:
            self._погода_пробовали = сейчас
        try:
            где = self.где() if self.где is not None else None
        except Exception:                       # noqa: BLE001
            где = None
        if not где or not any(где):
            return
        try:
            данные = self._погода_из(*где)
        except Exception:                       # noqa: BLE001
            log.debug("погода для лица не получилась", exc_info=True)
            данные = None
        if not данные:
            return
        cur = данные.get("current") or {}
        daily = данные.get("daily") or {}
        t = cur.get("temperature_2m")
        if t is None:
            return
        код = int(cur.get("weather_code") or 0)
        макс = (daily.get("temperature_2m_max") or [None])[0]
        мин = (daily.get("temperature_2m_min") or [None])[0]
        with self._lock:
            self._погода = {
                "t": round(float(t)),
                "код": код,
                "описание": описание_погоды(код),
                "макс": round(float(макс)) if макс is not None else None,
                "мин": round(float(мин)) if мин is not None else None,
            }
            self._погода_когда = сейчас

    # --- запись -----------------------------------------------------------
    def выложить(self, состояние: dict | None = None) -> bool:
        """Записать файл. True — записали. Атомарно: читатель не увидит половину."""
        if состояние is None:
            состояние = self.состояние()
        try:
            self._файл.parent.mkdir(parents=True, exist_ok=True)
            временный = self._файл.with_suffix(".tmp")
            временный.write_text(json.dumps(состояние, ensure_ascii=False),
                                 encoding="utf-8")
            os.replace(временный, self._файл)
            self._записей += 1
            return True
        except OSError as e:
            if not self._не_смог_писать:
                self._не_смог_писать = True
                log.warning("лицо: не могу писать %s (%s) — экран останется "
                            "спящим", self._файл, e)
            return False

    def _отправить_на_пк(self, состояние: dict) -> None:
        """То же состояние — ещё и аватару на ПК, если он настроен и жив.

        Не должно мешать основному делу. Короткий тайм-аут и остывание после
        сбоя — без них недоступный ПК тормозил бы запись файла на экран
        каждые сто миллисекунд, а лицо на роботе от аватара не зависит.
        """
        if not self.аватар_url or self._часы() < self._аватар_вниз_до:
            return
        try:
            тело = json.dumps(состояние, ensure_ascii=False).encode("utf-8")
            запрос = urllib.request.Request(
                self.аватар_url + "/avatar/state", data=тело, method="POST",
                headers={"Content-Type": "application/json; charset=utf-8"})
            urllib.request.urlopen(запрос, timeout=1.0).close()
        except Exception as e:                       # noqa: BLE001
            self._аватар_вниз_до = self._часы() + 5.0
            log.debug("лицо: аватар на ПК не принял состояние (%s)", e)

    @property
    def записей(self) -> int:
        return self._записей

    def _крутиться(self) -> None:
        while not self._стоп.wait(ПИШЕМ_РАЗ_В):
            try:
                self._обновить_погоду()
                self._прочитать_нажатие()
                состояние = self.состояние()
                self.выложить(состояние)
                self._отправить_на_пк(состояние)
            except Exception:                   # noqa: BLE001
                log.exception("лицо: сбой при записи состояния")

    def start(self) -> None:
        if self._файл == Path(ФАЙЛ) and not self._файл.parent.exists():
            # Не systemd — значит, /run/robot-ai никто не создаст. Пишем
            # рядом с остальным, как карта и сетка.
            self._файл = Path(ЗАПАСНОЙ_ФАЙЛ).expanduser()
        threading.Thread(target=self._крутиться, name="лицо", daemon=True).start()
        log.info("лицо: выкладываю состояние в %s", self._файл)

    def stop(self) -> None:
        self._стоп.set()
        # Последнее слово — «сплю»: служба остановилась, и экран обязан это
        # показать, а не держать последнее живое лицо.
        with self._lock:
            self._эмоция = "сплю"
            self._говорит = ""
        self.выложить()
