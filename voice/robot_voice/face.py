class Лицо:
    """Собирает состояние робота в одно и выкладывает его файлом.

    Всё, что меняет лицо, зовётся из голосового цикла: `слушаю`, `думаю`,
    `говорю`, `сказал`, `услышал`, `не_понял`, `рад`, `огорчён`,
    `встревожен`. Остальное — батарея, колёса, взгляд, музыка — лицо
    спрашивает само у тех, кто это знает.

    `состояние()` — чистая функция от того, что накоплено: её можно проверить
    без файла, без потоков и без робота. Поток только пишет.
    """

    def __init__(self, *, ros=None, глаза=None, player=None, где=None,
                 тихо=None, таймеры=None, часы=time.monotonic,
                 файл: str | None = None, погода=weather_api.fetch,
                 слушаю_секунд: float = 20.0, аватар_url: str = "",
                 видео_устройство: str = "") -> None:
        self.ros = ros
        self.таймеры = таймеры            # tools.Timers или None
        self._погода_показать_до = float("-inf")
        # (номер, когда) последнего ПРОЧИТАННОГО нажатия. Пара, а не один
        # номер, и сравнение на равенство, а не «больше»: экран нумерует
        # нажатия от своего запуска, и после перезапуска robot-face счёт
        # начинается с единицы заново. Пока здесь стояло «номер <= было —
        # пропустить», после каждого перезапуска экрана кнопки молча не
        # работали, пока его счётчик не догонит наш.
        self._нажатие_было: tuple[int, float] | None = None
        self._нажатие_поток: threading.Thread | None = None
        # Настенные часы запуска — отсеять touch.json из прошлой жизни.
        self._запущено = time.time()
        # Рот по звуку: то, что робот кладёт в динамик, приходит сюда через
        # speaker.on_pcm (app.py). Пока говорит — рот идёт по огибающей.
        self.губы = lips.Губы(часы)
        # Движение в кадре камеры (motion.Движение) — или None.
        self.движение = None
        # Последний позванный инструмент: {номер, что}.
        self._делает: dict = {"номер": 0, "что": ""}
        # Личное дело узнало, что сегодня чей-то день рождения — персонаж
        # празднует на экране. Тот же приём, что и «делает»: номер, а не
        # текст, — сценки ловят СМЕНУ, и повторный кадр с тем же текстом не
        # запускает сценку заново.
        self._праздник: dict = {"номер": 0, "текст": ""}
        # Необязательная копия того же состояния — на ПК, если там поднят
        # аватар (pc/avatar). Экран робота в этом не нуждается: как рисовал
        # сам, так и рисует, ПК тут ДОБАВКА, а не замена.
        self.аватар_url = (аватар_url or "").rstrip("/")
        self._аватар_вниз_до = 0.0
        # Отправка на ПК — своим потоком, с последним состоянием: сеть не
        # смеет задерживать запись файла на экран (см. _на_пк_в_фоне).
        self._на_пк: dict | None = None
        self._на_пк_есть = threading.Event()
        self._на_пк_поток: threading.Thread | None = None
        self._погода_поток: threading.Thread | None = None
        self._поток: threading.Thread | None = None
        # «Слушаю» держится ровно столько, сколько открыто окно разговора, и
        # число это — то же, что у голосового цикла (cfg.session_seconds), а
        # не своё. Свои двадцать секунд разошлись бы с окном при первой же
        # правке настройки, и лицо слушало бы, когда робот уже нет.
        self.слушаю_секунд = float(слушаю_секунд)
        self.глаза = глаза
        self.player = player
        self.где = где                    # () -> (lat, lon) | None
        self.тихо = тихо                  # () -> bool, тихие ли часы
        self._часы = часы
        self._погода_из = погода
        self._файл = Path(файл or ФАЙЛ)
        self._lock = threading.RLock()
        self._стоп = threading.Event()

        self._эмоция = "спокоен"
        self._эмоция_с = 0.0
        self._услышал = ""
        self._говорит = ""
        self._строка = ""
        self._причина = ""               # чем встревожен
        self._погода: dict | None = None
        self._погода_когда = 0.0
        self._погода_пробовали = 0.0
        self._записей = 0
        self._не_смог_писать = False
        # Видео (YouTube) — тот же ALSA-выход, что и музыка: колонка у робота
        # одна, и звук мультика должен идти из неё же, а не в пустоту.
        self._видео_устройство = (видео_устройство or "").strip()
        self._видео: dict = {"играет": False, "пауза": False, "url": "",
                             "название": "", "громкость": 70}
        # Список последнего поиска и то, докуда по нему дошли — «следующий
        # мультик» двигается по этому списку, а не ищет заново: повторный
        # поиск того же слова честно вернул бы тот же самый первый ролик.
        self._видео_список: list[tuple[str, str]] = []
        self._видео_индекс = 0

    # --- то, что зовёт голосовой цикл -------------------------------------
    def _стать(self, эмоция: str) -> None:
        if эмоция not in ЭМОЦИИ:
            raise ValueError(f"нет такой эмоции: {эмоция!r}")
        with self._lock:
            self._эмоция = эмоция
            self._эмоция_с = self._часы()

    def слушаю(self) -> None:
        """Окно разговора открыто: робота позвали, он ждёт продолжения.

        «Слушаю» — служебное состояние конвейера, и ставится оно в конце
        КАЖДОЙ обработанной команды. Из-за этого радость, поставленную парой
        секунд раньше, стирало прежде, чем её успевали увидеть: человек
        говорил «молодец», робот отвечал — и лицо тут же становилось
        дежурным. Короткое живое чувство важнее служебной метки: пока оно не
        отгорело само (ГАСНУТ_ЧЕРЕЗ), окно разговора его не трогает.
        """
        with self._lock:
            self._говорит = ""
            if self._эмоция_сейчас() in ЖИВЫЕ_ВАЖНЕЕ_СЛУЖЕБНОГО:
                return
            self._стать("слушаю")

    def думаю(self) -> None:
        """Ждём модель. Держится, пока не начнётся ответ."""
        with self._lock:
            self._говорит = ""
            self._стать("думаю")

    def говорю(self, фраза: str) -> None:
        """Звучит реплика. Лицо спокойное — эмоцию несёт текст, не глаза."""
        with self._lock:
            self._говорит = (фраза or "").strip()
            # Тревога и огорчение переживают реплику: робот, который говорит
            # «впереди стена» со спокойным лицом, врёт лицом.
            if self._эмоция not in ("встревожен", "огорчён"):
                self._стать("спокоен")

    def сказал(self) -> None:
        """Реплика отзвучала — или её оборвали. Огибающую не доигрываем."""
        with self._lock:
            self._говорит = ""
        self.губы.сбросить()

    def делает(self, что: str) -> None:
        """Мозг позвал инструмент — персонаж на экране «делает» это сам.

        Номер растёт на каждый вызов: сценки на ПК и у домовёнка ловят его
        смену, а не имя — два «drive» подряд должны дать два жеста.
        """
        with self._lock:
            self._делает = {"номер": self._делает.get("номер", 0) + 1,
                            "что": str(что or "")}

    def праздник(self, текст: str) -> None:
        """Личное дело узнало день рождения — персонаж празднует на экране.

        Зовётся из app.py на КАЖДОЙ узнанной фразе того, у кого сегодня
        праздник; people.отпраздновать() сама решает, поздравлять ли (раз в
        день), — сюда доходит уже готовое непустое поздравление.
        """
        if not текст:
            return
        with self._lock:
            self._праздник = {"номер": self._праздник.get("номер", 0) + 1,
                              "текст": str(текст)}

    def озвучил(self, pcm: bytes, rate: int) -> None:
        """Звук ушёл в динамик — рот пойдёт по нему (speaker.on_pcm)."""
        try:
            self.губы.добавить(pcm, int(rate))
        except Exception:                       # noqa: BLE001
            log.debug("лицо: не разобрал звук под рот", exc_info=True)

    def _рот(self, говорит: str) -> float | None:
        """0..1 по звуку, пока говорит; None — звука не видели, пусть синус."""
        if not говорит:
            return None
        return self.губы.рот()

    def _движение(self) -> dict:
        д = self.движение
        if д is None:
            return {"есть": False, "сила": 0.0, "где": 0.0}
        try:
            return д.состояние()
        except Exception:                       # noqa: BLE001
            return {"есть": False, "сила": 0.0, "где": 0.0}

    def услышал(self, текст: str) -> None:
        with self._lock:
            self._услышал = (текст or "").strip()
            # Похвалили или посмеялись — радуется. Не «правильно ответил», а
            # именно услышал доброе: радость от похвалы человек считывает
            # мгновенно, и это единственный повод, по которому «рад» вообще
            # достижимо. Тревога и огорчение при этом не перебиваются: они
            # про безопасность, и врать поверх них лицом нельзя.
            низ = self._услышал.lower()
            if (self._эмоция_сейчас() not in ("встревожен", "огорчён", "сплю")
                    and any(с in низ for с in ТЁПЛЫЕ_СЛОВА)):
                self._стать("рад")
            # Спросили о погоде — карточка появляется на время. Именно по
            # услышанному, а не по вызову инструмента: погоду отвечают и
            # правилом, и моделью, и навыком, а услышанное общее для всех.
            if "погод" in self._услышал.lower():
                self._погода_показать_до = self._часы() + ПОГОДА_ПОКАЗЫВАТЬ

    def нажали(self, действие: str) -> str:
        """Кнопка на экране — то же, что голосом. Возвращает ответ проигрывателя."""
        p = self.player
        if p is None or действие not in НАЖАТИЯ:
            return ""
        try:
            if действие == "дальше":
                return str(p.дальше(вслух=False) or "")
            if действие == "стоп":
                return str(p.выключить() or "")
            if действие == "тише":
                return str(p.тише() or "")
            return str(p.громче() or "")
        except Exception as e:                       # noqa: BLE001
            log.warning("лицо: нажатие «%s» не вышло (%s)", действие, e)
            return ""

    def _прочитать_нажатие(self) -> None:
        """touch.json от экрана: новая запись — новое нажатие, исполнить раз.

        Новизна — по паре (номер, когда), а не по росту номера: после
        перезапуска экрана номера идут с единицы заново, и «меньше прежнего»
        — это не повтор, а новая жизнь экрана. Повтор — это та же запись,
        прочитанная на следующем такте.

        Исполняется в своём потоке: «стоп» и «дальше» ходят к проигрывателю,
        а тот — по HTTP к пульту; секунда такого ожидания в потоке писателя
        — секунда застывшего лица.
        """
        файл = self._файл.with_name("touch.json")
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
            номер = int(данные.get("номер") or 0)
            действие = str(данные.get("действие") or "")
            когда = данные.get("когда")
            когда = float(когда) if когда is not None else файл.stat().st_mtime
        except (OSError, ValueError, TypeError, AttributeError):
            return
        отметка = (номер, когда)
        if отметка == self._нажатие_было:
            return
        self._нажатие_было = отметка
        if когда < self._запущено - НАЖАТИЕ_ИЗ_ПРОШЛОГО:
            # Файл пережил перезапуск голосовой службы: это нажатие уже
            # исполнялось прошлой жизнью, а если и нет — человек давно ушёл.
            log.info("лицо: нажатие «%s» в touch.json старше меня — не исполняю",
                     действие)
            return
        self._нажатие_поток = threading.Thread(
            target=self._исполнить_нажатие, args=(действие,),
            name="лицо-нажатие", daemon=True)
        self._нажатие_поток.start()

    def _исполнить_нажатие(self, действие: str) -> None:
        ответ = self.нажали(действие)
        log.info("лицо: нажали «%s»%s", действие, f" — {ответ}" if ответ else "")

    def не_понял(self) -> None:
        self._стать("не_понял")

    def рад(self) -> None:
        self._стать("рад")

    def огорчён(self) -> None:
        self._стать("огорчён")

    def встревожен(self, почему: str = "") -> None:
        """Не пускаю вперёд. Держится, пока не позовут `спокоен`."""
        with self._lock:
            self._причина = (почему or "").strip()
            self._стать("встревожен")

    def спокоен(self) -> None:
        with self._lock:
            self._причина = ""
            self._стать("спокоен")

    def путь_свободен(self) -> None:
        """Сторож пути пропустил — тревога снимается. Остальное не трогаем.

        Зовётся из сторожа в main пятнадцать раз в секунду, пока робот едет,
        и потому НЕ то же, что `спокоен`: тот сменил бы «думаю» или «слушаю»
        на покой посреди поездки. Здесь гаснет только тревога — то, что
        поставил тот же сторож.
        """
        with self._lock:
            if self._эмоция == "встревожен":
                self._причина = ""
                self._стать("спокоен")

    # --- сборка -----------------------------------------------------------
    def _эмоция_сейчас(self) -> str:
        """Короткие настроения гаснут сами — иначе это застывшее лицо."""
        эмоция = self._эмоция
        держим = ГАСНУТ_ЧЕРЕЗ.get(эмоция)
        if эмоция == "слушаю":
            держим = self.слушаю_секунд
        if держим is not None and self._часы() - self._эмоция_с > держим:
            return "спокоен"
        return эмоция

    def _едет(self) -> bool:
        try:
            return bool(self.ros is not None and self.ros.moving)
        except Exception:                       # noqa: BLE001
            return False

    def _батарея(self) -> float | None:
        try:
            в = self.ros.voltage if self.ros is not None else None
        except Exception:                       # noqa: BLE001
            return None
        return round(float(в), 2) if в is not None else None

    def _взгляд(self) -> tuple[bool, float | None]:
        """(видит ли человека, куда смотреть). Взгляд только по свежему."""
        г = self.глаза
        if г is None:
            return False, None
        try:
            if not г.свежий:
                return False, None
            return True, round(float(г.угол), 3)
        except Exception:                       # noqa: BLE001
            return False, None

