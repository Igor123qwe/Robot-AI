    def видео_начать(self, что: str) -> str:
        """Ищет и запускает мультик/видео. Пустой запрос — просто «мультики»."""
        что = " ".join((что or "").split()) or "мультики"
        найдено = video_api.search(что)
        if not найдено:
            если_нет_ytdlp = ("" if video_api.possible() else
                              " Поиск видео не настроен (нет yt-dlp).")
            return f"Не нашёл: {что}.{если_нет_ytdlp}"
        with self._lock:
            self._видео_список = найдено
            self._видео_индекс = 0
            url, название = найдено[0]
            громкость = self._видео.get("громкость", 70)
            self._видео = {"играет": True, "пауза": False, "url": url,
                           "название": название, "громкость": громкость}
        log.info("видео: включаю «%s» (%s)", название or что, url)
        return f"Включаю{f' — {название}' if название else ''}."

