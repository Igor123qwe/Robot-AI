"""Лицо робота: что показывать на экране, решает голосовая служба.

ЧТО ЭТО. Экран рисует отдельная служба `robot-face` (каталог `face/`), и она
НИЧЕГО не знает про робота. Она умеет одно: прочитать файл и нарисовать то,
что в нём написано. Всё знание о том, что робот делает, живёт здесь — в
процессе, который этим и занят, — и раз в десятую секунды выкладывается в
`/run/robot-ai/face.json`.

Так сделано по двум причинам, и обе записаны в docs/screen.md:

  • лицо не должно замирать, пока модель думает. Голосовой цикл висит в
    разговоре с моделью секундами, и если бы он же и рисовал, глаза бы
    застывали ровно тогда, когда человек ждёт ответа;
  • экран не имеет права врать. Он показывает только то, что робот знает о
    себе сам, теми же словами, что уходят в журнал. Никакой «задумчивости»,
    которой нет в коде.

ПОЧЕМУ ФАЙЛ, А НЕ СОКЕТ. По той же причине, что сетка дальномера и карта:
второй процесс, ещё один сетевой канал — ещё один способ всё сломать. Файл в
/run живёт в памяти, systemd убирает его при остановке службы, и застывшее
вчерашнее лицо не переживёт падения. Метка времени в файле — НАСТЕННЫЕ часы:
читает другой процесс, и сравнивать ему надо со своими часами, а не с чужим
счётчиком от загрузки.

ЧТО В ФАЙЛЕ. Ровно то, что нужно нарисовать, и ничего сверх:

    эмоция     — одна из ЭМОЦИИ; форма глаз
    строка     — что робот делает, словами: «слушаю», «думаю», «говорю», «еду»
    услышал    — последняя распознанная фраза: половина вечера уходит на
                 «он меня не понял», а тут видно сразу, что именно он услышал
    говорит    — что произносит прямо сейчас
    батарея    — вольты или null, если шасси молчит
    взгляд     — куда смотреть, радианы влево+, или null: глаза следуют за
                 человеком по пеленгу с камеры
    человек    — видит ли камера человека сейчас (от этого зависит яркость)
    едет       — крутятся ли колёса
    музыка     — {играет, название, режим («поток» — радио, «треки»),
                 прошло, длина} — секунды; длина 0 у радио
    погода     — {t, код, макс, мин, описание} или null. ТОЛЬКО когда о ней
                 спросили — сорок секунд после «какая погода», как карточка
                 у колонок с экраном: виджет появляется по делу, а не висит
    таймеры    — [{имя, осталось}] по ближайшему; пусто — ничего не идёт
    подсказка  — «Скажи: „Кузя, включи радио“» — только в покое: ни музыки,
                 ни речи, ни движения. Фразы — те, что робот правда понимает
    рот        — 0..1 по громкости звука, пока говорит (face/lips.py), или
                 null, если звук прошёл мимо (piper напрямую в динамик)
    движение   — {есть, сила, где} — что-то шевельнулось в кадре камеры
                 (motion.py), где: −1 слева … +1 справа
    делает     — {номер, что} — какой инструмент мозг позвал последним;
                 персонаж на экране изображает действие (сценки)
    видео      — {играет, url, название, пауза, громкость, устройство} —
                 мультик/видео с YouTube (voice/robot_voice/video.py). Пока
                 «играет» истинно, экран целиком уходит mpv (face/videoplayer.py)
                 — сама отрисовка лица на это время не идёт, см. face/face.py
    ночь       — тихие часы: лицо тускнеет и теплеет

И ОБРАТНО: `/run/robot-ai/touch.json` пишет экран, когда на нём нажали
кнопку (тач), — {номер, действие}; голосовая служба читает его тем же
тактом и делает то же, что сделала бы по голосу: «дальше», «стоп»,
«тише», «громче». Номер растёт на каждое нажатие — одно нажатие
исполняется один раз.

ЭМОЦИИ — НЕ УКРАШЕНИЕ, А СОСТОЯНИЕ КОДА. Каждая наступает от конкретного
события в цикле и держится ровно столько, сколько это событие длится:
«слушаю» — пока открыто окно разговора, «думаю» — пока ждём модель, «говорю»
— пока звучит реплика. Короткие («рад», «не понял», «огорчён») сами гаснут
через несколько секунд: настроение, которое держится, пока его не сменят, —
это застывшее лицо, только медленное.
"""

