def _загрузить_губы():
    """face/lips.py — по пути, а не через sys.path.

    Рот по звуку — общий модуль с ПК (face/lips.py): одна огибающая на
    двоих, чтобы своё лицо и аватар на ПК открывали рот по одним и тем же
    правилам. Раньше ради него в sys.path вставлялся ВЕСЬ каталог face/, и
    первым: с этого момента любой `import face`, `import scenes` или
    `import diag` в голосовом процессе получал бы файл экрана вместо того,
    что искал, — а в face/ лежит face.py с pygame и DRM. Загрузка по
    точному пути даёт тот же модуль и не трогает чужие импорты.
    """
    путь = Path(__file__).resolve().parents[2] / "face" / "lips.py"
    спец = importlib.util.spec_from_file_location("robot_face_lips", путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


