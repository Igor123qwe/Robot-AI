"""Человек упал — заметить по скелету, который и так приходит с детектора.

Зачем это здесь. Робот ездит там же, где живут люди, и большую часть суток он
единственный, кто вообще смотрит в комнату. Упавший человек — это не «событие
интерфейса», это единственный случай, когда домашний робот может оказаться
по-настоящему нужен. Всё остальное, что он умеет, можно сделать самому.

Откуда берём. Алгоритм взят у D-Robotics из пакета `hobot_falldown_detection`
(Apache-2.0) и переписан здесь на питон. Сам пакет мы НЕ ставим, и это
осознанно: он подписывается ровно на тот топик, на который уже подписаны мы
(`/hobot_mono2d_body_detection`), и считает по нему сорок строк тригонометрии.
Ставить ради этого сборку colcon, ещё одну службу systemd и второй круг
ai_msgs по сети — значит завести отдельно живущий узел, который однажды
молча не поднимется, ради арифметики, которую видно глазом.

Как это работает. Детектор тела на BPU отдаёт для каждого человека скелет из
девятнадцати точек и рамку. Из них считаются три числа:

  • КОРПУС — наклон отрезка «плечи → бёдра» к горизонту. 90° стоит, 0° лежит;
  • ОСЬ — наклон главной оси всего скелета, метод главных компонент по всем
    найденным точкам. То же самое, но не зависящее от конкретных номеров точек;
  • СИЛУЭТ — во сколько раз рамка человека шире, чем выше. Лежащий шире.

Решение принимается по МЕДИАНАМ этих трёх за несколько секунд, а не по
каждому кадру. Это главное, и это вывод из замера на роботе, а не из статьи.

ПОЧЕМУ НЕ ПО КАДРУ. Первая версия считала по кадру и голосовала булевыми
ответами. Робот на первом же вечере трижды объявил упавшим человека, который
спокойно стоял. Замер (475 кадров, scripts/falldown_probe.py) показал,
насколько шумны признаки: у СТОЯЩЕГО человека силуэт гулял от 0.38 до 1.52,
ось от 14° до 90°. Булев ответ по такому кадру — подбрасывание монеты, а
голосование по монеткам даёт монетку. Медианы за то же окно при этом стояли
как вкопанные: корпус 82°, ось 82°, силуэт 0.65. Копим числа, решаем по
медианам — шум расходится, поза остаётся.

ЧЕГО ЗДЕСЬ НЕТ, хотя было у D-Robotics. Угол «бёдра → щиколотки» и разбег
между ним и корпусом. У них это главная защита от «нагнулся»: у нагнувшегося
корпус горизонтален при вертикальных ногах. На нашей камере — она в двадцати
пяти сантиметрах от пола и смотрит снизу вверх — этот угол оказался шумом: у
стоящего человека он прыгал от 1° до 88° от кадра к кадру. Значит шум и
разбег. Признак, про который известно, что он случаен, одинаково легко
поднимет ложную тревогу и проглотит настоящую, поэтому он выброшен из решения
и остался только в журнале. «Нагнулся» отсекают силуэт и время: у него силуэт
около единицы, а не полтора, и держится он секунду, а не четыре.

ПРОПУЩЕННЫЕ ТОЧКИ. Детектор ставит (0, 0) там, где точку не нашёл, — это уже
известно по `vision_track.ноги`. Оригинал нули не отбрасывает: стоящий
человек, у которого не видно бёдер (стол, спинка стула — для низкой камеры
это каждый вечер), считается у него упавшим. Проверено арифметикой: корпус
25.1°, ноги 54.0°, разбег 28.9°, все три порога оригинала пройдены. Здесь
точка в нуле означает «не знаю».

ЧЕГО ЭТА ШТУКА НЕ УМЕЕТ, и врать про это нельзя. Камера одна, и глубины у
неё нет. Человек, лежащий ногами К камере, в кадре сильно укорочен: его
корпус выглядит почти вертикальным, и падение мы пропустим. Человек за
диваном, у которого видно только голову, тоже не считается. Это не сторож
и не медицинское устройство — это «робот заметил и спросил».
"""

from __future__ import annotations

import logging
import math
import time

log = logging.getLogger(__name__)

# Как называется набор точек скелета в сообщении детектора.
СКЕЛЕТ = "body_kps"

# Сколько точек в скелете. Проверяем ровно как оригинал: другой размер значит
# другую модель, а под другую модель не совпадут и номера точек ниже.
ТОЧЕК = 19

# Номера точек. Разметка COCO: 5-6 плечи, 11-12 бёдра, 15-16 щиколотки.
ПЛЕЧИ = (5, 6)
БЁДРА = (11, 12)
ЩИКОЛОТКИ = (15, 16)

# Пороги наклона в градусах от горизонта: 0° — лежит, 90° — стоит.
#
# Числа взяты у D-Robotics, набор «ExLow» — САМЫЙ СТРОГИЙ из четырёх, а не
# самый чувствительный. Сначала я взял «High», рассудив, что лишние
# срабатывания отсеет время. Робот на первом же вечере трижды объявил
# упавшим человека, который спокойно стоял. Рассуждение было неверным:
# ошибка тут не случайная, а систематическая — при одной и той же позе
# признак врёт во всех кадрах подряд, и никакое накопление по времени
# систематическую ошибку не лечит.
КОРПУС_НИЗКО = 30.0
КОРПУС_ВЫСОКО = 60.0
НОГИ_НИЗКО = 40.0
НОГИ_ВЫСОКО = 70.0

# Насколько корпус и ноги могут разойтись по наклону. Больше — человек согнут,
# то есть нагнулся или сидит, а не лежит. Это главная защита от ложной
# тревоги на уборке.
РАЗБЕГ = 20.0

# Каким должен быть силуэт, чтобы считать его лежащим. Лежащий человек в кадре
# ШИРЕ, ЧЕМ ВЫШЕ, и это признак, не зависящий ни от разметки скелета, ни от
# того, какие точки детектор нашёл. Стоящий — наоборот, вдвое-вчетверо выше
# ширины, и никакая перспектива низкой камеры этого не переворачивает.
#
# Ради этого признака всё и переписано. Три пары точек скелета — признак
# ОДИН, и проверить его нечем: соврал — соврала вся тревога. Силуэт врёт
# по другим причинам и в других позах, поэтому согласие двух признаков
# отсеивает то, что каждый из них поодиночке пропускает.
ЛЕЖИТ_ШИРЕ = 1.15

# Сколько точек скелета должно быть найдено, чтобы вообще судить. Меньше
# половины — это не поза, это догадка по обрывкам.
ТОЧЕК_ХВАТИТ = 8

# Насколько вытянутым должен быть скелет, чтобы у него была осмысленная ось.
# Комок точек оси не имеет, и угол у него получается случайным.
ВЫТЯНУТ_ОТ = 1.8

# Сколько человек должен пролежать, чтобы мы поверили. Четыре секунды:
# нагнуться и распрямиться быстрее, а упавший встаёт заметно дольше — либо не
# встаёт вовсе. Было две с половиной; после ложных тревог поднято, потому что
# цена ожидания тут — полторы секунды, а цена ошибки — доверие к роботу.
ДЕРЖИТСЯ = 4.0

# Пороги ПО МЕДИАНАМ за окно. Сняты с живого робота: у стоящего человека,
# 475 кадров, медиана корпуса около 82°, медиана оси около 82°, медиана
# силуэта около 0.65. Отдельные кадры при этом улетали куда угодно — силуэт
# доходил до 1.52, ось падала до 14°, — но медиана не шелохнулась. Ради этого
# всё и считается по медианам.
#
# Числа для ЛЕЖАЩЕГО человека на этой камере ещё не сняты, поэтому пороги
# поставлены с запасом от измеренного стоящего, а не подогнаны под лежащего.
МЕДИАНА_КОРПУС = 40.0
МЕДИАНА_ОСЬ = 45.0
МЕДИАНА_СИЛУЭТ = 1.3

# Сколько кадров нужно как минимум. Доля от трёх кадров — это не большинство,
# это совпадение.
КАДРОВ_ХВАТИТ = 8

# Сколько молчим после тревоги про этого же человека. Минута: робот всё равно
# ничем не поможет чаще, а повторять каждые три секунды — значит быть выключенным
# в первый же вечер.
МОЛЧИМ = 60.0

# Через сколько забываем человека, которого не видим. Номера целей детектор
# выдаёт по кругу и однажды повторяет; держаться за старый номер значит
# приписать новому человеку чужую историю.
ЗАБЫВАЕМ = 10.0


def _точка(точки, номер) -> tuple[float, float] | None:
    """Координаты точки скелета. None — точки нет или она в нуле.

    Ноль-ноль детектор ставит там, где точку не нашёл. Считать её координатой
    — значит померить угол до левого верхнего угла кадра и получить
    правдоподобное число ни о чём.
    """
    if номер >= len(точки):
        return None
    т = точки[номер]
    if isinstance(т, dict):
        x, y = т.get("x"), т.get("y")
    else:
        return None
    try:
        x, y = float(x), float(y)
    except (TypeError, ValueError):
        return None
    if x <= 0.0 and y <= 0.0:
        return None
    return x, y


def середина(точки, пара) -> tuple[float, float] | None:
    """Середина между двумя точками скелета. None — хоть одной не видно.

    Требуем ОБЕ. По одному плечу середину не восстановить, а подставить вместо
    середины единственную видимую точку — значит сдвинуть отрезок на полкорпуса
    и получить наклон, которого не было.
    """
    a = _точка(точки, пара[0])
    b = _точка(точки, пара[1])
    if a is None or b is None:
        return None
    return (a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0


def наклон(верх, низ) -> float:
    """Наклон отрезка к горизонту в градусах: 0 — лежит, 90 — стоит.

    Знак нам не нужен вовсе: лежащий головой влево и головой вправо — одинаково
    лежащий. Поэтому берём модуль и получаем угол в диапазоне 0..90.
    """
    dy = верх[1] - низ[1]
    dx = верх[0] - низ[0]
    if abs(dx) < 1e-6:
        # Отрезок строго вертикален. Оригинал в этом месте возвращает «не
        # упал», что по сути верно, но проходит мимо через деление на ноль;
        # честнее сказать прямо: девяносто градусов.
        return 90.0
    return math.degrees(math.atan(abs(dy / dx)))


def силуэт(рамка) -> float | None:
    """Во сколько раз рамка человека шире, чем выше. None — рамки нет.

    Признак грубый и именно поэтому ценный: он не зависит ни от разметки
    скелета, ни от того, какие точки детектор сумел найти. Лежащий человек
    шире, чем выше; стоящий — вдвое-вчетверо выше ширины.
    """
    if not isinstance(рамка, dict):
        return None

    def число(*ключи):
        for ключ in ключи:
            if ключ in рамка:
                try:
                    return float(рамка[ключ])
                except (TypeError, ValueError):
                    return None
        return None

    ширина = число("width", "w")
    высота = число("height", "h")
    if ширина is None or высота is None:
        лево, право = число("x1", "left"), число("x2", "right")
        верх, низ = число("y1", "top"), число("y2", "bottom")
        if None in (лево, право, верх, низ):
            return None
        ширина, высота = abs(право - лево), abs(низ - верх)
    if not высота or высота <= 0 or ширина <= 0:
        return None
    return ширина / высота


def ось(точки) -> tuple[float, float] | None:
    """Наклон главной оси скелета к горизонту и его вытянутость.

    Считаем по ВСЕМ найденным точкам сразу, а не по трём парам. Смысл тот же,
    что у силуэта: не зависеть от того, какие именно точки нашлись и как они
    занумерованы в этой версии модели. Человек — фигура вытянутая, и
    направление, вдоль которого он вытянут, и есть направление его тела.

    Это обычный метод главных компонент на двух измерениях: он сводится к
    собственным векторам матрицы ковариации два на два, то есть к формуле, а
    не к численному поиску.
    """
    точки_есть = [т for т in (_точка(точки, i) for i in range(len(точки)))
                  if т is not None]
    if len(точки_есть) < ТОЧЕК_ХВАТИТ:
        return None
    n = float(len(точки_есть))
    сx = sum(т[0] for т in точки_есть) / n
    сy = sum(т[1] for т in точки_есть) / n
    xx = sum((т[0] - сx) ** 2 for т in точки_есть) / n
    yy = sum((т[1] - сy) ** 2 for т in точки_есть) / n
    xy = sum((т[0] - сx) * (т[1] - сy) for т in точки_есть) / n

    след = xx + yy
    опред = xx * yy - xy * xy
    под_корнем = след * след / 4.0 - опред
    if под_корнем < 0.0:
        под_корнем = 0.0
    большое = след / 2.0 + math.sqrt(под_корнем)
    малое = след / 2.0 - math.sqrt(под_корнем)
    if большое <= 1e-9:
        return None
    вытянутость = math.sqrt(большое / малое) if малое > 1e-9 else float("inf")

    # Собственный вектор для большего собственного числа. Если xy нулевой,
    # оси совпадают с осями кадра, и вектор берём по тому, что больше.
    if abs(xy) > 1e-9:
        вектор = (большое - yy, xy)
    else:
        вектор = (1.0, 0.0) if xx >= yy else (0.0, 1.0)
    угол = math.degrees(math.atan2(abs(вектор[1]), abs(вектор[0])))
    return угол, вытянутость


def лежит(точки, рамка=None) -> bool | None:
    """Похоже ли на лежащего человека. None — по этому кадру не судим.

    ДВА НЕЗАВИСИМЫХ ПРИЗНАКА, И ОБА ДОЛЖНЫ СОГЛАСИТЬСЯ. Сначала здесь был
    один — три пары точек скелета, как у D-Robotics. Робот на первом же
    вечере трижды объявил упавшим стоящего человека, и стало видно, в чём
    беда: у одного признака нет способа ошибиться незаметно. Он либо прав,
    либо вся тревога врёт, а проверить его нечем.

    Второй признак — силуэт и главная ось скелета — врёт в других позах и по
    другим причинам, поэтому согласие двух отсеивает то, что каждый из них
    поодиночке пропускает. Заодно второй признак не зависит от разметки
    точек: если в этой версии модели номера окажутся другими, первый признак
    сойдёт с ума, а второй продолжит работать — и тревоги не будет.

    Три исхода вместо двух не прихоть. «Не вижу ног» и «вижу, что стоит» —
    разные вещи: первое не должно ни поднимать тревогу, ни гасить уже
    набранные подтверждения, иначе мигающий детектор обнулял бы счёт вечно.
    """
    подробно = разобрать(точки, рамка)
    if подробно is None:
        return None
    return подробно["лежит"]


def разобрать(точки, рамка=None):
    """Всё, что мы поняли про позу. None — судить не по чему.

    Отдельно от `лежит`, потому что числа нужны не только для решения: без
    них нельзя ни настроить пороги на живом роботе, ни объяснить, почему
    тревога сработала. Ровно этого не хватило, когда робот трижды ошибся —
    в журнале было «лежит дольше 2.5 с» и ни одного числа.
    """
    if not isinstance(точки, list) or len(точки) != ТОЧЕК:
        return None

    плечи = середина(точки, ПЛЕЧИ)
    бёдра = середина(точки, БЁДРА)
    щиколотки = середина(точки, ЩИКОЛОТКИ)
    по_осям = ось(точки)
    ширее = силуэт(рамка)

    если = {"корпус": None, "ноги": None, "ось": None, "вытянутость": None,
            "силуэт": ширее, "по_точкам": None, "по_форме": None,
            "лежит": None}

    if плечи is not None and бёдра is not None and щиколотки is not None:
        корпус = наклон(плечи, бёдра)
        ноги = наклон(щиколотки, бёдра)
        если["корпус"], если["ноги"] = корпус, ноги
        if abs(корпус - ноги) > РАЗБЕГ:
            # Согнут — значит не лежит. Нагнувшийся за упавшей вилкой имеет
            # горизонтальный корпус при вертикальных ногах.
            если["по_точкам"] = False
        else:
            если["по_точкам"] = (
                (корпус <= КОРПУС_НИЗКО and ноги <= НОГИ_ВЫСОКО)
                or (ноги <= НОГИ_НИЗКО and корпус <= КОРПУС_ВЫСОКО))

    if по_осям is not None:
        угол, вытянутость = по_осям
        если["ось"], если["вытянутость"] = угол, вытянутость
        # Комок точек оси не имеет: угол у него случайный, и доверять ему
        # нельзя ни в какую сторону.
        осмысленная_ось = вытянутость >= ВЫТЯНУТ_ОТ
        лёжа_по_оси = осмысленная_ось and угол <= КОРПУС_ВЫСОКО
        лёжа_по_рамке = ширее is not None and ширее >= ЛЕЖИТ_ШИРЕ
        if ширее is None:
            если["по_форме"] = лёжа_по_оси if осмысленная_ось else None
        else:
            если["по_форме"] = лёжа_по_оси and лёжа_по_рамке

    # Оба признака обязаны сказать «лежит». Если хоть один молчит — молчим и
    # мы: тревога по одному признаку это ровно то, что уже трижды ошиблось.
    if если["по_точкам"] is None or если["по_форме"] is None:
        если["лежит"] = None
    else:
        если["лежит"] = bool(если["по_точкам"] and если["по_форме"])
    return если


def рамка_тела(цель):
    """Рамка тела из цели детектора. None — рамки тела в ней нет.

    Нужна именно рамка ТЕЛА: детектор отдаёт ещё голову, лицо и кисти, а
    силуэт головы к позе отношения не имеет — она круглая в любой позе.
    """
    рамки = (цель or {}).get("rois") or []
    if not isinstance(рамки, list):
        return None
    запасная = None
    for roi in рамки:
        if not isinstance(roi, dict):
            continue
        прямоугольник = roi.get("rect") or roi.get("bbox") or roi
        имя = str(roi.get("type") or "").lower()
        if "body" in имя or "person" in имя:
            return прямоугольник
        if запасная is None and not имя:
            запасная = прямоугольник
    return запасная


def объяснить(подробно) -> str:
    """Числа признаков одной строкой — для журнала."""
    if not подробно:
        return "нечего показать"
    def н(ключ, вид="%.0f"):
        значение = подробно.get(ключ)
        return "—" if значение is None else вид % значение
    return (f"корпус {н('корпус')}°, ноги {н('ноги')}°, "
            f"ось {н('ось')}°, вытянутость {н('вытянутость', '%.1f')}, "
            f"силуэт {н('силуэт', '%.2f')}, "
            f"по точкам {подробно.get('по_точкам')}, "
            f"по форме {подробно.get('по_форме')}")


def скелет(цель):
    """Точки скелета из цели детектора. None — скелета в ней нет."""
    наборы = (цель or {}).get("points") or []
    if not isinstance(наборы, list):
        return None
    for набор in наборы:
        if not isinstance(набор, dict):
            continue
        if str(набор.get("type") or "") != СКЕЛЕТ:
            continue
        точки = набор.get("point")
        return точки if isinstance(точки, list) else None
    return None


def медиана(числа):
    """Серединное значение. None — считать не из чего.

    Именно медиана, а не среднее. Среднее одно значение в 88° утаскивает
    заметно, медиана не замечает вовсе, а у нас ровно такие выбросы: замер на
    живом роботе показал, что угол «бедро — щиколотка» у СТОЯЩЕГО человека
    прыгает от 1° до 88° от кадра к кадру.
    """
    живые = sorted(ч for ч in числа if ч is not None)
    if not живые:
        return None
    середина = len(живые) // 2
    if len(живые) % 2:
        return живые[середина]
    return (живые[середина - 1] + живые[середина]) / 2.0


def лежит_по_итогу(итог) -> bool:
    """Лежит ли человек, судя по медианам за окно.

    Угол «бедро — щиколотка» в решении НЕ УЧАСТВУЕТ, и это вывод из замера, а
    не упрощение. На живом роботе у стоящего человека он прыгал от 1° до 88°
    от кадра к кадру, пока корпус ровно держал 70-90°. Точки щиколоток на
    этой камере — шум; значит шум и разбег между углами, который был главной
    защитой от «нагнулся». Держаться за признак, про который известно, что он
    случаен, нельзя ни в какую сторону: он одинаково легко и поднимет ложную
    тревогу, и проглотит настоящую.

    Вместо него «нагнулся» отсекают силуэт и ось: у нагнувшегося силуэт около
    единицы, а не полтора, и держится он секунду, а не четыре.
    """
    return (итог["корпус"] <= МЕДИАНА_КОРПУС
            and итог["ось"] <= МЕДИАНА_ОСЬ
            and итог["силуэт"] >= МЕДИАНА_СИЛУЭТ)


class _Человек:
    """Что мы намерили про этого человека за последние секунды.

    Раньше здесь лежал счётчик кадров, «похожих на лежачие». Замер на живом
    роботе показал, почему так нельзя: признаки шумят так сильно, что булев
    ответ по одному кадру — это подбрасывание монеты, и голосование по
    монеткам даёт монетку. Копим ЧИСЛА и решаем по их медианам: шум
    расходится, а поза остаётся.
    """

    __slots__ = ("замеры", "виден", "кричали")

    def __init__(self) -> None:
        # (когда, корпус, ось, силуэт) — любое из трёх может быть None.
        self.замеры: list[tuple[float, float | None, float | None,
                                float | None]] = []
        self.виден = 0.0
        self.кричали = 0.0

    def подрезать(self, сейчас: float) -> None:
        край = сейчас - ДЕРЖИТСЯ
        self.замеры = [з for з in self.замеры if з[0] >= край]

    def итог(self, сейчас: float):
        """Медианы за окно. None — замеров мало, судить рано."""
        if len(self.замеры) < КАДРОВ_ХВАТИТ:
            return None
        if сейчас - self.замеры[0][0] < ДЕРЖИТСЯ * 0.8:
            # Окно ещё не заполнилось по времени. Двадцать кадров за полсекунды
            # — это не «человек лежит четыре секунды», это быстрый детектор.
            return None
        корпус = медиана([з[1] for з in self.замеры])
        ось = медиана([з[2] for з in self.замеры])
        силуэт = медиана([з[3] for з in self.замеры])
        if корпус is None or ось is None or силуэт is None:
            return None
        return {"корпус": корпус, "ось": ось, "силуэт": силуэт,
                "замеров": len(self.замеры)}


class Сторож:
    """Смотрит на детекции и говорит, когда человек лежит уже долго.

    Отдельно от `vision_track.Глазомер` намеренно. Глазомер — это про
    следование: он ведёт ОДНУ цель, ту, за которой идём, и всех остальных
    выбрасывает. Падение же нужно замечать у любого, кто попал в кадр, — и
    как раз тогда, когда робот никуда не идёт и никого не ведёт.
    """

    def __init__(self, *, упал=None, часы=time.monotonic) -> None:
        # `упал(номер)` — что делать при подтверждённом падении. Отдельным
        # ходом, а не прямым вызовом голоса: этот модуль ничего не знает ни
        # про речь, ни про колёса, и проверять его можно без них.
        self.упал = упал
        self._часы = часы
        self._люди: dict[int, _Человек] = {}
        self._показал = False

    def принять(self, сообщение) -> None:
        """Разобрать сообщение детектора. Зовётся из потока связи с ROS."""
        цели = сообщение.get("targets") or сообщение.get("perceptions") or []
        if not isinstance(цели, list):
            return
        сейчас = self._часы()
        for цель in цели:
            if not isinstance(цель, dict):
                continue
            точки = скелет(цель)
            if точки is None:
                continue
            if not self._показал:
                self._показал = True
                log.info("сторож падений: скелет пришёл, точек %d", len(точки))
            подробно = разобрать(точки, рамка_тела(цель))
            self._судить(int(цель.get("track_id") or 0), подробно, сейчас)
        self._забыть_старых(сейчас)

    def _судить(self, номер: int, подробно, сейчас: float) -> None:
        человек = self._люди.get(номер)
        if человек is None:
            человек = self._люди[номер] = _Человек()
        человек.виден = сейчас

        if подробно is None:
            # Кадр непригоден — скелета нет вовсе. Замер не кладём, но и
            # накопленное не трогаем: мигающий детектор не должен обнулять
            # окно, иначе оно не наберётся никогда.
            return

        человек.замеры.append((сейчас, подробно.get("корпус"),
                               подробно.get("ось"), подробно.get("силуэт")))
        человек.подрезать(сейчас)

        итог = человек.итог(сейчас)
        if итог is None:
            return
        if not лежит_по_итогу(итог):
            return
        if человек.кричали and сейчас - человек.кричали < МОЛЧИМ:
            return

        человек.кричали = сейчас
        # Окно чистим: если человек так и лежит, оно наберётся заново и через
        # МОЛЧИМ секунд робот спросит ещё раз. Молча смотреть на лежащего
        # хуже, чем повториться.
        человек.замеры.clear()
        # С ЧИСЛАМИ. Когда робот ошибся трижды подряд, в журнале было «лежит
        # дольше 2.5 с» и ни одного числа — починить по такому журналу нельзя
        # вовсе, только гадать.
        log.error("сторож падений: цель %d лежит дольше %.0f с "
                  "(медианы: корпус %.0f°, ось %.0f°, силуэт %.2f, по %d замерам)",
                  номер, ДЕРЖИТСЯ, итог["корпус"], итог["ось"], итог["силуэт"],
                  итог["замеров"])
        if self.упал is not None:
            try:
                self.упал(номер)
            except Exception:                    # noqa: BLE001
                # Сторож не имеет права уронить поток связи с шасси: по нему
                # ходят и команды колёсам, и «стоп».
                log.exception("сторож падений: обработчик упал")

    def _забыть_старых(self, сейчас: float) -> None:
        протухли = [н for н, ч in self._люди.items()
                    if сейчас - ч.виден > ЗАБЫВАЕМ]
        for н in протухли:
            del self._люди[н]
