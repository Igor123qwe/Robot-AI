"""Проигрыватель: очередь треков и поток радио — в одних руках.

Играть есть куда двумя способами, и оба выглядят для очереди одинаково.
Пульт — вкладка браузера, она тянет звук сама; так было, пока своего динамика
у робота не было. Колонка — mpv на самом роботе; нужна с тех пор, как голос
переехал на свой динамик, иначе робот честно ставит песню и рапортует
«включаю», а человек не слышит ничего, потому что вкладка закрыта.

Разница между радио и Яндексом только в том, кончается ли то, что играет.
Радио — бесконечный поток: отдал адрес и забыл. Яндекс — трек за треком, и
после каждого кто-то должен включить следующий.

Очередь поэтому живёт здесь, а не в пульте: ссылки Яндекса подписанные и
живут минуты, так что нарезать плейлист вперёд нельзя — адрес надо добывать
ровно перед включением. Пульт сообщает «доиграл» на `/music/ended`, мы это
видим по счётчику и ставим следующее.

Почему счётчик, а не событие. Обратного канала от пульта к голосовому
процессу нет вовсе: пульт разговаривает с веб-сервером, веб-сервер — с
пультом по SSE, а голос ходит к веб-серверу запросами. Заводить ради одного
события четвёртый канал дороже, чем раз в секунду спросить число.
"""

from __future__ import annotations

import json
import logging
import shutil
import socket
import subprocess
import threading
import time
import urllib.error
import urllib.request

from . import yandex

log = logging.getLogger(__name__)

# Как часто спрашивать пульт, не кончился ли трек. Секунда — это пауза между
# песнями, которую слышно, но которая никого не раздражает; чаще опрашивать
# localhost можно, но незачем.
POLL = 1.0

# Ниже этого остатка идём к станции за новой партией — чтобы следующий трек
# уже лежал готовым, а не добывался в паузе.
REFILL = 2

# Насколько дольше самой песни ждать слова «доиграл». Вкладку могут закрыть,
# обновить или увести в сон — тогда сообщения не будет вовсе, и без этого
# запаса музыка вставала бы намертво до следующей команды голосом. Минута
# сверх длины трека; если длина неизвестна — четверть часа.
SLACK = 900.0
OVER = 60.0

# Громкость музыки: доля от полной. Робот говорит поверх, поэтому «обычная» —
# заметно меньше единицы.
LOUD = 0.7
# Шага здесь больше нет: громкость наружу ходит ступенями от 1 до 10, и
# постоянная STEP = 0.2 от прежней доли осталась без единого читателя.
FLOOR = 0.1


class Pult:
    """Веб-сервер пульта глазами голосового процесса.

    Все ошибки — предупреждение в лог и False: пульт могут закрыть в любой
    момент, и музыка не тот повод, чтобы ронять разговор.
    """

    def __init__(self, база: str) -> None:
        self.база = база.rstrip("/")

    def _post(self, путь: str, тело: str = "") -> bool:
        запрос = urllib.request.Request(
            self.база + путь, data=тело.encode("utf-8"), method="POST",
            headers={"Content-Type": "text/plain; charset=utf-8"})
        try:
            urllib.request.urlopen(запрос, timeout=5).close()
            return True
        except Exception as e:                      # noqa: BLE001
            log.warning("пульт не принял %s (%s)", путь, e)
            return False

    def поток(self, адрес: str) -> bool:
        """Радио: бесконечный поток. Пустой адрес — выключить всё."""
        return self._post("/speak/radio", адрес)

    def трек(self, адрес: str, название: str = "") -> bool:
        """Одна песня. Пульт скажет, когда доиграет."""
        return self._post("/speak/track",
                          json.dumps({"адрес": адрес, "название": название},
                                     ensure_ascii=False))

    def громкость(self, доля: float) -> bool:
        return self._post("/speak/volume", f"{доля:.2f}")

    def сыграно(self) -> int | None:
        """Сколько треков пульт доиграл с начала своей жизни. None — молчит."""
        try:
            with urllib.request.urlopen(self.база + "/music/state", timeout=3) as ответ:
                return int(json.loads(ответ.read()).get("кончилось") or 0)
        except Exception:                           # noqa: BLE001
            return None


class Колонка:
    """Музыка в динамик самого робота — тот же интерфейс, что у пульта.

    Пульт играет музыку во вкладке браузера, и пока голос робота шёл туда же,
    это было естественно. С отдельной колонкой на роботе вкладка становится
    лишним звеном: робот честно ставит песню, рапортует «включаю» — и человек
    не слышит ничего, потому что вкладка закрыта. Ровно так и вышло на живом
    роботе.

    Играет mpv: он умеет и бесконечный поток радио, и одиночный файл по
    ссылке, и не разваливается, когда поток моргнул. Громкость меняем через
    его же управляющий сокет — иначе пришлось бы перезапускать песню с начала,
    а это слышно.
    """

    def __init__(self, device: str = "", сокет: str = "/tmp/robot-mpv.sock",
                 игрок: str = "") -> None:
        self.device = device.strip()
        self.сокет = сокет
        self.игрок = игрок or (self.живой() or "")
        self._proc: subprocess.Popen | None = None
        self._доиграно = 0
        self._громкость = 1.0
        self._поток = ""          # что играет сейчас, если это радио
        self._lock = threading.Lock()

    # Чем играть, по убыванию удобства. mpv умеет менять громкость на лету
    # через управляющий сокет; остальные — нет, им придётся перезапускать.
    ИГРОКИ = ("mpv", "ffplay", "mpg123")

    @classmethod
    def живой(cls) -> str | None:
        """Первый проигрыватель, который не просто есть, а работает.

        Проверять наличие файла мало. На живом роботе mpv поставился и падал с
        «undefined symbol: vkCreateWaylandSurfaceKHR» — фирменные драйверы
        Rockchip против стандартной сборки. По which() он выглядел полностью
        исправным, и музыка молча уходила в никуда.
        """
        for имя in cls.ИГРОКИ:
            if shutil.which(имя) is None:
                continue
            try:
                готов = subprocess.run(
                    [имя, "--version"], stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL, timeout=10).returncode == 0
            except (OSError, subprocess.SubprocessError):
                готов = False
            if готов:
                return имя
            log.warning("%s установлен, но не запускается — пробую следующий",
                        имя)
        return None

    @classmethod
    def есть(cls) -> bool:
        return cls.живой() is not None

    def _стоп(self) -> None:
        proc, self._proc = self._proc, None
        if proc is None:
            return
        proc.terminate()
        try:
            proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            proc.kill()

    def _команда(self, адрес: str) -> list[str]:
        """Как позвать выбранный проигрыватель. Громкость — в процентах."""
        громко = int(max(0.0, min(1.0, self._громкость)) * 100)
        if self.игрок == "mpv":
            команда = ["mpv", "--no-video", "--really-quiet", "--no-terminal",
                       f"--volume={громко}",
                       f"--input-ipc-server={self.сокет}"]
            if self.device:
                команда.append(f"--audio-device=alsa/{self.device}")
            return команда + [адрес]
        if self.игрок == "ffplay":
            команда = ["ffplay", "-nodisp", "-autoexit", "-vn",
                       "-loglevel", "quiet", "-volume", str(громко)]
            return команда + [адрес]
        # mpg123: громкость долей от единицы, устройство — ключом -a.
        команда = ["mpg123", "-q", "--no-control", "-f",
                   str(int(32768 * max(0.0, min(1.0, self._громкость))))]
        if self.device:
            команда += ["-a", self.device]
        return команда + [адрес]

    def _играть(self, адрес: str, следить: bool) -> bool:
        with self._lock:
            self._стоп()
            self._поток = "" if следить else адрес
            if not адрес:
                return True
            if not self.игрок:
                log.warning("играть нечем: ни mpv, ни ffplay, ни mpg123")
                return False
            команда = self._команда(адрес)
            try:
                self._proc = subprocess.Popen(команда, stdout=subprocess.DEVNULL,
                                              stderr=subprocess.DEVNULL)
            except OSError as e:
                log.warning("не смог запустить %s (%s)", self.игрок, e)
                return False
            if следить:
                # Кто-то должен заметить, что песня кончилась: у пульта об этом
                # сообщает браузер, а здесь сообщать некому.
                threading.Thread(target=self._дождаться, args=(self._proc,),
                                 daemon=True).start()
            return True

    def _дождаться(self, proc: subprocess.Popen) -> None:
        proc.wait()
        with self._lock:
            if proc is self._proc:
                self._доиграно += 1
                self._proc = None

    def поток(self, адрес: str) -> bool:
        """Радио: бесконечный поток. Пустой адрес — выключить всё."""
        return self._играть(адрес, следить=False)

    def трек(self, адрес: str, название: str = "") -> bool:
        """Одна песня. Когда доиграет, счётчик сдвинется сам."""
        return self._играть(адрес, следить=True)

    def громкость(self, доля: float) -> bool:
        """Сделать тише или громче то, что играет прямо сейчас.

        У mpv для этого есть управляющий сокет, и это лучший случай: песня не
        прерывается. У остальных живой громкости нет вовсе, и остаётся выбор
        между «перезапустить» и «применить к следующему». Радио перезапускаем —
        у потока нет места, которое можно потерять. Песню не трогаем: начать её
        заново в ответ на «сделай тише» хуже, чем подождать до следующей.
        """
        self._громкость = max(0.0, min(1.0, доля))
        if self.игрок == "mpv":
            приказ = json.dumps({"command": ["set_property", "volume",
                                             int(self._громкость * 100)]}) + "\n"
            try:
                with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as s:
                    s.settimeout(2)
                    s.connect(self.сокет)
                    s.sendall(приказ.encode())
            except OSError:
                pass            # никто не играет — громкость запомнена на потом
            return True
        if self._поток:
            self._играть(self._поток, следить=False)
        return True

    def сыграно(self) -> int | None:
        return self._доиграно


class Player:
    """Что сейчас звучит и что зазвучит следующим.

    Одно место на оба источника намеренно: «выключи музыку», «сделай тише»,
    «что играет» человек говорит одинаково, а под ними то радио, то Яндекс.
    Развилка внутри — снаружи её быть не должно.
    """

    def __init__(self, пульт: Pult, музыка: yandex.Music | None = None,
                 громкость: float = LOUD,
                 on_volume=None, on_playing=None) -> None:
        self.пульт = пульт
        self.музыка = музыка
        self.громкость_ = min(1.0, max(FLOOR, громкость))
        self.on_volume = on_volume          # запомнить громкость между запусками
        self.on_playing = on_playing        # сказать микрофону, что стало шумно

        self.режим = ""                     # "" | "поток" | "треки"
        self.название = ""
        self._очередь: list = []
        self._станция = ""
        self._партия = ""
        self._последний = ""                # id последнего трека — для ротора
        self._начали = 0.0
        self._потолок = SLACK               # когда сдаться и ставить следующий
        self._отметка: int | None = None
        # Номер поколения. Растёт на каждой смене того, что играет: включили
        # очередь, включили радио, выключили совсем. Долгий поход за ссылкой
        # запоминает свой номер и перед отправкой в пульт сверяется — если за
        # это время человек сказал «выключи», трек уже никому не нужен.
        self._поколение = 0
        self._lock = threading.RLock()
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None

    # --- жизненный цикл -------------------------------------------------
    def start(self) -> None:
        if self._thread and self._thread.is_alive():
            return
        self._stop.clear()
        self._thread = threading.Thread(target=self._run, daemon=True)
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()

    def _run(self) -> None:
        while not self._stop.wait(POLL):
            try:
                self._tick()
            except Exception as e:                  # noqa: BLE001
                log.warning("проигрыватель споткнулся: %s", e)

    def _tick(self) -> None:
        with self._lock:
            if self.режим != "треки":
                return
            зависли = time.monotonic() - self._начали > self._потолок
        if зависли:
            # Вкладку закрыли, обновили или увели в сон — «доиграл» не придёт
            # никогда, и музыка встанет молча. Ждём заведомо дольше самой
            # песни и идём дальше сами.
            log.info("пульт не сказал, что трек кончился, — иду дальше")
            self.дальше(вслух=False)
            return
        сыграно = self.пульт.сыграно()
        if сыграно is None:
            return
        with self._lock:
            if self.режим != "треки":
                return
            if self._отметка is None:
                self._отметка = сыграно
                return
            if сыграно < self._отметка:
                # Счётчик уехал назад — значит, веб-сервер перезапустился и
                # начал считать заново. Без этого музыка вставала бы навсегда:
                # его ноль никогда не станет больше нашей семёрки.
                self._отметка = сыграно
                return
            if сыграно == self._отметка:
                return
            self._отметка = сыграно
        self._доиграл()
        self.дальше(вслух=False)

    # --- радио ----------------------------------------------------------
    def поток(self, имя: str, адрес: str) -> bool:
        """Включить бесконечный поток. Очередь треков при этом бросаем."""
        with self._lock:
            self._очередь = []
            self._станция = self._партия = self._последний = ""
            self._поколение += 1
        if not self.пульт.поток(адрес):
            return False
        with self._lock:
            self.режим, self.название = "поток", имя
        self.пульт.громкость(self.громкость_)
        self._шумно(True)
        return True

    # --- Яндекс ---------------------------------------------------------
    def очередь(self, треки: list, станция: str = "", партия: str = "") -> str:
        """Поставить список треков. Возвращает название первого — или пусто."""
        if not треки:
            return ""
        with self._lock:
            self._очередь = list(треки)
            self._станция, self._партия = станция, партия
            self._последний = ""
            self.режим = "треки"
            self._отметка = None
            self._поколение += 1
            # Отсчёт начинаем здесь, а не после того, как заиграет первый трек.
            # Иначе всё время, пока robot ходит за ссылкой, сторож в фоне видит
            # старую отметку и считает ещё не начавшуюся песню зависшей — и
            # включает следующую поверх неё. Слышно это как оборванное начало.
            self._начали = time.monotonic()
            self._потолок = SLACK
        if станция and self.музыка is not None:
            self.музыка.started(станция, партия)
        return self.дальше(вслух=False)

    def дальше(self, вслух: bool = True) -> str:
        """Следующий трек. Пусто — играть больше нечего.

        Замок здесь отпускается на каждом походе в сеть: и ссылка, и запрос к
        станции идут секунды, а в это время из главного потока могут спросить
        «что играет» или сказать «выключи». Держать очередь запертой всё это
        время — значит подвесить разговор ради музыки.
        """
        with self._lock:
            if self.режим != "треки":
                return "Сейчас играет радио, там треков нет." if вслух else ""
        self._пополнить()

        while True:
            with self._lock:
                if self.режим != "треки":
                    return ""
                if not self._очередь:
                    self.режим = self.название = ""
                    self.пульт.поток("")
                    self._шумно(False)
                    log.info("музыка кончилась")
                    return "Треки кончились." if вслух else ""
                трек = self._очередь.pop(0)
                станция, партия = self._станция, self._партия
                моё = self._поколение

            адрес = self.музыка.link(трек) if self.музыка else ""
            if not адрес:
                # Один нерабочий трек — не повод молчать весь вечер: берём
                # следующий. Пустая очередь остановит нас сама.
                continue

            # Счётчик читаем ДО отправки. Иначе так: трек не пошёл, пульт тут
            # же сообщил «доиграл», счётчик вырос — а мы к этому моменту ещё
            # не знали, от чего считать, приняли новое число за исходное и
            # больше не включили ничего. Музыка молча вставала на первой же
            # битой ссылке.
            with self._lock:
                if self._поколение != моё:
                    # Пока ходили за ссылкой, человек сказал «выключи» или
                    # включил радио. Отправить трек сейчас — значит заиграть
                    # музыку, про которую робот уверен, что она выключена.
                    return ""
            метка = self.пульт.сыграно()
            название = yandex.title(трек)
            if not self.пульт.трек(адрес, название):
                return "Пульт не отвечает, включить музыку некуда."

            длина = (getattr(трек, "duration_ms", 0) or 0) / 1000.0
            with self._lock:
                if self._поколение != моё:
                    # Успели передумать между проверкой и отправкой. Окно тут
                    # уже не в секунды, а в микросекунды, но раз мы всё-таки
                    # в него попали — гасим пульт, а не оставляем играть тайком.
                    self.пульт.поток("")
                    return ""
                self.название = название
                self._последний = getattr(трек, "track_id", "") or ""
                self._начали = time.monotonic()
                self._потолок = длина + OVER if длина else SLACK
                self._отметка = метка
                номер = self._последний
            self.пульт.громкость(self.громкость_)
            self._шумно(True)
            if станция and self.музыка is not None:
                self.музыка.playing(станция, номер, партия)
            log.info("играет: %s", название)
            return f"Включаю: {название}." if вслух else название

    def _пополнить(self) -> None:
        """Дозаказать треков у станции, пока очередь не опустела совсем."""
        with self._lock:
            if (len(self._очередь) > REFILL or not self._станция
                    or self.музыка is None):
                return
            станция, после = self._станция, self._последний
        треки, партия = self.музыка.wave(станция, after=после)
        if not треки:
            return
        with self._lock:
            # Ротор возвращает и то, что уже лежит в очереди: сравниваем по id.
            есть = {getattr(т, "track_id", "") for т in self._очередь}
            свежие = [т for т in треки if getattr(т, "track_id", "") not in есть]
            self._очередь.extend(свежие)
            if партия:
                self._партия = партия
        log.info("станция подсыпала треков: %d", len(свежие))

    def _доиграл(self) -> None:
        """Сказать ротору, что трек дослушали до конца."""
        with self._lock:
            станция, трек = self._станция, self._последний
            сколько = max(0.0, time.monotonic() - self._начали)
        if станция and трек and self.музыка is not None:
            self.музыка.played(станция, трек, round(сколько, 1), self._партия)

    # --- общее ----------------------------------------------------------
    @property
    def играет(self) -> bool:
        return bool(self.режим)

    def что_играет(self) -> str:
        with self._lock:
            if not self.режим:
                return "Сейчас ничего не играет."
            return f"Играет {self.название}." if self.название else "Играет музыка."

    def выключить(self) -> str:
        with self._lock:
            было = bool(self.режим)
            self._очередь = []
            self.режим = self.название = ""
            self._станция = self._партия = self._последний = ""
            self._поколение += 1
        self.пульт.поток("")
        self._шумно(False)
        return "Выключил." if было else "Музыка и так не играет."

    # --- громкость: наружу ступенями от 1 до 10 ---------------------------
    #
    # Внутри доля от нуля до единицы — её понимает браузер. Наружу целые
    # ступени: «сделай на семь» человек говорит и слышит в ответ, а «ноль
    # шестьдесят пять» не говорит никто. Раньше робот на «убавь до двух»
    # отвечал «звук уменьшен до двух», ничего не трогая: числа ему сказать
    # было нечем, и модель просто повторяла услышанное.

    СТУПЕНЕЙ = 10

    @property
    def ступень(self) -> int:
        """Текущая громкость по-человечески: 1 тихо, 10 во всю."""
        return max(1, min(self.СТУПЕНЕЙ, round(self.громкость_ * self.СТУПЕНЕЙ)))

    def на_ступень(self, номер: int) -> str:
        """«Сделай громкость семь». Мимо шкалы — прижимаем к краю, не спорим."""
        номер = max(1, min(self.СТУПЕНЕЙ, int(номер)))
        return self._уровень(round(номер / self.СТУПЕНЕЙ, 2))

    def громче(self, шаг: int = 1) -> str:
        return self.на_ступень(self.ступень + шаг)

    def тише(self, шаг: int = 1) -> str:
        return self.на_ступень(self.ступень - шаг)

    def обычная(self) -> str:
        return self._уровень(LOUD)

    def _уровень(self, доля: float) -> str:
        было, self.громкость_ = self.громкость_, доля
        if self.on_volume:
            self.on_volume(доля)
        self.пульт.громкость(доля)
        стало = self.ступень
        if доля == было:
            # «Уже столько и было» — это не то же самое, что «упёрлись в край».
            # Обычная громкость как раз семь из десяти, и просьба поставить
            # семь получала в ответ «тише уже некуда», хотя тише было куда.
            if доля >= 1.0:
                return f"Громче уже некуда. Сейчас {стало} из {self.СТУПЕНЕЙ}."
            if доля <= FLOOR:
                return f"Тише уже некуда. Сейчас {стало} из {self.СТУПЕНЕЙ}."
            return f"Уже {стало} из {self.СТУПЕНЕЙ}."
        куда = "тише" if доля < было else "громче"
        return f"Сделал {куда}, {стало} из {self.СТУПЕНЕЙ}."

    def _шумно(self, да: bool) -> None:
        """Сообщить наверх, что фон изменился: от этого зависит слух робота."""
        if self.on_playing:
            try:
                self.on_playing(да)
            except Exception as e:                  # noqa: BLE001
                log.debug("не сказал про шум: %s", e)
