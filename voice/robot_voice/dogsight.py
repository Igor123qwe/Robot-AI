"""Глаз на собаку: сеть говорит кто и куда, дальномер — сколько метров.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, а не ветка в следовании. По той же причине, по которой
`vision_track` живёт отдельно от `follow`: восприятие и поведение — разные
вопросы, и смешивать их значит получить цикл, в котором нельзя проверить ни то,
ни другое по отдельности. Здесь только «что видно», без единой команды колёсам.

──────────────────────────────────────────────────────────────────────────────
РАЗДЕЛЕНИЕ ОБЯЗАННОСТЕЙ, и оно не наше изобретение — его выстрадало следование
за человеком.

    СЕТЬ говорит КТО и В КАКУЮ СТОРОНУ.
    ДАЛЬНОМЕР говорит СКОЛЬКО МЕТРОВ.

Почему не одна камера. Расстояние по картинке считается только через настоящий
размер предмета. У человека рост известен и почти постоянен. У собаки он
меняется ВТРОЕ: стоит 45 см, сидит 35, лежит 15 — и оценка по высоте рамки
разъезжается во столько же раз. Поэтому она здесь есть, но как проверочная.

Почему не один дальномер. Он не знает, кто перед ним. Пятно в полуметре — это
и собака, и тапок, и ножка стула. Следование это уже проходило: робот
полминуты вёл стену в 0.48 м, приняв её за человека, и лечилось это правилом
«цель объявляет КАМЕРА, дальномер только меряет». Здесь то же правило.

──────────────────────────────────────────────────────────────────────────────
ПОЧЕМУ СЕТЬ ОТВЕЧАЕТ ПОЛТОРА РАЗА В СЕКУНДУ, А НЕ ПЯТНАДЦАТЬ

На BPU уже четыре модели: детектор тела (30 Гц), точки кисти, жесты, DOSOD. На
них держатся следование, сторож падений и остановка по ладони. Один кадр DOSOD
стоит около 130 мс — то есть занимает плату почти целиком.

Отдать собаке четверть платы — это 0.25 / 0.13 ≈ 1.9 кадра в секунду. Больше
брать нельзя: разменять остановку по ладони на «где моя собака» — плохая
сделка. Считает и держит этот предел `Пульс`, и он не удобство, а сторож.

Полторы секунды между взглядами — это не мало, если помнить, что дальномер
работает всё это время на десяти герцах. Сеть отвечает на вопрос «где она
вообще», дальномер — на вопрос «сколько до неё сейчас».

──────────────────────────────────────────────────────────────────────────────
КАК ПОНИМАЕМ, ЧТО СОБАКА ЗАБРАЛАСЬ НА КРОВАТЬ

Тут была моя ошибка, и она стоила первой редакции замысла. Я объявил главным
признак от дальномера — «низ пятна выше 0.35 м над полом» — и он оказался слеп
ровно на рабочей дистанции. Дальномер стоит на 15 см и смотрит вниз на 12°,
поле по вертикали 60°, значит верхний луч идёт 18° над горизонтом:

    до кровати 0.60 м с метра — нужен луч 28.8°, НЕ ВИДНО
    с полутора метров          — 20.1°, НЕ ВИДНО
    с двух метров              — 15.4°, видно
    до дивана 0.80 м с двух    — 20.6°, НЕ ВИДНО
    с двух с половиной         — 16.7°, видно

Расчёт держит проверка `test_собаку_на_кровати_дальномер_не_видит`.

Поэтому главные признаки — КАМЕРНЫЕ, и они работают с метра:

  1. ПЕРЕКРЫТИЕ РАМОК. В одном кадре сеть даёт и собаку, и кровать. Рамка
     собаки лежит внутри рамки кровати по горизонтали, а низ собаки заметно
     ВЫШЕ низа кровати — значит она на ней, а не перед ней. Низ мебели тут
     ключевой: собака, стоящая перед кроватью, перекрывает её по горизонтали
     ровно так же, и различает эти два случая только высота нижнего края.

  2. НИЗ РАМКИ ВЫШЕ ЛИНИИ ПОЛА. Собака на полу: чем она дальше, тем выше её
     низ в кадре, и связь эта жёсткая. Собака на кровати: низ рамки оказывается
     выше, чем пол вообще может быть на измеренном дальномером расстоянии.
     Признак независим от того, увидела ли сеть кровать, — а она её видит не
     всегда: разобранная постель под пледом на кровать не похожа.

  3. ВЫСОТА ПЯТНА НАД ПОЛОМ — подтверждение, и только с наблюдательной
     позиции, куда робот уже отъехал. С метра его нет по геометрии выше.

Голосование: любой из первых двух заводит счётчик, третий подтверждает.

АСИММЕТРИЯ СЧЁТЧИКОВ НАМЕРЕННАЯ: войти в ожидание легко, выйти — трудно.
Ложный выход означает, что робот дёрнется к кровати, пока собака ещё там.
"""

from __future__ import annotations

import logging
import math
import time

from . import follow, rig

log = logging.getLogger(__name__)

# --- сколько платы можно тратить на собаку -----------------------------------
# Один кадр DOSOD, секунд. Из их же журнала.
КАДР_СТОИТ = 0.13
# Какую долю BPU отдаём Спутнику. Четверть: остальное — детектору тела на
# тридцати герцах, точкам кисти и жестам, то есть следованию, сторожу падений
# и остановке по ладони.
ДОЛЯ_BPU = 0.25
# Отсюда потолок частоты запросов. Считаем, а не пишем числом: поменяется цена
# кадра или доля — потолок поедет сам, и никто не забудет его поправить.
ПУЛЬС_ПРЕДЕЛ = ДОЛЯ_BPU / КАДР_СТОИТ

# Сколько раз в секунду просим кадр в каждом занятии. Ведём — чаще всего,
# ждём у кровати — реже некуда: собака там лежит минутами, и смотреть на неё
# по два раза в секунду значит греть плату впустую.
ПУЛЬС = {
    "ВЕДУ": ПУЛЬС_ПРЕДЕЛ,
    "СТОЮ": 1.0,
    # ИЩУ здесь НЕТ намеренно. В этом занятии кадры заказывает поиск по
    # квартире, а не спутник: сторож считает четверть платы за себя, и два
    # честных просителя вместе берут половину. Спутник в ИЩУ читает те же
    # `вещи`, просто не заказывает. Остаётся ПУЛЬС_ПО_УМОЛЧАНИЮ — на случай,
    # когда поиска нет вовсе и спутник смотрит сам.
    "НАБЛЮДАЮ": 0.5,
    "ОТСТУПАЮ": 0.5,
}
ПУЛЬС_ПО_УМОЛЧАНИЮ = 1.0

# --- какого роста собака ------------------------------------------------------
# В СЛОВАРЕ ЭТОГО НЕТ, И НЕ ДОЛЖНО БЫТЬ. Там рост и «движется» взаимно
# исключают друг друга: рост нужен пометкам, чтобы поставить вещь на карту, а
# подвижное на карту не идёт. Проверка это правило держит и меня на нём
# поймала. Здесь рост нужен для другого — для проверочной оценки расстояния.
#
# ПОМЕРИТЬ ПОД СВОЮ СОБАКУ. Числа для средней; у мелкой или крупной оценка по
# рамке разъедется во столько же раз, во сколько отличается рост.
РОСТ_СТОЯ = 0.45
РОСТ_СИДЯ = 0.35
РОСТ_ЛЁЖА = 0.15
# По какому отношению сторон рамки судим о позе. Лежащая собака длинная и
# низкая, сидящая почти квадратная, стоящая между ними.
ЛЁЖА_ШИРЕ_ЧЕМ = 1.8
СИДЯ_УЖЕ_ЧЕМ = 1.1

# --- где искать пятно собаки в сетке -----------------------------------------
# Сколько колонок вокруг пеленга сети смотрим. Одна в каждую сторону: зона
# дальномера — конус в семь с половиной градусов, собака в метре занимает
# примерно столько же, а пеленг сети успевает устареть на поворот корпуса.
СЕКТОР = 1
# Сколько зон должны увидеть собаку, чтобы это была собака, а не блик.
ЗОН_ХВАТИТ = 2
# Ближе этого замерам не верим — паразитная засветка на упоре.
НЕ_ВЕРИМ_БЛИЖЕ = rig.ЗАСВЕТКА_БЛИЖЕ

# --- признаки «на мебели» -----------------------------------------------------
# Какая доля ширины собаки должна лежать над мебелью. Половина — из ТЗ.
ПЕРЕКРЫТИЕ_ДОЛЯ = 0.5
# Насколько низ собаки должен быть выше низа мебели — долей высоты кадра.
# Пятнадцать процентов от рамки мебели в ТЗ; в долях кадра это примерно
# столько же и не зависит от того, влезла ли мебель в кадр целиком.
НИЗ_ВЫШЕ_НА = 0.06
# На сколько низ рамки должен обгонять линию пола, чтобы это было возвышение,
# а не погрешность пеленга. Восьмая часть кадра.
НАД_ПОЛОМ_В_КАДРЕ = 0.12
# Классы, на которые собака забирается.
ЛЕЖБИЩА = ("bed", "couch", "armchair", "chair", "bench")

# Счётчики входа и выхода, в кадрах дальномера. Из ТЗ; асимметрия намеренная —
# войти в ожидание легко, выйти трудно. Считаем по дальномеру, а не по сети:
# двадцать кадров сети — это одиннадцать секунд, за которые робот успел бы
# доехать до кровати. Двадцать кадров дальномера — две секунды, как и
# задумывал ТЗ.
ПОДНЯЛАСЬ_КАДРОВ = 20
СПРЫГНУЛА_КАДРОВ = 15


class Пульс:
    """Сколько раз в секунду можно просить у сети кадр. Сторож, не удобство.

    Спрашивать «пора ли» надо на каждом круге; `пора` сама и решает, и
    отмечает. Любая просьба чаще `ПУЛЬС_ПРЕДЕЛ` зажимается — не потому что мы
    вежливые, а потому что за этим пределом начинается плата детектора людей.
    """

    def __init__(self, часы=time.monotonic) -> None:
        self._часы = часы
        # МИНУС БЕСКОНЕЧНОСТЬ, А НЕ НОЛЬ. С нулём первый же кадр оказывался
        # «слишком рано», если часы тоже начинались с нуля, — и Спутник молчал
        # до первой полной паузы. Поймано проверкой.
        self._спросили = float("-inf")
        self.всего = 0

    def частота(self, занятие: str) -> float:
        """Сколько кадров в секунду положено этому занятию."""
        return min(ПУЛЬС_ПРЕДЕЛ, ПУЛЬС.get(занятие, ПУЛЬС_ПО_УМОЛЧАНИЮ))

    def пора(self, занятие: str) -> bool:
        сейчас = self._часы()
        if сейчас - self._спросили < 1.0 / max(0.01, self.частота(занятие)):
            return False
        self._спросили = сейчас
        self.всего += 1
        return True

    def доля_платы(self, занятие: str) -> float:
        """Какую долю BPU занимает Спутник в этом занятии."""
        return self.частота(занятие) * КАДР_СТОИТ


def поза_по_рамке(ширина: float, высота: float) -> tuple[str, float]:
    """Как собака стоит и какого она роста в этой позе.

    Грубо, по отношению сторон рамки: лежащая длинная и низкая, сидящая почти
    квадратная. Точнее по одной рамке не выйдет, а точнее и не нужно — оценка
    по рамке всё равно проверочная.
    """
    if высота <= 0:
        return "стоя", РОСТ_СТОЯ
    отношение = ширина / высота
    if отношение >= ЛЁЖА_ШИРЕ_ЧЕМ:
        return "лёжа", РОСТ_ЛЁЖА
    if отношение <= СИДЯ_УЖЕ_ЧЕМ:
        return "сидя", РОСТ_СИДЯ
    return "стоя", РОСТ_СТОЯ


def сколько_по_рамке(встреча, фокус: float) -> tuple[str, float]:
    """Проверочная оценка расстояния по размеру собаки. ("поза", метры).

    Та же геометрия, что у мерки по росту человека: d = f·H/h. Разница в том,
    что рост собаки меняется ВТРОЕ между «стоит» и «лежит», поэтому сперва
    угадываем позу по отношению сторон рамки, а уже из позы берём рост.

    ЭТО ПРОВЕРКА, А НЕ ИЗМЕРЕНИЕ, и разница принципиальная. Числа РОСТ_* взяты
    для средней собаки и под эту собаку не мерены ни разу — гадать по ним о
    расстоянии и тем более решать на этом основании было бы ровно тем, что
    этот разбор весь вечер и вычищает. Оценка нужна для другого: сравнить с
    дальномером и СКАЗАТЬ В ЖУРНАЛ, когда они расходятся.

    Зачем сравнивать. Пятно в секторе — это ближайшее, что там есть, а не
    обязательно собака. Следование эту грабль уже прошло: робот полминуты вёл
    стену в 0.48 м, приняв её за человека. Если дальномер говорит «полметра»,
    а рамка — «два с половиной», то мерят они разное, и в журнале это видно.

    Ноль в ответе — рамки нет или она нелепая.
    """
    высота = float(getattr(встреча, "высота_рамки", 0.0) or 0.0)
    if высота <= 1.0 or фокус <= 0:
        return "", 0.0
    слева = float(getattr(встреча, "слева", 0.0) or 0.0)
    справа = float(getattr(встреча, "справа", 0.0) or 0.0)
    # Края хранятся в углах, а высота — в пикселях. Ширину в пикселях берём
    # через фокус: тем же преобразованием, что и всё остальное здесь.
    ширина = abs(math.tan(слева) - math.tan(справа)) * фокус
    поза, рост = поза_по_рамке(ширина, высота)
    return поза, фокус * рост / высота


def пятно_в_секторе(сетка, куда: float, поле: float = 60.0):
    """Ближайшее пятно в стороне `куда`. (метры, зон) или None.

    Сетка ждётся БЕЗ ПОЛА: иначе ближайшим пятном в любой комнате окажется
    собственный пол робота. Ту же граблю следование уже прошло, и в его шапке
    написано, чем это кончается.

    Берём минимум, а не медиану, и это не мелочь. Медиана по колонке — верная
    мера для человека: он занимает колонку целиком. Собака низкая, в колонке
    она даёт две зоны из шести, и медиана вернёт стену за ней.
    """
    если_нет = None
    if not сетка:
        return если_нет
    колонок = len(сетка[0]) if сетка[0] else 8
    середина = follow.колонка_под_углом(куда, колонок)
    ближе, зон = None, 0
    for ряд in сетка:
        for к in range(max(0, середина - СЕКТОР),
                       min(колонок, середина + СЕКТОР + 1)):
            з = ряд[к] if к < len(ряд) else 0.0
            if not з or з <= НЕ_ВЕРИМ_БЛИЖЕ:
                continue
            зон += 1
            if ближе is None or з < ближе:
                ближе = з
    if ближе is None or зон < ЗОН_ХВАТИТ:
        return если_нет
    return (ближе, зон)


def пеленг_сейчас(встреча, поза) -> float:
    """Пеленг встречи, поправленный на поворот корпуса с момента съёмки.

    ЗАЧЕМ. Сеть отвечает полтора раза в секунду, а подтверждение живёт две
    (ДЕРЖИМ_БЕЗ_СЕТИ). То есть пеленг, которым робот рулит прямо сейчас, может
    быть двухсекундной давности — а он записан ОТ ВЗГЛЯДА РОБОТА, и робот за
    эти две секунды повернулся. На разрешённых спутнику 0.5 рад/с это
    пятьдесят семь градусов: собака справа, робот доворачивается влево.

    Поправка ничего не стоит и ничего не выдумывает: курс на момент съёмки
    лежит во встрече (`откуда`), нынешний знает одометрия. Разница — это
    ровно то, на что уехал взгляд.

    Нет одной из поз — отдаём как есть. Это не хуже прежнего: прежде так было
    всегда.
    """
    угол = float(getattr(встреча, "угол", 0.0) or 0.0)
    было = getattr(встреча, "откуда", None)
    if поза is None or было is None or len(было) < 3 or len(поза) < 3:
        return угол
    ушли = float(поза[2]) - float(было[2])
    # Влево положительно и у пеленга, и у курса: робот повернулся влево на
    # `ушли` — значит предмет уехал в кадре вправо ровно на столько же.
    return (угол - ушли + math.pi) % (2 * math.pi) - math.pi


def над_мебелью(собака, мебель) -> bool:
    """Рамка собаки лежит НА рамке мебели, а не перед ней.

    Два условия, и второе важнее первого. Собака, стоящая ПЕРЕД кроватью,
    перекрывает её по горизонтали ровно так же — различает эти два случая
    только высота нижнего края: у стоящей на полу низ рамки ниже, чем у
    кровати, у забравшейся — заметно выше.
    """
    if собака is None or мебель is None:
        return False
    if собака.перекрытие(мебель) < ПЕРЕКРЫТИЕ_ДОЛЯ:
        return False
    if not собака.низ or not мебель.низ:
        return False
    return собака.низ < мебель.низ - НИЗ_ВЫШЕ_НА


def низ_выше_пола(низ_рамки: float, расстояние: float,
                  высота_камеры: float, поле_верт: float) -> bool:
    """Низ рамки выше, чем пол может быть на этом расстоянии.

    Собака на полу: точка опоры лежит на плоскости Z=0, и в кадре она тем
    выше, чем дальше собака. Связь жёсткая, считается из высоты камеры и её
    поля зрения. Если низ рамки оказался ВЫШЕ этой линии — собака стоит не на
    полу.

    Признак не зависит от того, увидела ли сеть кровать. Это важно: разобранная
    постель под пледом на кровать не похожа, и правило рамок тогда молчит.
    """
    если_не_знаем = False
    if расстояние <= 0 or низ_рамки <= 0 or поле_верт <= 0:
        return если_не_знаем
    # Угол вниз до точки пола на этом расстоянии.
    вниз = math.atan2(высота_камеры, расстояние)
    # Он же — доля кадра ниже середины.
    доля_пола = 0.5 + вниз / math.radians(поле_верт)
    return низ_рамки < доля_пола - НАД_ПОЛОМ_В_КАДРЕ


class Поднялась:
    """Счётчики «собака на мебели» с асимметричным гистерезисом.

    Вход в ожидание лёгкий, выход трудный, и это из ТЗ. Ложный выход означает,
    что робот дёрнется к кровати, пока собака ещё там, — а это ровно то
    поведение, которого вся затея и избегает.
    """

    def __init__(self) -> None:
        self.поднята = False
        self._за = 0
        self._против = 0
        self.почему = ""

    def кадр(self, признаки: dict) -> bool:
        """Один кадр дальномера. Отдаёт, поднята ли собака сейчас."""
        сработал = next((и for и, да in признаки.items() if да), "")
        if сработал:
            self._за += 1
            self._против = 0
            if not self.поднята and self._за >= ПОДНЯЛАСЬ_КАДРОВ:
                self.поднята = True
                self.почему = сработал
                log.info("собака: поднялась на мебель (%s)", сработал)
        else:
            self._против += 1
            self._за = 0
            if self.поднята and self._против >= СПРЫГНУЛА_КАДРОВ:
                self.поднята = False
                self.почему = ""
                log.info("собака: спрыгнула")
        return self.поднята

    def забыть(self) -> None:
        self.__init__()
