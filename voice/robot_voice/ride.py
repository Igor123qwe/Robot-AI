"""Переезд: проехать столько-то метров, объезжая, и повернуться на месте.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Ездить по квартире роботу надо не только в обходе.
Он ищет собаку, он пойдёт звать человека к столу — и каждый раз это одно и то
же: катить вперёд, спрашивая планировщик и дальномер, узнавать тупик по словам
планировщика, звать арбитра выбирания, следить за буксующими колёсами и уметь
отъехать назад по собственному следу.

Сто двадцать строк, каждая из которых написана по живой беде. Скопировать их
второй раз — значит завести две копии, которые разойдутся через месяц, и
разойдутся молча: обход будет ездить по исправленному, а поиск по прежнему.

ЧТО ЗДЕСЬ НЕ ЖИВЁТ. Числа политики — как быстро ехать, на сколько заворачивать,
сколько метров за переезд — стоят признаками объекта, а не константами модуля.
Обход ползёт медленно, потому что едет в неизвестность; поиск может ехать
иначе. Механика езды у них общая, осторожность — своя.

ВЫНЕСЕНО БЕЗ ЕДИНОГО ИЗМЕНЕНИЯ ПОВЕДЕНИЯ. Доказательство — старые проверки
обхода, которые остались зелёными и которые никто не правил.
"""

from __future__ import annotations

import logging
import math
import threading
import time

from . import planner, progress
from .follow import скорость_по_виду

log = logging.getLogger(__name__)

# Круг цикла. Тот же, что у следования: пятнадцать раз в секунду — это чаще,
# чем отдаёт дальномер, и реже, чем нужно, чтобы греть процессор впустую.
ШАГ = 1.0 / 15.0

# --- когда колёса давят, а робот стоит ----------------------------------
# ЖИВАЯ БЕДА, ради которой это заведено. Робот упёрся носом в стену — вся
# сетка дальномера, все шестьдесят четыре зоны, читалась 0.13-0.16 м — и
# ПЯТНАДЦАТЬ СЕКУНД честно вёл «стену слева», давя на колёса, которые не
# крутились. В журнале это выглядело безупречно: планировщик выдавал дуги,
# арбитр перебирал средства, дальномер писал «не пускаю вперёд». Никто не
# спросил самого простого: а робот-то едет?
#
# У следования такой сторож есть давно (progress.Ход), у обхода не было.
#
# Пороги здесь СВОИ, и без них сторож был бы слеп: у следования команда
# считается командой от 0.10 м/с и 0.9 рад/с, а обход ползёт от 0.03 м/с и
# крутится не сильнее 0.40 — в те пороги он не попадает вовсе.
КОМАНДА_ВСЕРЬЁЗ = 0.02
ПОВОРОТ_ВСЕРЬЁЗ = 0.15
# Сколько секунд следа помним, чтобы было куда отъехать. Восемь: сторож
# опознаёт упор примерно за две секунды, и остаток окна — это тот путь,
# который робот успел проехать ДО того, как встал.
СЛЕД_ПОМНИМ = 8.0
# Насколько курс мог уехать, чтобы след всё ещё считался «прямо позади».
# Двадцать градусов: дальше отъезд назад ведёт уже не по своему следу, а
# вбок от него — то есть вслепую, чего роботу нельзя.
СЛЕД_ПРЯМО_ДО = math.radians(20.0)


def _отступ_по_следу(след) -> float:
    """Сколько метров назад роботу МОЖНО отъехать. Ноль — нельзя.

    Пятиться вслепую роботу нельзя: сзади у него слепая зона, и об этом
    написано в шапке планировщика. Но «назад по следу, который сам же проехал
    полминуты назад» — не вслепую: тот кусок пола робот только что занимал
    собственным корпусом.

    Условие «по своему следу» и проверяется буквально: идём по записи назад,
    пока курс не разошёлся с нынешним больше чем на СЛЕД_ПРЯМО_ДО. Дальше
    отъезд вёл бы уже не по следу, а вбок от него.

    Это, кстати, само собой лечит и худший случай: если робот, упёршись,
    успел провернуться на сорок градусов, то весь его доупорный след
    отбрасывается и отъезд не разрешается вовсе. Так и надо — назад по прямой
    он уехал бы не туда, где был.
    """
    if len(след) < 2:
        return 0.0
    _, x, y, курс = след[-1]
    дальше = 0.0
    for было in reversed(след[:-1]):
        разница = abs((было[3] - курс + math.pi) % (2 * math.pi) - math.pi)
        if разница > СЛЕД_ПРЯМО_ДО:
            break
        дальше = math.hypot(было[1] - x, было[2] - y)
    return min(дальше, planner.ОТСТУП_НЕ_ДАЛЬШЕ)


class Переезд:
    """Умение ездить. Наследуется тем, кому надо куда-то доехать.

    Ждёт от наследника: `ros`, `tof`, `карта`, `компас`, `выбираюсь`,
    `_стоп`, `проехали`, `_велели` — и числа политики ниже.
    """

    # Числа политики. Значения по умолчанию — обходные: он ездит в
    # неизвестность и потому осторожнее всех. Кому нужно иначе — ставит своё
    # в __init__, а не правит здесь.
    едем_не_быстрее = 0.18
    поворот_на_ходу = 0.5
    поворот_на_месте = 0.9
    переезд_метров = 2.0
    забываем_неудачу = 30.0

    def _повернуть(self, на_сколько: float) -> bool:
        """Повернуться на месте на столько радиан. False — не вышло.

        Считаем по одометрии приращениями, а не разницей с началом: поворот
        идёт по кругу, и на трёхстах шестидесяти градусах разница вернулась бы
        к нулю. Нет одометрии — считаем по секундомеру от заказанной скорости:
        обход без неё станет кривым, но не сорвётся.
        """
        if not self._крутиться_можно():
            return False
        сторона = 1.0 if на_сколько >= 0 else -1.0
        цель = abs(на_сколько)
        повёрнуто = 0.0
        прошлая = self._поза()
        начали = time.monotonic()
        # Предохранитель: заказанная скорость плюс половина. Робот, у которого
        # буксуют колёса, иначе крутился бы вечно.
        предел = цель / self.поворот_на_месте * 1.5 + 1.0
        while not self._стоп.is_set() and повёрнуто < цель:
            if time.monotonic() - начали > предел:
                log.info("обход: поворот не сошёлся за %.1f с — еду дальше",
                         предел)
                break
            if not self._скорость(0.0, self.поворот_на_месте * сторона):
                return False
            self._стоп.wait(ШАГ)
            сейчас = self._поза()
            if сейчас is not None and прошлая is not None:
                шаг = (сейчас[2] - прошлая[2] + math.pi) % (2 * math.pi) - math.pi
                повёрнуто += abs(шаг)
            elif сейчас is None:
                повёрнуто += self.поворот_на_месте * ШАГ
            прошлая = сейчас
        self._встать()
        return повёрнуто >= цель

    def _ехать(self, метров: float) -> bool:
        """Проехать вперёд, объезжая. False — не проехали и метра из десяти.

        Дугу выбирает тот же планировщик, что и следование, и по тем же
        точкам: разница только в том, что цель здесь не человек, а «вперёд».
        Дальномер остаётся поверх всего — он и решает, ехать ли вообще.
        """
        начало = self._поза()
        проехали = 0.0
        прошлая = начало
        начали = time.monotonic()
        # Предохранитель от буксующих колёс. В него надо уложить не только
        # саму езду, но и ВЫБИРАНИЕ из тупика: лестница арбитра (подождать →
        # развернуться → идти вдоль стены) длится свои двадцать четыре секунды,
        # и предохранитель, срезающий её на середине, оставляет арбитра в
        # состоянии «иду вдоль стены» до следующего переезда — то есть до
        # первого же «сдался».
        предел = (метров / max(0.05, self.едем_не_быстрее) * 2.0 + 2.0
                  + planner.ЖДЁМ_СЕКУНДУ + planner.КРУТИМСЯ_НЕ_ДОЛЬШЕ
                  + planner.ВДОЛЬ_СТЕНЫ_НЕ_ДОЛЬШЕ)
        # КАЖДЫЙ ПЕРЕЕЗД — ПОПЫТКА С ЧИСТОГО ЛИСТА. Арбитр помнит, чем занят,
        # и без сброса это «чем занят» переживало весь обход: один тупик в
        # начале — и все следующие переезды начинались сразу с «иду вдоль
        # стены», а дальше с «сдался», который уже не сбрасывается ничем.
        # В обходе `сбросить()` звался ровно один раз, в начать().
        self.выбираюсь.сбросить()
        # Сторож буксующих колёс и след, по которому можно отъехать назад.
        # Оба живут ровно один переезд: чужой след — это не свой след.
        ход = progress.Ход(трогается_от=КОМАНДА_ВСЕРЬЁЗ,
                           крутится_от=ПОВОРОТ_ВСЕРЬЁЗ)
        след: list[tuple[float, float, float, float]] = []
        было_вперёд = было_поворот = 0.0
        # ПОЧЕМУ НЕ ЕДЕМ — В ЖУРНАЛ, и без этого разобрать нельзя ничего.
        #
        # Поймано на живой поездке: «Обошёл квартиру: два осмотра, НОЛЬ
        # МЕТРОВ». Робот полторы минуты честно крутил панорамы и никуда не
        # сдвинулся, а в журнале про переезд не было ни строки — ни сколько
        # свободно, ни что сказал сторож, ни какую дугу выбрал планировщик.
        # Разбирать было нечего.
        #
        # Пишем не каждый круг (пятнадцать раз в секунду), а раз в секунду и
        # в конце: причина держится секундами, а журнал, в котором не найти
        # нужного, не лучше пустого.
        отчёт = 0.0
        мешало = ""
        кругов = 0
        while not self._стоп.is_set() and проехали < метров:
            кругов += 1
            if time.monotonic() - начали > предел:
                break
            # ГДЕ МЫ И ЕДЕМ ЛИ ВООБЩЕ — в самом начале круга, до всех веток.
            # Обе ветки «упёрлись» уходят через continue, и запись в конце
            # цикла их не застаёт: сторож молчал бы ровно в том положении,
            # ради которого он и заведён.
            где = self._поза()
            ход.отметить(self._велели[0], self._велели[1], где)
            if где is not None:
                след.append((time.monotonic(), float(где[0]), float(где[1]),
                             float(где[2])))
                край = time.monotonic() - СЛЕД_ПОМНИМ
                while len(след) > 1 and след[0][0] < край:
                    del след[0]
            отступ = _отступ_по_следу(след) if ход.застряли() else 0.0
            взгляд = self.tof.взгляд() if self.tof is not None else None
            мешает = self.tof.мешает() if self.tof is not None else ""
            мешало = мешает
            if мешает:
                # Сторож сказал «нельзя» — это не повод бросать обход, это
                # повод свернуть. Пробуем выбраться тем же арбитром, что и
                # следование; не вышло — возвращаем «не проехали», и верхний
                # цикл сам решит, сколько раз это терпеть.
                if not self._обойти(взгляд, отступ=отступ):
                    break
                continue
            свободно = getattr(взгляд, "свободно_впереди", 0.0) if взгляд else 0.0
            точки = self._препятствия(взгляд)
            вперёд, поворот, почему = self._дуга(точки, свободно)
            сейчас_же = time.monotonic()
            if сейчас_же - отчёт > 1.0:
                отчёт = сейчас_же
                log.info("обход, переезд: проехал %.2f из %.2f м | свободно "
                         "%.2f м, точек %d, вперёд %.2f, поворот %.2f (%s)%s",
                         проехали, метров, свободно, len(точки), вперёд,
                         поворот, почему,
                         f", сторож: {мешало}" if мешало else "")
            # ТУПИК УЗНАЁМ ПО СЛОВАМ ПЛАНИРОВЩИКА, А НЕ ПО НУЛЯМ.
            #
            # Здесь стояло `вперёд <= 0 и |поворот| <= 1e-3`, и это условие НЕ
            # СРАБАТЫВАЛО НИКОГДА. Планировщик в тупике не отдаёт нули: он
            # отдаёт (0.0, обход(...)) — «вперёд некуда, разворачиваюсь»
            # (planner.py, ветки «все дуги упираются» и «ищу обход»). Поворот
            # выходил ненулевым, условие не выполнялось, и обход честно
            # крутился на месте до предохранителя по времени — пятнадцать
            # секунд на каждый переезд, ноль пройденных метров, арбитр
            # `выбираюсь` не спрошен ни разу.
            #
            # Так это и выглядело в живом журнале: восемнадцать остановок,
            # двенадцать метров — по две трети метра на переезд.
            #
            # Следование эту же развилку берёт ПРАВИЛЬНО и давно (follow.py:
            # «упираются» in план_сказал or «ищу обход» in план_сказал).
            # Берём то же самое: у планировщика надо спрашивать не «нулевая ли
            # скорость», а «нашёл ли ты дорогу».
            упёрлись = "упираются" in почему or "ищу обход" in почему
            if упёрлись or (вперёд <= 0.0 and abs(поворот) <= 1e-3):
                if not self._обойти(взгляд, почему, отступ=отступ):
                    break
                continue
            # Дуга нашлась — может быть, выбрались. Подтверждаем несколькими
            # кадрами подряд, иначе просвет, пойманный краем поля зрения на
            # развороте, сбросил бы манёвр на половине.
            if self.выбираюсь.выбираюсь:
                self.выбираюсь.едем()
            было_вперёд = planner.придержать(было_вперёд, вперёд, ШАГ,
                                             planner.РАЗГОН,
                                             planner.СБРОС)
            было_поворот = planner.придержать(было_поворот, поворот, ШАГ,
                                              planner.РАЗГОН_ПОВОРОТА,
                                              planner.РАЗГОН_ПОВОРОТА)
            if not self._скорость(было_вперёд, было_поворот):
                return проехали > 0.1
            self._стоп.wait(ШАГ)
            сейчас = self._поза()
            if сейчас is not None and прошлая is not None:
                проехали += math.hypot(сейчас[0] - прошлая[0],
                                       сейчас[1] - прошлая[1])
            elif сейчас is None:
                проехали += было_вперёд * ШАГ
            прошлая = сейчас
        self._встать()
        self.проехали += проехали
        уехали = проехали > 0.1
        if not уехали:
            log.warning("обход: переезд не удался — за %.0f с и %d кругов "
                        "проехал %.2f м. Последнее, что сказал сторож: %s",
                        time.monotonic() - начали, кругов, проехали,
                        мешало or "ничего, дорога свободна")
        return уехали

    def _дуга(self, точки, свободно: float) -> tuple[float, float, str]:
        """Куда и как быстро ехать вперёд. Ноль-ноль — некуда.

        Третьим возвращаем ОБЪЯСНЕНИЕ планировщика, и оно тут не для журнала.
        По нему и только по нему видно, что робот упёрся: см. _ехать.
        """
        потолок = min(self.едем_не_быстрее, скорость_по_виду(свободно)
                      if свободно > 0 else self.едем_не_быстрее)
        if потолок <= 0:
            return 0.0, 0.0, "дальномер не пускает"
        # Цель — «прямо и подальше»: обход никого не догоняет, ему нужно
        # просто проехать вперёд, обходя то, что мешает.
        вперёд, поворот, почему = planner.выбрать(self.переезд_метров, 0.0, точки,
                                                  потолок, self.поворот_на_ходу)
        return вперёд, поворот, почему

    def _обойти(self, взгляд, почему: str = "", *,
                отступ: float = 0.0) -> bool:
        """Тупик: спросить арбитра, что делать. False — сдался.

        ПЕРЕД АРБИТРОМ — ЧИСТИМ БЛИЖНЮЮ ПАМЯТЬ, и это не вольность: первое
        средство арбитра называется ЗАБЫЛ, и в нём написано «забывание уже
        случилось у вызывающего». У следования оно и вправду случается; обход
        же арбитра звал, ничего не забыв, — то есть пропускал самое дешёвое из
        четырёх средств и сразу переходил к ожиданию.

        Чистим только вблизи и только сейчас, когда упёрлись: карта в
        остальном полезна, а призрак вплотную — самая частая причина тупика на
        ровном месте (mapping.забыть_вокруг).

        ЗАДНИЙ ХОД СПРАШИВАЕМ У ПАМЯТИ. Дальномер смотрит вперёд и только
        вперёд; отъезд идёт назад, где робот слеп. Ограничений на него и так
        много — не дальше двадцати сантиметров, вдвое медленнее ходового,
        строго прямо и только по своему следу, — но «я тут проезжал» говорит
        про пол, а не про то, кто встал за спиной за эти секунды. Ребёнок,
        подошедший посмотреть, попадает ровно сюда.

        Память об этом знает: `mapping.можно_ехать` держит заднее полушарие
        по карте. К ней ходит голосовая команда «назад» (ros._motion_loop), а
        отъезд шёл мимо — он подаёт скорость через publish_twist, где этой
        проверки нет. Спрашиваем здесь, на каждом круге отъезда: поездка
        длится секунды, и человек за спиной успевает и подойти, и уйти.
        """
        точки = self._препятствия(взгляд)
        если_впервые = not self.выбираюсь.выбираюсь
        if если_впервые and self.карта is not None:
            try:
                self.карта.забыть_вокруг()
            except Exception:                   # noqa: BLE001
                log.exception("обход: не смог почистить карту вокруг")
        вперёд, поворот, чем_занят, вслух = self.выбираюсь.решить(
            точки, 0.0, отступ=отступ)
        if если_впервые:
            log.info("обход: упёрся (%s) — выбираюсь", почему or "планировщик "
                     "не нашёл дуги")
        if вперёд < 0 and not self._назад_можно(вперёд):
            # Память не пускает. Не беда и не отказ от выбирания: стоим этот
            # круг, а лестница сама перейдёт к следующему средству.
            вперёд = поворот = 0.0
        if чем_занят == planner.Выбираюсь.СДАЛСЯ:
            log.info("обход: выбраться не смог — %s", вслух or "молча")
            self.выбираюсь.сбросить()
            return False
        if not self._скорость(вперёд, поворот):
            return False
        self._стоп.wait(ШАГ)
        return True

    def _назад_можно(self, вперёд: float) -> bool:
        """Пустит ли память назад. Карты нет — пускаем: незнание не запрет."""
        if self.карта is None:
            return True
        try:
            можно, почему = self.карта.можно_ехать(вперёд, 0.0, 0.0)
        except Exception:                       # noqa: BLE001
            log.exception("обход: карта не ответила про задний ход")
            return True
        if not можно:
            log.info("обход: назад не пячусь — %s", почему)
        return bool(можно)

    def _крутиться_можно(self) -> bool:
        """Пустит ли память развернуться на месте.

        РАЗВОРОТ НА МЕСТЕ — ТОЖЕ СЛЕПОЕ ДВИЖЕНИЕ, и это упускали. Дальномер
        смотрит вперёд на шестьдесят градусов; при вращении корпус заметает
        окружность ЦЕЛИКОМ, включая те три четверти круга, которых робот не
        видит вовсе. Ребёнок, подошедший сзади посмотреть, находится ровно там.

        Спрашивать было чем: `mapping.можно_ехать` держит для этого случая
        отдельную ветку — всю окружность разом, с запасом ЗАПАС_ПОВОРОТА, — и
        ветка эта не звалась ниоткуда, кроме сторожа внутри `_motion_loop`.
        А обход, поиск и спутник крутятся своим циклом, мимо него.

        Карта молчит — крутимся: незнание не запрет, и робот, которому нельзя
        повернуться до первой карты, просто не работает.
        """
        if self.карта is None:
            return True
        try:
            можно, почему = self.карта.можно_ехать(0.0, 0.0, self.поворот_на_месте)
        except Exception:                       # noqa: BLE001
            log.exception("обход: карта не ответила про разворот")
            return True
        if not можно:
            log.info("обход: на месте не разворачиваюсь — %s", почему)
        return bool(можно)

    # --- мелочь -----------------------------------------------------------
    def _препятствия(self, взгляд=None):
        """Точки препятствий для планировщика: дальномер плюс память.

        БЕЗ ПОЛА, и это не мелочь — на этом обход и вставал.

        Здесь стояла СЫРАЯ сетка. Следование давно берёт `без_пола` и в его
        шапке написано, чем это кончается: при пологом креплении нижние ряды
        упираются в пол в полуметре, и ближайшим крупным пятном в любой
        комнате оказывается собственный пол. Следование от этого «не ехало
        НИКОГДА»; обход — «вперёд 0.00, поворот -0.40» по десять секунд
        подряд.

        В живом журнале это видно числом: «свободно 0.25-0.35 м, точек 45-73».
        Семьдесят три препятствия вокруг стоящего робота — это не мебель, это
        пол, посчитанный препятствием. Планировщик честно отбрасывал все дуги
        и никуда не ехал.
        """
        if взгляд is None and self.tof is not None:
            взгляд = self.tof.взгляд()
        точки = []
        if взгляд is not None:
            try:
                чистая = взгляд.сетка_без_пола
                точки = list(planner.препятствия(
                    чистая if чистая is not None else взгляд.сетка))
            except Exception:                   # noqa: BLE001
                log.exception("обход: не разобрал кадр дальномера")
        if self.карта is not None:
            try:
                точки += list(planner.из_карты(self.карта))
            except Exception:                   # noqa: BLE001
                log.exception("обход: карта не отдала препятствия")
        return точки

    def _поза(self):
        """Где робот. None — одометрии нет.

        КУРС БЕРЁМ ИСПРАВЛЕННЫЙ КОМПАСОМ, а не сырой, и это не украшение.

        Компас правит накопленный дрейф гироскопа, и постоянная карта
        квартиры строится ИМЕННО В ЭТОМ курсе. Спросить у карты «где
        неизведанное», держа в руках сырую одометрию, значит смешать две
        системы отсчёта, повёрнутые друг относительно друга ровно на
        накопленную поправку. Карта ответит курсом в своей, обход вычтет из
        него свой сырой — и довернётся мимо на всю поправку. А поправка
        растёт: в том и смысл компаса, что дрейф он копит и гасит.

        Снаружи это выглядело бы как «робот едет не туда, куда карта его
        зовёт», причём тем сильнее, чем дольше идёт обход. Разбирать такое по
        журналу почти невозможно: и карта права, и обход прав, а вместе не
        сходятся.
        """
        if self.ros is None:
            return None
        try:
            поза = self.ros.odom
        except Exception:                       # noqa: BLE001
            log.exception("обход: одометрия не ответила")
            return None
        if поза is None or self.компас is None:
            return поза
        try:
            return self.компас.поза(поза)
        except Exception:                       # noqa: BLE001
            log.debug("обход: компас не поправил позу", exc_info=True)
            return поза

    def _скорость(self, вперёд: float, поворот: float) -> bool:
        """Подать скорость, если обход не отменили. False — отменили.

        Проверка вплотную к публикации, а не только в условии цикла: тот же
        довод, что у следования, — «стоп», пришедший между началом круга и
        подачей, иначе стоил бы роботу ещё одного шага вперёд.
        """
        if self._стоп.is_set():
            return False
        # Запоминаем ПОДАННУЮ команду, а не задуманную: сторож буксующих колёс
        # судит по тому, что ушло в шасси. Ветка «выбираюсь» подаёт скорость
        # мимо основного круга, и без этой записи сторож судил бы обход по
        # команде, которая давно не действует.
        self._велели = (float(вперёд), float(поворот))
        self.ros.publish_twist(вперёд, 0.0, поворот)
        return True

    def _встать(self) -> None:
        try:
            self.ros.publish_twist()
        except Exception:                       # noqa: BLE001
            log.exception("обход: не смог остановить колёса")
