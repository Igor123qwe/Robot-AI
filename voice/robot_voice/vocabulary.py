# Всё, что робот может УВИДЕТЬ и назвать. Улица сюда входит.
ВСЁ: tuple[Вещь, ...] = МЕБЕЛЬ + ПОДВИЖНОЕ + ОПАСНОЕ + УЛИЧНОЕ

# А это то, что мы ПРОСИМ сеть искать. Улицы здесь нет.
ИЩЕМ: tuple[Вещь, ...] = МЕБЕЛЬ + ПОДВИЖНОЕ + ОПАСНОЕ

# --- то, ради чего модуль и заведён: три таблицы, выведенные из одного места
ПО_КЛАССУ: dict[str, Вещь] = {в.класс: в for в in ВСЁ}
ПО_РУССКИ: dict[str, tuple[str, ...]] = {в.класс: в.имена for в in ВСЁ}
РОСТ: dict[str, float] = {в.класс: в.рост for в in ВСЁ if в.рост > 0}
ДВИЖЕТСЯ: tuple[str, ...] = tuple(в.класс for в in ВСЁ if в.движется)
ОПАСНЫЕ: tuple[str, ...] = tuple(в.класс for в in ВСЁ if в.опасно)


def мебель(класс: str) -> bool:
    """Стоит ли эта вещь на месте — то есть можно ли ставить её на карту."""
    вещь = ПО_КЛАССУ.get(класс)
    return bool(вещь) and вещь.рост > 0 and not вещь.движется


