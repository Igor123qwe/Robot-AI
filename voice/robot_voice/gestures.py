"""Жесты рукой: то, что робот понимает без микрофона.

Зачем это, если есть голос. Голос отказывает ровно тогда, когда нужнее всего.
Робот едет — моторы шумят, и он же сам себя глушит на время своей реплики.
Робот в другом конце комнаты — до микрофона три метра и работающий телевизор.
Человек не хочет будить остальных — кричать «стоп» в полночь нельзя.

Во всех трёх случаях поднятая ладонь работает, а слово — нет. Поэтому ладонь
здесь заведена на ОСТАНОВКУ: это второй, независимый от звука путь к тем же
тормозам. Микрофон, звуковая карта, распознавание речи, слово «стоп» в шуме —
целая цепочка, каждое звено которой уже отказывало. У жеста из этой цепочки
нет ни одного звена.

Откуда берутся жесты. Считает их BPU, готовыми пакетами TogetheROS:

    mono2d_body_detection  →  hand_lmk_detection  →  hand_gesture_detection

Первый уже работает у нас постоянно (он же даёт пеленг человека и скелет для
сторожа падений), второй ищет двадцать одну точку кисти, третий по этим
точкам называет жест. Здесь мы не считаем ничего — только читаем готовое
число из топика и решаем, что с ним делать.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ СТОРОЖА ПАДЕНИЙ. Там мы отказались ставить чужой пакет
и переписали сорок строк тригонометрии сами. Здесь так нельзя: распознавание
кисти и жеста — это две обученные сети, а не арифметика. Их надо ставить.

ПОЧЕМУ РЕШАЕМ НЕ ПО ОДНОМУ КАДРУ. Сеть ошибается, и цена ошибки у разных
жестов разная. Ложный «стоп» стоит остановки, которой не просили, — неприятно
и безопасно. Ложное «иди за мной» — это робот, поехавший на человека, который
его не звал. Поэтому подтверждений требуется разное число: у остановки одно
(быстрее и безопаснее), у остальных несколько.
"""

from __future__ import annotations

import logging
import time

log = logging.getLogger(__name__)

ТОПИК = "/hobot_hand_gesture_detection"
ТИП = "ai_msgs/msg/PerceptionTargets"

# Номера жестов. Взяты из gesture_data.h пакета hand_gesture_detection —
# нумерация там неплотная (есть пропуски), так что перечислять по порядку
# нельзя, только по именам.
ФОН = 0
ПАЛЕЦ_ВВЕРХ = 2                 # большой палец вверх
ВИКТОРИЯ = 3                    # «V»
ТИШЕ = 4                        # палец к губам, «тсс»
ЛАДОНЬ = 5                      # раскрытая ладонь
ОКЕЙ = 11                       # кольцо из большого и указательного
ПАЛЕЦ_ВЛЕВО = 12
ПАЛЕЦ_ВПРАВО = 13
КЛАСС = 14                      # «666»

ИМЕНА = {
    ПАЛЕЦ_ВВЕРХ: "палец вверх",
    ВИКТОРИЯ: "victory",
    ТИШЕ: "тише",
    ЛАДОНЬ: "ладонь",
    ОКЕЙ: "окей",
    ПАЛЕЦ_ВЛЕВО: "палец влево",
    ПАЛЕЦ_ВПРАВО: "палец вправо",
    КЛАСС: "класс",
}

# Сколько кадров подряд нужно, чтобы поверить жесту.
#
# Ладони хватает двух. Это осознанный перекос в сторону чувствительности:
# лишняя остановка — это полсекунды неудобства, а неостановка — это уже
# столкновение. Сеть при этом не выдаёт «ладонь» из шума: чтобы её увидеть,
# в кадре должна быть найдена кисть и по ней двадцать одна точка.
#
# Остальным нужно четыре. Ложное «иди за мной» отправляет робота на человека,
# который его не звал, и стоит заметно дороже.
ПОДТВЕРЖДЕНИЙ = {ЛАДОНЬ: 2}
ПОДТВЕРЖДЕНИЙ_ОБЫЧНО = 4

# За сколько должны набраться эти подтверждения. Полторы секунды: жест держат
# секунду-две, а вот два случайных срабатывания за минуту складываться в один
# жест не должны.
НАБИРАЕМ_ЗА = 1.5

# Сколько молчим после того, как жест отработал. Две секунды: человек не
# успевает опустить руку за один кадр, и без этой паузы одна поднятая ладонь
# сработала бы десять раз подряд.
МОЛЧИМ = 2.0

# Через сколько забываем руку, которой не видим.
ЗАБЫВАЕМ = 5.0


def жесты_в_кадре(сообщение):
    """Пары «номер цели — номер жеста» из сообщения детектора.

    Жест лежит в атрибуте цели: `attributes: [{type: "gesture", value: N}]`,
    и относится он к цели, у которой среди рамок есть рука. Разбор терпимый по
    той же причине, что и в vision_track: версии пакетов расходятся в мелочах,
    а прибитый разбор ломается молча — со стороны это выглядит как «жесты
    просто не работают», и искать причину потом негде.
    """
    цели = сообщение.get("targets") or сообщение.get("perceptions") or []
    if not isinstance(цели, list):
        return []
    найдено = []
    for цель in цели:
        if not isinstance(цель, dict):
            continue
        свойства = цель.get("attributes") or []
        if not isinstance(свойства, list):
            continue
        номер = int(цель.get("track_id") or 0)
        for свойство in свойства:
            if not isinstance(свойство, dict):
                continue
            if str(свойство.get("type") or "") != "gesture":
                continue
            try:
                жест = int(свойство.get("value"))
            except (TypeError, ValueError):
                continue
            # Фон — это «жеста нет», а не жест. Пропускать его здесь важнее,
            # чем кажется: иначе он гасил бы набранные подтверждения ровно
            # так же, как настоящий другой жест.
            if жест == ФОН:
                continue
            найдено.append((номер, жест))
    return найдено


class _Рука:
    __slots__ = ("жест", "сколько", "начало", "виден", "сделали")

    def __init__(self) -> None:
        self.жест = 0
        self.сколько = 0
        self.начало = 0.0
        self.виден = 0.0
        self.сделали = 0.0


class Жесты:
    """Читает топик жестов и зовёт обработчик, когда жест подтверждён.

    Что делать с жестом, этот модуль не знает и знать не должен: он про
    распознавание, а не про поведение. Обработчик задаётся снаружи — так его
    можно проверить без колёс, без голоса и без платы.
    """

    def __init__(self, *, показал=None, часы=time.monotonic) -> None:
        # `показал(жест, номер)` — подтверждённый жест.
        self.показал = показал
        self._часы = часы
        self._руки: dict[int, _Рука] = {}
        self._первое = False

    def принять(self, сообщение) -> None:
        """Разобрать сообщение. Зовётся из потока связи с ROS."""
        сейчас = self._часы()
        for номер, жест in жесты_в_кадре(сообщение):
            if not self._первое:
                self._первое = True
                log.info("жесты: первый разобран — %s",
                         ИМЯ_ИЛИ_НОМЕР(жест))
            self._судить(номер, жест, сейчас)
        self._забыть_старых(сейчас)

    def _судить(self, номер: int, жест: int, сейчас: float) -> None:
        рука = self._руки.get(номер)
        if рука is None:
            рука = self._руки[номер] = _Рука()
        рука.виден = сейчас

        # Сменили жест или набирали слишком долго — начинаем заново. Второе
        # важно не меньше первого: без срока годности два случайных
        # распознавания с разницей в минуту сложились бы в один жест.
        if рука.жест != жест or сейчас - рука.начало > НАБИРАЕМ_ЗА:
            рука.жест = жест
            рука.сколько = 0
            рука.начало = сейчас
        рука.сколько += 1

        надо = ПОДТВЕРЖДЕНИЙ.get(жест, ПОДТВЕРЖДЕНИЙ_ОБЫЧНО)
        if рука.сколько < надо:
            return
        if рука.сделали and сейчас - рука.сделали < МОЛЧИМ:
            return

        рука.сделали = сейчас
        рука.сколько = 0
        рука.начало = сейчас
        log.info("жест: %s (цель %d)", ИМЯ_ИЛИ_НОМЕР(жест), номер)
        if self.показал is not None:
            try:
                self.показал(жест, номер)
            except Exception:                   # noqa: BLE001
                # Тот же поток, что и связь с шасси: уронить его нельзя.
                log.exception("жесты: обработчик упал")

    def _забыть_старых(self, сейчас: float) -> None:
        протухли = [н for н, р in self._руки.items()
                    if сейчас - р.виден > ЗАБЫВАЕМ]
        for н in протухли:
            del self._руки[н]

    def подписка(self) -> dict:
        """Что послать rosbridge, чтобы получать жесты."""
        return {"op": "subscribe", "topic": ТОПИК, "type": ТИП,
                "throttle_rate": 50}


def ИМЯ_ИЛИ_НОМЕР(жест: int) -> str:
    return ИМЕНА.get(жест, f"№{жест}")
