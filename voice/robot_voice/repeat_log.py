"""Повторяющаяся беда — одна строка в журнале, а не строка в минуту.

ЗАЧЕМ. Живой журнал одного вечера, три соседа, и каждый часами:

    погода не ответила: <urlopen error timed out>             — каждую минуту
    детектор тела: за 60 с — 900 сообщений, ни в одном не ...  — каждую минуту
    движение: поток оборвался: … Server returned 5XX           — каждые 15 с

Каждая строка по отдельности честна, а вместе они хоронят то, ради чего
журнал вообще открывают: «перебили словом», «ПК не ответил», «стоп». Беда,
о которой сказано один раз, от сотого повтора понятнее не становится.

КАК. Первый сбой — предупреждение, как и было. Повторы той же беды — в debug:
они не пропали, их видно с подробным журналом. Раз в НАПОМИНАТЬ_РАЗ_В — одна
строка «всё ещё так» с тем, сколько это длится. И первый успех после сбоев —
строка «снова в порядке»: без неё по журналу не отличить «беда кончилась» от
«о ней просто перестали говорить».
"""

from __future__ import annotations

import logging
import threading
import time

# Как часто напоминать о беде, которая всё длится. Полчаса: кто открыл журнал
# за последний час, увидит её хотя бы раз, а за ночь набежит шестнадцать
# строк, а не шестьсот.
НАПОМИНАТЬ_РАЗ_В = 1800.0


class Беда:
    """Один источник повторяющегося сбоя: погода, поток камеры, детектор."""

    def __init__(self, лог: logging.Logger, *,
                 напоминать: float = НАПОМИНАТЬ_РАЗ_В,
                 часы=time.monotonic) -> None:
        self._лог = лог
        self._напоминать = напоминать
        self._часы = часы
        self._замок = threading.Lock()
        self._с: float | None = None        # с какого мига длится; None — нет беды
        self._напомнили = 0.0
        self._раз = 0

    @property
    def есть(self) -> bool:
        """Длится ли беда: был сбой, а успеха после него ещё не было."""
        return self._с is not None

    def случилась(self, текст: str) -> None:
        """Ещё один сбой. Строка в журнал — только первая и напоминания.

        Текст пишется в журнал как есть, без «%s»: он уже собран, а проверки
        и люди ищут в журнале его самого, а не шаблон.
        """
        сейчас = self._часы()
        with self._замок:
            if self._с is None:
                self._с, self._напомнили, self._раз = сейчас, сейчас, 1
                как = "впервые"
            else:
                self._раз += 1
                как = "тихо"
                if сейчас - self._напомнили >= self._напоминать:
                    self._напомнили = сейчас
                    как = "напомнить"
            раз, минут = self._раз, (сейчас - self._с) / 60.0
        if как == "впервые":
            self._лог.warning(текст)
        elif как == "напомнить":
            self._лог.warning(f"{текст} — всё ещё так: {раз} раз подряд "
                              f"за {минут:.0f} мин")
        else:
            self._лог.debug(текст)

    def прошла(self, текст: str) -> None:
        """Успех. Если перед ним были сбои — сказать, что беда кончилась."""
        сейчас = self._часы()
        with self._замок:
            if self._с is None:
                return
            раз, минут = self._раз, (сейчас - self._с) / 60.0
            self._с, self._раз = None, 0
        self._лог.info(f"{текст} (до того сбоев подряд: {раз}, "
                       f"за {минут:.0f} мин)")
