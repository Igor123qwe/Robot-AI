"""Дневник робота: что он делал, чем это кончилось и где он тогда был.

ЗАЧЕМ. Робот уже умеет учиться на ПРОСЬБАХ: собрал новое действие из готовых,
сделал, запомнил под именем (см. skills.py). Но всё, что он проживает сам,
пропадает бесследно. Каждый вечер в одно и то же время просят одно и то же —
не замечено. На кухне следование срывается всегда, а в коридоре никогда — не
выучено. Порог наклона дальномера оказался вчетверо ниже собственного шума —
это нашлось только потому, что человек прислал журнал вручную.

Дневник — не журнал. Журнал пишется для человека и состоит из строк; его
нельзя ни сложить, ни сравнить, ни спросить «сколько раз за неделю». Дневник
пишется для СЧЁТА: одна запись — один разбираемый предмет с полями.

Без него следующие шаги невозможны в принципе:
  • ночной разбор («что повторяется, что срывается») — разбирать нечего;
  • свой опыт вместо подсказок («здесь я застреваю») — сравнивать нечего.

ЧТО ЗДЕСЬ НАРОЧНО СДЕЛАНО ПРОСТО.

Формат — JSON по строке на запись. Не база: база на этой плате означает
блокировки, схему, миграции и ещё один способ не подняться после обновления.
Строчный файл читается кусками, дописывается атомарно и переживает
выдёргивание питания посреди записи — потеряется самое большее последняя строка.

Время пишем ДВОЙНОЕ. У платы нет батарейки часов: после выключения питания
время берётся из сети, а если сети не было — остаётся каким попало (на живом
роботе разъезжалось на пять часов). Поэтому рядом с настенным временем
кладётся `от_старта` — секунды от запуска службы. Настенное может соврать,
порядок событий внутри одного запуска — никогда.

ЧТО СЮДА НЕ ПОПАДАЕТ. Ключи, пароли, содержимое запросов к модели. Записи
короткие и про действия, а не про переписку: «спросили погоду» — да, полный
текст ответа модели — нет. Это не только про тайну, но и про объём: дневник
живёт на той же карточке, что и система.
"""

from __future__ import annotations

import json
import logging
import os
import threading
import time

log = logging.getLogger(__name__)

# Сколько дней помним. Две недели: за это время видно и будни, и выходные, а
# «то же самое, что месяц назад» для дома уже неправда — мебель переставили.
ДНЕЙ = 14

# Сколько строк держим в файле максимум. Ограничение по строкам, а не по
# байтам: строка — это один разбираемый предмет, и «двадцать тысяч событий»
# понятнее, чем «двадцать мегабайт». Двадцать тысяч — это примерно неделя
# живой работы, места занимает единицы мегабайт.
СТРОК_ПРЕДЕЛ = 20000

# Как часто проверяем, не пора ли подрезать. Каждая запись — слишком часто:
# подрезка читает файл целиком.
ПОДРЕЗАТЬ_РАЗ_В = 600.0

# Насколько длинной может быть строка внутри записи. Реплики бывают длинные, а
# дневник нужен для счёта, а не для стенограммы.
ДЛИНА = 200


def сборка() -> str:
    """Какой код сейчас работает — короткий номер коммита. Пусто — не знаем.

    Нужно ночному разбору. Без версии «срывы участились» — это наблюдение ни
    о чём: непонятно, изменилась квартира или изменился робот. С версией это
    уже вопрос с ответом.

    Читаем .git руками, а не через `git`: запускать процесс на каждом старте
    ради одной строки незачем, да и git в окружении службы может не быть.
    """
    корень = os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))))
    голова = os.path.join(корень, ".git", "HEAD")
    try:
        with open(голова, encoding="utf-8") as f:
            строка = f.read().strip()
        if строка.startswith("ref:"):
            ссылка = строка.split(" ", 1)[1].strip()
            with open(os.path.join(корень, ".git", ссылка), encoding="utf-8") as f:
                строка = f.read().strip()
        return строка[:8]
    except OSError:
        return ""


def _оборвана(файл) -> bool:
    """Кончается ли файл незакрытой строкой. Пусто и нет файла — нет."""
    try:
        размер = os.path.getsize(файл)
    except OSError:
        return False
    if not размер:
        return False
    try:
        with open(файл, "rb") as f:
            f.seek(-1, os.SEEK_END)
            return f.read(1) != b"\n"
    except OSError:
        return False


def _укоротить(значение):
    if isinstance(значение, str) and len(значение) > ДЛИНА:
        return значение[:ДЛИНА] + "…"
    return значение


class Дневник:
    """Пишет события и умеет их потом складывать.

    Заводится один на робота и передаётся тем, кому есть что записать. Пишет
    в файл сразу: терять последние события при выключении питания — значит
    терять ровно то, что интереснее всего, потому что выключают обычно после
    того, как что-то пошло не так.
    """

    def __init__(self, файл, *, часы=time.time, предел=СТРОК_ПРЕДЕЛ) -> None:
        self.файл = файл
        self._часы = часы
        self._предел = предел
        self._замок = threading.Lock()
        self._старт = time.monotonic()
        self._подрезали = 0.0
        try:
            os.makedirs(os.path.dirname(str(файл)) or ".", exist_ok=True)
        except OSError:
            log.warning("дневник: не смог создать каталог для %s", файл)

    # --- запись ----------------------------------------------------------
    def записать(self, что: str, **подробности) -> None:
        """Одно событие. Никогда не роняет того, кто записывает.

        Дневник — вспомогательная вещь. Робот, упавший из-за того, что не смог
        записать про себя строчку, — это хуже, чем робот без дневника.
        """
        запись = {"что": что,
                  "когда": round(self._часы(), 1),
                  "от_старта": round(time.monotonic() - self._старт, 1)}
        for имя, значение in подробности.items():
            if значение is None:
                continue
            запись[имя] = _укоротить(значение)
        строка = json.dumps(запись, ensure_ascii=False)
        try:
            with self._замок:
                with open(self.файл, "a", encoding="utf-8") as f:
                    # Если прошлая запись оборвалась на середине — питание
                    # выдернули, — в файле остался кусок строки БЕЗ перевода
                    # строки. Дописать к нему значит склеить две записи в одну
                    # битую и потерять ОБЕ. Причём вторая — это первое, что
                    # робот записал после сбоя, то есть ровно то, ради чего
                    # дневник потом и открывают.
                    #
                    # Закрываем оборванную строку своим переводом. Она всё
                    # равно не разберётся и будет пропущена при чтении, но
                    # заразит только себя.
                    if _оборвана(self.файл):
                        f.write("\n")
                    f.write(строка + "\n")
            self._может_подрезать()
        except Exception:                       # noqa: BLE001
            log.debug("дневник: не смог записать", exc_info=True)

    def _может_подрезать(self) -> None:
        сейчас = time.monotonic()
        if сейчас - self._подрезали < ПОДРЕЗАТЬ_РАЗ_В:
            return
        self._подрезали = сейчас
        self.подрезать()

    def подрезать(self) -> None:
        """Оставить последние СТРОК_ПРЕДЕЛ строк и не старше ДНЕЙ.

        Переписываем через временный файл и переименование: если питание
        выдернут посреди подрезки, на месте останется целый старый файл, а не
        обрезанный на середине.
        """
        try:
            with self._замок:
                строки = self._прочитать()
                край = self._часы() - ДНЕЙ * 24 * 3600
                живые = [с for с in строки
                         if float(с.get("когда") or 0) >= край]
                if len(живые) > self._предел:
                    живые = живые[-self._предел:]
                if len(живые) == len(строки):
                    return
                врем = f"{self.файл}.новый"
                with open(врем, "w", encoding="utf-8") as f:
                    for с in живые:
                        f.write(json.dumps(с, ensure_ascii=False) + "\n")
                os.replace(врем, self.файл)
            log.info("дневник: подрезал до %d записей", len(живые))
        except Exception:                       # noqa: BLE001
            log.debug("дневник: не смог подрезать", exc_info=True)

    # --- чтение ----------------------------------------------------------
    def _прочитать(self):
        try:
            with open(self.файл, encoding="utf-8") as f:
                строки = f.readlines()
        except OSError:
            return []
        готовое = []
        for строка in строки:
            строка = строка.strip()
            if not строка:
                continue
            try:
                запись = json.loads(строка)
            except ValueError:
                # Оборванная строка после выключения питания. Молча
                # пропускаем: одна битая запись не повод потерять остальные.
                continue
            if isinstance(запись, dict):
                готовое.append(запись)
        return готовое

    def всё(self):
        with self._замок:
            return self._прочитать()

    def за(self, часов: float = 24.0):
        """Записи за последние `часов`."""
        край = self._часы() - часов * 3600
        return [з for з in self.всё() if float(з.get("когда") or 0) >= край]

    def свод(self, часов: float = 24.0):
        """Сколько чего случилось. Это и есть то, ради чего дневник.

        Отдельный метод, а не «человек сам посчитает»: свод нужен и ночному
        разбору, и инструменту «как прошёл день», и оба должны считать
        одинаково. Две реализации одного счёта однажды разойдутся, и объяснить
        расхождение будет нечем.
        """
        записи = self.за(часов)
        по_видам: dict[str, int] = {}
        по_итогам: dict[str, int] = {}
        срывы: list[dict] = []
        for з in записи:
            вид = str(з.get("что") or "?")
            по_видам[вид] = по_видам.get(вид, 0) + 1
            итог = з.get("итог")
            if итог:
                по_итогам[str(итог)] = по_итогам.get(str(итог), 0) + 1
            if з.get("сорвалось") or итог in ("отказ", "срыв"):
                срывы.append(з)
        return {"всего": len(записи), "часов": часов,
                "по_видам": по_видам, "по_итогам": по_итогам,
                "срывов": len(срывы), "срывы": срывы[-10:]}

    def повторы(self, часов: float = 24 * 7, хватит: int = 3):
        """Что человек просит снова и снова — с точностью до часа суток.

        Ради этого дневник и заводился. «Ты четвёртый вечер подряд в семь
        просишь включить радио» — это то, чего робот не может знать без
        памяти о себе, и то, из чего вырастает предложение вместо вопроса.

        Час суток берётся из настенного времени, и оно может врать: у платы
        нет батарейки часов. Поэтому записи с явно нелепым временем
        (до 2020 года) в счёт не идут — лучше не предложить ничего, чем
        предложить по выдуманному расписанию.
        """
        ЗДРАВОЕ_ВРЕМЯ = 1577836800.0            # 1 января 2020
        счёт: dict[tuple[str, int], int] = {}
        for з in self.за(часов):
            когда = float(з.get("когда") or 0)
            if когда < ЗДРАВОЕ_ВРЕМЯ:
                continue
            повод = з.get("команда") or з.get("инструмент")
            if not повод:
                continue
            час = time.localtime(когда).tm_hour
            ключ = (str(повод).lower().strip(), час)
            счёт[ключ] = счёт.get(ключ, 0) + 1
        найдено = [{"повод": повод, "час": час, "раз": сколько}
                   for (повод, час), сколько in счёт.items()
                   if сколько >= хватит]
        найдено.sort(key=lambda з: з["раз"], reverse=True)
        return найдено
