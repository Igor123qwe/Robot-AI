"""Железо робота числами: что где стоит и что чем видит.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Поле зрения дальномера — шестьдесят градусов — до сих
пор было записано в ПЯТИ файлах: `tof`, `fusion` (дважды), `mapping`, `plane`,
`follow`. Поле камеры и ширина кадра — в трёх: `things`, `vision_track`,
`fusion`. Это не стиль, это ловушка: переставишь камеру — и надо вспомнить про
три файла, а вспомнишь про два. Разойдутся они молча, потому что каждое число
по отдельности выглядит правильным, и увидеть расхождение можно только
положив файлы рядом.

Здесь лежит ФИЗИКА, а не политика. Физика — это то, что меряется рулеткой и
меняется вместе с железом: высота датчика, наклон кронштейна, угол обзора.
Политика — это то, на сколько робот сбавляет у стены и как близко подходит к
собаке; она живёт в своих модулях и к железу отношения не имеет.

ЧИСЛА, КОТОРЫЕ НАДО ПОМЕРИТЬ. Часть взята из паспорта, часть — по средней
сборке. Помеченные «ПОМЕРИТЬ» на этом роботе не проверялись ни разу, и ошибка
в них разъезжается по всему, что из них считается. Мерить рулеткой и уровнем,
робот при этом стоит на полу.
"""

from __future__ import annotations

import math

# --- дальномер VL53L7CX ------------------------------------------------------
# Матрица 8×8. Поле по горизонтали и вертикали одинаковое — так устроен сам
# датчик, это не совпадение и не подгонка.
ТОФ_ПОЛЕ_ГОР = 60.0
ТОФ_ПОЛЕ_ВЕРТ = 60.0

# Высота объектива дальномера над полом. Держится от прогона к прогону —
# замерено на роботе.
ТОФ_ВЫСОТА = 0.15
# Наклон вниз, градусы. ПОМЕРИТЬ РУЛЕТКОЙ — и это единственное число здесь,
# про которое точно известно, что оно спорит с роботом.
#
# Здесь стояло «выходит 12° каждый раз, когда норма пола ложится, то есть не
# задано, а измерено самим роботом». Робот действительно меряет свой кронштейн
# и кладёт результат на диск (tof.Пол.крепление) — и намеряет он ОКОЛО МИНУС
# ПЯТИ, то есть задран вверх. Медиана двенадцати живых подгонок дала -5.5°, на
# диске с прошлого запуска лежало -4°. Разница с записанным здесь —
# семнадцать градусов.
#
# Кто прав, решает рулетка, а не спор двух модулей. Подставлять сюда медиану
# нельзя: подгонка садится то на пол, то на стену, и медиана тоже бывает
# сбита. Поэтому здесь остаётся чертёжное число, а робот при каждом запуске
# говорит в журнал, что привинчено не оно (tof._сверить_с_чертежом).
#
# ПОКА НЕ ПОМЕРЕНО — ЭТО НЕ СЛУЧАЙНОЕ ЧИСЛО, А ОСТОРОЖНОЕ. Из него считаются
# двое, и обоим завышенный наклон вредит меньше заниженного:
#   • ТОФ_ВЕРХНИЙ_ЛУЧ выходит НИЖЕ настоящего (18° вместо 35°), и робот
#     считает, что собаку на кровати не видит, — теряет случай, а не выдумывает;
#   • ряды_видящие_стену отдаёт набор КОРОЧЕ честного — теряет годный ряд,
#     а не берёт ряд, смотрящий в пол.
ТОФ_НАКЛОН = 12.0

# Куда смотрит самый верхний луч, в градусах над горизонтом. Из этого числа
# растёт весь расчёт «видит ли дальномер собаку на кровати»: половина поля
# вверх минус наклон вниз.
ТОФ_ВЕРХНИЙ_ЛУЧ = ТОФ_ПОЛЕ_ВЕРТ / 2.0 - ТОФ_НАКЛОН

# Ближе этого замерам дальномера не верим вовсе: у VL53L7CX на упоре есть
# зона паразитной засветки, где он выдаёт единицы сантиметров на пустом
# месте. Это ФИЗИКА датчика, а не осторожность — осторожность у каждого
# потребителя своя и называется по-своему.
ЗАСВЕТКА_БЛИЖЕ = 0.05

# Высота потолка. ПОМЕРИТЬ: взята типовая панельная. Нужна ровно для одного
# вопроса — не упрётся ли верхний луч в потолок раньше, чем в стену. При
# нынешнем наклоне не упирается с большим запасом, и число это выбрано
# заведомо низким: ошибка в нём может только СУЗИТЬ выбор рядов, а не
# разрешить лишнее.
ПОТОЛОК = 2.4

# --- тележка WD550 -----------------------------------------------------------
# Полуширина и полудлина платформы. ПОМЕРИТЬ РУЛЕТКОЙ: числа по чертежу.
#
# Робот проверяется ПРЯМОУГОЛЬНИКОМ, а не кругом, и это принципиально: круг
# описанной окружности не пролезает в щель, в которую тележка проходит боком
# спокойно.
ПОЛУШИРИНА = 0.20
ПОЛУДЛИНА = 0.25

# Радиус круга, который корпус заметает при вращении НА МЕСТЕ. Здесь круг
# уместен: углы платформы описывают именно окружность, и её радиус — половина
# диагонали. ВЫЧИСЛЯЕМ, А НЕ ПИШЕМ ЧИСЛОМ, и вот почему.
#
# Раньше это число стояло в mapping отдельно и равнялось 0.30 — при том, что
# его собственный комментарий обещал «половина диагонали ПЛЮС ЗАПАС» и
# предупреждал: «ошибиться здесь можно только в одну сторону: занизишь — робот
# при развороте цепляет углом то, чего по расчёту не касается, и цепляет он
# обычно ногу». А половина диагонали при этих габаритах — 0.320. То есть
# число, заявленное как взятое с запасом вверх, было занижено на два
# сантиметра относительно габаритов, лежавших в соседнем модуле.
#
# Заметить это можно было, только положив planner и mapping рядом. Поэтому
# теперь не число, а формула: занизиться относительно собственных габаритов
# она уже не может.
#
# Запас здесь НЕ добавляем: его добавляют в месте применения
# (mapping.ЗАПАС_ПОВОРОТА, ЗАПАС_ВСЛЕПУЮ). Заложить второй раз внутрь значило
# бы посчитать его дважды.
РАДИУС_КОРПУСА = math.hypot(ПОЛУШИРИНА, ПОЛУДЛИНА)

# --- батарея -----------------------------------------------------------------
# Ниже этого напряжения робот не едет вообще: сборка 3S li-ion на 10.2 В уже
# на грани.
#
# ЗДЕСЬ, А НЕ У КАЖДОГО СВОЁ. Это число стояло дважды: tools.CUTOFF_VOLT и
# follow.БАТАРЕЯ_МИНИМУМ. Причём вторая копия честно писала в комментарии «то
# же число, что у обычной поездки» — то есть про совпадение знали и всё равно
# набрали его руками. Так и разъезжаются: поставят другую банку, поправят
# одно место, и робот перестанет ехать по команде на 10.5, продолжая идти за
# человеком до 10.2.
#
# Батарея — железо, и меняется она вместе с железом, поэтому место ей тут.
БАТАРЕЯ_ПУСТА = 10.2

# --- камера ------------------------------------------------------------------
# Поле по горизонтали и ширина кадра. В PerceptionTargets размеров кадра нет
# вовсе, взять их неоткуда — поэтому они здесь.
КАМЕРА_ПОЛЕ_ГОР = 130.0
КАМЕРА_ШИРИНА = 640.0
# Поле по вертикали. ПОМЕРИТЬ: взято по паспорту модуля.
КАМЕРА_ПОЛЕ_ВЕРТ = 65.0
# Высота объектива над полом. ПОМЕРИТЬ: взята по средней сборке. Из неё
# считается, где в кадре проходит линия пола, а из той — признак «собака стоит
# не на полу». Ошибка здесь смещает признак целиком.
КАМЕРА_ВЫСОТА = 0.25


def луч_до(высота: float, расстояние: float) -> float:
    """Под каким углом над горизонтом виден предмет. В градусах.

    Считает от дальномера: `высота` — над полом, `расстояние` — по полу.
    Отрицательный ответ значит «ниже горизонта», и это нормально: пол робот
    видит именно так.
    """
    if расстояние <= 0:
        return 0.0
    return math.degrees(math.atan2(высота - ТОФ_ВЫСОТА, расстояние))


def угол_ряда(ряд: int) -> float:
    """Куда смотрит середина ряда сетки, в градусах над горизонтом.

    Ряд 0 — верхний. Отсчёт тот же, что у зон по горизонтали в mapping:
    середина ряда, а не его край.
    """
    шаг = ТОФ_ПОЛЕ_ВЕРТ / 8.0
    return ТОФ_ПОЛЕ_ВЕРТ / 2.0 - (ряд + 0.5) * шаг - ТОФ_НАКЛОН


def ряды_видящие_стену(докуда: float) -> tuple[int, ...]:
    """Ряды, чей луч дойдёт до стены на `докуда` метрах, не встретив пол.

    ЗАЧЕМ. Компас меряет угол стены, а `лучи` берёт по колонке МИНИМУМ из
    рядов. Значит один ряд, смотрящий в пол, побеждает в колонке всю стену:
    вместо вертикальной плоскости компас получает горизонтальную, и та в
    поперечном срезе даёт не прямую, а дугу — то есть «не плоскость».

    Ряды под это выбирались руками: (2, 3, 4, 5), с доводом «нижние смотрят
    в пол». Довод верный, а граница поставлена не там. При нынешнем железе
    (0.15 м над полом, наклон 12°) пол попадает в окно стены у рядов 3, 4 и
    5 — на 1.03, 0.53 и 0.35 метра. То есть из четырёх рядов компаса три
    смотрели в пол, и работал он фактически по одному ряду из восьми. А два
    ряда, которые смотрят ВЫШЕ горизонта и пола не видят никогда (0 и 1),
    в набор не попали вовсе.

    Померено на модели ровной комнаты с шумом три процента от дальности:
    по прежним рядам компас принимал 25 % замеров, по выведенным — 49 %.

    Поэтому не список, а вывод из геометрии: переставят кронштейн — набор
    пересчитается сам.

    ОШИБАТЬСЯ В НАКЛОНЕ МОЖНО ТОЛЬКО ВВЕРХ. Робот меряет свой наклон сам, и
    в живом журнале выходит от трёх до семи градусов, а здесь записано
    двенадцать. Это не описка и трогать её нельзя без рулетки: завышенный
    наклон опускает расчётные лучи ниже настоящих, и набор выходит КОРОЧЕ
    честного — теряем годный ряд, не более. Заниженный опустит настоящие
    лучи ниже расчётных, и в набор попадёт ряд, смотрящий в пол, — то есть
    ровно та беда, от которой всё это писано.
    """
    годные = []
    for ряд in range(8):
        над = угол_ряда(ряд)
        if над < 0:
            # Смотрит вниз: где встретит пол?
            до_пола = ТОФ_ВЫСОТА / math.tan(math.radians(-над))
            if до_пола < докуда:
                continue
        elif над > 0:
            # Смотрит вверх: где встретит потолок? При нынешнем железе — за
            # девять метров, но наклон меняется вместе с кронштейном.
            до_потолка = (ПОТОЛОК - ТОФ_ВЫСОТА) / math.tan(math.radians(над))
            if до_потолка < докуда:
                continue
        годные.append(ряд)
    # ПУСТО НЕ ОТДАЁМ НИКОГДА. Пустой набор — это не «компас осторожничает»,
    # это компас, ослепший МОЛЧА: `лучи` по пустым рядам объявит все восемь
    # колонок промолчавшими, точек не наберётся ни одной, и «стен пока не
    # видел» будет стоять в журнале вечно. А курс без компаса уплывает на
    # градус в минуту, и через двадцать минут обхода прямой коридор на карте
    # становится веером.
    #
    # Случается это не в теории: сам робот советует в журнале «наклони
    # датчик вниз на 15-20 градусов». Посчитано по этой же формуле —
    # 20° дают два ряда, 25° один, а с 31° набор пуст. Отвёртка в руках
    # человека, который читает совет робота, доходит туда легко.
    #
    # Поэтому отдаём самый пологий ряд — тот, что дотягивается дальше
    # других. Компас на одном ряду работает плохо; компас на нуле рядов не
    # работает вовсе и об этом не говорит. Сказать — забота compass, у него
    # есть строка в журнал.
    if not годные:
        return (max(range(8), key=угол_ряда),)
    return tuple(годные)


def дальномер_видит(высота: float, расстояние: float) -> bool:
    """Попадёт ли предмет такой высоты на таком расстоянии в поле зрения.

    Ровно то, что развалило первую редакцию «Спутника»: собака на кровати
    0.60 м в метре от робота требует луча 28.8°, а верхний идёт 18°. Не
    видно — и никакой порог по высоте пятна этого не исправит.
    """
    return луч_до(высота, расстояние) <= ТОФ_ВЕРХНИЙ_ЛУЧ
