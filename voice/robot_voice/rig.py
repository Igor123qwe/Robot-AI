"""Железо робота числами: что где стоит и что чем видит.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Поле зрения дальномера — шестьдесят градусов — до сих
пор было записано в ПЯТИ файлах: `tof`, `fusion` (дважды), `mapping`, `plane`,
`follow`. Поле камеры и ширина кадра — в трёх: `things`, `vision_track`,
`fusion`. Это не стиль, это ловушка: переставишь камеру — и надо вспомнить про
три файла, а вспомнишь про два. Разойдутся они молча, потому что каждое число
по отдельности выглядит правильным, и увидеть расхождение можно только
положив файлы рядом.

Здесь лежит ФИЗИКА, а не политика. Физика — это то, что меряется рулеткой и
меняется вместе с железом: высота датчика, наклон кронштейна, угол обзора.
Политика — это то, на сколько робот сбавляет у стены и как близко подходит к
собаке; она живёт в своих модулях и к железу отношения не имеет.

ЧИСЛА, КОТОРЫЕ НАДО ПОМЕРИТЬ. Часть взята из паспорта, часть — по средней
сборке. Помеченные «ПОМЕРИТЬ» на этом роботе не проверялись ни разу, и ошибка
в них разъезжается по всему, что из них считается. Мерить рулеткой и уровнем,
робот при этом стоит на полу.
"""

from __future__ import annotations

import math

# --- дальномер VL53L7CX ------------------------------------------------------
# Матрица 8×8. Поле по горизонтали и вертикали одинаковое — так устроен сам
# датчик, это не совпадение и не подгонка.
ТОФ_ПОЛЕ_ГОР = 60.0
ТОФ_ПОЛЕ_ВЕРТ = 60.0
ТОФ_СЕТКА = 8

# Высота объектива дальномера над полом. Держится от прогона к прогону —
# замерено на роботе.
ТОФ_ВЫСОТА = 0.15
# Наклон вниз. Выходит 12° каждый раз, когда норма пола ложится, — то есть
# это не задано, а измерено самим роботом.
ТОФ_НАКЛОН = 12.0

# Куда смотрит самый верхний луч, в градусах над горизонтом. Из этого числа
# растёт весь расчёт «видит ли дальномер собаку на кровати»: половина поля
# вверх минус наклон вниз.
ТОФ_ВЕРХНИЙ_ЛУЧ = ТОФ_ПОЛЕ_ВЕРТ / 2.0 - ТОФ_НАКЛОН

# Ближе этого замерам дальномера не верим вовсе: у VL53L7CX на упоре есть
# зона паразитной засветки, где он выдаёт единицы сантиметров на пустом
# месте. Это ФИЗИКА датчика, а не осторожность — осторожность у каждого
# потребителя своя и называется по-своему.
ЗАСВЕТКА_БЛИЖЕ = 0.05

# --- камера ------------------------------------------------------------------
# Поле по горизонтали и ширина кадра. В PerceptionTargets размеров кадра нет
# вовсе, взять их неоткуда — поэтому они здесь.
КАМЕРА_ПОЛЕ_ГОР = 130.0
КАМЕРА_ШИРИНА = 640.0
# Поле по вертикали. ПОМЕРИТЬ: взято по паспорту модуля.
КАМЕРА_ПОЛЕ_ВЕРТ = 65.0
# Высота объектива над полом. ПОМЕРИТЬ: взята по средней сборке. Из неё
# считается, где в кадре проходит линия пола, а из той — признак «собака стоит
# не на полу». Ошибка здесь смещает признак целиком.
КАМЕРА_ВЫСОТА = 0.25


def луч_до(высота: float, расстояние: float) -> float:
    """Под каким углом над горизонтом виден предмет. В градусах.

    Считает от дальномера: `высота` — над полом, `расстояние` — по полу.
    Отрицательный ответ значит «ниже горизонта», и это нормально: пол робот
    видит именно так.
    """
    if расстояние <= 0:
        return 0.0
    return math.degrees(math.atan2(высота - ТОФ_ВЫСОТА, расстояние))


def дальномер_видит(высота: float, расстояние: float) -> bool:
    """Попадёт ли предмет такой высоты на таком расстоянии в поле зрения.

    Ровно то, что развалило первую редакцию «Спутника»: собака на кровати
    0.60 м в метре от робота требует луча 28.8°, а верхний идёт 18°. Не
    видно — и никакой порог по высоте пятна этого не исправит.
    """
    return луч_до(высота, расстояние) <= ТОФ_ВЕРХНИЙ_ЛУЧ
