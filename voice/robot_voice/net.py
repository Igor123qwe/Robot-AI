"""Почему не отвечает ПК — одной строкой, понятной человеку.

Все три звена, которыми робот опирается на домашний ПК — распознавание, синтез
и мозг, — отваливаются одинаково, и каждое пишет в журнал то, что отдала
библиотека. А отдаёт она вот что:

    HTTPConnectionPool(host='192.168.0.23', port=4000): Max retries exceeded
    with url: /stt (Caused by ConnectTimeoutError(<HTTPConnection object at
    0xffff69be4af0>, 'Connection to 192.168.0.23 timed out. (connect
    timeout=2.0)'))

Здесь есть всё, кроме ответа на единственный вопрос, который в этот момент
задают: чинить ПК, сеть или брандмауэр. Ответ в строке есть — он в номере
ошибки, и разные номера означают совершенно разные вечера:

    отказано в соединении (111) — ПК виден, но мост на нём не запущен;
    нет пути до хоста     (113) — робот и ПК оказались в разных сетях;
    истекло время               — пакеты уходят в никуда, обычно так режет
                                  брандмауэр Windows.

Различить их важно ещё и потому, что два из трёх чинятся на ПК за десять
секунд, а третий — это полчаса с маршрутами, и начинать с него незачем.

Прячут номер все по-разному: requests — в цепочке причин, urllib — в поле
`reason`, urllib3 — вообще нигде, только в тексте сообщения. Поэтому смотрим и
в причины, и в аргументы, и в текст.
"""

from __future__ import annotations

import errno
import socket

# Что случилось и куда смотреть. Формулировки без «ПК» и «облака»: этим же
# разбором пользуется мозг, а он ходит и в облако тоже, и «мост не запущен»
# про облако было бы неправдой. Кто именно замолчал, дописывает вызывающий.
ОТКАЗ = "порт закрыт — на той стороне никто не слушает"
НЕТ_ПУТИ = "нет пути — робот и та машина в разных сетях"
НЕТ_СЕТИ = "сети нет вовсе — у робота не поднят интерфейс"
НЕ_ДОЗВОН = "не дозвонился — пакеты уходят в никуда, обычно так режет брандмауэр"
НЕТ_ОТВЕТА = "соединился, но ответа не дождался — та машина занята"
ОБРЫВ = "соединение оборвалось на полуслове"
НЕТ_ИМЕНИ = "имя не разрешается — впишите в адрес числа, а не имя"

_ПО_НОМЕРУ = {
    errno.ECONNREFUSED: ОТКАЗ,
    errno.EHOSTUNREACH: НЕТ_ПУТИ,
    errno.ENETUNREACH: НЕТ_СЕТИ,
    errno.ETIMEDOUT: НЕ_ДОЗВОН,
    errno.ECONNRESET: ОБРЫВ,
    errno.EPIPE: ОБРЫВ,
}

# Классы важнее слов: «timed out» бывает и у дозвона, и у чтения, а беды это
# разные. Не дозвонились — виноваты сеть или брандмауэр. Не дождались ответа —
# машина жива и слышит, просто не справляется, и трогать сеть не нужно.
_ПО_КЛАССУ = {
    "ConnectTimeout": НЕ_ДОЗВОН,
    "ConnectTimeoutError": НЕ_ДОЗВОН,
    "ConnectError": НЕ_ДОЗВОН,
    "ReadTimeout": НЕТ_ОТВЕТА,
    "ReadTimeoutError": НЕТ_ОТВЕТА,
    "ReadError": ОБРЫВ,
    "RemoteProtocolError": ОБРЫВ,
}

# Последняя надежда: urllib3 заворачивает системную ошибку в свой класс и
# теряет номер, оставляя только текст. Английский — как его пишет сама
# библиотека, русский — как его отдаёт локализованная Windows.
_ПО_СЛОВАМ = (
    ("no route to host", НЕТ_ПУТИ),
    ("нет маршрута", НЕТ_ПУТИ),
    ("network is unreachable", НЕТ_СЕТИ),
    ("сеть недоступна", НЕТ_СЕТИ),
    ("connection refused", ОТКАЗ),
    ("отказано в подключении", ОТКАЗ),
    ("actively refused", ОТКАЗ),
    ("timed out", НЕ_ДОЗВОН),
    ("time out", НЕ_ДОЗВОН),
    ("превышено время", НЕ_ДОЗВОН),
)

# Длиннее этого в журнал не пишем: непонятную ошибку читают глазами, а
# трёхстрочная простыня от requests закрывает собой соседние строки.
ПРЕДЕЛ = 160


def _цепочка(beda: BaseException):
    """Ошибка и всё, что за ней стоит.

    Причина бывает где угодно: `__cause__` (raise from), `__context__` (упало
    внутри except), `reason` (так прячет urllib) и просто в аргументах —
    requests и urllib3 кладут вложенную ошибку туда, не связывая её с внешней
    никак: `ConnectTimeoutError(<HTTPConnection …>, 'timed out')`.
    """
    видели: set[int] = set()
    очередь = [beda]
    while очередь:
        beda = очередь.pop(0)
        if not isinstance(beda, BaseException) or id(beda) in видели:
            continue
        видели.add(id(beda))
        yield beda
        очередь.append(getattr(beda, "__cause__", None))
        очередь.append(getattr(beda, "__context__", None))
        очередь.append(getattr(beda, "reason", None))
        очередь.extend(getattr(beda, "args", ()))


def почему(beda: BaseException) -> str:
    """Короткая причина молчания — то, что и правда стоит прочесть в журнале.

    Не узнали — отдаём исходный текст, обрезанный до читаемого. Молчать в этом
    случае нельзя: неизвестная беда тем более требует, чтобы её увидели.
    """
    подряд = list(_цепочка(beda))

    # Сначала номер: он и есть ответ системы, всё остальное — пересказ.
    # Порядок здесь не вкусовщина. httpx.ConnectError означает и «не
    # дозвонился», и «порт закрыт» — по классу их не различить, а по номеру
    # внутри различить можно; спроси мы класс первым, отказ соединения
    # доложился бы как беда с сетью, и человек ушёл бы чинить маршруты вместо
    # того, чтобы открыть окно моста.
    for звено in подряд:
        if isinstance(звено, socket.gaierror):
            return НЕТ_ИМЕНИ
        причина = _ПО_НОМЕРУ.get(getattr(звено, "errno", None))
        if причина:
            return причина

    # Номера нет — смотрим класс. Так узнаётся таймаут: у него системного
    # номера не бывает вовсе, его ставит себе сама библиотека.
    for звено in подряд:
        причина = _ПО_КЛАССУ.get(type(звено).__name__)
        if причина:
            return причина

    текст = " ".join(str(з) for з in подряд).lower()
    for примета, причина in _ПО_СЛОВАМ:
        if примета in текст:
            return причина

    return коротко(beda)


def коротко(beda: BaseException) -> str:
    """Ошибка как есть, но в одну строку и без простыни."""
    текст = " ".join(str(beda).split()) or type(beda).__name__
    return текст if len(текст) <= ПРЕДЕЛ else текст[: ПРЕДЕЛ - 1] + "…"
