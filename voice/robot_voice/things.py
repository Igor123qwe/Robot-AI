"""Что робот видел и где: память вещей.

Зачем. Человек теряет вещи и спрашивает про них у того, кто был в комнате.
Робот в комнате был — и единственный, кто смотрел туда весь день. Вопрос «где
мой телефон» для домашнего робота естественнее половины того, что он умеет.

Как это считается. Распознаёт вещи DOSOD — открытословарная сеть на BPU из
пакета `hobot_dosod`. Она даёт восемьдесят классов COCO из коробки, и среди
них неожиданно много домашнего: кружка, бутылка, книга, рюкзак, ноутбук,
телефон, стул, диван, кровать, стол, телевизор, кошка, собака, цветок.
Расширить список словом «тапки» на лету нельзя: имена лежат в json, но сами
признаки вшиты в модель, и новое слово требует отдельного прогона на ПК.

Считает она НЕ ПОСТОЯННО, и это принципиально. Один кадр стоит около ста
тридцати миллисекунд BPU, то есть занимает плату почти целиком; пустить её на
живой поток — значит отобрать BPU у детектора людей, на котором держатся
следование, сторож падений и остановка по ладони. Поэтому кадр уходит в
модель только по запросу, через затвор (scripts/look_relay.py), а этот модуль
помнит, что она ответила.

ПОЧЕМУ ПАМЯТЬ, А НЕ ПРОСТО ОТВЕТ. «Кружки не вижу» — бесполезный ответ:
человек и сам видит, что её тут нет. Полезный ответ — «видел десять минут
назад, вон там», и для него нужно запомнить не только имя, но и КУДА робот
тогда смотрел: свои координаты по одометрии и угол до вещи в кадре. Из этих
двух чисел получается место в той же системе координат, где робот ездит, —
то есть туда можно съездить.
"""

