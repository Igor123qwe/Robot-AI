# Обратный указатель: русское слово → английский класс. Строится один раз.
ПО_АНГЛИЙСКИ = {слово: класс
                for класс, слова in ПО_РУССКИ.items()
                for слово in слова}


def назвать(класс: str) -> str:
    """Как сказать про этот класс по-русски. Не знаем — возвращаем как есть."""
    слова = ПО_РУССКИ.get(класс)
    return слова[0] if слова else класс


def распознать(слово: str) -> str:
    """Русское слово → класс сети. Пусто — такого мы не ищем.

    Ищем и по русскому словарю, и по английскому имени класса: человек может
    сказать «ноутбук», а может и «laptop», и отказывать во втором случае —
    это отказ на ровном месте.
    """
    слово = (слово or "").strip().lower()
    if not слово:
        return ""
    if слово in ПО_АНГЛИЙСКИ:
        return ПО_АНГЛИЙСКИ[слово]
    if слово in ПО_РУССКИ:
        return слово
    # Человек говорит «мою кружку», «кружку», «кружка» — падежи и лишние
    # слова. Совпадение по началу слова снимает большую часть этого без
    # морфологии: «кружк» есть и в «кружка», и в «кружку», и в «кружке».
    for имя, класс in ПО_АНГЛИЙСКИ.items():
        корень = имя[:max(4, len(имя) - 2)]
        if слово.startswith(корень) or имя.startswith(слово[:max(4, len(слово) - 2)]):
            return класс
    return ""


class Встреча:
    """Одна вещь: когда её видели, откуда и под каким углом."""

    __slots__ = ("класс", "когда", "откуда", "угол", "уверенность")

    def __init__(self, класс, когда, откуда, угол, уверенность) -> None:
        self.класс = класс
        self.когда = когда
        self.откуда = откуда            # (x, y, поворот) робота или None
        self.угол = угол                # радианы от взгляда робота, влево +
        self.уверенность = уверенность

    @property
    def где(self):
        """Куда примерно смотреть, в координатах робота. None — не знаем.

        Расстояния у нас нет: одна камера, и до произвольной вещи оно не
        считается никак. Поэтому отдаём НАПРАВЛЕНИЕ из точки, где робот тогда
        стоял, — этого хватает, чтобы доехать туда и посмотреть ещё раз, а
        врать про метры мы не будем.
        """
        if self.откуда is None:
            return None
        x, y, поворот = self.откуда
        куда = поворот + self.угол
        return x, y, куда


class Вещи:
    """Что робот видел и где. Помнит последнюю встречу с каждой вещью."""

    def __init__(self, *, ширина_кадра: float = ШИРИНА_КАДРА,
                 поле: float = ПОЛЕ_КАМЕРЫ, часы=time.monotonic) -> None:
        self.ширина_кадра = ширина_кадра
        self.поле = поле
        self._часы = часы
        self._встречи: dict[str, Встреча] = {}
        self._ответили = 0.0
        self._показал = False

    # --- со стороны ROS ---------------------------------------------------
    def принять(self, сообщение, откуда=None) -> None:
        """Ответ сети. `откуда` — где робот стоял, из одометрии."""
        сейчас = self._часы()
        self._ответили = сейчас
        if not self._показал:
            self._показал = True
            log.info("вещи: первый ответ разобран")
        ширина = self.ширина_кадра
        for класс, центр, счёт in _разобрать(сообщение):
            if счёт < ВЕРИМ_ОТ:
                continue
            доля = (ширина / 2.0 - центр) / max(1.0, ширина / 2.0)
            угол = доля * math.radians(self.поле) / 2.0
            self._встречи[класс] = Встреча(класс, сейчас, откуда, угол, счёт)
        self._забыть_старое(сейчас)

    def _забыть_старое(self, сейчас: float) -> None:
        старьё = [к for к, в in self._встречи.items()
                  if сейчас - в.когда > ПОМНИМ]
        for к in старьё:
            del self._встречи[к]

    # --- со стороны разговора ---------------------------------------------
    @property
    def отвечали(self) -> float:
        """Когда сеть отвечала в последний раз. Ноль — не отвечала ни разу."""
        return self._ответили

    def найти(self, слово: str):
        """Последняя встреча с этой вещью. None — не искали или не видели."""
        класс = распознать(слово)
        if not класс:
            return None
        return self._встречи.get(класс)

    def видно(self, свежее: float = 5.0):
        """Что видели за последние `свежее` секунд, от уверенного к прочим."""
        сейчас = self._часы()
        свежие = [в for в in self._встречи.values()
                  if сейчас - в.когда <= свежее]
        свежие.sort(key=lambda в: в.уверенность, reverse=True)
        return свежие

    def подписка(self) -> dict:
        return {"op": "subscribe", "topic": ТОПИК, "type": ТИП}


def _разобрать(сообщение):
    """Тройки «класс, середина рамки по горизонтали, уверенность»."""
    цели = сообщение.get("targets") or сообщение.get("perceptions") or []
    if not isinstance(цели, list):
        return []
    найдено = []
    for цель in цели:
        if not isinstance(цель, dict):
            continue
        класс = str(цель.get("type") or цель.get("class_name") or "").lower()
        if not класс:
            continue
        рамки = цель.get("rois") or []
        if not isinstance(рамки, list):
            continue
        for roi in рамки:
            if not isinstance(roi, dict):
                continue
            рамка = roi.get("rect") or roi.get("bbox") or roi
            центр = _середина(рамка)
            if центр is None:
                continue
            try:
                счёт = float(roi.get("confidence", цель.get("confidence", 1.0)))
            except (TypeError, ValueError):
                счёт = 1.0
            найдено.append((класс, центр, счёт))
            break
    return найдено


def _середина(рамка):
    """Середина рамки по горизонтали. None — рамку не разобрали.

    Три записи, как и у пеленга людей: углы, две точки, центр с размером.
    Разбирать все три дешевле, чем однажды выяснять на роботе, что обновление
    пакета поменяло одно поле и поиск вещей молча замолчал.
    """
    if not isinstance(рамка, dict):
        return None

    def число(*ключи):
        for ключ in ключи:
            if ключ in рамка:
                try:
                    return float(рамка[ключ])
                except (TypeError, ValueError):
                    return None
        return None

    лево = число("x_offset", "x1", "left", "x")
    ширина = число("width", "w")
    право = число("x2", "right")
    if лево is not None and ширина is not None:
        return лево + ширина / 2.0
    if лево is not None and право is not None:
        return (лево + право) / 2.0
    центр = число("center_x", "cx")
    return центр


def когда_сказать(прошло: float) -> str:
    """«Только что», «десять минут назад», «вчера вечером».

    Точное число секунд человеку не нужно и звучит по-роботски. Ему нужно
    понять, идти проверять сейчас или вещь давно унесли.
    """
    if прошло < 20:
        return "только что"
    if прошло < 90:
        return "с минуту назад"
    if прошло < 3600:
        return f"{int(прошло // 60)} минут назад"
    if прошло < 6 * 3600:
        return f"{int(прошло // 3600)} часа назад"
    return "давно"


def куда_сказать(угол: float) -> str:
    """«Прямо передо мной», «слева», «справа»."""
    градусы = math.degrees(угол)
    if abs(градусы) < 15:
        return "прямо передо мной"
    if abs(градусы) < 45:
        return "слева от меня" if градусы > 0 else "справа от меня"
    return "сильно слева" if градусы > 0 else "сильно справа"
