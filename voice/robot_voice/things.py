"""Что робот видел и где: память вещей.

Зачем. Человек теряет вещи и спрашивает про них у того, кто был в комнате.
Робот в комнате был — и единственный, кто смотрел туда весь день. Вопрос «где
мой телефон» для домашнего робота естественнее половины того, что он умеет.

Как это считается. Распознаёт вещи DOSOD — открытословарная сеть на BPU из
пакета `hobot_dosod`. Она даёт восемьдесят классов COCO из коробки, и среди
них неожиданно много домашнего: кружка, бутылка, книга, рюкзак, ноутбук,
телефон, стул, диван, кровать, стол, телевизор, кошка, собака, цветок.
Расширить список словом «тапки» на лету нельзя: имена лежат в json, но сами
признаки вшиты в модель, и новое слово требует отдельного прогона на ПК.

Считает она НЕ ПОСТОЯННО, и это принципиально. Один кадр стоит около ста
тридцати миллисекунд BPU, то есть занимает плату почти целиком; пустить её на
живой поток — значит отобрать BPU у детектора людей, на котором держатся
следование, сторож падений и остановка по ладони. Поэтому кадр уходит в
модель только по запросу, через затвор (scripts/look_relay.py), а этот модуль
помнит, что она ответила.

ПОЧЕМУ ПАМЯТЬ, А НЕ ПРОСТО ОТВЕТ. «Кружки не вижу» — бесполезный ответ:
человек и сам видит, что её тут нет. Полезный ответ — «видел десять минут
назад, вон там», и для него нужно запомнить не только имя, но и КУДА робот
тогда смотрел: свои координаты по одометрии и угол до вещи в кадре. Из этих
двух чисел получается место в той же системе координат, где робот ездит, —
то есть туда можно съездить.
"""

from __future__ import annotations

import logging
import math
import time

from . import landmarks, rig, vocabulary

log = logging.getLogger(__name__)

ТОПИК = "/perception/detection/dosod"
ТИП = "ai_msgs/msg/PerceptionTargets"
# Поле зрения камеры и ширина кадра — те же, что у пеленга людей, и по той же
# причине: в PerceptionTargets размеров кадра нет вовсе, взять их неоткуда.
ПОЛЕ_КАМЕРЫ = rig.КАМЕРА_ПОЛЕ_ГОР
ШИРИНА_КАДРА = rig.КАМЕРА_ШИРИНА

# Насколько уверенной должна быть сеть. У DOSOD порог по умолчанию 0.2 — для
# картинки в отладчике сойдёт, для ответа человеку мало: на этом пороге в их
# же примере «бейсбольная бита» находилась четыре раза в кадре, где её не
# было. Нам врать нельзя: человек пойдёт в комнату проверять.
ВЕРИМ_ОТ = 0.35

# Сколько живёт запомненный пеленг — тот, с которым потом пересекают новый.
# Две минуты: за это время робот успевает переехать на метр-полтора (то есть
# набрать базу), а одометрия ещё не уплыла настолько, чтобы пересечение
# потеряло смысл. Дольше держать нечестно: между привязками карта плывёт.
ПЕЛЕНГИ_ЖИВУТ = 120.0
# Сколько пеленгов на класс держим. Восемь: перебор идёт по всем при каждом
# новом взгляде, а восемь точек вокруг предмета — это уже полный обход.
ПЕЛЕНГОВ_ПОМНИМ = 8

# Сколько помним вещь. Сутки: «видел вчера вечером» — ещё осмысленный ответ,
# «видел на прошлой неделе» — уже нет, за неделю в доме переставили всё.
ПОМНИМ = 24 * 3600.0

# Сколько ждать ответа на запрос. Полторы секунды: затвор отдаёт три кадра
# подряд, модель считает каждый около ста тридцати миллисекунд, плюс дорога
# через rosbridge. Не дождались — честно говорим, что не посмотрели.
ЖДЁМ_ОТВЕТА = 1.5

# Имена. Сеть отвечает по-английски, человек спрашивает по-русски. Списком, а
# не переводчиком: классов восемьдесят, они не меняются, а переводчик на такой
# мелочи — это ещё одна сетевая зависимость там, где хватает словаря.
#
# Синонимов по несколько нарочно: человек говорит «телефон», «мобильник» и
# «трубка» об одном и том же, и робот, понимающий только первое, бесполезен.
# БЕРЁМ ИЗ ОБЩЕГО СЛОВАРЯ. Здесь лежала таблица руками, и она была одной из
# трёх, обязанных совпадать (см. шапку vocabulary). Теперь источник один:
# добавить класс — значит дописать одну строку в одном месте, а не вспомнить
# про три файла и молча забыть про третий.
ПО_РУССКИ = vocabulary.ПО_РУССКИ

# Обратный указатель: русское слово → английский класс. Строится один раз.
ПО_АНГЛИЙСКИ = {слово: класс
                for класс, слова in ПО_РУССКИ.items()
                for слово in слова}


def назвать(класс: str) -> str:
    """Как сказать про этот класс по-русски. Не знаем — возвращаем как есть."""
    слова = ПО_РУССКИ.get(класс)
    return слова[0] if слова else класс


def распознать(слово: str) -> str:
    """Русское слово → класс сети. Пусто — такого мы не ищем.

    Ищем и по русскому словарю, и по английскому имени класса: человек может
    сказать «ноутбук», а может и «laptop», и отказывать во втором случае —
    это отказ на ровном месте.
    """
    слово = (слово or "").strip().lower()
    if not слово:
        return ""
    if слово in ПО_АНГЛИЙСКИ:
        return ПО_АНГЛИЙСКИ[слово]
    if слово in ПО_РУССКИ:
        return слово

    # Падежи и лишние слова: «мою кружку», «кружке», «телефона». Морфологии у
    # нас нет и заводить её ради восьмидесяти слов незачем — хватает
    # совпадения по началу слова.
    #
    # Но совпадение надо брать САМОЕ ДЛИННОЕ, а не первое попавшееся, и это
    # не мелочь. Сначала бралось первое по словарю, и «телефона» цеплялось за
    # синоним «телек»: общее начало «теле» у них есть, а телевизор в словаре
    # стоит раньше. То есть на «ты не видел моего телефона» робот отвечал про
    # телевизор — уверенно и мимо.
    лучшее, сколько = "", 0
    for имя, класс in ПО_АНГЛИЙСКИ.items():
        общее = 0
        for а, б in zip(слово, имя):
            if а != б:
                break
            общее += 1
        # Общее начало должно покрывать почти всё СЛОВАРНОЕ слово, иначе
        # «теле» от «телека» проходило бы как совпадение с «телефоном».
        # Четыре буквы — не жёсткое дно, а «не длиннее самого слова»: в
        # словаре есть «нож» и «кот», и требование четырёх букв означало бы,
        # что «ножа» и «кота» не находятся вовсе. Короткому слову хватает его
        # целиком, и проверку это не ослабляет: «ложь» до «ложки» всё равно
        # не дотянется, потому что у «ложки» пять букв.
        if общее < min(4, len(имя)) or общее < len(имя) - 2:
            continue
        if общее > сколько:
            лучшее, сколько = класс, общее
    return лучшее


class Встреча:
    """Одна вещь: когда её видели, откуда и под каким углом."""

    __slots__ = ("класс", "когда", "откуда", "угол", "уверенность",
                 "высота_рамки", "слева", "справа", "низ")

    def __init__(self, класс, когда, откуда, угол, уверенность,
                 высота_рамки: float = 0.0,
                 слева: float = 0.0, справа: float = 0.0,
                 низ: float = 0.0) -> None:
        self.класс = класс
        self.когда = когда
        self.откуда = откуда            # (x, y, поворот) робота или None
        self.угол = угол                # радианы от взгляда робота, влево +
        self.уверенность = уверенность
        self.высота_рамки = высота_рамки
        # КРАЯ РАМКИ, В УГЛАХ, а не в пикселях. Углы потому же, почему и
        # пеленг: тот, кто читает встречу, про ширину кадра ничего не знает и
        # знать не должен. Слева больше справа — влево у нас плюс.
        #
        # Зачем края вообще. Правило «собака НА мебели» из ТЗ читается так:
        # рамка собаки перекрывает рамку кровати по горизонтали, а низ собаки
        # выше низа кровати. Первой половине нужны именно края, а не середина,
        # и до сих пор их никто не сохранял — считать было не из чего.
        self.слева = слева
        self.справа = справа
        # НИЖНИЙ КРАЙ РАМКИ — ДОЛЕЙ ВЫСОТЫ КАДРА, от верха. Вторая половина
        # правила «собака НА мебели»: низ собаки должен быть заметно ВЫШЕ низа
        # кровати, иначе она перед кроватью, а не на ней. Долей, а не
        # пикселями, по тому же доводу, что края углами: про размер кадра
        # читающий не знает.
        self.низ = низ

    @property
    def ширина(self) -> float:
        """Угловая ширина рамки, радианы. Ноль — краёв не разобрали."""
        return max(0.0, self.слева - self.справа)

    def перекрытие(self, другая) -> float:
        """Какая доля МОЕЙ ширины лежит внутри чужой рамки. 0..1.

        Считаем от своей ширины, а не от объединения (IoU): собака мельче
        кровати в разы, и честный IoU у них всегда близок к нулю. Вопрос
        стоит иначе — «целиком ли собака над кроватью», — и отвечает на него
        именно доля собственной ширины.
        """
        моя = self.ширина
        если_нет = 0.0
        if моя <= 0 or другая is None or другая.ширина <= 0:
            return если_нет
        общее = min(self.слева, другая.слева) - max(self.справа, другая.справа)
        return max(0.0, min(1.0, общее / моя))

    @property
    def где(self):
        """Куда примерно смотреть, в координатах робота. None — не знаем.

        Расстояния у нас нет: одна камера, и до произвольной вещи оно не
        считается никак. Поэтому отдаём НАПРАВЛЕНИЕ из точки, где робот тогда
        стоял, — этого хватает, чтобы доехать туда и посмотреть ещё раз, а
        врать про метры мы не будем.
        """
        if self.откуда is None:
            return None
        x, y, поворот = self.откуда
        куда = поворот + self.угол
        return x, y, куда


class Вещи:
    """Что робот видел и где. Помнит последнюю встречу с каждой вещью."""

    def __init__(self, *, ширина_кадра: float = ШИРИНА_КАДРА,
                 поле: float = ПОЛЕ_КАМЕРЫ, часы=time.monotonic) -> None:
        self.ширина_кадра = ширина_кадра
        self.поле = поле
        self._часы = часы
        self._встречи: dict[str, Встреча] = {}
        # Пеленги на каждый класс: откуда смотрели и куда. Из них потом
        # триангуляция — см. _свести_с_прошлым.
        self._пеленги: dict[str, list[tuple[float, float, float, float]]] = {}
        # Куда складывать мебель, которую стоит запомнить надолго. None —
        # некуда, и тогда вещи живут только в памяти на сутки, как раньше.
        self.пометки = None
        self._ответили = 0.0
        self._показал = False

    # --- со стороны ROS ---------------------------------------------------
    def принять(self, сообщение, откуда=None) -> None:
        """Ответ сети. `откуда` — где робот стоял, из одометрии."""
        сейчас = self._часы()
        self._ответили = сейчас
        if not self._показал:
            self._показал = True
            log.info("вещи: первый ответ разобран")
        ширина = self.ширина_кадра
        увидено: dict[str, tuple[float, float]] = {}
        def в_угол(пиксель: float) -> float:
            доля = (ширина / 2.0 - пиксель) / max(1.0, ширина / 2.0)
            return доля * math.radians(self.поле) / 2.0

        # Высота кадра — из чертежа, по той же ширине. Стояло здесь
        # `getattr(self, "высота_кадра", 0.0) or ширина * 3 / 4`, и поля
        # `высота_кадра` не заводит НИКТО: запасное значение побеждало всегда,
        # а выглядело как «возьмём настоящее, если оно есть».
        высота_кадра = rig.высота_кадра(ширина)
        for класс, центр, высота, счёт, края, низ in _разобрать(сообщение):
            if счёт < ВЕРИМ_ОТ:
                continue
            угол = в_угол(центр)
            слева, справа = ((в_угол(края[0]), в_угол(края[1]))
                             if края is not None else (0.0, 0.0))
            self._встречи[класс] = Встреча(
                класс, сейчас, откуда, угол, счёт, высота, слева, справа,
                min(1.0, max(0.0, низ / высота_кадра)) if низ else 0.0)
            место = self._где_это(класс, откуда, угол, высота)
            if место is not None:
                увидено[класс] = (место, счёт)
        # СНАЧАЛА ПРИВЯЗАТЬСЯ, ПОТОМ ПОМЕЧАТЬ, и порядок тут не мелочь.
        #
        # Робот включается носом куда попало, и вся сохранённая карта до
        # этого мига — груда чисел в чужой системе координат. Узнал два
        # знакомых предмета — понял, где стоит, и вчерашняя карта снова его.
        #
        # А если пометить раньше привязки, выйдет вот что: новый холодильник
        # ляжет в нынешних координатах рядом со старым, который лежит во
        # вчерашних, — и привязываться станет не по чему. Совмещение ищет
        # предметы, встречающиеся ПО ОДНОМУ разу с каждой стороны, а мы бы
        # сами и сделали их двойными. Проверено: холодильник раздваивался, и
        # робот больше не привязывался никогда.
        if self.пометки is not None and self.пометки.с_прошлого_раза:
            self.пометки.привязаться({к: м for к, (м, _) in увидено.items()})
        for класс, (место, счёт) in увидено.items():
            self._пометить(класс, место, счёт)
        self._забыть_старое(сейчас)

    def _где_это(self, класс, откуда, угол, высота):
        """Где предмет стоит в мировых координатах. None — не посчитать.

        ДВА СПОСОБА, И ПОРЯДОК ВАЖЕН.

        Сперва ТРИАНГУЛЯЦИЯ: если на эту же вещь смотрели раньше из другой
        точки, пересекаем два пеленга. Никаких допущений о размере предмета —
        чистая геометрия, и потому это главный способ. Так делают все, кто
        картирует одной камерой.

        Не вышло (второго взгляда ещё нет, или лучи сходятся слишком полого)
        — тогда ПО ВЫСОТЕ РАМКИ, как раньше: d = f·H/h, где H берётся из
        таблицы типичных размеров. Способ опирается на допущение «стул ростом
        90 см» и ошибается на четверть, зато работает с первого же взгляда.

        Запасной способ не выкинут именно поэтому: первую пометку он ставит
        сразу, а триангуляция потом её уточнит — середина у пометки считается
        скользящим средним, и верное число перетянет.
        """
        if откуда is None or not landmarks.мебель(класс):
            return None
        x, y, поворот = откуда
        куда = поворот + угол
        сведено = self._свести_с_прошлым(класс, x, y, куда)
        if сведено is not None:
            return сведено
        if высота <= 1.0:
            return None
        до = landmarks.расстояние_до(класс, высота, self.фокус)
        if до <= 0:
            return None
        return x + до * math.cos(куда), y + до * math.sin(куда)

    @property
    def фокус(self) -> float:
        """Фокусное в пикселях. Из поля зрения и ширины кадра, считать нечего.

        Отдаём наружу, а не считаем на месте: та же величина нужна спутнику,
        чтобы прикинуть расстояние по размеру рамки, и второй экземпляр этой
        формулы однажды разъехался бы с первым — ровно как разъехались поля
        зрения по шести файлам, пока их не свели в rig.
        """
        return (self.ширина_кадра / 2.0) / math.tan(
            math.radians(self.поле / 2.0))

    def _свести_с_прошлым(self, класс, x, y, куда):
        """Пересечь этот пеленг с прежними на ту же вещь. None — не с чем.

        Берём тот прежний взгляд, что сходится с нынешним КРУЧЕ ВСЕГО, а не
        просто последний по времени. Угол схождения — это и есть точность
        (см. landmarks.УГОЛ_СХОЖДЕНИЯ), и выбирать по свежести значило бы
        менять точность на новизну без всякой причины.

        ЧЕГО ЭТОТ СПОСОБ НЕ УМЕЕТ, и сказать это надо прямо: он не различает
        два одинаковых предмета. Четыре стула у стола дают четыре пеленга
        одного класса, и пересечь можно любой с любым — выйдут в том числе
        точки, где стула нет. Задача эта называется data association и в общем
        виде решается плохо даже там, где есть лидар. Нам её сглаживают две
        вещи: пометка принимается только после ДВУХ совпавших наблюдений
        (landmarks.ВИДЕТЬ_РАЗ), а призрачные пересечения от взгляда к взгляду
        не повторяются, потому что зависят от того, где робот стоял.
        """
        сейчас = self._часы()
        прежние = self._пеленги.setdefault(класс, [])
        прежние[:] = [п for п in прежние if сейчас - п[3] <= ПЕЛЕНГИ_ЖИВУТ]
        лучший = None
        for пx, пy, пкуда, _когда in прежние:
            точка = landmarks.свести((пx, пy, пкуда), (x, y, куда))
            if точка is None:
                continue
            схождение = abs((куда - пкуда + math.pi) % (2 * math.pi) - math.pi)
            схождение = min(схождение, math.pi - схождение)
            if лучший is None or схождение > лучший[0]:
                лучший = (схождение, точка)
        прежние.append((x, y, куда, сейчас))
        if len(прежние) > ПЕЛЕНГОВ_ПОМНИМ:
            прежние.pop(0)
        return лучший[1] if лучший else None

    def _пометить(self, класс, место, счёт) -> None:
        """Поставить точку на карте. Мебель — да, переезжающее — нет.

        Стол стоит годами, и его место — знание о квартире; бутылка
        переезжает по десять раз на дню, и «бутылка вот здесь» устареет
        раньше, чем робот договорит.
        """
        if self.пометки is None:
            return
        self.пометки.заметить(класс, место[0], место[1], счёт)

    def _забыть_старое(self, сейчас: float) -> None:
        старьё = [к for к, в in self._встречи.items()
                  if сейчас - в.когда > ПОМНИМ]
        for к in старьё:
            del self._встречи[к]

    # --- со стороны разговора ---------------------------------------------
    @property
    def отвечали(self) -> float:
        """Когда сеть отвечала в последний раз. Ноль — не отвечала ни разу."""
        return self._ответили

    def найти(self, слово: str):
        """Последняя встреча с этой вещью. None — не искали или не видели."""
        класс = распознать(слово)
        if not класс:
            return None
        return self._встречи.get(класс)

    def видно(self, свежее: float = 5.0):
        """Что видели за последние `свежее` секунд, от уверенного к прочим."""
        сейчас = self._часы()
        свежие = [в for в in self._встречи.values()
                  if сейчас - в.когда <= свежее]
        свежие.sort(key=lambda в: в.уверенность, reverse=True)
        return свежие

    def подписка(self) -> dict:
        return {"op": "subscribe", "topic": ТОПИК, "type": ТИП}


def _разобрать(сообщение):
    """Четвёрки «класс, середина по горизонтали, высота рамки, уверенность».

    Высота нужна для РАССТОЯНИЯ. Раньше её тут не было, и вещь могла быть
    отмечена только направлением — «стол где-то там». Направления хватает,
    чтобы доехать и посмотреть ещё раз, но не хватает, чтобы поставить точку
    на карте, а точка — это то, ради чего пометки и заводились.
    """
    цели = сообщение.get("targets") or сообщение.get("perceptions") or []
    if not isinstance(цели, list):
        return []
    найдено = []
    for цель in цели:
        if not isinstance(цель, dict):
            continue
        класс = str(цель.get("type") or цель.get("class_name") or "").lower()
        if not класс:
            continue
        рамки = цель.get("rois") or []
        if not isinstance(рамки, list):
            continue
        for roi in рамки:
            if not isinstance(roi, dict):
                continue
            рамка = roi.get("rect") or roi.get("bbox") or roi
            центр = _середина(рамка)
            if центр is None:
                continue
            try:
                счёт = float(roi.get("confidence", цель.get("confidence", 1.0)))
            except (TypeError, ValueError):
                счёт = 1.0
            найдено.append((класс, центр, _высота(рамка), счёт,
                            _края(рамка), _низ(рамка)))
            break
    return найдено


def _высота(рамка) -> float:
    """Высота рамки в пикселях. Ноль — не разобрали.

    Обрезанную краем кадра рамку здесь НЕ отсеиваем, в отличие от человека.
    Довод другой: человек ближе метра не влезает в кадр целиком, и это
    случается постоянно; мебель робот видит с двух-трёх метров, где она
    влезает. А если не влезла — расстояние выйдет заниженным, пометка
    поставится ближе, чем надо, и следующий взгляд с другой стороны её
    поправит: середина считается скользящим средним.
    """
    if not isinstance(рамка, dict):
        return 0.0

    def число(*ключи):
        for ключ in ключи:
            if ключ in рамка:
                try:
                    return float(рамка[ключ])
                except (TypeError, ValueError):
                    return None
        return None

    высота = число("height", "h")
    if высота is not None:
        return abs(высота)
    верх, низ = число("y_offset", "y1", "top", "y"), число("y2", "bottom")
    if верх is not None and низ is not None:
        return abs(низ - верх)
    return 0.0


def _низ(рамка) -> float:
    """Нижний край рамки в пикселях от верха кадра. Ноль — не разобрали."""
    if not isinstance(рамка, dict):
        return 0.0

    def число(*ключи):
        for ключ in ключи:
            if ключ in рамка:
                try:
                    return float(рамка[ключ])
                except (TypeError, ValueError):
                    return None
        return None

    низ = число("y2", "bottom")
    if низ is not None:
        return abs(низ)
    верх, высота = число("y_offset", "y1", "top", "y"), число("height", "h")
    if верх is not None and высота is not None:
        return верх + abs(высота)
    центр, высота = число("center_y", "cy"), число("height", "h")
    if центр is not None and высота is not None:
        return центр + abs(высота) / 2.0
    return 0.0


def _края(рамка):
    """Левый и правый край рамки в пикселях. None — не разобрали.

    Записей три, как и у середины: угол с размером, две точки, центр с
    размером. Разбирать все три дешевле, чем однажды выяснять на роботе, что
    обновление пакета поменяло одно поле и правило «на мебели» замолчало.
    """
    if not isinstance(рамка, dict):
        return None

    def число(*ключи):
        for ключ in ключи:
            if ключ in рамка:
                try:
                    return float(рамка[ключ])
                except (TypeError, ValueError):
                    return None
        return None

    лево = число("x_offset", "x1", "left", "x")
    ширина = число("width", "w")
    право = число("x2", "right")
    if лево is not None and ширина is not None:
        return (лево, лево + ширина)
    if лево is not None and право is not None:
        return (min(лево, право), max(лево, право))
    центр = число("center_x", "cx")
    if центр is not None and ширина is not None:
        return (центр - ширина / 2.0, центр + ширина / 2.0)
    return None


def _середина(рамка):
    """Середина рамки по горизонтали. None — рамку не разобрали.

    Три записи, как и у пеленга людей: углы, две точки, центр с размером.
    Разбирать все три дешевле, чем однажды выяснять на роботе, что обновление
    пакета поменяло одно поле и поиск вещей молча замолчал.
    """
    if not isinstance(рамка, dict):
        return None

    def число(*ключи):
        for ключ in ключи:
            if ключ in рамка:
                try:
                    return float(рамка[ключ])
                except (TypeError, ValueError):
                    return None
        return None

    лево = число("x_offset", "x1", "left", "x")
    ширина = число("width", "w")
    право = число("x2", "right")
    if лево is not None and ширина is not None:
        return лево + ширина / 2.0
    if лево is not None and право is not None:
        return (лево + право) / 2.0
    центр = число("center_x", "cx")
    return центр


def когда_сказать(прошло: float) -> str:
    """«Только что», «десять минут назад», «вчера вечером».

    Точное число секунд человеку не нужно и звучит по-роботски. Ему нужно
    понять, идти проверять сейчас или вещь давно унесли.
    """
    if прошло < 20:
        return "только что"
    if прошло < 90:
        return "с минуту назад"
    if прошло < 3600:
        return f"{int(прошло // 60)} минут назад"
    if прошло < 6 * 3600:
        return f"{int(прошло // 3600)} часа назад"
    return "давно"


def куда_сказать(угол: float) -> str:
    """«Прямо передо мной», «слева», «справа»."""
    градусы = math.degrees(угол)
    if abs(градусы) < 15:
        return "прямо передо мной"
    if abs(градусы) < 45:
        return "слева от меня" if градусы > 0 else "справа от меня"
    return "сильно слева" if градусы > 0 else "сильно справа"
