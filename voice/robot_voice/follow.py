"""«Иди за мной»: робот держится в шаге позади человека.

ПОЧЕМУ БЕЗ КАМЕРЫ. Следование за человеком принято делать зрением: найти в
кадре силуэт, вести его трекером, оценить дистанцию. У нас для этого нет ни
одной подходящей детали. Зрячая модель живёт в облаке и отвечает секундами —
за секунду человек уходит на метр. Своей нейросети на роботе нет: BPU не
умеет Vision Transformer, а поднимать YOLO ради пеленга — недели работы и
половина процессора.

А дальномер даёт ровно то, что нужно для следования, и сразу. Восемь колонок
на шестьдесят градусов — это семь с половиной градусов на колонку, то есть
пеленг с точностью лучше, чем нужно колёсам. Расстояние он меряет по
определению. Больше для следования ничего и не требуется: человек — это
ближайшее крупное пятно впереди.

Чего этот способ не умеет — и это надо знать заранее:
  • отличить человека от тумбочки. Он ведёт ближайшее крупное пятно, а не
    человека. Поэтому следование включается голосом и только голосом: робот
    едет за тем, кто попросил, и предполагает, что тот стоит перед ним;
  • держать цель за спиной. Поле зрения шестьдесят градусов, и человек,
    ушедший вбок, пропадает. Робот в этом случае честно останавливается и
    зовёт, а не гадает, куда тот делся;
  • разобрать двоих. Прошёл кто-то между — робот поедет за прошедшим.

Всё это лечится одним правилом: следование — короткое и по просьбе. Не
«режим жизни робота», а «дойди со мной до кухни».

БЕЗОПАСНОСТЬ. Робот едет за человеком, то есть В СТОРОНУ человека, и это
единственный случай, когда препятствие впереди — цель, а не помеха. Поэтому
здесь свои пределы, жёстче общих:

  • назад и боком не ездим НИКОГДА. Дальномер смотрит вперёд, сзади у робота
    слепая зона, а следование — это как раз тот случай, когда сзади может
    оказаться ребёнок, пришедший посмотреть;
  • ближе метра не подъезжаем и при этом не пятимся: подошли слишком близко —
    просто стоим и ждём, пока человек отойдёт;
  • скорость ниже обычной. Робот, догоняющий человека, страшнее робота,
    отстающего на шаг;
  • потеряли цель — колёса встают в тот же миг, а не «доедем по инерции».
"""

from __future__ import annotations

import logging
import math
import threading
import time

from . import mapping, planner, progress

log = logging.getLogger(__name__)

# Поле зрения дальномера по горизонтали. Отсюда цена колонки: 60/8 = 7.5°.
ПОЛЕ_ГРАДУСОВ = 60.0

# --- дистанции ---------------------------------------------------------------
# Насколько робот старается держаться. Метр — это расстояние вытянутой руки
# плюс запас: ближе человек начинает чувствовать робота за спиной, дальше
# теряется ощущение, что тот идёт с ним.
ДЕРЖАТЬ = 1.0
# Ближе этого не подъезжаем и стоим. Не пятимся: назад робот едет вслепую.
СТОЯТЬ_БЛИЖЕ = 0.75
# Дальше этого — трогаемся. Зазор между двумя порогами нужен, чтобы робот не
# дёргался на месте, когда человек стоит: без него он бы вечно то подъезжал,
# то тормозил.
ЕХАТЬ_ДАЛЬШЕ = 1.25
# Тот самый зазор, отдельным именем: желаемая дистанция теперь не постоянна
# (см. Слежка.дистанция), и оба порога обязаны ехать вместе с ней.
ЗАЗОР = ЕХАТЬ_ДАЛЬШЕ - ДЕРЖАТЬ
# Дальше этого пятно человеком не считаем. Два с половиной метра — граница, за
# которой VL53L7CX в комнате и так почти ничего не возвращает.
ТЕРЯЕМ_ДАЛЬШЕ = 2.5
# Ближе этого замерам не верим: у датчика на упоре паразитная засветка.
НЕ_ВЕРИМ_БЛИЖЕ = 0.15

# --- скорости ----------------------------------------------------------------
# ЭТО САМАЯ ВАЖНАЯ ЧАСТЬ ФАЙЛА, и раньше здесь стояло одно число.
#
# Стояло 0.22 м/с — «медленнее обычной поездки, догонять человека незачем».
# Довод звучал разумно и был неверен: человек по квартире идёт 1.0-1.4 м/с,
# то есть вшестеро быстрее. Робот отставал с первого шага, человек уходил из
# поля зрения, и следование кончалось словами «Больше не иду». Не настройка
# подвела — при такой скорости следование не могло работать в принципе.
#
# Но поднять предел одним числом тоже нельзя, и вот почему. Между появлением
# препятствия и остановкой проходит: кадр дальномера (до 100 мс), два кадра
# подряд для веры (200 мс), опрос сторожа (67 мс) и сам тормозной путь.
# Робот, едущий метр в секунду, за одно только время реакции проезжает
# треть метра — ровно тот порог, на котором сторож кричит «стоп».
#
# Поэтому скорость не константа, а ФУНКЦИЯ ОТ ТОГО, НАСКОЛЬКО ДАЛЕКО ВИДНО
# СВОБОДНО. Так устроена безопасность у всех, кто ездит рядом с людьми:
# видишь далеко — едешь быстро, видишь близко — ползёшь. Считает это
# скорость_по_виду().
#
# Потолок остаётся, и он не про физику, а про людей: робот, несущийся по
# квартире с ребёнком, пугает независимо от того, успеет ли он затормозить.
СКОРОСТЬ_ПОТОЛОК = 0.55

# Сколько робот теряет, прежде чем начнёт тормозить. Складывается из периода
# дальномера, двух кадров на подтверждение и опроса сторожа. Меряно по
# настройкам, а не угадано: 0.1 + 0.2 + 0.067, округлено вверх.
ЗАДЕРЖКА_РЕАКЦИИ = 0.4

# Замедление при торможении, м/с². Живёт в planner: тем же числом он
# прокатывает тормозной хвост пробных дуг. Два числа для одного торможения
# однажды разошлись бы, и робот планировал бы одну остановку, а совершал
# другую.
ЗАМЕДЛЕНИЕ = planner.ТОРМОЖЕНИЕ

# Сколько метров оставляем нетронутыми перед препятствием. Это не запас на
# ошибку, а место, в котором стоит человек: тормозить вплотную к ногам можно
# только на бумаге.
ЗАПАС_ДО_ПРЕПЯТСТВИЯ = 0.40

# Насколько быстро можно менять скорость, м/с² и рад/с². Без этих пределов
# команда прыгает ступенькой: колёса срываются в проскальзывание (у меканума
# ролики к этому особенно склонны), одометрия врёт, а человеку кажется, что
# робот дёргается.
#
# Числа переехали в planner, и не ради порядка. Планировщик прокатывает
# пробные дуги ЭТИМ ЖЕ разгоном: пока он считал дуги с постоянной скоростью,
# он проверял траекторию, по которой робот не поедет, — от неподвижности
# поворот набирается за треть секунды, а ход за секунду с лишним, то есть
# первый миг робот почти крутится на месте там, где ему обещали пологую дугу.
РАЗГОН = planner.РАЗГОН
ЗАМЕДЛЕНИЕ_ПЛАВНОЕ = planner.СБРОС
РАЗГОН_ПОВОРОТА = planner.РАЗГОН_ПОВОРОТА

# Прежнее имя оставлено: на него смотрят проверки и оно же — потолок при
# полностью свободном пути.
СКОРОСТЬ_МАКС = СКОРОСТЬ_ПОТОЛОК

# С какой скоростью ехать, когда не знаем, что впереди. Прежнее число: оно
# было выбрано осторожным, таким и остаётся. Незнание — повод для осторожности,
# а не для потолка.
ОСТОРОЖНО = 0.22
ПОВОРОТ_МАКС = 1.0
# Как быстро крутиться, когда впереди тесно или неизвестно. Вращение на месте
# кажется безобидным и таковым не является: робот сзади и по бокам слеп, а
# углы корпуса описывают окружность. Померить, что сбоку, нечем — значит
# остаётся осторожность.
ПОВОРОТ_ОСТОРОЖНО = 0.4
# С какого расстояния впереди считаем, что вокруг просторно и можно крутиться
# в полную силу.
ПОВОРОТ_СВОБОДНО = 1.2
# Коэффициенты простого пропорционального закона. ПИД тут не нужен: цель
# движется медленно, инерция тележки мала, а интегральная часть на роботе,
# который то и дело упирается в человека, копила бы ошибку и выстреливала
# рывком в момент, когда путь освободится.
ПО_РАССТОЯНИЮ = 0.6          # м/с на метр отставания
ПО_УГЛУ = 2.0                # рад/с на радиан отклонения
# Мёртвая зона по углу: ниже неё не крутимся вовсе. Половина колонки — меньше
# всё равно не разглядеть, а дрожание колёс на месте выглядит как неисправность.
УГОЛ_НЕ_ВАЖЕН = math.radians(ПОЛЕ_ГРАДУСОВ / 16)

# --- упреждение --------------------------------------------------------------
# На сколько вперёд целимся. Это вся задержка цепочки: кадр дальномера (до
# 100 мс), круг цикла (67 мс), разгон колёс. Треть секунды — и человек,
# идущий 1.2 м/с, за это время уходит на сорок сантиметров.
УПРЕЖДЕНИЕ = 0.35
# Постоянная сглаживания оценки скорости. Меньше — оценка дёргается от
# каждого промаха дальномера, больше — робот узнаёт о повороте человека
# позже, чем тот успевает завернуть.
СГЛАЖИВАНИЕ = 0.35
# Больше этого угла упреждение не добавляем. Одиночный промах дальномера
# смещает пеленг на целую колонку, а делённый на шаг цикла он превращается в
# «человек летит десять радиан в секунду».
УПРЕЖДАЕМ_НЕ_БОЛЬШЕ = math.radians(20.0)
# Через сколько тишины оценка скорости считается протухшей и счёт начинается
# заново. Две секунды: разность через больший промежуток описывает не
# движение, а телепортацию.
ЗАБЫВАЕМ_ПОСЛЕ = 2.0
# На сколько метров растёт желаемая дистанция на каждый метр в секунду
# скорости человека. Полсекунды хода — столько же берут у чемоданов и
# тележек, следующих за хозяином.
К_ЗА_СКОРОСТЬ = 0.5
# Дальше этого не отстаём даже за бегущим: следование должно оставаться
# следованием, а не наблюдением издалека.
ДЕРЖАТЬ_МАКС = 1.6

# --- потеря цели -------------------------------------------------------------
# Сколько кадров подряд нужно, чтобы поверить в цель. Тот же довод, что у
# стопа: одиночный кадр — это помеха.
КАДРОВ_ЧТОБЫ_ПОВЕРИТЬ = 2
# ЖДЁМ_СЕКУНД здесь БЫЛА и удалена. Она объявляла «полторы секунды стоим и
# ждём вернувшуюся цель», но нигде не использовалась — то есть описывала
# поведение, которого не было. Такой комментарий хуже отсутствия кода: он
# врёт читателю уверенно и бесплатно.
#
# И само поведение неверно. Человек пропадает из кадра почти всегда вбок —
# завернул за угол, обошёл кресло. Стоять и ждать полторы секунды значит
# терять его насовсем; правильно ДОВОРАЧИВАТЬСЯ туда, куда он ушёл, и это
# теперь делается сразу (см. ПОВОРОТ_ПОИСКА в _вести).
# Через сколько сдаёмся совсем и говорим об этом вслух.
СДАЁМСЯ_ЧЕРЕЗ = 6.0
# Сколько молча стоять, если сторож не пускает вперёд, прежде чем сказать об
# этом вслух. Полторы секунды: короче — робот забормочет на каждой помехе,
# которую сам же объедет через кадр; дольше — человек успеет уйти и решить,
# что робот сломался.
МОЛЧА_НЕ_ЕДЕМ = 1.5
# Сколько всего может длиться следование. Пять минут: дольше это уже не
# «дойдём до кухни», а робот, катающийся за человеком по квартире, о котором
# тот забыл.
ВСЕГО_НЕ_ДОЛЬШЕ = 300.0

# Как часто повторять жалобу «развернуться некуда». Цикл крутится пятнадцать
# раз в секунду, и без этого предела робот забормотал бы одну фразу подряд.
ЖАЛУЕМСЯ_НЕ_ЧАЩЕ = 8.0

# Как часто писать в журнал, почему робот едет именно так. Две секунды: цикл
# крутится десять раз в секунду, и отчёт на каждом кадре залил бы журнал.
ОТЧЁТ_РАЗ_В = 2.0

# Как быстро крутиться, разыскивая пропавшего человека. Медленнее обычного
# поворота: робот, резко вертящийся на месте, пугает, а искать надо не
# быстро, а внимательно — цель вернётся в кадр всё равно на скорости шага.
ПОВОРОТ_ПОИСКА = 0.5

# Сколько зон должно увидеть пятно, чтобы считать его человеком. Две: человек
# на метре занимает по ширине градусов двадцать, то есть две-три колонки, а
# по высоте — несколько рядов. Одна зона — это блик или угол мебели.
ЗОН_ДЛЯ_ЦЕЛИ = 2

# Насколько близко к ведомому должно оказаться «препятствие», чтобы счесть,
# что это он и есть. Двадцать сантиметров: человек не точка, дальномер меряет
# то грудь, то живот, то сумку в руке, и требовать совпадения до сантиметра
# значило бы всё равно на него жаловаться.
ЭТО_ВЕДОМЫЙ = 0.25

# Ближе этого человек стоит СЛИШКОМ близко, чтобы за ним идти. Не потому, что
# опасно — вперёд робот и так не поедет, — а потому, что на таком расстоянии
# всё разъезжается сразу: дальномер видит не человека, а ДВЕ НОГИ ПО
# ОТДЕЛЬНОСТИ и кидает цель с левой на правую, а камера человека уже не
# вмещает и пеленг не поправляет.
#
# На живом роботе это выглядело так: до человека 0.55-0.78 м при желаемом
# метре, вперёд ноль во всех кадрах, а угол скачет -25°, +5°, +10°, -21°,
# +20°, -20°. Со стороны — «робот крутит туда-сюда и всё». И ни слова
# человеку: он видит бессмысленное верчение и решает, что робот сломался.
СЛИШКОМ_БЛИЗКО = 0.85

# --- сличение датчиков -------------------------------------------------------
# Во сколько раз должны разойтись дальномер и камера, чтобы счесть, что они
# меряют РАЗНОЕ. Полтора — это ещё погрешность: камера считает расстояние по
# высоте рамки, допуская рост 1.7 м, и на человеке ростом 1.6 или 1.9 промах
# именно такого порядка. Втрое — это уже не промах.
РАСХОЖДЕНИЕ_РАЗ = 2.0
# А вот это прощаем всегда, каким бы ни было отношение. Вблизи любое
# отношение выглядит страшно: 0.30 против 0.15 — это ровно вдвое, а по сути
# пятнадцать сантиметров, то есть толщина человека.
РАСХОЖДЕНИЕ_ПРОЩАЕМ = 0.35

# Сколько робот молча вертится, прежде чем сказать, что человек слишком
# близко. Полторы секунды: за меньшее человек и сам отойдёт, за большее
# успевает решить, что робот сломался.
МОЛЧА_ВЕРТИМСЯ = 1.5

# Во сколько раз мягче крутиться, когда вперёд ехать всё равно нельзя. Точный
# пеленг в этом положении не нужен вовсе: робот никуда не двинется, а рывки
# на месте — это то самое, что выглядит поломкой. Вдобавок пеленг здесь
# заведомо врёт, прыгая между ногами.
ПОВОРОТ_НА_МЕСТЕ = 0.4

# Как часто крутится цикл. Дальномер отдаёт десять кадров в секунду; чаще
# спрашивать нечего, реже — робот начнёт запаздывать за человеком.
ШАГ = 1 / 15

# Ниже этого напряжения следование прекращается. То же число, что у обычной
# поездки: 3S li-ion на 10.2 В уже на грани, и робот, севший посреди коридора,
# не безобиднее — он там и останется, а человек будет думать, что тот
# сломался.
#
# Проверяется НА ХОДУ, а не только при старте. Следование длится до пяти
# минут, и батарея за это время садится: проверка только на входе означала бы,
# что робот заезжает в разряд и молча встаёт.
БАТАРЕЯ_МИНИМУМ = 10.2


class Слежка:
    """Куда человек ДВИЖЕТСЯ, а не только где он стоит.

    До сих пор следование было чистой пропорцией: увидели пеленг — повернули
    настолько же. Это работает, пока цель стоит, и опаздывает ровно на время
    цепочки, как только она пошла. Цепочка у нас длинная: кадр дальномера до
    100 мс, круг цикла 67 мс, разгон колёс. За треть секунды человек, идущий
    1.2 м/с, уходит на сорок сантиметров — и на повороте коридора это ровно
    та разница, после которой он оказывается за краем поля зрения.

    Лечится тем же, чем у всех, кто ведёт движущуюся цель: не гнаться за
    последним замером, а править на УПРЕЖДЕНИЕ. Простой оценки скорости для
    этого достаточно — в обзорах следования за человеком лучшие результаты
    получают с обычным фильтром Калмана поверх пеленга, без нейросетевых
    планировщиков.

    ГЛАВНАЯ ТОНКОСТЬ, И ОНА НЕ ОЧЕВИДНА. Пеленг меняется по двум причинам
    сразу: человек идёт И робот поворачивается. Разность замеров смешивает их
    и годится только для успокоения собственных колебаний, а для упреждения
    нужна СКОРОСТЬ ЧЕЛОВЕКА — то есть измеренная разность ПЛЮС то, что робот
    сделал сам. Свою скорость мы знаем точно: сами её и подали. Без этой
    поправки упреждение считало бы движением человека собственный доворот и
    раскачивало бы робота вместо того, чтобы вести.
    """

    def __init__(self) -> None:
        self._угол = None
        self._расстояние = None
        self.поворот_цели = 0.0        # рад/с, в мире
        self.скорость_цели = 0.0       # м/с, от робота

    def забыть(self) -> None:
        self._угол = None
        self._расстояние = None
        self.поворот_цели = 0.0
        self.скорость_цели = 0.0

    def обновить(self, расстояние: float, угол: float, прошло: float,
                 наша_скорость: float = 0.0, наш_поворот: float = 0.0) -> None:
        if прошло <= 0 or прошло > ЗАБЫВАЕМ_ПОСЛЕ:
            # Слишком давно (цель терялась) — начинаем счёт заново: разность
            # через две секунды описывает не скорость, а телепортацию.
            self._угол, self._расстояние = угол, расстояние
            return
        if self._угол is None or self._расстояние is None:
            self._угол, self._расстояние = угол, расстояние
            return
        # Разность пеленгов + собственный поворот = поворот цели в мире.
        измеренный = (угол - self._угол) / прошло
        сырой_поворот = измеренный + наш_поворот
        # Разность дистанций + своя скорость = скорость цели от робота.
        сырая_скорость = (расстояние - self._расстояние) / прошло + наша_скорость
        доля = min(1.0, прошло / СГЛАЖИВАНИЕ)
        self.поворот_цели += доля * (сырой_поворот - self.поворот_цели)
        self.скорость_цели += доля * (сырая_скорость - self.скорость_цели)
        self._угол, self._расстояние = угол, расстояние

    def упредить(self, угол: float) -> float:
        """Куда целиться с поправкой на то, что человек идёт.

        Поправку ограничиваем: одиночный промах дальномера даёт скачок
        пеленга на целую колонку, а делённый на 67 мс он превращается в
        «человек летит десять радиан в секунду». Без предела робот на такой
        помехе разворачивался бы вокруг себя.
        """
        поправка = self.поворот_цели * УПРЕЖДЕНИЕ
        поправка = max(-УПРЕЖДАЕМ_НЕ_БОЛЬШЕ, min(УПРЕЖДАЕМ_НЕ_БОЛЬШЕ, поправка))
        return угол + поправка

    def дистанция(self) -> float:
        """Сколько метров держать. Быстрее идёт — дальше держимся.

        Не вежливость, а тормозной путь. Робот за быстрым человеком и сам
        едет быстро, а тормозной путь растёт как квадрат скорости: держать
        метр и на прогулочном шаге, и на быстром — значит однажды не успеть.
        Ровно так же считают дистанцию следования у чемоданов и тележек: чем
        быстрее хозяин, тем больше зазор.

        Отрицательная скорость (человек идёт НА робота) дистанцию не
        уменьшает: подпускать ближе того, кто сам приближается, незачем.
        """
        добавка = К_ЗА_СКОРОСТЬ * max(0.0, self.скорость_цели)
        return min(ДЕРЖАТЬ_МАКС, ДЕРЖАТЬ + добавка)


def без_пола(взгляд) -> list[list[float]]:
    """Сетка, в которой пол вычеркнут. Пустая — вычеркнуть не вышло.

    ЭТО САМАЯ ВАЖНАЯ СТРОКА ВО ВСЁМ СЛЕДОВАНИИ, и её здесь долго не было.

    Следование ищет ближайшее крупное пятно. При наклоне датчика вниз на
    10-15°, как записано в docs/hardware.md, нижние ряды упираются в пол на
    0.2-0.5 м — и ближайшим крупным пятном в любой комнате оказывается
    собственный пол. Робот честно находил цель в тридцати сантиметрах, видел,
    что до неё ближе СТОЯТЬ_БЛИЖЕ, и не ехал НИКОГДА, при любом расположении
    человека. Ровно на это и жаловался хозяин: «он вообще не едет за мной».

    Хуже: начать() тоже искал цель на сырой сетке, пол всегда её давал, и
    ветка «Не вижу тебя, встань передо мной» была недостижима. Робот отвечал
    «Иду за тобой» в пустой комнате и потом пять минут стоял.

    Плоскость не нашлась — возвращаем ПУСТО, а не сырую сетку. Не зная, где
    пол, отличить человека от пола нечем, и «ближайшее пятно» снова окажется
    полом. Пусть лучше робот скажет «не вижу тебя»: неправда про то, что он
    кого-то ведёт, дороже отказа. Камерный пеленг при этом продолжает
    работать — следование без дальномера умеет доворачиваться и вести.
    """
    чистая = getattr(взгляд, "сетка_без_пола", None)
    if чистая is not None:
        return чистая
    return [[0.0] * 8 for _ in range(8)]


def колонка_под_углом(угол: float, колонок: int = 8) -> int:
    """Какая колонка сетки смотрит в эту сторону. Угол в радианах, влево плюс."""
    градусы = math.degrees(угол)
    к = (колонок - 1) / 2.0 - градусы / (ПОЛЕ_ГРАДУСОВ / колонок)
    return max(0, min(колонок - 1, int(round(к))))


def не_похоже(а: float, б: float) -> bool:
    """Говорят ли два датчика о разных предметах.

    Не «равны ли числа» — они и не должны быть равны. Дальномер меряет грудь,
    камера считает по высоте рамки с допущением о росте, и разница в четверть
    метра тут норма. А вот разница ВТРОЕ — это уже не погрешность, это разные
    предметы: человек в полутора метрах и стена в полуметре.

    Сравниваем отношением, а не разностью: на полуметре промах в двадцать
    сантиметров огромен, на трёх метрах — обычное дело.
    """
    if а <= 0 or б <= 0:
        return False
    if abs(а - б) <= РАСХОЖДЕНИЕ_ПРОЩАЕМ:
        return False
    return max(а, б) / min(а, б) > РАСХОЖДЕНИЕ_РАЗ


def найти_цель(сетка: list[list[float]],
               куда: float | None = None) -> tuple[float, float, int] | None:
    """Человек впереди: (расстояние, угол в радианах, зон). None — нет цели.

    Угол положительный влево, как в ROS.

    `куда` — пеленг с КАМЕРЫ, если он свежий. Это главный довод в пользу
    того, какое пятно считать человеком, и вот почему.

    Дальномер не знает, что перед ним. Он берёт БЛИЖАЙШЕЕ крупное пятно и
    называет его целью — а в жилой комнате ближайшее пятно почти никогда не
    человек. На живом роботе: слева стена, справа кровать, по тридцать
    сантиметров вбок. Человек ходил в полутора метрах, а «до человека»
    прыгало 0.55 → 1.00 → 0.68 → 0.54 за секунды: дальномер по очереди мерил
    то человека, то мебель. Робот при этом не трогался вовсе — он едет
    только когда цель ДАЛЬШЕ желаемой дистанции, а мебель всегда ближе.

    Камера же знает, что перед ней человек, и видит сто тридцать градусов
    против шестидесяти. Поэтому разделение обязанностей такое: камера
    говорит КУДА смотреть, дальномер — СКОЛЬКО МЕТРОВ в эту сторону. Каждый
    делает то, что умеет, и ни один не делает того, чего не умеет.

    Без камерного пеленга остаётся прежнее «ближайшее пятно» — это лучше,
    чем ничего, и так робот работал раньше.

    Ищем по колонкам, а не по отдельным зонам, и это не мелочь. Человек в
    сетке выглядит вертикальной полосой: он высокий и узкий, и попадает в
    несколько рядов одной-двух колонок. Считать по зонам значило бы находить
    центр тяжести всего, что близко, — и уводить робота между человеком и
    дверным косяком, потому что среднее между ними как раз посередине.
    """
    колонки: list[tuple[int, float, int]] = []
    for к in range(8):
        свои = [сетка[р][к] for р in range(8)
                if НЕ_ВЕРИМ_БЛИЖЕ < сетка[р][к] <= ТЕРЯЕМ_ДАЛЬШЕ]
        if len(свои) >= 1:
            свои.sort()
            колонки.append((к, свои[len(свои) // 2], len(свои)))
    if not колонки:
        return None

    # Ближайшая колонка задаёт дистанцию, а пятно вокруг неё набирается
    # ПОДРЯД — влево и вправо, пока соседняя колонка держится той же глубины.
    # Полметра допуска: человек не плоский, плечо дальше груди сантиметров на
    # двадцать.
    #
    # Именно подряд, а не «все колонки на той же глубине», и это поймала
    # собственная проверка. Два пятна по краям сетки — человек слева и косяк
    # справа, оба в метре, — давали средний пеленг ровно посередине, и робот
    # ехал между ними. Причём уверенно: цель «найдена», зон много, всё
    # выглядит исправно.
    по_номеру = {с[0]: с for с in колонки}
    ближняя = min(колонки, key=lambda с: с[1])
    if куда is not None:
        # Камера показала направление — начинаем пятно ОТТУДА, а не от
        # ближайшего. Соседнюю колонку тоже пробуем: пеленг камеры точнее
        # колонки дальномера, но человек не обязан стоять ровно в её середине.
        цель_к = колонка_под_углом(куда)
        по_камере = next((по_номеру[к] for к in
                          (цель_к, цель_к - 1, цель_к + 1, цель_к - 2, цель_к + 2)
                          if к in по_номеру), None)
        if по_камере is not None:
            ближняя = по_камере
    рядом = [ближняя]
    for шаг in (-1, 1):
        к = ближняя[0] + шаг
        while к in по_номеру and abs(по_номеру[к][1] - ближняя[1]) <= 0.5:
            рядом.append(по_номеру[к])
            к += шаг
    зон = sum(с[2] for с in рядом)
    if зон < ЗОН_ДЛЯ_ЦЕЛИ:
        return None

    # Пеленг — среднее по колонкам пятна, взвешенное числом зон. Так центр
    # приходится на середину человека, а не на его край.
    вес = sum(с[2] for с in рядом)
    середина = sum(с[0] * с[2] for с in рядом) / вес
    # Колонка 0 — слева, колонка 7 — справа; влево угол положительный.
    угол = math.radians(ПОЛЕ_ГРАДУСОВ * (3.5 - середина) / 8.0)
    расстояние = min(с[1] for с in рядом)
    return расстояние, угол, зон


def скорость_по_виду(свободно: float) -> float:
    """Быстрее чего ехать нельзя, если впереди свободно на столько метров.

    Считаем честно, из физики торможения, а не подбором.

    Робот замечает препятствие не мгновенно: сперва должен прийти кадр
    дальномера, потом второй для подтверждения, потом опроситься сторож. Всё
    это время он едет прежним ходом. Дальше начинается торможение, и путь
    торможения растёт КАК КВАДРАТ скорости — вдвое быстрее означает вчетверо
    дальше.

    Отсюда уравнение: за время реакции проехали v·T, потом тормозили
    v²/(2a), и всё это должно уместиться в свободное расстояние минус запас,
    в котором стоит человек. Решаем относительно v:

        v = -aT + sqrt((aT)² + 2a·(свободно - запас))

    Свободно меньше запаса — стоим, и это не перестраховка: там уже нога.

    Именно так связывают скорость с дистанцией все, кто ездит рядом с людьми
    (в стандартах это зовётся speed and separation monitoring). Робот с
    постоянной скоростью либо всегда слишком медленный, либо однажды слишком
    быстрый; третьего у него нет.
    """
    место = свободно - ЗАПАС_ДО_ПРЕПЯТСТВИЯ
    if место <= 0:
        return 0.0
    aT = ЗАМЕДЛЕНИЕ * ЗАДЕРЖКА_РЕАКЦИИ
    v = -aT + math.sqrt(aT * aT + 2.0 * ЗАМЕДЛЕНИЕ * место)
    return max(0.0, min(СКОРОСТЬ_ПОТОЛОК, v))


def поворот_по_виду(свободно: float, вокруг: float = 0.0) -> float:
    """Быстрее чего нельзя крутиться. Ноль — крутиться нельзя вовсе.

    Поворот на месте выглядит безобидным и таковым не является. Углы корпуса
    при вращении описывают окружность радиусом в половину диагонали, а сзади
    и по бокам дальномер не видит НИЧЕГО. Человек, стоящий сбоку в двадцати
    сантиметрах, для него не существует — и получает углом.

    Раньше здесь была честно названная ДОГАДКА: «если впереди что-то близко,
    робот почти наверняка стоит рядом с мебелью, значит крутимся медленно».
    Догадка не нужна, если помнить. Стул, который был перед роботом секунду
    назад, никуда не делся оттого, что робот отвернулся, — он лежит в карте
    памяти (mapping.py), и та отвечает настоящим числом: `вокруг` — до
    ближайшего занятого места по всей окружности.

    Ноль в `вокруг` значит «карты нет, не знаю» — тогда судим по фронту, как
    раньше. Незнание — повод для осторожности, а не для смелости.

    А вот ноль НА ВЫХОДЕ теперь возможен, и это перемена. Прежний текст
    гласил «ноль не возвращаем никогда: поворот — единственный способ
    разыскать потерянного человека». Довод неверен ровно в одном случае —
    когда занятая клетка лежит ВНУТРИ круга, который заметает корпус. Там
    поворот не «рискованный», а гарантированно задевающий, и медленный
    задевает так же, как быстрый. Робот в этом положении обязан стоять и
    сказать об этом, а не тихо тереться боком о человека.
    """
    известно = вокруг if вокруг > 0 else свободно
    if вокруг > 0 and вокруг <= mapping.РАДИУС_КОРПУСА:
        return 0.0
    if известно <= 0:
        return ПОВОРОТ_ОСТОРОЖНО
    доля = min(1.0, max(0.0, (известно - ЗАПАС_ДО_ПРЕПЯТСТВИЯ)
                        / max(0.1, ПОВОРОТ_СВОБОДНО - ЗАПАС_ДО_ПРЕПЯТСТВИЯ)))
    return ПОВОРОТ_ОСТОРОЖНО + доля * (ПОВОРОТ_МАКС - ПОВОРОТ_ОСТОРОЖНО)


# Сглаживание команды живёт в planner: ЭТОЙ ЖЕ функцией он прокатывает
# пробные дуги. Будь их две, они однажды разошлись бы — и робот поехал бы не
# по той дуге, которую перед этим проверил на просвет.
придержать = planner.придержать


def как_ехать(расстояние: float, угол: float,
              свободно: float = 0.0, вокруг: float = 0.0,
              держать: float = ДЕРЖАТЬ) -> tuple[float, float]:
    """Скорость и поворот по дистанции и пеленгу. Простой пропорциональный.

    Возврат (вперёд м/с, поворот рад/с). Ноль вперёд — стоим, но крутиться
    при этом можно: повернуться к человеку, не приближаясь, безопасно и
    выглядит внимательно.

    `свободно` — на сколько метров впереди чисто. Ноль означает «не знаю», и
    тогда держимся прежнего осторожного предела: незнание не повод разгоняться.

    `держать` — сколько метров держать до человека. Не постоянная величина:
    за быстро идущим держимся дальше, потому что и сами едем быстрее, а
    тормозной путь растёт как квадрат скорости. Считает это Слежка.дистанция.
    Оба порога — «стоим» и «трогаемся» — едут вместе с ней: зазор между ними
    нужен, чтобы робот не дёргался на месте, пока человек стоит.
    """
    держать = max(СТОЯТЬ_БЛИЖЕ + ЗАЗОР / 2, держать)
    стоять_ближе = держать - ЗАЗОР
    ехать_дальше = держать + ЗАЗОР
    предел_поворота = поворот_по_виду(свободно, вокруг)
    поворот = 0.0
    if abs(угол) > УГОЛ_НЕ_ВАЖЕН:
        поворот = max(-предел_поворота,
                      min(предел_поворота, ПО_УГЛУ * угол))

    # Потолок этого мига: чем дальше видно, тем быстрее можно. Не знаем, что
    # впереди, — едем как раньше, медленно.
    предел = скорость_по_виду(свободно) if свободно > 0 else ОСТОРОЖНО

    вперёд = 0.0
    if расстояние > ехать_дальше:
        вперёд = min(предел, ПО_РАССТОЯНИЮ * (расстояние - держать))
    elif расстояние < стоять_ближе:
        # Ближе некуда — стоим. Пятиться нельзя: назад робот едет вслепую, а
        # сзади у следования чаще всего тот, кто пришёл посмотреть.
        вперёд = 0.0

    # Круто поворачиваем — сперва довернём, потом поедем. Иначе робот
    # описывает дугу мимо человека и теряет его на краю поля зрения.
    if abs(угол) > math.radians(ПОЛЕ_ГРАДУСОВ / 4):
        вперёд = 0.0
    return вперёд, поворот


class Следование:
    """Держится за человеком, пока не попросят прекратить."""

    def __init__(self, ros, tof, говорить=None, глаза=None, карта=None) -> None:
        self.ros = ros
        self.tof = tof
        # Карта памяти вокруг робота. None — её нет, и поворот судится по
        # одному фронту, как раньше: следование обязано работать и без карты.
        self.карта = карта
        # Детектор людей с камеры. None — его нет, и ведём по одному
        # дальномеру, как раньше: следование обязано работать и без него,
        # иначе не запущенный узел ROS означал бы онемевшую команду.
        self.глаза = глаза
        self.говорить = говорить or (lambda фраза: None)
        self._поток: threading.Thread | None = None
        self._стоп = threading.Event()
        # Когда в последний раз жаловались, что негде развернуться.
        self._жаловался_на_тесноту = 0.0
        # Куда записать, чем кончилась поездка. None — дневника нет.
        self.дневник = None
        # Когда в последний раз писали в журнал, почему едем именно так.
        # Заводится здесь, а не только в цикле: `_отчёт` могут позвать и до
        # первого круга, и объект следования переживает не одну поездку.
        self._отчитались = 0.0
        self.почему_кончилось = ""

    @property
    def идёт(self) -> bool:
        return self._поток is not None and self._поток.is_alive()

    def начать(self) -> str:
        """Пойти за человеком. Возвращает фразу для него же."""
        if self.tof is None:
            return "Не могу идти за тобой: дальномера нет."
        # Без шасси ехать некуда, и заводить цикл нельзя: он в любом случае
        # доберётся до publish_twist — хотя бы в finally, останавливая колёса,
        # — и умрёт там молча, оставив «Иду за тобой» единственным следом.
        if self.ros is None:
            return "Не могу идти за тобой: нет связи с колёсами."
        взгляд = self.tof.взгляд()
        if not взгляд.свежий:
            return "Не могу идти за тобой: дальномер молчит."
        цель = найти_цель(без_пола(взгляд),
                          self.глаза.угол
                          if self.глаза is not None
                          and getattr(self.глаза, "свежий", False) else None)
        # Дальномер видит шестьдесят градусов, камера — сто тридцать. Человек,
        # стоящий чуть в стороне, для дальномера не существует, а на картинке
        # он посреди кадра. Отказывать ему значит требовать встать по линейке
        # там, где робот и так прекрасно его видит.
        #
        # Раньше этой развилки не было и она была не нужна: цель находилась
        # всегда, потому что ею оказывался пол. Вычеркнув пол, мы сделали
        # отказ настоящим — и вот теперь второй источник обязателен.
        видит_камера = (self.глаза is not None
                        and getattr(self.глаза, "свежий", False))
        if self.глаза is None:
            # БЕЗ КАМЕРЫ СЛЕДОВАНИЯ НЕТ ВОВСЕ. Не «работает хуже» — нет.
            # Дальномер не умеет отличить человека от мебели: он берёт
            # ближайшее крупное пятно, а в жилой комнате ближайшее пятно —
            # это стена, кровать или косяк. На живом роботе он полминуты вёл
            # стену в 0.48 м и требовал у неё отойти на пару шагов, пока
            # человек был в другой комнате.
            #
            # Отказ с названной причиной честнее исправной с виду работы: во
            # втором случае человек полчаса гадает, почему робот сошёл с ума.
            return ("Не вижу тебя камерой, а без неё я пойду за мебелью. "
                    "Похоже, зрение не запустилось.")
        if цель is None and not видит_камера:
            # Не начинаем вслепую. Робот, поехавший «искать» человека,
            # которого не видит, — это робот, поехавший неизвестно куда.
            return "Не вижу тебя. Встань передо мной, шагах в двух."
        if self.идёт:
            return "Я и так иду за тобой."
        # Колёса у одного хозяина. Робот, которому в этот миг велели проехать
        # метр вперёд, поездку прекращает: «иди за мной» — это новое намерение
        # человека, а не добавка к прежнему. Без этого два потока пятнадцать
        # раз в секунду подавали бы разные скорости в один топик.
        освободить = getattr(self.ros, "stop_motion", None)
        if освободить is not None:
            try:
                освободить()
            except Exception:                   # noqa: BLE001
                log.exception("не смог освободить колёса перед следованием")
        # Именно ПОСЛЕ отмены: stop_motion зовёт и наш собственный «хватит»,
        # и очищенный до него флаг встал бы обратно — следование кончилось бы,
        # не начавшись.
        self._стоп.clear()
        self.почему_кончилось = ""
        self._поток = threading.Thread(target=self._вести, daemon=True)
        self._поток.start()
        return "Иду за тобой. Скажи стоп, когда хватит."

    def хватит(self, почему: str = "", *, ждать: bool = True) -> bool:
        """Прекратить. True — следование правда шло.

        `ждать=False` — не дожидаться, пока поток свернётся. Нужно тем, кто
        зовёт это из потока websocket: тот в это время не читает сообщения, и
        секунда ожидания — это секунда глухоты как раз тогда, когда человек
        жмёт аварийную кнопку. Колёса от этого не страдают: цикл проверяет
        отмену вплотную к публикации (см. _крутить), поэтому после `_стоп`
        ни одной новой скорости не уходит, а нули пошлёт тот, кто позвал.
        """
        шло = self.идёт
        self._стоп.set()
        # Отпускаем цель: следующее «иди за мной» должно выбирать человека
        # заново. Без этого робот держался бы за номер, выданный полчаса
        # назад, и, встретив его случайное повторение, пошёл бы за чужим.
        if self.глаза is not None:
            self.глаза.забыть()
        if шло:
            self.почему_кончилось = почему or "попросили"
            поток = self._поток
            if ждать and поток is not None and поток is not threading.current_thread():
                поток.join(timeout=1.0)
        return шло

    def _крутить(self, вперёд: float, поворот: float) -> bool:
        """Подать скорость, если следование ещё не отменили. False — отменили.

        Проверка стоит ВПЛОТНУЮ К ПУБЛИКАЦИИ, а не только в условии цикла, и
        это не перестраховка. Между началом круга и подачей скорости проходит
        разбор кадра дальномера, поиск цели и арифметика — миллисекунды, но
        «стоп», пришедший в этот зазор, раньше приводил к тому, что робот
        после команды остановиться делал ещё один шаг вперёд. Человек при
        этом уже отпустил кнопку и видел, что робот на неё не послушался.
        """
        if self._стоп.is_set():
            return False
        self.ros.publish_twist(вперёд, 0.0, поворот)
        return True

    def _вокруг(self) -> float:
        """До ближайшего занятого места по всей окружности. Ноль — не знаю."""
        карта = self.карта
        if карта is None:
            return 0.0
        try:
            return float(карта.ближайшее())
        except Exception:                       # noqa: BLE001
            # Карта — подсказка, а не опора: её сбой не должен ронять
            # следование. Незнание наверху уже означает осторожность.
            log.exception("карта не ответила, что вокруг")
            return 0.0

    def сказать_на_ходу(self, текст: str) -> None:
        """Сказать, НЕ останавливая цикл следования.

        Это не украшение, а исправление настоящей поломки. `voice.say` ждёт,
        пока реплика отзвучит целиком, а зовут его прямо из цикла — значит на
        всю длину фразы в /cmd_vel не уходит ни одной команды.

        Сторож мёртвой руки видит эту тишину и делает ровно то, для чего он
        заведён: решает, что тот, кто крутил колёса, умер, и шлёт нули. Робот
        принимает нули за чужой стоп и гасит следование. На живом роботе это
        выглядело так: «Иду за тобой» в 16:16:18, фраза «Ты слишком близко,
        отойди» в 16:16:20, три нуля в ту же секунду и «следование кончилось:
        кнопка стоп» — при том, что кнопки никто не трогал.

        Сторож при этом ПРАВ. Неправ был цикл: он не имеет права ждать ни на
        чём, кроме собственного шага. Поэтому речь уезжает в свой поток и
        звучит, пока колёса продолжают получать команды.
        """
        if not текст:
            return
        threading.Thread(target=self.говорить, args=(текст,),
                         daemon=True, name="следование-речь").start()

    def _спланировать(self, взгляд, расстояние, угол, держать,
                      потолок_вперёд, потолок_поворот,
                      было_вперёд, было_поворот, *, можно_вперёд=True):
        """Перебрать дуги и выбрать проезжую. None — планировать не по чему.

        Возвращает (вперёд, поворот, объяснение). Нет препятствий в виду —
        None, и тогда остаётся простая пропорция: перебирать дуги в пустой
        комнате незачем, а лишний слой между командой и колёсами это лишний
        способ ошибиться.

        `можно_вперёд` — ложь означает «вперёд нельзя вообще», и тогда
        планировщику остаётся один доворот. Это не совет и не потолок: он
        физически не сможет выбрать ход, потому что нечего будет выбирать.
        """
        сетка = без_пола(взгляд)
        точки = planner.препятствия(сетка)
        точки += planner.из_карты(self.карта)
        if not точки:
            return None
        # Человека из препятствий вычёркиваем: дальномер не знает, что перед
        # ним, и цель для него — обычное пятно. Оставить её значит велеть
        # роботу от неё уворачиваться, то есть кружить вокруг, не подходя.
        точки = planner.без_цели(точки, расстояние, угол)
        if not точки:
            return None
        ехать = max(0.0, расстояние - держать)
        # Потолок для перебора. Ноль в `потолок_вперёд` бывает по двум
        # совершенно разным поводам, и раньше они были свалены в один `or`:
        #
        #   • «вперёд нельзя» — человек слишком близко. Тут ноль и должен
        #     остаться нулём, иначе запрет ничего не запрещает;
        #   • «сперва довернём» — человек сильно вбок, пропорция обнуляет ход
        #     до разворота. Вот здесь запасной потолок и нужен: планировщик
        #     как раз умеет ехать по дуге вместо разворота на месте.
        if not можно_вперёд:
            потолок = 0.0
        else:
            потолок = abs(потолок_вперёд) or СКОРОСТЬ_ПОТОЛОК * 0.5
        v, w, почему = planner.выбрать(
            ехать, угол, точки,
            скорость_потолок=потолок,
            поворот_потолок=max(abs(потолок_поворот), ПОВОРОТ_ОСТОРОЖНО),
            было_вперёд=было_вперёд, было_поворот=было_поворот)
        return v, w, почему

    def _отчёт(self, почему: str, **числа) -> None:
        """Раз в несколько секунд — почему робот едет именно так.

        Заведено после живого испытания, на котором робот сказал «Иду за
        тобой» и не сдвинулся, а в журнале про это не было НИ ОДНОЙ строки.
        Ровно та же беда, что была со сторожем падений: событие есть, чисел
        нет, и починить нечем — только гадать.

        Раз в несколько секунд, а не на каждом кадре: цикл крутится десять
        раз в секунду, и посекундный отчёт залил бы журнал так, что в нём
        потерялось бы всё остальное.
        """
        сейчас = time.monotonic()
        if сейчас - self._отчитались < ОТЧЁТ_РАЗ_В:
            return
        self._отчитались = сейчас
        хвост = ", ".join(f"{имя} {значение}" for имя, значение in числа.items())
        log.info("следование: %s | %s", почему, хвост)

    def _пожаловаться_на_тесноту(self) -> None:
        """Сказать, что развернуться некуда. Один раз, а не на каждом кадре."""
        сейчас = time.monotonic()
        if сейчас - self._жаловался_на_тесноту < ЖАЛУЕМСЯ_НЕ_ЧАЩЕ:
            return
        self._жаловался_на_тесноту = сейчас
        log.warning("следование: развернуться некуда, в круге корпуса занято")
        self.сказать_на_ходу("Не могу развернуться, вокруг тесно.")

    def _вести(self) -> None:
        начало_поездки = time.monotonic()
        конец = начало_поездки + ВСЕГО_НЕ_ДОЛЬШЕ
        видел = 0.0
        подряд = 0
        сказал_что_потерял = False
        сказал_про_расхождение = False
        # Когда сторож впервые не пустил вперёд и сказали ли мы об этом.
        держат_с = 0.0
        сказал_что_держат = False
        # Когда человек впервые оказался слишком близко и сказали ли мы ему.
        вертимся_с = 0.0
        сказал_что_близко = False
        # Что публиковали в прошлый раз — чтобы не прыгать ступенькой.
        было_вперёд = было_поворот = 0.0
        прошлый_миг = time.monotonic()
        # Куда человек ушёл в последний раз, когда мы его видели. Нужно,
        # чтобы искать его поворотом, а не стоять столбом.
        последний_угол = 0.0
        # Куда он ДВИЖЕТСЯ. Пропорциональный закон опаздывает ровно на время
        # цепочки, и на повороте коридора это та самая разница, после которой
        # человек оказывается за краем поля зрения.
        слежка = Слежка()
        видел_когда = 0.0
        # Сторож застревания: сравнивает команду с одометрией. Заводится на
        # одну поездку, потому что копит окно последних секунд, и окно от
        # прошлой поездки к этой отношения не имеет.
        ход = progress.Ход()
        self._отчитались = 0.0
        try:
            while not self._стоп.is_set() and time.monotonic() < конец:
                # Батарею смотрим ПЕРВЫМ делом и на ходу.
                #
                # Первым — потому что разряженный робот обязан встать, даже
                # если он в этот миг никого не видит и крутится, разыскивая
                # человека. Проверка ниже по циклу это пропускала: она стояла
                # за поиском цели, и потерявший цель робот вертелся бы до
                # полного разряда. Поймано своей же проверкой.
                #
                # На ходу — потому что следование длится до пяти минут, и
                # батарея за это время садится. Проверка только на входе
                # означала бы, что робот заезжает в разряд и молча встаёт
                # посреди коридора, а выглядит это как поломка.
                вольт = getattr(self.ros, "voltage", None)
                if вольт is not None and вольт < БАТАРЕЯ_МИНИМУМ:
                    self.почему_кончилось = "батарея"
                    self.говорить("Больше не могу идти: батарея садится.")
                    return

                взгляд = self.tof.взгляд()
                # Что вокруг — по карте памяти. Дальномер видит шестьдесят
                # градусов вперёд, а корпус при вращении заметает круг; карта
                # помнит то, что уже вышло из поля зрения, и отвечает про
                # круг целиком. Нет карты — ноль, то есть «не знаю».
                вокруг = self._вокруг()
                # КАМЕРА ВЕДЁТ, ДАЛЬНОМЕР ПОПРАВЛЯЕТ. Пеленг с камеры отдаём
                # в выбор цели: пусть дальномер меряет расстояние ТУДА, куда
                # смотрит камера, а не до ближайшего пятна.
                #
                # Разница решает всё. Дальномер не знает, что перед ним, и
                # берёт ближайшее крупное пятно — в жилой комнате это почти
                # никогда не человек. На живом роботе: стена слева, кровать
                # справа по тридцать сантиметров, человек в полутора метрах, а
                # «до человека» прыгало 0.55 → 1.00 → 0.68 → 0.54 за секунды.
                # Робот при этом не трогался ни разу: он едет, только когда
                # цель ДАЛЬШЕ желаемой дистанции, а мебель всегда ближе.
                видит_камера = (self.глаза is not None and self.глаза.свежий)
                глядит = self.глаза.угол if видит_камера else None
                # ЧЕЛОВЕКА ОБЪЯВЛЯЕТ ТОЛЬКО КАМЕРА. Дальномер меряет метры и
                # больше ничего не решает — и это не предпочтение, а вывод из
                # тридцати секунд живого журнала:
                #
                #   18:34:31 до_человека 0.48 м, угол  -5° … зазор inf
                #   18:34:43 до_человека 0.48 м, угол  -6°
                #   18:34:51 до_человека 0.48 м, угол +21°
                #   18:35:01 до_человека 0.49 м, угол +19°
                #
                # Полминуты РОВНО 0.48 м, пеленг гуляет на сорок градусов, а
                # человек в это время был в другой комнате. Робот вёл стену.
                #
                # Хуже того, он и планировщику сказал, что стены нет: цель из
                # препятствий вычёркивается (иначе робот кружил бы вокруг
                # человека), и вычеркнулась ровно та стена, в которую он
                # смотрел. Отсюда «зазор inf, отброшено 0 из 35» — вокруг
                # чисто, ехать можно куда угодно.
                #
                # Так и должно было выйти. Дальномер физически не умеет
                # отличить человека от мебели: он берёт ближайшее крупное
                # пятно, а в жилой комнате ближайшее пятно — это никогда не
                # человек. Раньше здесь стояло «без камеры остаётся прежнее
                # ближайшее пятно — лучше, чем ничего». Оказалось, ХУЖЕ, чем
                # ничего: робот не просто ошибался, он ошибался уверенно и
                # заражал этой уверенностью остальных — планировщик считал
                # дорогу чистой, а глазомер учил «рост человека 2.19 м» по
                # расстоянию до стены.
                цель = (найти_цель(без_пола(взгляд), глядит)
                        if взгляд.свежий and видит_камера else None)
                # Человек шагнул вбок и вышел из шестидесяти градусов
                # дальномера — но камера его видит. Не терять же его: раньше
                # робот в этот момент вставал и через шесть секунд говорил
                # «Больше не иду», хотя человек был в двух шагах, просто
                # правее. Едем на камерный пеленг, а расстояние берём
                # последнее известное — оно нужно только чтобы не разгоняться.
                не_по_камере = цель is not None
                if цель is None and видит_камера:
                    # Дальномер потерял, камера видит. Расстояние берём у
                    # выученной связи «пиксель ног — метры»; не выучилась —
                    # считаем, что человек на желаемой дистанции, и тогда
                    # робот только доворачивается, никуда не разгоняясь.
                    по_камере = self.глаза.далеко_ли
                    цель = (по_камере or ДЕРЖАТЬ, self.глаза.угол, 0)

                if цель is None:
                    подряд = 0
                    видел_когда = 0.0
                    # Вперёд — НОЛЬ, в тот же миг. Доезжать по инерции туда,
                    # где в прошлый раз был человек, — ровно то поведение, от
                    # которого людям страшно.
                    #
                    # А вот повернуться в его сторону можно и нужно. Человек
                    # почти всегда пропадает не «вообще», а вбок: завернул за
                    # угол, обошёл кресло, шагнул за край поля зрения. Робот,
                    # стоящий столбом, теряет его насовсем; робот, доворачивающий
                    # туда, куда тот ушёл, обычно находит его снова. Так делают
                    # все, кто ходит за человеком, и это ничего не стоит:
                    # поворот на месте безопасен, вперёд мы при этом не едем.
                    ищем = 0.0
                    if видел and abs(последний_угол) > УГОЛ_НЕ_ВАЖЕН:
                        # Разыскивая, крутимся не быстрее, чем позволяет
                        # теснота: робот слеп сзади и по бокам, а углы
                        # корпуса при вращении описывают окружность.
                        тесно = поворот_по_виду(
                            getattr(взгляд, "свободно_впереди", 0.0), вокруг)
                        ищем = math.copysign(
                            min(ПОВОРОТ_ПОИСКА, тесно,
                                abs(ПО_УГЛУ * последний_угол)),
                            последний_угол)
                    self._отчёт(
                        "цели нет — стою",
                        дальномер="свеж" if взгляд.свежий else "молчит",
                        камера=("видит" if (self.глаза is not None
                                            and self.глаза.свежий) else "нет"),
                        ищем=f"{ищем:.2f}")
                    было_вперёд = придержать(было_вперёд, 0.0, ШАГ,
                                             РАЗГОН, ЗАМЕДЛЕНИЕ_ПЛАВНОЕ)
                    было_поворот = придержать(было_поворот, ищем, ШАГ,
                                              РАЗГОН_ПОВОРОТА, РАЗГОН_ПОВОРОТА)
                    if not self._крутить(0.0, было_поворот):
                        return
                    if видел and time.monotonic() - видел > СДАЁМСЯ_ЧЕРЕЗ:
                        self.почему_кончилось = "потерял"
                        if not сказал_что_потерял:
                            self.говорить("Потерял тебя. Стою.")
                        return
                    self._стоп.wait(ШАГ)
                    continue

                расстояние, угол, _зон = цель
                # СЛИЧАЕМ ДВА ДАТЧИКА. Камера видит человека и умеет прикинуть
                # расстояние по высоте рамки; дальномер меряет точнее, но не
                # знает, что именно он померил. Расходятся в разы — верим той,
                # которая знает, ЧТО перед ней.
                #
                # Без этой сверки выходило вот что. Камера ведёт человека,
                # пеленг честный, но в той же колонке дальномера стоит стена в
                # полуметре — и «до человека» становится 0.48 м навсегда. Робот
                # говорит «ты слишком близко, отойди» человеку, который в
                # соседней комнате, и стоит так, пока не надоест.
                if видит_камера and не_по_камере:
                    по_камере = self.глаза.далеко_ли
                    if по_камере and не_похоже(по_камере, расстояние):
                        if not сказал_про_расхождение:
                            сказал_про_расхождение = True
                            log.info("следование: дальномер говорит %.2f м, "
                                     "камера %.2f м — верю камере: она знает, "
                                     "что перед ней человек",
                                     расстояние, по_камере)
                        расстояние = по_камере
                        не_по_камере = False
                # Пеленг предпочитаем КАМЕРНЫЙ. У дальномера шестьдесят
                # градусов и восемь колонок — то есть человек либо в узком
                # секторе, либо его нет вовсе, а угол известен с точностью до
                # семи с половиной градусов. У камеры сто тридцать градусов и
                # рамка в пикселях: точнее и втрое шире.
                #
                # Расстояние при этом остаётся за дальномером: камера метров
                # не знает, а знать их обязательно — держать дистанцию по
                # размеру рамки значит подъезжать вплотную к худому и
                # отставать от полного.
                if self.глаза is not None and self.глаза.свежий:
                    угол = self.глаза.угол
                подряд += 1
                if подряд < КАДРОВ_ЧТОБЫ_ПОВЕРИТЬ:
                    # Одиночный кадр — помеха, а не человек. Пока не поверили,
                    # стоим: тронуться на помехе хуже, чем опоздать на десятую
                    # долю секунды.
                    if not self._крутить(0.0, 0.0):
                        return
                    self._стоп.wait(ШАГ)
                    continue
                видел = time.monotonic()
                сказал_что_потерял = False
                # Скорость цели считаем ДО того, как подменим угол
                # упреждённым: иначе оценка стала бы считать собственную
                # поправку движением человека и разогналась бы сама от себя.
                слежка.обновить(расстояние, угол, видел - видел_когда,
                                наша_скорость=было_вперёд,
                                наш_поворот=было_поворот)
                видел_когда = видел
                последний_угол = угол
                угол = слежка.упредить(угол)
                # Дальномер сказал метры, камера видит ноги — вот и пара для
                # обучения. Собирается сама, пока робот идёт: линейкой мерить
                # не надо, а задели камеру — переучится.
                if self.глаза is not None and не_по_камере:
                    self.глаза.сверить(расстояние)

                # Сколько впереди свободно — отсюда потолок скорости этого
                # мига. Робот с постоянной скоростью либо всегда слишком
                # медленный, либо однажды слишком быстрый.
                свободно = getattr(взгляд, "свободно_впереди", 0.0)
                держать_сейчас = слежка.дистанция()
                вперёд, поворот = как_ехать(расстояние, угол, свободно, вокруг,
                                            держать=держать_сейчас)

                # А ТЕПЕРЬ ПЛАНИРОВЩИК. Он не заменяет расчёт выше, а решает
                # то, чего тот не умеет: ОБОЙТИ. Пропорция знает только «езжай»
                # и «стой», и стул на дороге для неё — повод остановиться.
                #
                # Планировщик перебирает четыре десятка дуг, отбрасывает те, на
                # которых корпус во что-то войдёт, и берёт лучшую по близости к
                # цели. Проверено прогонами: стул точно по курсу он обходит
                # крюком в девять сантиметров, щель со стеной и кроватью по
                # тридцать два проходит на полной скорости, в тупике честно
                # встаёт.
                #
                # Потолок скорости остаётся прежним — тем, что посчитан из
                # тормозного пути. Планировщик выбирает, КУДА, а не насколько
                # быстро можно себе позволить.
                #
                # А «слишком близко» он не может переехать вовсе, и это
                # считается ДО него, а не после. Раньше считалось после — и на
                # живом роботе вышло вот что:
                #
                #   до_человека 0.65 м … близко ДА … вперёд 0.28
                #
                # То есть пропорция честно сказала «стоим», планировщик
                # получил вместо нуля запасной потолок и поехал НА человека.
                # Запрет, который применяется после решения, — это не запрет.
                близко = 0 < расстояние < СЛИШКОМ_БЛИЗКО
                план = self._спланировать(взгляд, расстояние, угол,
                                          держать_сейчас, вперёд, поворот,
                                          было_вперёд, было_поворот,
                                          можно_вперёд=not близко)
                план_сказал = ""
                if план is not None:
                    вперёд, поворот, план_сказал = план
                # Крутиться нельзя вовсе — значит в круге, который заметает
                # корпус, что-то стоит. Молчать об этом нельзя: со стороны
                # робот, который перестал доворачиваться к человеку, выглядит
                # как сломавшийся, и человек подходит ближе — то есть ровно
                # туда, откуда его и не пускают.
                if (поворот == 0.0 and abs(угол) > УГОЛ_НЕ_ВАЖЕН
                        and поворот_по_виду(свободно, вокруг) == 0.0):
                    self._пожаловаться_на_тесноту()
                # Общий сторож остаётся поверх всего: он про то, что ближе
                # тридцати пяти сантиметров, а мы держим метр. Если он всё же
                # сработал — значит между нами что-то влезло, и это важнее
                # следования.
                # Сторож остаётся поверх всего, но его надо УМЕТЬ ЧИТАТЬ.
                #
                # Он не знает, что мы кого-то ведём, и честно сообщает про
                # всё ближе тридцати пяти сантиметров. А ближе всех при
                # следовании обычно сам ведомый: человек остановился, робот
                # подкатился — и вот уже «Не могу идти следом, впереди
                # что-то». «Что-то» — это тот, за кем робот идёт, и жаловаться
                # на него глупо.
                #
                # Отличаем по расстоянию: если ближайшее совпадает с тем, где
                # мы видим человека, это он. Тогда просто не едем вперёд —
                # что и так следует из дистанции, — и молчим.
                # Человек ближе, чем мы вообще способны за ним идти. Вперёд
                # тут уже ноль — и у пропорции, и у планировщика, которому
                # это сказано выше; наша задача — не дёргаться и сказать.
                if близко:
                    поворот *= ПОВОРОТ_НА_МЕСТЕ
                    if not вертимся_с:
                        вертимся_с = time.monotonic()
                    elif (not сказал_что_близко
                            and time.monotonic() - вертимся_с > МОЛЧА_ВЕРТИМСЯ):
                        сказал_что_близко = True
                        log.info("следование: человек в %.2f м — это ближе "
                                 "%.2f м, идти не за чем; прошу отойти",
                                 расстояние, СЛИШКОМ_БЛИЗКО)
                        self.сказать_на_ходу(
                            "Ты слишком близко, я так не поеду. "
                            "Отойди на пару шагов.")
                else:
                    вертимся_с = 0.0
                    сказал_что_близко = False

                мешает = self.tof.мешает() if вперёд > 0 else ""
                это_он = (мешает and расстояние > 0
                          and abs(расстояние - СТОЯТЬ_БЛИЖЕ) < ЭТО_ВЕДОМЫЙ)
                if мешает:
                    вперёд = 0.0
                    # Молчать об этом нельзя, и это выяснилось на живом
                    # роботе. Человек сказал «едь за мной», робот ответил «Иду
                    # за тобой» — и стоял, потому что дальномер видел
                    # неподвижное препятствие (в журнале: «одно и то же
                    # препятствие уже 60 секунд, колонки 1, 4, 5, 6» — свой же
                    # кронштейн в кадре). Со стороны это выглядит как «робот
                    # сломался и врёт»: он обещал идти следом и не идёт.
                    #
                    # Говорим один раз за поездку, не на каждом кадре: цикл
                    # крутится десять раз в секунду, и робот забормотал бы.
                    if это_он:
                        # Это человек, а не преграда. Молчим и ждём, пока он
                        # отойдёт: сказать «не могу идти» тому, кто сам стоит
                        # перед роботом, — это упрёк, а не сообщение.
                        держат_с = 0.0
                        сказал_что_держат = False
                    elif not держат_с:
                        держат_с = time.monotonic()
                    elif (держат_с and not сказал_что_держат
                            and time.monotonic() - держат_с > МОЛЧА_НЕ_ЕДЕМ):
                        сказал_что_держат = True
                        log.warning("следование: сторож держит уже %.0f с (%s) "
                                    "— говорю человеку", МОЛЧА_НЕ_ЕДЕМ, мешает)
                        self.сказать_на_ходу(f"Не могу идти следом, {мешает}.")
                else:
                    держат_с = 0.0
                    сказал_что_держат = False
                self._отчёт(
                    "еду" if вперёд or поворот else "НЕ ЕДУ",
                    до_человека=f"{расстояние:.2f} м",
                    угол=f"{math.degrees(угол):.0f}°",
                    держать=f"{слежка.дистанция():.2f} м",
                    свободно=f"{свободно:.2f} м",
                    вокруг=f"{вокруг:.2f} м",
                    вперёд=f"{вперёд:.2f}",
                    поворот=f"{поворот:.2f}",
                    сторож=(мешает or "молчит"),
                    близко=("ДА" if близко else "нет"),
                    план=(план_сказал or "не нужен"),
                    по=("камере" if not не_по_камере else "дальномеру"))
                # Плавно, а не ступенькой: у меканума ролики срываются в
                # проскальзывание от рывка, одометрия после этого врёт, а
                # человеку кажется, что робот дёргается.
                сейчас = time.monotonic()
                прошло = min(0.5, max(0.0, сейчас - прошлый_миг))
                прошлый_миг = сейчас
                было_вперёд = придержать(было_вперёд, вперёд, прошло,
                                         РАЗГОН, ЗАМЕДЛЕНИЕ_ПЛАВНОЕ)
                было_поворот = придержать(было_поворот, поворот, прошло,
                                          РАЗГОН_ПОВОРОТА, РАЗГОН_ПОВОРОТА)
                if not self._крутить(было_вперёд, было_поворот):
                    return

                # А ПОЕХАЛИ ЛИ МЫ. Единственное место, где робот сверяет то,
                # что велел колёсам, с тем, что показала одометрия. Без этой
                # сверки любая беда с ходовой выглядит одинаково — робот
                # стоит и молчит, — и разбираться приходится по журналу
                # задним числом.
                ход.отметить(было_вперёд, было_поворот,
                             getattr(self.ros, "odom", None))
                застряли = ход.беда()
                if застряли:
                    self.почему_кончилось = "застряли"
                    log.warning("следование: %s — останавливаюсь", застряли)
                    self.сказать_на_ходу(
                        "Я застрял, колёса не едут. Посмотри, что подо мной.")
                    return
                self._стоп.wait(ШАГ)
            if time.monotonic() >= конец:
                self.почему_кончилось = "долго"
                self.говорить("Хватит, я за тобой уже пять минут.")
        except Exception:                    # noqa: BLE001 — колёса важнее
            log.exception("следование оборвалось")
            self.почему_кончилось = "сбой"
        finally:
            # Три раза, как и в обычной остановке: пакет может потеряться, а
            # шасси держит последнюю скорость, пока ему не скажут иначе.
            for _ in range(3):
                self.ros.publish_twist()
                time.sleep(0.02)
            log.info("следование кончилось: %s", self.почему_кончилось or "само")
            # И в дневник — с местом. Ради этого он и заводился: «на кухне я
            # срываюсь восемь раз из десяти, а в коридоре ни разу» нельзя
            # узнать ниоткуда, кроме как сложив концы поездок с координатами.
            if self.дневник is not None:
                где = getattr(self.ros, "odom", None)
                self.дневник.записать(
                    "следование",
                    итог=self.почему_кончилось or "само",
                    сорвалось=self.почему_кончилось in ("потерял", "сбой",
                                                        "батарея", "застряли"),
                    секунд=round(time.monotonic() - начало_поездки, 1),
                    x=round(где[0], 2) if где else None,
                    y=round(где[1], 2) if где else None)
