def поза_плоха(поза) -> bool:
    """Годится ли поза робота для счёта. Отдельно — потому что зовут дважды."""
    if поза is None:
        return True
    try:
        return len(поза) < 3
    except TypeError:
        return True


def куда_словами(угол: float) -> str:
    """Направление человеческим языком. Радианы, влево положительно."""
    градусы = math.degrees(угол)
    if abs(градусы) <= 20:
        return "прямо передо мной"
    if abs(градусы) >= 160:
        return "позади меня"
    сторона = "слева" if градусы > 0 else "справа"
    if abs(градусы) >= 110:
        return f"сзади {сторона}"
    if abs(градусы) >= 60:
        return сторона
    return f"впереди {сторона}"


# --- привязка: где я стою относительно того, что помню -----------------------
# Сколько пар «помню — вижу» нужно, чтобы привязаться. Две: одна пара даёт
# только сдвиг при известном повороте, а поворот нам как раз и неизвестен —
# робот включается носом куда попало.
ПАР_ДЛЯ_ПРИВЯЗКИ = 2

# Насколько сильно могут разойтись расстояния между парами, чтобы счесть
# совмещение правдоподобным. Сорок сантиметров: расстояние до мебели мы меряем
# по размеру рамки, а стулья разные, и промах в четверть высоты — обычное
# дело. Больше — значит мы совместили стол со стулом, и лучше не привязаться
# вовсе, чем привязаться неверно: неверная привязка портит карту молча.
НЕВЯЗКА_ПРЕДЕЛ = 0.4

# --- перебор соответствий: как привязаться, когда стульев четыре -------------
# Сколько совпавших ориентиров нужно, чтобы поверить привязке.
#
# ТРИ, И ЭТО ГЛАВНОЕ ЧИСЛО ЗДЕСЬ. Двух хватает, чтобы ВЫЧИСЛИТЬ сдвиг и
# поворот, — и ровно поэтому двух мало, чтобы им ПОВЕРИТЬ: на двух точках
# решение проходит через них точно, невязка выходит нулевой всегда, и
# проверять оказывается нечем. Одна ошибка распознавания — и карта испорчена
# молча и навсегда.
#
# Третий ориентир в вычислении не участвует, он свидетель: если решение,
# построенное по двум, ставит третий на место — совпадение не случайно.
ИНЛАЙЕРОВ_ХВАТИТ = 3

# Насколько далеко должны стоять друг от друга два ориентира, по которым
# строится решение. Полметра: чем ближе точки, тем хуже по ним считается
# ПОВОРОТ — ошибка в положении превращается в ошибку угла, делённую на базу.
# На двадцати сантиметрах промах в пять сантиметров даёт четырнадцать
# градусов, и карта ляжет косо.
БАЗА_ПАРЫ = 0.5

# Насколько может разойтись расстояние между двумя ориентирами в памяти и в
# том, что видно сейчас. Это предфильтр, и он почти даровой: жёсткое
# перемещение расстояний не меняет, значит пара, у которой они разошлись,
# заведомо негодная. Отсеивает подавляющее большинство сочетаний до всякой
# арифметики.
РЕБРО_СХОДИТСЯ = 0.5

# На сколько может промахнуться ориентир, чтобы всё ещё считаться совпавшим.
# Полметра: место предмета берётся пересечением пеленгов и врёт на четверть
# метра, а пометки схлопываются в одну на восьмидесяти сантиметрах.
ИНЛАЙЕР_ДО = 0.5

# Сколько сочетаний перебираем, прежде чем сдаться. Перебор идёт по ПАРАМ
# соответствий, то есть растёт квадратично; при десятке предметов в кадре и
# полусотне в памяти это тысячи сочетаний, и все они дешёвые. Потолок стоит
# не ради скорости, а чтобы дурная карта с сотнями пометок не подвесила
# робота на минуту.
СОЧЕТАНИЙ_ХВАТИТ = 20000

# С какого расхождения два решения считаются РАЗНЫМИ, а не одним и тем же,
# посчитанным по разным парам. Двадцать сантиметров и десять градусов: это
# заметно меньше промаха, с которым мы вообще меряем мебель, и заметно больше
# разброса от того, какая пара легла в основу.
СПОРЩИК_ДАЛЬШЕ = 0.2
СПОРЩИК_КРУЧЕ = math.radians(10)


def подобрать(старые, видно, база=БАЗА_ПАРЫ):
    """Совместить два облака ориентиров, не зная, что чему соответствует.

    `старые` и `видно` — {класс: [(x, y), ...]}. Отдаёт (привязка, пары) или
    (None, []).

    ЗАЧЕМ ЭТО НУЖНО, ЕСЛИ ЕСТЬ `совместить`. Затем, что `совместить` требует
    ГОТОВЫХ пар «этот стол — тот самый стол», а взять их неоткуда. Прежний код
    решал это так: брал только классы, встреченные РОВНО ПО ОДНОМУ РАЗУ и в
    памяти, и в кадре, — тогда пара очевидна.
    Правило честное и почти всегда невыполнимое. Стульев в квартире четыре,
    и они выбывают все; тумбочек две — выбывают обе. В живой квартире
    однозначными остаются два-три предмета, и если хоть один не попал в кадр,
    привязки нет, а значит КАРТА НЕ РАСТЁТ ВООБЩЕ. Именно так она и копилась
    ровно один запуск в жизни файла.

    Задача называется data association, и решается она не отказом от
    неоднозначных предметов, а перебором с проверкой. Берём ВСЕ мыслимые
    соответствия одного класса — да, все шестнадцать сочетаний четырёх
    стульев с четырьмя, — и ищем среди них то, что согласуется само с собой.

    ТРИ СИТА, ОТ ДАРОВОГО К ДОРОГОМУ:

      1. Расстояние. Жёсткое перемещение расстояний не меняет: если между
         двумя предметами в памяти метр восемьдесят, а между их кандидатами
         сейчас три метра, это не они. Стоит одно вычитание и отсеивает почти
         всё.
      2. База. Два ориентира должны стоять врозь: по близким точкам поворот
         считается плохо (см. БАЗА_ПАРЫ).
      3. Голосование. По паре строим решение и проверяем ВСЕМИ остальными
         соответствиями: сколько из них это решение ставит на место. Больше
         всего голосов — победитель.

    Это RANSAC с полным перебором вместо случайных проб: сочетаний здесь
    тысячи, а не миллионы, и перебрать их дешевле, чем гадать. Заодно ответ
    получается один и тот же на одних данных, а это важно — со случайным
    робот привязывался бы по-разному от запуска к запуску.
    """
    кандидаты = []
    # ОДНОЗНАЧНЫЕ КЛАССЫ ДЕРЖИМ ОСОБНЯКОМ. Соответствие по классу, который и в
    # памяти, и в кадре встречается ровно раз, сомнений не вызывает: холодильник
    # в квартире один, и спутать его не с чем. Двух таких хватает, чтобы
    # привязаться, — ровно на этом и работал прежний отбор, и работал безопасно.
    #
    # А вот два соответствия по СТУЛЬЯМ ничего не доказывают: они сойдутся
    # точно при любой паре, потому что решение по двум точкам проходит через
    # них всегда. Там нужен третий свидетель.
    надёжные = set()
    for класс, места in видно.items():
        помню = старые.get(класс, ())
        for где_сейчас in места:
            for где_помню in помню:
                кандидаты.append((где_помню, где_сейчас))
                if len(места) == 1 and len(помню) == 1:
                    надёжные.add((где_помню, где_сейчас))
    if len(кандидаты) < ПАР_ДЛЯ_ПРИВЯЗКИ:
        return None, []

    лучшее = None
    решения = []
    сочетаний = 0
    for i in range(len(кандидаты)):
        (сa, нa) = кандидаты[i]
        for j in range(i + 1, len(кандидаты)):
            (сb, нb) = кандидаты[j]
            сочетаний += 1
            if сочетаний > СОЧЕТАНИЙ_ХВАТИТ:
                break
            # Один и тот же предмет не может соответствовать двум разным.
            if сa == сb or нa == нb:
                continue
            было = math.hypot(сa[0] - сb[0], сa[1] - сb[1])
            стало = math.hypot(нa[0] - нb[0], нa[1] - нb[1])
            if было < база or стало < база:
                continue
            if abs(было - стало) > РЕБРО_СХОДИТСЯ:
                continue
            решение = совместить([(сa, нa), (сb, нb)])
            if решение is None:
                continue
            голоса = _кто_согласен(кандидаты, решение)
            if not _хватит_голосов(голоса, надёжные):
                continue
            решения.append((len(голоса), решение, голоса))
            if лучшее is None or len(голоса) > len(лучшее[0]):
                лучшее = (голоса, решение)
        if сочетаний > СОЧЕТАНИЙ_ХВАТИТ:
            log.info("привязка: перебрал %d сочетаний и остановился",
                     сочетаний)
            break

    if лучшее is None:
        return None, []

    # НЕОДНОЗНАЧНОСТЬ — ОТКАЗ, и это не перестраховка.
    #
    # Мебель в квартире расставлена симметрично чаще, чем кажется. Четыре
    # стула вокруг стола стоят прямоугольником, а у прямоугольника есть
    # поворот на сто восемьдесят градусов, при котором он совпадает сам с
    # собой. Значит решений ДВА, оба сходятся идеально, и выбрать между ними
    # по данным нельзя в принципе — второе поставит квартиру вверх ногами.
    #
    # Ошибиться тут дороже, чем не привязаться: непривязанность обратима и
    # проходит сама, как только робот увидит несимметричное, а вывернутая
    # карта портится молча и навсегда. Поэтому при двух одинаково хороших и
    # РАЗНЫХ решениях не выбираем ни одного.
    голоса, решение = лучшее
    спорщики = [р for сколько, р, _ in решения
                if сколько >= len(голоса) and _далеко_ли(р, решение)]
    if спорщики:
        log.info("привязка: нашлось %d одинаково хороших, но разных решений "
                 "(%d ориентиров в каждом) — не привязываюсь, чтобы не "
                 "перевернуть карту", len(спорщики) + 1, len(голоса))
        return None, []
    # ПЕРЕСЧИТЫВАЕМ ПО ВСЕМ СОГЛАСНЫМ, а не оставляем решение по двум точкам:
    # две точки дают решение, проходящее через них точно, а десяток — решение,
    # усреднённое по всем, и оно точнее ровно настолько, насколько больше в
    # нём данных.
    уточнённое = совместить(голоса)
    if уточнённое is None or уточнённое[3] > НЕВЯЗКА_ПРЕДЕЛ:
        return None, []
    return уточнённое, голоса


def _хватит_голосов(голоса, надёжные) -> bool:
    """Довольно ли этих совпадений, чтобы поверить решению.

    Два порога вместо одного, и вот почему. Решение строится по ДВУМ точкам и
    проходит через них ТОЧНО — невязка на них нулевая всегда, каким бы диким
    ни было совмещение. Значит две точки себя не проверяют, и нужен третий,
    который в построении не участвовал.

    Исключение — однозначные предметы. Холодильник в квартире один, диван
    один; спутать их не с чем, и двух таких хватало прежнему коду, который
    работал безопасно годами. Ломать это ради единообразия незачем: там, где
    сомнений нет, лишний свидетель не нужен.
    """
    if len(голоса) >= ИНЛАЙЕРОВ_ХВАТИТ:
        return True
    return (len(голоса) >= ПАР_ДЛЯ_ПРИВЯЗКИ
            and all(г in надёжные for г in голоса))


def _далеко_ли(одно, другое) -> bool:
    """Разные ли это привязки. Мелкие расхождения — та же, считанная иначе."""
    угол = abs((одно[2] - другое[2] + math.pi) % (2 * math.pi) - math.pi)
    сдвиг = math.hypot(одно[0] - другое[0], одно[1] - другое[1])
    return сдвиг > СПОРЩИК_ДАЛЬШЕ or угол > СПОРЩИК_КРУЧЕ


def _кто_согласен(кандидаты, привязка):
    """Соответствия, которые это решение ставит на место. Один к одному."""
    согласны = []
    занято_старых = set()
    занято_новых = set()
    # По возрастанию промаха: если на один и тот же предмет претендуют
    # несколько, забирает ближайший, а остальные остаются ни с чем.
    промахи = []
    for где_помню, где_сейчас in кандидаты:
        сюда = перенести(где_помню, привязка)
        промахи.append((math.hypot(сюда[0] - где_сейчас[0],
                                   сюда[1] - где_сейчас[1]),
                        где_помню, где_сейчас))
    for промах, где_помню, где_сейчас in sorted(промахи, key=lambda т: т[0]):
        if промах > ИНЛАЙЕР_ДО:
            break
        if где_помню in занято_старых or где_сейчас in занято_новых:
            continue
        занято_старых.add(где_помню)
        занято_новых.add(где_сейчас)
        согласны.append((где_помню, где_сейчас))
    return согласны


def совместить(пары):
    """Найти (сдвиг_x, сдвиг_y, поворот, невязка) по парам «было → стало».

    `пары` — список ((старый_x, старый_y), (новый_x, новый_y)).

    Это задача Прокруста в двух измерениях, и решается она точно, без
    подбора: считаем середины обоих облаков, поворот берём из суммы векторных
    и скалярных произведений, сдвиг — из совмещения середин.

    Масштаб не ищем: комната не растягивается. Искать его значило бы дать
    решению лишнюю свободу, которой оно воспользуется, чтобы «объяснить»
    ошибку измерения растяжением квартиры.

    Невязка — среднее расхождение после совмещения. Она и есть проверка:
    правильное совмещение сводит точки почти в ноль, а совмещение стола со
    стулом оставляет заметный остаток. Без невязки формула ответит всегда, и
    ответит уверенно, даже когда совмещать было нечего.
    """
    if len(пары) < ПАР_ДЛЯ_ПРИВЯЗКИ:
        return None
    старые = [п[0] for п in пары]
    новые = [п[1] for п in пары]
    сx = sum(т[0] for т in старые) / len(старые)
    сy = sum(т[1] for т in старые) / len(старые)
    нx = sum(т[0] for т in новые) / len(новые)
    нy = sum(т[1] for т in новые) / len(новые)
    вверх = вниз = 0.0
    for (ax, ay), (bx, by) in пары:
        ax, ay = ax - сx, ay - сy
        bx, by = bx - нx, by - нy
        вверх += ax * by - ay * bx        # векторное: даёт синус угла
        вниз += ax * bx + ay * by         # скалярное: даёт косинус
    if abs(вверх) < 1e-9 and abs(вниз) < 1e-9:
        return None
    поворот = math.atan2(вверх, вниз)
    cos, sin = math.cos(поворот), math.sin(поворот)
    сдвиг_x = нx - (cos * сx - sin * сy)
    сдвиг_y = нy - (sin * сx + cos * сy)
    остаток = 0.0
    for (ax, ay), (bx, by) in пары:
        пx = cos * ax - sin * ay + сдвиг_x
        пy = sin * ax + cos * ay + сдвиг_y
        остаток += math.hypot(bx - пx, by - пy)
    return сдвиг_x, сдвиг_y, поворот, остаток / len(пары)


def перенести(точка, привязка):
    """Точку из старой системы координат — в нынешнюю."""
    x, y = точка
    сдвиг_x, сдвиг_y, поворот = привязка[0], привязка[1], привязка[2]
    cos, sin = math.cos(поворот), math.sin(поворот)
    return cos * x - sin * y + сдвиг_x, sin * x + cos * y + сдвиг_y
