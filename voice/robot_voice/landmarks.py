"""Пометки на карте: где стоит стол, где диван, где робот застревает.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ КАРТЫ ЗАНЯТОСТИ (mapping.py). Та карта — про «проеду
или нет»: шесть метров вокруг робота, пять сантиметров на клетку, и она
ЗАБЫВАЕТ — половину уверенности за тридцать пять секунд. Так и надо: стул
унесли, кот ушёл, дверь закрыли, и держаться за увиденное минуту назад значит
объезжать призраков.

Но у мебели свойство ровно обратное. Стол стоит на своём месте годами, и
забывать его через тридцать пять секунд — значит не помнить квартиру вовсе.
Поэтому пометки живут отдельно: их мало, они именованные, они не тускнеют от
времени и переживают перезапуск.

ОТКУДА БЕРУТСЯ КООРДИНАТЫ. Направление даёт распознавание вещей (things.py),
расстояние — размер рамки в кадре и известный размер предмета. Та же оптика,
что и для человека: d = f·H/h. Для человека H — рост, для стула — высота
стула. Точность отсюда невелика, потому что стулья разные, — но нам и не надо
точнее полуметра: пометка отвечает на вопрос «где примерно искать», а не «дай
координаты с точностью до сантиметра».

ГДЕ ЖИВУТ КООРДИНАТЫ. В системе одометрии ТЕКУЩЕГО запуска. Робот включается —
и его нынешний ноль лежит там, где он в этот раз стоял; вчерашние координаты
после этого означают другое место. Поэтому всё, прочитанное из файла,
помечается «с прошлого раза»: робот это помнит, но за своё нынешнее знание не
выдаёт.

ПРИВЯЗКА — то, что превращает вчерашние пометки обратно в знание. Увидел стол
и холодильник, помнит, где они стояли, — и этого хватает, чтобы вычислить и
сдвиг, и поворот (совместить + привязаться). Одного ориентира мало: одна пара
даёт сдвиг, но не поворот, а привязка наизнанку портит карту молча и навсегда.

Пробует робот сам, раз в несколько секунд, пока не узнает квартиру:
привязаться_чем_вижу берёт «что вижу сейчас» из этих же пометок — те, что
увидены своими глазами в этот запуск. Пока не узнал, постоянная карта
(atlas.py) не копится вовсе, и пульт пишет, чего не хватает.

ЧЕГО ЗДЕСЬ НЕТ. Ориентиром служит только ОДНОЗНАЧНЫЙ класс — тот, что
встречается по одному разу и в памяти, и в поле зрения. Стульев в квартире
четыре, и какой из них какой, мы не знаем; стол, холодильник и диван обычно по
одному, они и работают. Значит квартира без узнаваемой мебели роботу не
дастся, и честно об этом сказать — часть работы.
"""

from __future__ import annotations

import json
import logging
import math
import os
import time

from . import vocabulary

log = logging.getLogger(__name__)

# Типичная высота предмета в метрах — то самое H в d = f·H/h. Числа грубые
# нарочно: это не справочник мебели, а способ отличить «стол в метре» от
# «стола в четырёх». Ошибка в четверть высоты даёт ошибку в четверть
# расстояния, и для пометки этого достаточно.
#
# Берём только то, что в квартире действительно стоит на месте. Ни яблоки, ни
# бутылки, ни телефоны сюда не входят: они переезжают по десять раз на дню, и
# пометка «телефон вот здесь» устареет раньше, чем робот договорит.
# БЕРЁМ ИЗ ОБЩЕГО СЛОВАРЯ, А НЕ ДЕРЖИМ СВОЮ КОПИЮ. Здесь стояли две таблицы
# руками — рост и список подвижного, — и обе обязаны были согласовываться с
# третьей, в things.ПО_РУССКИ. Ничто их к этому не принуждало, и разъехаться
# они могли молча: класс, забытый в росте, узнаётся, называется по-русски и НЕ
# ПОПАДАЕТ НА КАРТУ — потому что мебель() требует именно роста. Снаружи это
# «робот видит стол и не запоминает его», а причина в другом файле.
#
# Теперь источник один (vocabulary), а здесь — имена, под которыми он известен
# этому модулю.
РОСТ_ПРЕДМЕТА = vocabulary.РОСТ

# Что переезжает и потому в пометки не идёт. Отдельным списком, а не
# отсутствием в предыдущем: так видно, что про них ПОДУМАЛИ и решили.
НЕ_МЕБЕЛЬ = vocabulary.ДВИЖЕТСЯ

# На каком расстоянии две пометки одного класса считаются одной вещью.
# Восемьдесят сантиметров: стол — предмет крупный, и робот, увидевший его с
# двух сторон, оценит середину по-разному. Меньше — и один стол размножится
# на четыре; больше — два стула у стены сольются в один.
ОДНА_ВЕЩЬ = 0.8

# Сколько раз вещь надо увидеть, чтобы поверить. Два: одиночное срабатывание
# распознавания бывает и на отражении в стекле.
ВИДЕТЬ_РАЗ = 2

# Сколько пометок держим. Полсотни: столько в квартире и есть заметного, а
# копить больше значит отвечать на «что вокруг» списком на две минуты.
ПОМЕТОК_ПРЕДЕЛ = 50

# Дальше этого расстоянию по рамке не верим. Три метра: дальше предмет
# занимает десятки пикселей, и четверть высоты ошибки превращается в метры.
ВЕРИМ_ДО = 3.0
# И ближе этого тоже: вплотную рамка обрезана краем кадра.
ВЕРИМ_ОТ = 0.3


def расстояние_до(класс: str, высота_рамки: float, фокус: float) -> float:
    """Метры до предмета по высоте его рамки. Ноль — считать не из чего.

    d = f·H/h — та же оптика, что и для человека, только H берётся из таблицы
    типичных размеров, а не из роста.
    """
    рост = РОСТ_ПРЕДМЕТА.get(класс)
    if not рост or высота_рамки <= 1.0 or фокус <= 0:
        return 0.0
    метры = фокус * рост / высота_рамки
    if not (ВЕРИМ_ОТ <= метры <= ВЕРИМ_ДО):
        return 0.0
    return метры


def мебель(класс: str) -> bool:
    """Стоит ли эта вещь на месте достаточно долго, чтобы её помечать."""
    return класс in РОСТ_ПРЕДМЕТА and класс not in НЕ_МЕБЕЛЬ


# --- где вещь стоит на самом деле: два взгляда вместо линейки ----------------
#
# ПОЧЕМУ НЕ ХВАТАЕТ ВЫСОТЫ РАМКИ. Способ выше (расстояние_до) честен, но
# опирается на допущение: стул ростом ровно 90 см. Живые стулья бывают от 75
# до 110, и ошибка в росте переходит в ошибку расстояния один в один — то
# есть плюс-минус четверть. Плюс рамка, обрезанная краем кадра, даёт
# заниженную высоту и завышенное расстояние.
#
# КАК ДЕЛАЮТ ДРУГИЕ. Тот же вопрос у всех, кто картирует одной камерой, и
# ответ у всех один — ТРИАНГУЛЯЦИЯ: посмотреть на предмет из двух разных
# точек и пересечь два пеленга. Никаких допущений о размере предмета вообще:
# работает и со стулом, и с холодильником, и с тем, чего в таблице нет.
#
# ЧТО ТУТ ВАЖНО, И ЧТО ЛЕГКО УПУСТИТЬ. Решает не длина базы сама по себе, а
# УГОЛ СХОЖДЕНИЯ двух лучей в точке предмета. Когда лучи почти параллельны,
# геометрия вырождается и ошибка расходится в бесконечность: сдвинь пеленг на
# полградуса — и точка уедет на метры. Прямой угол — идеал, и чем ближе к
# нему, тем точнее.
#
# Отсюда порог. Пеленг у нас шумит градуса на три (дрожание рамки детектора
# плюс поле камеры, взятое из паспорта, а не измеренное). Ошибка дальности
# при схождении δ примерно равна дальности, умноженной на шум и делённой на
# δ. Чтобы уложиться в четверть дальности, нужно δ ≥ 4·шум, то есть градусов
# двенадцать. Берём пятнадцать — с запасом, и это достижимо: при переезде
# обхода на 1.2 м предмет в двух метрах даёт схождение больше тридцати.
УГОЛ_СХОЖДЕНИЯ = 15.0              # градусы
# И минимальная база. Пятнадцать сантиметров: меньше — это уже не «две точки»,
# а одна и та же с точностью до ошибки одометрии.
БАЗА_ОТ = 0.15
# Дальше этого не верим и сведённому. Пять метров: дальше квартира кончается,
# а схождение при нашей базе становится меньше порога само собой.
СВЕДЁННОЕ_ДО = 5.0


def свести(луч_а, луч_б):
    """Пересечь два пеленга. (x, y) или None, если сводить нельзя.

    Луч — (x, y, курс) в мире: откуда смотрели и куда. Возвращаем точку, где
    лучи пересекаются, или None, если геометрия негодная.

    Отказываем в четырёх случаях, и каждый — не придирка:
      база короче БАЗА_ОТ — это один и тот же взгляд, а не два;
      лучи сходятся площе УГОЛ_СХОЖДЕНИЯ — вырожденная геометрия, см. выше;
      точка позади любого из наблюдателей — значит лучи разошлись, а
          пересеклись их продолжения назад, чего в жизни не бывает;
      вышло дальше СВЕДЁННОГО_ДО — за пределами квартиры и веры.
    """
    ах, ау, акурс = луч_а
    бх, бу, бкурс = луч_б
    if math.hypot(бх - ах, бу - ау) < БАЗА_ОТ:
        return None
    схождение = abs((бкурс - акурс + math.pi) % (2 * math.pi) - math.pi)
    # Лучи, идущие навстречу, сходятся так же хорошо, как и под острым углом:
    # 170° — это те же 10° до вырождения, только с другой стороны.
    схождение = min(схождение, math.pi - схождение)
    if схождение < math.radians(УГОЛ_СХОЖДЕНИЯ):
        return None
    дах, дау = math.cos(акурс), math.sin(акурс)
    дбх, дбу = math.cos(бкурс), math.sin(бкурс)
    знаменатель = дах * дбу - дау * дбх
    if abs(знаменатель) < 1e-9:
        return None
    та = ((бх - ах) * дбу - (бу - ау) * дбх) / знаменатель
    тб = ((бх - ах) * дау - (бу - ау) * дах) / знаменатель
    if та <= 0 or тб <= 0 or та > СВЕДЁННОЕ_ДО or тб > СВЕДЁННОЕ_ДО:
        return None
    return ах + дах * та, ау + дау * та


class Пометки:
    """Именованные места квартиры. Одна на робота.

    Хранит то, что стоит на месте: мебель и трудные места. Не тускнеет от
    времени — в отличие от карты занятости, где забывание обязательно.
    """

    def __init__(self, файл=None, часы=time.time) -> None:
        self.файл = файл
        self._часы = часы
        self.метки: list[dict] = []
        self._с_прошлого_раза = 0
        if файл:
            self.метки = self._прочитать()
            for метка in self.метки:
                # Всё, что было до этого запуска, помечаем честно: координаты
                # у него от прошлой системы отсчёта и нынешнему нулю робота не
                # соответствуют. Помнить — помним, выдавать за своё нынешнее
                # знание — нет.
                метка["прошлый_раз"] = True
            self._с_прошлого_раза = len(self.метки)

    # --- хранение --------------------------------------------------------
    def _прочитать(self) -> list[dict]:
        try:
            with open(self.файл, encoding="utf-8") as f:
                данные = json.load(f)
        except (OSError, ValueError):
            return []
        if not isinstance(данные, list):
            return []
        return [м for м in данные if isinstance(м, dict) and "класс" in м]

    def сохранить(self) -> None:
        if not self.файл:
            return
        try:
            os.makedirs(os.path.dirname(str(self.файл)) or ".", exist_ok=True)
            врем = f"{self.файл}.новый"
            with open(врем, "w", encoding="utf-8") as f:
                json.dump(self.метки[-ПОМЕТОК_ПРЕДЕЛ:], f,
                          ensure_ascii=False, indent=1)
            os.replace(врем, self.файл)
        except OSError:
            log.debug("пометки: не смог сохранить", exc_info=True)

    # --- накопление ------------------------------------------------------
    def заметить(self, класс: str, x: float, y: float,
                 уверенность: float = 0.0) -> dict | None:
        """Робот увидел вещь вот здесь. Отдаёт пометку или None.

        Пометки того же класса поблизости СЛИВАЮТСЯ, а не копятся: стол,
        увиденный с четырёх сторон, — это один стол, а не четыре. Середину
        подтягиваем скользящим средним, и чем больше подтверждений, тем
        меньше её двигает новый замер: сотый взгляд на стол знает о нём не
        больше, чем первые десять.
        """
        if not мебель(класс):
            return None
        for метка in self.метки:
            if метка["класс"] != класс:
                continue
            if math.hypot(x - метка["x"], y - метка["y"]) > ОДНА_ВЕЩЬ:
                continue
            метка["раз"] += 1
            доля = 1.0 / min(метка["раз"], 10)
            метка["x"] += (x - метка["x"]) * доля
            метка["y"] += (y - метка["y"]) * доля
            метка["когда"] = round(self._часы(), 1)
            # Увидели своими глазами в этом запуске — координаты снова наши.
            метка["прошлый_раз"] = False
            return метка
        метка = {"класс": класс, "x": round(x, 2), "y": round(y, 2),
                 "раз": 1, "когда": round(self._часы(), 1),
                 "прошлый_раз": False,
                 "уверенность": round(уверенность, 2)}
        self.метки.append(метка)
        if len(self.метки) > ПОМЕТОК_ПРЕДЕЛ:
            # Выбрасываем самую редко виденную, а не самую старую: стол,
            # увиденный тридцать раз, важнее вазы, замеченной однажды час
            # назад.
            self.метки.sort(key=lambda м: (м["раз"], м["когда"]))
            self.метки.pop(0)
        return метка

    def трудное_место(self, x: float, y: float, чем: str = "") -> dict | None:
        """Пометить место, где робот застревает. Тот же слой, свой класс."""
        for метка in self.метки:
            if метка["класс"] != "тупик":
                continue
            if math.hypot(x - метка["x"], y - метка["y"]) > ОДНА_ВЕЩЬ:
                continue
            метка["раз"] += 1
            метка["когда"] = round(self._часы(), 1)
            метка["прошлый_раз"] = False
            if чем:
                метка["чем"] = чем
            return метка
        метка = {"класс": "тупик", "x": round(x, 2), "y": round(y, 2),
                 "раз": 1, "когда": round(self._часы(), 1),
                 "прошлый_раз": False, "чем": чем}
        self.метки.append(метка)
        return метка

    # --- привязка --------------------------------------------------------
    def привязаться(self, видно_сейчас) -> tuple | None:
        """Понять, где робот стоит относительно вчерашней карты.

        `видно_сейчас` — {класс: (x, y)} в НЫНЕШНЕЙ системе координат.

        Робот включился носом куда попало, и его нынешний ноль не имеет
        отношения к вчерашнему. Пока это так, вся сохранённая карта —
        бесполезная груда чисел: наложить её на сегодняшний день нельзя,
        а наложить неверно — хуже, чем не накладывать.

        Лечится единственным доступным способом: узнать знакомые предметы.
        Увидел стол и холодильник, помнит, где они стояли, — и этого хватает,
        чтобы вычислить и сдвиг, и поворот (см. совместить). Так делают все,
        у кого нет ни лидара, ни маяков.

        Пары ищем только по ОДНОЗНАЧНЫМ классам — тем, что встречаются по
        одному разу и в памяти, и в поле зрения. Стульев в квартире четыре, и
        какой из них какой, мы не знаем; стол, холодильник и диван обычно по
        одному, и вот они и служат ориентирами. Гадать, какой стул с каким
        совпал, значит однажды привязаться наизнанку — а неверная привязка
        портит карту молча и навсегда.
        """
        старые: dict[str, list] = {}
        for метка in self.метки:
            if not метка.get("прошлый_раз") or метка["класс"] == "тупик":
                continue
            старые.setdefault(метка["класс"], []).append(
                (метка["x"], метка["y"]))
        # Что видно сейчас — тоже списком на класс, а не по одному месту:
        # четыре стула больше не повод выбросить стулья из рассмотрения.
        вижу: dict[str, list] = {}
        for класс, где in видно_сейчас.items():
            вижу[класс] = list(где) if isinstance(где, list) else [где]
        найдено, пары = подобрать(старые, вижу)
        if найдено is None:
            log.info("карта: не привязался — помню %d ориентиров, вижу %d, "
                     "согласованного решения нет",
                     sum(len(с) for с in старые.values()),
                     sum(len(с) for с in вижу.values()))
            return None
        сдвиг_x, сдвиг_y, поворот, невязка = найдено
        # Переносим ВСЮ старую карту в нынешние координаты — и мебель, и
        # трудные места. Тупики переносятся тоже: «здесь я застреваю» ценно
        # ровно тем, что показывает место, а без привязки места нет.
        for метка in self.метки:
            if not метка.get("прошлый_раз"):
                continue
            метка["x"], метка["y"] = перенести((метка["x"], метка["y"]),
                                               найдено)
            метка["прошлый_раз"] = False
        self._схлопнуть()
        self._с_прошлого_раза = 0
        log.info("карта: привязался по %d ориентирам, сдвиг (%.2f, %.2f), "
                 "поворот %.0f°, расхождение %.2f м — вчерашняя карта снова "
                 "моя", len(пары), сдвиг_x, сдвиг_y,
                 math.degrees(поворот), невязка)
        return найдено

    def привязаться_чем_вижу(self) -> tuple | None:
        """Попробовать привязаться по мебели, уже замеченной в этот запуск.

        ЭТОГО ЗВЕНА НЕ БЫЛО, и без него вся постоянная карта не работала.
        Метод привязаться() был написан, покрыт проверками — и НЕ ЗВАЛСЯ
        НИОТКУДА. А в app.py стояло `привязан = not пометки.с_прошлого_раза`:
        то есть первый запуск копил карту (сравнивать не с чем, портить
        нечего), а начиная со ВТОРОГО — не копил уже никогда, потому что
        сбросить `с_прошлого_раза` может только удавшаяся привязка.

        Игорь это и увидел: «карту не сохраняет, каждый раз заново рисует».
        Карта копилась ровно один запуск в жизни файла пометок.

        Что нужно привязке — «что я вижу прямо сейчас», {класс: (x, y)} в
        нынешних координатах. Строить это отдельно неоткуда и не надо: робот
        уже кладёт увиденное сюда же, в метки, и метка, увиденная своими
        глазами в этот запуск, помечена `прошлый_раз = False`. Берём их.

        ОТДАЁМ ВСЁ, ЧТО ВИДИМ, а не только однозначное. Здесь стоял отбор
        «класс, встреченный ровно один раз», и он выбрасывал ровно то, чего в
        квартире больше всего: четыре стула, две тумбочки, три полки. В живой
        комнате после такого отбора оставалось два-три предмета, и стоило
        одному не попасть в кадр — привязки нет, а значит карта не растёт
        вовсе. Разбираться, какой стул с каким, теперь умеет `подобрать`:
        перебором с проверкой, а не отказом от неоднозначного.
        """
        if not self._с_прошлого_раза:
            return None
        где: dict[str, list] = {}
        for метка in self.метки:
            if метка.get("прошлый_раз") or метка["класс"] == "тупик":
                continue
            где.setdefault(метка["класс"], []).append(
                (метка["x"], метка["y"]))
        # Порог здесь — САМЫЙ МЯГКИЙ ИЗ ВОЗМОЖНЫХ: сколько нужно на самом
        # деле, решает `подобрать`, и решает по-разному. Двух однозначных
        # предметов ей хватит, двух стульев из четырёх — нет. Ставить тут своё
        # число значило бы завести второе мнение о том же вопросе, и однажды
        # оно разошлось бы с первым.
        if sum(len(с) for с in где.values()) < ПАР_ДЛЯ_ПРИВЯЗКИ:
            return None
        return self.привязаться(где)

    def чего_не_хватает_для_привязки(self) -> str:
        """Почему ещё не привязались — словами, для пульта и журнала.

        Пустая строка — привязываться не надо, координаты и так наши.

        Молчать тут нельзя. Робот, который не копит карту, снаружи
        неотличим от робота, который копит и теряет; человек видит пустую
        панель и решает, что сломано. Сказать «узнаю стол, жду второй
        предмет» — значит объяснить, что делать: показать роботу комнату.
        """
        if not self._с_прошлого_раза:
            return ""
        вижу = sum(1 for метка in self.метки
                   if not метка.get("прошлый_раз")
                   and метка["класс"] != "тупик")
        return (f"не узнаю квартиру: помню {self._с_прошлого_раза} пометок с "
                f"прошлого раза, а сейчас вижу {вижу} "
                f"(нужно {ИНЛАЙЕРОВ_ХВАТИТ} совпавших). "
                f"Покажи мне комнату — проедься по ней")

    def _схлопнуть(self) -> None:
        """Слить пометки, совпавшие после переноса.

        Пока робот не привязан, он ставит новые пометки в своей нынешней
        системе, а старые лежат во вчерашней — и это два разных стола. После
        привязки они оказываются в одной системе и на одном месте, но так и
        останутся двумя, если их не слить: пометки сливаются в момент
        постановки, а тут они уже стоят.

        Двойники не просто занимают место. Привязка ищет предметы,
        встречающиеся ПО ОДНОМУ разу, и раздвоившийся холодильник перестаёт
        быть ориентиром — робот больше не привяжется никогда.
        """
        слитые: list[dict] = []
        for метка in sorted(self.метки, key=lambda м: -м["раз"]):
            для_него = None
            for готовая in слитые:
                if готовая["класс"] != метка["класс"]:
                    continue
                if math.hypot(метка["x"] - готовая["x"],
                              метка["y"] - готовая["y"]) <= ОДНА_ВЕЩЬ:
                    для_него = готовая
                    break
            if для_него is None:
                слитые.append(метка)
                continue
            всего = для_него["раз"] + метка["раз"]
            доля = метка["раз"] / всего
            для_него["x"] += (метка["x"] - для_него["x"]) * доля
            для_него["y"] += (метка["y"] - для_него["y"]) * доля
            для_него["раз"] = всего
            для_него["когда"] = max(для_него["когда"], метка["когда"])
        self.метки = слитые

    # --- чтение ----------------------------------------------------------
    def надёжные(self, включая_прошлый_раз: bool = False):
        """Пометки, которым можно верить: виденные не один раз."""
        готово = []
        for метка in self.метки:
            if метка["раз"] < ВИДЕТЬ_РАЗ:
                continue
            if метка.get("прошлый_раз") and not включая_прошлый_раз:
                continue
            готово.append(метка)
        готово.sort(key=lambda м: -м["раз"])
        return готово

    def вокруг(self, поза, дальше: float = 4.0):
        """Что рядом с роботом: список (класс, метры, угол в радианах).

        Угол — от текущего направления робота, влево положительный, как у
        всего остального в этом роботе.
        """
        если_нет: list[tuple[str, float, float]] = []
        if поза_плоха(поза):
            return если_нет
        рx, рy, курс = поза
        рядом = []
        for метка in self.надёжные():
            дx, дy = метка["x"] - рx, метка["y"] - рy
            до = math.hypot(дx, дy)
            if до > дальше:
                continue
            угол = math.atan2(дy, дx) - курс
            угол = (угол + math.pi) % (2 * math.pi) - math.pi
            рядом.append((метка["класс"], до, угол))
        рядом.sort(key=lambda п: п[1])
        return рядом

    def для_пульта(self) -> list[dict]:
        """Что показать на карте в пульте.

        ИМЯ ОТДАЁМ ГОТОВЫМ, по-русски, а не оставляем пульту переводить.
        В пульте лежала своя таблица «класс -> русское слово» — четвёртая
        копия того же справочника, и жила она хуже прочих: в ней было
        пятнадцать классов из восьмидесяти, так что шкаф, дверь и батарея
        нарисовались бы по-английски, а новый класс появлялся бы на карте
        английским словом до тех пор, пока кто-нибудь не вспомнит про
        html-файл. Ровно от этого расхождения мы и уходили, сводя таблицы
        в vocabulary; пульт был последним, кто держал свою.

        Тупик помечаем отдельно: «здесь я застреваю» — это не мебель, и
        рисовать его жёлтой точкой наравне со стулом значит прятать самое
        полезное, что есть на карте.
        """
        from . import things

        вышло = []
        for м in self.метки:
            класс = м["класс"]
            вышло.append({
                "класс": класс,
                "имя": "застреваю" if класс == "тупик"
                       else things.назвать(класс),
                "тупик": класс == "тупик",
                "x": м["x"], "y": м["y"],
                "раз": м["раз"], "старое": bool(м.get("прошлый_раз")),
            })
        return вышло

