"""Навыки: то, чему робот научился сам.

ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. У робота два слоя понимания. Правила (intents.py)
разбирают фразу на месте и зовут инструмент за двадцать пять миллисекунд —
без сети, без модели, надёжно. Модель делает всё остальное, но отвечает
секундами и стоит денег. Оба слоя умеют ровно то, что в них заложено.

И между ними дыра, которую видно на первой же непривычной просьбе. «Иди
исследуй квартиру» — правила такого не знают, отдельного инструмента нет.
Модель выкрутится один раз, а на второй будет выкручиваться заново: то же
время, те же деньги, и результат может выйти другим. Робот НЕ УМЕЕТ
ПРИОБРЕТАТЬ СОСТАВНЫЕ УМЕНИЯ — он выполняет, но не научается.

Правила при этом писать может только человек с редактором. Навыки — это тот
же слой правил, но пишет его робот.

ЧТО ТАКОЕ НАВЫК, И ПОЧЕМУ ЭТО БЕЗОПАСНО. Навык — НЕ НОВЫЙ КОД. Это
сохранённая последовательность вызовов тех же самых инструментов, что у
робота уже есть. Из этого следует главное: навык не может ничего, чего робот
не умеет одной командой. Все сторожа остаются на своих местах — дальномер
на ходу вперёд, карта памяти на слепые направления, обрыв, сторож мёртвой
руки. Модель здесь сочиняет сочетание, а не расширяет возможности.

Отсюда же и запреты. В навык нельзя класть:
  • сам навык — робот, переписывающий себя рекурсивно, это не то, что нужно
    в квартире с ребёнком;
  • «стоп» — бессмыслица: навык, который сам себя останавливает;
  • всё, что стирает без спроса (очистить список, снять все таймеры). Одна
    ошибка модели при сочинении — и оно повторяется при каждом вызове.

ЧТО ЭТО НЕ ЕСТЬ. Не обучение модели: веса никуда не двигаются, и завтра она
не станет умнее. Это процедурная память робота — список выученных рецептов,
который накапливается, показывается и чистится. Разница существенная, и
путать её не надо: у навыка нет обобщения. Выучил «обход квартиры» — не
значит понял, что такое обход.

И ЧЕГО НАВЫКИ НЕ ЗАМЕНЯТ. «Исследовать квартиру» по-настоящему — это помнить,
где уже был. У робота карта шесть на шесть метров, которая забывает за
полминуты, и одометрия, которая уплывает. Навык здесь даст «поездил змейкой
и рассказал, что видел», и это честно полезно, но планом квартиры не станет.
Для настоящего обхода нужна долгоживущая карта — работа отдельная и большая.
"""

from __future__ import annotations

import json
import logging
import re
import threading
import time
from pathlib import Path

log = logging.getLogger(__name__)

# Сколько навыков помним. Полсотни: больше человек всё равно не удержит в
# голове, а список, который нельзя дочитать, — это список, в который не
# смотрят.
ПРЕДЕЛ = 50

# Сколько шагов может быть в одном навыке. Восемь: каждый шаг — это целый
# инструмент, а маршрут внутри одного шага сам по себе до двенадцати колен и
# полутора минут. Длиннее — робот занят так долго, что человек успевает
# забыть, зачем просил.
ШАГОВ = 8

# Короче этого слова-зацепки не берём. «Иди» подошло бы к половине фраз в
# доме, и навык перехватывал бы чужие команды — причём молча, потому что до
# модели дело бы просто не дошло.
ЗАЦЕПКА_КОРОЧЕ_НЕЛЬЗЯ = 8

# Сколько срывов подряд терпим, прежде чем предложить забыть. Три: один — это
# случайность (человек передумал), два — совпадение, три — навык плохой.
СРЫВОВ_ХВАТИТ = 3

# Что можно класть в навык. Список белый, а не чёрный, и это принципиально:
# новый инструмент по умолчанию НЕ попадает в навыки, пока кто-то не подумал,
# что будет, если звать его вслепую по десять раз.
МОЖНО = frozenset({
    # движение — ради него всё и затевалось
    "drive", "turn", "route", "follow_me",
    # посмотреть и померить
    "look_around", "path_check", "battery",
    # сказать что-то по делу
    "time_now", "date_now", "weather", "news", "what_is_playing",
    "calculate", "convert_units", "random_pick", "look_up", "rates",
    # музыка и громкость
    "play_music", "stop_music", "music_next", "music_volume", "volume",
    # заметки и таймеры — только добавляющие
    "notes_add", "set_timer", "set_alarm", "set_reminder",
})

# Чего нельзя, с причинами. Держим отдельным списком не для проверки, а для
# чтения: белый список говорит «что», этот — «почему».
НЕЛЬЗЯ_ПОТОМУ_ЧТО = {
    "remember_skill": "навык, создающий навыки, — это робот, переписывающий себя",
    "forget_skill": "то же самое с другой стороны",
    "list_skills": "рассказ о себе внутри действия ничего не делает",
    "stop": "навык, который сам себя останавливает, бессмыслен",
    "hush": "то же самое",
    "notes_clear": "стирает без спроса, и повторяется при каждом вызове",
    "cancel_all_timers": "то же самое",
    "notes_remove": "то же самое",
    "cancel_timer": "то же самое",
}


def очистить(фраза: str) -> str:
    """Фраза → сравнимый вид: без знаков, без ё, без лишних пробелов."""
    ровно = re.sub(r"[^\w\s]", " ", (фраза or "").lower().replace("ё", "е"))
    return " ".join(ровно.split())


class Навык:
    def __init__(self, имя: str, зовут: list[str], шаги: list[dict],
                 создан: float = 0.0, звали: int = 0, сбоев: int = 0,
                 последний: float = 0.0) -> None:
        self.имя = имя
        self.зовут = зовут
        self.шаги = шаги
        self.создан = создан or time.time()
        self.звали = звали
        self.сбоев = сбоев
        self.последний = последний

    def как_словарь(self) -> dict:
        return {"имя": self.имя, "зовут": self.зовут, "шаги": self.шаги,
                "создан": self.создан, "звали": self.звали,
                "сбоев": self.сбоев, "последний": self.последний}

    def подходит(self, команда: str) -> bool:
        """Про этот ли навык сказали.

        Совпадение целиком или зацепка отдельными словами внутри фразы.
        Именно отдельными: без границ слов «дом» нашлось бы в «домофоне», и
        навык перехватывал бы фразы, к которым не имеет отношения.
        """
        ровно = очистить(команда)
        if not ровно:
            return False
        for зацепка in self.зовут:
            з = очистить(зацепка)
            if len(з) < ЗАЦЕПКА_КОРОЧЕ_НЕЛЬЗЯ:
                continue
            if ровно == з or re.search(rf"(?:^|\s){re.escape(з)}(?:\s|$)", ровно):
                return True
        return False


class Навыки:
    """Всё, чему робот научился. Живёт в JSON и переживает перезапуск."""

    def __init__(self, store: Path | None = None) -> None:
        self._список: list[Навык] = []
        self._замок = threading.Lock()
        self.store = store
        self._прочитать()

    # --- чтение и запись -------------------------------------------------
    def _прочитать(self) -> None:
        if not self.store:
            return
        try:
            данные = json.loads(self.store.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return
        for запись in данные if isinstance(данные, list) else []:
            try:
                self._список.append(Навык(
                    имя=str(запись["имя"]),
                    зовут=[str(з) for з in запись["зовут"]],
                    шаги=list(запись["шаги"]),
                    создан=float(запись.get("создан") or 0),
                    звали=int(запись.get("звали") or 0),
                    сбоев=int(запись.get("сбоев") or 0),
                    последний=float(запись.get("последний") or 0)))
            except (KeyError, TypeError, ValueError):
                # Битую запись пропускаем, но не роняем остальные: файл
                # правит и человек тоже.
                log.warning("навыки: непонятная запись пропущена")
        log.info("навыков помню: %d", len(self._список))

    def _записать(self) -> None:
        if not self.store:
            return
        try:
            self.store.parent.mkdir(parents=True, exist_ok=True)
            врем = self.store.with_name(self.store.name + ".tmp")
            врем.write_text(json.dumps([н.как_словарь() for н in self._список],
                                       ensure_ascii=False, indent=1),
                            encoding="utf-8")
            врем.replace(self.store)
        except OSError as e:
            log.warning("навыки: не смог записать (%s)", e)

    # --- наружу ----------------------------------------------------------
    @property
    def все(self) -> list[Навык]:
        with self._замок:
            return list(self._список)

    def проверить(self, шаги) -> str:
        """Годятся ли шаги для навыка. Пусто — годятся, иначе причина.

        Причину возвращаем словами: её услышит модель и сможет поправиться,
        а не будет вслепую повторять то же самое.
        """
        if not isinstance(шаги, list) or not шаги:
            return "в навыке нет ни одного шага"
        if len(шаги) > ШАГОВ:
            return f"шагов больше {ШАГОВ} — это уже не навык, а программа"
        for шаг in шаги:
            if not isinstance(шаг, dict):
                return "шаг должен быть словарём с инструментом и доводами"
            имя = str(шаг.get("инструмент") or шаг.get("tool") or "").strip()
            if not имя:
                return "в шаге не назван инструмент"
            если_нельзя = НЕЛЬЗЯ_ПОТОМУ_ЧТО.get(имя)
            if если_нельзя:
                return f"{имя} в навык класть нельзя: {если_нельзя}"
            if имя not in МОЖНО:
                return (f"{имя} в навыки не пускают — можно только то, что "
                        "робот делает по одной команде и безопасно повторять")
            доводы = шаг.get("аргументы", шаг.get("args", {}))
            if not isinstance(доводы, dict):
                return f"доводы шага {имя} должны быть словарём"
        return ""

    def запомнить(self, имя: str, зовут: list[str], шаги: list[dict]) -> str:
        """Сохранить навык. Пусто — сохранили, иначе причина отказа."""
        имя = (имя or "").strip()
        if not имя:
            return "у навыка нет имени"
        годные = [з for з in (зовут or [])
                  if len(очистить(з)) >= ЗАЦЕПКА_КОРОЧЕ_НЕЛЬЗЯ]
        if not годные:
            return ("слова-зацепки слишком короткие: по одному слову навык "
                    "перехватывал бы чужие команды")
        беда = self.проверить(шаги)
        if беда:
            return беда

        with self._замок:
            # Тем же именем — заменяем. Робот, у которого два «обхода
            # квартиры», выберет случайный, и человек не поймёт, почему
            # сегодня иначе.
            self._список = [н for н in self._список
                            if очистить(н.имя) != очистить(имя)]
            if len(self._список) >= ПРЕДЕЛ:
                # Выбрасываем самый забытый: тот, которого дольше всех не
                # звали. Не самый старый — старый и любимый нужнее нового и
                # ненужного.
                self._список.sort(key=lambda н: н.последний or н.создан)
                self._список.pop(0)
            self._список.append(Навык(имя, годные, list(шаги)))
            self._записать()
        log.info("запомнил навык «%s» (%d шагов, зовут: %s)",
                 имя, len(шаги), ", ".join(годные))
        return ""

    def забыть(self, имя: str) -> str | None:
        """Убрать навык. Возвращает убранное имя или None."""
        ровно = очистить(имя)
        with self._замок:
            для_удаления = [н for н in self._список
                            if очистить(н.имя) == ровно or н.подходит(имя)]
            if not для_удаления:
                return None
            убрали = для_удаления[0]
            self._список.remove(убрали)
            self._записать()
        log.info("забыл навык «%s»", убрали.имя)
        return убрали.имя

    def найти(self, команда: str) -> Навык | None:
        """Какой навык просят. None — ни один не подходит.

        При нескольких подходящих берём тот, у кого зацепка ДЛИННЕЕ: она
        точнее. Иначе «обход» перехватывал бы «обход квартиры сверху вниз».
        """
        with self._замок:
            подошли = [н for н in self._список if н.подходит(команда)]
        if not подошли:
            return None
        подошли.sort(key=lambda н: max(len(очистить(з)) for з in н.зовут),
                     reverse=True)
        return подошли[0]

    def отметить(self, навык: Навык, сорвался: bool) -> bool:
        """Записать, чем кончился вызов. True — пора предложить забыть."""
        with self._замок:
            навык.звали += 1
            навык.последний = time.time()
            навык.сбоев = навык.сбоев + 1 if сорвался else 0
            надо = навык.сбоев >= СРЫВОВ_ХВАТИТ
            self._записать()
        if надо:
            log.warning("навык «%s» сорвался %d раза подряд",
                        навык.имя, навык.сбоев)
        return надо
