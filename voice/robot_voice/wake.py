"""Ловля имени робота в непрерывном потоке звука.

Как было. Звук резался на фразы по паузам, каждая фраза уезжала в полное
распознавание, и уже в тексте искалось «Кузя». В тихой комнате это работает, а
в живой — нет: паузы не случается, кусок растёт до предела длины, и робот
отзывается через столько секунд, сколько этот предел. Со стороны выглядит как
глухота, хотя слышно всё. Плюс любая музыка ломала нарезку.

Как надо, и как устроены все настоящие ассистенты. Отдельный дешёвый детектор
крутится на сыром потоке непрерывно: он не режет фраз, не ждёт пауз и не
распознаёт речь — только слушает, не прозвучало ли имя. Услышал — открывается
окно записи команды, и вот ТУТ уже нужен детектор пауз, но только чтобы
понять, где команда кончилась. В полное распознавание уходит одна команда, а
не двадцать секунд комнаты.

Внутри — Vosk с суженным до имени словарём. Русский у него родной, обучать
ничего не надо, модель `small-ru` весит около сорока мегабайт и тянет поток в
реальном времени на A55. Сужение словаря — это и есть режим ключевого слова:
распознавателю незачем знать все слова языка, когда ищется одно.

Сверху лежит нечёткое сравнение — то же самое, которым раньше искали имя в
тексте. Оно нужно и здесь: распознавание пишет имя по-разному, и «Кузь»,
«Куся», «Хузя» должны считаться обращением.
"""

from __future__ import annotations

import difflib
import json
import logging
from pathlib import Path

log = logging.getLogger(__name__)


def clean_token(token: str) -> str:
    return token.lower().replace("ё", "е").strip(" ,.!?…—-\"'()")


def sounds_like_wake(token: str, wake_words: tuple[str, ...], ratio: float,
                     канон: tuple[str, ...] = ()) -> bool:
    """Похоже ли слово на имя робота.

    Распознавание пишет имя по-разному — «Кузя», «Кузь», «Куся», — поэтому
    сравниваем нестрого. Порог держим высоким: имя короткое, а на четырёх
    буквах послабление начинает ловить всё подряд.

    НЕЧЁТКО СРАВНИВАЕМ ТОЛЬКО С НАСТОЯЩИМ ИМЕНЕМ, а не со всем списком, и вот
    почему. В списке лежат и само имя, и его ОШИБКИ РАСПОЗНАВАНИЯ: «кузь»,
    «куся», «кузи». Нечёткое сравнение, применённое и к ним, сравнивает
    нестрого с уже нестрогой целью — послабление умножается на послабление.

    Померено на списке («кузя», «кузь», «куся», «кузи», «кузьма») и пороге
    0.75, на котором он и настроен:

        было — своих узнаём 13 из 14, чужих ловим 13 из 28
        стало — своих узнаём 13 из 14, чужих ловим  4 из 28

    Ни одного своего варианта не потеряно, ложных срабатываний втрое меньше.
    Уходят ровно те, что притянуты через ошибки: «курс» отстоит на 0.75 от
    «куся», «купи» — от «кузи», «кус» и «куск» — оттуда же. Это обычные слова,
    и в комнате с телевизором они звучат постоянно.

    Настройка в config обещала «чистый зазор» между 0.67 и 0.75 и мерила его
    ПО ОДНОМУ «кузя» — а применяется порог ко всем пяти. Примеры в том
    комментарии верны («куда» 0.60, «кухня» 0.67), вывод из них — нет.

    Точное совпадение и начало слова по-прежнему идут по ВСЕМУ списку: на них
    держатся «кузьку» и «кузьмич», и они ничего лишнего не притягивают.

    Пустой `канон` значит «нечётко сравнивай со всем списком» — так зовут
    старые проверки, и так это работало раньше.
    """
    if not token:
        return False
    for wake in wake_words:
        if token == wake or token.startswith(wake):
            return True
    for wake in (канон or wake_words):
        if difflib.SequenceMatcher(None, token, wake).ratio() >= ratio:
            return True
    return False


# Короткие команды, которые незачем гонять на ПК. Слово услышано прямо здесь,
# на роботе, и действие происходит через доли секунды вместо двух с лишним:
# запись команды, отправка по сети, распознавание, ответ. Для «стоп» эта
# разница — метр проезда, и она единственная, ради которой всё затевалось.
#
# Справа — то, что понимают правила разбора. Отдаём им готовую фразу, а не
# заводим второй набор действий: один разбор надёжнее двух согласованных.
# Здесь ТОЛЬКО срочное, и это главная защита от ложных срабатываний.
# Словарь у детектора узкий, и Vosk обязан впихнуть в него любой звук: слова
# «что ты ВИдишь» он услышал как «ТИше» и убавил громкость вместо ответа —
# три раза подряд на живом роботе. Чем меньше слов, тем реже такое.
#
# Правило отбора простое: попадает то, где ложное срабатывание безобидно, а
# опоздание — нет. Ложный «стоп» стоящему роботу не стоит ничего, он ответит
# «я и так стою»; опоздавший «стоп» едущему стоит лишнего метра. А вот
# «тише» и «следующая» никакой срочности не имеют вовсе — лишняя секунда
# там не заметна, зато ложное срабатывание сбивает разговор и заставляет
# человека повторять вопрос.
МГНОВЕННЫЕ = {
    "стоп": "стоп",
    "стой": "стоп",
    "хватит": "стоп",
    "замолчи": "замолчи",
}

# Слова, которыми человек перебивает ГОВОРЯЩЕГО робота. Список шире
# мгновенных приказов: там речь о едущем роботе, где цена ложного стопа
# высока, а здесь — о болтающем, и худшее, что случится, это оборванная на
# полуслове реплика. Перебить хочется именно тогда, когда робот завёл длинный
# рассказ, и требовать в этот момент точной формулировки — издевательство.
# Значение — ЧТО именно человек просит прекратить, и различие тут не
# косметическое. «Ясно» и «понял» просят замолчать: человек услышал
# достаточно. А «стоп» и «стой», сказанные ЕДУЩЕМУ роботу, просят остановить
# КОЛЁСА, и остановить их важнее, чем речь.
#
# Раньше все эти слова вели к одному — hush, то есть к молчанию. Робот, едущий
# и говорящий одновременно, на крик «стоп» послушно замолкал и ЕХАЛ ДАЛЬШЕ:
# микрофон в это время заглушён, обычный путь команды закрыт, а перебивание
# колёс не касалось. Дыру завёл я сам вместе с перебиванием, поэтому и
# закрываю здесь.
ПЕРЕБИВАНИЕ = {
    "стоп": "колёса",
    "стой": "колёса",
    "стоять": "колёса",
    "хватит": "колёса",
    "замолчи": "молчи",
    "молчи": "молчи",
    "тихо": "молчи",
    "погоди": "колёса",
    "подожди": "колёса",
    "всё": "молчи",
    "понял": "молчи",
    "ясно": "молчи",
}


class Spotter:
    """Детектор имени на потоке. Кормится теми же кадрами, что и нарезка."""

    def __init__(self, model_dir: Path, wake_words: tuple[str, ...],
                 sample_rate: int = 16000, ratio: float = 0.8,
                 full_vocab: bool = False, канон: tuple[str, ...] = ()) -> None:
        from vosk import KaldiRecognizer, Model, SetLogLevel

        SetLogLevel(-1)          # иначе Kaldi засыпает журнал своей отладкой
        self.wake_words = wake_words
        # Настоящие имена — с ними и только с ними сравниваем нестрого.
        # Пусто — со всем списком, как было. См. sounds_like_wake.
        self.канон = канон
        self.ratio = ratio
        self.sample_rate = sample_rate
        # Модель храним: она весит десятки мегабайт и грузится секундами, а
        # распознавателей от неё нужно два — обычный и для перебивания.
        self.model = model = Model(str(model_dir))
        if full_vocab:
            # Полный словарь: дороже по процессору, но берёт имя, которого нет
            # в лексиконе модели. «Кузя» — имя собственное, и в маленькой
            # модели его может не оказаться вовсе; тогда суженный словарь не
            # сработает никогда, а полный — вытащит через нечёткое сравнение.
            self._rec = KaldiRecognizer(model, sample_rate)
        else:
            грамматика = json.dumps(
                list(wake_words) + list(МГНОВЕННЫЕ) + ["[unk]"],
                ensure_ascii=False)
            self._rec = KaldiRecognizer(model, sample_rate, грамматика)

    def слух_для_перебивания(self):
        """Отдельный распознаватель, слышащий только слова перебивания.

        Отдельный, а не тот же самый, и это принципиально: пока робот говорит,
        основной распознаватель обязан молчать (иначе робот услышит собственное
        имя в своей же реплике и позовёт сам себя). А этот слушает ровно в то
        время, когда основной глух, и знает всего десяток слов.

        Словарь суженный намеренно. Полный словарь на говорящем роботе — это
        распознавание собственного голоса во весь опор: и процессор, и поток
        ложных срабатываний. Десять слов плюс «[unk]» дают вознице сказать
        «это не из моего словаря» вместо того, чтобы притянуть шум к ближайшему
        известному слову.
        """
        from vosk import KaldiRecognizer

        грамматика = json.dumps(list(ПЕРЕБИВАНИЕ) + ["[unk]"],
                                ensure_ascii=False)
        return KaldiRecognizer(self.model, self.sample_rate, грамматика)

    def сбросить(self) -> None:
        """Забыть накопленное — после срабатывания и после своей же речи."""
        self._rec.Reset()

    def услышал(self, frame: bytes) -> bool:
        """Прозвучало ли имя. Кадр — те же 20 мс, что и у нарезки.

        Смотрим ЧАСТИЧНЫЙ результат, а не окончательный: окончательный Vosk
        отдаёт по концу реплики, то есть опять по паузе — ровно то, от чего мы
        здесь уходим. Частичный обновляется по мере слов, и имя видно сразу
        после того, как оно договорено.
        """
        if self._rec.AcceptWaveform(frame):
            текст = json.loads(self._rec.Result()).get("text", "")
        else:
            текст = json.loads(self._rec.PartialResult()).get("partial", "")
        if not текст:
            return False
        for слово in текст.split():
            if sounds_like_wake(clean_token(слово), self.wake_words,
                                self.ratio, self.канон):
                self.сбросить()
                return True
        return False

    def команда(self, frame: bytes) -> str:
        """Короткая команда сразу за именем — уже готовой для правил фразой.

        Зовётся только после того, как имя услышано. Смысл ровно один: не
        гонять «стоп» на ПК. Полный путь — запись до паузы, отправка по сети,
        распознавание, разбор — это две с лишним секунды, а на «стоп» это
        лишний метр проезда. Здесь то же слово срабатывает за доли секунды.

        Сравниваем точно, а не нестрого, как имя. Имени послабление нужно —
        его коверкают и распознавание, и сам говорящий. А вот «стоп»,
        опознанный нестрого в чужом слове, остановит робота посреди дела, и
        цена такой ошибки выше выигрыша.
        """
        if self._rec.AcceptWaveform(frame):
            текст = json.loads(self._rec.Result()).get("text", "")
        else:
            текст = json.loads(self._rec.PartialResult()).get("partial", "")
        for слово in текст.split():
            приказ = МГНОВЕННЫЕ.get(clean_token(слово))
            if приказ:
                self.сбросить()
                return приказ
        return ""


def make_spotter(cfg) -> "Spotter | None":
    """Собрать детектор или честно сказать, почему не вышло.

    None — это не поломка, а откат на прежний способ: резать по паузам и
    искать имя в тексте. Он хуже, но работает, поэтому отсутствие модели не
    повод не запускаться. А вот молчать об этом нельзя: разница в поведении
    видна сразу, и человек должен знать, какой из двух режимов у него сейчас.
    """
    if cfg.wake_engine != "vosk":
        log.info("ловля имени на потоке выключена — режу по паузам, "
                 "имя ищу в тексте")
        return None
    if not cfg.wake_words:
        log.warning("имя робота не задано — ловить нечего")
        return None
    model_dir = Path(cfg.wake_model).expanduser()
    if not model_dir.is_dir():
        log.error("нет модели для ловли имени: %s. Робот будет слышать хуже — "
                  "резать по паузам и искать имя в тексте. Как поставить — "
                  "см. voice/README.md", model_dir)
        return None
    try:
        spotter = Spotter(model_dir, cfg.wake_words, cfg.sample_rate,
                          cfg.wake_ratio, cfg.wake_full_vocab,
                          tuple(и for и in getattr(cfg, "wake_canon", ())
                                if и in cfg.wake_words))
    except ImportError:
        log.error("библиотека vosk не установлена — режу по паузам. "
                  "Поставить: voice/.venv/bin/pip install vosk")
        return None
    except Exception:
        log.exception("не смог поднять ловлю имени — режу по паузам")
        return None
    log.info("ловлю имя «%s» прямо в потоке, словарь %s",
             cfg.wake_words[0], "полный" if cfg.wake_full_vocab else "суженный")
    return spotter
