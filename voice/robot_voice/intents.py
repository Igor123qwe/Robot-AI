def numerals_to_digits(text: str) -> str:
    """«сорок пять минут» → «45 минут». Составные числа складываются.

    Так все правила ниже работают с цифрами, и их не приходится дублировать
    под словесную запись.
    """
    out: list[str] = []
    total = 0.0          # то, что набрано после последнего множителя
    итог = 0.0           # то, что уже умножено на тысячи
    started = False

    def flush() -> None:
        nonlocal total, итог, started
        if started:
            число = итог + total
            # Целое пишем целым. Через %g миллион выходит как «1e+06», и такое
            # ни одно правило ниже уже не разберёт — а виновата была бы запись,
            # а не разбор. Дробные бывают только от «полутора».
            out.append(str(int(число)) if число == int(число) else f"{число:g}")
            total, итог, started = 0.0, 0.0, False

    for word in text.split():
        множитель = _NUM_SCALE.get(word)
        if множитель is not None:
            if total == 0 and итог:
                # Множитель сразу за множителем умножает всё набранное:
                # «тысяча тысяч» — это миллион, а не две тысячи.
                итог *= множитель
            else:
                # «две тысячи» — 2 × 1000, «тысяча» без числа — просто 1000.
                итог += (total or 1) * множитель
            total, started = 0.0, True
            continue
        value = _NUM_WORDS.get(word)
        if value is None:
            flush()
            out.append(word)
        else:
            # «сорок пять» складываем, «пять пять» — нет: второе начинает новое
            # число. С тысячами так же: в «две тысячи триста» тройка меньше
            # набранного, значит она продолжение, а не начало нового числа.
            if started and total and value >= total:
                flush()
            total += value
            started = True
    flush()
    return " ".join(out)


