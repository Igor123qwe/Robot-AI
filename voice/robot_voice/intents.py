def _video(t: str) -> Match | None:
    if _VIDEO_PAUSE.match(t):
        return Match("video_pause", {}, "пауза видео")
    if _VIDEO_RESUME.match(t):
        return Match("video_resume", {}, "продолжить видео")
    if _VIDEO_NEXT.match(t):
        return Match("video_next", {}, "следующий мультик")
    if _VIDEO_STOP.match(t):
        return Match("video_stop", {}, "вернуть аватар")
    # Включение — ПОСЛЕ управления: «включи другой мультик» — это «дальше»,
