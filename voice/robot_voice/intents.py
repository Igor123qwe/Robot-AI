    _birthday,
    # Погода и часы — раньше зова и поиска: «скажи, который час» и «скажи
    # погоду» — вопросы, а не просьба искать человека по имени «который».
    # Обе проверяются целой фразой и чужого не перехватят.
    _weather, _clock,
