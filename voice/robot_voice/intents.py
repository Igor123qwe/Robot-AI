def _where(t: str) -> Match | None:
    m = _WHERE_WE_ARE.match(t)
    if m is None:
        return None
    город = next(g for g in m.groups() if g)
    if город in _НЕ_ГОРОД:
        # «Я в порядке» — не переезд. Пусть отвечает модель.
        return None
    return Match("set_home", {"город": город}, "где мы")


