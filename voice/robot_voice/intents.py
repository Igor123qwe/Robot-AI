def _cancel_timers(t: str) -> Match | None:
    # Место в команде («все таймеры на кухне») пропускаем: таймеры у робота
    # общие, комнат он не различает. Отказываться понимать фразу из-за этого
    # глупо — человек всё равно имеет в виду «сними все».
    if re.fullmatch(
        rf"{_PREFIX}{_TIMER_CANCEL}\s+(?:{_PLACE}\s+)?все\s+"
        rf"(?:таймер\w+|будильник\w+|напоминани\w+)"
        rf"(?:\s+{_PLACE})?",
        t,
    ):
        return Match("cancel_all_timers", {}, "снять все таймеры")

    # «отмени таймер чай», «выключи таймер на 5 минут», «удали таймер»
    m = re.fullmatch(
        rf"{_PREFIX}{_TIMER_CANCEL}\s+таймер\w*\s*"
        rf"(?:(?:на\s*)?{_DURATION}|([а-я][а-я -]{{0,20}}))?",
        t.strip(),
    )
    if not m:
        return None

    duration, label = m.group(1), (m.group(2) or "").strip()
    if duration:
        # Таймер называют по длительности: «отмени таймер на пять минут».
        # Имя приводим к той же словесной форме, которой робот сам назвал
        # второй безымянный таймер. Раньше сюда уходило «10 минут» цифрами, а
        # в хранилище лежало «десять минут» — совпасть они не могли никогда, и
        # робот на «отмени таймер на десять минут» переспрашивал, перечисляя
        # ровно тот таймер, который у него просили снять.
        return Match("cancel_timer",
                     {"label": ru.duration(_duration_minutes(duration) * 60)},
                     "снять таймер по времени")
    if not label:
        # «Отмени таймер» без уточнения: если он один — снимаем, если их
        # несколько — инструмент переспросит. Снимать все по такой фразе
        # нельзя, это потеря чужого таймера.
        return Match("cancel_timer", {}, "снять таймер")
    return Match("cancel_timer", {"label": label}, "снять таймер")


def _pause_timers(t: str) -> Match | None:
    # «останови таймер» сюда намеренно не входит: Home Assistant понимает это
    # как паузу, но живому роботу так говорят, когда таймер больше не нужен.
    # Пауза — только там, где о ней сказано прямо.
    m = re.fullmatch(
        rf"{_PREFIX}(?:приостанови\w*|пауза|поставь\s+на\s+паузу)\s+"
        rf"таймер\w*(?:\s+([а-я][а-я -]{{0,20}}))?|"
        rf"{_PREFIX}(?:постав(?:ь|ить)\s+)?таймер\w*\s*([а-я][а-я -]{{0,20}}?)?"
        rf"\s*на\s+паузу|"
        rf"{_PREFIX}пауза\s+таймера",
        t.strip(),
    )
    if m:
        label = (m.group(1) or m.group(2) or "").strip()
        return Match("pause_timer", {"label": label} if label else {}, "пауза таймера")

    m = re.fullmatch(
        rf"{_PREFIX}(?:возобнови\w*|продолжи\w*|запусти\s+заново)\s+"
        rf"таймер\w*(?:\s+([а-я][а-я -]{{0,20}}))?|"
        rf"{_PREFIX}сними\s+таймер\w*\s*([а-я][а-я -]{{0,20}}?)?\s*с\s+паузы",
        t.strip(),
    )
    if m:
        label = (m.group(1) or m.group(2) or "").strip()
        return Match("resume_timer", {"label": label} if label else {}, "продолжить таймер")
    return None


_WAKE_ME = r"(?:разбуд\w+|подним\w+\s+меня|буди)"
_ALARM_NOUN = r"будильник\w*"
_REMIND = r"(?:напомн\w+|напоминай)"
# «через 20 минут» — точно срок. «на 20 минут» — тоже.
_THROUGH = re.compile(rf"через\s+{_DURATION}")
_FOR = re.compile(rf"(?:^|\s)на\s+{_DURATION}")


def _relative_minutes(t: str) -> float | None:
    """Срок в минутах, если он назван как промежуток, а не как время суток."""
    m = _THROUGH.search(t)
    if m:
        return _duration_minutes(m.group(1))
    m = _FOR.search(t)
    # «будильник на 8 часов» — это восемь утра, а не восемь часов ожидания:
    # так говорят про время суток. «на 20 минут» — однозначно срок.
    if m and not re.search(r"\bчас", m.group(1)):
        return _duration_minutes(m.group(1))
    return None


def _cancel_alarm(t: str) -> Match | None:
    """Снять будильник.

    Перенос («перенеси будильник на восемь») правилом не разбираем: там надо
    снять один и поставить другой, и ошибиться — значит не разбудить.
    Отдаём модели, она переспросит.
    """
    if not re.match(rf"{_PREFIX}{_TIMER_CANCEL}\b", t):
        return None
    if not re.search(rf"\b(?:{_ALARM_NOUN}|{_WAKE_ME})", t):
        return None
    # «Отмени ВСЕ будильники» — это не «отмени будильник». Снимался ровно
    # один, а человек был уверен, что снял оба, и просыпался по второму.
    if re.search(r"\bвсе\b", t):
        return Match("cancel_all_timers", {}, "снять все будильники")
    return Match("cancel_timer", {"label": "будильник"}, "снять будильник")


def _alarm(t: str) -> Match | None:
    """Будильник и напоминание: «разбуди в семь», «напомни в восемь позвонить»."""
    is_alarm = re.search(rf"\b{_WAKE_ME}", t) or re.search(rf"\b{_ALARM_NOUN}", t)
    is_remind = re.search(rf"\b{_REMIND}", t)
    if not is_alarm and not is_remind:
        return None
    # Фраза начинается с «напомни» — это напоминание, чем бы она ни
    # продолжалась. «Напомни в семь разбудить детей» уходило в будильник:
    # слово «разбудить» ловилось как просьба разбудить самого человека, и
    # текст напоминания терялся целиком.
    if is_remind and re.match(rf"{_PREFIX}{_REMIND}", t):
        is_alarm = None

    # «отмени будильник на семь», «перенеси будильник» — это не постановка.
    # Слово «будильник» ловилось где угодно во фразе, независимо от глагола,
    # и снятие оборачивалось новым будильником на то же время: человек
    # просил отменить подъём, а робот его подтверждал.
    if re.match(rf"{_PREFIX}(?:{_TIMER_CANCEL}|перенес\w+|перевед\w+|"
                rf"передвинь\w*|измени\w*)\b", t):
        return _cancel_alarm(t)

    minutes = _relative_minutes(t)
    at = None if minutes is not None else when.at_time(t)
    if minutes is None and at is None:
        return None      # «напомни мне позвонить маме» — когда? спросит модель

    if is_alarm:
        if at is None:
            # «поставь будильник через двадцать минут» — это тот же таймер.
            return Match("set_timer", {"minutes": minutes, "label": "будильник"},
                         "будильник через")
        # Дата целиком, а не время суток: «завтра» правило уже учло, а по
        # голому «07:00» инструмент разобрал бы заново и взял сегодняшнее.
        return Match("set_alarm", {"at": at.isoformat(timespec="minutes")}, "будильник")

    text = _reminder_text(t)
    if not text:
        return None      # напомнить-то о чём?
    args = {"text": text}
    if at is not None:
        args["at"] = at.isoformat(timespec="minutes")
    else:
        args["minutes"] = minutes
    return Match("set_reminder", args, "напоминание")


# Всё, что стоит между «напомни» и самим делом: «мне», «завтра», время.
_REMINDER_HEAD = re.compile(
    rf"^{_PREFIX}{_REMIND}\s*(?:мне\s+)?(?:завтра\s+)?"
    rf"(?:через\s+{_DURATION}|(?:в|на|к|во)\s+(?:\d{{1,2}}(?:[ .:-]+\d{{2}})?|час|полдень|полночь)"
    rf"\s*(?:час\w*)?\s*(?:утра|утром|дня|вечера|вечером|ночи|ночью)?)?\s*"
    rf"(?:завтра\s+)?(?:что\s+|чтобы\s+|чтоб\s+)?"
)


def _reminder_text(t: str) -> str:
    return _REMINDER_HEAD.sub("", t, count=1).strip(" ,.!?;:-")


def _abilities(t: str) -> Match | None:
    if re.fullmatch(
        rf"{_PREFIX}(?:"
        rf"что\s+(?:ты\s+)?(?:уме\w+|можешь(?:\s+делать)?)|"
        rf"(?:какие\s+)?тво\w+\s+(?:умения|возможности|функции)|"
        rf"на\s+что\s+ты\s+способен|"
        rf"расскажи\s+(?:мне\s+)?(?:о\s+себе|что\s+уме\w+)|"
        rf"кто\s+ты(?:\s+такой)?"
        rf")",
        t,
    ):
        return Match("abilities", {}, "что умею")
    return None


def _small_talk(t: str) -> Match | None:
    """«Привет», «как дела», «спасибо», «пока» — и всё это МГНОВЕННО.

    ЗАЧЕМ ПРАВИЛО НА ПРИВЕТСТВИЕ. Затем же, зачем оно на «что ты умеешь»:
    ответ известен заранее, и платить за него походом к модели незачем. Только
    здесь цена куда выше, и она посчитана в самом роботе (pc/kuzya_pc.py,
    DEFAULT_CTX): постоянная часть запроса — системный промпт плюс схемы
    инструментов — это около двенадцати тысяч символов, то есть примерно
    ЧЕТЫРЕ ТЫСЯЧИ ТОКЕНОВ ДО ТОГО, как человек сказал хоть слово. На «привет»
    модель сперва прожёвывает их все.

    Игорь: «я ему Кузя привет — он очень долго думает и говорит мне привет
    малыш дружит; раньше намного быстрее отвечал». Здесь обе беды сразу, и обе
    от одного: четыре тысячи токенов ждать долго, а на односложной реплике
    модели не за что зацепиться, кроме самого промпта, — вот она и вытаскивает
    из него обрывки. «Дружит» — очень похоже на кусок описания характера.

    ЧТО ЭТО ПРАВИЛО НЕ ДЕЛАЕТ, и это важнее того, что оно делает. Оно
    срабатывает ТОЛЬКО НА ЦЕЛУЮ ФРАЗУ (fullmatch), а не на начало. «Привет» —
    наше, «привет, а что там на кухне» — модели целиком. Иначе робот
    здоровался бы вместо ответа на вопрос, и это было бы хуже медленного
    ответа: медленный хотя бы верный.
    """
    # Имя впереди снимается выше по потоку, но не всегда: распознавание
    # слипает реплики, и «кузя привет» доезжает сюда целиком. Разрешаем.
    if re.fullmatch(
        rf"{_PREFIX}(?:кузя[,\s]+)?(?:"
        rf"привет(?:ик|ствую)?|здравствуй(?:те)?|здорово|здоров|салют|"
        rf"добр\w+\s+(?:утр\w+|день|дня|вечер\w*)|"
        rf"хай|ку|прив"
        rf")(?:\s+кузя)?",
        t,
    ):
        return Match("small_talk", {"вид": "привет"}, "поздоровались")
    if re.fullmatch(
        rf"{_PREFIX}(?:"
        # «что нового» сюда НЕ входит: это уже новости, и правило на них
        # стоит ниже. Перехватить его значило бы отобрать умение —
        # проверка это и поймала.
        rf"как\s+(?:у\s+тебя\s+)?дела(?:шки)?|как\s+ты|как\s+жизнь|"
        rf"как\s+сам|чё\s+как|как\s+настроение|ты\s+как"
        rf")",
        t,
    ):
        return Match("small_talk", {"вид": "как дела"}, "спросили как дела")
    if re.fullmatch(
        rf"{_PREFIX}(?:спасибо(?:\s+большое)?|благодарю|спасиб|"
        rf"молодец|умница|хорош|отлично)",
        t,
    ):
        return Match("small_talk", {"вид": "спасибо"}, "поблагодарили")
    if re.fullmatch(
        rf"{_PREFIX}(?:пока|до\s+свидания|до\s+встречи|прощай|бывай|"
        rf"спокойной\s+ночи|доброй\s+ночи|споки)",
        t,
    ):
        return Match("small_talk", {"вид": "пока"}, "попрощались")
    return None


def _voice_control(t: str) -> Match | None:
    """Громкость, «замолчи», «повтори» — то, что просят каждый день."""
    if re.fullmatch(
        rf"{_PREFIX}(?:замолчи|молчи|тихо|тишина|помолчи|хватит\s+(?:болтать|говорить)|"
        rf"перестань\s+говорить|заткнись)",
        t,
    ):
        return Match("hush", {}, "замолчи")

    m = re.fullmatch(
        rf"{_PREFIX}(?:говори\s+|сделай\s+|стань\s+|будь\s+|включи\s+)?"
        rf"(потише|тише|погромче|громче|обычн\w+\s+громкость\w*|"
        rf"нормальн\w+\s+громкость\w*)"
        rf"(?:\s+(?:говори|пожалуйста))?",
        t,
    )
    if m:
        word = m.group(1)
        if "громкость" in word:
            change = "обычная"
        else:
            change = "тише" if "тише" in word else "громче"
        # «Говори тише» — это про голос и только про голос. Голое «сделай
        # тише» под музыку человек говорит про музыку, и решает это уже
        # инструмент: он один знает, играет ли что-нибудь.
        про_голос = bool(re.search(r"\bговори", t))
        return Match("volume", {"change": change, "про_голос": про_голос},
                     "громкость голоса" if про_голос else "громкость")

    if re.fullmatch(
        rf"{_PREFIX}(?:повтори(?:\s+(?:еще\s+раз|пожалуйста))?|"
        rf"что\s+ты\s+сказал\w*|еще\s+раз|повтори\s+что\s+сказал)",
        t,
    ):
        return Match("repeat", {}, "повтори")
    return None


# «список», «в списке», «из списка» — корень плюс окончание.
# Уточнение «покупок»/«дел» — часть названия списка, а не первый пункт:
# «добавь в список покупок молоко» записывало пункт «покупок молоко».
# Новости. Спрашивают коротко и по-разному, а ответ один и тот же — правилу
# тут самое место: мгновенно, бесплатно и без риска, что модель начнёт
# пересказывать новости годичной давности из своей памяти.
_NEWS = re.compile(
    r"^(?:а\s+|ну\s+|давай\s+)*"
    r"(?:(?:расскажи|почитай|прочитай|зачитай|скажи)\s+(?:мне\s+)?)?"
    r"(?:(?:какие|что\s+за|какие-нибудь)\s+)?"
    r"(?:последние\s+)?(?:новост\w+|нового\s+в\s+мире)"
    r"(?:\s+(?:последние|в\s+мире|сегодня|дня|на\s+сегодня|были|есть))*$"
    r"|^(?:а\s+)?что\s+(?:там\s+)?нового(?:\s+в\s+мире)?$")


# Курс валют и музыка — самые частые бытовые просьбы после погоды и таймера.
_RATES = re.compile(
    r"^(?:а\s+|ну\s+)*(?:какой|каков|что\s+с|скажи|назови|узнай)?\s*"
    r"(?:(?:сейчас|сегодня)\s+)?"
    r"(?:курс\s+(?:доллара|евро|валют\w*|рубля)|"
    r"сколько\s+(?:стоит|сейчас|нынче)\s+доллар\w*|"
    r"доллар\s+сколько|почем\s+доллар\w*)"
    r"(?:\s+(?:сейчас|сегодня|нынче))?$")

# Жанры, которые называют без слова «музыка»: «включи джаз». Список короткий
# намеренно. Первая версия принимала за станцию всё подряд после «поставь» — и
# «поставь будильник на 18 часов» уехало включать радиостанцию «будильник на
# 18 часов». Всё, чего в списке нет, пусть разбирает модель: инструмент ей
# виден, и она позовёт его сама, если речь и правда о музыке.
_GENRE = (r"джаз\w*|рок|классик\w+|шансон|поп|рэп|хип-хоп|блюз|метал\w*|"
          r"электрон\w+|лаундж|ретро|транс|техно|диско|фонк|инструментал\w+")

_MUSIC_ON = re.compile(
    rf"^(?:а\s+|ну\s+|давай\s+)*(?:включи|поставь|запусти|врубай|врубить)\s+"
    rf"(?:мне\s+)?(?P<носитель>музык\w+|радио|песн\w+|станци\w+|"
    # «Включи группу Краски» правилами не разбиралось, уходило модели, а та,
    # наученная прошлыми отказами, отвечала «не найдено в моих источниках», не
    # вызвав инструмент ни разу. Живой вечер: Яндекс подключён и работает,
    # волна играет, а по названию — ничего.
    rf"групп\w+|исполнител\w+|альбом\w*|трек\w*|композици\w+|сингл\w*)"
    rf"(?:\s+(?P<уточнение>(?!на\s|в\s|под\s|за\s|с\s|до\s|по\s)"
    rf".{{2,40}}))?$"
    rf"|^(?:а\s+|ну\s+|давай\s+)*(?:включи|поставь|запусти|врубай)\s+"
    rf"(?:мне\s+)?(?P<жанр>{_GENRE})$"
    # «Моя волна» — то же «включи музыку», только словами Яндекса. Пустой
    # запрос и означает волну, поэтому уточнения здесь не бывает.
    rf"|^(?:а\s+|ну\s+|давай\s+)*(?:включи|поставь|запусти)\s+"
    rf"(?:мою\s+|свою\s+)?волну$"
    rf"|^(?:а\s+|ну\s+|давай\s+)*(?:включи|поставь)\s+что-нибудь"
    rf"(?:\s+(?:послушать|из\s+музыки|весел\w+|спокойн\w+))?$"
    # Голое имя: «включи Грота», «поставь Короля и Шута». Одно-три слова без
    # предлогов — предлог почти всегда означает не музыку, а комнату или
    # прибор: «включи свет в зале», «поставь чайник на плиту». Что это за имя,
    # решать не правилу: не нашлось — робот честно скажет.
    rf"|^(?:а\s+|ну\s+|давай\s+)*(?:включи|поставь|врубай)\s+"
    rf"(?P<имя>(?!в\s|на\s|под\s|за\s)[^\s]{{3,20}}"
    rf"(?:\s+(?!в\s|на\s|под\s|за\s)[^\s]{{1,20}}){{0,2}})$")

_MUSIC_OFF = re.compile(
    r"^(?:выключи|вырубай|вырубить|останови|убери|прекрати)\s+"
    r"(?:музык\w+|радио|песн\w+)$"
    r"|^(?:музык\w+|радио)\s+(?:выключи|стоп)$"
    # Голое «выключи» без дополнения. На живом роботе человек дважды сказал
    # его, имея в виду музыку, а модель дважды позвала остановку движения и
    # ответила «ты и так стоишь» — при играющей музыке. Что имелось в виду,
    # видно только по тому, играет ли что-нибудь, поэтому решает инструмент:
    # музыка есть — глушим её, нет — останавливаем колёса.
    r"|^(?:выключи|выключай|вырубай|вырубь)$")

# Громкость музыки. Отдельно от громкости голоса намеренно: под музыку
# «убавь» почти всегда про неё, а робот на живом доме понял это как «выключи»
# и оборвал песню. Что именно человек имел в виду, решает инструмент — он
# один знает, играет ли сейчас хоть что-нибудь.
_ЗВУК = r"(?:музык\w*|радио|звук|громкость|песн\w+|это|этот\s+звук)"
_ТИШЕ = r"убав\w+|потише|тише|уменьш\w+|приглуш\w+"
_ГРОМЧЕ = r"прибав\w+|погромче|громче|увелич\w+"

_MUSIC_LEVEL = re.compile(
    rf"^(?:а\s+|ну\s+|давай\s+|пожалуйста\s+)*(?:можешь\s+|можно\s+)?"
    rf"(?:сделай\s+|поставь\s+)?"
    rf"(?:({_ТИШЕ}|{_ГРОМЧЕ})\s+(?:мне\s+)?{_ЗВУК}"
    rf"|{_ЗВУК}\s+({_ТИШЕ}|{_ГРОМЧЕ}))"
    rf"(?:\s+пожалуйста)?$")

# Громкость числом: «сделай звук на семь», «убавь до двух», «громкость 3».
# Раньше это уходило модели, и она отвечала «звук уменьшен до двух», ничего не
# трогая: передать число было нечем. Числа словами тоже — вслух говорят «на
# семь», а не «на 7», и Whisper пишет как услышал.
# Числительных словами тут больше нет, и это не потеря: normalize() переводит
# их в цифры раньше, чем правила доберутся до текста. Раньше здесь лежало
# двадцать шесть ключей, из которых работали два — остальные не мог увидеть
# никто. Слова, которые в цифру не превращаются, остались.
_ЦИФРЫ = {"максимум": 10, "минимум": 1}
_ЧИСЛО = r"\d{1,2}|" + "|".join(sorted(_ЦИФРЫ, key=len, reverse=True))


def _число(слово: str) -> int:
    """«семь» и «7» — одно и то же. Вслух говорят словом, Whisper так и пишет."""
    слово = (слово or "").strip().lower()
    return int(слово) if слово.isdigit() else _ЦИФРЫ.get(слово, 0)

#   «до семи» — это куда поставить, «на два» после «убавь» — это насколько
#   подвинуть. Разница живая: «убавь до двух» и «убавь на два» с громкости
#   восемь дают четвёрку разницы, и перепутать их обиднее, чем не понять.
_MUSIC_SET = re.compile(
    rf"^(?:а\s+|ну\s+|давай\s+|пожалуйста\s+)*(?:можешь\s+|можно\s+)?"
    rf"(?:"
    rf"(?P<куда>{_ТИШЕ}|{_ГРОМЧЕ})\s+(?:мне\s+)?(?:{_ЗВУК}\s+)?"
    rf"(?:(?P<предлог>на|до)\s+)?(?P<шаг>{_ЧИСЛО})"
    rf"|(?:сделай|поставь|выстави|установи|включи)\s+(?:мне\s+)?{_ЗВУК}\s+"
    rf"(?:на\s+|до\s+|=\s*)?(?P<число>{_ЧИСЛО})"
    rf"|{_ЗВУК}\s+(?:на\s+|до\s+|=\s*)?(?P<число2>{_ЧИСЛО})"
    rf")"
    rf"(?:\s*(?:из|/)\s*(?:10|десяти))?"
    rf"(?:\s+пожалуйста)?$")

# Следующий трек. У радио следующего нет, но объяснять это должен робот
# голосом, а не молчащее правило.
_MUSIC_NEXT = re.compile(
    r"^(?:а\s+|ну\s+|давай\s+)*"
    r"(?:(?:поставь|включи)\s+(?:друг\w+|следующ\w+)\s+"
    r"(?:песню|песн\w+|трек|музыку|композицию)"
    r"|(?:следующ\w+|друг\w+)\s+(?:песн\w+|трек|композиц\w+)"
    r"|переключи(?:\s+(?:песню|трек|музыку))?"
    r"|пропусти(?:\s+(?:песню|трек|эту|этот\s+трек))?"
    # Голое «следующая» — так и говорят, когда музыка уже играет: называть
    # существительное в такой момент незачем. А вот голого «дальше» здесь
    # намеренно нет. Двадцать секунд после любой команды короткая фраза из
    # комнаты идёт в разбор без имени робота, и «а дальше?» ребёнка посреди
    # разговора перематывало бы песню. «Дальше песню» ниже никуда не делось.
    r"|следующ\w+"
    r"|дальше\s+(?:песню|трек|музыку))$")

_WHAT_PLAYS = re.compile(
    r"^(?:а\s+|ну\s+)*(?:что|кто|какая|какой)\s+(?:это\s+|сейчас\s+|там\s+|у\s+тебя\s+)*"
    r"(?:играет|звучит|поет|поёт|за\s+песн\w+|за\s+трек|за\s+музык\w+|"
    r"песн\w+|трек|композиц\w+)"
    r"(?:\s+(?:сейчас|это|играет|звучит))?$")


def _rates(t: str) -> Match | None:
    if _RATES.match(t):
        return Match("rates", {}, "курс валют")
    return None


def _music(t: str) -> Match | None:
    if _MUSIC_OFF.match(t):
        return Match("stop_music", {}, "выключить музыку")

    m = _MUSIC_SET.match(t)
    if m:
        число = _число(m.group("число") or m.group("число2") or m.group("шаг"))
        куда = m.group("куда")
        изменение = ("тише" if куда and re.fullmatch(_ТИШЕ, куда)
                     else "громче" if куда else "тише")
        # «Поставь звук на ноль» — просьба о тишине, а не отсутствие числа.
        # Шкала начинается с единицы, ноль на ней и есть самое тихое; без
        # этого инструмент принимал ноль за «не сказали» и убавлял на ступень.
        if not m.group("куда") and число == 0:
            число = 1
        # «Убавь на два» — подвинуть на две ступени, «убавь до двух» —
        # поставить вторую. Без предлога («убавь два») понимаем как «до».
        if куда and m.group("предлог") == "на":
            args = {"изменение": изменение, "шаг": число}
        else:
            args = {"изменение": изменение, "уровень": число}
        return Match("music_volume", args, "громкость музыки числом")

    m = _MUSIC_LEVEL.match(t)
    if m:
        слово = next(g for g in m.groups() if g)
        изменение = "тише" if re.fullmatch(_ТИШЕ, слово) else "громче"
        return Match("music_volume", {"изменение": изменение}, "громкость музыки")

    if _MUSIC_NEXT.match(t):
        return Match("music_next", {}, "следующий трек")

    if _WHAT_PLAYS.match(t):
        return Match("what_is_playing", {}, "что играет")

    m = _MUSIC_ON.match(t)
    if m is None:
        return None
    что = (m.group("уточнение") or m.group("жанр")
           or m.group("имя") or "").strip()
    # «Включи свет» и «включи зарядку» — это не музыка, а то, чего у робота
    # нет вовсе. Пусть отвечает модель, она объяснит честнее правила.
    if что and _NOT_MUSIC.search(что):
        return None
    # Голое имя — только если это и правда похоже на название. Пустое место
    # («включи это», «поставь его») пусть разбирает модель: она переспросит.
    if m.group("имя") and _пустое_имя(что):
        return None
    # Сказал «радио» — значит, радио, а не Яндекс. Без этого «включи радио»
    # уезжало в «Мою волну», а «включи радио Рекорд» искало в Яндексе песни
    # со словом «Рекорд» в названии.
    носитель = (m.group("носитель") or "").lower()
    args = {"что": что}
    if носитель.startswith(("радио", "станц")):
        args["источник"] = "радио"
    return Match("play_music", args, "музыка")


# Слова, которые именем исполнителя не бывают. «Включи это», «поставь его»,
# «включи давай» — это не просьба поставить группу «Это»: разбор голого имени
# без такой проверки отправлял робота искать в Яндексе местоимения и частицы.
_NOT_A_NAME = {
    "это", "то", "той", "тот", "та", "те", "сюда", "туда", "там", "тут",
    "здесь", "меня", "мне", "мной", "тебя", "тебе", "его", "ее", "их", "им",
    "ему", "ей", "нас", "нам", "вас", "вам", "себя", "себе", "кто", "что",
    "чего", "как", "где", "когда", "куда", "давай", "давайте", "пожалуйста",
    "ка", "же", "вот", "так", "уже", "снова", "опять", "потом", "сейчас",
    "быстро", "громко", "тихо", "всё", "все", "чуть", "немного", "обратно",
    "мне-ка", "нибудь", "хоть", "что-то", "чего-то", "нам", "нибудь",
}


def _пустое_имя(что: str) -> bool:
    """Осталось ли после отсева хоть одно слово, похожее на название."""
    слова = [с for с in что.split() if с not in _NOT_A_NAME]
    return not слова


# Что «включают» дома, кроме музыки. Правило про радио на это не срабатывает.
_NOT_MUSIC = re.compile(
    r"свет|лампоч|телевизор|чайник|плит|пылесос|зарядк|розетк|компьютер|"
    r"кондиционер|обогрев|таймер|будильник|секундомер|"
    # Добавлено вместе с разбором голого имени: «включи фонарик» правило
    # теперь ловит, и без этого списка робот пошёл бы искать фонарик в
    # Яндекс.Музыке. Всё, что дома включают руками, — сюда.
    r"фонар|камер|вентилятор|насос|утюг|духовк|микроволнов|стиральн|"
    r"посудомоеч|увлажнител|обогреватель|котёл|котел|бойлер|колонк|"
    r"чайничек|мотор|двигател|фар|подсветк|гирлянд|нагрев|"
    # Книжная основа мимо разговорной формы — та же дыра, что и с фонариком.
    # «Стиральн» не совпадает со «стиралкой», «посудомоеч» — с «посудомойкой»,
    # и обе фразы уезжали в Яндекс.Музыку. Новости и погода тоже: у робота на
    # них есть свои инструменты, и модель их видит.
    r"стирал|стирк|посудомой|новост|погод|вод[уы]|газ|кран|душ|"
    r"свет|отоплен|воздух|музыкальн\w*\s+центр")


def _news(t: str) -> Match | None:
    if _NEWS.match(t):
        return Match("news", {}, "новости")
    return None


# «Мы в Калининграде», «я живу в Калининграде» — так робот узнаёт, где стоит.
# Без этого погода отвечала «я не знаю, где мы находимся» даже после того, как
# город назвали вслух: координаты полагалось вписать руками в файл настроек.
# Бытовые места и обороты, которые начинаются так же, как название города.
# Без этого списка «я в порядке», «мы в шоке» и «я в душ» переставляли роботу
# дом, а погода после этого отвечала про чужое место. Защищала только неудача
# геокодера — то есть ничего.
_НЕ_ГОРОД = {
    "душ", "душе", "ванной", "ванне", "туалете", "кровати", "постели",
    "школе", "садике", "саду", "магазине", "машине", "автобусе", "метро",
    "парке", "лесу", "поле", "гостях", "отпуске", "командировке", "пути",
    "дороге", "порядке", "норме", "курсе", "шоке", "ссоре", "деле", "работе",
    "офисе", "больнице", "поликлинике", "бассейне", "спортзале", "зале",
    "комнате", "кухне", "коридоре", "подъезде", "лифте", "интернете", "сети",
    "игре", "чате", "деревне", "городе",
}

_WHERE_WE_ARE = re.compile(
    r"^(?:а\s+|ну\s+)*(?:мы|я)\s+(?:живем|живу|находимся|нахожусь|сейчас)?\s*"
    r"(?:в|во)\s+(?:городе\s+)?([а-яё-]{3,30})$"
    r"|^(?:а\s+|ну\s+)*(?:наш\s+)?город\s+([а-яё-]{3,30})$"
    r"|^(?:а\s+|ну\s+)*живу\s+(?:я\s+)?(?:в|во)\s+(?:городе\s+)?([а-яё-]{3,30})$")


def _where(t: str) -> Match | None:
    m = _WHERE_WE_ARE.match(t)
    if m is None:
        return None
    город = next(g for g in m.groups() if g)
    if город in _НЕ_ГОРОД:
        # «Я в порядке» — не переезд. Пусть отвечает модель.
        return None
    return Match("set_home", {"город": город}, "где мы")


_LIST = (r"(?:список|списк\w+|перечень|перечн\w+)"
         r"(?:\s+(?:покупок|покупк\w+|дел|продуктов|задач))?")

# Чужие области: почта, музыка, календарь, умный дом. Ничего этого у робота
# нет, и «добавь новый контакт» не должно попадать в список покупок. Проверено
# на корпусе MASSIVE — именно такие фразы и лезли.
_NOT_MINE = re.compile(
    r"контакт|письм|почт|мейл|mail|адрес|песн|музык|плейлист|подкаст|радио|"
    r"канал|событи|встреч|календар|уведомлен|напоминани|свет|лампоч|розетк|"
    r"телевизор|пылесос|\bплюс\b|\bминус\b")


def _notes(t: str) -> Match | None:
    """Список покупок и дел — то, за чем к ассистенту идут каждый день."""
    if re.fullmatch(rf"{_PREFIX}(?:очисти|сотри|удали|обнули)\s+(?:весь\s+)?{_LIST}", t):
        return Match("notes_clear", {}, "очистить список")

    if re.fullmatch(
        rf"{_PREFIX}(?:(?:что|чего)\s+(?:там\s+)?в\s+{_LIST}|"
        rf"(?:прочитай|покажи|назови|перечисли|зачитай)\s+(?:мне\s+)?"
        rf"(?:весь\s+|мой\s+)?{_LIST}|"
        rf"{_LIST}\s+покупок|"
        rf"что\s+(?:мне\s+)?(?:нужно|надо)\s+купить)",
        t,
    ):
        return Match("notes_list", {}, "список")

    # «добавь в список молоко», «добавь молоко в список», «запиши молоко»
    m = re.fullmatch(
        rf"{_PREFIX}(?:добавь|запиши|внеси|положи)\s+(?:мне\s+)?"
        rf"(?:в\s+{_LIST}\s+(.+)|(.+?)\s+в\s+{_LIST}|(.+))",
        t,
    )
    if m:
        item = (m.group(1) or m.group(2) or m.group(3) or "").strip()
        if not item:
            return None
        if m.group(3):
            # «добавь молоко» — без слова «список». Годится, только если это
            # не «добавь песню в плейлист», «добавь встречу в календарь» и не
            # «запиши, что я должен зайти в банк»: у робота нет ни плейлиста,
            # ни календаря, и такие просьбы должна разбирать модель.
            if re.search(r"\bв\b|\bво\b|\bчто\b", m.group(3)):
                return None
            if re.search(r"^(?:запиши|внеси)\b", t) or _NOT_MINE.search(item):
                return None
        return Match("notes_add", {"item": item}, "в список")

    m = re.fullmatch(
        rf"{_PREFIX}(?:убери|вычеркни|удали|выкинь)\s+(?:мне\s+)?"
        rf"(?:из\s+{_LIST}\s+(.+)|(.+?)\s+из\s+{_LIST})",
        t,
    )
    if m:
        item = (m.group(1) or m.group(2) or "").strip()
        if item:
            return Match("notes_remove", {"item": item}, "из списка")

    # «Вычеркни молоко» — без слов «из списка». Вычёркивают только из списка,
    # так что путать не с чем; «убери молоко» сюда не берём — «убери» говорят
    # и про музыку, и про вещи на полу.
    m = re.fullmatch(rf"{_PREFIX}вычеркни\s+(?:мне\s+)?(.+)", t)
    if m:
        item = m.group(1).strip()
        if item and not _NOT_MINE.search(item):
            return Match("notes_remove", {"item": item}, "из списка")
    return None


def _weather(t: str) -> Match | None:
    """Погода. Самый частый вопрос после таймеров — и модель её выдумывает."""
    day_word = r"(?:завтра|на\s+завтра)"
    m = re.fullmatch(
        rf"{_PREFIX}{_ASK}(?:{_NOW}\s+|{day_word}\s+)?(?:"
        rf"как(?:ая|ое)\s+(?:там\s+|{_NOW}\s+|{day_word}\s+)?погод\w*"
        rf"(?:\s+будет)?|"
        rf"погод\w*|"
        rf"что\s+(?:там\s+)?(?:с\s+погодой|на\s+улице)|"
        rf"сколько\s+(?:там\s+|{_NOW}\s+)?градус\w*|"
        rf"(?:тепло|холодно)\s+ли\s+на\s+улице|"
        # «Какая температура на улице» и «будет ли дождь» — это тот же вопрос
        # о погоде, а уходили модели, и та отвечала выдуманным числом.
        rf"как(?:ая|ое)\s+(?:там\s+)?температур\w*|"
        rf"(?:будет\s+ли|будет|пойдет|пойдёт)\s+(?:там\s+)?"
        rf"(?:дождь|снег|гроза|ветер)|"
        rf"(?:дождь|снег)\s+(?:будет|идет|идёт)|"
        rf"(?:брать|нужен)\s+(?:ли\s+)?зонт"
        rf")(?:\s+на\s+улице)?(?:\s+(?:{_NOW}|{day_word}))?",
        t,
    )
    if not m:
        return None
    day = "завтра" if "завтра" in t else "сейчас"
    return Match("weather", {"day": day}, "погода")


def _clock(t: str) -> Match | None:
    """Который час и какое сегодня число.

    Часов у модели нет — без инструмента она бы их выдумала. Здесь ответ
    берётся из системных часов робота: мгновенно и бесплатно.

    Про другой город («сколько времени во Владивостоке») правило намеренно
    молчит: часовые пояса — работа для модели.
    """
    if re.fullmatch(
        rf"{_PREFIX}{_ASK}(?:"
        rf"котор\w+\s+(?:{_NOW}\s+)?час|"
        rf"как(?:ое|ая)\s+(?:{_NOW}\s+)?врем\w+|"
        rf"сколько\s+(?:{_NOW}\s+)?врем\w+(?:\s+{_NOW})?|"
        rf"сколько\s+(?:{_NOW}\s+)?на\s+часах|"
        rf"(?:{_NOW}\s+)?врем\w+"
        rf")",
        t,
    ):
        return Match("time_now", {}, "время")

    # «какой сегодня день» — про дату, а не про самочувствие робота.
    if re.fullmatch(
        rf"{_PREFIX}{_ASK}(?:"
        rf"как(?:ое|ая|ой)\s+(?:{_NOW}\s+)?{_DATE_NOUN}(?:\s+{_NOW})?|"
        rf"(?:{_NOW}\s+)?{_DATE_CLEAR}(?:\s+{_NOW})?|"
        rf"{_NOW}\s+{_DATE_AMBIG}|{_DATE_AMBIG}\s+{_NOW}"
        rf")",
        t,
    ):
        return Match("date_now", {}, "дата")
    return None


# --- секундомер, жребий, счёт ---------------------------------------------
#
# Всё это спрашивают играючи и подряд («ещё раз!»), поэтому через модель было
# бы и медленно, и за деньги. А жребий ей и нельзя доверять: на «загадай число
# от одного до десяти» она отвечает семёркой заметно чаще прочего.

_СЕКУНДОМЕР = r"секундомер\w*|время"

_WATCH_START = re.compile(
    rf"^{_PREFIX}(?:(?:включи|поставь|запусти|заведи)\s+секундомер\w*"
    rf"|засеки(?:\s+(?:время|секундомер\w*))?"
    rf"|(?:начни|начинай)\s+считать\s+время)$")
_WATCH_STOP = re.compile(
    rf"^{_PREFIX}(?:(?:останови|выключи|стоп|прекрати)\s+секундомер\w*"
    rf"|секундомер\s+стоп)$")
_WATCH_RESET = re.compile(
    rf"^{_PREFIX}(?:сбрось|обнули|сброс)\s+секундомер\w*$")
_WATCH_ASK = re.compile(
    rf"^{_PREFIX}(?:сколько\s+(?:там\s+|уже\s+)?(?:прошло|натикало|на\s+секундомере)"
    rf"|что\s+на\s+секундомере"
    rf"|сколько\s+времени\s+прошло)$")

_COIN = re.compile(
    rf"^{_PREFIX}(?:(?:подбрось|брось|кинь|подкинь)\s+монет\w+"
    rf"|орёл\s+или\s+решка|орел\s+или\s+решка|монетк\w+)$")
_DICE = re.compile(
    rf"^{_PREFIX}(?:(?:брось|кинь|подбрось)\s+(?:кубик|кости)"
    rf"|кубик)(?:\s+на\s+(?P<граней>\d{{1,3}}))?$")
_RANDOM = re.compile(
    rf"^{_PREFIX}(?:загадай|назови|выбери|скажи)\s+(?:мне\s+)?"
    rf"(?:любое\s+|случайное\s+)?число"
    rf"(?:\s+от\s+(?P<от>{_ЧИСЛО}|\d{{1,6}})\s+до\s+(?P<до>{_ЧИСЛО}|\d{{1,6}}))?$")

# Счёт: только то, что записано числами и знаками. «Два плюс два» словами
# отдаём модели — она переведёт в выражение и позовёт тот же инструмент.
_MATH = re.compile(
    r"^(?:а\s+|ну\s+|пожалуйста\s+)*(?:посчитай|сколько\s+будет|вычисли|"
    r"подсчитай|сосчитай)\s+(?P<что>[\d\s+\-*/%^().,]{3,60})"
    r"(?:\s+пожалуйста)?$")
_MATH_PERCENT = re.compile(
    r"^(?:а\s+|ну\s+|пожалуйста\s+)*(?:посчитай|сколько\s+будет|вычисли)?\s*"
    r"(?P<сколько>\d{1,3}(?:[.,]\d+)?)\s*(?:%|процент\w*)\s+от\s+"
    r"(?P<чего>\d{1,12}(?:[.,]\d+)?)$")


# Вслух знаки называют словами: «два плюс два», «пять умножить на три».
# Числа к этому месту уже цифры — их перевёл numerals_to_digits.
_ЗНАКИ_СЛОВАМИ = (
    (re.compile(r"\bплюс\b"), "+"),
    (re.compile(r"\bминус\b"), "-"),
    (re.compile(r"\b(?:умножить|умнож|помножить)\s+на\b"), "*"),
    (re.compile(r"\b(?:разделить|раздели|поделить|подели)\s+на\b"), "/"),
    (re.compile(r"\bв\s+степени\b"), "**"),
)


def _знаками(t: str) -> str:
    for шаблон, знак in _ЗНАКИ_СЛОВАМИ:
        t = шаблон.sub(знак, t)
    return t


_МЕРА = r"[а-я]{1,14}"
_CONVERT = re.compile(
    # Глагол обязателен. Без него под правило подходило любое утверждение
    # вида «<число> <мера> в <мера>», и обычные бытовые фразы — «спит восемь
    # часов в сутки», «пей два часа в день» — робот переводил в единицы и
    # отвечал вслух «ноль целых тридцать три дня».
    rf"^{_PREFIX}(?:переведи|переводи|сколько\s+(?:будет\s+)?)\s*"
    rf"(?P<сколько>\d{{1,9}}(?:[.,]\d+)?)\s+(?P<из>{_МЕРА})\s+"
    rf"(?:в|во)\s+(?P<во>{_МЕРА})$")
# «Сколько сантиметров в метре» — то же самое, только наизнанку: спрашивают
# про одну единицу и называют её второй.
_CONVERT_ONE = re.compile(
    rf"^{_PREFIX}сколько\s+(?P<во>{_МЕРА})\s+(?:в|во)\s+(?P<из>{_МЕРА})$")

_CITY_TIME = re.compile(
    rf"^{_PREFIX}(?:сколько\s+(?:сейчас\s+)?времени|который\s+час|"
    rf"сколько\s+времени\s+сейчас)\s+(?:в|во)\s+(?P<город>[а-я-]{{3,20}})$")


def _мера_известна(слово: str) -> bool:
    """Правило спрашивает словарь, а не гадает по форме фразы.

    Без этого «сколько лет в году» и «сколько человек в комнате» разбирались
    как перевод мер, а «сколько времени в пути» — как время в городе Пути.
    Форма у этих фраз ровно та же, отличаются они только словами.
    """
    from . import counting
    from . import lookup

    return (counting.найти_меру(слово) is not None
            or lookup.валюта(слово) is not None)


# Вопрос про дорогу — не то же самое, что «опиши комнату», и спросить надо
# прямо: иначе модель добросовестно перечислит цвет стен, а робот всё так же
# не будет знать, ехать ему или нет. Здесь только сам вопрос — кто спрашивает
# и как отвечать, дописывает камера: обрамление вопроса её дело, а не правил.
ПРО_ДОРОГУ = ("Свободен ли путь прямо передо мной? "
              "Если нет — что мешает и с какой стороны?")


def _look(t: str) -> Match | None:
    """«Что ты видишь» и «свободен ли путь» — прямо к камере, минуя модель.

    Зачем правило, если модель и так зовёт этот инструмент сама. Затем, что
    через неё выходит вдвое дольше: четырёхмиллиардная модель на ПК читает
    промпт сначала чтобы решить «надо посмотреть», потом чтобы пересказать
    увиденное своими словами. На живом роботе это девять секунд вместо пяти,
    и пересказ вдобавок теряет подробности — предел в две фразы срезает как
    раз хвост описания.

    Ответ зрячей модели уже готов для человека, пересказывать его незачем.

    Ловим только бесспорное. Правило здесь — ускоритель, а не единственная
    дорога: не узнало фразу — она уйдёт модели, и та всё равно посмотрит,
    просто на четыре секунды дольше. Поэтому ошибиться в сторону «не поймал»
    дёшево, а в сторону «поймал лишнее» — обидно: на «ты видишь в этом
    смысл?» робот принялся бы описывать комнату.
    """
    if re.fullmatch(
        rf"{_PREFIX}(?:"
        rf"(?:что|кого)\s+(?:ты\s+)?вид\w+|"
        rf"что\s+(?:там\s+)?видно|"
        rf"что\s+(?:у\s+тебя\s+)?перед\s+(?:тобой|глазами)|"
        rf"(?:о[гб])?ляд\w+|осмотрись|"
        rf"кто\s+(?:здесь|тут|передо\s+мной)|"
        rf"(?:ты\s+)?вид\w+\s+(?:ли\s+)?меня|"
        rf"сколько\s+пальцев(?:\s+(?:ты\s+)?вид\w+)?"
        rf")",
        t,
    ):
        # Вопрос отдаём как есть: «сколько пальцев» и «что видишь» — разные
        # вопросы к одной картинке, и подменять их общим описанием значит
        # отвечать не на то, что спросили.
        return Match("look_around", {"question": t}, "смотрю")

    # А голое «посмотри» вопроса не содержит вовсе. Отдать его как вопрос
    # значит спросить у зрячей модели «посмотри» — она и ответит чем угодно.
    # Пустой вопрос камера заменит своим описанием обстановки.
    if re.fullmatch(rf"{_PREFIX}посмотри(?:\s+(?:вокруг|по\s+сторонам))?", t):
        return Match("look_around", {}, "смотрю")

    if re.fullmatch(
        rf"{_PREFIX}(?:"
        rf"что\s+(?:там\s+)?впереди|"
        rf"(?:свобод\w+|чист\w+)\s+(?:ли\s+)?(?:путь|дорог\w+|впереди)|"
        rf"(?:путь|дорог\w+)\s+(?:ли\s+)?свобод\w+|"
        rf"можно\s+(?:ли\s+)?(?:ехать|проехать|проезжать)|"
        rf"(?:ты\s+)?проедешь(?:\s+ли)?|"
        rf"есть\s+ли\s+(?:впереди\s+)?препятстви\w+|"
        rf"не\s+врежешься(?:\s+ли)?|"
        rf"куда\s+можно\s+(?:ехать|поехать|проехать)"
        rf")",
        t,
    ):
        # К дальномеру, а не к камере: он отвечает за сотую долю секунды
        # против двух у облака и видит в темноте. Нет дальномера — правило
        # назовёт инструмент, которого нет, ход уйдёт модели, и та посмотрит
        # камерой. Мы на этом ничего не теряем, кроме тех самых двух секунд.
        return Match("path_check", {}, "смотрю на дорогу")

    # «Иди за мной» разбираем правилом, а не моделью, и это не про экономию.
    # Фраза короткая, произносится на ходу — человек уже развернулся и пошёл,
    # — и две секунды раздумий он проводит, оглядываясь. Правило отвечает
    # мгновенно, и робот трогается, пока человек ещё в поле зрения.
    # Список глаголов длинный не от жадности. «Кузя, едь за мной» правило
    # пропустило, ход ушёл модели, та ответила про что-то своё — и робот не
    # поехал. Человек в этот момент уже шёл по коридору. «Едь» — не по
    # словарю, но говорят именно так, и разбирать надо живую речь.
    if re.fullmatch(
        rf"{_PREFIX}(?:"
        rf"(?:иди|идем|пойдем|пошли|поехали|поедем|едем|едь|езжай|ехай|"
        rf"поезжай|следуй|двигай|двигайся|катись|шагай|ступай|топай)"
        rf"\s+(?:за\s+мной|со\s+мной)|"
        rf"(?:за|со)\s+мной|"
        rf"(?:иди|пошли)\s+сюда\s+за\s+мной|"
        rf"(?:будь|держись)\s+(?:рядом|за\s+мной)|"
        rf"провод\w+\s+меня"
        rf")",
        t,
    ):
        return Match("follow_me", {}, "иду за тобой")

    # ОБХОД КВАРТИРЫ. Правилом, а не моделью, по тому же доводу, что и
    # следование: команда трогает колёса, и полторы секунды на раздумье
    # модели человек воспринимает как «не услышал» и повторяет громче.
    #
    # Спрашивают про это двумя разными способами, и различать их обязательно:
    #   «обследуй квартиру» — ПОЕЗЖАЙ и посмотри;
    #   «что где стоит»     — расскажи по памяти, никуда не езди.
    # Робот, который на второй вопрос уезжает кататься, — это робот, которого
    # боятся спрашивать.
    if re.fullmatch(
        rf"{_PREFIX}(?:"
        rf"(?:обследуй|обойди|осмотри|изучи|разведай|обследовать|обойти)"
        rf"\s+(?:всю\s+)?(?:квартиру|дом|комнаты|жильё|помещение)|"
        # «Сделай объезд квартиры», «проведи аудит дома», «сделай осмотр» —
        # так говорят живьём, и правило обязано это ловить. Поймано на
        # роботе: «сделай объезд квартиры» правило пропустило, ход ушёл
        # модели, и та вместо инструмента поговорила про новый навык.
        rf"(?:сделай|проведи|давай|устрой)?\s*(?:полный\s+)?"
        rf"(?:объезд|обход|аудит|осмотр|обследование)"
        rf"(?:\s+(?:всей\s+|всего\s+)?(?:квартиры|дома|комнат|жилья))?|"
        rf"(?:составь|сделай|нарисуй)\s+(?:карту|план|опись)"
        rf"(?:\s+(?:квартиры|дома|комнат))?|"
        rf"(?:иди|пойди|поезжай)\s+(?:и\s+)?(?:осмотрись|осмотри\s+всё)"
        rf")",
        t,
    ):
        return Match("survey_flat", {}, "обхожу квартиру")

    if re.fullmatch(
        rf"{_PREFIX}(?:"
        rf"что\s+(?:где|у\s+нас\s+где)\s+(?:стоит|находится|есть)|"
        rf"(?:что|чего)\s+ты\s+знаешь\s+(?:про|о)\s+(?:квартиру|квартире|"
        rf"доме|дом|комнатах?)|"
        rf"(?:покажи|расскажи|зачитай)\s+(?:мне\s+)?опись|"
        rf"какая\s+(?:у\s+нас\s+)?мебель"
        rf")",
        t,
    ):
        return Match("what_is_where", {}, "что где стоит")
    return None


def _counting(t: str) -> Match | None:
    m = _CITY_TIME.match(t)
    if m:
        from . import counting
        город = m.group("город")
        if город.replace("ё", "е") in counting.ПОЯСА:
            return Match("time_now", {"город": город}, "время в городе")

    m = _CONVERT.match(t)
    if m and _мера_известна(m.group("из")) and _мера_известна(m.group("во")):
        return Match("convert_units",
                     {"сколько": float(m.group("сколько").replace(",", ".")),
                      "из_чего": m.group("из"), "во_что": m.group("во")},
                     "перевод мер")
    m = _CONVERT_ONE.match(t)
    if m and _мера_известна(m.group("из")) and _мера_известна(m.group("во")):
        return Match("convert_units",
                     {"сколько": 1, "из_чего": m.group("из"),
                      "во_что": m.group("во")}, "перевод мер")

    if _WATCH_START.match(t):
        return Match("stopwatch", {"действие": "пуск"}, "секундомер")
    if _WATCH_STOP.match(t):
        return Match("stopwatch", {"действие": "стоп"}, "секундомер стоп")
    if _WATCH_RESET.match(t):
        return Match("stopwatch", {"действие": "сброс"}, "секундомер сброс")
    if _WATCH_ASK.match(t):
        return Match("stopwatch", {"действие": "сколько"}, "сколько прошло")

    if _COIN.match(t):
        return Match("random_pick", {"вид": "монетка"}, "монетка")
    m = _DICE.match(t)
    if m:
        граней = int(m.group("граней") or 6)
        return Match("random_pick", {"вид": "кубик", "сверху": граней}, "кубик")
    m = _RANDOM.match(t)
    if m:
        от = _число(m.group("от")) if m.group("от") else 1
        до = _число(m.group("до")) if m.group("до") else 10
        return Match("random_pick", {"вид": "число", "снизу": от, "сверху": до},
                     "случайное число")

    m = _MATH_PERCENT.match(t)
    if m:
        сколько = m.group("сколько").replace(",", ".")
        чего = m.group("чего").replace(",", ".")
        return Match("calculate", {"выражение": f"{сколько}/100*{чего}"}, "счёт")
    m = _MATH.match(_знаками(t))
    if m:
        # «^» вслух говорят как степень, а Python ждёт «**». Запятая в числах
        # русская, точка питонья.
        что = m.group("что").replace("^", "**").replace(",", ".")
        if any(з in что for з in "+-*/%"):
            return Match("calculate", {"выражение": что}, "счёт")
    return None


