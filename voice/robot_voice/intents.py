def командное_слово(слово: str) -> bool:
    """Слово из command-словаря робота — «вперёд», «таймер», «громче».

    Нужно там, где чужой разбор может принять команду за что-то своё. Первым
    таким местом стало знакомство: на «как тебя зовут?» человек ответил
    «вперёд проедь на метр», и робот записал его в личное дело под именем
    «Вперёд». Правилом эта фраза не разбиралась — порядок слов не тот, — а
    имя из неё выделилось прекрасно.

    Ё приводим к Е: в словаре «вперед», а распознавание отдаёт «вперёд».
    """
    return слово.strip(" ,.!?…—-").lower().replace("ё", "е") in set(_VOCABULARY)


def _distance(a: str, b: str, limit: int) -> int:
    """Расстояние Левенштейна, но дальше limit не считаем — незачем."""
    if abs(len(a) - len(b)) > limit:
        return limit + 1
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1,
                           prev[j - 1] + (ca != cb)))
        if min(cur) > limit:
            return limit + 1
        prev = cur
    return prev[-1]


# Что починка сделала в последний раз. Пишем в лог не всегда, а только когда
# правка помогла разобрать команду: «насколько» похоже на «сколько», и на
# каждом вопросе «насколько они сильнее» строка «расслышал X — понял как Y»
# читалась как ошибка распознавания, хотя всё было расслышано верно.
_fixed: list[tuple[str, str]] = []


def repair(text: str) -> str:
    """Чинит слова команд, которые распознавание услышало почти правильно.

    Правит только по своему словарю и только однозначные случаи: если слово
    одинаково похоже на два разных, не трогаем вовсе. Чужую речь — имена,
    пункты списка, содержание напоминаний — не портим, потому что таких слов
    в словаре нет.
    """
    out = []
    _fixed.clear()
    for word in text.split():
        bare = word.strip(" ,.!?…—-").lower()
        limit = next((d for n, d in _REPAIR_RULES if len(bare) >= n), 0)
        if not limit or bare in _VOCABULARY:
            out.append(word)
            continue
        best, near = limit + 1, []
        for known in _VOCABULARY:
            d = _distance(bare, known, limit)
            if d < best:
                best, near = d, [known]
            elif d == best:
                near.append(known)
        if best <= limit and len(near) == 1:
            _fixed.append((bare, near[0]))
            out.append(word.lower().replace(bare, near[0]))
        else:
            out.append(word)
    return " ".join(out)


# Просьба позвать умного. Дома отвечает маленькая модель — быстро и даром, —
# но иногда нужен ответ получше, и человек это знает лучше любого автомата.
# Так устроено у всех, кто держит и своё, и облачное: сначала дешёвое, а
# дорогое — по делу. Разница в том, что решение здесь принимает человек, а не
# классификатор, который сам может ошибиться.
_SMART = re.compile(
    r"^(?:а\s+)?(?:ну\s+)?(?:давай\s+)?"
    r"(?:подумай(?:\s+(?:хорошо|получше|как\s+следует|серьезно))?|"
    r"поразмысли|спроси\s+умного|включи\s+умного|"
    r"поду?май\s+головой|напряги(?:сь|\s+мозги))"
    r"[\s,.:—-]*")


# Повелительные глаголы движения. Ими человек не рассуждает о поездках, а
# требует ехать: услышав такое, робот обязан либо поехать, либо честно
# сказать, что не понял. Направления («вперёд», «назад») сюда намеренно не
# попали — «два дня назад» и «что там впереди» это не команды.
_ЕЗДА = re.compile(
    r"\b(?:едь|езжай|поезжай|поехали|проедь|проезь|проезжай|проежай|"
    r"подъедь|отъедь|"
    r"двигайся|двинься|сдвинься|катись|покатили|"
    r"развернись|разворачивайся|повернись|поверни|поворачивай|"
    r"крутись|покрутись|прокрутись|покружись|"
    # «Иди сюда» и «подойди ко мне»: модель отвечала «Иду к тебе!», не позвав
    # ни одного инструмента, и это звучало сразу — колёса не трогались.
    # Голого «иди» здесь нет и быть не должно: «иди спать» — не поездка, а
    # придержанный ответ на него превратился бы в «не понял, куда ехать».
    r"иди\s+(?:сюда|ко\s+мне)|подойди|подъезжай|приезжай|приходи|"
    r"сдай\s+назад|подай\s+назад|потанцуй|станцуй|объедь|"
    # Фигура — только при глаголе и не дальше одного слова от него: «что
    # такое квадрат» — вопрос, и придержать ответ на него значило бы
    # ответить ребёнку «не понял, куда ехать» вместо геометрии.
    r"(?:сделай|нарисуй|начерти|изобрази)\s+(?:[а-я0-9]+\s+)?"
    r"(?:круг\w*|квадрат\w*|зигзаг\w*|восьмерк\w*|змейк\w*))\b")


def просят_ехать(text: str) -> bool:
    """Требуют ли ехать — так, что молчаливый отказ будет враньём.

    Нужно для проверки после ответа модели: если человек сказал «поезжай», а
    модель ни одного инструмента не позвала, значит она рассказала о поездке
    вместо поездки. На живом роботе это выглядело как «Приехал вперёд. Теперь
    назад. Готов к следующему!» при неподвижном роботе — и хуже отказа, потому
    что человек уверен, что всё получилось.
    """
    return bool(_ЕЗДА.search(normalize(text)))


# Пустое поддакивание: человек соглашается, мычит или отмахивается — но не
# роботу. В открытом окне разговора такое прилетает постоянно: человек
# отвечает другому человеку, телевизору или самому себе.
#
# Раньше это уходило модели, и та отвечала тем, чем отвечают на пустоту:
# «Понял, Игорь. Готов к следующему. Что нужно?» — три казённые фразы на
# ровном месте, из-за которых разговор и выглядит тупым. Живой человек на
# чужое «да» просто молчит.
#
# Проверяется только тогда, когда робот сам ни о чём не спрашивал: если
# вопрос был, «да» — это ответ, и его разбирает Pending.
_ПОДДАКИВАНИЕ = {
    "да", "ага", "угу", "мгм", "нет", "не", "неа", "ну", "ну да", "ну нет",
    "ок", "окей", "хорошо", "ладно", "понятно", "ясно", "точно", "именно",
    "вот", "во", "э", "а", "и", "так", "да да", "нет нет",
}


def поддакивание(text: str) -> bool:
    """Пустое «да» само по себе — не команда и не вопрос, а шум разговора."""
    t = normalize(text)
    return bool(t) and t in _ПОДДАКИВАНИЕ


def wants_smart(text: str) -> tuple[bool, str]:
    """Просили ли позвать умного. Возвращает решение и фразу без просьбы.

    Если кроме просьбы ничего не сказано, фразу оставляем целиком: «подумай»
    в одиночку — это продолжение прошлого разговора, а не пустой вопрос.
    """
    m = _SMART.match(text.strip())
    if not m:
        return False, text
    rest = text.strip()[m.end():].strip()
    return True, rest or text


def normalize(text: str) -> str:
    """Приводит фразу к виду, удобному для регулярок."""
    t = text.lower().replace("ё", "е")
    # Знаки счёта не выбрасываем, а разводим пробелами: «посчитай 2+2» иначе
    # превращалось в «посчитай 2 2», и правило про счёт не видело, что между
    # числами вообще что-то было. Пробелы вокруг ничему не мешают — Python
    # разбирает «2 + 2» так же, как «2+2», а в живой речи этих знаков нет.
    t = re.sub(r"[+*/%^]", r" \g<0> ", t)
    t = re.sub(r"[^\w\s.,+*/%^()-]", " ", t)
    t = re.sub(r"\s+", " ", t).strip(" .,-")
    for шаблон, замена in _HALVES:
        t = шаблон.sub(замена, t)
    t = _БЕЗ.sub(_без_цифрами, t)
    return numerals_to_digits(t)


def _to_metres(value: str, unit: str) -> float:
    v = float(value.replace(",", "."))
    if unit.startswith("см") or unit.startswith("сантиметр"):
        return v / 100
    return v


@dataclass
class Match:
    """Что распознало правило: имя инструмента и аргументы к нему."""

    tool: str
    args: dict
    rule: str


# Граница предложения. Те же знаки, что и у разбора обращения в app.py:
# точка, восклицательный, вопросительный, многоточие.
_ПРЕДЛОЖЕНИЕ = re.compile(r"[.!?…]+")


# Слова, которые после «позови» или «найди» именем не являются. Без этого
# «найди меня» уехало бы искать человека по имени «меня», а «позови на помощь»
# — человека по имени «на».
_НЕ_ИМЯ = frozenset((
    "меня", "нас", "себя", "его", "её", "их", "кого", "кто", "что",
    "на", "в", "к", "по", "мне", "тебя", "сюда", "туда", "домой",
    "помощь", "время", "музыку", "свет", "погоду",
))

# Семья в любом падеже: «маму», «бабулю», «братика». Формы перечислены, а не
# «пап\w*» и «баб\w*», потому что «найди папку» и «найди бабочку» — про вещи.
_СЕМЬЯ = (r"(?:мам(?:а|у|е|ой|очк\w*|ул\w*)?|пап(?:а|у|е|ой|очк\w*|ул\w*)?|"
          r"бабушк\w*|баб(?:а|у|е|ой|ул\w*)|дедушк\w*|дед(?:а|у|е|ом|ул\w*)?|"
          r"брат\w*|сестр\w*)")

# Наречия и сравнения на «-е», «-у», «-и»: после «скажи» они похожи на «кому».
_НЕ_КОМУ = (r"(?:\w+ее|лучше|больше|меньше|тоже|также|еще|уже|вообще|сразу|"
            r"громче|тише|потише|погромче|проще|короче|позже|раньше|дальше|"
            r"ближе|выше|ниже|хуже|чаще|реже|почему|всегда|снова|опять|"
            r"честно|вслух|сейчас|всем|всему)")


# Междометия, которыми начинают просьбу. Срезаем их, только если за словом
# стоит запятая: «Слушай, включи музыку» — это просьба, а «слушай музыку» и
# «давай поиграем» — нет, и трогать их нельзя.
_ВСТУПЛЕНИЕ = re.compile(
    r"(?:^|(?<=\. ))(?:(?:пожалуйста|слушай|ну|так|давай|эй|ой|блин|короче|"
    r"кстати)\s*,\s*)+")
_ПОЖАЛУЙСТА = re.compile(r",?\s*\bпожалуйста\b,?")


def _вежливость(t: str) -> str:
    """Снять с фразы то, чем человек её украсил, а правило не ждёт.

    GigaAM ставит знаки препинания, а правила сверяют фразу целиком. Замер на
    сорока рабочих командах: без украшений разбираются все сорок, а «X,
    пожалуйста», «Пожалуйста, X» и «Слушай, X» — по одной. Промах правила
    стоит похода к модели (секунда-другая, а при холодном кэше тишина), и
    часть команд модели не видна вовсе: «Повтори, пожалуйста», «Сделай потише,
    пожалуйста» не выполнялись никак. А попавшие в правило уносили вежливость
    в аргументы: play_music искал «музыку, пожалуйста».

    Запятую меняем на пробел только вместе с пробелом за ней — «1,5 метра»
    остаётся числом. Цепочки (parse_chain) режутся по исходным запятым, и
    их это не касается.
    """
    t = _ВСТУПЛЕНИЕ.sub("", t)
    t = _ПОЖАЛУЙСТА.sub("", t)
    t = re.sub(r",\s+", " ", t)
    return re.sub(r"\s+", " ", t).strip(" .,-")


def parse(text: str) -> Match | None:
    """Разбирает фразу. None — значит это разговор, отдаём модели.

    Заходов два. Сначала как услышали — и почти всегда этого хватает. Не
    совпало ни одно правило — пробуем ещё раз, починив слова по словарю
    команд. Порядок именно такой, и это важно: у «напомни» и «добавь» внутри
    едет произвольный текст человека, и правка его испортила бы. Раз первый
    заход не сработал, портить уже нечего.
    """
    t = _вежливость(normalize(text))
    m = _match(t)
    if m is not None:
        return m
    # ЗАХОД ПО ПРЕДЛОЖЕНИЯМ. В одно распознавание слипается по два-три
    # предложения, и команда часто во втором:
    #
    #   услышано «Кузя, поехали. Иди за мной.» → в разбор «поехали. Иди за
    #   мной» → ни одно правило не совпало → модель → «Не понял, куда ехать»
    #   через десять с половиной секунд.
    #
    # Правила пишутся под ОДНУ просьбу, и это правильно: «иди за мной» с
    # приклеенным спереди «поехали.» не должно требовать своего шаблона.
    # Разбираем каждое предложение отдельно и берём ПОСЛЕДНЕЕ совпавшее — по
    # тому же доводу, по которому берётся последнее обращение по имени:
    # свежее и есть настоящее, «поехали, то есть иди за мной» кончается
    # следованием, а не поездкой.
    #
    # Только когда целиком не совпало: составные команды («метр вперёд и метр
    # назад») разбирает parse_chain, и отбирать у него работу нельзя.
    куски = [к.strip() for к in _ПРЕДЛОЖЕНИЕ.split(t) if к.strip()]
    if len(куски) > 1:
        нашлось = None
        for кусок in куски:
            свой = _match(кусок)
            if свой is not None:
                нашлось = свой
        if нашлось is not None:
            return нашлось
    fixed = normalize(repair(t))
    if fixed == t:
        return None
    правки = list(_fixed)
    m = _match(fixed)
    if m is not None and правки:
        # Логируем только удачную починку: она объясняет, почему сработало
        # правило, которого в исходной фразе не видно.
        for было, стало in правки:
            log.info("расслышал %r — понял как %r", было, стало)
    return m


# Инструменты, которые двигают робота. По этому списку видно, поехал робот
# или только рассказал о поездке. route сюда входит наравне с drive: фигуру
# вроде зигзага модель собирает сама, и это такое же настоящее движение.
ДВИЖЕНИЕ = ("drive", "turn", "stop", "route")

# То же, плюс следование, — но ТОЛЬКО для проверки «робот сказал, что едет:
# а поехал ли». Отдельный набор, а не расширенный ДВИЖЕНИЕ, и это важно:
# ДВИЖЕНИЕ даёт освобождение от имени в открытом разговоре, и запись туда
# следования означала бы, что робот пойдёт за любым, кто скажет «за мной», —
# включая телевизор. Он уже один раз пошёл.
ПОЕХАЛ = ДВИЖЕНИЕ + ("follow_me",)

# Чем модель ОБЕЩАЕТ движение. Проверка зеркальна просят_ехать: та смотрит на
# просьбу человека, эта — на ответ робота.
#
# Зачем понадобилась вторая. Живой случай: рядом работал телевизор, оттуда
# прозвучало «Преследование. Нет никакого смысла плакать. Пришла пора
# действовать», разговорное окно было открыто — и робот ответил «Понял, иду за
# тобой». Инструмент он при этом не звал и никуда не пошёл: имени не было, и
# сторож движения его бы не пустил.
#
# Старая проверка это пропустила, потому что смотрела на ПРОСЬБУ: человек
# ехать не просил (просил телевизор, да и то не робота), значит и сверять
# нечего. А соврал робот всё равно — и соврал о том, что он якобы едет за
# человеком по квартире. Человек, услышав такое, оборачивается и ищет робота.
_ОБЕЩАЕТ_ЕХАТЬ = re.compile(
    r"\b(?:еду|едем|поехал\w*|поеду|иду\s+за|иду\s+следом|следую|двигаюсь|"
    r"пошёл\s+за|пошел\s+за|приехал\w*|разворачиваюсь|поворачиваю|"
    r"останавливаюсь|торможу|качу|качусь|"
    # «Иду к тебе!» на «иди сюда» — с колёсами, стоящими на месте.
    r"иду\s+к|подхожу|подъезжаю|бегу|кручусь|танцую|"
    # «Делаю» и «рисую» сами по себе — не езда («делаю вывод»), а вот с
    # фигурой рядом — обещание проехать её.
    r"(?:делаю|рисую)\s+(?:[а-я0-9]+\s+)?"
    r"(?:круг\w*|квадрат\w*|зигзаг\w*|восьмерк\w*|змейк\w*|разворот\w*|"
    r"поворот\w*|оборот\w*|танец))\b")


def обещает_движение(text: str) -> bool:
    """Говорит ли робот, что он едет. Проверяется, когда колёса не тронулись."""
    return bool(_ОБЕЩАЕТ_ЕХАТЬ.search(normalize(text)))


# Чем модель объявляет движение ЗАКОНЧЕННЫМ. Третья проверка того же рода, и
# заведена она по третьему живому случаю — самому неприятному из трёх.
#
# В журнале это выглядит так:
#   18:06:32 маршрут 'объезд квартиры': 6 шагов, 35 с
#   18:06:32 маршрут: шаг 1 из 6
#   18:06:33 робот: Объезд квартиры сделан.
#   18:06:35 сторож оборвал поездку: впереди что-то справа
#   18:06:38 маршрут отменён на шаге 2 из 6
#
# То есть робот отчитался об успехе через секунду после старта — и через пять
# секунд маршрут развалился. Инструмент при этом ответил честно: «Делаю объезд
# квартиры, 6 шагов». Соврала не машина, а пересказ: модель приняла «начал» за
# «сделал» и поставила глагол в прошедшее время.
#
# Отличать это от честного отчёта нельзя по одному тексту — можно только по
# тому, ЕДУТ ЛИ КОЛЁСА в момент, когда фраза готова. Едут — значит ничего ещё
# не сделано, и вслух идёт то, что вернул инструмент.
_ОБЕЩАЕТ_ГОТОВО = re.compile(
    r"\b(?:сделан\w*|сделал\w*|выполнил\w*|выполнен\w*|готово|закончил\w*|"
    r"завершил\w*|объехал\w*|обошёл|обошел|проехал\w*|доехал\w*|"
    r"прибыл\w*|на\s+месте)\b")


def обещает_готово(text: str) -> bool:
    """Объявляет ли робот дело законченным. Проверяется, пока колёса едут."""
    return bool(_ОБЕЩАЕТ_ГОТОВО.search(normalize(text)))

# Инструменты музыки — для той же проверки после ответа, что и движение.
МУЗЫКА = ("play_music", "play_radio", "stop_music", "music_next", "music_volume")


def просят_музыку(text: str) -> bool:
    """Требуют ли включить музыку — так, что молчаливый отказ будет враньём.

    Та же проверка, что и у движения, и заведена по той же живой беде: «Кузя,
    включи музыку» приехало как «Друзья, включи музыку», правило из-за лишнего
    слова не сработало, фраза ушла модели — и та ответила «Включаю музыку на
    твой вкус», не позвав ни одного инструмента. Тишина, а человек уверен, что
    играет.
    """
    return bool(re.search(
        r"\b(?:включи|поставь|запусти|врубай|врубить)\b.{0,20}"
        r"\b(?:музык\w+|радио|песн\w+|волну|станци\w+|плейлист\w*)\b",
        normalize(text)))


# --- обещание дела без дела -------------------------------------------------
# Та же беда, что с ездой (обещает_движение), только про дела без колёс. С
# живого робота: на «что я делаю» — «Ставлю таймер на 10 минут…», а set_timer
# в журнале нет; на «у меня день рождения первого августа» — «С сегодняшнего
# дня — в памяти!», а в личное дело не записано ничего.
#
# УЗКО, и это главное. Ищем только первое лицо в начале предложения или
# клаузы: «Ставлю таймер», «Хорошо, запомнил.», «— в памяти!». Прошедшее время
# строже настоящего: «ставлю» говорит только я, а «поставил» — и дед в сказке,
# поэтому прошедшее — лишь в начале предложения и без «да» и «уже» впереди:
# «Да, поставил» — ответ о сделанном раньше, а не новое обещание. «Я
# запомнил, что ты любишь чай» — тоже о прошлом: память в прошедшем времени
# считается обещанием, только когда ею клауза и кончается («Запомнил!»).
_ВВОДНОЕ = (r"(?:хорошо|ладно|ок|окей|понял[аи]?|договорились|отлично|конечно|"
            r"ага|есть|итак|так|сейчас|вот|давай|супер|принято|готово)")
_ВВОДНОЕ_БЫЛО = rf"(?:{_ВВОДНОЕ}[\s,!—–-]+)*(?:я\s+)?"
_ВВОДНОЕ_СЕЙЧАС = (rf"(?:(?:{_ВВОДНОЕ}|да|уже)[\s,!—–-]+)*"
                   r"(?:я\s+(?:\w+\s+)?)?")
# Начало предложения — для прошедшего; начало клаузы — для настоящего.
_С_ПРЕДЛОЖЕНИЯ = r"^\s*"
_С_КЛАУЗЫ = r"(?:^|[,—–:;]|\s-)\s*"
# Клауза кончилась: «Запомнил!», «Запомнил, Рома.» — но не «Запомнил, что…».
_КОНЕЦ_КЛАУЗЫ = r"(?=\s*(?:$|[.!?…;—–]|\s-|,\s*\w+\s*(?:$|[.!?…])))"
_ДЕЛО_СРОК = r"(?:таймер|будильник|напоминани)"
_ДЕЛО_ЗВУК = r"(?:музык|песн|радио|волн|трек|плейлист|мелоди|станци)"
_ДЕЛО_ЭКРАН = r"(?:мульт|видео|ролик|клип)"
# Между глаголом и делом в прошедшем — только эти слова: «поставил тебе
# таймер», «включил твою волну». «Поставил дед будильник» — сказка.
_МЕЖДУ_БЫЛО = (r"(?:\s+(?:тебе|вам|себе|новый|новую|еще|один|твою|твой|твои|"
               r"свою|любимую|веселую|спокойную|детскую|другую))?\s+")
_ОБЕЩАНИЯ = (
    ("таймер", re.compile(
        rf"{_С_КЛАУЗЫ}{_ВВОДНОЕ_СЕЙЧАС}(?:ставлю|поставлю|завожу|заведу|"
        rf"запускаю|запущу|устанавливаю|установлю)"
        rf"(?:\s+\w+){{0,2}}?\s+{_ДЕЛО_СРОК}"
        rf"|{_С_КЛАУЗЫ}{_ВВОДНОЕ_СЕЙЧАС}разбужу\b"
        rf"|{_С_КЛАУЗЫ}{_ВВОДНОЕ_СЕЙЧАС}напомню(?:\s+(?:тебе|вам))?\s+"
        r"(?:через|в|во|к|завтра|утром|днем|вечером|позже|попозже|потом)\b")),
    ("таймер", re.compile(
        rf"{_С_ПРЕДЛОЖЕНИЯ}{_ВВОДНОЕ_БЫЛО}(?:поставил|завел|запустил|установил)"
        rf"{_МЕЖДУ_БЫЛО}{_ДЕЛО_СРОК}")),
    ("память", re.compile(
        rf"{_С_КЛАУЗЫ}{_ВВОДНОЕ_СЕЙЧАС}(?:запоминаю|запомню|записываю|запишу|"
        r"сохраняю|сохраню|заношу|занесу)\b")),
    ("память", re.compile(
        rf"{_С_ПРЕДЛОЖЕНИЯ}{_ВВОДНОЕ_БЫЛО}(?:запомнил|записал|сохранил|занес|"
        r"записано|запомнено|сохранено)"
        r"(?:\s+(?:это|себе|тебя|навсегда|в\s+памят\w*|в\s+список))*"
        rf"{_КОНЕЦ_КЛАУЗЫ}"
        # «С сегодняшнего дня — в памяти!»: клауза из одной памяти.
        rf"|{_С_КЛАУЗЫ}(?:{_ВВОДНОЕ}[\s,!—–-]+)*(?:теперь\s+|это\s+|все\s+)*"
        rf"в\s+(?:моей\s+)?памяти{_КОНЕЦ_КЛАУЗЫ}")),
    ("музыка", re.compile(
        rf"{_С_КЛАУЗЫ}{_ВВОДНОЕ_СЕЙЧАС}(?:включаю|включу|ставлю|поставлю|"
        rf"запускаю|запущу)(?:\s+\w+){{0,2}}?\s+{_ДЕЛО_ЗВУК}"
        rf"|{_С_ПРЕДЛОЖЕНИЯ}{_ВВОДНОЕ_БЫЛО}(?:включил|поставил|запустил)"
        rf"{_МЕЖДУ_БЫЛО}{_ДЕЛО_ЗВУК}")),
    ("видео", re.compile(
        rf"{_С_КЛАУЗЫ}{_ВВОДНОЕ_СЕЙЧАС}(?:включаю|включу|ставлю|поставлю|"
        rf"запускаю|запущу)(?:\s+\w+){{0,2}}?\s+{_ДЕЛО_ЭКРАН}"
        rf"|{_С_ПРЕДЛОЖЕНИЯ}{_ВВОДНОЕ_БЫЛО}(?:включил|поставил|запустил)"
        rf"{_МЕЖДУ_БЫЛО}{_ДЕЛО_ЭКРАН}")),
)

_ПРЕДЛАГАЕТ = re.compile(r"\b(?:если|хочешь|хотите|могу|можно)\b")

