"""Найти в квартире названного — и, если просили, передать ему слова.

    «Кузя, найди собаку»          — поехал, объехал, нашёл, сказал где.
    «Кузя, позови Рому кушать»    — поехал, нашёл Рому, сказал ему «кушать».

ПОЧЕМУ ОДИН МЕХАНИЗМ, А НЕ ДВА. Потому что это одно и то же дело: доехать,
осмотреться, узнать названного, что-то сделать. Разное в нём только «кого
ищем» и «что сказать, когда найду». Написать сперва поиск собаки, а потом
поиск человека — значит получить две копии, которые разойдутся на первой же
правке, и разойдутся молча.

──────────────────────────────────────────────────────────────────────────────
ГДЕ ИСКАТЬ. Не фронтиром, и это главное отличие от обхода.

Обход спрашивает «где я не был» — ему нужно покрытие. Поиску нужен другой
вопрос: «где ОНА обычно бывает». Разница видна на первой же минуте: собака
девять раз из десяти лежит на своём месте, а фронтир погонит робота в
неосмотренный угол за шкафом.

Порядок точек, от самого вероятного к последнему доводу:

  1. ГДЕ ВИДЕЛИ ПОСЛЕДНИЙ РАЗ. Память вещей помнит направление из точки, где
     робот тогда стоял. Живёт недолго — собака не мебель.
  2. ИЗЛЮБЛЕННЫЕ МЕСТА. Где её находили раньше. Копится наблюдением, переживает
     перезапуск, схлопывается по тому же радиусу, что и пометки.
  3. МЕБЕЛЬ ИЗ ОПИСИ. Робот объехал квартиру и знает, где кровать и диван, —
     вот описи и применение. Для человека мебель другая: стол и стул.
  4. НЕОСМОТРЕННОЕ. Через тот же атлас, что и у обхода.
  5. ЗНАКОМЫЕ МЕСТА. Последним доводом: куда вообще можно доехать по карте.
     Без него полная карта делала поиск БЕСПОЛЕЗНЕЕ пустой — неизведанного
     не остаётся, и робот, знающий квартиру наизусть, сдавался с одной точки.
     См. atlas.куда_поглядеть.

Кончились точки всех пяти сортов — говорим «не нашёл» и называем, где
смотрели. Робот, который ищет вечно, хуже робота, который честно сдался.

Куда уже съездили в этот поиск — помним, иначе источники, отдающие СПИСОК
точек, возвращали бы одну и ту же вечно.

──────────────────────────────────────────────────────────────────────────────
ЧЕГО ЭТОТ ПОИСК НЕ УМЕЕТ, и сказать это надо сразу.

ОН НЕ РАЗЛИЧАЕТ ЛЮДЕЙ ПО ЛИЦУ. Сеть говорит «человек», а не «Рома». Поэтому
«позови Рому» работает честно: робот находит ЧЕЛОВЕКА, подъезжает и
обращается к нему по имени вслух. Если это не Рома — человек так и скажет, и
это лучше, чем робот, молча решивший, что нашёл нужного. Голос робот
различает (на ПК живут отпечатки), но для этого человек должен заговорить, а
он сперва должен услышать обращение.

ОН НЕ РАЗЛИЧАЕТ ДВУХ СОБАК. У сети нет номеров, которым можно верить.

ОН НЕ ХОДИТ ПО КОМНАТАМ. Комнат робот не знает — у него нет ни лидара, ни
разметки. Он едет к точкам, а не «на кухню».
"""

from __future__ import annotations

import json
import logging
import math
import threading
import time
from pathlib import Path

from . import landmarks, planner, ride, things, vocabulary

log = logging.getLogger(__name__)

# Как быстро едем в поиске. Быстрее обхода: обход едет в неизвестность и
# осматривает каждый метр, а поиск едет к ИЗВЕСТНОЙ точке по уже накопленной
# карте. Но не быстрее следования — впереди может оказаться тот, кого ищем.
ЕДЕМ_НЕ_БЫСТРЕЕ = 0.22
ПОВОРОТ_В_ПОИСКЕ = 0.5
# Как крутимся, осматриваясь. То же, что в обходе: кадр просят стоя, и
# скорость поворота влияет только на дорогу между взглядами.
ПОВОРОТ_ОСМОТРА = 0.9
# На сколько частей делим круг при осмотре с места. Шесть: поле камеры сто
# тридцать градусов, соседние взгляды перекрываются вдвое.
ВЗГЛЯДОВ_ЗА_КРУГ = 6
# Сколько ждём ответа сети на один взгляд. Потолок, а не такса: пришёл
# раньше — едем дальше.
ЖДЁМ_СЕТЬ = 2.0
# Сколько метров за один переезд к точке.
ПЕРЕЕЗД_МЕТРОВ = 2.0
# Сколько помним неудачную точку, чтобы не биться в неё по кругу.
ЗАБЫВАЕМ_НЕУДАЧУ = 30.0

# Сколько всего ищем, если не прервать. Три минуты: дольше человек ждать не
# станет, а робот за это время объедет привычные места дважды.
ХВАТИТ_ЧЕРЕЗ = 180.0
# Сколько точек осматриваем, прежде чем признать, что не нашли.
ТОЧЕК_НЕ_БОЛЬШЕ = 8

# Сколько живёт «где видели последний раз». Две минуты: собака не мебель, и
# вчерашнее направление никуда не ведёт.
ПОСЛЕДНЕЕ_ЖИВЁТ = 120.0
# С какого числа встреч точка считается излюбленным местом. Три: один раз —
# случайность, два — совпадение.
МЕСТО_С_ТРЁХ = 3
# Ближе этого две находки считаются одним местом. Тот же радиус, что у
# пометок: разные числа для одного вопроса однажды разъедутся.
ОДНО_МЕСТО = landmarks.ОДНА_ВЕЩЬ

# На какую дистанцию подъезжаем к найденному, прежде чем говорить.
ПОДОЙТИ_НА = 1.2

# Насколько заход обязан сократить путь до точки, чтобы считаться заходом.
#
# Полметра — это четверть переезда. Меньше бывает и при честной езде в обход
# препятствия, поэтому порог низкий; а вот робот, ползающий вдоль стены, не
# набирает и этого. Без такой проверки он выбирал бы одну и ту же точку до
# конца запаса поездок: она по-прежнему ближайшая и по-прежнему не вычеркнута,
# а `_доехать` честно говорит «вышло» на каждые десять сантиметров.
ПОДВИНУЛИСЬ = 0.5
# Насколько точно доворачиваемся на найденного.
ДОВЕРНУТЬ_ТОЧНЕЕ = math.radians(12.0)

# Кого где искать. Собака лежит на мягком, человек сидит за столом — и
# перебирать ради человека кровати так же глупо, как ради собаки стулья.
ГДЕ_БЫВАЮТ = {
    "dog": ("bed", "couch", "armchair", "chair", "bench"),
    "cat": ("bed", "couch", "armchair", "chair", "windowsill"),
    "person": ("chair", "couch", "dining table", "desk", "bed"),
}
ГДЕ_БЫВАЮТ_ОБЫЧНО = ("couch", "chair", "bed", "dining table")


class Места:
    """Где робот находил названного раньше. Переживает перезапуск.

    ПОЧЕМУ ЭТО НЕ ПОМЕТКИ. Пометки — про мебель: она стоит и не двигается,
    и место у неё одно. Собака бывает в трёх местах, и все три настоящие;
    сложить их в одну пометку значило бы получить точку между ними, где её не
    бывает никогда.

    ПОЧЕМУ КООРДИНАТЫ ЧЕСТНЫЕ. Они те же, что у пометок, а пометки
    привязываются к вчерашней карте по узнанной мебели. Пока привязки нет,
    места молчат: одометрия после включения начинается с нуля, и вчерашние
    числа в ней означают другое место квартиры. Молчать честнее, чем везти
    человека в стену.
    """

    def __init__(self, файл=None, часы=time.time) -> None:
        self.файл = Path(файл) if файл else None
        self._часы = часы
        self.где: dict[str, list[dict]] = {}
        self._прочитать()

    def _прочитать(self) -> None:
        if self.файл is None or not self.файл.exists():
            return
        try:
            прочитано = json.loads(self.файл.read_text(encoding="utf-8"))
            if isinstance(прочитано, dict):
                self.где = {к: list(в) for к, в in прочитано.items()
                            if isinstance(в, list)}
        except (OSError, ValueError):
            log.warning("места: файл %s не читается — начинаю с чистого",
                        self.файл)

    def сохранить(self) -> None:
        if self.файл is None:
            return
        try:
            self.файл.parent.mkdir(parents=True, exist_ok=True)
            врем = self.файл.with_name(self.файл.name + ".tmp")
            врем.write_text(json.dumps(self.где, ensure_ascii=False),
                            encoding="utf-8")
            врем.replace(self.файл)
        except OSError as e:
            log.warning("места: не записались (%s)", e)

    def заметить(self, кого: str, x: float, y: float) -> None:
        """Здесь его нашли. Рядом с прежней находкой — та же точка."""
        точки = self.где.setdefault(кого, [])
        for точка in точки:
            if math.hypot(точка["x"] - x, точка["y"] - y) <= ОДНО_МЕСТО:
                # Середина скользящим средним, а не заменой: одна находка не
                # должна утаскивать место на полметра.
                сколько = точка["раз"] + 1
                точка["x"] += (x - точка["x"]) / сколько
                точка["y"] += (y - точка["y"]) / сколько
                точка["раз"] = сколько
                точка["когда"] = self._часы()
                self.сохранить()
                return
        точки.append({"x": float(x), "y": float(y), "раз": 1,
                      "когда": self._часы()})
        self.сохранить()

    def любимые(self, кого: str) -> list[tuple[float, float]]:
        """Излюбленные места, от частого к редкому. Пустой список — не знаем."""
        годные = [т for т in self.где.get(кого, [])
                  if т.get("раз", 0) >= МЕСТО_С_ТРЁХ]
        годные.sort(key=lambda т: (-т.get("раз", 0), -т.get("когда", 0)))
        return [(т["x"], т["y"]) for т in годные]


def кого_ищем(слово: str) -> str:
    """Слово человека → класс сети. Пусто — не знаем такого.

    Через общий словарь, а не своей таблицей: имена вещей у нас в одном
    месте, и вторая копия однажды разойдётся с первой.

    ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ: правила «незнакомое слово — значит имя человека».
    Оно напрашивается («найди Рому»), и оно превращает опечатку в поездку:
    «найди холодильникус» отправило бы робота искать человека. Про людей
    знает `кого_звать` — и знает не по слову, а по ГЛАГОЛУ: «позови» и
    «найди» просят разного.
    """
    return things.распознать(слово) if слово else ""


def кого_звать(имя: str) -> str:
    """«Позови Рому» — это человек, как бы его ни звали.

    Имён сеть не различает: она говорит «человек», а не «Рома». Поэтому
    зовущий глагол и есть всё, что нам нужно знать, — а само имя пойдёт в
    обращение вслух, когда робот кого-нибудь найдёт.
    """
    return "person" if (имя or "").strip() else ""


def где_бывает(кого: str) -> tuple:
    """На какой мебели искать. Собака лежит на мягком, человек сидит за столом."""
    return ГДЕ_БЫВАЮТ.get(кого, ГДЕ_БЫВАЮТ_ОБЫЧНО)


class Поиск(ride.Переезд):
    """Найти названного в квартире и, если просили, передать ему слова."""

    def __init__(self, ros, tof, *, план=None, карта=None, пометки=None,
                 вещи=None, компас=None, места=None, говорить=None) -> None:
        self.ros = ros
        self.tof = tof
        self.план = план
        self.карта = карта
        self.пометки = пометки
        self.вещи = вещи
        self.компас = компас
        self.места = места
        self.говорить = говорить or (lambda фраза: None)
        self.выбираюсь = planner.Выбираюсь()
        self._поток: threading.Thread | None = None
        self._стоп = threading.Event()
        self._велели = (0.0, 0.0)
        self.проехали = 0.0
        # Числа политики — свои: поиск едет к известной точке, обход в
        # неизвестность. Механика езды у них общая (ride.Переезд).
        self.едем_не_быстрее = ЕДЕМ_НЕ_БЫСТРЕЕ
        self.поворот_на_ходу = ПОВОРОТ_В_ПОИСКЕ
        self.поворот_на_месте = ПОВОРОТ_ОСМОТРА
        self.переезд_метров = ПЕРЕЕЗД_МЕТРОВ
        self.забываем_неудачу = ЗАБЫВАЕМ_НЕУДАЧУ
        # Итоги последнего поиска — чтобы про них можно было спросить потом.
        self.кого = ""
        self.сказать_ему = ""
        self.молча = False
        self.нашёл = False
        self.осмотрено = 0
        self.почему_кончилось = ""
        # ПРЕРВАЛИ ЛИ НАС СНАРУЖИ. Раньше это выяснялось сравнением
        # `почему_кончилось` со строкой «сказали стоп», и на живом роботе
        # сравнение промахнулось: ладонь и слово «стоять» доходят до поиска
        # через `ros.stop_motion`, а тот пишет свою причину — «остановили».
        # Промах стоил ложного доклада: человек сказал «стоять», а робот
        # ответил «Не нашёл. Нигде нет: собака», хотя не успел даже
        # оглядеться. Факт остановки снаружи — это факт, а не текст.
        self._прервали = False
        self._неудачные: list[tuple[float, float, float]] = []
        # ГДЕ УЖЕ ПОСМОТРЕЛИ В ЭТОТ ПОИСК. Живёт один поиск и не забывается по
        # сроку — в отличие от неудачных, которые через полминуты стоит
        # попробовать снова.
        #
        # Без этого списка любой источник, отдающий СПИСОК точек, зацикливал
        # поиск: `_куда_смотреть` каждый раз строит перебор заново и
        # возвращает первую подходящую, а «подходящая» после осмотра не
        # менялась ничем. Робот съездил бы к ближайшей точке, осмотрелся,
        # снова получил бы её же — и так до предела по числу точек. Пока
        # работал один атлас, беда не всплывала: он отдаёт направление ОТ
        # НЫНЕШНЕЙ позы, и точка уезжала вместе с роботом.
        self._осмотренные: list[tuple[float, float]] = []
        # Удалось ли оглядеться кругом на последней остановке. См. _осмотреться.
        self._кругом_вышло = True

    # --- снаружи ---------------------------------------------------------
    @property
    def идёт(self) -> bool:
        return self._поток is not None and self._поток.is_alive()

    def начать(self, кого: str, *, сказать: str = "", вслух: str = "",
               вытеснять: bool = True, молча: bool = False) -> str:
        """Пойти искать. Отдаёт фразу, которую робот скажет сразу.

        `вытеснять` — освободить ли колёса перед стартом. По умолчанию да:
        две команды на один топик означают, что робот едет в среднее место.
        Выключается ровно в одном случае — когда поиск заводит СПУТНИК,
        потерявший собаку. Спутник сам заявлен движителем, и вытеснение
        остановило бы его же, то есть того, кто поиск и затеял.

        `молча` — не докладывать голосом. Тоже про Спутника: доклад про
        собаку делает он сам и ровно один раз, а поиск внутри него —
        служебный шаг, а не отдельное поручение.
        """
        if self.идёт:
            return "Уже ищу."
        класс = кого_ищем(кого)
        if not класс:
            return f"Не знаю, кто такой {кого}."
        if self.ros is None or self.tof is None:
            return "Не могу ехать: колёса или дальномер не отвечают."
        if вытеснять:
            # Колёса у одного хозяина — тот же довод, что у обхода и
            # следования. Без этой строки «иди за мной», а следом «найди
            # собаку» давали два потока, публикующих в один /cmd_vel.
            освободить = getattr(self.ros, "stop_motion", None)
            if освободить is not None:
                try:
                    освободить()
                except Exception:               # noqa: BLE001
                    log.exception("не смог освободить колёса перед поиском")
        self.молча = молча
        self.кого = класс
        self.сказать_ему = сказать
        self.нашёл = False
        self.осмотрено = 0
        self.почему_кончилось = ""
        self._прервали = False
        self._неудачные.clear()
        self._осмотренные.clear()
        self._кругом_вышло = True
        self._стоп.clear()
        self.выбираюсь.сбросить()
        self._поток = threading.Thread(target=self._искать, daemon=True)
        self._поток.start()
        return вслух or f"Пошёл искать: {self._имя()}."

    def хватит(self, почему: str = "", *, ждать: bool = True) -> bool:
        """Прекратить поиск. False — он и не шёл."""
        if not self.идёт:
            return False
        self.почему_кончилось = почему or "сказали стоп"
        self._прервали = True
        self._стоп.set()
        if ждать and self._поток is not None:
            self._поток.join(timeout=3.0)
        return True

    # --- сам поиск -------------------------------------------------------
    def _искать(self) -> None:
        начали = time.monotonic()
        # СЧИТАЕМ ПОЕЗДКИ, А НЕ ТОЛЬКО УДАВШИЕСЯ ОСМОТРЫ.
        #
        # Предел стоял на `осмотрено`, и пока каждая доехавшая точка его
        # увеличивала, этого хватало. Как только несостоявшаяся панорама
        # перестала считаться осмотром (и правильно перестала — робот в
        # неё не повернулся ни разу), предел стал недостижим: зажатый в
        # углу робот ездит от точки к точке, нигде не может оглядеться,
        # `осмотрено` стоит на нуле, и держит его только общий срок в три
        # минуты. Три минуты бессмысленной возни — это не «честно сдался».
        поездок = 0
        try:
            # СНАЧАЛА ОСМОТРЕТЬСЯ, А ПОТОМ ЕХАТЬ. Половина находок случается
            # на месте: собака лежит в этой же комнате, и ехать за ней через
            # всю квартиру, не оглядевшись, — это и есть тот робот, над
            # которым смеются.
            if self._осмотреться():
                return
            while not self._стоп.is_set():
                if time.monotonic() - начали > ХВАТИТ_ЧЕРЕЗ:
                    self.почему_кончилось = "искал слишком долго"
                    break
                if поездок >= ТОЧЕК_НЕ_БОЛЬШЕ:
                    self.почему_кончилось = "обошёл, где мог"
                    break
                куда, откуда_знаю = self._куда_смотреть()
                if куда is None:
                    self.почему_кончилось = "обошёл всё, что помню"
                    break
                log.info("поиск: еду смотреть %s (%s)",
                         self._место_словами(куда), откуда_знаю)
                было_далеко = self._далеко_ли(куда)
                if not self._доехать(куда):
                    self._не_вышло(куда)
                    continue
                поездок += 1
                # ПРИБЛИЗИЛИСЬ ЛИ ВООБЩЕ. `_доехать` говорит «вышло», если
                # колёса прокрутились хоть на десять сантиметров, — а робот,
                # упёршийся в стену на пути к точке, ползает вдоль неё и
                # каждый раз честно «проезжает». Без этой проверки он выбирал
                # бы ту же точку снова и снова, пока не кончится запас
                # поездок: она ведь по-прежнему ближайшая и по-прежнему не
                # вычеркнута.
                стало_далеко = self._далеко_ли(куда)
                if (было_далеко is not None and стало_далеко is not None
                        and стало_далеко > было_далеко - ПОДВИНУЛИСЬ):
                    log.info("поиск: к %s не приблизился (%.1f → %.1f м) — "
                             "вычёркиваю", self._место_словами(куда),
                             было_далеко, стало_далеко)
                    self._не_вышло(куда)
                    continue
                if self._осмотреться():
                    return
                # Оглядеться не дали — место не осмотрено, что бы ни говорил
                # счётчик. Пишем в неудачные, а не в осмотренные: через
                # полминуты робот будет стоять иначе, и попытка станет другой.
                if not self._кругом_вышло:
                    self._не_вышло(куда)
                elif self._дошли(куда):
                    self.осмотрено += 1
                    self._посмотрел(куда)
                else:
                    # Проехали, но не приехали: за раз едем не дальше переезда.
                    # Точку НЕ вычёркиваем — следующим кругом она снова
                    # окажется ближайшей, и робот продолжит к ней. Иначе он
                    # объявлял бы осмотренным то, до чего не доехал, и брал
                    # следующую ближайшую — то есть снова возле себя.
                    log.info("поиск: до %s ещё далеко — еду дальше",
                             self._место_словами(куда))
        except Exception:                       # noqa: BLE001
            log.exception("поиск: сорвался")
            self.почему_кончилось = "что-то пошло не так"
        finally:
            self._встать()
            self._доложить()

    def _осмотреться(self) -> bool:
        """Панорама с места. True — нашли и всё сделали.

        ОТКАЗ ПОВЕРНУТЬСЯ — ЭТО КОНЕЦ ПАНОРАМЫ, А НЕ ПОВОД ПОСМОТРЕТЬ ЕЩЁ РАЗ
        ТУДА ЖЕ. Живой журнал, шесть строк подряд за пять секунд:

            обход: на месте не разворачиваюсь — вплотную что-то в 0.3 м
            обход: на месте не разворачиваюсь — вплотную что-то в 0.3 м
            ... ещё четыре таких же ...
            робот: Не нашёл. Нигде нет: собака. Смотрел в 1 местах.

        Робот стоял носом в батарею. `_повернуть` честно возвращал False —
        память не пускает крутиться, корпус заметает круг вслепую, — но
        возврат никто не смотрел, и цикл просто шёл дальше. Шесть взглядов в
        ОДНУ И ТУ ЖЕ точку, шесть запросов к сети, пять секунд, и место
        засчитано осмотренным.

        Разжимать себя здесь не будем, и это осознанно: отъезд назад слеп
        (дальномер смотрит вперёд), и все ограничения на него живут в лестнице
        выбирания — не дальше двадцати сантиметров, вдвое медленнее, только по
        своему следу. Дублировать её тут значило бы завести второй, более
        глупый задний ход. Правильный выход проще: панораму прекратить, место
        осмотренным НЕ считать, и пусть цикл поиска едет к следующей точке —
        по дороге туда лестница выбирания отработает как надо.

        `_кругом_вышло` читает `_искать`: место, где не удалось оглядеться,
        честнее записать в неудачные и вернуться к нему позже, чем объявить
        осмотренным.
        """
        self._кругом_вышло = True
        for взгляд in range(ВЗГЛЯДОВ_ЗА_КРУГ):
            if self._стоп.is_set():
                self._кругом_вышло = False
                return False
            if self._взглянуть():
                return self._нашли()
            if взгляд == ВЗГЛЯДОВ_ЗА_КРУГ - 1:
                break               # последний взгляд, доворачивать незачем
            if not self._повернуть(2 * math.pi / ВЗГЛЯДОВ_ЗА_КРУГ):
                log.info("поиск: повернуться не дали — оглядеться отсюда не "
                         "вышло (успел %d взглядов из %d)",
                         взгляд + 1, ВЗГЛЯДОВ_ЗА_КРУГ)
                self._кругом_вышло = False
                break
        return False

    def _взглянуть(self) -> bool:
        """Один кадр сети. True — названный в кадре.

        ОДИН КАДР, А НЕ ТРИ. Затвор умеет и то и другое; обходу нужны три
        (встал, попросил раз, второй попытки не будет), поиску — один: он
        просит на каждом повороте, и втрое дороже там, где просят втрое чаще.
        """
        if self.ros is None or self.вещи is None:
            return False
        self._встать()
        # СВОЙСТВО, А НЕ МЕТОД. Со скобками здесь стоял TypeError, и поиск
        # срывался на первой же строке — до единого движения. Соседний обход
        # берёт то же самое через getattr и потому не падал; я написал иначе,
        # а проверки этот путь не трогали вовсе.
        было = self.вещи.отвечали
        try:
            self.ros.посмотреть_разок()
        except Exception:                       # noqa: BLE001
            log.exception("поиск: не смог попросить кадр")
            return False
        ждём = time.monotonic() + ЖДЁМ_СЕТЬ
        ответила = False
        while time.monotonic() < ждём and not self._стоп.is_set():
            if self.вещи.отвечали != было:
                ответила = True
                break
            self._стоп.wait(ride.ШАГ)
        # `видно` отдаёт СПИСОК ВСТРЕЧ, а не пары. Здесь стояло
        # `dict(...)` — третья по счёту ошибка обращения к `вещи` в этой
        # функции, и опять TypeError на роботе. Пустая заглушка в проверках
        # её прятала: dict() от пустого списка выходит успешно.
        видно = self.вещи.видно(свежее=ЖДЁМ_СЕТЬ) or []
        нашли = any(getattr(в, "класс", "") == self.кого for в in видно)
        # ЧТО СЕТЬ ВИДЕЛА — В ЖУРНАЛ, И ИМЕННО КОГДА НЕ НАШЛИ.
        #
        # «Он не нашёл, хотя смотрел прямо на собаку» — на это журнал ответить
        # не мог ничем. Про взгляд в нём стояло РОВНО НИЧЕГО: одна строка
        # «вещи: первый ответ разобран» за весь поиск, и дальше сразу «не
        # нашёл». Отсюда неотличимы три совершенно разных случая: сеть не
        # ответила вовсе; ответила, но не увидела никого; увидела собаку под
        # другим именем или ниже порога уверенности. Лечатся они по-разному, а
        # выглядят одинаково.
        #
        # Пишем на каждом взгляде, потому что взглядов за поиск немного —
        # шесть на панораму, — а цена молчания здесь ровно та, что видно выше.
        if not нашли:
            log.info("поиск: взглянул — %s (искал %s)",
                     ", ".join(f"{getattr(в, 'класс', '?')} "
                               f"{getattr(в, 'уверенность', 0.0):.2f}"
                               for в in видно)
                     or ("сеть не ответила за %.1f с" % ЖДЁМ_СЕТЬ
                         if not ответила else "сеть ответила, но никого"),
                     self.кого)
        return нашли

    def _нашли(self) -> bool:
        """Подъехать, сказать, запомнить место. Всегда True."""
        self.нашёл = True
        встреча = self.вещи.найти(self.кого) if self.вещи else None
        угол = float(getattr(встреча, "угол", 0.0) or 0.0)
        if abs(угол) > ДОВЕРНУТЬ_ТОЧНЕЕ:
            self._повернуть(угол)
        # Подъезжать НЕ ОБЯЗАТЕЛЬНО и не всегда можно: собака могла лечь в
        # угол, куда робот не влезает. Не доехали — говорим оттуда, где
        # стоим. Найти и сказать важнее, чем встать ровно.
        взгляд = self.tof.взгляд() if self.tof is not None else None
        свободно = getattr(взгляд, "свободно_впереди", 0.0) if взгляд else 0.0
        if свободно > ПОДОЙТИ_НА:
            self._ехать(свободно - ПОДОЙТИ_НА)
        self._встать()
        поза = self._поза()
        if поза is not None:
            if self.места is not None:
                try:
                    self.места.заметить(self.кого, поза[0], поза[1])
                except Exception:               # noqa: BLE001
                    log.exception("поиск: место не запомнилось")
        self.почему_кончилось = "нашёл"
        return True

    # --- куда ехать ------------------------------------------------------
    def _куда_смотреть(self):
        """Следующая точка и откуда мы про неё знаем. (None, причина) — некуда."""
        поза = self._поза()
        for точка, откуда in self._все_точки(поза):
            if точка is None or self._уже_не_вышло(точка):
                continue
            if self._уже_смотрел(точка):
                continue
            return точка, откуда
        return None, "точек больше нет"

    def _уже_смотрел(self, точка) -> bool:
        return any(math.hypot(x - точка[0], y - точка[1]) < ОДНО_МЕСТО
                   for x, y in self._осмотренные)

    def _посмотрел(self, точка) -> None:
        self._осмотренные.append((точка[0], точка[1]))

    def _все_точки(self, поза):
        """Точки по убыванию вероятности. Порядок — в шапке модуля."""
        # 1. Где видели последний раз.
        встреча = self.вещи.найти(self.кого) if self.вещи else None
        # Возраст — у памяти, теми же часами, которыми метка и ставилась.
        # Прежнее `time.time() - встреча.когда` смешивало настенные часы с
        # монотонными, и первый — САМЫЙ ВЕРОЯТНЫЙ — источник точек не выдавал
        # ничего никогда. Робот шёл искать куда угодно, кроме места, где
        # только что видел.
        если_свежая = (встреча is not None
                       and self.вещи.давно_ли(встреча) < ПОСЛЕДНЕЕ_ЖИВЁТ)
        if если_свежая:
            куда = встреча.где
            if куда is not None:
                yield куда, "там видели в последний раз"
        # 2. Излюбленные места — только если карта привязана к вчерашней.
        if self.места is not None and self._привязаны():
            for точка in self.места.любимые(self.кого):
                yield точка, "там его обычно находят"
        # 3. Мебель из описи.
        if self.пометки is not None:
            где = где_бывает(self.кого)
            for метка in self._мебель_по_близости(поза):
                if метка.get("класс") in где:
                    yield (метка["x"], метка["y"]), "там подходящая мебель"
        # 4. Неосмотренное.
        #
        # АТЛАС ОТВЕЧАЕТ НЕ ТОЧКОЙ, А НАПРАВЛЕНИЕМ, и здесь его ответ клали в
        # список точек как есть. Это самая дорогая ошибка этого файла, потому
        # что этот источник — ЕДИНСТВЕННЫЙ, который работает у свежего робота:
        # первые три требуют либо свежей встречи, либо привязанной карты с
        # тремя посещениями, либо описи мебели. Ничего этого после включения
        # нет.
        #
        # `куда_неизвестно` отдаёт `(курс в мире, сколько новых клеток)` — это
        # написано в её собственной подписи, и соседний обход так её и
        # читает: «доворачиваю на курс, еду переезд». А здесь пара уезжала в
        # `_доехать`, где первое число становилось иксом в метрах, а второе —
        # игреком:
        #
        #     куда = (1.2 рад, 30 клеток)  →  точка (1.2 м, 30.0 м)
        #     далеко = 30 м, нужный курс = 88° вместо 69°
        #
        # То есть робот доворачивался почти перпендикулярно тому, куда стоило
        # ехать, и «расстоянием» ему служил счётчик клеток. Второе число —
        # это ОЦЕНКА, сколько нового по лучу, а не сколько метров.
        if self.план is not None and поза is not None:
            try:
                ответ = self.план.куда_неизвестно(поза)
            except Exception:                   # noqa: BLE001
                log.debug("поиск: атлас не ответил", exc_info=True)
                ответ = None
            if ответ is not None:
                курс = float(ответ[0])
                # Один переезд в ту сторону — ровно так же поступает обход.
                # Ехать «до неизвестного» нельзя: атлас не говорит, далеко ли
                # оно, и приехать туда одним махом всё равно не выйдет.
                yield (поза[0] + self.переезд_метров * math.cos(курс),
                       поза[1] + self.переезд_метров * math.sin(курс)), \
                    "туда ещё не смотрел"

        # 5. ЗНАКОМЫЕ МЕСТА — последним доводом, когда кончилось всё.
        #
        # Четырёх источников не хватало ровно там, где робот прожил в доме
        # дольше дня. Живой журнал:
        #
        #     атлас: помню 4557 клеток квартиры (45.6 м²) за 0 поездок
        #     поиск: еду смотреть точку -2.5, -2.4 (туда ещё не смотрел)
        #     поиск: не нашёл dog — обошёл всё, что помню (точек 1)
        #
        # Неизведанного не осталось, потому что карта ПОЛНАЯ. Свежей встречи
        # нет, привязки нет, описи мебели нет — и «найди собаку» в квартире на
        # сорок пять метров кончилось одной точкой и словами «Смотрел в 1
        # местах». То есть чем дольше робот живёт в доме, тем хуже ищет: это
        # ровно наоборот тому, как должно быть.
        #
        # Знакомые проезжие места и есть тот самый последний довод. Они не
        # вероятнее прочих — потому и стоят последними, — но их много, они
        # покрывают квартиру, и «объехать и посмотреть» всегда лучше, чем
        # сдаться с места.
        if self.план is not None and поза is not None:
            try:
                знакомые = self.план.куда_поглядеть(поза)
            except Exception:                   # noqa: BLE001
                log.debug("поиск: атлас не отдал знакомых мест", exc_info=True)
                знакомые = ()
            for точка in знакомые:
                yield точка, "туда можно доехать и посмотреть"

    def _мебель_по_близости(self, поза):
        try:
            метки = list(self.пометки.надёжные())
        except Exception:                       # noqa: BLE001
            log.debug("поиск: пометки не отдались", exc_info=True)
            return []
        if поза is None:
            return метки
        метки.sort(key=lambda м: math.hypot(м.get("x", 0.0) - поза[0],
                                            м.get("y", 0.0) - поза[1]))
        return метки

    def _привязаны(self) -> bool:
        """Знаем ли, где стоим относительно вчерашней карты.

        Без привязки вчерашние координаты означают другое место квартиры:
        одометрия после включения начинается с нуля. Молчать честнее, чем
        везти человека в стену.
        """
        if self.пометки is None:
            return False
        try:
            return not self.пометки.с_прошлого_раза
        except Exception:                       # noqa: BLE001
            return False

    def _уже_не_вышло(self, точка) -> bool:
        сейчас = time.monotonic()
        self._неудачные = [(x, y, к) for x, y, к in self._неудачные
                           if сейчас - к < self.забываем_неудачу]
        return any(math.hypot(x - точка[0], y - точка[1]) < ОДНО_МЕСТО
                   for x, y, _ in self._неудачные)

    def _не_вышло(self, точка) -> None:
        self._неудачные.append((точка[0], точка[1], time.monotonic()))
        log.info("поиск: до %s не доехал — вычёркиваю на %.0f с",
                 self._место_словами(точка), self.забываем_неудачу)

    def _далеко_ли(self, куда) -> float | None:
        """Сколько метров до точки. None — одометрии нет, мерить нечем."""
        поза = self._поза()
        if поза is None:
            return None
        return math.hypot(куда[0] - поза[0], куда[1] - поза[1])

    def _дошли(self, куда) -> bool:
        """Стоим ли мы уже у этой точки.

        ЗАЧЕМ ОТДЕЛЬНО ОТ `_доехать`. Тот едет НЕ ДАЛЬШЕ ОДНОГО ПЕРЕЕЗДА —
        двух метров, — и возвращает «вышло» и тогда, когда до точки осталось
        ещё три. Цикл поиска на этом помечал точку осмотренной вместе с шаром
        в 0.8 м вокруг неё, и робот к ней уже не возвращался.

        Пока источником точек был один атлас, беды не было: он отдаёт
        направление, и точка сама лежала ровно в переезде. С появлением
        знакомых мест точки стали настоящими и разбросанными по квартире —
        и почти каждая оказалась дальше переезда. То есть робот «осматривал»
        места, не доехав до них, а следующей выбирал ближайшую из оставшихся,
        то есть снова возле себя: вместо обхода квартиры вышло бы топтание.

        Без одометрии ответить нечем, и тогда честнее «дошли»: иначе поиск
        зациклится на первой же точке, до которой не может проверить путь.
        """
        поза = self._поза()
        if поза is None:
            return True
        return math.hypot(куда[0] - поза[0], куда[1] - поза[1]) < ПОДОЙТИ_НА

    def _доехать(self, куда) -> bool:
        """Подъехать к точке. False — не вышло.

        «Вышло» здесь значит «проехали», а не «приехали»: за один раз едем не
        дальше переезда. Дошли ли — спрашивают отдельно, см. `_дошли`.
        """
        поза = self._поза()
        if поза is None:
            # Без одометрии ехать «к точке» нельзя — можно только вперёд.
            return self._ехать(self.переезд_метров)
        далеко = math.hypot(куда[0] - поза[0], куда[1] - поза[1])
        if далеко < ПОДОЙТИ_НА:
            return True
        нужный = math.atan2(куда[1] - поза[1], куда[0] - поза[0])
        доворот = (нужный - поза[2] + math.pi) % (2 * math.pi) - math.pi
        if abs(доворот) > ДОВЕРНУТЬ_ТОЧНЕЕ:
            self._повернуть(доворот)
        return self._ехать(min(далеко, self.переезд_метров))

    # --- итог ------------------------------------------------------------
    def _имя(self) -> str:
        """Как назвать искомого по-русски. Имена — из общего словаря."""
        имена = vocabulary.ПО_РУССКИ.get(self.кого)
        return имена[0] if имена else self.кого

    def _место_словами(self, точка) -> str:
        return f"точку {точка[0]:+.1f}, {точка[1]:+.1f}"

    def _доложить(self) -> None:
        """Одна фраза в конце. Ровно одна.

        Робот, комментирующий каждый свой шаг, заглушает сам себя — за этим
        потоком не слышно того единственного раза, когда он просит помощи.
        Довод тот же, что записан в шапке обхода со слов хозяина.

        Внутри Спутника молчим совсем: там доклад делает он, и тоже один раз.
        Иначе на одну потерянную собаку пришлось бы две фразы — «не нашёл» от
        поиска и своя от Спутника, — а вторая противоречила бы первой, потому
        что Спутник после находки идёт дальше.
        """
        if self.молча:
            log.info("поиск: %s %s (молча, внутри спутника)",
                     "нашёл" if self.нашёл else "не нашёл", self.кого)
            return
        имя = self._имя()
        if self.нашёл:
            if self.сказать_ему:
                # Сперва слова адресату — за ними и ходили.
                self.говорить(self.сказать_ему)
            else:
                self.говорить(f"Нашёл: {имя}.")
            log.info("поиск: нашёл %s за %d точек", self.кого, self.осмотрено)
            return
        if self._прервали:
            # ПРЕРВАЛИ — МОЛЧИМ. Говорит тот, кто прервал: команда «стоп»
            # отвечает «Искать перестал.» сама (tools.py), а перебивание
            # голосом молчит нарочно — человек кричал не для того, чтобы
            # выслушать ещё одну фразу. Здесь стояло «Прекратил искать.», и
            # на команду «стоп» робот выдавал ДВЕ фразы подряд про одно и то
            # же. Так же молчат обход и следование — оба говорят только о
            # СВОИХ поводах кончить.
            log.info("поиск: прекратил искать %s — %s (точек %d)",
                     self.кого, self.почему_кончилось, self.осмотрено)
            return
        где = (f" Смотрел в {self.осмотрено} местах."
               if self.осмотрено else "")
        # БЕЗ СОГЛАСОВАНИЯ ПО РОДУ. Здесь стояло «{имя} нигде не попался», и
        # на живом роботе это прозвучало как «Собака нигде не попался».
        # Согласовывать род пришлось бы для каждого слова словаря; проще
        # построить фразу так, чтобы род в ней не участвовал вовсе.
        self.говорить(f"Не нашёл. Нигде нет: {имя}.{где}")
        log.info("поиск: не нашёл %s — %s (точек %d)",
                 self.кого, self.почему_кончилось, self.осмотрено)
