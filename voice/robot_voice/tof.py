def аргументы_режима(разрешение: int = РЕЖИМ_8X8, режим: int = 0) -> bytes:
    """0 — выдача матрицы, 1 — обход препятствий (у вендора он назван сырым)."""
    return bytes([режим, 0, 0, разрешение])


