CMD_ALL_DATA = 0x02          # отдать всю сетку разом
CMD_CONFIG = 0x01            # переключить разрешение сетки
РЕЖИМ_8X8 = 0x08
РЕЖИМ_4X4 = 0x04

# Аргументы CMD_CONFIG у вендора — четыре байта: режим, два неизвестных нуля и
