ОБРЫВ_ЗОН = 2
# Сколько кадров учим пол. Двадцать на десяти герцах — две секунды стояния.
УЧИТЬ_КАДРОВ = 20

# На сколько градусов должен уехать наклон датчика, чтобы счесть норму пола
# негодной. Три: меньше — это дрожание подгонки плоскости, больше — робот уже
