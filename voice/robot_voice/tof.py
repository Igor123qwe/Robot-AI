def разброс(числа) -> float | None:
    """Насколько числа гуляют вокруг своей середины. None — замеров мало.

    Считаем срединное отклонение от медианы, а не обычное стандартное. Причина
    та же, что и у медианы вместо среднего: один выброс в одиннадцать градусов
    раздувает стандартное отклонение и вместе с ним порог, а срединное
    отклонение он не двигает. Нам нужен разброс ТИПИЧНОГО замера, а не мера,
    которую определяет самый дурной из них.
    """
    if len(числа) < ШУМА_ХВАТИТ:
        return None
    ряд = sorted(числа)
    середина = ряд[len(ряд) // 2]
    откл = sorted(abs(ч - середина) for ч in числа)
    return откл[len(откл) // 2]


def порог_наклона(числа) -> float:
    """Насколько наклону можно уехать, прежде чем не верить норме пола.

    Отдельной функцией, а не строкой внутри проверки, ровно затем, чтобы её
    можно было проверить тестом. Формула, скопированная в тест, однажды
    разойдётся с кодом и будет проверять саму себя.

    Пока шум не измерен, отдаём САМЫЙ ЧУВСТВИТЕЛЬНЫЙ порог, а не самый
    терпимый: переучивание — это аварийный выход из «норма снята в другой
    геометрии, робот застрял на порожке навсегда», и закрывать выход, пока мы
    ещё ничего не знаем, — худшее из двух. Знать мы начинаем быстро:
    дальномер идёт десять раз в секунду.
    """
    измерен = разброс(числа)
    if измерен is None:
        return НАКЛОН_НЕ_МЕНЬШЕ
    return min(НАКЛОН_НЕ_БОЛЬШЕ,
               max(НАКЛОН_НЕ_МЕНЬШЕ, измерен * НАКЛОН_ЗА_ШУМОМ))


def найти_устройство() -> str:
    """Постоянное имя дальномера, и только оно.

    Рядом на /dev/ttyACM* живёт контроллер приводов, а номера раздаются в
    порядке появления при загрузке и меняются местами. Ошибиться здесь — это
    слать запросы дальности в моторы, поэтому никаких /dev/ttyACM0: ищем по
    имени платы, которое привязано к самому устройству.
    """
    своё = os.environ.get("ROBOT_TOF_DEVICE", "").strip()
    if своё:
        return своё
    # Внутри SEN0628 стоит RP2040, поэтому система зовёт его «Pico».
    for образец in ("*Raspberry_Pi_Pico*", "*RP2040*", "*DFRobot*"):
        нашлось = sorted(glob.glob(f"/dev/serial/by-id/usb-{образец}-if00"))
        if нашлось:
            return нашлось[0]
    return ""


def _кадр(cmd: int, args: bytes = b"") -> bytes:
    """Собрать кадр запроса, как это делает библиотека вендора.

    Число в двух байтах — это НЕ длина аргументов, а длина аргументов ПЛЮС
    ЕДИНИЦА: команда считается вместе с ними. В исходнике DFRobot это выглядит
    как «argsNumL = (length + 1) & 0xFF» при length = 4 и четырёх байтах
    аргументов.

    Я этой единицы не знал и слал на единицу меньше. Прошивка, ожидая на байт
    больше, дочитывала недостающее из НАЧАЛА СЛЕДУЮЩЕГО ПАКЕТА — то есть
    съедала чужой заголовок и получала команду с мусорными аргументами.
    Именно так плата и оказалась в состоянии, из которого её вывело только
    снятие питания. Ошибка тихая: отдельный запрос выглядит правильно, ломает
    её только соседство со следующим.
    """
    длина = len(args) + 1
    return bytes([ЗАГОЛОВОК, (длина >> 8) & 0xFF, длина & 0xFF, cmd]) + args


def разобрать(ответ: bytes) -> tuple[int, bytes] | None:
    """Разобрать кадр ответа: (команда, данные). None — кадр не наш.

    Отдельной функцией, чтобы разбор проверялся без железа: собрать байты в
    проверке легко, а воткнуть датчик в сборочную машину — нет.
    """
    if len(ответ) < 4:
        return None
    состояние, cmd = ответ[0], ответ[1]
    if состояние not in (УДАЧА, ОТКАЗ):
        return None
    длина = ответ[2] | (ответ[3] << 8)
    данные = ответ[4:4 + длина]
    if len(данные) < длина:
        return None
    return (cmd, b"") if состояние == ОТКАЗ else (cmd, данные)


# Плата может отдавать данные строками, сама, без запроса: «y0:1200,1180,...»
# по строке на ряд. Это другой протокол, не тот, что в библиотеке для Arduino,
# и какой из двух живёт в конкретной прошивке — заранее неизвестно. Понимаем
# оба: гадать дешевле один раз в коде, чем каждый раз при перепрошивке.
def строками(текст: str) -> list[list[float]] | None:
    """Разобрать ASCII-вид «y0:…» в метры. None — не тот формат.

    Значения в миллиметрах, 4000 означает «не измерил» — это не расстояние в
    четыре метра, а признак промаха, и путать их нельзя: четыре метра
    выглядят как свободный путь.
    """
    ряды: dict[int, list[float]] = {}
    for строка in текст.splitlines():
        строка = строка.strip()
        if len(строка) < 3 or строка[0] != "y" or ":" not in строка:
            continue
        голова, _, хвост = строка.partition(":")
        try:
            номер = int(голова[1:])
        except ValueError:
            continue
        значения: list[float] = []
        for кусок in хвост.replace(";", ",").split(","):
            кусок = кусок.strip()
            if not кусок:
                continue
            try:
                мм = int(кусок)
            except ValueError:
                значения = []
                break
            значения.append(НЕ_ИЗМЕРИЛ if мм >= 4000 or замер_негоден(мм)
                            else мм / 1000.0)
        if len(значения) in (4, 8) and 0 <= номер < 8:
            ряды[номер] = значения

    # Сетка 4×4 — это те же строки, только четыре по четыре. Понимать её
    # обязательно, а не «на всякий случай»: 4×4 отдаёт вчетверо больше света
    # на зону и потому видит там, где 8×8 молчит, — это единственный рычаг
    # дальности, который у нас вообще есть. Не умей мы её читать, переход на
    # 4×4 выглядел бы как ослепший робот.
    #
    # Растягиваем до восьми на восемь: каждая зона накрывает квадрат два на
    # два. Разрешение от этого не появляется, но весь остальной код —
    # решение о стопе, норма пола, наложение на видео — продолжает работать,
    # не зная о смене режима. Поле зрения ведь то же самое.
    если_четыре = [р for р, з in ряды.items() if len(з) == 4]
    if len(ряды) == 4 and len(если_четыре) == 4 and set(ряды) == {0, 1, 2, 3}:
        крупно = [[ряды[р][к // 2] for к in range(8)] for р in range(4)]
        return [крупно[р // 2][:] for р in range(8)]

    if len(ряды) < 8 or any(len(з) != 8 for з in ряды.values()):
        return None
    return [ряды[р] for р in range(8)]


def сколько_строк(текст: str) -> int:
    """Сколько рядов в потоке: 4 или 8. Ноль — не разобрал.

    Считается по сырому тексту, до растяжения 4×4 до восьми на восемь: после
    него режимы неразличимы, а знать, в каком плата, нужно — от этого зависит
    дальность, и это единственный рычаг, который у нас есть.
    """
    номера = set()
    for строка in текст.splitlines():
        строка = строка.strip()
        if len(строка) > 2 and строка[0] == "y" and ":" in строка:
            try:
                номера.add(int(строка.partition(":")[0][1:]))
            except ValueError:
                continue
    if номера >= {0, 1, 2, 3, 4, 5, 6, 7}:
        return 8
    if номера >= {0, 1, 2, 3}:
        return 4
    return 0


def замер_негоден(мм: int) -> bool:
    """Замер, которому нельзя верить: ноль, отрицательный или в упор."""
    return мм <= 0 or мм < НЕ_ВЕРИМ_БЛИЖЕ * 1000


def сгладить(сетка: list[list[float]]) -> list[list[float]]:
    """Медиана три на три. Убирает одиночные выбросы, край не размывает.

    Соседи берутся только измеренные: усреднять с «не знаю» — значит
    превращать незнание в число, а потом принимать его за расстояние.
    """
    гладко = [[НЕ_ИЗМЕРИЛ] * 8 for _ in range(8)]
    for р in range(8):
        for к in range(8):
            соседи = [сетка[р2][к2]
                      for р2 in range(max(0, р - 1), min(8, р + 2))
                      for к2 in range(max(0, к - 1), min(8, к + 2))
                      if сетка[р2][к2] > НЕ_ИЗМЕРИЛ]
            if соседи:
                соседи.sort()
                гладко[р][к] = соседи[len(соседи) // 2]
    return гладко


def в_метры(данные: bytes) -> list[list[float]]:
    """Сырые байты сетки — в метры, строками сверху вниз.

    Каждая зона — два байта, младший первым, в сантиметрах. Ноль означает
    «не измерил», и он остаётся нулём: заменять его большим числом нельзя,
    иначе стекло и зеркала превратятся в открытый путь.
    """
    точек = min(64, len(данные) // 2)
    плоско = [(данные[2 * i] | (данные[2 * i + 1] << 8)) / 100.0
              for i in range(точек)]
    плоско += [НЕ_ИЗМЕРИЛ] * (64 - точек)
    return [плоско[ряд * 8:(ряд + 1) * 8] for ряд in range(8)]


class Пол:
    """Где у робота пол — чтобы заметить, когда он кончится.

    Норму нельзя вычислить: она зависит от того, на какой высоте и под каким
    наклоном привинчена плата, а это меряется отвёрткой, а не в коде. Поэтому
    робот запоминает её сам, по первым секундам после запуска, и хранит на
    диске — чтобы не переучиваться каждый раз и, главное, чтобы не выучить
    нормой то, что видно с края лестницы.

    Отсюда единственное требование к человеку: включать робота на ровном полу.
    Если он однажды включится у самой ступеньки, файл надо стереть:
        rm ~/.robot-ai/tof_floor.json
    """

    def __init__(self, файл: Path | None = None) -> None:
        self.файл = файл or (Path.home() / ".robot-ai" / "tof_floor.json")
        self.норма: list[list[float]] | None = None
        # В какой ориентации снята норма — ВСЯ ориентация, все четыре
        # признака. Хранится рядом с ней и по той же причине, по которой
        # хранится она сама: снять заново нельзя, не поставив робота обратно
        # на ровный пол.
        #
        # Раньше хранился один признак из четырёх, и этого не хватало:
        # человек ставил галку «поперёк», робот разворачивал сетку — и брал к
        # ней норму, снятую в другой ориентации. То есть искал обрыв не там,
        # где смотрит, и выглядело это исправной работой. Ровно та беда, от
        # которой норма и должна была защищать.
        self.ориентация: tuple | None = None
        # Наклон датчика в тот миг, когда норма снята, градусы вниз.
        #
        # Хранится ровно затем же, зачем ориентация: норма верна только для
        # той геометрии, в которой снята. Но ориентацию меняет человек
        # галкой, а наклон меняет ЕЗДА — колёсная база WD550 всего 19.5 см,
        # и подъём передних колёс на дверной порожек в 17 мм даёт крен в пять
        # градусов. Норма после этого показывает обрыв там, где порожек.
        #
        # None — норма снята до того, как мы научились выводить наклон
        # плоскостью, либо плоскости в том кадре не нашлось. Тогда сверять
        # нечего и мы не сверяем: молча считать «наклон ноль» значило бы
        # переучиваться на ровном месте.
        self.наклон: float | None = None
        # Отказались ли учить норму совсем. Отличать «ещё коплю кадры» от
        # «посмотрел и не принял» ОБЯЗАТЕЛЬНО, и вот почему.
        #
        # `учить` возвращает False в обоих случаях: и пока копится двадцать
        # кадров, и когда норма посчитана и отвергнута. Снаружи стояло
        # «вернул False и нормы нет — значит пол не в кадре, перестаём
        # пробовать». На первом же кадре это условие истинно ВСЕГДА, и защита
        # от обрыва выключалась через сотую долю секунды после запуска.
        #
        # На роботе, у которого файл нормы уже лежал на диске, это не
        # проявлялось: норма грузилась, ветка обучения не входила вовсе. А на
        # новом роботе обрыв не искался НИКОГДА, и файл нормы не появлялся
        # никогда — то есть починить это перезапуском было нельзя.
        self.отказался = False
        self._копилка: list[list[list[float]]] = []

    def загрузить(self) -> bool:
        try:
            данные = json.loads(self.файл.read_text())
        except (OSError, ValueError):
            return False
        норма = данные.get("норма")
        if (isinstance(норма, list) and len(норма) == 8
                and all(isinstance(р, list) and len(р) == 8 for р in норма)):
            self.норма = [[float(з) for з in ряд] for ряд in норма]
            снято = данные.get("ориентация")
            # Норма без записанной ориентации — это норма неизвестно откуда.
            # Такую нельзя ни принять, ни поправить: остаётся не верить.
            self.ориентация = tuple(bool(з) for з in снято) if (
                isinstance(снято, list) and len(снято) == 4) else None
            наклон = данные.get("наклон")
            self.наклон = float(наклон) if isinstance(наклон, (int, float)) else None
            return True
        return False

    def сохранить(self) -> None:
        if self.норма is None:
            return
        try:
            self.файл.parent.mkdir(parents=True, exist_ok=True)
            врем = self.файл.with_name(self.файл.name + ".tmp")
            врем.write_text(json.dumps(
                {"норма": self.норма,
                 "ориентация": list(self.ориентация or ()),
                 "наклон": self.наклон},
                ensure_ascii=False))
            врем.replace(self.файл)
        except OSError as e:
            log.warning("дальномер: не смог запомнить пол (%s)", e)

    def учить(self, сетка: list[list[float]],
              наклон: float | None = None) -> bool:
        """Скормить кадр. True — норма готова прямо сейчас.

        Медиана, а не среднее: одиночный промах не должен сдвигать норму, а
        именно промахов на границе дальности больше всего.
        """
        if self.норма is not None:
            return False
        self._копилка.append([ряд[:] for ряд in сетка])
        if len(self._копилка) < УЧИТЬ_КАДРОВ:
            return False
        норма = [[НЕ_ИЗМЕРИЛ] * 8 for _ in range(8)]
        for р in ОБРЫВ_РЯДЫ:
            for к in range(8):
                замеры = sorted(кадр[р][к] for кадр in self._копилка
                                if кадр[р][к] > НЕ_ИЗМЕРИЛ)
                if len(замеры) >= УЧИТЬ_КАДРОВ * УЧИТЬ_НАДЁЖНОСТЬ:
                    норма[р][к] = замеры[len(замеры) // 2]
        self.норма = норма
        self.наклон = наклон
        self.отказался = False
        self._копилка.clear()
        живых = sum(1 for р in ОБРЫВ_РЯДЫ for к in range(8)
                    if норма[р][к] > НЕ_ИЗМЕРИЛ)
        всего = len(ОБРЫВ_РЯДЫ) * 8
        log.info("дальномер: запомнил пол по %d зонам из %d", живых, всего)

        # А ТЕПЕРЬ — НА КАКОМ РАССТОЯНИИ этот пол. Числа зон мало, и это
        # выяснилось на живом роботе: он принял норму по пятнадцати зонам из
        # шестнадцати и тут же объявил обрыв на пятьсот кадров подряд.
        #
        # Дело в геометрии. Датчик стоит на высоте 13 см, и пол он видит на
        # h/sin(наклон):
        #
        #     наклон 20° → пол в 0.38 м     надёжно
        #     наклон 10° → пол в 0.75 м     надёжно
        #     наклон  7° → пол в 1.07 м     вскользь
        #     наклон  3° → пол в 2.48 м     луч уходит и не возвращается
        #
        # Под малым углом луч отражается от пола вскользь, и часть замеров не
        # возвращается вовсе. А пропавший замер у нас считается ОБРЫВОМ — так
        # и надо, за краем ступеньки луч тоже пропадает. Значит норма, снятая
        # при почти горизонтальном датчике, обречена: половина её зон будет
        # «обрываться» на ровном полу.
        #
        # Так и вышло: «обрыв 500 кадров, ближайшее 0.00 м», и робот не
        # тронулся ни разу.
        далёкие = sorted(норма[р][к] for р in ОБРЫВ_РЯДЫ for к in range(8)
                         if норма[р][к] > НЕ_ИЗМЕРИЛ)
        середина = далёкие[len(далёкие) // 2] if далёкие else 0.0
        if далёкие and середина > ПОЛ_НЕ_ДАЛЬШЕ:
            log.warning(
                "дальномер: пол вижу только в %.2f м — это слишком далеко. "
                "При высоте датчика 13 см столько получается, когда он "
                "наведён почти горизонтально (меньше 8° вниз). Под таким "
                "углом луч скользит по полу, часть замеров не возвращается, "
                "и я приму ровный пол за обрыв. НЕ ЗАПОМИНАЮ: наклони датчик "
                "вниз на 15-20 градусов — тогда пол ляжет в 0.4-0.5 м и "
                "замеры станут устойчивыми. Проверить: "
                f"{ПРОБНИК} --карта 30", середина)
            self.норма = None
            self.наклон = None
            self.отказался = True
            return False

        if живых < всего // 2:
            # Нижние ряды, упирающиеся в пол, обязаны отвечать почти все: пол
            # близко, он матовый, и мерить его — самое лёгкое, что есть. Если
            # ответила меньше половины, «полом» запомнилось что-то другое.
            #
            # На живом роботе именно это и вышло: шесть зон из шестнадцати, и
            # по картинке с камеры видно, что это ровная вертикальная полоса —
            # стена справа, а не пол. Датчик наведён слишком горизонтально и
            # пола не видит вовсе.
            #
            # Норму в таком виде принимать НЕЛЬЗЯ. Обрыв по ней ищется в
            # стене: она никуда не денется, значит обрыва не будет никогда, и
            # робот спокойно уедет с лестницы, считая себя защищённым. Пустая
            # защита хуже отсутствующей — на неё полагаются.
            self.норма = None
            self.наклон = None
            self.отказался = True
            self._копилка.clear()
            log.warning(
                "дальномер: пол ответил всего %d зонами из %d — для нижних "
                "рядов это мало, полом запомнилось не то. НЕ ЗАПОМИНАЮ: "
                "обрыв по такой норме искался бы в стене и не нашёлся бы "
                "никогда. Скорее всего датчик наведён слишком горизонтально "
                "и пола не видит — наклони его вниз на 10-15 градусов. "
                "Проверить: " + ПРОБНИК + " --карта 30",
                живых, всего)
            return False
        self.сохранить()
        return True

    def обрыв(self, сетка: list[list[float]]) -> int:
        """Сколько нижних зон говорят, что пола там больше нет.

        Считаем и «стало сильно дальше», и «пропало совсем»: за краем луч
        уходит в пустоту и не возвращается вовсе, и это самый частый вид
        обрыва, а не редкий.

        Честно про ложные срабатывания: чёрный ковёр поглощает инфракрасный
        луч так же, как пустота, и на нём робот скажет «обрыв» и не поедет.
        Это осознанный перекос — стоящий робот поправим, упавший нет, — но
        если ковёр в квартире побеждает, выключается одним ROBOT_TOF_CLIFF=0.
        """
        if self.норма is None:
            return 0
        сколько = 0
        for р in ОБРЫВ_РЯДЫ:
            for к in range(8):
                норма = self.норма[р][к]
                if норма <= НЕ_ИЗМЕРИЛ:
                    continue          # эта зона пола и не видела — не судья
                замер = сетка[р][к]
                if замер <= НЕ_ИЗМЕРИЛ or замер > норма * ОБРЫВ_ДАЛЬШЕ:
                    сколько += 1
        return сколько


class Взгляд:
    """Что видит дальномер прямо сейчас, уже осмысленно.

    Два счётчика приходят снаружи, от Дальномера: одиночный кадр про них
    ничего знать не может, а именно они отличают помеху от препятствия.
    """

    def __init__(self, сетка: list[list[float]], когда: float,
                 подряд: int = 0, обрыв: int = 0,
                 пол: list[list[float]] | None = None) -> None:
        self.сетка = сетка
        self.когда = когда
        # Пол этого кадра как плоскость: считается лениво, см. свойство.
        self._плоскость = _ЕЩЁ_НЕ_ИСКАЛИ
        # Та же сетка без пола — тоже лениво и тоже один раз на кадр.
        self._без_пола = _ЕЩЁ_НЕ_ИСКАЛИ
        # Норма пола, если она выучена. Нужна, чтобы отличить лежащее НА полу
        # от самого пола: без неё нижние ряды — слепое пятно, и нога человека
        # в них не видна.
        self.пол_норма = пол
        # Сколько кадров ПОДРЯД видят препятствие по курсу.
        self.подряд = подряд
        # Сколько кадров подряд видят обрыв.
        self.обрыв = обрыв

    @property
    def свежий(self) -> bool:
        return time.monotonic() - self.когда < ЗАВИС_ЧЕРЕЗ

    @property
    def слепой(self) -> bool:
        """Больше половины зон не прочиталось — кадру нельзя верить целиком.

        Так выглядит солнце в окне: доля промахов скачет с десятой части до
        половины, и уцелевшие зоны описывают уже не комнату, а те несколько
        лучей, которым повезло. Строить по ним решение «свободно» — значит
        ехать по случайности.
        """
        живых = sum(1 for ряд in self.сетка for д in ряд if д > НЕ_ИЗМЕРИЛ)
        return живых < 64 * (1.0 - СЛЕПОЙ_КАДР)

    def _живые(self, ряды: range, колонки: range,
               сырьё: bool = False) -> list[float]:
        """Замеры, в которых пол уже вычеркнут плоскостью.

        Раньше читалась СЫРАЯ сетка, и от этого робот противоречил сам себе в
        одном и том же кадре. Пустая ровная комната, штатный наклон датчика
        12° при высоте 13 см: `свободно_впереди` = 3.5 м, `ехать_можно` =
        «да», а `впереди` = 0.33 м — потому что пол. Человек спрашивал
        «свободна ли дорога», слышал «впереди препятствие в 0.3 метра» и тут
        же видел, как робот преспокойно едет. Хуже того, эта же цифра шла в
        журнал строкой «не пускаю вперёд: ближайшее 0.33 м» — то есть разбор
        настоящих бед по журналу был испорчен постоянной величиной.

        Плоскость не нашлась — честно откатываемся на сырую сетку: это ровно
        то поведение, что было до сих пор, и ослепнуть от неудачи нового
        способа робот не должен.
        """
        сетка = self.сетка if сырьё else (self.сетка_без_пола or self.сетка)
        return [сетка[р][к] for р in ряды for к in колонки
                if сетка[р][к] > НЕ_ИЗМЕРИЛ]

    @property
    def впереди(self) -> float:
        """Ближайшее препятствие НА ПУТИ, метры. Ноль — не измерил ничего.

        Берём середину сетки по высоте: четыре центральных ряда. Верхние ряды
        смотрят выше робота (туда он не поедет), нижние упираются в пол и в
        оценке пути только мешают.

        А ВОТ ПО ШИРИНЕ БРАЛИСЬ ВСЕ КОЛОНКИ, И ЭТО БЫЛО НЕВЕРНО. Датчик видит
        шестьдесят градусов, то есть по тридцать в каждую сторону; крайняя
        колонка смотрит вбок, а не по курсу. Робот же едет ПРЯМО и заметает
        полосу шириной со свой корпус — тридцать сантиметров радиуса.

        Разница не теоретическая. На живом роботе: слева стена, справа
        кровать, по тридцать сантиметров вбок, впереди пустая комната. В
        крайних колонках стояло 0.6-0.7 м, `впереди` брал минимум по всем
        колонкам и выдавал 0.64 — и робот отказывался ехать вперёд по пустому
        полу, потому что рядом с ним стояла кровать. Мимо которой он бы
        спокойно проехал.

        Поэтому зона считается «на пути», только если её луч отходит от оси не
        дальше, чем сам робот плюс запас. Отступ считается от НАСТОЯЩЕЙ длины
        луча: далёкая зона под тем же углом отходит вбок сильнее и на пути
        уже не лежит.
        """
        живые = [(р, к, з) for р, к, з in self._живые_с_местом(range(2, 6),
                                                              range(0, 8))
                 if отступ_вбок(к, з) <= КОРИДОР]
        return min(з for _р, _к, з in живые) if живые else НЕ_ИЗМЕРИЛ

    def _живые_с_местом(self, ряды: range, колонки: range):
        """То же, что _живые, но с номерами ряда и колонки.

        Нужно там, где решает не только расстояние, но и НАПРАВЛЕНИЕ: одна и
        та же цифра в средней колонке и в крайней означает разное — по курсу
        и мимо.
        """
        сетка = self.сетка_без_пола or self.сетка
        return [(р, к, сетка[р][к]) for р in ряды for к in колонки
                if сетка[р][к] > НЕ_ИЗМЕРИЛ]

    @property
    def слева(self) -> float:
        живые = self._живые(range(2, 6), range(0, 3))
        return min(живые) if живые else НЕ_ИЗМЕРИЛ

    @property
    def справа(self) -> float:
        живые = self._живые(range(2, 6), range(5, 8))
        return min(живые) if живые else НЕ_ИЗМЕРИЛ

    @property
    def пол(self) -> float:
        """Расстояние до пола по нижнему ряду. Ноль — пола не видно.

        Единственное место, где сетка нужна СЫРАЯ: вопрос здесь про сам пол,
        а очищенная от пола сетка ответила бы на него нулём — «пола не вижу»
        ровно там, где он прекрасно виден.
        """
        живые = self._живые(range(7, 8), range(0, 8), сырьё=True)
        return max(живые) if живые else НЕ_ИЗМЕРИЛ

    @property
    def зон_близко(self) -> int:
        """Сколько зон видят препятствие НА ПУТИ робота, а не вообще.

        Различие принципиальное, и без него робот стоит посреди свободной
        комнаты. Поле зрения — шестьдесят градусов, то есть крайние колонки
        смотрят на двадцать шесть градусов в сторону. На полутора метрах это
        уже семьдесят сантиметров вбок: дверной косяк, край дивана, стена
        коридора — всё, мимо чего робот преспокойно проедет.

        Считаем не расстояние, а БОКОВОЕ СМЕЩЕНИЕ: d·sin(угол). Попадает в
        коридор шириной с робота плюс запас — препятствие. Не попадает —
        робот проедет мимо, и тормозить незачем.

        На живом роботе это выглядело так: «два метра вперёд» — «стою,
        впереди что-то справа», при том что впереди было пусто, а справа в
        полуметре стояла стена.
        """
        # Пол ищем ПЛОСКОСТЬЮ, и когда она нашлась — считаем по ней.
        #
        # Старый счёт по рядам 2-5 с порогом 35 см держался на допущении, что
        # пол в эти ряды не попадает. Он попадает. При наклоне датчика вниз на
        # 10-15°, как было записано в docs/hardware.md моей же рукой, ряд 5
        # упирается в пол на 33 см — ближе порога. Робот, собранный строго по
        # инструкции, не ехал вперёд НИКОГДА и жаловался в журнал на «одно и
        # то же препятствие уже 60 секунд». Препятствием был его собственный
        # пол.
        #
        # По плоскости этот вопрос не стоит вовсе: пол — это точки НА ней,
        # препятствие — точки НАД ней, и наклон датчика перестаёт что-либо
        # значить.
        по_плоскости = self._зон_по_плоскости()
        if по_плоскости is not None:
            return по_плоскости

        сколько = 0
        for р in range(2, 6):
            for к in range(8):
                д = self.сетка[р][к]
                if not (НЕ_ИЗМЕРИЛ < д < СТОП_БЛИЖЕ):
                    continue
                if self._в_коридоре(д, к):
                    сколько += 1
        return сколько + self.зон_на_полу

    def _зон_по_плоскости(self) -> int | None:
        """Сколько зон видят предмет НАД полом. None — плоскость не нашлась.

        None означает «решай по-старому», и это не отговорка: пол может не
        попасть в кадр вовсе — робот на столе, датчик смотрит в горизонт,
        комната больше трёх с половиной метров. Ослепнуть от того, что новый
        способ не сработал, робот не должен.

        Считаем препятствием точку, которая ОДНОВРЕМЕННО:
          выше пола больше чем на толщину ковра — иначе тормозим о стыки плитки;
          ниже макушки робота — люстра и притолока ему не мешают;
          ближе порога стопа — дальнее объедем;
          в коридоре шириной с робота — косяк в полуметре вбок не помеха.
        """
        плоскость = self.плоскость
        if плоскость is None:
            return None
        точки, живые = plane.точки(self.сетка)
        высоты = плоскость.высоты(точки)
        сколько = 0
        for р in range(8):
            for к in range(8):
                if not живые[р][к]:
                    continue
                д = self.сетка[р][к]
                if д >= СТОП_БЛИЖЕ or not self._в_коридоре(д, к):
                    continue
                h = float(высоты[р][к])
                if plane.ТОЛЩИНА_ПОЛА < h < ВЫШЕ_НЕ_МЕШАЕТ:
                    сколько += 1
        return сколько

    def _в_коридоре(self, д: float, к: int) -> bool:
        """Лежит ли зона в полосе, которую робот заметёт, если поедет прямо.

        Считает через отступ_вбок — ту же функцию, что и `впереди`. Раньше
        формула стояла здесь второй копией; две копии одной геометрии однажды
        разойдутся, и разойдутся тихо: сторож будет считать коридор одной
        ширины, а ответ «что впереди» — другой.
        """
        return отступ_вбок(к, д) <= КОРИДОР

    @property
    def зон_на_полу(self) -> int:
        """Сколько нижних зон видят что-то ЛЕЖАЩЕЕ на полу.

        Зеркало проверки обрыва: обрыв — пол дальше нормы, предмет — пол ближе
        неё. Нога, кошка, игрушка, порог — всё это стоит на полу, то есть в
        тех самых нижних рядах, которые сторож исключал, чтобы не принимать
        пол за препятствие.

        Без выученной нормы вернём ноль, и это честно: не зная, где пол, мы не
        отличим ногу от пола и не имеем права гадать. Но и молчать об этом
        нельзя — робот, который не видит низа, не должен ездить рядом с
        людьми, и он про это говорит.
        """
        if not self.пол_норма:
            return 0
        сколько = 0
        for р in ОБРЫВ_РЯДЫ:
            for к in range(8):
                норма = self.пол_норма[р][к]
                д = self.сетка[р][к]
                if норма <= НЕ_ИЗМЕРИЛ or д <= НЕ_ИЗМЕРИЛ:
                    continue
                if д < норма * НА_ПОЛУ_БЛИЖЕ and self._в_коридоре(д, к):
                    сколько += 1
        return сколько

    @property
    def свободно_впереди(self) -> float:
        """До ближайшего препятствия НА ПУТИ, метры. Ноль — не знаю.

        Не то же самое, что `впереди`. Тот берёт минимум по рядам 2-5 и
        считает препятствием всё подряд — в том числе пол, если датчик
        наклонён вниз, и косяк в полуметре вбок. Здесь только то, обо что
        робот и правда стукнется: над плоскостью пола, ниже своей макушки, в
        коридоре шириной с себя.

        Нужно это для скорости. Робот, едущий с постоянной скоростью, либо
        всегда слишком медленный, либо однажды слишком быстрый; третьего не
        бывает. Скорость обязана зависеть от того, насколько далеко видно
        свободно, и вот эта цифра — то самое «насколько далеко».

        Ноль отдаём, когда сказать нечего: кадр несвежий, кадр слепой, или
        плоскость не нашлась и старые правила про пол ничего не знают.
        Незнание — повод ехать осторожно, а не быстро, и наверху это так и
        понимается.
        """
        if not self.свежий or self.слепой:
            return НЕ_ИЗМЕРИЛ
        плоскость = self.плоскость
        ближе_всех = ПРЕДЕЛ_ДАЛЬНОСТИ
        нашли = False
        точки = высоты = None
        if плоскость is not None:
            точки, живые = plane.точки(self.сетка)
            высоты = плоскость.высоты(точки)
        for р in range(8):
            for к in range(8):
                д = self.сетка[р][к]
                if д <= НЕ_ИЗМЕРИЛ or not self._в_коридоре(д, к):
                    continue
                if высоты is not None:
                    h = float(высоты[р][к])
                    # Пол под колёсами и притолока над головой — не преграда.
                    if h <= plane.ТОЛЩИНА_ПОЛА or h >= ВЫШЕ_НЕ_МЕШАЕТ:
                        continue
                elif not (2 <= р < 6):
                    # Без плоскости верим только середине кадра — как раньше.
                    continue
                нашли = True
                ближе_всех = min(ближе_всех, д)
        if not нашли and плоскость is None:
            # Ни плоскости, ни препятствий — сказать про свободу нечего.
            return НЕ_ИЗМЕРИЛ
        return ближе_всех

    @property
    def сетка_без_пола(self) -> list[list[float]] | None:
        """Та же сетка, но пол вычеркнут. None — плоскость не нашлась.

        Нужна тем, кто ищет в кадре ПРЕДМЕТ, а не преграду, — и в первую
        очередь следованию за человеком. Оно ищет ближайшее крупное пятно, и
        до сих пор находило собственный пол.

        Это не догадка, а буквально та же беда, что чинилась в стороже, и
        ровно с теми же числами. При наклоне датчика вниз на 10-15°, как
        записано в docs/hardware.md, нижние ряды упираются в пол на 0.2-0.5 м.
        Для «ближайшего крупного пятна» это и есть ближайшее крупное пятно:
        десятки зон, одна и та же дистанция в любой комнате. Следование
        честно находило цель в тридцати сантиметрах, видело, что до неё ближе
        СТОЯТЬ_БЛИЖЕ, и не ехало НИКОГДА — при любом расположении человека.
        Отсюда и живая жалоба «он вообще не едет за мной».

        Вычеркнутые зоны становятся нулём, то есть «не измерил». Именно
        нулём, а не большим числом: ноль везде в этом коде значит «не знаю», и
        всякий, кто читает сетку, его уже правильно пропускает.

        Потолка по высоте здесь НЕТ, и это отличие от сторожа намеренное. У
        сторожа он есть (ВЫШЕ_НЕ_МЕШАЕТ: под люстрой робот проедет), а тут
        всё, что выше тридцати сантиметров, — это и есть человек. Оставить
        потолок значило бы вести не человека, а его щиколотки: на двух метрах
        от них остаётся две зоны, а тёмные брюки ToF не возвращает вовсе.
        """
        if self._без_пола is _ЕЩЁ_НЕ_ИСКАЛИ:
            self._без_пола = self._вычеркнуть_пол()
        return self._без_пола

    def _вычеркнуть_пол(self) -> list[list[float]] | None:
        плоскость = self.плоскость
        if плоскость is None:
            return None
        точки, живые = plane.точки(self.сетка)
        высоты = плоскость.высоты(точки)
        чистая = [list(ряд) for ряд in self.сетка]
        for р in range(8):
            for к in range(8):
                if not живые[р][к]:
                    continue
                # Ниже толщины ковра над плоскостью — это пол или яма под
                # ним. Ни то, ни другое человеком не является.
                if float(высоты[р][к]) <= plane.ТОЛЩИНА_ПОЛА:
                    чистая[р][к] = НЕ_ИЗМЕРИЛ
        return чистая

    @property
    def плоскость(self):
        """Пол этого кадра как плоскость. None — не нашёлся.

        Считается один раз на взгляд и запоминается: подгонка идёт перебором,
        а спрашивают про пол несколько раз за кадр (сторож, обрыв, подсказка
        модели), и считать её каждому заново — это отдать процессор впустую.
        """
        if self._плоскость is _ЕЩЁ_НЕ_ИСКАЛИ:
            найдена = plane.найти(self.сетка)
            if найдена is not None and not найдена.похожа_на_пол:
                # Нашлась плоскость, но не горизонтальная: робот носом в стену
                # или в столешницу. Считать её полом — значит объявить стену
                # проезжей.
                найдена = None
            self._плоскость = найдена
        return self._плоскость

    @property
    def низ_не_вижу(self) -> bool:
        """Правда ли, что робот не различает лежащее на полу.

        С найденной плоскостью — различает всегда: предмет это точка над ней,
        и никакой выученной нормы для этого не нужно.
        """
        return self.плоскость is None and not self.пол_норма

    def ехать_можно(self) -> tuple[bool, str]:
        """Можно ли двигаться вперёд, и если нет — почему, по-русски.

        Причину возвращаем словами намеренно: этот ответ идёт и в журнал, и
        человеку вслух, и модели в инструмент. Один текст на всех избавляет от
        трёх согласованных наборов формулировок, которые разъезжаются.

        Препятствием считается только то, что видят НЕСКОЛЬКО зон. Одиночная
        зона у ToF — это норма, а не событие: на кромке предмета луч попадает
        между двумя глубинами и возвращает что угодно. Стоп по одной такой
        зоне тормозил бы робота посреди пустого коридора несколько раз в
        минуту, и человек быстро научился бы этот стоп отключать — что хуже,
        чем не иметь его вовсе.
        """
        if not self.свежий:
            return False, "не вижу дорогу"
        # Слепота движение НЕ запрещает, и это не недосмотр. Пустая сетка
        # означает одно из двух: датчик ослеп (солнце, стекло) — или впереди
        # просто просторно, всё дальше трёх с половиной метров. Различить их
        # изнутри нельзя, а цена ошибок разная: приняв простор за слепоту,
        # робот встанет посреди гостиной и не поедет, и человек отключит
        # датчик совсем. Поэтому сторож запрещает только по ПОЛОЖИТЕЛЬНОМУ
        # свидетельству — когда несколько зон видят препятствие.
        #
        # А вот на прямой вопрос «свободно ли» отвечать «свободно» в этом
        # случае нельзя: там незнание надо назвать незнанием, и для этого
        # снаружи есть признак «слепой».
        # Обрыв идёт первым: стену объезжают, с лестницы падают один раз.
        if self.обрыв >= КАДРОВ_ПОДРЯД:
            # Обрыв, который длится минутами, — это не обрыв. Говорим человеку
            # то, что можно проверить руками, а не то, что формально верно.
            if self.обрыв >= ОБРЫВ_СЛИШКОМ_ДОЛГО:
                ближе = self.впереди
                где = f" Ближе всего — {ближе:.2f} м." if ближе else ""
                return False, ("я уже долго вижу перед собой одно и то же." + где
                               + " Похоже, я упёрся или дальномер чем-то "
                                 "загорожен — посмотри, что перед ним")
            return False, "дальше пола нет"
        # Кадров ПОДРЯД, а не одного. Помеха живёт один кадр, стена — все.
        # На десяти герцах два кадра — это пятая доля секунды, то есть шесть
        # сантиметров пути на нашей скорости: за такую задержку платить
        # незачем, а половину ложных стопов она снимает.
        if self.зон_близко >= ЗОН_ДЛЯ_СТОПА and self.подряд >= КАДРОВ_ПОДРЯД:
            близко = self.впереди
            сторона = ("слева" if self.слева and self.слева <= self.справа
                       else "справа")
            return False, f"впереди что-то {сторона}"
        return True, ""


class Дальномер:
    # Значение по умолчанию на самом классе, а не только в __init__.
    # Дальномер собирают и через __new__ — в проверках, где сеть и порт
    # недоступны, — и обращение к признаку, заведённому только в __init__,
    # там падает. Разрешение искать обрыв безопаснее по умолчанию иметь, чем
    # не иметь: настоящее значение всё равно поставит __init__ из окружения.
    обрыв_разрешён = True
    # Сколько замеров подряд наклон сбит. На уровне класса — как и соседние:
    # проверки создают объекты через __new__, минуя __init__.
    _наклон_подряд = 0
    _шум_наклона = None
    # По той же причине: __new__-объекты в проверках его не заводят, а
    # троттлинг переучивания спрашивается на каждом кадре.
    _переучили = 0.0

    """Читает сетку в отдельном потоке, отдаёт последнее увиденное."""

    def __init__(self, устройство: str = "", частота: float = 10.0,
                 пол: "Пол | None" = None) -> None:
        self.устройство = устройство or найти_устройство()
        self.период = 1.0 / max(1.0, частота)
        self._взгляд = Взгляд([[НЕ_ИЗМЕРИЛ] * 8 for _ in range(8)], 0.0)
        self._замок = threading.Lock()
        self._стоп = threading.Event()
        self._поток: threading.Thread | None = None
        self._беда = ""
        self._сырьё: bytes = b""      # последний кадр как есть, для разбора бед
        # На что жаловались в журнал в прошлый раз и когда. Причина отказа
        # держится десятками секунд, а спрашивают о ней пятнадцать раз в
        # секунду — см. мешает().
        self._жаловался = ""
        self._жаловался_когда = 0.0
        self._молчал = 0
        # Обрыв ищем, только если это не отключили: чёрный ковёр для лазера
        # неотличим от пустоты, и в квартире, где это мешает, человеку нужен
        # выключатель, а не переписывание кода.
        # Разрешён ли поиск обрыва вообще (настройкой человека) — и ищем ли
        # мы его прямо сейчас. Два разных вопроса, и раньше они были одним:
        # робот, однажды не разобравший, где верх, выключал обрыв НАВСЕГДА.
        # Человек после этого мог хоть десять раз поправить разворот — робот
        # оставался слепым до перезапуска службы и молчал об этом.
        self.обрыв_разрешён = os.environ.get("ROBOT_TOF_CLIFF", "1") != "0"
        self.ищем_обрыв = self.обрыв_разрешён
        self.пол = пол if пол is not None else Пол()
        # Разворот: настройка перебивает, иначе — что запомнили в прошлый раз,
        # иначе — определим сами по полу за первые две секунды.
        self.разворот: bool | None = None
        if ПЕРЕВЕРНУТЬ:
            self.разворот = ПЕРЕВЕРНУТЬ == "1"
            log.info("дальномер: разворот задан настройкой (%s)",
                     "низом вверх" if self.разворот else "как есть")
        # Норму пола с прошлого раза берём, а вот РАЗВОРОТ — нет, и это не
        # непоследовательность. Норму не снять заново, не поставив робота на
        # ровный пол; разворот определяется за две секунды сам, так что
        # хранить его — значит хранить лишнее и однажды поверить устаревшему.
        if self.ищем_обрыв and self.пол.загрузить():
            log.info("дальномер: пол помню с прошлого раза, ориентацию сверю")
        self._на_разворот: list[list[list[float]]] = []
        self._подряд = 0              # кадров подряд с препятствием
        self._обрыв_подряд = 0        # кадров подряд с обрывом
        self._переучили = 0.0         # когда переучивали пол по наклону
        self._мешает_с = 0.0          # когда препятствие появилось
        self._жаловался_на_вечное = False
        self._зеркало = False         # первая колонка справа
        self._вверхногами = False     # первый ряд снизу (поверх автоопределения)
        self._поперёк = False         # «y» в потоке — колонка, а не строка
        self._разрешение = 0          # 4 или 8 — что плата отдаёт на самом деле
        self._прочитано = 0.0         # когда последний раз перечитывали галки
        self._выложено = 0.0          # когда последний раз писали сетку в файл
        self._не_выложил = False
        # Сказали ли уже человеку, что плата висит. Один раз, а не по кругу.
        self._сдался = False
        self._тряс = False            # встряхивали ли порт хоть раз
        # Зоны, смотрящие в сам робот. Пока список пуст, свои детали
        # неотличимы от стены, и робот будет стоять — это заметно сразу и
        # чинится одной командой, в отличие от тихо испорченных данных.
        self.свои = загрузить_своих()
        if self.свои:
            log.info("дальномер: %d зон смотрят в сам робот, не считаю их",
                     len(self.свои))

    @property
    def беда(self) -> str:
        return self._беда

    @property
    def сырьё(self) -> bytes:
        """Последний ответ платы байтами. Нужен, когда протокол не сошёлся."""
        return self._сырьё

    def доступен(self) -> bool:
        return bool(self.устройство) and os.path.exists(self.устройство)

    def взгляд(self) -> Взгляд:
        with self._замок:
            return self._взгляд

    def _норма_пола(self) -> list[list[float]] | None:
        """Норма пола для проверки «лежит ли что-то на полу», если она есть.

        Отдельный метод, а не self.пол.норма по месту: норма живёт своей
        жизнью — её стирают при смене ориентации, её отказываются учить, если
        пол не в кадре, — и все эти «нет нормы» должны сходиться в одну точку.
        """
        return self.пол.норма

    def низ_не_вижу(self) -> bool:
        """Правда ли, что робот не отличит ногу на полу от самого пола.

        Спрашивают снаружи, перед поездкой: это единственное известное нам
        слепое пятно, про которое человек имеет право узнать ЗАРАНЕЕ, а не
        после наезда на ногу. Молчать про него нельзя.

        Но и пугать зря нельзя. Раньше здесь стояло «нет выученной нормы пола
        — значит не вижу», и это перестало быть правдой в тот день, когда пол
        начали искать плоскостью: с найденной плоскостью предмет на полу — это
        просто точка над ней, и никакой нормы для него не нужно. Робот,
        который на каждую поездку повторяет «под ноги я не смотрю», при том
        что смотрит, обесценивает предупреждение ровно тогда, когда оно
        однажды окажется настоящим.

        Спрашиваем последний кадр, а не норму: плоскость считается по кадру.
        """
        взгляд = self.взгляд()
        if взгляд is not None and взгляд.свежий:
            return bool(взгляд.низ_не_вижу)
        # Кадра нет вовсе — низа мы точно не видим, как и всего остального.
        return True

    def мешает(self) -> str:
        """Короткая фраза для человека, если ехать вперёд нельзя. Пусто — можно.

        Единственное место, где принимается это решение, — и это важно.
        Раньше правило было записано дважды: проверка перед командой прощала
        молчащий датчик, а сторож на ходу — нет. Пока плата отвечала, разницы
        не было видно; стоило ей замолчать, и робот стал обрывать КАЖДУЮ
        поездку на первой миллисекунде со словами «дальномер молчит». То есть
        сломанный датчик запер робота — ровно то, чего вся эта конструкция
        обещала не делать.

        Фраза человеческая, без чисел. Числа нужны в журнале, а вслух робот
        должен говорить как робот, а не как отчёт.
        """
        взгляд = self.взгляд()
        if not взгляд.свежий:
            # Молчит — значит про дорогу ничего не известно. Незнание не
            # повод стоять: робот жил без датчика и должен жить дальше.
            return ""
        можно, почему = взгляд.ехать_можно()
        if можно:
            return ""
        # В ЖУРНАЛ — НЕ ЧАЩЕ РАЗА В ДВЕ СЕКУНДЫ, и это не косметика.
        # Спрашивают отсюда пятнадцать раз в секунду, а причина держится
        # десятками секунд. На живом роботе одно застревание дало ПЯТЬСОТ
        # одинаковых строк подряд, и в них утонуло всё остальное — в том
        # числе строки следования, по которым только и видно, что робот
        # делает. Журнал, в котором не найти нужного, не лучше пустого.
        #
        # Копим при этом счётчик и печатаем его: «то же самое, 47 раз»
        # говорит больше, чем сорок семь одинаковых строк.
        # Через getattr: в проверках Дальномер собирают и в обход __init__,
        # и падать там из-за журнальной мелочи незачем.
        сейчас = time.monotonic()
        было = getattr(self, "_жаловался", "")
        когда = getattr(self, "_жаловался_когда", 0.0)
        self._молчал = getattr(self, "_молчал", 0) + 1
        if почему != было or сейчас - когда >= ЖАЛУЮСЬ_РАЗ_В:
            сколько = (f", подряд {self._молчал}"
                       if self._молчал > 1 and почему == было else "")
            log.info("не пускаю вперёд: %s (зон близко %d, обрыв %d кадров, "
                     "ближайшее %.2f м%s)", почему, взгляд.зон_близко,
                     взгляд.обрыв, взгляд.впереди, сколько)
            self._жаловался = почему
            self._жаловался_когда = сейчас
            self._молчал = 0
        return почему

    def запустить(self) -> bool:
        if not self.доступен():
            self._беда = f"нет устройства {self.устройство or '/dev/serial/by-id/*Pico*'}"
            log.info("дальномер: %s — еду вслепую", self._беда)
            return False
        self._поток = threading.Thread(target=self._читать, daemon=True)
        self._поток.start()
        return True

    def закрыть(self) -> None:
        self._стоп.set()

    # --- внутри ---------------------------------------------------------
    def _открыть(self):
        """Открыть порт на нужной скорости средствами системы.

        Без pyserial: на роботе и так хватает библиотек, а нужно отсюда ровно
        одно — выставить скорость и отключить всякую обработку символов.
        Термios это умеет, он есть в поставке Python.
        """
        import termios

        fd = os.open(self.устройство, os.O_RDWR | os.O_NOCTTY)
        настройки = termios.tcgetattr(fd)
        iflag, oflag, cflag, lflag, ispeed, ospeed, cc = настройки
        скорость = getattr(termios, f"B{СКОРОСТЬ}")
        # Сырой режим: никаких переводов строк, эха и разбора управляющих
        # символов. Данные двоичные, и любая «помощь» их портит.
        iflag = 0
        oflag = 0
        lflag = 0
        cflag = termios.CS8 | termios.CREAD | termios.CLOCAL
        cc = list(cc)
        cc[termios.VMIN] = 0
        cc[termios.VTIME] = 1          # десятые доли секунды
        termios.tcsetattr(fd, termios.TCSANOW,
                          [iflag, oflag, cflag, lflag, скорость, скорость, cc])
        termios.tcflush(fd, termios.TCIOFLUSH)
        return fd

    def _спросить(self, fd: int, cmd: int, args: bytes = b"") -> bytes:
        os.write(fd, _кадр(cmd, args))
        срок = time.monotonic() + ОТВЕТ_ЖДЁМ
        буфер = b""
        while time.monotonic() < срок:
            кусок = os.read(fd, 4096)
            if кусок:
                буфер += кусок
                # Заголовок ответа — четыре байта, дальше объявленная длина.
                if len(буфер) >= 4:
                    нужно = 4 + (буфер[2] | (буфер[3] << 8))
                    if len(буфер) >= нужно:
                        return буфер[:нужно]
            else:
                time.sleep(0.005)
        return буфер

    def _принять(self, сырая: list[list[float]]) -> None:
        """Кадр пришёл: сгладить, посчитать подряд, обновить взгляд.

        Сглаживание идёт ДО всех решений, а не после. Медиана три на три
        убирает ровно те одиночные выбросы, из-за которых робот тормозил на
        пустом месте, и не размывает кромку: на настоящей стене все девять
        соседей говорят одно и то же, и медиана говорит то же самое.
        """
        # СГЛАЖИВАНИЯ ЗДЕСЬ НЕТ, И ЭТО ГЛАВНОЕ В ЭТОЙ ФУНКЦИИ.
        #
        # Сначала было: медиана три на три перед всеми решениями, «чтобы
        # убрать одиночные выбросы». На живых данных оказалось, что она
        # убирает не выбросы, а ПРЕПЯТСТВИЯ. У зоны с краю сетки соседей
        # шесть: три своих близких и три далёких, и медиана шести — это
        # четвёртый по порядку, то есть далёкий. Колонка исчезает целиком.
        # В середине то же самое: предмет шириной в одну зону — ножка стула,
        # ножка стола, косяк двери — растворяется в соседях без следа.
        #
        # А от того, ради чего фильтр ставился, уже защищают два правила:
        # ЗОН_ДЛЯ_СТОПА (одна зона — не препятствие) и КАДРОВ_ПОДРЯД (один
        # кадр — не препятствие). Фильтр не добавлял к ним ничего и вредил в
        # ту сторону, в которую вредить нельзя: не выдумывал стену, а стирал
        # ножку стола. Ошибаться безопасно можно только в сторону лишнего
        # стопа.
        #
        # Сама функция сгладить() осталась — она нужна карте глубины, где
        # красивая картинка важнее ножки стула. Но не решению «ехать или нет».
        # Галки из пульта перечитываем на ходу, но не каждый кадр: десять
        # чтений файла в секунду ради двух булевых значений — расточительство
        # на плате, где и без того тесно.
        сейчас = time.monotonic()
        if сейчас - self._прочитано > ПЕРЕЧИТЫВАТЬ_РАЗ_В:
            self._прочитано = сейчас
            было = (self._зеркало, self._вверхногами, self._поперёк)
            self._зеркало, self._вверхногами, self._поперёк = как_лежит()
            стало = (self._зеркало, self._вверхногами, self._поперёк)
            if было != стало:
                log.info("дальномер: сетка теперь %s",
                         ", ".join(имя for имя, есть in
                                   zip(("зеркально", "вверх ногами", "поперёк"),
                                       стало) if есть) or "как есть")
                # Развернули сетку — всё, что из неё выведено, устарело.
                # Норма пола снята в прежней ориентации, разворот по полу
                # искался в прежней, и отказ «пола не вижу» относился к
                # прежней же. Учим заново, здесь и сейчас, без перезапуска:
                # человек только что покрутил галку и ждёт, что подействует.
                self._переучиться("сетку развернули")

        if self.свои:
            сырая = [ряд[:] for ряд in сырая]
            for р, к in self.свои:
                сырая[р][к] = НЕ_ИЗМЕРИЛ

        # Сперва галки человека, и только потом всё остальное. Порядок здесь
        # был неверен, и ошибка тихая: определитель разворота смотрел на
        # СЫРУЮ сетку, до галок. То есть человек ставил «поперёк», сетка на
        # картинке разворачивалась, а робот продолжал искать пол в прежней
        # ориентации и по-прежнему его не находил. Галка выглядела
        # неработающей, хотя работала — просто не там, где надо.
        сетка = ([list(колонка) for колонка in zip(*сырая)]
                 if self._поперёк else сырая)
        if self._вверхногами:
            сетка = сетка[::-1]
        if self._зеркало:
            сетка = [ряд[::-1] for ряд in сетка]

        # Автоопределение разворота — поверх галок, а не вместо них. Оно
        # доворачивает ряды, если человек ничего не указал; указал — верим
        # ему, он видит наложение на видео, а мы нет.
        if self.разворот is None:
            self._на_разворот.append([ряд[:] for ряд in сетка])
            if len(self._на_разворот) >= РАЗВОРОТ_КАДРОВ:
                решение = куда_смотрит(self._на_разворот)
                self._на_разворот.clear()
                if решение is None:
                    # Пола не видно — датчик смотрит строго вперёд или ослеп.
                    # Не переворачиваем и обрыв не ищем: искать его в рядах,
                    # про которые неизвестно, куда они смотрят, — значит
                    # тормозить наугад.
                    self.разворот = False
                    if self.ищем_обрыв:
                        self.ищем_обрыв = False
                        log.warning(
                            "дальномер: пола не вижу, где верх — не понял. "
                            "Обрыв не ищу: гадать тут нельзя. Либо наклони "
                            "датчик вниз на 10-15 градусов, либо поправь "
                            "разворот сетки галками в пульте — от них я "
                            "переучусь сам, перезапускать не надо.")
                else:
                    self.разворот = решение
                    log.info("дальномер: разобрался сам — сетка %s",
                             "перевёрнута, y0 внизу" if решение else "как есть")
                # Норма, снятая в другой ориентации, лежит к сетке боком.
                # Пользоваться ей нельзя: обрыв искался бы не там, где робот
                # смотрит, а выглядело бы это исправной работой. Сверяем ВСЮ
                # ориентацию; неизвестная равносильна чужой.
                сейчас_ориентация = (bool(self.разворот), self._зеркало,
                                     self._вверхногами, self._поперёк)
                if (self.пол.норма is not None
                        and self.пол.ориентация != сейчас_ориентация):
                    log.warning(
                        "дальномер: пол помнился в другой ориентации (%s) — "
                        "забываю и учу заново",
                        "неизвестной" if self.пол.ориентация is None
                        else str(self.пол.ориентация))
                    self.пол.норма = None
                self.пол.ориентация = сейчас_ориентация

        if self.разворот:
            сетка = сетка[::-1]

        # Считать «сколько зон близко» умеет сам Взгляд, и считать это здесь
        # вторым, отдельным способом мы уже пробовали. Разошлось: в счётчик
        # кадров подряд не попали ни коридорная проверка, ни нижние ряды, и
        # получилось, что зон_близко видит ногу, а подряд её не видит — стоп
        # требует обоих, значит стопа нет. Робот наехал человеку на ногу
        # ровно так. Одно определение на всех, а кадр без счётчика — это тот
        # же кадр: зон_близко от подряд не зависит.
        взгляд = Взгляд(сетка, time.monotonic(), пол=self._норма_пола())

        # Пол учим один раз за жизнь файла — то есть в первые две секунды
        # после запуска, пока робот заведомо стоит. Переучивать на ходу
        # нельзя: робот, подъезжающий к стене, запомнил бы нормой стену, а
        # робот у самого края лестницы — нормой пустоту.
        #
        # Вместе с нормой запоминаем НАКЛОН датчика: норма верна только для
        # той геометрии, в которой снята, а геометрию меняет езда (см.
        # _сверить_наклон). Наклон берём у плоскости этого же кадра — она
        # тут уже посчитана и кэширована, второй раз перебор не пойдёт.
        if self.ищем_обрыв and self.разворот is not None and self.пол.норма is None:
            плоскость = взгляд.плоскость
            наклон = (плоскость.наклон
                      if плоскость is not None and плоскость.похожа_на_пол
                      else None)
            if self.пол.учить(сетка, наклон):
                # Норма появилась прямо сейчас — этот же кадр обязан её
                # видеть, иначе «лежит ли что-то на полу» посчитается вслепую.
                взгляд.пол_норма = self._норма_пола()
            elif self.пол.отказался:
                # Пол ПОСМОТРЕЛИ и не приняли: он не в кадре. Перестаём
                # пробовать, чтобы не писать одно и то же в журнал раз в две
                # секунды, — и остаёмся без защиты от обрыва честно, а не
                # понарошку. Вернёт её либо отвёртка, либо правка галок:
                # и то, и другое проходит через _переучиться.
                #
                # Спрашиваем именно `отказался`, а не «вернул False». False
                # приходит и пока копятся двадцать кадров, и раньше защита от
                # обрыва выключалась на ПЕРВОМ ЖЕ кадре — то есть на новом
                # роботе обрыв не искался никогда, и норма не появлялась
                # никогда, и перезапуск этого не чинил.
                self.ищем_обрыв = False

        близко = взгляд.зон_близко
        self._подряд = self._подряд + 1 if близко >= ЗОН_ДЛЯ_СТОПА else 0
        self._пожаловаться_на_вечное(сетка, близко)

        self._передумать_про_обрыв(взгляд)
        self._сверить_наклон(взгляд)
        обрыв = self.пол.обрыв(сетка) if self.ищем_обрыв else 0
        self._обрыв_подряд = self._обрыв_подряд + 1 if обрыв >= ОБРЫВ_ЗОН else 0

        взгляд.подряд = self._подряд
        взгляд.обрыв = self._обрыв_подряд
        with self._замок:
            self._взгляд = взгляд
        self._выложить(сетка)

    def _передумать_про_обрыв(self, взгляд) -> None:
        """Вернуть защиту от обрыва, если пол снова виден. Раз в десять секунд.

        ЗАЧЕМ. У поиска обрыва два выключателя, и оба были ВЕЧНЫМИ: «где верх
        — не понял» и «пол не выучился». Обратно включало только переучивание,
        а оно звалось из одного места — смены галок разворота в пульте. Не
        трогал галки — не включится до перезапуска.

        Чем это кончается, проверено прогоном, а не рассуждением. Робот
        включили носом в стену: пола в кадре нет, `куда_смотрит` возвращает
        «не понял», защита от обрыва выключается. Робота уносят в комнату,
        где пол виден в каждом кадре и плоскость находится всегда, — защита
        так и остаётся выключенной. Дальше настоящий край: обрыв 0, «ехать
        можно». Робот съезжает с лестницы, и разрешение на это выдаёт его
        собственный сторож.

        Отказ, который нельзя отменить, — это не осторожность, а поломка,
        замаскированная под осторожность.

        Условие возврата ровно одно и оно проверяемое: в ЭТОМ кадре найдена
        плоскость, и она похожа на пол. То есть пол мы прямо сейчас видим —
        значит и мерить его можно, и вопрос «где верх» больше не открыт.
        Переучивание дальше защищено собственной проверкой «пол ответил хотя
        бы половиной зон»: на краю ступени нижние ряды молчат, норма не
        примется, и робот останется без защиты честно, а не понарошку.
        """
        if self.ищем_обрыв or not self.обрыв_разрешён:
            return
        плоскость = взгляд.плоскость
        if плоскость is None or not плоскость.похожа_на_пол:
            return
        сейчас = time.monotonic()
        if сейчас - self._переучили < ПЕРЕУЧИТЬ_НЕ_ЧАЩЕ:
            return
        self._переучили = сейчас
        log.info("дальномер: пол снова вижу (наклон %.0f°) — возвращаю поиск "
                 "обрыва и учу норму заново. Отказ, который нельзя отменить, "
                 "это не осторожность.", плоскость.наклон)
        self.ищем_обрыв = True
        self.пол.норма = None
        self.пол.наклон = None
        self.пол.отказался = False
        self.пол._копилка.clear()
        self._обрыв_подряд = 0

    def _сверить_наклон(self, взгляд) -> None:
        """Не уехал ли наклон датчика с тех пор, как снята норма пола.

        ЗАЧЕМ. Норма замораживается при запуске и с тех пор считается истиной.
        А наклон датчика меняется — не от отвёртки, от езды. Колёсная база
        WD550 всего 19.5 см: подъём передних колёс на 17 мм, то есть обычный
        дверной порожек, стык пола или край ковра, даёт крен в пять градусов.
        Датчик стоит на передней кромке, значит при крене он ещё и
        поднимается, и нижние ряды начинают смотреть ДАЛЬШЕ, чем помнит
        норма.

        Дальше — «обрыв». Робот отказывается ехать и выйти из этого не может:
        кадр не меняется, счётчик обрыва не сбрасывается, переучивание
        зовётся только по смене галок в пульте. Робот замирал на пороге
        навсегда — и, что хуже, молча: жалоба на «вечное препятствие»
        считает близкие зоны, а не обрыв.

        ЧТО ДЕЛАЕМ. Спрашиваем плоскость этого кадра: она даёт наклон датчика
        относительно пола прямо сейчас. Уехал больше, чем позволяет ИЗМЕРЕННЫЙ
        шум этого датчика, и держится несколько замеров подряд, —
        норма снята в другой геометрии и к делу не относится. Забываем её и
        учим заново, здесь же.

        ЧЕГО НЕ ДЕЛАЕМ, И ЭТО ВАЖНЕЕ. Не подменяем обрыв плоскостью. Наверху
        лестницы нижняя площадка — тоже горизонтальная плоскость, и подгонка
        может сесть на неё: тогда все замеры «совпадают с полом», обрыва нет,
        и робот съезжает со ступеней. Обмен «встал на пороге» на «поехал с
        лестницы» недопустим ни при каком приоритете.

        Поэтому три условия сразу, и все обязательны:
          плоскость НАЙДЕНА в этом кадре — то есть пол мы прямо сейчас видим,
              а не висим над пустотой;
          она ПОХОЖА НА ПОЛ — не стена и не столешница;
          наклон УЕХАЛ — то есть причина в геометрии, а не в лестнице.
        А переучивание защищено собственной проверкой «пол ответил хотя бы
        половиной зон»: на краю ступени нижние ряды молчат, норма не примется,
        и робот останется стоять — как и должен.
        """
        if self.пол.норма is None or self.пол.наклон is None:
            return
        плоскость = взгляд.плоскость
        if плоскость is None or not плоскость.похожа_на_пол:
            return
        # Копим наклоны и меряем по ним собственный шум. Порог берём от него,
        # а не из головы: зашитые три градуса оказались МЕНЬШЕ шума этого
        # датчика на этом полу, и норма выбрасывалась каждые десять секунд.
        шум = getattr(self, "_шум_наклона", None)
        if шум is None:
            шум = self._шум_наклона = []
        шум.append(плоскость.наклон)
        if len(шум) > ШУМ_ПОМНИМ:
            шум.pop(0)
        измерен = разброс(шум)
        порог = порог_наклона(шум)

        if abs(плоскость.наклон - self.пол.наклон) <= порог:
            # Наклон на месте — копилку сбитых замеров обнуляем. Иначе
            # редкие выбросы, разбросанные по минутам, однажды сложились бы
            # в «устойчивое отклонение», которого не было.
            self._наклон_подряд = 0
            return
        self._наклон_подряд = getattr(self, "_наклон_подряд", 0) + 1
        if self._наклон_подряд < НАКЛОН_ПОДРЯД:
            return
        сейчас = time.monotonic()
        if сейчас - self._переучили < ПЕРЕУЧИТЬ_НЕ_ЧАЩЕ:
            return
        self._переучили = сейчас
        self._наклон_подряд = 0
        log.warning(
            "дальномер: наклон уехал с %.0f° на %.0f° и держится %d замеров "
            "(мой шум %s, порог %.0f°) — норма пола снята в другой геометрии. "
            "Забываю и учу заново: иначе я объявлю обрыв там, где всего лишь "
            "порожек, и не сдвинусь с места никогда.",
            self.пол.наклон, плоскость.наклон, НАКЛОН_ПОДРЯД,
            "ещё не измерен" if измерен is None else f"{измерен:.0f}°", порог)
        self.пол.норма = None
        self.пол.наклон = None
        self.пол.отказался = False
        self.пол._копилка.clear()
        self._обрыв_подряд = 0
        # Учить снова разрешено: без этого мы бы просто отключили обрыв.
        self.ищем_обрыв = True

    def _выложить(self, сетка) -> None:
        """Последняя сетка — в файл, чтобы её видели, не отнимая порт."""
        сейчас = time.monotonic()
        if сейчас - self._выложено < ПИСАТЬ_РАЗ_В:
            return
        self._выложено = сейчас
        try:
            файл = Path.home() / ".robot-ai" / ФАЙЛ_СЕТКИ
            файл.parent.mkdir(parents=True, exist_ok=True)
            врем = файл.with_name(файл.name + ".tmp")
            # time.time, а не monotonic: читать будет ДРУГОЙ процесс, и
            # сравнивать ему надо с собственными часами, а не с моими.
            врем.write_text(json.dumps({"когда": time.time(), "сетка": сетка}))
            врем.replace(файл)
        except OSError as e:
            # Диск переполнен или права не те. Ехать это не мешает: файл
            # нужен только человеку с пробником, а не самому роботу.
            if not self._не_выложил:
                self._не_выложил = True
                log.warning("дальномер: не пишу сетку в файл (%s)", e)

    def _переучиться(self, почему: str) -> None:
        """Забыть всё, что выведено из прежней ориентации сетки."""
        if not ПЕРЕВЕРНУТЬ:
            self.разворот = None
        self._на_разворот.clear()
        self.пол.норма = None
        self.пол.наклон = None
        # Отказ снимается вместе с нормой: переучивание затем и зовут, что
        # геометрия изменилась и прежний отказ к ней не относится.
        self.пол.отказался = False
        self.пол._копилка.clear()
        self.ищем_обрыв = self.обрыв_разрешён
        log.info("дальномер: %s — заново ищу, где верх, и переучиваю пол",
                 почему)

    def _пожаловаться_на_вечное(self, сетка, близко: int) -> None:
        """Если препятствие не двигается минуту — сказать об этом вслух.

        Робот, отказывающийся ехать из-за собственного кронштейна, снаружи
        неотличим от робота, перед которым стена: на каждую просьбу он честно
        говорит «впереди препятствие» и честно стоит. Так он может простоять
        неделю, и никто не догадается посмотреть в сетку.

        Настоящее препятствие рано или поздно исчезает: человек отходит, дверь
        открывают, робота разворачивают. Своё железо не исчезает никогда — и
        ровно это отличие здесь и ловится.
        """
        if близко < ЗОН_ДЛЯ_СТОПА:
            self._мешает_с = 0.0
            self._жаловался_на_вечное = False
            return
        if not self._мешает_с:
            self._мешает_с = time.monotonic()
            return
        if (self._жаловался_на_вечное
                or time.monotonic() - self._мешает_с < ВЕЧНОЕ_ЧЕРЕЗ):
            return
        self._жаловался_на_вечное = True
        зоны = [(р, к) for р in range(2, 6) for к in range(8)
                if НЕ_ИЗМЕРИЛ < сетка[р][к] < СТОП_БЛИЖЕ]
        колонки = sorted({к for _, к in зоны})
        log.warning(
            "дальномер: одно и то же препятствие уже %.0f секунд: зон %d, "
            "колонки %s. Ехать вперёд я всё это время отказываюсь. Если это "
            "не стена, а мой же кронштейн, лечится так: "
            + ПРОБНИК + " --свои",
            ВЕЧНОЕ_ЧЕРЕЗ, len(зоны),
            ", ".join(str(к) for к in колонки) or "не понял какие")

    def _встряхнуть(self, fd: int) -> None:
        """Программный перевтык: уронить DTR и RTS, подождать, поднять.

        Для устройства, которое видно системе как USB-CDC, это ближайшее к
        выдёргиванию кабеля, что можно сделать без рук и без прав
        администратора. Многие прошивки привязывают начало передачи именно к
        появлению DTR — то есть к моменту, когда хост «взял трубку».

        Чуда не обещает: если микроконтроллер завис намертво, поможет только
        снятие питания. Но попробовать обязано железо, а не человек, — робот
        в корпусе рук не дождётся.

        Скорость при этом НЕ трогаем. У плат на RP2040 открытие порта на 1200
        бод — это команда «уйти в загрузчик»: устройство исчезло бы с шины
        совсем и превратилось бы в флешку. Здесь скорость остаётся своей.
        """
        try:
            import fcntl
            import struct
            import termios

            линии = struct.pack("I", termios.TIOCM_DTR | termios.TIOCM_RTS)
            fcntl.ioctl(fd, termios.TIOCMBIC, линии)   # уронить
            time.sleep(0.3)
            fcntl.ioctl(fd, termios.TIOCMBIS, линии)   # поднять
            time.sleep(0.3)
            # Громко — только в первый раз. Дальше встряхивание повторяется
            # каждые полминуты, и строка про него быстро вытеснила бы из
            # журнала всё остальное.
            (log.info if not self._тряс else log.debug)(
                "дальномер: встряхнул порт")
        except (OSError, AttributeError) as e:
            (log.info if not self._тряс else log.debug)(
                "дальномер: встряхнуть порт не вышло (%s)", e)
        self._тряс = True

    def _распознать(self, fd: int) -> str:
        """Каким протоколом говорит плата. «строки» или «кадры».

        Гадать один раз при запуске дешевле, чем требовать от человека знать,
        какая прошивка ему досталась. Сперва просто слушаем: часть прошивок
        DFRobot сыплет строками «y0:…» сама, и тогда никаких команд не надо
        вовсе. Молчит — значит разговаривает запросами.
        """
        тишина = b""
        срок = time.monotonic() + 1.0
        while time.monotonic() < срок and not self._стоп.is_set():
            кусок = os.read(fd, 4096)
            if кусок:
                тишина += кусок
            else:
                time.sleep(0.01)
        if тишина:
            self._сырьё = тишина
            if строками(тишина.decode("ascii", "replace")) is not None:
                log.info("дальномер: плата сыплет строки сама")
                return "строки"
        log.info("дальномер: плата молчит без запроса, спрашиваю кадрами")
        return "кадры"

    def _читать(self) -> None:
        """Внешняя петля: держать датчик живым, что бы с ним ни случилось.

        Раньше эта функция выполнялась один раз. Оборвалось чтение — поток
        закончился, и датчик был мёртв до перезапуска службы. А обрывается
        оно от вещей совершенно житейских: человек передёрнул USB, плата
        перезагрузила прошивку, ядро переназвало устройство. Робот при этом
        продолжает ездить и продолжает думать, что видит дорогу.

        Имя устройства ищем заново на каждом круге: после передёргивания USB
        номер уезжает, и старый путь ведёт в никуда — или, что хуже, на
        соседнюю плату.
        """
        while not self._стоп.is_set():
            self._круг_чтения()
            if not self._стоп.is_set():
                self._стоп.wait(ОЖИВАТЬ_ЧЕРЕЗ)

    def _круг_чтения(self) -> None:
        fd = -1
        try:
            # Ищем заново ТОЛЬКО если прежнего пути больше нет. Искать всегда
            # значило бы перебивать явно заданный ROBOT_TOF_DEVICE найденным
            # наугад — то есть чинить работающее.
            if not self.доступен():
                найдено = найти_устройство()
                if найдено and найдено != self.устройство:
                    log.info("дальномер: устройство переехало, теперь %s",
                             найдено)
                    self.устройство = найдено
            if not self.доступен():
                беда = f"нет устройства {self.устройство or 'по имени платы'}"
                if беда != self._беда:
                    self._беда = беда
                    log.warning("дальномер: %s", беда)
                return
            fd = self._открыть()
            log.info("дальномер: слушаю %s", self.устройство)
            кругов = 0
            # Режим выбираем не раз навсегда, а заново всякий раз, когда
            # выбранный перестал давать кадры. Выбор «раз навсегда» уже
            # подвёл: пробник вслепую перебрал двоичные команды, одна из них
            # выключила плате автоотдачу, RP2040 это запомнил — и драйвер,
            # решивший при запуске «плата молчит, буду спрашивать кадрами»,
            # остался в неверном режиме навсегда. В журнале это выглядело как
            # исправно работающий сервис, который ничего не видит.
            while not self._стоп.is_set():
                if self._распознать(fd) == "строки":
                    self._читать_строками(fd)
                else:
                    self._читать_кадрами(fd)
                if self._стоп.is_set():
                    break
                кругов += 1
                # После главного сообщения повторять эту строку каждые шесть
                # секунд бессмысленно: она перестаёт нести новость и начинает
                # прятать в журнале всё остальное. Изредка напоминаем — чтобы
                # человек, заглянувший через час, всё-таки увидел, что робот
                # до сих пор слеп, — но раз в десять минут, а не постоянно.
                if not self._сдался:
                    log.warning("дальномер: кадров нет %.0f с — переспрашиваю, "
                                "каким протоколом говорит плата",
                                ПЕРЕСПРОСИТЬ_ЧЕРЕЗ)
                elif кругов % НАПОМИНАТЬ_КАЖДЫЕ == 0:
                    log.warning("дальномер: всё ещё молчит, еду вслепую. "
                                "Передёрни USB дальномера.")
                # Повторять один и тот же намёк по кругу бесполезно: человек
                # прочтёт его дважды и перестанет читать. После нескольких
                # безуспешных кругов плата не «временно занята» — она висит,
                # и вывести её оттуда можно только снятием питания. Так и
                # говорим, один раз, и с готовым действием.
                if кругов == МОЛЧИТ_СОВСЕМ:
                    # Прежде чем звать человека — попробовать самому. Робот
                    # в корпусе не должен требовать рук, а для USB-CDC
                    # «перевтык» делается программно: сбросить DTR, закрыть
                    # порт, открыть заново. Прав администратора не нужно.
                    self._встряхнуть(fd)
                    if not self._сдался:
                        self._сдался = True
                        log.error(
                            "дальномер: плата молчит совсем — ни сама не "
                            "сыплет, ни на запросы не отвечает. Встряхиваю "
                            "порт и пробую снова. Если через минуту так и не "
                            "оживёт — тут нужны руки: передёрнуть USB "
                            "дальномера. Перезапускать службу не надо, "
                            "подхватит сам. До тех пор еду вслепую.")
                    return          # выйти, чтобы порт закрылся и открылся
        except Exception as e:            # noqa: BLE001 — отвал не повод падать
            self._беда = str(e)
            log.warning("дальномер: чтение оборвалось (%s)", e)
        finally:
            if fd >= 0:
                with __import__("contextlib").suppress(OSError):
                    os.close(fd)

    def _читать_кадрами(self, fd: int) -> None:
        """Двоичный опрос. Возврат — значит пора переспросить протокол."""
        # Просим сетку 8×8. Плата умеет и 4×4, и умолчание у неё своё.
        self._спросить(fd, CMD_CONFIG, аргументы_режима(РЕЖИМ_8X8))
        # Смена разрешения занимает у платы пять секунд, и всё это время она
        # молчит. Спросить раньше — получить тишину и решить, что она умерла.
        self._стоп.wait(ПОСЛЕ_СМЕНЫ_РЕЖИМА)
        жаловался = ""
        сдаться = time.monotonic() + ПЕРЕСПРОСИТЬ_ЧЕРЕЗ
        while not self._стоп.is_set() and time.monotonic() < сдаться:
            ответ = self._спросить(fd, CMD_ALL_DATA)
            self._сырьё = ответ
            разбор = разобрать(ответ)
            if разбор is None or not разбор[1]:
                # Жалуемся на КАЖДУЮ НОВУЮ беду, но не на повтор той же:
                # иначе десять раз в секунду в журнал польётся одно и то
                # же, и настоящую причину в нём будет не найти.
                что = f"нет ответа ({ответ[:8].hex() or 'пусто'})"
                if что != жаловался:
                    жаловался = что
                    log.warning("дальномер: %s", что)
                    self._беда = что
                time.sleep(self.период)
                continue
            жаловался = ""
            self._беда = ""
            self._принять(в_метры(разбор[1]))
            сдаться = time.monotonic() + ПЕРЕСПРОСИТЬ_ЧЕРЕЗ
            time.sleep(self.период)

    def _читать_строками(self, fd: int) -> None:
        """Плата говорит сама — просто слушаем поток строк.

        Копим до полной восьмёрки рядов и после разбора буфер чистим целиком:
        держать хвост незачем, следующая восьмёрка придёт через десятую долю
        секунды. Предел на размер буфера — на случай, если плата начнёт
        сыпать чем-то посторонним: расти он тогда будет вечно.
        """
        буфер = ""
        сдаться = time.monotonic() + ПЕРЕСПРОСИТЬ_ЧЕРЕЗ
        while not self._стоп.is_set() and time.monotonic() < сдаться:
            кусок = os.read(fd, 4096)
            if not кусок:
                time.sleep(0.01)
                continue
            буфер += кусок.decode("ascii", "replace")
            if len(буфер) > 8192:
                буфер = буфер[-4096:]
            сетка = строками(буфер)
            if сетка is None:
                continue
            # Какое разрешение сейчас на плате — видно только здесь, до
            # растяжения: дальше 4×4 и 8×8 выглядят одинаково. А знать это
            # важно: от разрешения зависит и дальность (вчетверо больше света
            # на зону), и то, что вообще значит «зона». Без этой строки
            # человек не может ответить на простой вопрос «в каком режиме
            # плата» иначе как считая одинаковые числа в соседних колонках.
            сколько = сколько_строк(буфер)
            if сколько and сколько != self._разрешение:
                self._разрешение = сколько
                log.info("дальномер: плата отдаёт сетку %d×%d",
                         сколько, сколько)
            self._сырьё = буфер.encode("ascii", "replace")
            буфер = ""
            self._беда = ""
            сдаться = time.monotonic() + ПЕРЕСПРОСИТЬ_ЧЕРЕЗ
            self._принять(сетка)
