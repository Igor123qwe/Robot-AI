# на полпути.
ФАЙЛ_ПРИЦЕЛА = "tof_aim.json"
ПЕРЕЧИТЫВАТЬ_РАЗ_В = 2.0


def как_лежит(файл: Path | None = None) -> tuple[bool, bool, bool]:
    """(зеркально, вверх ногами, поперёк). Нет файла — всё «нет».

    Третье — транспонирование, и оно тут не для полноты картины. Плата
    подписывает строки «y0:…y7:», и что такое y — строка или колонка — нигде
    не сказано. Разведка дала признак, по которому это различается: у датчика,
    наклонённого вниз, молчащие зоны обязаны группироваться СТРОКАМИ (нижние
    бьют в пол под скользящим углом, верхние уходят за предел дальности). У
    нас они шли колонками — а это ровно то, во что превращается строчная
    картина, если сетку читать поперёк.

    Три галки вместе дают все восемь возможных разворотов, так что гадать не
    придётся ни в одном случае.
    """
    файл = файл or (Path.home() / ".robot-ai" / ФАЙЛ_ПРИЦЕЛА)
    try:
        данные = json.loads(файл.read_text())
    except (OSError, ValueError):
        return False, False, False
    return (bool(данные.get("зеркало")), bool(данные.get("вверхногами")),
            bool(данные.get("поперёк")))

# Насколько ближний край должен быть ближе дальнего, чтобы это считалось
# полом, а не шумом. Пятнадцать процентов: на полуметре это семь сантиметров,
# втрое больше паспортной ошибки.
НАКЛОН_ЗНАЧИМ = 0.15
# Дальше этого «пол» полом не считаем. Полтора метра: датчик стоит в
# полуметре от земли и наклонён вниз, так что пол под ним ближе метра. А вот
# полтора метра по прямой — это уже может быть и стена, и мебель.
ПОЛ_НЕ_ДАЛЬШЕ = 1.5
# Какая доля шагов между рядами должна идти в одну сторону, чтобы это
# считалось плоскостью, а не пятном. Три четверти: настоящий пол даёт ровную
# лесенку, один-два шага против хода — это шум, а половина на половину — уже
# не плоскость.
МОНОТОННОСТЬ = 0.75

# По скольким кадрам решаем. Двадцать — две секунды на десяти герцах, столько
# же, сколько уходит на изучение пола.
РАЗВОРОТ_КАДРОВ = 20


def куда_смотрит(кадры: list[list[list[float]]]) -> bool | None:
    """Перевёрнута ли сетка. True — y0 внизу. None — не понять.

    Плата подписывает ряды «y0…y7» и нигде не говорит, какой из них верхний.
    А от этого зависит защита от лестницы: перепутав, робот ищет обрыв в
    потолке — и находит там пустоту, то есть «обрыв» на ровном месте, или,
    наоборот, не находит настоящий.

    Спрашивать человека — плохой выход: он ответит один раз, потом переставит
    датчик и не вспомнит. Зато у робота есть свидетель, который врать не
    умеет: ПОЛ. Он всегда ближе внизу и уходит вдаль кверху, до горизонта, за
    которым замеров нет вовсе. Достаточно посмотреть, с какого края сетки
    расстояния меньше.

    Требование к человеку от этого не меняется и остаётся одно и то же:
    включать робота на ровном полу.

    None означает «не разобрал» — например, датчик смотрит строго вперёд и
    пола не видит вовсе. Тогда ничего не переворачиваем: догадка тут хуже
    честного незнания, потому что молча меняет смысл всех нижних рядов.
    """
    if len(кадры) < 3:
        return None
    по_рядам: list[float | None] = []
    for р in range(8):
        замеры = sorted(кадр[р][к] for кадр in кадры for к in range(8)
                        if кадр[р][к] > НЕ_ИЗМЕРИЛ)
        # Ряд считается видящим, если хотя бы треть его лучей вернулась.
        хватает = len(замеры) >= len(кадры) * 8 // 3
        по_рядам.append(sorted(замеры)[len(замеры) // 2] if хватает else None)

    верх = [м for м in по_рядам[:2] if м]
    низ = [м for м in по_рядам[-2:] if м]

    # Один край пуст, другой уверенно мерит вблизи — это и есть правильно
    # наклонённый датчик, а не повод сдаться.
    #
    # Раньше здесь стоял отказ, и он срабатывал ровно в том случае, ради
    # которого всё затевалось. У наклонённого вниз датчика верхние ряды
    # уходят в комнату дальше предела дальности и молчат ЗАКОННО — это норма,
    # а не слепота. На живом роботе так и вышло: нижние ряды мерили в каждом
    # кадре, верхние молчали в девяноста процентах, и робот на этом объявлял
    # «пола не вижу» и выключал защиту от лестницы.
    #
    # Требуем двух вещей сразу: пустой край ДЕЙСТВИТЕЛЬНО пуст, а видящий
    # мерит близко — ближе полутора метров. Просто пустой край бывает и от
    # чёрного ковра, и от солнца; пустой край НАПРОТИВ близкого пола бывает
    # только от того, что там верх.
    if bool(верх) != bool(низ):
        видит = верх or низ
        if sum(видит) / len(видит) < ПОЛ_НЕ_ДАЛЬШЕ:
            return bool(верх)      # видящий край — низ; если это начало сетки,
                                   # её надо перевернуть
        return None
    if not верх or not низ:
        return None
    ближе_сверху = sum(верх) / len(верх)
    ближе_снизу = sum(низ) / len(низ)
    разница = abs(ближе_сверху - ближе_снизу) / max(ближе_сверху, ближе_снизу)
    if разница < НАКЛОН_ЗНАЧИМ:
        return None

    # Разницы краёв мало. Пол — это ЛЕСЕНКА: расстояние растёт от ряда к ряду
    # монотонно, потому что это плоскость под углом. А рука, стул или коробка
    # перед датчиком дают пятно, у которого края тоже разные, но между ними
    # ничего не растёт.
    #
    # Проверка добавлена не из осторожности. По прошлым кадрам я решил, что
    # y0 внизу, — а в следующем замере наклон оказался обратным, при том что
    # датчик не двигали. Значит в одном из двух случаев я принял за пол
    # что-то другое, скорее всего руку, которой махали перед датчиком. Разница
    # краёв это пропускает, лесенка — нет.
    видимые = [м for м in по_рядам if м]
    if len(видимые) < 5:
        return None
    вверх = sum(1 for a, b in zip(видимые, видимые[1:]) if b > a)
    вниз = sum(1 for a, b in zip(видимые, видимые[1:]) if b < a)
    # Делим на ВСЕ шаги, включая ровные. Считать только неровные — значит
    # признать плоскостью сетку, у которой края разные, а между ними ничего
    # не меняется: два шага из семи в одну сторону дали бы «единогласно».
    if max(вверх, вниз) / (len(видимые) - 1) < МОНОТОННОСТЬ:
        return None

    # Ближний край — это низ. Если он оказался в начале сетки, её надо
    # перевернуть, чтобы ряд 0 стал верхом, как ждёт весь остальной код.
    return ближе_сверху < ближе_снизу

# --- свои же зоны ------------------------------------------------------------
# Часть лучей упирается в сам робот: кронштейн, провод, край корпуса. Такая
# зона мерит честно и стабильно — и ровно поэтому опасна: она сообщает
# «препятствие в шести сантиметрах» вечно, и робот не поедет никуда.
#
# Отличить своё железо от чужой стены изнутри нельзя, и учить это на ходу
# нельзя тем более: робот, включённый носом в стену, запомнил бы стену своей
# деталью и потом поехал бы в неё. Поэтому список зон записывает человек —
# один раз, освободив место перед роботом:
#     python3 scripts/tof_probe.py --свои
ФАЙЛ_СВОИХ = "tof_blind.json"
# Насколько зона должна быть неподвижна, чтобы считаться своей деталью.
# Четыре сантиметра: живая сцена столько не выстаивает даже в пустой комнате,
# а привинченный кронштейн не шевелится вовсе.
СВОЁ_ДРОЖИТ = 0.04
# И насколько близко. Мерить надо НЕ ДЛИНУ ЛУЧА, а то, насколько зона смотрит
# в сторону от робота, — и вот почему.
#
# Крайняя колонка смотрит вбок на тридцать градусов. Луч длиной 0.65 м под
# таким углом отходит от оси всего на 0.32 м — то есть упирается ровно в край
# корпуса, у которого радиус 0.30 м. По длине луча это «далеко», по существу
# это собственная железка.
#
# Поэтому проверок теперь ДВЕ, и обе тесные. Отступ вбок привязан к корпусу:
# своя деталь не может отстоять от оси дальше, чем сам робот плюс запас на
# выносы — кронштейн камеры, ручку, антенну. Длина луча остаётся прежней.
#
# Ослаблять их нельзя, и это проверено живым случаем. На роботе крайние
# колонки видели 0.6-0.7 м во всех рядах сразу, и это выглядело как своя
# железка — вертикальная полоса у края поля зрения. Оказалось: слева стена,
# справа кровать, по тридцать сантиметров вбок. Послабление порога объявило бы
# СТЕНУ деталью робота, то есть велело бы её не замечать. Такая ошибка не
# видна ничем: робот не тормозит и не жалуется, просто однажды едет в стену.
СВОЁ_ВБОК = 0.35
# Предел и по лучу тоже — иначе зона, смотрящая почти вперёд, попадала бы под
# «отступ вбок мал» на любом расстоянии, и стена в трёх метрах прямо по курсу
# считалась бы своей деталью.
СВОЁ_БЛИЖЕ = 0.5
# Сколько зон вообще может быть своими. Больше четверти сетки — это не
# кронштейн, это ошибка разметки или робот, который во время съёмки не
# повернулся. Заклеить полсетки значит ослепить робота молча, а молчаливая
# слепота хуже отказа ехать.
СВОИХ_НЕ_БОЛЬШЕ = 16

# Насколько должна измениться сцена между двумя съёмками, чтобы поверить, что
# робот ПРАВДА повернулся. Без этой проверки застрявший робот (колёса в
# ковре, кто-то держит рукой) снял бы два одинаковых кадра, и своими оказались
# бы все зоны разом — то есть вся защита выключилась бы одним движением.
ПОВОРОТ_СМЕНИЛ_ДОЛЮ = 0.3
# Как часто зона должна отвечать, чтобы вообще судить о её постоянстве.
СВОЁ_НАДЁЖНОСТЬ = 0.9


def отступ_вбок(колонка: int, луч: float, колонок: int = 8) -> float:
    """На сколько метров зона смотрит в сторону от оси робота.

    Своё железо стоит рядом с осью, даже когда луч до него длинный: крайняя
    колонка смотрит вбок на тридцать градусов, и 0.65 м по лучу — это всего
    0.32 м вбок, то есть край корпуса.
    """
    угол = ((колонок - 1) / 2.0 - колонка) * (ПОЛЕ_ГОР / колонок)
    return abs(луч * math.sin(math.radians(угол)))


def _постоянные(кадры: list[list[list[float]]]) -> dict[tuple[int, int], float]:
    """Зоны, которые в этой съёмке не шевелились. Зона → её расстояние."""
    ровные: dict[tuple[int, int], float] = {}
    if not кадры:
        return ровные
    for р in range(8):
        for к in range(8):
            замеры = [кадр[р][к] for кадр in кадры if кадр[р][к] > НЕ_ИЗМЕРИЛ]
            if len(замеры) < len(кадры) * СВОЁ_НАДЁЖНОСТЬ:
                continue          # зона молчит — значит там пусто, а не деталь
            if max(замеры) - min(замеры) > СВОЁ_ДРОЖИТ:
                continue          # дышит — значит комната
            расстояние = sorted(замеры)[len(замеры) // 2]
            if расстояние >= СВОЁ_БЛИЖЕ:
                continue          # далеко по лучу — это уже комната
            if отступ_вбок(к, расстояние) > СВОЁ_ВБОК:
                continue          # в стороне от корпуса — не наша деталь
            ровные[(р, к)] = расстояние
    return ровные


def свои_зоны(кадры: list[list[list[float]]],
              после_поворота: list[list[list[float]]] | None = None,
              ) -> list[tuple[int, int]]:
    """Какие зоны смотрят в сам робот.

    Первый признак — НЕПОДВИЖНОСТЬ вблизи: стена в двадцати сантиметрах тоже
    близка, но она дышит (шум датчика, дрожание робота, тень от лампы), а
    кронштейн не дышит.

    Одного этого признака мало, и разница тут не теоретическая. Стена сбоку
    неподвижна ровно так же, как кронштейн, — а пометить стену «своей
    деталью» значит велеть роботу её не замечать. Такая ошибка не видна
    вообще ничем: робот не тормозит и ни на что не жалуется, просто однажды
    едет в стену.

    Поэтому решает второй замер, снятый ПОСЛЕ ПОВОРОТА робота на месте.
    Своё железо повёрнуто вместе с датчиком и осталось на том же расстоянии.
    Комната — нет: стена ушла, мебель сменилась, расстояния другие. Разделить
    их иначе изнутри нельзя, и гадать тут нечего.

    Без второго замера возвращаем пустой список, а не догадку: список своих
    зон отключает защиту, и лучше его не иметь, чем иметь неверный.
    """
    первые = _постоянные(кадры)
    if после_поворота is None:
        return []
    вторые = _постоянные(после_поворота)
    свои: list[tuple[int, int]] = []
    for зона, было in первые.items():
        стало = вторые.get(зона)
        if стало is None:
            continue              # после поворота там пусто — значит комната
        if abs(стало - было) > СВОЁ_ДРОЖИТ:
            continue              # расстояние сменилось — значит комната
        свои.append(зона)
    return свои


def загрузить_своих(файл: Path | None = None) -> set[tuple[int, int]]:
    файл = файл or (Path.home() / ".robot-ai" / ФАЙЛ_СВОИХ)
    try:
        данные = json.loads(файл.read_text())
    except (OSError, ValueError):
        return set()
    зоны = данные.get("зоны") or []
    return {(int(р), int(к)) for р, к in зоны
            if 0 <= int(р) < 8 and 0 <= int(к) < 8}


def сохранить_своих(зоны, файл: Path | None = None) -> Path:
    файл = файл or (Path.home() / ".robot-ai" / ФАЙЛ_СВОИХ)
    файл.parent.mkdir(parents=True, exist_ok=True)
    врем = файл.with_name(файл.name + ".tmp")
    врем.write_text(json.dumps({"зоны": [list(з) for з in sorted(зоны)]},
                               ensure_ascii=False))
    врем.replace(файл)
    return файл


