# известном расстоянии. Это расстояние робот запоминает на ровном полу. Дальше
# правило такое: пол на своём месте — норма, пол ВНЕЗАПНО ДАЛЬШЕ обычного или
# пропал вовсе — впереди край.
ОБРЫВ_РЯДЫ = (6, 7)
# Во сколько раз дальше нормы — уже не пол.
#
# ЗДЕСЬ СТОЯЛО 1.25, И ОБОСНОВАНИЕ БЫЛО ПРОСТО НЕВЕРНЫМ. В нём говорилось,
# что «порог в пять сантиметров уводит луч метра на полтора». Считаем: датчик
# на высоте 13 см под наклоном 22° видит пол в 0.35 м; ступенька в 5 см
# добавляет к высоте те же 5 см, и луч уходит на (0.13+0.05)/sin(22°) = 0.48 м.
# Не полтора метра, а сорок восемь сантиметров — в три раза меньше.
#
# Из-за этой ошибки порог оказался вплотную к обычному крену тележки:
#
#     крен 4° → пол в 0.43 м → 1.22х нормы    ещё молчим
#     крен 5° → пол в 0.45 м → 1.29х нормы    ЛОЖНЫЙ ОБРЫВ
#     крен 8° → пол в 0.54 м → 1.56х нормы    ЛОЖНЫЙ ОБРЫВ
#
