"""Дальномер: сетка 8×8 расстояний перед роботом.

Это спинной мозг робота. Он не понимает, что перед ним, — он знает только
«близко» и «далеко», зато знает это за сотую долю секунды и в темноте.
Понимание живёт выше: камера и модель разбираются, что там за предмет, и
тратят на это секунды. Пока они думают, робот уже успел бы приехать в стену,
поэтому решение «стоп» принимается здесь и ни с кем не согласовывается.

Железо: DFRobot Gravity 8×8 Matrix ToF (SEN0628) на VL53L7CX, подключён по
USB. Внутри платы RP2040, поэтому в системе он выглядит как «Raspberry Pi
Pico» и получает имя /dev/ttyACM*. Номер меняется при загрузке, а на соседнем
живёт контроллер приводов — поэтому обращаемся только по постоянному имени из
/dev/serial/by-id.

Поле зрения 60 градусов, дальность до 3.5 метра, но верить можно до двух:
паспортная точность VL53L7CX ±15 мм держится до 2 м, дальше ошибка растёт до
одиннадцати процентов.

Про пол. Сетка смотрит и вниз тоже, поэтому нижние ряды упираются в пол
метрах в полутора и честно докладывают препятствие. Это не помеха, а второй
датчик: пол на известном расстоянии — норма, пол ВНЕЗАПНО ДАЛЬШЕ обычного —
обрыв, ступенька или порог. Ради этого нижние ряды разбираются отдельно.
"""

from __future__ import annotations

import glob
import json
import logging
import os
import threading
import time
from pathlib import Path

log = logging.getLogger(__name__)

# Скорость порта у этой платы зашита намертво и настройке не подлежит.
СКОРОСТЬ = 115200

# Кадр запроса: заголовок, число аргументов (два байта), команда, аргументы.
ЗАГОЛОВОК = 0x55
# Кадр ответа: состояние, эхо команды, длина (два байта), данные.
УДАЧА = 0x53
ОТКАЗ = 0x63

CMD_ALL_DATA = 0x02          # отдать всю сетку разом
CMD_CONFIG = 0x01            # переключить разрешение сетки
РЕЖИМ_8X8 = 0x08

# Сколько ждать ответа на один запрос. Плата отвечает за миллисекунды; всё,
# что дольше, — это уже не задержка, а молчание.
ОТВЕТ_ЖДЁМ = 0.5

# Через сколько тишины считать датчик отвалившимся. Исправный сыплет кадры
# непрерывно, поэтому секунда молчания — это уже беда.
ЗАВИС_ЧЕРЕЗ = 2.0

# Ближе этого — стоп. Тридцать пять сантиметров: полная реакция от кадра до
# остановки укладывается в четверть секунды, на 0.3 м/с это семь-двенадцать
# сантиметров пути, плюс датчик мерит от своей платы, а впереди неё ещё
# бампер и колёса.
СТОП_БЛИЖЕ = 0.35

# Ближе этого — ехать можно, но шагом.
ТИХО_БЛИЖЕ = 0.70

# Ближе этого замерам не верим вовсе. У VL53L7CX на упоре есть зона паразитной
# засветки, где он выдаёт единицы сантиметров на пустом месте.
НЕ_ВЕРИМ_БЛИЖЕ = 0.05

# Сколько зон должны увидеть препятствие, чтобы это считалось препятствием.
# Одиночная зона — это норма для ToF: на кромке предмета луч попадает между
# двумя глубинами и возвращает что угодно. Такой «летающий пиксель» тормозил
# бы робота посреди пустого коридора.
ЗОН_ДЛЯ_СТОПА = 3

# И сколько кадров подряд. Помеха живёт один кадр, стена — все.
КАДРОВ_ПОДРЯД = 2

# Через сколько секунд неподвижного препятствия жаловаться в журнал. Минута:
# человек в дверях столько не стоит, а кронштейн стоит вечно.
ВЕЧНОЕ_ЧЕРЕЗ = 60.0

# Через сколько пробовать снова, если чтение оборвалось совсем — порт исчез,
# права не те, USB передёрнули. Три секунды: чаще незачем, реже — робот
# слишком долго едет вслепую.
ОЖИВАТЬ_ЧЕРЕЗ = 3.0

# Сколько безуспешных переспросов подряд, прежде чем сказать человеку прямо,
# что плата висит и нужен USB. Четыре круга — это около двадцати секунд:
# достаточно, чтобы отсеять перезагрузку прошивки, и мало, чтобы не гадать.
МОЛЧИТ_СОВСЕМ = 4

# Как часто напоминать о молчащей плате после того, как всё уже сказано.
# Сотня кругов — это около десяти минут: заглянувший в журнал через час
# увидит, что робот до сих пор слеп, а сплошной стены сообщений не будет.
НАПОМИНАТЬ_КАЖДЫЕ = 100

# Через сколько без единого кадра переспрашивать, каким протоколом говорит
# плата. Пять секунд: живая плата в любом режиме укладывается в доли секунды,
# а перевыбор стоит ровно одну секунду тишины.
ПЕРЕСПРОСИТЬ_ЧЕРЕЗ = 5.0

# --- окно наружу -------------------------------------------------------------
# Порт нельзя читать вдвоём: открыть его могут двое, и они делят байты пополам.
# То есть пробник, запущенный при живом роботе, не просто ничего не видит — он
# ПОРТИТ роботу датчик ровно в тот момент, когда человек проверяет датчик.
# Останавливать ради этого сервис — четыре команды и две забытых, и мы это уже
# проходили трижды.
#
# Поэтому владелец порта один, как и у камеры, а всем остальным он выкладывает
# последнюю сетку в файл. Пять раз в секунду, пара сотен байт — глазами столько
# всё равно не читается, а на диск это ничто.
ФАЙЛ_СЕТКИ = "tof_last.json"
ПИСАТЬ_РАЗ_В = 0.2

# Доля непрочитанных зон, после которой кадру нельзя верить целиком. На солнце
# она скачет с десятой части до половины, и оставшиеся зоны описывают уже не
# комнату, а случайные удачные лучи.
СЛЕПОЙ_КАДР = 0.5

# Ноль от датчика — это не «расстояние ноль», а «не измерил»: слишком далеко,
# слишком темно, стекло, зеркало. Считать его нулём значит тормозить посреди
# пустого коридора, поэтому такие зоны выбрасываются целиком.
НЕ_ИЗМЕРИЛ = 0.0

# --- какой стороной вверх ----------------------------------------------------
# Плата подписывает ряды «y0…y7», но какой из них верхний, в её документации
# не сказано ни слова. А от этого зависит всё: обрыв ищется в нижних рядах, и
# перепутать верх с низом значит искать лестницу в потолке.
#
# Проверяется за двадцать секунд: провести рукой сверху вниз перед датчиком и
# посмотреть, в каком порядке отзываются ряды. Если снизу вверх — ROBOT_TOF_FLIP=1.
ПЕРЕВЕРНУТЬ = os.environ.get("ROBOT_TOF_FLIP", "0") == "1"

# --- свои же зоны ------------------------------------------------------------
# Часть лучей упирается в сам робот: кронштейн, провод, край корпуса. Такая
# зона мерит честно и стабильно — и ровно поэтому опасна: она сообщает
# «препятствие в шести сантиметрах» вечно, и робот не поедет никуда.
#
# Отличить своё железо от чужой стены изнутри нельзя, и учить это на ходу
# нельзя тем более: робот, включённый носом в стену, запомнил бы стену своей
# деталью и потом поехал бы в неё. Поэтому список зон записывает человек —
# один раз, освободив место перед роботом:
#     python3 scripts/tof_probe.py --свои
ФАЙЛ_СВОИХ = "tof_blind.json"
# Насколько зона должна быть неподвижна, чтобы считаться своей деталью.
# Четыре сантиметра: живая сцена столько не выстаивает даже в пустой комнате,
# а привинченный кронштейн не шевелится вовсе.
СВОЁ_ДРОЖИТ = 0.04
# И насколько близко. Дальше полуметра свои детали не бывают — там уже комната.
СВОЁ_БЛИЖЕ = 0.5
# Как часто зона должна отвечать, чтобы вообще судить о её постоянстве.
СВОЁ_НАДЁЖНОСТЬ = 0.9


def _постоянные(кадры: list[list[list[float]]]) -> dict[tuple[int, int], float]:
    """Зоны, которые в этой съёмке не шевелились. Зона → её расстояние."""
    ровные: dict[tuple[int, int], float] = {}
    if not кадры:
        return ровные
    for р in range(8):
        for к in range(8):
            замеры = [кадр[р][к] for кадр in кадры if кадр[р][к] > НЕ_ИЗМЕРИЛ]
            if len(замеры) < len(кадры) * СВОЁ_НАДЁЖНОСТЬ:
                continue          # зона молчит — значит там пусто, а не деталь
            if max(замеры) - min(замеры) > СВОЁ_ДРОЖИТ:
                continue          # дышит — значит комната
            расстояние = sorted(замеры)[len(замеры) // 2]
            if расстояние >= СВОЁ_БЛИЖЕ:
                continue          # далеко — не наша деталь
            ровные[(р, к)] = расстояние
    return ровные


def свои_зоны(кадры: list[list[list[float]]],
              после_поворота: list[list[list[float]]] | None = None,
              ) -> list[tuple[int, int]]:
    """Какие зоны смотрят в сам робот.

    Первый признак — НЕПОДВИЖНОСТЬ вблизи: стена в двадцати сантиметрах тоже
    близка, но она дышит (шум датчика, дрожание робота, тень от лампы), а
    кронштейн не дышит.

    Одного этого признака мало, и разница тут не теоретическая. Стена сбоку
    неподвижна ровно так же, как кронштейн, — а пометить стену «своей
    деталью» значит велеть роботу её не замечать. Такая ошибка не видна
    вообще ничем: робот не тормозит и ни на что не жалуется, просто однажды
    едет в стену.

    Поэтому решает второй замер, снятый ПОСЛЕ ПОВОРОТА робота на месте.
    Своё железо повёрнуто вместе с датчиком и осталось на том же расстоянии.
    Комната — нет: стена ушла, мебель сменилась, расстояния другие. Разделить
    их иначе изнутри нельзя, и гадать тут нечего.

    Без второго замера возвращаем пустой список, а не догадку: список своих
    зон отключает защиту, и лучше его не иметь, чем иметь неверный.
    """
    первые = _постоянные(кадры)
    if после_поворота is None:
        return []
    вторые = _постоянные(после_поворота)
    свои: list[tuple[int, int]] = []
    for зона, было in первые.items():
        стало = вторые.get(зона)
        if стало is None:
            continue              # после поворота там пусто — значит комната
        if abs(стало - было) > СВОЁ_ДРОЖИТ:
            continue              # расстояние сменилось — значит комната
        свои.append(зона)
    return свои


def загрузить_своих(файл: Path | None = None) -> set[tuple[int, int]]:
    файл = файл or (Path.home() / ".robot-ai" / ФАЙЛ_СВОИХ)
    try:
        данные = json.loads(файл.read_text())
    except (OSError, ValueError):
        return set()
    зоны = данные.get("зоны") or []
    return {(int(р), int(к)) for р, к in зоны
            if 0 <= int(р) < 8 and 0 <= int(к) < 8}


def сохранить_своих(зоны, файл: Path | None = None) -> Path:
    файл = файл or (Path.home() / ".robot-ai" / ФАЙЛ_СВОИХ)
    файл.parent.mkdir(parents=True, exist_ok=True)
    врем = файл.with_name(файл.name + ".tmp")
    врем.write_text(json.dumps({"зоны": [list(з) for з in sorted(зоны)]},
                               ensure_ascii=False))
    врем.replace(файл)
    return файл


