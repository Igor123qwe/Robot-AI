# Отсюда «дальше пола нет» пятьсот кадров подряд на живом роботе — на ровном
# полу, в комнате без единой ступеньки.
#
# Настоящий обрыв даёт куда больше:
#
#     ступенька  8 см → 1.60х нормы
#     ступенька 10 см → 1.77х
#     ступенька 15 см (ступень лестницы) → 2.15х
#     край стола, пустота → замер пропадает вовсе
#
# Берём 1.6: терпим крен до восьми градусов и ловим ступеньку от восьми
# сантиметров. Ниже восьми — это порожек между комнатами, с него робот не
# упадёт. А главное, пропадание замера считается обрывом отдельно и порогом
# не смягчается: за краем ступеньки луч не возвращается вовсе, и это самый
# частый вид обрыва, а не редкий.
ОБРЫВ_ДАЛЬШЕ = 1.6
# И обратное: во сколько раз БЛИЖЕ нормы, чтобы считать, что на полу что-то
# лежит. Три четверти: нога, кошка, игрушка, порог — всё это ближе пола, и
# заметно ближе, а не на сантиметр.
#
# Это зеркало проверки обрыва, и появилось оно дорогой ценой. Сторож смотрел
# только на средние ряды — там, где стены и мебель, — а нижние исключал, чтобы
