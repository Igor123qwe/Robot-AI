"""Дальномер: сетка 8×8 расстояний перед роботом.

Это спинной мозг робота. Он не понимает, что перед ним, — он знает только
«близко» и «далеко», зато знает это за сотую долю секунды и в темноте.
Понимание живёт выше: камера и модель разбираются, что там за предмет, и
тратят на это секунды. Пока они думают, робот уже успел бы приехать в стену,
поэтому решение «стоп» принимается здесь и ни с кем не согласовывается.

Железо: DFRobot Gravity 8×8 Matrix ToF (SEN0628) на VL53L7CX, подключён по
USB. Внутри платы RP2040, поэтому в системе он выглядит как «Raspberry Pi
Pico» и получает имя /dev/ttyACM*. Номер меняется при загрузке, а на соседнем
живёт контроллер приводов — поэтому обращаемся только по постоянному имени из
/dev/serial/by-id.

Поле зрения 63 градуса, дальность до 3.5 метра, до 15 кадров в секунду.

Про пол. Сетка смотрит и вниз тоже, поэтому нижние ряды упираются в пол
метрах в полутора и честно докладывают препятствие. Это не помеха, а второй
датчик: пол на известном расстоянии — норма, пол ВНЕЗАПНО ДАЛЬШЕ обычного —
обрыв, ступенька или порог. Ради этого нижние ряды разбираются отдельно.
"""

from __future__ import annotations

import glob
import logging
import os
import threading
import time

log = logging.getLogger(__name__)

# Скорость порта у этой платы зашита намертво и настройке не подлежит.
СКОРОСТЬ = 115200

# Кадр запроса: заголовок, число аргументов (два байта), команда, аргументы.
ЗАГОЛОВОК = 0x55
# Кадр ответа: состояние, эхо команды, длина (два байта), данные.
УДАЧА = 0x53
ОТКАЗ = 0x63

CMD_ALL_DATA = 0x02          # отдать всю сетку разом
CMD_CONFIG = 0x01            # переключить разрешение сетки
РЕЖИМ_8X8 = 0x08

# Сколько ждать ответа на один запрос. Плата отвечает за миллисекунды; всё,
# что дольше, — это уже не задержка, а молчание.
ОТВЕТ_ЖДЁМ = 0.5

# Через сколько тишины считать датчик отвалившимся. Исправный сыплет кадры
# непрерывно, поэтому секунда молчания — это уже беда.
ЗАВИС_ЧЕРЕЗ = 2.0

# Ближе этого — стоп. Тридцать сантиметров на скорости 0.3 м/с дают секунду
# на остановку, а сама остановка занимает доли. Запас нужен: датчик мерит
# от своей платы, а у робота есть ещё бампер и колёса впереди неё.
СТОП_БЛИЖЕ = 0.30

# Ближе этого — ехать можно, но медленно. Полтора метра выбраны по паспорту:
# дальше показания VL53L7CX в комнате уже пляшут.
ТИХО_БЛИЖЕ = 1.00

# Ноль от датчика — это не «расстояние ноль», а «не измерил»: слишком далеко,
# слишком темно, стекло, зеркало. Считать его нулём значит тормозить посреди
# пустого коридора, поэтому такие зоны выбрасываются целиком.
НЕ_ИЗМЕРИЛ = 0.0


def найти_устройство() -> str:
    """Постоянное имя дальномера, и только оно.

    Рядом на /dev/ttyACM* живёт контроллер приводов, а номера раздаются в
    порядке появления при загрузке и меняются местами. Ошибиться здесь — это
    слать запросы дальности в моторы, поэтому никаких /dev/ttyACM0: ищем по
    имени платы, которое привязано к самому устройству.
    """
    своё = os.environ.get("ROBOT_TOF_DEVICE", "").strip()
    if своё:
        return своё
    # Внутри SEN0628 стоит RP2040, поэтому система зовёт его «Pico».
    for образец in ("*Raspberry_Pi_Pico*", "*RP2040*", "*DFRobot*"):
        нашлось = sorted(glob.glob(f"/dev/serial/by-id/usb-{образец}-if00"))
        if нашлось:
            return нашлось[0]
    return ""


def _кадр(cmd: int, args: bytes = b"") -> bytes:
    """Собрать кадр запроса."""
    return bytes([ЗАГОЛОВОК, (len(args) >> 8) & 0xFF, len(args) & 0xFF, cmd]) + args


def разобрать(ответ: bytes) -> tuple[int, bytes] | None:
    """Разобрать кадр ответа: (команда, данные). None — кадр не наш.

    Отдельной функцией, чтобы разбор проверялся без железа: собрать байты в
    проверке легко, а воткнуть датчик в сборочную машину — нет.
    """
    if len(ответ) < 4:
        return None
    состояние, cmd = ответ[0], ответ[1]
    if состояние not in (УДАЧА, ОТКАЗ):
        return None
    длина = ответ[2] | (ответ[3] << 8)
    данные = ответ[4:4 + длина]
    if len(данные) < длина:
        return None
    return (cmd, b"") if состояние == ОТКАЗ else (cmd, данные)


def в_метры(данные: bytes) -> list[list[float]]:
    """Сырые байты сетки — в метры, строками сверху вниз.

    Каждая зона — два байта, младший первым, в сантиметрах. Ноль означает
    «не измерил», и он остаётся нулём: заменять его большим числом нельзя,
    иначе стекло и зеркала превратятся в открытый путь.
    """
    точек = min(64, len(данные) // 2)
    плоско = [(данные[2 * i] | (данные[2 * i + 1] << 8)) / 100.0
              for i in range(точек)]
    плоско += [НЕ_ИЗМЕРИЛ] * (64 - точек)
    return [плоско[ряд * 8:(ряд + 1) * 8] for ряд in range(8)]


class Взгляд:
    """Что видит дальномер прямо сейчас, уже осмысленно."""

    def __init__(self, сетка: list[list[float]], когда: float) -> None:
        self.сетка = сетка
        self.когда = когда

    @property
    def свежий(self) -> bool:
        return time.monotonic() - self.когда < ЗАВИС_ЧЕРЕЗ

    def _живые(self, ряды: range, колонки: range) -> list[float]:
        return [self.сетка[р][к] for р in ряды for к in колонки
                if self.сетка[р][к] > НЕ_ИЗМЕРИЛ]

    @property
    def впереди(self) -> float:
        """Ближайшее препятствие по курсу, метры. Ноль — не измерил ничего.

        Берём середину сетки: четыре центральных ряда и все колонки. Верхние
        ряды смотрят выше робота (туда он не поедет), нижние упираются в пол
        и в оценке пути только мешают.
        """
        живые = self._живые(range(2, 6), range(0, 8))
        return min(живые) if живые else НЕ_ИЗМЕРИЛ

    @property
    def слева(self) -> float:
        живые = self._живые(range(2, 6), range(0, 3))
        return min(живые) if живые else НЕ_ИЗМЕРИЛ

    @property
    def справа(self) -> float:
        живые = self._живые(range(2, 6), range(5, 8))
        return min(живые) if живые else НЕ_ИЗМЕРИЛ

    @property
    def пол(self) -> float:
        """Расстояние до пола по нижнему ряду. Ноль — пола не видно."""
        живые = self._живые(range(7, 8), range(0, 8))
        return max(живые) if живые else НЕ_ИЗМЕРИЛ

    def ехать_можно(self) -> tuple[bool, str]:
        """Можно ли двигаться вперёд, и если нет — почему, по-русски.

        Причину возвращаем словами намеренно: этот ответ идёт и в журнал, и
        человеку вслух, и модели в инструмент. Один текст на всех избавляет от
        трёх согласованных наборов формулировок, которые разъезжаются.
        """
        if not self.свежий:
            # Молчащий датчик — не разрешение ехать. Отказ при отказе.
            return False, "дальномер молчит"
        близко = self.впереди
        if близко > НЕ_ИЗМЕРИЛ and близко < СТОП_БЛИЖЕ:
            сторона = ("слева" if self.слева and self.слева <= self.справа
                       else "справа")
            return False, f"впереди препятствие в {близко:.1f} м, {сторона}"
        return True, ""


class Дальномер:
    """Читает сетку в отдельном потоке, отдаёт последнее увиденное."""

    def __init__(self, устройство: str = "", частота: float = 10.0) -> None:
        self.устройство = устройство or найти_устройство()
        self.период = 1.0 / max(1.0, частота)
        self._взгляд = Взгляд([[НЕ_ИЗМЕРИЛ] * 8 for _ in range(8)], 0.0)
        self._замок = threading.Lock()
        self._стоп = threading.Event()
        self._поток: threading.Thread | None = None
        self._беда = ""
        self._сырьё: bytes = b""      # последний кадр как есть, для разбора бед

    @property
    def беда(self) -> str:
        return self._беда

    @property
    def сырьё(self) -> bytes:
        """Последний ответ платы байтами. Нужен, когда протокол не сошёлся."""
        return self._сырьё

    def доступен(self) -> bool:
        return bool(self.устройство) and os.path.exists(self.устройство)

    def взгляд(self) -> Взгляд:
        with self._замок:
            return self._взгляд

    def запустить(self) -> bool:
        if not self.доступен():
            self._беда = f"нет устройства {self.устройство or '/dev/serial/by-id/*Pico*'}"
            log.info("дальномер: %s — еду вслепую", self._беда)
            return False
        self._поток = threading.Thread(target=self._читать, daemon=True)
        self._поток.start()
        return True

    def закрыть(self) -> None:
        self._стоп.set()

    # --- внутри ---------------------------------------------------------
    def _открыть(self):
        """Открыть порт на нужной скорости средствами системы.

        Без pyserial: на роботе и так хватает библиотек, а нужно отсюда ровно
        одно — выставить скорость и отключить всякую обработку символов.
        Термios это умеет, он есть в поставке Python.
        """
        import termios

        fd = os.open(self.устройство, os.O_RDWR | os.O_NOCTTY)
        настройки = termios.tcgetattr(fd)
        iflag, oflag, cflag, lflag, ispeed, ospeed, cc = настройки
        скорость = getattr(termios, f"B{СКОРОСТЬ}")
        # Сырой режим: никаких переводов строк, эха и разбора управляющих
        # символов. Данные двоичные, и любая «помощь» их портит.
        iflag = 0
        oflag = 0
        lflag = 0
        cflag = termios.CS8 | termios.CREAD | termios.CLOCAL
        cc = list(cc)
        cc[termios.VMIN] = 0
        cc[termios.VTIME] = 1          # десятые доли секунды
        termios.tcsetattr(fd, termios.TCSANOW,
                          [iflag, oflag, cflag, lflag, скорость, скорость, cc])
        termios.tcflush(fd, termios.TCIOFLUSH)
        return fd

    def _спросить(self, fd: int, cmd: int, args: bytes = b"") -> bytes:
        os.write(fd, _кадр(cmd, args))
        срок = time.monotonic() + ОТВЕТ_ЖДЁМ
        буфер = b""
        while time.monotonic() < срок:
            кусок = os.read(fd, 4096)
            if кусок:
                буфер += кусок
                # Заголовок ответа — четыре байта, дальше объявленная длина.
                if len(буфер) >= 4:
                    нужно = 4 + (буфер[2] | (буфер[3] << 8))
                    if len(буфер) >= нужно:
                        return буфер[:нужно]
            else:
                time.sleep(0.005)
        return буфер

    def _читать(self) -> None:
        fd = -1
        try:
            fd = self._открыть()
            log.info("дальномер: слушаю %s", self.устройство)
            # Просим сетку 8×8. Плата умеет и 4×4, и умолчание у неё своё.
            self._спросить(fd, CMD_CONFIG, bytes([РЕЖИМ_8X8]))
            жаловался = ""
            while not self._стоп.is_set():
                ответ = self._спросить(fd, CMD_ALL_DATA)
                self._сырьё = ответ
                разбор = разобрать(ответ)
                if разбор is None or not разбор[1]:
                    # Жалуемся на КАЖДУЮ НОВУЮ беду, но не на повтор той же:
                    # иначе десять раз в секунду в журнал польётся одно и то
                    # же, и настоящую причину в нём будет не найти.
                    что = f"нет ответа ({ответ[:8].hex() or 'пусто'})"
                    if что != жаловался:
                        жаловался = что
                        log.warning("дальномер: %s", что)
                        self._беда = что
                    time.sleep(self.период)
                    continue
                жаловался = ""
                self._беда = ""
                with self._замок:
                    self._взгляд = Взгляд(в_метры(разбор[1]), time.monotonic())
                time.sleep(self.период)
        except Exception as e:            # noqa: BLE001 — отвал не повод падать
            self._беда = str(e)
            log.warning("дальномер: чтение оборвалось (%s)", e)
        finally:
            if fd >= 0:
                with __import__("contextlib").suppress(OSError):
                    os.close(fd)
