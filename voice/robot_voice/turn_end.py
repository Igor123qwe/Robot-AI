"""Договорил ли человек — по звуку, а не по тишине.

Зачем это вообще нужно, лучше всего видно из живого журнала:

    gigaam: 0.55 с на 5.0 с звука
    gigaam: 0.50 с на 5.0 с звука
    gigaam: 0.53 с на 5.0 с звука

Пять секунд — это потолок окна команды. Запись обязана кончаться через
полтысячи миллисекунд тишины, а она раз за разом упирается в предел. Причина
простая: в квартире с ребёнком тишины не наступает вовсе. Человек сказал
«Кузя, сколько времени» за две секунды — и дальше ТРИ СЕКУНДЫ робот молча
пишет комнату, уже всё расслышав.

Это самое обидное ожидание из всех, и в секундомере его не видно: он
заводится, когда кусок уже нарезан. Снаружи это выглядит как «робот долго
думает», хотя робот в это время не думает, а ждёт тишины, которой не будет.

Тишина — плохой признак конца реплики. Хороший признак — сама реплика: люди
заканчивают говорить с определённой интонацией, темпом и грамматикой, и это
слышно ДО паузы. На этом устроены современные определители конца хода
(Smart Turn и родня): маленькая сеть смотрит на сырую волну последних секунд
и говорит, закончил человек или взял дыхание посреди фразы.

Здесь — обёртка вокруг такой сети в формате ONNX. Своей модели мы не учим и
не поставляем: файл кладёт человек, путь задаётся настройкой.

ГЛАВНОЕ СВОЙСТВО, ради которого это можно включать без опаски: определитель
умеет резать только РАНЬШЕ, никогда не позже. Старые правила (тишина и
потолок окна) остаются на месте нетронутыми. Значит худший случай — ровно
сегодняшнее поведение, а модели нет или она молчит — робот работает как
работал. Ни одна ветка здесь не может сделать хуже.
"""

from __future__ import annotations

import logging
import math
import os
import time
from pathlib import Path

import numpy as np

log = logging.getLogger(__name__)

# Сколько звука показывать сети. Восемь секунд — столько берут обученные на
# это модели; больше не нужно, конец реплики слышен по её последним секундам.
ОКНО_СЕКУНД = 8.0

# Насколько уверенной должна быть сеть, чтобы мы поверили ей и оборвали
# запись. Планка высокая намеренно: ошибка «решил, что договорил» обрезает
# человека на полуслове, а ошибка «не решил» стоит всего лишь сегодняшнего
# ожидания. Цена этих ошибок несоизмерима, и планка это отражает.
ПОРОГ = float(os.environ.get("ROBOT_TURN_THRESHOLD", "0.85"))

# Как часто спрашивать. Двести пятьдесят миллисекунд: чаще — жжём процессор
# на A55 без пользы (реплика за четверть секунды не заканчивается дважды),
# реже — теряем ту самую четверть секунды, ради которой всё затевалось.
СПРАШИВАТЬ_РАЗ_В = 0.25

# Раньше этого не спрашиваем вовсе. Человек не успевает договорить за
# полсекунды, а вот сеть на таком огрызке отвечает наугад.
НЕ_РАНЬШЕ_СЕКУНД = 0.7

# «Ещё не знаю, чем отвечает сеть». Отдельное значение, а не False: незнание
# и «точно вероятность» ведут себя по-разному, и путать их нельзя.
_ЖДЁМ_ЛОГИТЫ = None


def _ответ_настройкой() -> bool | None:
    """Человек может сказать прямо, чем отвечает его модель.

    Нужно на случай, когда сеть назвала выход невнятно, а угадали мы неверно.
    Признак этого в журнале ясный: «спросили N, оборвали 0» при N в сотнях.
    """
    задано = os.environ.get("ROBOT_TURN_OUTPUT", "").strip().lower()
    if задано in ("вероятность", "prob", "probability"):
        return False
    if задано in ("логит", "логиты", "logit", "logits"):
        return True
    return None


_ОТВЕТ_НАСТРОЙКОЙ = _ответ_настройкой()


class КонецРеплики:
    """Маленькая сеть, отвечающая на один вопрос: человек договорил?

    Пусто (None из `договорил`) — не знаю. Это полноценный ответ, а не
    поломка: не зная, обрываем ли мы человека, права оборвать у нас нет, и
    решение остаётся за прежними правилами.
    """

    def __init__(self, путь: Path, частота: int = 16000,
                 порог: float = ПОРОГ) -> None:
        self.частота = частота
        self.порог = порог
        self.сессия = None
        self._вход = ""
        # Чем отвечает сеть: True — логитом, False — вероятностью,
        # None — ещё не разобрались. Ставится при подъёме, см. _поднять.
        self.логиты = _ЖДЁМ_ЛОГИТЫ
        self._длина = 0          # сколько отсчётов ждёт сеть; 0 — любая длина
        self._спрошено = 0.0
        self._жалоба = ""
        # Сколько раз сеть сказала «договорил» и сколько всего спрашивали.
        # Нужно, чтобы человек по журналу видел, работает она или молчит:
        # определитель, который всегда отвечает «нет», внешне неотличим от
        # выключенного, а лечится совсем иначе (порогом, а не установкой).
        self.спросили = 0
        self.оборвали = 0
        self._мс = 0.0
        self._поднять(путь)

    # --- подъём -----------------------------------------------------------
    def _поднять(self, путь: Path) -> None:
        if not путь.exists():
            self._жалоба = f"нет файла модели {путь}"
            return
        try:
            import onnxruntime as ort
        except ImportError:
            self._жалоба = ("нет onnxruntime — поставить: "
                            "voice/.venv/bin/pip install onnxruntime")
            return
        try:
            наст = ort.SessionOptions()
            # Одно ядро, и это не скупость. Рядом крутятся ловля имени,
            # дальномер на десяти герцах и сторож колёс на пятнадцати;
            # определитель, разбежавшийся на все восемь ядер, отнимет их у
            # того, от чего зависит безопасность движения.
            наст.intra_op_num_threads = 1
            наст.inter_op_num_threads = 1
            сессия = ort.InferenceSession(
                str(путь), sess_options=наст, providers=["CPUExecutionProvider"])
        except Exception as e:                  # noqa: BLE001
            self._жалоба = f"не поднялся ({e})"
            return

        входы = сессия.get_inputs()
        if not входы:
            self._жалоба = "у модели нет входов — это не та модель"
            return
        # Имя входа и ожидаемую длину читаем У САМОЙ МОДЕЛИ, а не забиваем
        # константой. Модели этого рода выходят версиями, и у версий разнятся
        # и имена входов, и длина окна; прибитая константа означала бы, что
        # обновление модели молча ломает определитель — а молча он и так
        # выглядит выключенным.
        self._вход = входы[0].name
        # Чем сеть отвечает — вероятностью или логитом. Разобраться надо ДО
        # первого ответа: по самому числу их не различить (см. _вероятность),
        # а ошибка стоит обрезанной на полуслове фразы.
        #
        # Спрашиваем у модели, как зовут её выход. Это не догадка по имени
        # файла, а объявленное самой сетью имя тензора, и авторы называют его
        # осмысленно. Не разобрали — скажем об этом вслух и пойдём безопасной
        # дорогой, а человек при желании поправит настройкой.
        self.логиты = _ЖДЁМ_ЛОГИТЫ
        выходы = сессия.get_outputs()
        имя_выхода = (выходы[0].name if выходы else "").lower()
        if "prob" in имя_выхода or "sigmoid" in имя_выхода:
            self.логиты = False
        elif "logit" in имя_выхода:
            self.логиты = True
        if _ОТВЕТ_НАСТРОЙКОЙ is not None:
            self.логиты = _ОТВЕТ_НАСТРОЙКОЙ
        форма = входы[0].shape or []
        последнее = форма[-1] if форма else None
        if isinstance(последнее, int) and последнее > 0:
            self._длина = последнее
        else:
            self._длина = int(ОКНО_СЕКУНД * self.частота)
        self.сессия = сессия
        чем = {True: "логитом", False: "вероятностью"}.get(
            self.логиты, "непонятно чем — считаю логитом, поправить можно "
                         "настройкой ROBOT_TURN_OUTPUT=вероятность")
        log.info("конец реплики: %s, окно %.1f с, порог %.2f, отвечает %s",
                 путь.name, self._длина / self.частота, self.порог, чем)

    @property
    def готов(self) -> bool:
        return self.сессия is not None

    def почему_нет(self) -> str:
        return self._жалоба

    # --- вопрос -----------------------------------------------------------
    def пора_спросить(self, накоплено_секунд: float) -> bool:
        """Стоит ли тратить процессор прямо сейчас."""
        if not self.готов or накоплено_секунд < НЕ_РАНЬШЕ_СЕКУНД:
            return False
        сейчас = time.monotonic()
        if сейчас - self._спрошено < СПРАШИВАТЬ_РАЗ_В:
            return False
        self._спрошено = сейчас
        return True

    def договорил(self, звук: np.ndarray) -> bool | None:
        """Договорил ли человек. None — не знаю, решай прежними правилами."""
        if not self.готов:
            return None
        try:
            начало = time.monotonic()
            вероятность = self._спросить(звук)
            self._мс = (time.monotonic() - начало) * 1000.0
        except Exception as e:                  # noqa: BLE001
            # Сеть отказала — молчим и живём дальше по-старому. Ронять из-за
            # определителя весь слух робота нельзя: он ускоряет, а не работает.
            if not self._жалоба:
                self._жалоба = f"сеть отказала ({e})"
                log.warning("конец реплики: %s — дальше по тишине", self._жалоба)
            self.сессия = None
            return None
        self.спросили += 1
        if вероятность is None:
            return None
        if вероятность >= self.порог:
            self.оборвали += 1
            log.debug("конец реплики: договорил (%.2f, %.0f мс)",
                      вероятность, self._мс)
            return True
        return False

    def _спросить(self, звук: np.ndarray) -> float | None:
        окно = self._окно(звук)
        выход = self.сессия.run(None, {self._вход: окно})
        if not выход:
            return None
        return self._вероятность(np.asarray(выход[0]).ravel())

    def _окно(self, звук: np.ndarray) -> np.ndarray:
        """Последние секунды звука в том виде, который ждёт сеть.

        Берём ХВОСТ, а не начало: конец реплики слышен по её концу, и первые
        секунды длинной фразы для этого вопроса бесполезны. Короткое дополняем
        тишиной СЛЕВА — чтобы конец реплики оставался у правого края окна,
        там же, где он был у примеров при обучении.
        """
        куски = звук.astype(np.float32)
        if куски.dtype != np.float32 or куски.max(initial=0.0) > 1.5:
            # Пришли целые отсчёты — приводим к отрезку [-1, 1].
            куски = куски / 32768.0
        нужно = self._длина
        if len(куски) >= нужно:
            куски = куски[-нужно:]
        else:
            куски = np.pad(куски, (нужно - len(куски), 0))
        return куски.reshape(1, нужно).astype(np.float32)

    def _вероятность(self, выход: np.ndarray) -> float | None:
        """Число сети — в вероятность «договорил».

        Два числа — логиты двух классов, разбираются однозначно.

        А вот ОДНО число неоднозначно, и неоднозначность здесь опасная. Сети
        этого рода отдают либо готовую вероятность, либо сырой логит, и по
        самому числу их не различить: 0.9 — это и вероятность 0.9 (обрывать
        пора), и логит 0.9 (на деле 0.71, обрывать рано). Приняв логит за
        вероятность, робот обрежет человека на полуслове — то есть сделает
        ровно ту ошибку, цену которой мы всюду здесь считаем высшей.

        Гадать нельзя, поэтому не гадаем, а ВЫЯСНЯЕМ — тем же приёмом, что и
        в других местах этого проекта, где свойство собеседника узнаётся
        делом, а не объявляется. Число вне отрезка [0, 1] бывает только у
        логита; увидели такое — запомнили навсегда и дальше считаем сигмоиду.

        Пока не выяснили, держимся безопасной стороны: считаем число логитом.
        Ошибка в эту сторону стоит лишней доли секунды ожидания, ошибка в
        другую — обрезанной фразы.
        """
        if выход.size == 2:
            а, б = float(выход[0]), float(выход[1])
            верх = max(а, б)
            эа, эб = math.exp(а - верх), math.exp(б - верх)
            return эб / (эа + эб)
        if выход.size != 1:
            return None
        число = float(выход[0])
        if not (0.0 <= число <= 1.0):
            if self.логиты is not True:
                log.info("конец реплики: сеть отдаёт логиты (%.2f) — считаю "
                         "сигмоиду", число)
            self.логиты = True
        return self._сигмоида(число) if self.логиты is not False else число

    @staticmethod
    def _сигмоида(число: float) -> float:
        return 1.0 / (1.0 + math.exp(-max(-60.0, min(60.0, число))))


def собрать(cfg) -> "КонецРеплики | None":
    """Поднять определитель или честно сказать, почему не вышло.

    None — не поломка, а прежний порядок: режем по тишине. Поэтому и жалоба
    идёт одной строкой info, а не воплем: у человека может не быть модели, и
    это нормальный, рабочий режим робота.
    """
    путь = str(getattr(cfg, "turn_model", "") or "").strip()
    if not путь:
        return None
    файл = Path(путь).expanduser()
    определитель = КонецРеплики(файл, частота=getattr(cfg, "sample_rate", 16000))
    if определитель.готов:
        return определитель
    log.info("конец реплики не включён: %s. Режу по тишине, как раньше",
             определитель.почему_нет())
    return None
