#!/usr/bin/env python3
"""Подойдёт ли эта модель VRM нашему Кузе — не глядя на неё в браузере.

    python pc/vrm_проверить.py путь/к/модели.vrm

Зачем: на VRoid Hub тысячи моделей, и по картинке не видно главного — есть ли
у неё то, чем персонаж оживает. Скачал, натравил эту проверку, за секунду
знаешь, стоит ли возиться. Что смотрим и почему:

  • ВЫРАЖЕНИЯ (happy/sad/angry/relaxed/surprised) — эмоции робота показывать
    нечем без них: лицо будет неподвижным при любом настроении;
  • МОРГАНИЕ (blink) — неморгающий взгляд первым выдаёт мертвечину;
  • ВИЗЕМЫ (aa/ih/ou/ee/oh) — рот под речь. Нет — Кузя будет говорить с
    закрытым ртом;
  • ФИЗИКА (spring bones) — волосы, одежда, уши и хвост качаются сами, без
    единой анимации. Это половина ощущения живого, и это ГЛАВНОЕ отличие от
    Live2D: у длинноволосой модели в юбке жизни больше, чем у стриженой в
    комбинезоне, при том же нашем коде;
  • КОСТИ — по ним работают все 192 наши сценки (голова, корпус, руки);
  • ЛИЦЕНЗИЯ — что автор разрешил. Печатаем как есть, решать вам.

Файл .vrm — это glTF (glb) со своими расширениями, поэтому всё читается
питоном, без браузера и без чужих библиотек.
"""
from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

НУЖНЫ_ВЫРАЖЕНИЯ = ["happy", "sad", "angry", "relaxed", "surprised"]
НУЖНЫ_ВИЗЕМЫ = ["aa", "ih", "ou", "ee", "oh"]
НУЖНЫ_КОСТИ = ["head", "spine", "leftUpperArm", "rightUpperArm"]


def читать_glb(путь: Path) -> dict:
    """JSON-часть файла .vrm (он же .glb). Не glb — понятная ошибка."""
    данные = путь.read_bytes()
    if len(данные) < 20 or данные[:4] != b"glTF":
        raise ValueError("это не файл glb/vrm (нет подписи glTF в начале)")
    длина, тип = struct.unpack("<II", данные[12:20])
    if тип != 0x4E4F534A:
        raise ValueError("первый кусок файла — не JSON, файл повреждён")
    return json.loads(данные[20:20 + длина])


def разобрать(gltf: dict) -> dict:
    """Что есть у модели — одинаково для VRM 0.x и 1.0."""
    расш = gltf.get("extensions") or {}
    новый = расш.get("VRMC_vrm")
    старый = расш.get("VRM")
    итог: dict = {"версия": "", "выражения": [], "кости": [], "пружин": 0,
                  "лицензия": {}, "имя": ""}
    if новый:
        итог["версия"] = "VRM " + str(новый.get("specVersion", "1.0"))
        итог["выражения"] = sorted((новый.get("expressions") or {}).get("preset", {}))
        итог["кости"] = sorted((новый.get("humanoid") or {}).get("humanBones", {}))
        мета = новый.get("meta") or {}
        итог["имя"] = мета.get("name", "")
        итог["лицензия"] = {
            "автор": ", ".join(мета.get("authors") or []),
            "кем можно играть": мета.get("avatarPermission", "?"),
            "коммерческое использование": мета.get("commercialUsage", "?"),
            "можно ли раздавать дальше": ("да" if мета.get("allowRedistribution") else "нет"),
            "правки модели": мета.get("modification", "?"),
        }
        итог["пружин"] = len(((расш.get("VRMC_springBone") or {}).get("springs")) or [])
    elif старый:
        итог["версия"] = "VRM 0.x"
        группы = ((старый.get("blendShapeMaster") or {}).get("blendShapeGroups")) or []
        # У старых имя выражения лежит в presetName («joy», «blink»…), а имена
        # у них свои: joy вместо happy, sorrow вместо sad. Переводим сразу,
        # иначе проверка ниже честно скажет «нет happy» у модели, где он есть.
        перевод = {"joy": "happy", "sorrow": "sad", "angry": "angry", "fun": "relaxed",
                   "surprised": "surprised", "neutral": "neutral", "blink": "blink",
                   "a": "aa", "i": "ih", "u": "ou", "e": "ee", "o": "oh"}
        имена = {перевод.get(str(г.get("presetName", "")).lower(),
                             str(г.get("presetName", "")).lower()) for г in группы}
        итог["выражения"] = sorted(и for и in имена if и and и != "unknown")
        итог["кости"] = sorted(к.get("bone", "") for к in
                               ((старый.get("humanoid") or {}).get("humanBones")) or [])
        мета = старый.get("meta") or {}
        итог["имя"] = мета.get("title", "")
        итог["лицензия"] = {
            "автор": мета.get("author", "?"),
            "кем можно играть": мета.get("allowedUserName", "?"),
            "коммерческое использование": мета.get("commercialUssageName", "?"),
            "можно ли раздавать дальше": мета.get("licenseName", "?"),
            "насилие/взрослое": f"{мета.get('violentUssageName', '?')}/"
                                f"{мета.get('sexualUssageName', '?')}",
        }
        итог["пружин"] = len((((старый.get("secondaryAnimation") or {})
                               .get("boneGroups")) or []))
    else:
        raise ValueError("в файле нет расширения VRM — это обычная 3D-модель "
                         "glTF, наша страница её не оживит")
    # Треугольники — грубо, по числам вершинных указателей: важен порядок
    # величины, а не точность. Десятки тысяч — обычная модель с VRoid.
    доступ = gltf.get("accessors") or []
    итог["треугольников"] = sum(д.get("count", 0) for п in (gltf.get("meshes") or [])
                                for пр in п.get("primitives", [])
                                if (i := пр.get("indices")) is not None
                                for д in [доступ[i]]) // 3
    return итог


def напечатать(данные: dict, размер_мб: float) -> bool:
    """Печатает разбор и отвечает, годится ли модель (False — что-то важное нет)."""
    есть = set(данные["выражения"])
    нет_эмоций = [в for в in НУЖНЫ_ВЫРАЖЕНИЯ if в not in есть]
    нет_визем = [в for в in НУЖНЫ_ВИЗЕМЫ if в not in есть]
    нет_костей = [к for к in НУЖНЫ_КОСТИ if к not in данные["кости"]]

    print(f"  {данные['версия']}, «{данные['имя'] or 'без имени'}», "
          f"{размер_мб:.1f} МБ, ~{данные['треугольников']:,} треугольников"
          .replace(",", " "))
    print(f"  выражений: {len(данные['выражения'])} — {', '.join(данные['выражения']) or 'нет ни одного'}")
    print(f"  физика (пружинных цепочек волос/одежды): {данные['пружин']}")
    print(f"  костей: {len(данные['кости'])}")
    print("  лицензия:")
    for ключ, значение in данные["лицензия"].items():
        print(f"    {ключ}: {значение}")

    беды = []
    if нет_эмоций:
        беды.append("нет выражений " + ", ".join(нет_эмоций) +
                    " — эмоции робота показывать нечем, лицо будет каменным")
    if "blink" not in есть:
        беды.append("нет blink — не будет моргать, а это первое, на чём глаз "
                    "замечает неживое")
    if нет_визем:
        беды.append("нет визем " + ", ".join(нет_визем) +
                    " — рот под речь; Кузя будет говорить с закрытым ртом")
    if нет_костей:
        беды.append("нет костей " + ", ".join(нет_костей) +
                    " — наши сценки (192 штуки) двигают именно их")
    if данные["пружин"] == 0:
        беды.append("нет физики (spring bones) — волосы и одежда будут как "
                    "приклеенные; это половина ощущения живого")
    if размер_мб > 60:
        беды.append(f"{размер_мб:.0f} МБ — тяжеловата: ПК будет делить "
                    "видеокарту с моделью языка")

    print()
    if not беды:
        print("  ГОДИТСЯ: есть всё, что нашему Кузе нужно.")
        return True
    for б in беды:
        print("  ⚠ " + б)
    важное = нет_эмоций or нет_костей or "blink" not in есть
    print()
    print("  ВЫВОД: " + ("не годится — без этого персонаж будет мёртвым."
                         if важное else
                         "жить можно, но чего-то не хватает (см. выше)."))
    return not важное


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__.strip().splitlines()[2].strip())
        return 2
    плохих = 0
    for имя in sys.argv[1:]:
        путь = Path(имя)
        print(f"\n=== {путь.name} ===")
        try:
            данные = разобрать(читать_glb(путь))
        except (OSError, ValueError, KeyError, IndexError) as e:
            print(f"  не разобрал: {e}")
            плохих += 1
            continue
        if not напечатать(данные, путь.stat().st_size / 1048576):
            плохих += 1
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
