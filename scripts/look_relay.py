#!/usr/bin/env python3
"""Затвор для поиска вещей: один кадр по запросу, а не поток круглосуточно.

ЗАЧЕМ ЗАТВОР. Распознавание вещей (DOSOD) — это четвёртая модель на BPU
вдобавок к детектору людей, точкам кисти и жестам. По их же журналу один кадр
стоит около ста тридцати миллисекунд, то есть модель занимает плату почти
целиком. Пустить её на живой поток в тридцать кадров — значит отобрать BPU у
детектора людей, а на нём держатся следование, сторож падений и остановка по
ладони. Менять безопасность на «где моя кружка» нельзя.

Поэтому DOSOD подписан не на камеру, а на наш топик, куда кадр попадает
только когда о нём попросили. Пока не просят — модель не считает ничего.

ЗАЧЕМ ПЕРЕВОД. Камера отдаёт jpeg (`sensor_msgs/CompressedImage`), а DOSOD в
обычном режиме принимает `sensor_msgs/Image` с кодировкой bgr8 или nv12 —
сжатый кадр он не разберёт. Так что переходник понадобился бы и без затвора;
затвор достался бесплатно.

    камера → /image (jpeg) → [мы] → /robot_ai/look_image (bgr8) → DOSOD

Запрос приходит пустым сообщением в /robot_ai/look. Пустым, потому что
единственное, что нужно сказать, — «посмотри сейчас».

ВТОРАЯ ОБЯЗАННОСТЬ: РАЗДАЧА КАРТИНКИ В ПУЛЬТ. Досталась почти бесплатно и
завелась по живой беде.

Раздачей занимался web_video_server из чужой сборки. Он работает, но у службы
своё окружение, чужой слой в нём не подключён, и `ros2 run` падал с «package
not found» — молча, из-за &. Со стороны это семь часов выглядело как «камера
не работает»: детектор в те же секунды исправно вёл людей на тридцати кадрах,
а пульт писал «Connection refused» на 8080.

Раздать кадр отсюда — двадцать строк, потому что мы УЖЕ подписаны на /image, а
там лежит готовый jpeg. Никакого сжатия и разжатия: MJPEG — это те же байты
плюс разделитель между кадрами. Зависимость от чужого слоя сборки при этом
исчезает совсем, а с ней и целый способ сломаться молча.

Адрес нарочно тот же, что был у web_video_server:

    http://127.0.0.1:8080/stream?topic=/image

Менять ничего не надо ни в пульте, ни в настройках. А если настоящий
web_video_server всё-таки поднялся и порт занял — мы отходим в сторону и
говорим об этом в журнал: два раздатчика на одном порту не нужны.
"""

import errno
import os
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

try:
    import rclpy
    from rclpy.node import Node
    from rclpy.qos import qos_profile_sensor_data
    from sensor_msgs.msg import CompressedImage, Image
    from std_msgs.msg import Empty
except ImportError as e:                    # pragma: no cover — только на плате
    print(f"Нет ROS: {e}. Запускать это надо после source /opt/tros/*/setup.bash",
          file=sys.stderr)
    raise SystemExit(1)

ПОРТ_РАЗДАЧИ = int(os.environ.get("ROBOT_STREAM_PORT", "8080"))
# Сколько ждать нового кадра, прежде чем решить, что камера встала. Две
# секунды: камера идёт тридцать кадров в секунду, и две секунды тишины — это
# уже не заминка.
ЖДЁМ_КАДРА = 2.0

КАМЕРА = "/image"
ЗАПРОС = "/robot_ai/look"
# ТОТ ЖЕ ЗАПРОС, НО НА ОДИН КАДР. Отдельным топиком, а не полем в сообщении:
# сообщение здесь пустое нарочно, и заводить в нём поле значило бы менять
# формат ради одного бита.
#
# Зачем понадобился. Три кадра на запрос — верное число для ОБХОДА: робот
# встал, попросил один раз, и второй попытки у него не будет. Для СЛЕЖЕНИЯ
# всё наоборот: просят постоянно, и каждый лишний кадр — это 130 мс BPU,
# отнятые у детектора людей, на котором держатся следование, сторож падений
# и остановка по ладони. Втрое дороже там, где просят втрое чаще.
ЗАПРОС_ОДИН = "/robot_ai/look_once"
КАДР = "/robot_ai/look_image"

# Сколько кадров отдать на один запрос. Три, а не один: камера могла как раз
# моргнуть, робот мог качнуться на повороте, а второй попытки человек не
# делает — он спросил один раз. Три кадра стоят четырёх десятых секунды BPU.
КАДРОВ_НА_ЗАПРОС = 3

# Как часто спрашивать у ROS, кто публикует в /image, пока публикатора нет.
ИЩЕМ_КАМЕРУ_РАЗ_В = 0.5
# Сколько ждать камеру, прежде чем подписаться вслепую и сказать об этом
# громко. Пятнадцать секунд: узлы камеры и кодека поднимаются вместе с нами,
# и первые секунды топика может не быть просто потому, что мы стартовали
# быстрее.
ЖДЁМ_КАМЕРУ = 15.0
# Как часто жаловаться в журнал, что кадров нет. Раз в минуту: чаще — и
# журнал заплывёт, реже — и человек успеет решить, что «камера не работает»,
# так и не увидев ни строчки о причине.
ЖАЛУЕМСЯ_РАЗ_В = 60.0

# ТИПЫ, КОТОРЫЕ МЫ УМЕЕМ ЧИТАТЬ С КАМЕРЫ.
#
# Их два, и это не запас на будущее, а живая беда. hobot_usb_cam публикует в
# /image либо сжатый jpeg (sensor_msgs/CompressedImage), либо сырой кадр
# (sensor_msgs/Image) — в зависимости от pixel_format, который задаётся не у
# нас, а в их файле запуска, и может поменяться от обновления их пакета.
#
# Подписка с НЕВЕРНЫМ типом не ошибка и не исключение: ROS просто не свяжет
# её ни с одним публикатором, и обработчик не вызовется НИ РАЗУ. Снаружи это
# выглядит идеально: узел жив, порт занят, `ros2 topic hz /image` показывает
# тридцать кадров — а в пульте пусто. Единственный след — `ros2 topic echo`
# ворчит, что на топике «больше одного типа»: это мы сами и есть, со своей
# несвязанной подпиской.
#
# Поэтому тип не угадываем, а СПРАШИВАЕМ у ROS: get_publishers_info_by_topic
# говорит, что там на самом деле течёт.
СЖАТЫЙ = "sensor_msgs/msg/CompressedImage"
СЫРОЙ = "sensor_msgs/msg/Image"


def _разжать(данные):
    """jpeg → массив bgr8. None — разжать нечем.

    cv2 приходит вместе с cv_bridge, то есть он на плате есть почти наверняка.
    Но «почти» здесь мало: без запасного пути отсутствие одной библиотеки
    молча превратило бы поиск вещей в вечное «ничего не вижу».
    """
    try:
        import cv2
        import numpy as np
        кадр = cv2.imdecode(np.frombuffer(данные, dtype=np.uint8),
                            cv2.IMREAD_COLOR)
        return кадр if кадр is not None else None
    except ImportError:
        pass
    try:
        import io

        import numpy as np
        from PIL import Image as PILImage
        картинка = PILImage.open(io.BytesIO(данные)).convert("RGB")
        # PIL отдаёт RGB, а DOSOD ждёт bgr8. Перепутать порядок каналов —
        # значит кормить модель синими людьми и удивляться, что она молчит.
        return np.asarray(картинка)[:, :, ::-1].copy()
    except ImportError:
        return None


def _в_bgr(сообщение):
    """Сырой кадр (sensor_msgs/Image) → массив bgr8. None — не осилили.

    Кодировок у камеры может быть несколько, и молчаливо принять чужую за
    свою нельзя: перепутанные каналы — это не «чуть другой цвет», а синие
    люди на входе сети, которая после этого не находит ничего и не жалуется.
    """
    try:
        import numpy as np
    except ImportError:
        return None
    кодировка = (getattr(сообщение, "encoding", "") or "").lower()
    высота = int(getattr(сообщение, "height", 0))
    ширина = int(getattr(сообщение, "width", 0))
    данные = bytes(сообщение.data)
    if not высота or not ширина or not данные:
        return None
    if кодировка in ("bgr8", "rgb8"):
        кадр = np.frombuffer(данные, dtype=np.uint8)[:высота * ширина * 3]
        кадр = кадр.reshape(высота, ширина, 3)
        return кадр if кодировка == "bgr8" else кадр[:, :, ::-1].copy()
    if кодировка == "mono8":
        серый = np.frombuffer(данные, dtype=np.uint8)[:высота * ширина]
        return np.repeat(серый.reshape(высота, ширина, 1), 3, axis=2)
    # nv12 — родной формат платы, и без cv2 его не развернуть руками дёшево.
    if кодировка in ("nv12", "yuv420sp"):
        try:
            import cv2
        except ImportError:
            return None
        сырое = np.frombuffer(данные, dtype=np.uint8)
        нужно = высота * ширина * 3 // 2
        if сырое.size < нужно:
            return None
        return cv2.cvtColor(сырое[:нужно].reshape(высота * 3 // 2, ширина),
                            cv2.COLOR_YUV2BGR_NV12)
    return None


def _в_jpeg(кадр):
    """Массив bgr8 → байты jpeg. None — сжать нечем."""
    try:
        import cv2
        вышло, буфер = cv2.imencode(".jpg", кадр)
        return bytes(буфер) if вышло else None
    except ImportError:
        pass
    try:
        import io

        from PIL import Image as PILImage
        память = io.BytesIO()
        PILImage.fromarray(кадр[:, :, ::-1]).save(память, format="JPEG")
        return память.getvalue()
    except ImportError:
        return None


class Затвор(Node):

    def __init__(self) -> None:
        super().__init__("robot_ai_look_relay")
        self._последний = None
        self._jpeg = None
        self._сырой = None
        self._когда_кадр = 0.0
        self._замок = threading.Lock()
        self._осталось = 0
        self._жаловались = False
        self._тип = None
        self._подписка = None
        self._встали = time.monotonic()
        self._ныли = 0.0
        self.create_subscription(Empty, ЗАПРОС, self._просят, 1)
        self.create_subscription(Empty, ЗАПРОС_ОДИН, self._просят_разок, 1)
        self._выход = self.create_publisher(Image, КАДР, 1)
        self.get_logger().info(
            f"затвор: жду запрос в {ЗАПРОС} ({КАДРОВ_НА_ЗАПРОС} кадра) "
            f"и в {ЗАПРОС_ОДИН} (один), кадр отдам в {КАДР}")
        # Подписываемся не сразу, а когда узнаем тип: см. СЖАТЫЙ/СЫРОЙ выше.
        self._поиск = self.create_timer(ИЩЕМ_КАМЕРУ_РАЗ_В, self._искать_камеру)
        self._сторож = self.create_timer(ЖАЛУЕМСЯ_РАЗ_В, self._как_там_камера)

    # ── откуда берём кадры ────────────────────────────────────────────────

    def _типы_на_камере(self):
        """Какие типы сообщений реально публикуются в /image."""
        спросить = getattr(self, "get_publishers_info_by_topic", None)
        if спросить is None:                # pragma: no cover — древний rclpy
            return []
        try:
            return [и.topic_type for и in спросить(КАМЕРА)]
        except Exception:                   # pragma: no cover — гонка при старте
            return []

    def _искать_камеру(self) -> None:
        типы = [т for т in self._типы_на_камере() if т in (СЖАТЫЙ, СЫРОЙ)]
        if not типы:
            if time.monotonic() - self._встали < ЖДЁМ_КАМЕРУ:
                return
            # Камеры так и нет. Подписываемся на сжатый — он у нас обычный, —
            # но говорим об этом громко: молчание здесь и есть та самая беда,
            # когда «камера не работает» без единой строчки в журнале.
            чужие = self._типы_на_камере()
            self.get_logger().warning(
                f"{КАМЕРА}: за {ЖДЁМ_КАМЕРУ:.0f} с публикатора не видно"
                + (f" (есть чужие типы: {', '.join(sorted(set(чужие)))})"
                   if чужие else "")
                + ". Подписываюсь на сжатый вслепую. "
                  "Проверь hobot_usb_cam в journalctl -u robot-body")
            self._подписаться(СЖАТЫЙ)
            return
        # Если камера почему-то отдаёт оба типа сразу — берём сжатый: его же
        # ждёт кодек (codec_sub_topic=/image), значит он и есть настоящий.
        self._подписаться(СЖАТЫЙ if СЖАТЫЙ in типы else типы[0])

    def _подписаться(self, тип: str) -> None:
        if self._подписка is not None:
            return
        self._тип = тип
        сжатый = тип == СЖАТЫЙ
        # НАДЁЖНОСТЬ БЕРЁМ КАК У ДАТЧИКА, а не по умолчанию, и это второй
        # способ не получить ни одного кадра при живой камере. Камеры почти
        # всегда публикуют best_effort; подписка по умолчанию просит reliable,
        # а reliable-подписка с best_effort-публикатором НЕ СВЯЗЫВАЕТСЯ —
        # молча, без ошибки. Обратная сторона совместима: best_effort-подписка
        # спокойно читает и reliable-публикатора, так что этот выбор безопасен
        # в обе стороны.
        self._подписка = self.create_subscription(
            CompressedImage if сжатый else Image, КАМЕРА,
            self._кадр if сжатый else self._кадр_сырой,
            qos_profile_sensor_data)
        self.get_logger().info(
            f"камера: подписался на {КАМЕРА}, тип {тип.split('/')[-1]}")
        if self._поиск is not None:
            self._поиск.cancel()
            self._поиск = None

    def _как_там_камера(self) -> None:
        """Раз в минуту сказать в журнал, если кадров нет. Молчать нельзя.

        Пустой пульт без единой строчки в журнале — это часы поисков там, где
        одна строка называет причину.
        """
        if self.последний_jpeg() is not None:
            return
        сейчас = time.monotonic()
        if сейчас - self._встали < ЖДЁМ_КАМЕРУ or \
                сейчас - self._ныли < ЖАЛУЕМСЯ_РАЗ_В:
            return
        self._ныли = сейчас
        типы = sorted(set(self._типы_на_камере()))
        self.get_logger().warning(
            f"камера: кадров нет уже {сейчас - self._встали:.0f} с. "
            f"Подписан на {self._тип or 'ничего'}, "
            f"в {КАМЕРА} публикуют: {', '.join(типы) if типы else 'никто'}")

    def последний_jpeg(self):
        """Последний кадр с камеры как есть, сжатым. None — камера молчит.

        Свежесть проверяем ЗДЕСЬ, а не у того, кто спрашивает: раздача не
        должна показывать в пульте картинку двухминутной давности как живую.
        Застывший кадр хуже пустого экрана — по нему принимают решения.
        """
        with self._замок:
            кадр, сырой, когда = self._jpeg, self._сырой, self._когда_кадр
        if когда == 0.0 or time.monotonic() - когда > ЖДЁМ_КАДРА:
            return None
        if кадр is not None:
            return кадр
        if сырой is None:
            return None
        # Камера отдаёт сырые кадры — сжимаем ЗДЕСЬ, по запросу пульта, а не
        # тридцать раз в секунду впустую. Тот же принцип, что и с разжатием.
        массив = _в_bgr(сырой)
        кадр = _в_jpeg(массив) if массив is not None else None
        if кадр is None:
            self._не_осилили(
                f"нечем сжать кадр {getattr(сырой, 'encoding', '?')} в jpeg: "
                "нет ни cv2, ни PIL. Пульт останется без картинки")
            return None
        with self._замок:
            if self._сырой is сырой:
                self._jpeg = кадр
        return кадр

    def _не_осилили(self, что: str) -> None:
        """Сказать один раз. Повторять тридцать раз в секунду незачем."""
        if not self._жаловались:
            self._жаловались = True
            self.get_logger().error(что)

    def _кадр(self, сообщение) -> None:
        # Храним СЖАТЫЙ кадр и не разжимаем ничего, пока не попросят: разжимать
        # тридцать кадров в секунду впустую — это тот же расход, от которого мы
        # и уходим, только на процессоре вместо BPU.
        self._последний = сообщение
        # Копию для раздачи держим отдельно и под замком: её читает поток
        # HTTP-сервера, а этот метод зовёт поток ROS.
        with self._замок:
            self._jpeg = bytes(сообщение.data)
            self._сырой = None
            self._когда_кадр = time.monotonic()
        if self._осталось > 0:
            self._осталось -= 1
            self._отдать(сообщение)

    def _кадр_сырой(self, сообщение) -> None:
        # То же самое, но кадр пришёл несжатым. Сжатия здесь нет нарочно:
        # см. последний_jpeg().
        self._последний = сообщение
        with self._замок:
            self._сырой = сообщение
            self._jpeg = None
            self._когда_кадр = time.monotonic()
        if self._осталось > 0:
            self._осталось -= 1
            self._отдать(сообщение)

    def _просят_разок(self, _сообщение) -> None:
        """Один кадр. Для слежения, где просят постоянно.

        Счётчик не обнуляем, а поднимаем до единицы: если прямо сейчас
        доигрывается тройка от обхода, отнимать у него кадры незачем — он
        просил их не зря.
        """
        self._отдать_сколько(1)

    def _просят(self, _сообщение) -> None:
        self._отдать_сколько(КАДРОВ_НА_ЗАПРОС)

    def _отдать_сколько(self, кадров: int) -> None:
        self._осталось = max(self._осталось, кадров)
        # Первый кадр отдаём сразу из запаса, не дожидаясь следующего с
        # камеры: между кадрами тридцатая доля секунды, но если камера как раз
        # встала, ждать пришлось бы вечно и молча.
        if self._последний is not None:
            self._осталось -= 1
            self._отдать(self._последний)

    def _отдать(self, пришло) -> None:
        # Кадр от камеры уже сырой и уже в том виде, который сеть понимает, —
        # отдаём как есть, без круга «разжать и собрать заново».
        if self._тип == СЫРОЙ:
            кодировка = (getattr(пришло, "encoding", "") or "").lower()
            if кодировка in ("bgr8", "nv12"):
                self._выход.publish(пришло)
                return
            кадр = _в_bgr(пришло)
        else:
            кадр = _разжать(bytes(пришло.data))
        if кадр is None:
            self._не_осилили(
                "нечем подготовить кадр для сети: нет ни cv2, ни PIL "
                f"(или незнакомая кодировка {getattr(пришло, 'encoding', '')}). "
                "Поиск вещей работать не будет")
            return
        высота, ширина = кадр.shape[:2]
        сообщение = Image()
        сообщение.header = пришло.header
        сообщение.height = высота
        сообщение.width = ширина
        сообщение.encoding = "bgr8"
        сообщение.is_bigendian = 0
        сообщение.step = ширина * 3
        сообщение.data = кадр.tobytes()
        self._выход.publish(сообщение)


class _Раздача(BaseHTTPRequestHandler):
    """MJPEG наружу. Кадр берётся из узла как есть, сжатым.

    Отдаём ровно те байты, что пришли с камеры. Разжимать и сжимать обратно —
    это тратить процессор на то, чтобы получить тот же jpeg, только хуже.
    """

    узел = None                      # ставится при запуске
    protocol_version = "HTTP/1.0"

    def log_message(self, формат, *аргументы):
        # Молчим: иначе каждый кадр уходит строкой в журнал службы, а их
        # тридцать в секунду.
        pass

    def _кадр_или_ошибка(self):
        кадр = self.узел.последний_jpeg() if self.узел else None
        if кадр is None:
            self.send_response(503)
            self.send_header("Content-Type", "text/plain; charset=utf-8")
            self.end_headers()
            self.wfile.write(
                "Кадра нет: камера молчит дольше двух секунд.\n"
                "Смотри journalctl -u robot-body — жив ли hobot_usb_cam."
                .encode())
            return None
        return кадр

    def do_GET(self):                # noqa: N802 — имя задано базовым классом
        путь = self.path.split("?", 1)[0].rstrip("/")
        if путь in ("/snapshot", "/image"):
            кадр = self._кадр_или_ошибка()
            if кадр is None:
                return
            self.send_response(200)
            self.send_header("Content-Type", "image/jpeg")
            self.send_header("Content-Length", str(len(кадр)))
            self.end_headers()
            self.wfile.write(кадр)
            return
        if путь not in ("/stream", ""):
            self.send_response(404)
            self.end_headers()
            return
        # Поток. Заголовок тот же, что у web_video_server, чтобы пульт и
        # браузер не заметили подмены.
        if self._кадр_или_ошибка() is None:
            return
        self.send_response(200)
        self.send_header("Content-Type",
                         "multipart/x-mixed-replace; boundary=frame")
        self.send_header("Cache-Control", "no-cache")
        self.end_headers()
        try:
            while True:
                кадр = self.узел.последний_jpeg() if self.узел else None
                if кадр is None:
                    return
                self.wfile.write(b"--frame\r\n")
                self.wfile.write(b"Content-Type: image/jpeg\r\n")
                self.wfile.write(
                    f"Content-Length: {len(кадр)}\r\n\r\n".encode())
                self.wfile.write(кадр)
                self.wfile.write(b"\r\n")
                # Тридцать кадров в секунду отдавать незачем: пульт смотрят
                # глазами, а каждый лишний кадр — это байты по вайфаю.
                time.sleep(1 / 15)
        except (BrokenPipeError, ConnectionResetError):
            # Пульт закрыли — обычное дело, а не беда.
            return


def поднять_раздачу(узел, порт: int = ПОРТ_РАЗДАЧИ):
    """Запустить HTTP-раздачу. Отдаёт сервер или None, если порт занят.

    Занятый порт — не ошибка: значит настоящий web_video_server всё-таки
    поднялся, и два раздатчика на одном порту не нужны. Отходим в сторону и
    говорим об этом.
    """
    _Раздача.узел = узел
    try:
        сервер = ThreadingHTTPServer(("0.0.0.0", порт), _Раздача)
    except OSError as e:
        if e.errno == errno.EADDRINUSE:
            узел.get_logger().info(
                f"порт {порт} уже занят — раздаёт кто-то другой, не мешаю")
        else:
            узел.get_logger().warning(f"раздача не поднялась: {e}")
        return None
    сервер.daemon_threads = True
    threading.Thread(target=сервер.serve_forever, daemon=True).start()
    узел.get_logger().info(
        f"раздаю картинку: http://127.0.0.1:{порт}/stream?topic=/image")
    return сервер


def main() -> None:
    rclpy.init()
    узел = Затвор()
    поднять_раздачу(узел)
    try:
        rclpy.spin(узел)
    except KeyboardInterrupt:
        pass
    finally:
        узел.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
