#!/usr/bin/env python3
"""Словарь классов для DOSOD — из одного списка робота, а не руками.

ЧТО ЭТО И ЗАЧЕМ. Сеть узнавания DOSOD открытословарная: набор классов у неё не
зашит намертво, а задаётся списком слов. Слова прогоняют через текстовый
кодировщик, эмбеддинги впекают в веса модели, и дальше на роботе она ищет
ровно то, что ей назвали. Восемьдесят классов COCO, с которыми она приезжает,
— это комплектация, а не предел.

Комплектация нам не годится дважды: в ней нет ШКАФА, ДВЕРИ, БАТАРЕИ,
ТУМБОЧКИ, ПОЛКИ, СТИРАЛЬНОЙ МАШИНЫ — то есть половины квартиры, — зато есть
жирафы, зебры и сёрфборды, которых дома не будет никогда, а решать про них
сеть обязана каждый кадр.

Этот скрипт делает первый шаг переучивания: пишет json со списком слов. Слова
берутся из voice/robot_voice/vocabulary.py — того самого списка, по которому
робот их потом называет по-русски, кладёт на карту и считает мебелью. Держать
рядом две копии списка нельзя: ПОРЯДОК СЛОВ — ЭТО НОМЕРА КЛАССОВ, и разъехавшись
на одну строку, они превратят стул в холодильник молча, без единой ошибки.

ЧЕГО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ. Он не переучивает модель — он готовит вход.
Остальные шаги идут на ПК (нужен torch и CLIP) и в тулчейне Horizon:

  1. этот скрипт                     -> vocabulary_kuzya.json
  2. tools/generate_text_prompts_dosod.py   -> .npy с эмбеддингами
  3. tools/reparameterize_dosod.py          -> .pth с впечёнными классами
  4. deploy/export_onnx.py                  -> .onnx
  5. тулчейн X5 (docker OpenExplorer)       -> .bin для BPU

Команды — в docs/vocabulary.md. Прогон разовый; на роботе после него меняется
только файл модели.

ЦЕНА ПО СКОРОСТИ — НОЛЬ, и это стоит сказать, потому что звучит слишком
хорошо. Буква D в DOSOD — decoupled: текстовая ветка отделена от картиночной и
считается заранее, на ПК. На роботе от размера словаря меняется только
последнее перемножение с матрицей классов, а восемьдесят классов там или сто —
не разница даже в миллисекунду.

    python3 scripts/make_vocabulary.py [--out ФАЙЛ] [--показать]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "voice"))

from robot_voice import vocabulary  # noqa: E402


def собрать() -> list[str]:
    return vocabulary.для_сети()


def главное(аргв=None) -> int:
    разбор = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    разбор.add_argument("--out", default="vocabulary_kuzya.json",
                        help="куда положить json со списком слов")
    разбор.add_argument("--показать", action="store_true",
                        help="просто перечислить классы и выйти")
    дано = разбор.parse_args(аргв)

    слова = собрать()
    if дано.показать:
        свои = {в.класс for в in vocabulary.ВСЁ if в.откуда == "наш"}
        for н, слово in enumerate(слова):
            метка = "новый" if слово in свои else "coco "
            по_русски = vocabulary.назвать(слово) if hasattr(
                vocabulary, "назвать") else vocabulary.ПО_РУССКИ[слово][0]
            print(f"{н:3d}  {метка}  {слово:18} {по_русски}")
        print(f"\nвсего {len(слова)}, из них новых {len(свои)}")
        return 0

    # Формат — тот же, что у них в data/texts/offline_vocabulary.json: список
    # списков, по одному синониму на класс. Синонимы русские сюда не идут:
    # текстовый кодировщик у DOSOD английский (CLIP), и «шкаф» он не знает.
    куда = Path(дано.out)
    куда.write_text(json.dumps([[с] for с in слова], ensure_ascii=False,
                               indent=1))
    print(f"словарь на {len(слова)} классов записан в {куда}")
    print("дальше — шаги 2-5 из docs/vocabulary.md, на ПК")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
