#!/usr/bin/env bash
# Ставит определитель конца реплики: onnxruntime и модель Smart Turn.
#
# Зачем он нужен. Робот сейчас понимает, что человек договорил, по тишине:
# полтысячи миллисекунд молчания — значит всё. В тихой комнате это работает,
# а в квартире с ребёнком или телевизором тишины не наступает вовсе, и запись
# каждый раз доезжает до потолка окна. В журнале ПК это видно как «на 5.0 с
# звука» подряд: человек сказал «Кузя, сколько времени» за две секунды и ждёт
# ещё три, пока робот молча пишет комнату, уже всё расслышав.
#
# Модель слушает саму реплику — интонацию, темп, грамматику — и слышит конец
# ДО паузы. Восемь миллионов параметров, восемь мегабайт, десятки миллисекунд
# на ядро A55. Русский она поддерживает.
#
# Обрывать запись раньше прежних правил она может, позже — нет. Значит худший
# случай равен сегодняшнему поведению, и включать её не страшно.
#
#     bash scripts/setup_turn_end.sh
#
# После установки скрипт напечатает строку для ~/.robot-ai.env.

set -euo pipefail

VOICE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/voice"
VENV_PY="$VOICE_DIR/.venv/bin/python"
MODEL_DIR="$HOME/smart-turn"

# Репозиторий модели.
REPO="pipecat-ai/smart-turn-v3"

# Имя файла НЕ вшито намеренно, и это не перестраховка — на этом уже
# споткнулись. В репозитории лежит несколько сборок сразу, имена меняются от
# версии к версии (smart-turn-v3.0.onnx, потом smart-turn-v3.1-cpu.onnx,
# рядом gpu-вариант вчетверо тяжелее), и угаданное имя дало ровно то, что и
# должно было: 404 и скрипт, который «не работает».
#
# Поэтому список файлов спрашиваем у самого репозитория и выбираем из него.
# Нам нужна сборка под ПРОЦЕССОР: видеокарты у робота нет, а gpu-файл вчетверо
# больше и считает на A55 медленнее — то есть выбрать не тот файл значит
# получить замедление там, где мы боролись за миллисекунды.
API="https://huggingface.co/api/models/$REPO"

if [ ! -x "$VENV_PY" ]; then
    echo "Нет $VENV_PY — сначала scripts/install.sh" >&2
    exit 1
fi

echo "== onnxruntime"
# Считает на CPU, видеокарты у робота нет и не будет. Колесо под aarch64 есть.
"$VENV_PY" -m pip install --quiet --upgrade onnxruntime

echo "== какие сборки есть в репозитории"
mkdir -p "$MODEL_DIR"

PICK="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/pick_turn_model.py"
LIST_FILE="$(mktemp)"
trap 'rm -f "$LIST_FILE"' EXIT

# Сперва в ФАЙЛ, потом разбор. Не через конвейер, и это не вкусовщина: программу
# питону раньше скармливали heredoc'ом, а данные конвейером — оба идут в stdin,
# heredoc побеждает, и разбор молча читал пустоту. Скрипт не падал, а честно
# печатал «не удалось спросить список», и человек шёл проверять сеть, которая
# была ни при чём.
NAME=""
if curl -fsSL --retry 3 --retry-delay 2 -o "$LIST_FILE" "$API"; then
    NAME="$("$VENV_PY" "$PICK" "$LIST_FILE")" || NAME=""
else
    echo "  репозиторий не ответил ($API)" >&2
fi

if [ -z "$NAME" ]; then
    # Список не дался — не сдаёмся. Сеть может пускать к файлам и не пускать
    # к API, а имена сборок мы знаем. Пробуем известные по очереди: это ровно
    # то, что человек сделал бы руками, и незачем заставлять его это делать.
    echo "  список не дался — пробую известные имена" >&2
    for CANDIDATE in smart-turn-v3.1-cpu.onnx smart-turn-v3.0.onnx; do
        if curl -fsIL "https://huggingface.co/$REPO/resolve/main/$CANDIDATE" \
                >/dev/null 2>&1; then
            NAME="$CANDIDATE"
            break
        fi
    done
fi

if [ -z "$NAME" ]; then
    echo "" >&2
    echo "Ни список, ни известные имена не дались." >&2
    echo "Скачай .onnx руками отсюда: https://huggingface.co/$REPO/tree/main" >&2
    echo "(нужна сборка со словом cpu в имени, около 9 МБ)" >&2
    echo "и положи в $MODEL_DIR, потом укажи путь в ROBOT_TURN_MODEL." >&2
    exit 1
fi
echo "  беру: $NAME"

MODEL_FILE="$MODEL_DIR/$NAME"
if [ -s "$MODEL_FILE" ]; then
    echo "уже скачано: $MODEL_FILE"
else
    # Скачиваем напрямую, без huggingface_hub: одна библиотека ради одного
    # файла — это сотня мегабайт зависимостей на плату, где и так тесно.
    URL="https://huggingface.co/$REPO/resolve/main/$NAME?download=true"
    echo "качаю $URL"
    if ! curl -fL --retry 3 --retry-delay 2 -o "$MODEL_FILE.tmp" "$URL"; then
        echo "" >&2
        echo "Не скачалось. Скачай файл руками и положи сюда:" >&2
        echo "    $MODEL_FILE" >&2
        echo "Взять здесь: https://huggingface.co/$REPO/tree/main" >&2
        rm -f "$MODEL_FILE.tmp"
        exit 1
    fi
    mv "$MODEL_FILE.tmp" "$MODEL_FILE"
fi

echo "== проверка"
# Проверяем ДО того, как советовать включать: файл мог скачаться битым или
# оказаться страницей с ошибкой вместо модели, и узнать об этом лучше здесь,
# чем из молчащего робота.
"$VENV_PY" - "$MODEL_FILE" <<'PY'
import sys
from pathlib import Path

import onnxruntime as ort

путь = Path(sys.argv[1])
размер = путь.stat().st_size / 1024 / 1024
# Проверяем ДО того, как советовать включать. Скачаться могла страница с
# ошибкой вместо модели — она весит килобайты и открывается с невнятным
# сообщением; узнать об этом здесь честнее, чем из молчащего робота.
сессия = ort.InferenceSession(str(путь), providers=["CPUExecutionProvider"])
вход = сессия.get_inputs()[0]
выход = сессия.get_outputs()[0]
print(f"  размер: {размер:.1f} МБ")
print(f"  вход:  {вход.name} {вход.shape}")
print(f"  выход: {выход.name} {выход.shape}")
# По имени выхода робот сам решит, вероятность ему отдают или логит. Если имя
# невнятное — скажем об этом сейчас, пока человек ещё смотрит в экран, а не
# через неделю по строчке «оборвали 0» в журнале.
имя = выход.name.lower()
if not any(с in имя for с in ("prob", "sigmoid", "logit")):
    print(f"  ВНИМАНИЕ: по имени выхода «{выход.name}» не понять, вероятность")
    print("  это или логит. Робот пойдёт безопасной дорогой (посчитает как")
    print("  логит). Если в журнале будет «оборвали 0» — добавь в env:")
    print("      ROBOT_TURN_OUTPUT=вероятность")
PY

echo
echo "Готово. Добавь в ~/.robot-ai.env:"
echo
echo "    ROBOT_TURN_MODEL=$MODEL_FILE"
echo
echo "и перезапусти:  sudo systemctl restart robot-voice"
echo
echo "В журнале появится строка «конец реплики: … отвечает …»."
echo "Если она говорит «непонятно чем», а дальше в журнале «спросили много,"
echo "оборвали 0» — добавь ещё ROBOT_TURN_OUTPUT=вероятность."
