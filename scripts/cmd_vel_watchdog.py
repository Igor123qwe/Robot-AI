#!/usr/bin/env python3
"""Сторож мёртвой руки: колёса встают, если тот, кто их крутил, замолчал.

ЗАЧЕМ. Драйвер шасси WHEELTEC не тормозит сам. Это проверено по исходнику
turn_on_wheeltec_robot/src/wheeltec_robot.cpp: Cmd_Vel_Callback() пакует
пришедший Twist в кадр для STM32 и пишет в серийный порт — и всё. Ни таймера,
ни отметки времени последней команды, ни повторной посылки нуля. Единственное
место, где скорость обнуляется, — деструктор узла, а деструктор при kill -9,
segfault или отключении питания платы не вызывается никогда.

Значит буквально: ПОСЛЕДНЯЯ ОТПРАВЛЕННАЯ СКОРОСТЬ ДЕЙСТВУЕТ, ПОКА НЕ ПРИДЁТ
СЛЕДУЮЩАЯ. Робот, у которого посреди поездки упал голосовой сервис, порвалось
соединение с rosbridge или кончилась память, продолжает ехать. Не «доезжает по
инерции» — едет, пока не упрётся или не сядет батарея.

В нашем коде до сегодняшнего дня стояло обратное утверждение: «шасси при
паузе само тормозит, поэтому команду повторяем 15 раз в секунду». Повторять
всё равно надо — но не по этой причине, и утверждение было опасно неверным.

ЧТО ДЕЛАЕТ ЭТОТ СЛУЖЕБНЫЙ ПРОЦЕСС. Смотрит в /cmd_vel и, если последняя
увиденная команда была ненулевой, а после неё наступила тишина дольше
ТИШИНА_ДО_СТОПА, — сам публикует нули. Тот, кто крутил колёса, замолчал:
умер, оторвался, завис. Колёса встают.

ПОЧЕМУ ОТДЕЛЬНЫМ ПРОЦЕССОМ, А НЕ ПОТОКОМ ВНУТРИ РОБОТА. Потому что защищаем
мы как раз от смерти того процесса. Сторож, живущий внутри охраняемого,
умирает вместе с ним и охраняет ровно ничего.

ЧЕГО ОН НЕ МОЖЕТ. Если умер сам rosbridge или отвалился USB шасси, публиковать
некуда, и робота не остановит никто. От этого спасает только watchdog в
прошивке STM32 или физическая кнопка, разрывающая питание драйверов моторов.
Этот сторож — средний слой, а не единственный, и врать про него не надо.

Запуск:  python3 scripts/cmd_vel_watchdog.py [ws://127.0.0.1:9090]
"""

from __future__ import annotations

import json
import logging
import os
import sys
import threading
import time

import websocket

log = logging.getLogger("сторож")

ТОПИК = "/cmd_vel"

# Сколько тишины после ненулевой команды считаем смертью издателя.
#
# Полсекунды. Все наши источники движения публикуют пятнадцать раз в секунду,
# то есть каждые 66 мс; полсекунды — это семь пропущенных подряд. Меньше
# ставить нельзя: разовая заминка планировщика на нагруженной плате даст
# ложный стоп посреди поездки. Больше — это лишние сантиметры хода мёртвого
# робота, а на 0.55 м/с полсекунды и так уже двадцать семь сантиметров.
ТИШИНА_ДО_СТОПА = float(os.getenv("ROBOT_DEADMAN_TIMEOUT", "0.5"))

# Как часто просыпаемся и смотрим на часы.
ШАГ = 0.05

# Сколько нулей послать. Три — как и везде в этом проекте: пакет может
# потеряться, а второй попытки у нас не будет.
НУЛЕЙ = 3

# Скорость ниже этой считается нулём.
ПОЧТИ_НОЛЬ = 1e-3


class Сторож:
    def __init__(self, url: str) -> None:
        self.url = url
        self._ws: websocket.WebSocketApp | None = None
        self._замок = threading.Lock()
        # Когда в последний раз видели ненулевую команду. Ноль — значит после
        # неё уже пришёл ноль, и сторожить нечего: колёса и так стоят.
        self._едет_с = 0.0
        self._жив = True
        self._остановок = 0

    # --- связь ----------------------------------------------------------
    def работать(self) -> None:
        while self._жив:
            try:
                self._ws = websocket.WebSocketApp(
                    self.url,
                    on_open=self._открылось,
                    on_message=self._сообщение,
                    on_close=lambda *_a: log.warning("связь с rosbridge закрыта"),
                )
                self._ws.run_forever(ping_interval=20, ping_timeout=10)
            except Exception:                   # noqa: BLE001
                log.exception("сбой соединения")
            # Связи нет — сторожить нечем. Забываем, что робот ехал: когда
            # связь вернётся, мы всё равно не знаем, что происходило без нас,
            # а слать нули «за прошлое» бессмысленно — они и так уйдут при
            # первой же новой команде с последующей тишиной.
            with self._замок:
                self._едет_с = 0.0
            if self._жив:
                time.sleep(2)

    def _открылось(self, ws) -> None:
        log.info("подключён к %s, сторожу %s (тишина до стопа %.2f с)",
                 self.url, ТОПИК, ТИШИНА_ДО_СТОПА)
        self._послать({"op": "advertise", "topic": ТОПИК,
                       "type": "geometry_msgs/msg/Twist"})
        # Без throttle: пропущенная ненулевая команда — это лишние полсекунды
        # хода, а разбор трёх десятков json в секунду не стоит ничего.
        self._послать({"op": "subscribe", "topic": ТОПИК,
                       "type": "geometry_msgs/msg/Twist"})

    def _послать(self, что: dict) -> bool:
        ws = self._ws
        if ws is None:
            return False
        try:
            ws.send(json.dumps(что))
        except Exception:                       # noqa: BLE001
            log.warning("не удалось отправить %s", что.get("op"))
            return False
        return True

    # --- слух -----------------------------------------------------------
    def _сообщение(self, ws, сырое: str) -> None:
        try:
            письмо = json.loads(сырое)
        except ValueError:
            return
        if письмо.get("op") != "publish" or письмо.get("topic") != ТОПИК:
            return
        try:
            тело = письмо["msg"]
            скорость = (abs(тело["linear"]["x"]) + abs(тело["linear"]["y"])
                        + abs(тело["angular"]["z"]))
        except (KeyError, TypeError):
            return
        with self._замок:
            # Ноль — значит колёса уже остановлены кем-то. Сторожить нечего до
            # следующей ненулевой команды. Считаем это и про свои собственные
            # нули: они приходят обратно эхом и правильно снимают тревогу.
            self._едет_с = time.monotonic() if скорость > ПОЧТИ_НОЛЬ else 0.0

    # --- собственно сторожение -------------------------------------------
    def сторожить(self) -> None:
        while self._жив:
            time.sleep(ШАГ)
            with self._замок:
                едет_с = self._едет_с
            if not едет_с:
                continue
            тишина = time.monotonic() - едет_с
            if тишина < ТИШИНА_ДО_СТОПА:
                continue
            with self._замок:
                # Проверяем ещё раз под замком: пока считали, могла прийти
                # свежая команда, и тогда останавливать нечего.
                if self._едет_с != едет_с:
                    continue
                self._едет_с = 0.0
                self._остановок += 1
                номер = self._остановок
            log.warning("в %s тишина %.2f с после хода — останавливаю колёса "
                        "(остановка №%d)", ТОПИК, тишина, номер)
            for _ in range(НУЛЕЙ):
                self._послать({
                    "op": "publish",
                    "topic": ТОПИК,
                    "msg": {"linear": {"x": 0.0, "y": 0.0, "z": 0.0},
                            "angular": {"x": 0.0, "y": 0.0, "z": 0.0}},
                })
                time.sleep(0.02)

    def стоп(self) -> None:
        self._жив = False
        if self._ws is not None:
            self._ws.close()


def main() -> int:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    url = sys.argv[1] if len(sys.argv) > 1 else os.getenv(
        "ROBOT_ROSBRIDGE", "ws://127.0.0.1:9090")
    сторож = Сторож(url)
    threading.Thread(target=сторож.работать, daemon=True).start()
    try:
        сторож.сторожить()
    except KeyboardInterrupt:
        сторож.стоп()
    return 0


if __name__ == "__main__":
    sys.exit(main())
