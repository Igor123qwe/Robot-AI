def проверить_сторожа():
    раздел("сторож мёртвой руки")
    # Свой процесс, своя служба: он остаётся жив, даже когда голосовая служба
    # упала, и в этом весь смысл. Спрашиваем systemd, а не себя.
    try:
        import subprocess
        итог = subprocess.run(
            ["systemctl", "is-active", "robot-deadman"],
            capture_output=True, text=True, timeout=5)
        живой = итог.stdout.strip() == "active"
        сказать("сторож", "служба robot-deadman", ХОРОШО if живой else ПЛОХО,
                итог.stdout.strip() or "не отвечает")
    except Exception as e:                   # noqa: BLE001
        сказать("сторож", "служба robot-deadman", СОМНИТЕЛЬНО, str(e))


