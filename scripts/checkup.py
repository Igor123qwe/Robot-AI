ХОРОШО, ПЛОХО, СОМНИТЕЛЬНО = "ok", "ПЛОХО", "?"

ИТОГИ: list[tuple[str, str, str, str]] = []


def сказать(раздел: str, что: str, как: str, подробно: str = "") -> None:
    ИТОГИ.append((раздел, что, как, подробно))
    знак = {ХОРОШО: "  ok  ", ПЛОХО: " ПЛОХО", СОМНИТЕЛЬНО: "  ?   "}[как]
    строка = f"{знак} {что}"
    if подробно:
        строка += f"  —  {подробно}"
    print(строка, flush=True)


def раздел(имя: str) -> None:
    print(f"\n== {имя}", flush=True)


# --- связь -------------------------------------------------------------------

def взять(адрес: str, таймаут: float = 3.0):
    """GET с веб-сервера робота. None — не ответил."""
    try:
        with urllib.request.urlopen(адрес, timeout=таймаут) as ответ:
            return ответ.read()
    except Exception:                        # noqa: BLE001
        return None


class Мост:
    """Разговор с rosbridge. Только слушаем, если не просили ехать."""

    def __init__(self, адрес: str) -> None:
        import websocket
        self.связь = websocket.create_connection(адрес, timeout=5)
        self.связь.settimeout(0.5)

    def подписаться(self, топик: str, тип: str, throttle: int = 0) -> None:
        письмо = {"op": "subscribe", "topic": топик, "type": тип}
        if throttle:
            письмо["throttle_rate"] = throttle
        self.связь.send(json.dumps(письмо))

    def слушать(self, сколько: float):
        """Всё, что пришло за `сколько` секунд: список (топик, сообщение)."""
        край = time.monotonic() + сколько
        пришло = []
        while time.monotonic() < край:
            try:
                сырьё = self.связь.recv()
            except Exception:                # noqa: BLE001 — просто тишина
                continue
            try:
                письмо = json.loads(сырьё)
            except ValueError:
                continue
            if письмо.get("op") == "publish":
                пришло.append((письмо.get("topic"), письмо.get("msg") or {}))
        return пришло

    def топики(self):
        """Список топиков через сервис rosapi. Пусто — сервис не отвечает."""
        self.связь.send(json.dumps({
            "op": "call_service", "service": "/rosapi/topics", "id": "т"}))
        край = time.monotonic() + 3.0
        while time.monotonic() < край:
            try:
                письмо = json.loads(self.связь.recv())
            except Exception:                # noqa: BLE001
                continue
            if письмо.get("id") == "т":
                return (письмо.get("values") or {}).get("topics") or []
        return []

    def послать(self, топик: str, тип: str, сообщение: dict) -> None:
        self.связь.send(json.dumps({"op": "advertise", "topic": топик,
                                    "type": тип}))
        time.sleep(0.2)
        self.связь.send(json.dumps({"op": "publish", "topic": топик,
                                    "msg": сообщение}))

    def закрыть(self) -> None:
        try:
            self.связь.close()
        except Exception:                    # noqa: BLE001
            pass


