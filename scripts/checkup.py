def проверить_колёса(мост, ехать: bool):
    раздел("колёса и питание")
    мост.подписаться("/odom", "nav_msgs/msg/Odometry", throttle=100)
    мост.подписаться("/PowerVoltage", "std_msgs/msg/Float32", throttle=1000)
    пришло = мост.слушать(3.0)

    одом = [м for т, м in пришло if т == "/odom"]
    if not одом:
        сказать("колёса", "одометрия идёт", ПЛОХО,
                "шасси молчит — проверь robot-base и питание контроллера")
    else:
        сказать("колёса", "одометрия идёт", ХОРОШО,
                f"{len(одом) / 3.0:.0f} сообщений в секунду")
        точка = одом[-1].get("pose", {}).get("pose", {}).get("position", {})
        сказать("колёса", "координаты читаются", ХОРОШО,
                f"x={точка.get('x', 0):.2f} y={точка.get('y', 0):.2f}")

    вольты = [м.get("data") for т, м in пришло if т == "/PowerVoltage"]
    if not вольты:
        сказать("колёса", "напряжение батареи", СОМНИТЕЛЬНО,
                "топик молчит — робот не узнает, что садится")
    else:
        в = float(вольты[-1])
        # 3S li-ion: 12.6 полный, 9.9 пустой. Ниже 10.5 — пора на зарядку.
        как = ХОРОШО if в > 10.5 else ПЛОХО
        сказать("колёса", "напряжение батареи", как,
                f"{в:.1f} В" + ("" if как == ХОРОШО else " — садится, заряди"))

    if not ехать:
        сказать("колёса", "поедет ли по команде", СОМНИТЕЛЬНО,
                "не проверял: нужен --ехать и свободный пол вокруг")
        return

    if not одом:
        сказать("колёса", "поедет ли по команде", ПЛОХО,
                "не поеду без одометрии — иначе не увижу, сдвинулся ли")
        return

    было = одом[-1]["pose"]["pose"]["position"]
    print("\n   ЕДЕМ. Три секунды поворота на месте. Отойди.", flush=True)
    time.sleep(2.0)
    мост.послать("/cmd_vel", "geometry_msgs/msg/Twist",
                 {"linear": {"x": 0.0, "y": 0.0, "z": 0.0},
                  "angular": {"x": 0.0, "y": 0.0, "z": 0.4}})
    пришло = мост.слушать(1.5)
    мост.послать("/cmd_vel", "geometry_msgs/msg/Twist",
                 {"linear": {"x": 0.0, "y": 0.0, "z": 0.0},
                  "angular": {"x": 0.0, "y": 0.0, "z": 0.0}})
    одом2 = [м for т, м in пришло if т == "/odom"]
    if not одом2:
        сказать("колёса", "поедет ли по команде", ПЛОХО,
                "одометрия замолчала прямо во время поездки")
        return
    стало = одом2[-1]["pose"]["pose"]["orientation"]
    было_у = одом[-1]["pose"]["pose"]["orientation"]
    сдвиг = abs(float(стало.get("z", 0)) - float(было_у.get("z", 0)))
    как = ХОРОШО if сдвиг > 0.01 else ПЛОХО
    сказать("колёса", "поворот дошёл до колёс", как,
            f"поворот кватерниона изменился на {сдвиг:.3f}"
            + ("" if как == ХОРОШО else " — команда ушла, а робот стоит"))
    _ = было


def проверить_дальномер(веб: str):
    раздел("дальномер")
    сырьё = взять(f"{веб}/tof")
    if сырьё is None:
        сказать("дальномер", "данные с веб-сервера", ПЛОХО,
                f"{веб}/tof не отвечает — поднят ли robot-web?")
        return
    try:
        данные = json.loads(сырьё)
    except ValueError:
        сказать("дальномер", "данные с веб-сервера", ПЛОХО, "ответ не json")
        return

    # Ключи здесь ровно те, что кладёт web/server.py: «есть», «почему»,
    # «возраст», «сетка». Свериться с ними важнее, чем кажется: проверка,
    # читающая несуществующее поле, молча объявит исправным что угодно.
    if not данные.get("есть"):
        почему = str(данные.get("почему") or "нет данных")
        # Остановленная голосовая служба — не поломка датчика, а её отсутствие.
        # Разница дорогая: в первом случае человек лезет к шлейфу, во втором
        # набирает одну команду.
        if not ГОЛОС_ЖИВ:
            сказать("дальномер", "датчик отвечает", СОМНИТЕЛЬНО,
                    f"{почему} — но сетку выкладывает robot-voice, "
                    "а она остановлена. Это не про датчик")
        else:
            сказать("дальномер", "датчик отвечает", ПЛОХО, почему)
        return
    возраст = float(данные.get("возраст") or 0)
    как = ХОРОШО if возраст < 2.0 else ПЛОХО
    сказать("дальномер", "данные свежие", как, f"кадру {возраст:.1f} с"
            + ("" if как == ХОРОШО else " — служба выкладывает сетку и встала"))

    сетка = данные.get("сетка") or []
    живых = sum(1 for ряд in сетка for з in ряд if з)
    всего = sum(len(ряд) for ряд in сетка)
    if not всего:
        сказать("дальномер", "кадры идут", ПЛОХО, "сетка пуста")
        return
    доля = живых / всего
    как = ХОРОШО if доля > 0.5 else (СОМНИТЕЛЬНО if доля > 0.2 else ПЛОХО)
    сказать("дальномер", "зоны отвечают", как,
            f"{живых} из {всего}"
            + ("" if как == ХОРОШО else
               " — мало. Наклони датчик вниз на 10-15°, "
               "проверь: sudo systemctl stop robot-voice && cd ~/Robot-AI "
               "&& python3 scripts/tof_probe.py --карта 30"))

    # Ближайшее препятствие — заодно проверка, что числа осмысленные, а не
    # ноль и не бесконечность.
    близко = [з for ряд in сетка for з in ряд if з and з > 0.05]
    if близко:
        сказать("дальномер", "ближайшее препятствие", ХОРОШО,
                f"{min(близко):.2f} м, дальнее {max(близко):.2f} м")

    # И САМА СЕТКА ГЛАЗАМИ. Числа выше говорят «сколько зон отвечает», но не
    # говорят ГДЕ. А почти все беды дальномера — про «где»: пол в нижних
    # рядах, свой кронштейн в крайней колонке, стена сбоку, которую робот
    # принимает за препятствие по курсу. Один взгляд на восемь строк отвечает
    # на это сразу, и не надо ни скриншотов, ни пульта.
    print("\n   сетка 8x8, метры (· — зона молчит):")
    for р, ряд in enumerate(сетка):
        клетки = " ".join(f"{з:4.2f}" if з else "   ·" for з in ряд)
        print(f"     ряд {р}: {клетки}")
    print("     колонка 0 — слева, колонка 7 — справа;"
          " нижние ряды обычно пол")

    # И разбор: что из этого ЛЕЖИТ НА ПУТИ, а что стоит сбоку. Это ровно то
    # различие, на котором робот однажды отказался ехать по пустому полу,
    # потому что рядом стояла кровать.
    sys.path.insert(0, os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "voice"))
    try:
        from robot_voice import tof as дальномер
    except Exception:                        # noqa: BLE001
        return
    на_пути, мимо = [], []
    for р, ряд in enumerate(сетка):
        for к, з in enumerate(ряд):
            if not з:
                continue
            (на_пути if дальномер.отступ_вбок(к, з) <= дальномер.КОРИДОР
             else мимо).append(з)
    сказать("дальномер", "на пути робота",
            ХОРОШО if not на_пути or min(на_пути) > 0.5 else СОМНИТЕЛЬНО,
            (f"{len(на_пути)} зон, ближайшая {min(на_пути):.2f} м"
             if на_пути else "пусто — путь свободен"))
    if мимо:
        сказать("дальномер", "стоит сбоку (роботу не мешает)", ХОРОШО,
                f"{len(мимо)} зон, ближайшая {min(мимо):.2f} м")


def проверить_камеру(веб: str):
    раздел("камера")
    начало = time.monotonic()
    кадр = взять(f"{веб}/camera/snapshot", таймаут=6.0)
    прошло = time.monotonic() - начало
    if not кадр or len(кадр) < 1000:
        # РАЗЛИЧАЕМ ДВЕ РАЗНЫЕ БЕДЫ, и это стоит десяти строк.
        #
        # «Камера не работает» и «картинку некому раздать» выглядят для
        # человека одинаково — пустой квадрат в пульте, — а чинятся
        # совершенно по-разному. На живом роботе это уже стоило вечера:
        # детектор исправно вёл людей, то есть камера была цела, а пульт
        # писал «Connection refused» на 8080, и поиск шёл в камере.
        #
        # Камеру держит ОДИН узел (hobot_usb_cam) и публикует в ROS-топик;
        # все остальные — и детектор, и раздача — подписчики. Значит если
        # детекции идут, то камера жива наверняка, что бы ни показывал пульт.
        детекции = взять(f"{веб}/api/state", таймаут=3.0)
        видит = b"body" in (детекции or b"") or b"\xd0\xbb\xd1\x8e\xd0\xb4" in (детекции or b"")
        if видит:
            сказать("камера", "кадр приходит", ПЛОХО,
                    "камера ЖИВА (детектор видит людей), а раздачи нет: "
                    "не поднят web_video_server на 8080. "
                    "sudo apt install ros-$ROS_DISTRO-web-video-server, "
                    "потом systemctl restart robot-body")
        else:
            сказать("камера", "кадр приходит", ПЛОХО,
                    "снимок не получен. Смотри journalctl -u robot-body: "
                    "либо не запущен hobot_usb_cam, либо нет раздачи на 8080")
        return False
    сказать("камера", "кадр приходит", ХОРОШО,
            f"{len(кадр) // 1024} КБ за {прошло:.2f} с")
    # Размер кадра берём из самого jpeg: он важен для пеленга — ошибка втрое
    # в ширине кадра означает пеленг втрое мимо.
    ширина, высота = размер_jpeg(кадр)
    if ширина:
        как = ХОРОШО if ширина == 640 else СОМНИТЕЛЬНО
        сказать("камера", "размер кадра", как, f"{ширина}x{высота}"
                + ("" if как == ХОРОШО else
                   " — пеленг настроен на 640, поправь vision_track.ШИРИНА_КАДРА"))
    return True


def размер_jpeg(данные: bytes):
    """Ширина и высота из заголовка jpeg. (0, 0) — не разобрали."""
    i = 2
    try:
        while i < len(данные):
            if данные[i] != 0xFF:
                i += 1
                continue
            метка = данные[i + 1]
            if метка in (0xC0, 0xC1, 0xC2, 0xC3):
                высота = int.from_bytes(данные[i + 5:i + 7], "big")
                ширина = int.from_bytes(данные[i + 7:i + 9], "big")
                return ширина, высота
            длина = int.from_bytes(данные[i + 2:i + 4], "big")
            i += 2 + длина
    except Exception:                        # noqa: BLE001
        pass
    return 0, 0


def проверить_зрение(мост):
    раздел("зрение: детектор тела на BPU")
    мост.подписаться("/hobot_mono2d_body_detection",
                     "ai_msgs/msg/PerceptionTargets", throttle=50)
