#!/usr/bin/env python3
"""Проверка ходовки целиком: связь, датчики, камера, зрение, тормоза.

    ~/Robot-AI/voice/.venv/bin/python scripts/checkup.py
    ~/Robot-AI/voice/.venv/bin/python scripts/checkup.py --ехать

Зачем отдельная команда. Проверок у нас больше сотни, но все они живут на
сборочной машине и проверяют ЛОГИКУ. Работает ли шлейф камеры, крутится ли
левое колесо, видит ли дальномер пол — из них не узнать ничего: там нет ни
одного провода. А ломается на роботе именно железо и стыки с ним.

Раньше это выяснялось так: человек говорил «иди за мной», робот не ехал, и
дальше шёл вечер чтения журналов, в котором половина времени уходила на
«а работает ли вообще камера». Теперь на этот вопрос отвечает одна команда.

ЧТО ПРОВЕРЯЕТСЯ И В КАКОМ ПОРЯДКЕ. Порядок не случайный: он идёт от корня к
листьям, чтобы первая же красная строка называла ПРИЧИНУ, а не следствие.
Мёртвая камера утащит за собой и пеленг, и зрение, и поиск вещей — и если
проверять их вперемешку, три красные строки будут об одном и том же.

    1. связь        rosbridge, топики, службы
    2. колёса       одометрия, напряжение, сторож мёртвой руки
    3. дальномер    кадры, пол, обрыв, измеренный шум наклона
    4. камера       поток кадров, размер, частота
    5. зрение       детектор тела на BPU, пеленг человека
    6. сходимость   дальномер и камера про ОДНОГО человека — то самое место,
                    где два датчика либо согласны, либо врозь
    7. модель       ответ ПК или облака и за сколько
    8. вещи         DOSOD, если поднят

КОЛЁСА НЕ КРУТИМ БЕЗ ПРОСЬБЫ. По умолчанию проверка только слушает; чтобы
робот дёрнулся на месте и мы посмотрели, отвечает ли одометрия, нужен явный
--ехать и три метра свободного пола вокруг.

Порт дальномера скрипт НЕ ОТКРЫВАЕТ: его держит robot-voice, а два читателя
делят байты пополам и портят замеры обоим. Всё про дальномер берётся с
веб-сервера, оттуда же, откуда его берёт пульт.

ИЗ ЭТОГО СЛЕДУЕТ ГЛАВНОЕ ПРАВИЛО ЗАПУСКА: **robot-voice должна РАБОТАТЬ**.
Сетку в файл, откуда её читает и пульт, и эта проверка, выкладывает именно
она. Остановишь голосовую службу «чтобы не мешала» — и проверка честно
доложит «датчик отвечает: ПЛОХО, сетке 6 с», отправив человека искать
поломку в шлейфе там, где всего лишь никто не читает порт.

Так и вышло в живом разборе, и виновата была не машина, а совет её
остановить. Поэтому первое, что делает проверка, — спрашивает systemd, жива
ли голосовая служба, и если нет, называет это причиной, а не датчик.
"""

from __future__ import annotations

