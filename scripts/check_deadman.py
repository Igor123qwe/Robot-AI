#!/usr/bin/env python3
"""Останавливается ли шасси само, если перестать слать /cmd_vel.

ЗАЧЕМ ЭТО МЕРИТЬ. В коде робота с самого начала стояло утверждение: «шасси
ждёт /cmd_vel непрерывно — при паузе оно само тормозит, поэтому команду
повторяем 15 раз в секунду». На нём держится вся уверенность в том, что
упавший голосовой сервис не оставит робота едущим.

Утверждение оказалось неверным для драйвера: в turn_on_wheeltec_robot нет ни
таймера, ни таймаута — последняя посланная скорость действует, пока не придёт
следующая. Но остаётся вторая возможность: таймаут может быть в ПРОШИВКЕ
STM32, а её исходника у нас нет. Гадать тут нельзя — это разница между
«робот встанет сам» и «робот поедет, пока не упрётся».

Меряем одометрией, а не глазами: шасси докладывает /odom, и если колёса
крутятся, координата растёт. Это ответ числом, а не впечатлением.

БЕЗОПАСНОСТЬ. Проверка нарочно доводит робота до состояния «команда подана,
издатель замолчал» — то есть ровно до аварии, которую мы изучаем. Поэтому:

    КОЛЁСА ДОЛЖНЫ БЫТЬ В ВОЗДУХЕ. Поставь робота на коробку или подставку так,
    чтобы колёса не касались пола. Иначе он поедет и, возможно, не остановится.

Скрипт откажется работать, пока человек не подтвердит это словом.

    python3 scripts/check_deadman.py
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import threading
import time

import websocket

ТОПИК = "/cmd_vel"
ОДОМЕТРИЯ = "/odom"

# Скорость проверки. Малая нарочно: нам нужен факт вращения, а не поездка.
СКОРОСТЬ = 0.10
# Сколько крутим колёса, подавая команду как положено.
ГОНИМ = 1.0
# Сколько молчим и смотрим, что будет.
МОЛЧИМ = 3.0
# Насколько должна сдвинуться одометрия за время молчания, чтобы счесть, что
# колёса продолжали крутиться. Сантиметр: меньше — это выбег и шум энкодеров.
СДВИГ_ЗНАЧИМЫЙ = 0.01


class Проба:
    def __init__(self, url: str) -> None:
        self.url = url
        self._ws: websocket.WebSocketApp | None = None
        self._на_связи = threading.Event()
        self._замок = threading.Lock()
        self._путь = 0.0
        self._было: tuple[float, float] | None = None
        self.след: list[tuple[float, float]] = []

    def start(self) -> None:
        threading.Thread(target=self._жить, daemon=True).start()

    def _жить(self) -> None:
        self._ws = websocket.WebSocketApp(
            self.url, on_open=self._открылось, on_message=self._сообщение)
        self._ws.run_forever(ping_interval=20, ping_timeout=10)

    def _открылось(self, ws) -> None:
        self._послать({"op": "advertise", "topic": ТОПИК,
                       "type": "geometry_msgs/msg/Twist"})
        self._послать({"op": "subscribe", "topic": ОДОМЕТРИЯ,
                       "type": "nav_msgs/msg/Odometry"})
        self._на_связи.set()

    def _послать(self, что: dict) -> None:
        if self._ws is not None:
            self._ws.send(json.dumps(что))

    def _сообщение(self, ws, сырое: str) -> None:
        try:
            письмо = json.loads(сырое)
            точка = письмо["msg"]["pose"]["pose"]["position"]
            x, y = float(точка["x"]), float(точка["y"])
        except (ValueError, KeyError, TypeError):
            return
        with self._замок:
            if self._было is not None:
                dx, dy = x - self._было[0], y - self._было[1]
                self._путь += (dx * dx + dy * dy) ** 0.5
            self._было = (x, y)
            self.след.append((time.monotonic(), self._путь))

    @property
    def путь(self) -> float:
        with self._замок:
            return self._путь

    def ехать(self, скорость: float) -> None:
        self._послать({
            "op": "publish", "topic": ТОПИК,
            "msg": {"linear": {"x": скорость, "y": 0.0, "z": 0.0},
                    "angular": {"x": 0.0, "y": 0.0, "z": 0.0}}})


def _служба_жива(имя: str) -> bool:
    try:
        готово = subprocess.run(["systemctl", "is-active", "--quiet", имя],
                                check=False)
    except FileNotFoundError:
        return False
    return готово.returncode == 0


def main() -> int:
    url = os.getenv("ROBOT_ROSBRIDGE", "ws://127.0.0.1:9090")

    print(__doc__.split("Скрипт откажется")[0].strip())
    print()
    # Сторож мёртвой руки обязан быть выключен: иначе мы измерим его, а не
    # шасси, и получим бодрое «всё тормозит само» на роботе, который не
    # тормозит. Это ровно тот способ обмануть себя, ради которого проверка и
    # затевалась.
    for служба in ("robot-deadman", "robot-voice"):
        if _служба_жива(служба):
            print(f"Сначала останови {служба}:  sudo systemctl stop {служба}")
            print("Иначе проверка измерит его, а не шасси.")
            return 2

    ответ = input("Колёса В ВОЗДУХЕ и робот стоит устойчиво? напиши «да»: ")
    if ответ.strip().lower() not in ("да", "yes", "y"):
        print("Не подтверждено — не проверяю.")
        return 1

    проба = Проба(url)
    проба.start()
    if not проба._на_связи.wait(10):
        print(f"Нет связи с rosbridge на {url}.")
        return 3

    # Одометрия обязана идти: без неё мерить нечем, и «ноль сдвига» будет
    # означать «молчит датчик», а не «встали колёса».
    было = проба.путь
    time.sleep(1.0)
    if проба.путь == было and not проба.след:
        print(f"Шасси молчит в {ОДОМЕТРИЯ} — мерить нечем. "
              "Проверь, что узел шасси запущен.")
        return 3

    print(f"Гоню колёса {ГОНИМ:.0f} с на {СКОРОСТЬ} м/с …")
    до = проба.путь
    конец = time.monotonic() + ГОНИМ
    while time.monotonic() < конец:
        проба.ехать(СКОРОСТЬ)
        time.sleep(1 / 15)
    крутились = проба.путь - до
    print(f"  одометрия отсчитала {крутились:.3f} м — колёса вращались")
    if крутились < СДВИГ_ЗНАЧИМЫЙ:
        print("Колёса не завращались вовсе. Проверка невозможна: либо шасси не "
              "приняло команду, либо одометрия не считает.")
        return 3

    print(f"ЗАМОЛКАЮ. Ни одной команды {МОЛЧИМ:.0f} с. Смотри на колёса.")
    молча = проба.путь
    time.sleep(МОЛЧИМ)
    после = проба.путь - молча

    # На всякий случай останавливаем сами — что бы там ни выяснилось.
    for _ in range(5):
        проба.ехать(0.0)
        time.sleep(0.02)

    print()
    print(f"За {МОЛЧИМ:.0f} с молчания одометрия насчитала {после:.3f} м.")
    if после > СДВИГ_ЗНАЧИМЫЙ:
        скорость = после / МОЛЧИМ
        print()
        print("ВЫВОД: ШАССИ САМО НЕ ТОРМОЗИТ.")
        print(f"  Колёса продолжали крутиться примерно на {скорость:.2f} м/с.")
        print("  Значит последняя посланная скорость действует, пока не придёт")
        print("  следующая, и упавший голосовой сервис оставит робота едущим.")
        print()
        print("  Что делать: включить сторожа мёртвой руки —")
        print("      sudo cp systemd/robot-deadman.service /etc/systemd/system/")
        print("      sudo systemctl enable --now robot-deadman")
        print("  и понимать, что он не спасёт от смерти самого rosbridge.")
        print("  Настоящая защита — таймаут в прошивке STM32 или физическая")
        print("  кнопка, разрывающая питание драйверов моторов.")
        return 1

    print()
    print("ВЫВОД: шасси тормозит само при паузе в /cmd_vel.")
    print("  Сторож мёртвой руки остаётся полезен как второй слой, но не")
    print("  является единственным.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
