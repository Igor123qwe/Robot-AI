#!/usr/bin/env python3
"""Какую сборку модели «конец реплики» качать. Список берётся из репозитория.

    python3 scripts/pick_turn_model.py список.json
    curl -fsSL "$API" | python3 scripts/pick_turn_model.py -

Печатает в stdout одно имя файла, в stderr — всё, что нашлось. Код возврата 1
означает «подходящего нет», и это честный отказ, а не повод брать что попало.

Почему это отдельный файл, а не пять строк внутри shell-скрипта. Именно там
они и были, и там же сломались — тихо и неотличимо от «нет интернета».
Программу питону скармливали heredoc'ом, а данные — конвейером; и то и другое
идёт в stdin, heredoc побеждает, и разбор читал пустоту. Скрипт при этом не
падал: он честно печатал «не удалось спросить список», человек шёл проверять
сеть, а сеть была ни при чём.

Отдельный файл убирает саму возможность такой ошибки и, что важнее, делает
выбор проверяемым: самопроверка запускает ЭТОТ ЖЕ файл ТЕМ ЖЕ способом, каким
его зовёт скрипт. Проверка, которая гоняет логику иначе, чем боевой вызов,
подтверждает не то — ровно это здесь и случилось.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def выбрать(имена: list[str]) -> str:
    """Имя файла для нашего железа. Пусто — подходящего нет.

    У робота нет видеокарты и не будет. В репозитории рядом с процессорной
    сборкой лежит видеокартная — вчетверо тяжелее и на Cortex-A55 медленнее,
    так что взять её значит получить замедление там, где мы боремся за
    миллисекунды. Поэтому gpu не берём даже когда больше нечего взять: лучше
    отказ с показанным списком, чем тихо выбранный не тот файл.
    """
    onnx = [и for и in имена if и.endswith(".onnx")]
    if not onnx:
        return ""
    свои = [и for и in onnx if "cpu" in и.lower()]
    if not свои:
        свои = [и for и in onnx if "gpu" not in и.lower()]
    if not свои:
        return ""
    # Последняя по алфавиту — она же самая новая: имена версионированы
    # (smart-turn-v3.0, smart-turn-v3.1), и «больше» совпадает с «свежее».
    return sorted(свои)[-1]


def главное(аргументы: list[str]) -> int:
    if not аргументы:
        print("нужен файл со списком или «-» для stdin", file=sys.stderr)
        return 2
    откуда = аргументы[0]
    try:
        сырьё = (sys.stdin.read() if откуда == "-"
                 else Path(откуда).read_text(encoding="utf-8"))
        данные = json.loads(сырьё or "{}")
    except (OSError, ValueError) as e:
        print(f"не разобрал список: {e}", file=sys.stderr)
        return 1

    имена = [ф.get("rfilename", "") for ф in данные.get("siblings", [])
             if isinstance(ф, dict)]
    onnx = [и for и in имена if и.endswith(".onnx")]
    if onnx:
        # Печатаем ВСЁ найденное: если выбор окажется неверным, человек должен
        # видеть, из чего выбирали, а не гадать по одному имени.
        print("  нашлось:", ", ".join(sorted(onnx)), file=sys.stderr)

    имя = выбрать(имена)
    if not имя:
        print("  подходящей сборки под процессор нет", file=sys.stderr)
        return 1
    print(имя)
    return 0


if __name__ == "__main__":
    sys.exit(главное(sys.argv[1:]))
