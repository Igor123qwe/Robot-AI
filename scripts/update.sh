#!/usr/bin/env bash
# Забрать свежий код с GitHub и перезапустить только то, что реально изменилось.
#
# Работает в двух режимах:
#   от wheeltec  — вручную, sudo спросит пароль;
#   от root      — по таймеру (robot-autopull), git при этом идёт от владельца
#                  репозитория, иначе не найдёт его ssh-ключ.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OWNER="$(stat -c %U "$REPO")"
cd "$REPO"

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

# --- не обновляемся на ходу ------------------------------------------------
# Голосовой сервис держит этот файл, пока робот движется — по своей команде
# или с веб-пульта. Перезапуск в этот момент убил бы поток движения; нули в
# /cmd_vel он отправить успеет, но проверять это на живом роботе не хочется.
# Таймер попробует снова через две минуты, торопиться некуда.
BUSY_FLAG="${ROBOT_BUSY_FLAG:-/run/robot-ai/moving}"
if [ "$FORCE" = 0 ] && [ -e "$BUSY_FLAG" ]; then
  AGE=$(( $(date +%s) - $(stat -c %Y "$BUSY_FLAG") ))
  # Признак старше минуты — значит сервис убили посреди движения.
  # Дольше самой длинной поездки (три метра на 0.2 м/с — пятнадцать секунд).
  if [ "$AGE" -lt 60 ]; then
    echo "==> робот в движении, откладываю обновление"
    exit 0
  fi
  echo "==> признак движения залежался ($AGE с), не верю ему"
fi

if [ "$(id -u)" = 0 ]; then
  SUDO=""
  git() { runuser -u "$OWNER" -- env "HOME=$(getent passwd "$OWNER" | cut -d: -f6)" \
            git -C "$REPO" "$@"; }
else
  SUDO="sudo"
fi

# --- код -------------------------------------------------------------------
BEFORE="$(git rev-parse HEAD)"
# Ограничение по времени обязательно. Молча потерянный TCP до GitHub вешает
# fetch навсегда; юнит oneshot своего таймаута не имеет, таймер новый проход
# не запускает, пока висит старый, — и обновления перестают приезжать до
# перезагрузки, ни строчкой не пожаловавшись. А это единственный штатный путь
# доставки кода на робота.
if ! timeout 60 git fetch -q origin; then
  echo "==> нет связи с GitHub, попробую в следующий раз"
  exit 0
fi

# Робот — не рабочая машина, а потребитель кода: его ветка обязана совпадать с
# GitHub. Раньше одного локального коммита или правки файла хватало, чтобы
# --ff-only падал каждые две минуты вечно и обновления переставали приезжать
# молча. Теперь расхождение — не тупик: откладываем локальное в отдельную
# ветку (ничего не теряется) и встаём на удалённую.
if ! git merge --ff-only -q '@{u}' 2>/dev/null; then
  MARK="local-$(date +%Y%m%d-%H%M%S)"
  echo "==> локальные изменения расходятся с GitHub, откладываю их как $MARK"
  # Незакоммиченное — в stash, коммиты — в ветку. Достать: git stash list,
  # git log local-*. Ничего не удаляется, но робот встаёт на код с GitHub.
  # Личность задаём явно: stash делает коммит и без user.name/user.email
  # падает, а на роботе их обычно никто не настраивал. Раньше падение
  # глоталось, и следующий reset --hard уносил правку, которую обещали
  # сохранить.
  if ! git -c user.name=robot -c user.email=robot@local \
       stash push -u -q -m "$MARK"; then
    echo "!! не смог отложить локальные правки — обновление подождёт"
    echo "   разберитесь вручную: git -C $REPO status"
    exit 0
  fi
  git branch "$MARK" HEAD || true
  git reset -q --hard '@{u}'
fi
AFTER="$(git rev-parse HEAD)"

# От чего считать изменения. Не от того, что притянул этот заход, а от того,
# что РЕАЛЬНО КРУТИТСЯ в сервисах, — и разница тут не теоретическая.
#
# Человек, потянувший git pull руками, забирает коммиты себе. Следующий заход
# видит «нового нет», перезапускать ему нечего, и службы продолжают работать
# со старым кодом. Снаружи это выглядит хуже некуда: правка доехала, файл на
# диске новый, git чистый — а поведение прежнее. Ищут потом в коде.
#
# Поэтому запоминаем на диске тот коммит, на котором службы были перезапущены,
# и сравниваем с ним. Кто именно притянул код — неважно.
DEPLOYED_FILE="$HOME/.robot-ai.deployed"
DEPLOYED="$(cat "$DEPLOYED_FILE" 2>/dev/null || true)"

CHANGED=""
if [ -n "$DEPLOYED" ] && git cat-file -e "$DEPLOYED^{commit}" 2>/dev/null; then
  FROM="$DEPLOYED"
else
  # Первый заход после установки этой версии: отметки ещё нет. Считаем от
  # того, что притянули сами, — как раньше. Ничего лишнего не перезапустим.
  FROM="$BEFORE"
fi

if [ "$FROM" != "$AFTER" ]; then
  CHANGED="$(git diff --name-only "$FROM" "$AFTER")"
  if [ "$BEFORE" != "$AFTER" ]; then
    echo "==> обновление: $(git log --oneline -1)"
  else
    echo "==> код уже свежий, но службы его ещё не подхватили"
  fi
else
  echo "==> нового нет"
fi

# --- юниты systemd ---------------------------------------------------------
# Сверяем по факту, а не по коммитам: файл в /etc мог разойтись с репозиторием.
RELOAD=0
RESTART=""
for f in systemd/*.service; do
  # Проверка, что файл есть: без неё пустой каталог даёт незакрытую маску,
  # cp падает на несуществующем «systemd/*.service», и весь скрипт умирает по
  # set -e — не дойдя ни до перезапуска, ни до отметки. У таймеров ниже такая
  # проверка была, у сервисов нет.
  [ -e "$f" ] || continue
  unit="$(basename "$f" .service)"
  if ! $SUDO cmp -s "$f" "/etc/systemd/system/$unit.service"; then
    $SUDO cp "$f" "/etc/systemd/system/$unit.service"
    RELOAD=1
    RESTART="$RESTART $unit"
    echo "    юнит $unit обновлён"
  fi
done
for f in systemd/*.timer; do
  [ -e "$f" ] || continue
  unit="$(basename "$f")"
  if ! $SUDO cmp -s "$f" "/etc/systemd/system/$unit"; then
    $SUDO cp "$f" "/etc/systemd/system/$unit"
    RELOAD=1
    echo "    таймер $unit обновлён"
  fi
done
[ "$RELOAD" = 1 ] && $SUDO systemctl daemon-reload

# --- что перезапускать из-за кода ------------------------------------------
# Статику в web/ не трогаем: она отдаётся прямо с диска. А вот сам сервер
# (он же прокси камеры) — это код, его надо перезапускать.
# robot-base и robot-bridge живут вне этого репозитория — дёргаем их только
# если поменялся сам юнит. Иначе таймер остановит робота посреди команды.
# Ровно то, что сервис исполняет. README и selftest.py лежат в той же папке,
# меняются почти в каждом коммите, а перезапуск не бесплатен: заново
# поднимается Whisper и теряется контекст разговора — посреди разговора.
if echo "$CHANGED" | grep -qE '^voice/(robot_voice/|requirements\.txt$)'; then
  RESTART="$RESTART robot-voice"
fi
# Не только server.py: рядом с ним живут tls.py, wsproxy.py и camera.py — всё
# это код, который сервер исполняет. Раньше здесь стояло одно имя файла, и
# правки камеры доезжали до робота, но не запускались: git их приносил,
# служба продолжала работать со старыми. Снаружи это выглядит как «починил, а
# не помогло» — худший вид отказа, потому что ищут потом в коде, а дело в
# том, что код не тот.
if echo "$CHANGED" | grep -qE '^web/[^/]+\.py$'; then
  RESTART="$RESTART robot-web"
fi
# А ЭТО ТО ЖЕ САМОЕ ПРО ДЕТЕКТОР, и дыра была ровно такая же.
#
# robot-body исполняет НАШИ файлы из scripts/: юнит зовёт body_service.sh, тот
# — mono2d_no_web.launch.py, а тот поднимает узлы, включая затвор look_relay.py
# и поиск вещей. Ни один из них в правилах перезапуска не значился: git их
# исправно привозил, а служба продолжала крутить старые.
#
# Стоило это целого вечера. В launch-файле параметр поиска вещей стоял так,
# что узел читал картинку из файла вместо кадров с камеры; правку я привёз, а
# перезапуска не случилось — и человек ещё дважды перезапускал детектор
# руками, гадая, почему ничего не изменилось. Тот же «починил, а не помогло»,
# от которого выше защищён web/.
#
# robot-base и robot-bridge по-прежнему не трогаем: они живут вне репозитория,
# и дёргать их из-за наших правок незачем.
if echo "$CHANGED" | grep -qE '^scripts/(body_service\.sh|look_relay\.py|mono2d_no_web\.launch\.py)$'; then
  RESTART="$RESTART robot-body"
fi

# --- что перезапускать из-за настроек --------------------------------------
# Файл настроек в репозитории не лежит, его правит человек руками — и до сих
# пор это не приводило ни к чему: git не видел изменений, перезапускать было
# «нечего», а служба продолжала работать со старым окружением. Человек при
# этом уверен, что настройку поменял. Поэтому запоминаем слепок файла рядом с
# отметками обновления и сравниваем при каждом заходе.
# Имена переменных ЛАТИНИЦЕЙ: shell других не понимает вовсе. Присваивание
# вида СЛЕПОК=... он читает как имя команды и отвечает «command not found»,
# причём в стандартную ошибку, — а скрипт спокойно идёт дальше с пустыми
# значениями. Проверка при этом остаётся на месте и выглядит рабочей.
ENVFILE="${ROBOT_ENV_FILE:-$HOME/.robot-ai.env}"
ENVSHA="$HOME/.robot-ai.env.sha"
if [ -f "$ENVFILE" ]; then
  ENVNOW="$(sha256sum "$ENVFILE" | cut -d' ' -f1)"
  ENVWAS="$(cat "$ENVSHA" 2>/dev/null || true)"
  if [ "$ENVNOW" != "$ENVWAS" ]; then
    echo "    настройки изменились — перезапускаю обе службы"
    RESTART="$RESTART robot-voice robot-web"
    echo "$ENVNOW" > "$ENVSHA"
  fi
fi

# --- перезапуск ------------------------------------------------------------
DONE=""
FAILED=0
for unit in $RESTART; do
  case " $DONE " in *" $unit "*) continue ;; esac
  # Себя не перезапускаем: этот скрипт и есть robot-autopull, и systemctl
  # restart убьёт его на полуслове — остальные сервисы обновлены не будут.
  # Новый юнит подхватится сам при следующем срабатывании таймера.
  [ "$unit" = robot-autopull ] && continue
  DONE="$DONE $unit"
  if systemctl is-enabled --quiet "$unit" 2>/dev/null; then
    if $SUDO systemctl restart "$unit"; then
      echo "    $unit — перезапущен"
    else
      # Не вышло — чаще всего это неверный пароль sudo при ручном запуске.
      # Отметку в этом случае двигать НЕЛЬЗЯ: следующий заход решил бы, что
      # службы уже на свежем коде, и обновление потерялось бы навсегда,
      # молча. Ровно та беда, ради которой отметка и заведена.
      echo "!! $unit — перезапустить не вышло, отметку не двигаю"
      FAILED=1
    fi
  fi
done

[ -z "$DONE" ] && echo "==> перезапускать нечего"

# Отметка «службы крутят вот этот коммит». Пишем, когда перезапускать было
# нечего (значит они и так свежие) или когда всё перезапустилось. Без записи
# следующий заход считал бы изменения от того же старого коммита и
# перезапускал одно и то же каждые две минуты.
if [ "$FAILED" = 0 ]; then
  echo "$AFTER" > "$DEPLOYED_FILE"
  echo "==> готово"
else
  echo "==> готово наполовину: попробую снова через две минуты"
fi
