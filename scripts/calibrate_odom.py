#!/usr/bin/env python3
"""Замер систематической ошибки одометрии по квадрату (UMBmark).

ЗАЧЕМ. Одометрия врёт двумя способами, и они разные по природе:

  СЛУЧАЙНО — проскальзывание, неровности, ковёр. Это лечится только новыми
  измерениями (компас по стенам, привязка к мебели) и не лечится калибровкой;

  СИСТЕМАТИЧЕСКИ — колёса чуть разного диаметра и колёсная база, отличающаяся
  от той, что записана в драйвере. Это не шум: это одна и та же ошибка в одну
  и ту же сторону, накапливающаяся ровно пропорционально пройденному пути.

Второе — половина всей беды с картой, и оно снимается ДВУМЯ ЧИСЛАМИ, без
единой строчки в рантайме. Расхождение диаметров в один процент — величина,
которую не увидишь глазом и не измеришь штангенциркулем через резину, — даёт
после квадрата со стороной четыре метра промах в ДВА МЕТРА. Проверено на
модели: при Ed = 1.008 робот приезжает в точку (-0.94, -2.05) вместо начала.

ЧТО ДЕЛАТЬ (полчаса, нужна рулетка и свободные четыре метра).

  1. Поставь робота в угол комнаты или коридора. Отметь на полу малярным
     скотчем ДВЕ точки: где стоит колесо и куда смотрит нос. Направление
     важно: все замеры считаются в системе «x вперёд по первому отрезку,
     y влево».

  2. Прогони его по квадрату ПО ЧАСОВОЙ, голосом, четыре раза подряд:

         Кузя, проедь вперёд четыре метра
         Кузя, повернись направо

     Именно голосом и именно так: команда идёт по одометрии, а нам и нужно
     померить, насколько одометрия врёт.

  3. Померь рулеткой, где робот оказался ОТНОСИТЕЛЬНО МЕТКИ: сколько вперёд
     (или назад — тогда со знаком минус) и сколько влево (вправо — минус).

  4. То же самое ПРОТИВ ЧАСОВОЙ («повернись налево»).

  5. Скорми числа сюда:

         python3 scripts/calibrate_odom.py --почасовой=-0.94,-2.05 \\
                                           --против=1.27,-0.69

     ЗНАК РАВЕНСТВА ОБЯЗАТЕЛЕН, и это не придирка: числа почти всегда
     начинаются с минуса, а argparse принимает «-0.94» за имя флага и
     ругается «expected one argument». Через равенство он читает их верно.

Заходов можно сделать по нескольку в каждую сторону — тогда перечисли их все,
скрипт усреднит. Но и одного хватает: ошибка выходит метровая, а рулетка врёт
на сантиметр, так что шум тут не помеха (проверено — при рулетке ±2 см и одном
заходе расхождение диаметров определяется до четвёртого знака).

КАК ЭТО СЧИТАЕТСЯ. Не замкнутыми формулами из статьи, а решением обратной
задачи по кинематике: у нас есть модель дифференциального привода, в которой
расхождение диаметров и ошибка базы ЗАДАЮТСЯ, значит можно посчитать, какую
конечную ошибку они дают, и подобрать те, что объясняют измеренную. Формулы
Borenstein & Feng я пробовал взять по памяти, и проверка на модели с заранее
известной ошибкой их забраковала — вспомнились неверно. Подбор же
восстанавливает заложенные числа точно, и это проверяется прямо здесь:

         python3 scripts/calibrate_odom.py --проверить

Основание метода: Borenstein & Feng, UMBmark, University of Michigan, 1994.
"""

from __future__ import annotations

import argparse
import math

# Колёсная база по паспорту шасси wheeltec, в метрах. То же число, что в
# voice/robot_voice/tof.py; если оно там изменится, менять надо и здесь —
# скрипт живёт отдельно от голосовой службы и импортировать её не может.
БАЗА_ПО_ПАСПОРТУ = 0.195

# Сторона квадрата по умолчанию. Четыре метра: меньше — ошибка не успевает
# накопиться до различимой рулеткой, больше — не влезает в квартиру.
СТОРОНА = 4.0

# Насколько мелко считаем дугу в модели. Тысячные доли оборота: считаем один
# раз, а точность нужна, чтобы модель не вносила своей ошибки поверх искомой.
ШАГОВ_НА_ОТРЕЗОК = 4000

# Приращение, которым щупаем чувствительность. Две тысячных: заметно больше
# ошибок округления и заметно меньше искомых величин.
ЩУП = 0.002

# Сколько раз пересчитываем. Восемь с запасом: на живых числах сходится за
# три-четыре.
ПОДХОДОВ = 8


def квадрат(сторона: float, по_часовой: bool, Ed: float, Eb: float,
            база: float = БАЗА_ПО_ПАСПОРТУ) -> tuple[float, float]:
    """Куда приедет робот с такими ошибками. (x вперёд, y влево) в метрах.

    Ed — отношение диаметров правого колеса к левому.
    Eb — отношение настоящей колёсной базы к той, что записана в драйвере.

    Средний диаметр считаем верным: общий масштаб ловится не квадратом, а
    простым проездом вдоль рулетки, и он же обычно и верен — паспортный
    диаметр колеса ошибается редко, а вот РАЗНИЦА между колёсами есть всегда.
    """
    к_л = 2 / (1 + Ed)
    к_п = к_л * Ed
    настоящая = база * Eb
    x = y = курс = 0.0
    знак = -1.0 if по_часовой else 1.0

    def катить(путь_л: float, путь_п: float, шагов: int) -> None:
        nonlocal x, y, курс
        for _ in range(шагов):
            дл = путь_л / шагов * к_л
            дп = путь_п / шагов * к_п
            д = (дл + дп) / 2
            дθ = (дп - дл) / настоящая
            x += д * math.cos(курс + дθ / 2)
            y += д * math.sin(курс + дθ / 2)
            курс += дθ

    for _ in range(4):
        катить(сторона, сторона, ШАГОВ_НА_ОТРЕЗОК)
        дуга = знак * (math.pi / 2) * база / 2
        катить(-дуга, дуга, max(50, ШАГОВ_НА_ОТРЕЗОК // 20))
    return x, y


def подобрать(сторона: float, почасовой, против,
              база: float = БАЗА_ПО_ПАСПОРТУ):
    """Измеренные промахи -> (Ed, Eb). None — система вырождена.

    ИТЕРАЦИЯМИ, А НЕ ОДНИМ ШАГОМ. Зависимость промаха от Ed и Eb линейна
    только при малых ошибках; на трёх процентах расхождения колёс одношаговое
    решение промахивалось в восемь раз больше допустимого и — хуже того —
    путало Ed с Eb, потому что оба дают похожий разворот. Пересчёт
    чувствительности в текущей точке лечит это за три-четыре подхода.
    """
    цx_ч = sum(т[0] for т in почасовой) / len(почасовой)
    цy_ч = sum(т[1] for т in почасовой) / len(почасовой)
    цx_п = sum(т[0] for т in против) / len(против)
    цy_п = sum(т[1] for т in против) / len(против)
    измерено = [цx_ч, цy_ч, цx_п, цy_п]

    def отклик(Ed: float, Eb: float):
        а = квадрат(сторона, True, Ed, Eb, база)
        б = квадрат(сторона, False, Ed, Eb, база)
        return [а[0], а[1], б[0], б[1]]

    Ed = Eb = 1.0
    for _ in range(ПОДХОДОВ):
        сейчас = отклик(Ed, Eb)
        по_Ed = отклик(Ed + ЩУП, Eb)
        по_Eb = отклик(Ed, Eb + ЩУП)
        J = [[(по_Ed[и] - сейчас[и]) / ЩУП, (по_Eb[и] - сейчас[и]) / ЩУП]
             for и in range(4)]
        цель = [измерено[и] - сейчас[и] for и in range(4)]
        a11 = sum(с[0] * с[0] for с in J)
        a12 = sum(с[0] * с[1] for с in J)
        a22 = sum(с[1] * с[1] for с in J)
        b1 = sum(с[0] * ц for с, ц in zip(J, цель))
        b2 = sum(с[1] * ц for с, ц in zip(J, цель))
        опр = a11 * a22 - a12 * a12
        if abs(опр) < 1e-18:
            return None
        дEd = (b1 * a22 - b2 * a12) / опр
        дEb = (a11 * b2 - a12 * b1) / опр
        Ed += дEd
        Eb += дEb
        if abs(дEd) < 1e-7 and abs(дEb) < 1e-7:
            break
    return Ed, Eb


def проверить(сторона: float = СТОРОНА,
              база: float = БАЗА_ПО_ПАСПОРТУ) -> int:
    """Подсунуть модели известные ошибки и убедиться, что они восстановились.

    Без этой проверки скрипту нельзя верить: замкнутые формулы из статьи я уже
    один раз вспомнил неверно, и заметил это только потому, что проверил.
    """
    print(f"квадрат {сторона} м, база по паспорту {база} м\n")
    print(f"{'заложено Ed':>12} {'заложено Eb':>12} | "
          f"{'вышло Ed':>10} {'вышло Eb':>10} | промах")
    худший = 0.0
    for Ed, Eb in ((1.01, 1.0), (1.0, 1.02), (1.005, 0.99), (1.02, 1.03),
                   (1.0, 1.0), (0.99, 1.01), (1.03, 0.97)):
        ч = квадрат(сторона, True, Ed, Eb, база)
        п = квадрат(сторона, False, Ed, Eb, база)
        нашли = подобрать(сторона, [ч], [п], база)
        промах = max(abs(нашли[0] - Ed), abs(нашли[1] - Eb))
        худший = max(худший, промах)
        print(f"{Ed:12.4f} {Eb:12.4f} | {нашли[0]:10.4f} {нашли[1]:10.4f} | "
              f"{промах:.6f}")
    print(f"\nхудший промах: {худший:.6f}")
    сошлось = худший < 1e-3
    print("сошлось" if сошлось else "НЕ СОШЛОСЬ — считать нельзя")
    return 0 if сошлось else 1


def _точки(значения):
    вышло = []
    for кусок in значения or ():
        части = кусок.replace(";", ",").split(",")
        if len(части) != 2:
            raise SystemExit(f"не понял «{кусок}»: нужно «вперёд,влево», "
                             f"например -0.94,-2.05")
        вышло.append((float(части[0]), float(части[1])))
    return вышло


def главное(аргв=None) -> int:
    разбор = argparse.ArgumentParser(
        description="Замер систематической ошибки одометрии по квадрату.",
        epilog="Числа пиши через знак равенства: --почасовой=-0.94,-2.05 . "
               "Они почти всегда отрицательные, а минус в начале argparse "
               "принимает за имя флага.")
    разбор.add_argument("--почасовой", action="append", metavar="ВПЕРЁД,ВЛЕВО",
                        help="где робот оказался после квадрата по часовой")
    разбор.add_argument("--против", action="append", metavar="ВПЕРЁД,ВЛЕВО",
                        help="то же для квадрата против часовой")
    разбор.add_argument("--сторона", type=float, default=СТОРОНА,
                        help=f"сторона квадрата в метрах (по умолчанию "
                             f"{СТОРОНА})")
    разбор.add_argument("--база", type=float, default=БАЗА_ПО_ПАСПОРТУ,
                        help=f"колёсная база по паспорту (по умолчанию "
                             f"{БАЗА_ПО_ПАСПОРТУ})")
    разбор.add_argument("--проверить", action="store_true",
                        help="прогнать метод на известных ошибках и выйти")
    дано = разбор.parse_args(аргв)

    if дано.проверить:
        return проверить(дано.сторона, дано.база)

    почасовой = _точки(дано.почасовой)
    против = _точки(дано.против)
    if not почасовой or not против:
        разбор.print_help()
        print("\nНужны замеры В ОБЕ СТОРОНЫ. Одной мало: по одному квадрату "
              "\nошибку базы и расхождение колёс не различить — они дают "
              "похожий\nразворот, и разводит их только смена направления "
              "обхода.")
        return 2

    нашли = подобрать(дано.сторона, почасовой, против, дано.база)
    if нашли is None:
        print("Замеры вырождены: похоже, обе стороны дали одно и то же.")
        return 1
    Ed, Eb = нашли
    настоящая_база = дано.база * Eb
    print(f"замеров: по часовой {len(почасовой)}, против {len(против)}\n")
    print(f"  расхождение диаметров колёс  Ed = {Ed:.5f}   "
          f"(правое {'больше' if Ed > 1 else 'меньше'} левого на "
          f"{abs(Ed - 1) * 100:.2f} %)")
    print(f"  ошибка колёсной базы         Eb = {Eb:.5f}   "
          f"(на самом деле {настоящая_база * 100:.2f} см, "
          f"а не {дано.база * 100:.2f})")

    # Насколько это вообще важно — говорим числом, а не «много/мало».
    промах = math.hypot(*квадрат(дано.сторона, True, Ed, Eb, дано.база))
    print(f"\nЧто это значит: за квадрат в {дано.сторона:.0f} м робот "
          f"промахивается мимо старта на {промах:.2f} м.")
    if промах < 0.15:
        print("Это мало. Систематической ошибки практически нет, "
              "калибровать нечего.")
    else:
        print("Столько же он накапливает за каждые "
              f"{4 * дано.сторона:.0f} метров пути — и ровно это разносит "
              "карту квартиры.")
    print("\nЧисла записаны? Пришли их — поправку к курсу надо вносить в "
          "коде,\nа не в драйвере: шасси отдаёт готовую позу и колёсные "
          "обороты наружу\nне показывает.")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
