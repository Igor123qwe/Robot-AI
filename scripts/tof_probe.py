СКОРОСТЬ = 115200
ОПАСНЫЕ = ("wch", "usb_single_serial")    # так представляется плата приводов


def открыть(путь: str) -> int:
    import termios

    fd = os.open(путь, os.O_RDWR | os.O_NOCTTY)
    iflag, oflag, cflag, lflag, ispeed, ospeed, cc = termios.tcgetattr(fd)
    скорость = getattr(termios, f"B{СКОРОСТЬ}")
    cc = list(cc)
    cc[termios.VMIN] = 0
    cc[termios.VTIME] = 2
    termios.tcsetattr(fd, termios.TCSANOW, [
        0, 0, termios.CS8 | termios.CREAD | termios.CLOCAL, 0,
        скорость, скорость, cc])
    termios.tcflush(fd, termios.TCIOFLUSH)
    return fd


def собрать(cmd: int, args: bytes = b"") -> bytes:
    """Кадр запроса. Длина считается ВМЕСТЕ с командой — см. tof._кадр."""
    длина = len(args) + 1
    return bytes([0x55, (длина >> 8) & 0xFF, длина & 0xFF, cmd]) + args


def почитать(fd: int, сколько: float = 0.4) -> bytes:
    срок = time.monotonic() + сколько
    буфер = b""
    while time.monotonic() < срок:
        кусок = os.read(fd, 4096)
        if кусок:
            буфер += кусок
        else:
            time.sleep(0.005)
    return буфер


def сеткой(сетка, отступ: str = "      ") -> None:
    """Восемь на восемь метров столбиком. Ноль — «не измерил»."""
    for ряд in сетка:
        print(отступ + " ".join("  —  " if м <= 0 else f"{м:5.2f}"
                                for м in ряд))


def показать(байты: bytes, подпись: str) -> None:
    if not байты:
        print(f"  {подпись}: тишина")
        return
    print(f"  {подпись}: {len(байты)} байт")
    print(f"    начало: {байты[:16].hex(' ')}")
    if len(байты) > 16:
        print(f"    хвост:  {байты[-8:].hex(' ')}")
    if tof is None:
        return
    # Строковый вид пробуем первым: живая плата говорит именно им, и
    # показать человеку метры полезнее, чем шестнадцатеричный дамп.
    сетка = tof.строками(байты.decode("ascii", "replace"))
    if сетка is not None:
        print("    РАЗОБРАЛОСЬ как строки «y0:…» в миллиметрах:")
        сеткой(сетка)
        return
    разбор = tof.разобрать(байты)
    if разбор and разбор[1]:
        print(f"    РАЗОБРАЛОСЬ как двоичный кадр, команда {разбор[0]}, "
              f"{len(разбор[1])} байт данных:")
        сеткой(tof.в_метры(разбор[1]))


СЕРВИС = "robot-voice"

# Был ли порт свободен в тот момент, когда мы решили его открыть. Нужно,
# чтобы не выдать в одном выводе два противоречащих утверждения.
БЫЛО_СВОБОДНО = [False]


def кто_держит(порт: str) -> list[tuple[int, str]]:
    """Кто РЕАЛЬНО открыл этот порт. Список (pid, имя процесса).

    Смотрим в /proc, а не гадаем по systemctl. Разница принципиальная: «сервис
    запущен» и «сервис держит порт» — разные утверждения, и подменять первым
    второе значит уверенно говорить человеку неправду. Дальномер внутри
    сервиса мог не подняться вовсе, и тогда порт свободен, а мы отказываемся
    его открывать, ссылаясь на занятость.

    Root не нужен: сервис работает от того же пользователя, что и пробник,
    и его файловые дескрипторы нам видны.
    """
    цель = os.path.realpath(порт)
    держат: list[tuple[int, str]] = []
    for запись in glob.glob("/proc/[0-9]*"):
        pid = int(os.path.basename(запись))
        if pid == os.getpid():
            continue
        try:
            for fd in os.listdir(f"{запись}/fd"):
                if os.path.realpath(f"{запись}/fd/{fd}") == цель:
                    имя = Path(f"{запись}/comm").read_text().strip()
                    держат.append((pid, имя))
                    break
        except OSError:
            continue          # процесс умер или он не наш — не наше дело
    return держат


def соперник(порт: str) -> str:
    """Кто ещё читает этот порт. Пусто — никто.

    Последовательный порт в Linux не эксклюзивен: открыть его могут двое, и
    тогда они воруют байты друг у друга. Снаружи это выглядит как молчащая
    плата — самый обидный вид поломки, потому что чинить бросаются железо.

    Первым делом смотрим на сам сервис робота: с тех пор как драйвер к нему
    подключён, это единственный вероятный соперник, и узнаётся он без
    всякого root.
    """
    import subprocess
    try:
        готово = subprocess.run(["systemctl", "is-active", СЕРВИС],
                                capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return ""
    if готово.stdout.strip() == "active":
        return СЕРВИС
    return ""


def пожаловаться_на_тишину(порт: str, было_свободно: bool = False) -> None:
    """Плата молчит. Объяснить, что это может быть не плата.

    Смотрим в /proc, а не гадаем по systemctl: «служба запущена» и «служба
    держит порт» — разные утверждения, и подменять одно другим значит
    уверенно посылать человека чинить не то.
    """
    print("\nНи одного кадра. Это не обязательно поломка.")
    держат = [(pid, имя) for pid, имя in кто_держит(порт)] if порт else []
    if держат:
        кто = ", ".join(f"{имя} (pid {pid})" for pid, имя in держат)
        if было_свободно:
            # Порт был свободен, когда мы начинали, и занят через три
            # секунды. Значит держатель ПОЯВИЛСЯ, пока мы смотрели, — то
            # есть служба перезапускается по кругу. Про это надо сказать
            # прямо: иначе человек читает два противоречащих сообщения в
            # одном выводе и справедливо перестаёт им верить.
            print(f"\nПорт был свободен, а теперь его держит {кто}.")
            print("Держатель появился, пока я смотрел, — значит служба")
            print("перезапускается по кругу. Смотреть надо туда:")
            print(f"\n    systemctl status {СЕРВИС} --no-pager | head -20")
            print(f"    journalctl -u {СЕРВИС} -n 200 --no-pager | "
                  "grep -iE 'дальномер|Traceback|Error'")
            return
        print(f"\nПорт уже читает {кто} — байты делятся пополам, и пробнику")
        print("не достаётся ничего. Обнови службу, тогда она покажет сетку")
        print("сама и останавливать ничего не придётся:")
        print(f"\n    git pull && sudo systemctl restart {СЕРВИС}")
    else:
        print("Порт никто не держит, значит молчит сама плата. Смотри провод,")
        print("питание и что говорит служба:")
        print("    ls -l /dev/serial/by-id/")
        print(f"    journalctl -u {СЕРВИС} -n 100 --no-pager | grep -i дальномер")


class ИзПорта:
    """Кадры прямо с платы. Годится, только когда сервис робота не работает."""

    откуда = "порт"

    def __init__(self, fd: int) -> None:
        self.fd = fd
        self.буфер = ""

    def кадр(self):
        кусок = os.read(self.fd, 4096)
        if not кусок:
            time.sleep(0.01)
            return None
        self.буфер += кусок.decode("ascii", "replace")
        if len(self.буфер) > 8192:
            self.буфер = self.буфер[-4096:]
        сетка = tof.строками(self.буфер) if tof is not None else None
        if сетка is not None:
            self.буфер = ""
        return сетка


class ИзФайла:
    """Кадры из того, что выкладывает сам робот.

    Так пробник не отнимает порт. Раньше он его отнимал — и это не просто
    «ничего не видно»: две программы делят байты пополам, то есть проверка
    датчика ПОРТИЛА датчик ровно в тот момент, когда его проверяют.
    """

    откуда = "робот"
    УСТАРЕЛ = 3.0

    def __init__(self, путь: Path) -> None:
        self.путь = путь
        self.прошлое = 0.0

    def свежесть(self) -> float:
        """Сколько секунд назад робот обновлял файл. Минус — файла нет."""
        try:
            данные = json.loads(self.путь.read_text())
        except (OSError, ValueError):
            return -1.0
        return time.time() - float(данные.get("когда") or 0)

    def кадр(self):
        try:
            данные = json.loads(self.путь.read_text())
        except (OSError, ValueError):
            time.sleep(0.05)
            return None
        когда = float(данные.get("когда") or 0)
        if когда <= self.прошлое:
            time.sleep(0.02)          # нового кадра ещё нет
            return None
        self.прошлое = когда
        сетка = данные.get("сетка")
        if not (isinstance(сетка, list) and len(сетка) == 8):
            return None
        return сетка


def кадры_подряд(источник, сколько: int, срок: float = 30.0):
    """Собрать сколько-то разобранных кадров подряд."""
    собрано = []
    предел = time.monotonic() + срок
    while len(собрано) < сколько and time.monotonic() < предел:
        сетка = источник.кадр()
        if сетка is not None:
            собрано.append(сетка)
    return собрано


def показать_зоны(зоны: dict) -> None:
    """Сетка с расстояниями там, где зона попала в список.

    Печатать одно только число («неподвижных зон: 17») мало: по нему не
    видно, колонка это с краю или пятно посередине, а именно это и решает,
    железо перед нами или комната. Один взгляд на сетку отвечает сразу.
    """
    for р in range(8):
        строка = "".join(f"[{зоны[(р, к)]:4.2f}]" if (р, к) in зоны
                         else "  .   " for к in range(8))
        print(f"  y{р}: {строка}")


def записать_своих(источник, порт_имя: str = "") -> int:
    """Запомнить зоны, которые смотрят в сам робот.

    Два замера с поворотом между ними, и это не занудство. Первый признак
    своей детали — неподвижность вблизи, но стена сбоку неподвижна ровно так
    же. А пометить стену «своей деталью» значит велеть роботу её не замечать:
    ошибка, которую не видно ничем — он не тормозит, ни на что не жалуется,
    просто однажды едет в стену.

    Своё железо повёрнуто вместе с датчиком и после поворота осталось на том
    же расстоянии. Комната — нет. Разделить их иначе изнутри нельзя.
    """
    print("\nЗАМЕР ПЕРВЫЙ. Освободи перед роботом метра полтора и ничего")
    print("не двигай: я ищу то, что НЕ шевелится. Четыре секунды.\n")
    первые = кадры_подряд(источник, 40)
    if len(первые) < 20:
        print(f"Кадров пришло всего {len(первые)} — записывать не по чему.")
        пожаловаться_на_тишину(порт_имя)
        return 1
    видно = tof._постоянные(первые)
    if not видно:
        print("Неподвижных зон вблизи нет. Датчик ни во что не упирается —")
        print("записывать нечего, и это хорошая новость.")
        return 0
    print(f"Неподвижных зон вблизи: {len(видно)}. Часть из них — робот,")
    print("часть — комната, и различить их можно только поворотом. Вот они:\n")
    показать_зоны(видно)

    print("ТЕПЕРЬ ПОВЕРНИ РОБОТА НА МЕСТЕ примерно на четверть оборота.")
    print("Можно рукой, можно с пульта — важно, чтобы он именно повернулся,")
    print("а не переехал. Своё железо повернётся вместе с ним, комната нет.")
    input("\nПовернул — нажми Enter.")

    вторые = кадры_подряд(источник, 40)
    if len(вторые) < 20:
        print(f"Во второй раз кадров всего {len(вторые)}. Не записал.")
        пожаловаться_на_тишину(порт_имя)
        return 1
    свои = tof.свои_зоны(первые, вторые)
    if not свои:
        print("\nПосле поворота не осталось ни одной зоны. Два прочтения:")
        print("  — датчик ни во что не упирается, всё виденное было комнатой;")
        print("  — датчик не закреплён на роботе, и поворот его не повернул.")
        print("Второе тоже даёт этот ответ, и отличить их отсюда нельзя.")
        print("Записывать нечего.")
        return 0

    print(f"\nСвоими деталями оказались {len(свои)} зон из 64 "
          f"(из {len(видно)} неподвижных):\n")
    показать_зоны({з: видно[з] for з in свои})
    куда = tof.сохранить_своих(свои)
    print(f"\nЗаписал в {куда}. Эти зоны робот больше не считает.")
    print("Если тут оказалась стена — сотри файл и повтори:")
    print("незамеченная стена хуже лишнего стопа.")
    return 0


def лесенкой(кадры: list) -> bool:
    """Идут ли ряды лесенкой по дальности — признак верно читаемой сетки.

    У датчика, наклонённого вниз, нижний ряд бьёт в пол ближе всего, соседний
    дальше, следующий ещё дальше. Это геометрия, и подделать её нечем: если бы
    сетка читалась поперёк, лесенка шла бы по колонкам, а по рядам её бы не
    было. Поэтому наличие лесенки — прямое доказательство, что ряды это ряды.

    Считаем по медианам живых замеров в ряду, чтобы одиночный промах не решал.
    """
    if not кадры:
        return False
    медианы = []
    for р in range(8):
        свои = sorted(с[р][к] for с in кадры for к in range(8) if с[р][к] > 0)
        медианы.append(свои[len(свои) // 2] if len(свои) >= len(кадры) else 0.0)
    низ = [м for м in медианы[4:] if м > 0]
    # Лесенка должна быть видна хотя бы на трёх рядах подряд и расти книзу
    # заметно — не на сантиметр, а в полтора раза от края до края.
    if len(низ) < 3:
        return False
    по_убыванию = all(a >= b for a, b in zip(низ, низ[1:]))
    return по_убыванию and низ[0] >= низ[-1] * 1.5


def как_видит_робот(кадры: list) -> tuple[list, str]:
    """Развернуть кадры ровно так, как их разворачивает робот.

    Пробник читает сырой поток, а робот перед всеми решениями прикладывает к
    нему три галки из пульта и своё автоопределение разворота. Считать обрыв
    по сырой сетке значит считать его не по той сетке, по которой считает
    робот, — то есть получить ответ на другой вопрос и поверить ему.
    """
    зеркало, вверхногами, поперёк = tof.как_лежит()
    готово = []
    for сырая in кадры:
        сетка = ([list(к) for к in zip(*сырая)] if поперёк else
                 [ряд[:] for ряд in сырая])
        if вверхногами:
            сетка = сетка[::-1]
        if зеркало:
            сетка = [ряд[::-1] for ряд in сетка]
        готово.append(сетка)
    галки = (f"поперёк={'да' if поперёк else 'нет'}, "
             f"зеркало={'да' if зеркало else 'нет'}, "
             f"вверхногами={'да' if вверхногами else 'нет'}")

    # Автоопределение разворота — поверх галок, как и у робота.
    решение = tof.куда_смотрит(готово[:tof.РАЗВОРОТ_КАДРОВ])
    if решение is None:
        return готово, галки + "; где верх — не разобрал"
    if решение:
        готово = [сетка[::-1] for сетка in готово]
    return готово, галки + f"; ряды перевёрнуты={'да' if решение else 'нет'}"


def объявил_бы_обрыв(кадры: list) -> None:
    """Прогнать НАСТОЯЩЕЕ правило обрыва по снятым кадрам.

    ВОТ РАДИ ЧЕГО СТОИТ СНИМАТЬ КАРТУ. Всё остальное в этом режиме — доли
    молчания, полосы, советы про наклон — это признаки, по которым человек (и
    я) гадаем, доволен ли робот сценой. А тут гадать нечего: берётся тот же
    класс tof.Пол, тем же способом учится норма, и по тем же кадрам считается,
    сколько раз робот сказал бы «дальше пола нет» и по каким именно зонам.

    Появилось это после того, как я дважды подряд поставил диагноз по форме
    карты и дважды ошибся. Один раз объявил ровный пол деталью робота — Игорь
    поднял робота в воздух, пол пропал, и стало видно, что это был пол. Другой
    раз посчитал вероятность ложного обрыва в два процента и тут же напечатал
    вывод, этой самой вероятности противоречащий.

    Форма карты — слабое свидетельство. Прогон правила — сильное.
    """
    if tof is None:
        return
    print("\n--- А объявил бы робот обрыв на этой сцене? ---\n")
    развёрнутые, ориентация = как_видит_робот(кадры)
    print(f"Ориентация: {ориентация}")
    if len(развёрнутые) <= tof.УЧИТЬ_КАДРОВ:
        print(f"Кадров мало: норма учится по {tof.УЧИТЬ_КАДРОВ}, а снято "
              f"{len(развёрнутые)}. Возьми --карта подольше.")
        return

    # Норму учим В ОТДЕЛЬНЫЙ ФАЙЛ. Настоящую трогать нельзя: робот запоминает
    # пол один раз, и подменить его замером из-под пробника — это ровно тот
    # способ сломать защиту от лестницы, от которого весь файл и написан.
    времянка = Path("/tmp") / f"tof_floor_probe_{os.getpid()}.json"
    пол = tof.Пол(времянка)
    for сетка in развёрнутые[:tof.УЧИТЬ_КАДРОВ]:
        пол.учить(сетка)
    времянка.unlink(missing_ok=True)

    if пол.норма is None:
        print("НОРМУ ПОЛА РОБОТ БЫ НЕ ПРИНЯЛ — и это уже ответ.")
        print("Без нормы обрыв не ищется вовсе: робот едет без защиты от")
        print("ступеньки. Причина напечатана выше в предупреждении, а лечение")
        print("одно и то же — наклон датчика вниз на 15-20 градусов.")
        return

    # Порог берём У САМОГО ПОЛА, а не константой: он считается из измеренного
    # шума этого датчика при обучении, и печатать тут другое число значило бы
    # объяснять человеку решение, которого робот не принимал.
    порог_зон = getattr(пол, "порог_зон", tof.ОБРЫВ_ЗОН)
    зоны = [(р, к) for р in tof.ОБРЫВ_РЯДЫ for к in range(8)
            if пол.норма[р][к] > tof.НЕ_ИЗМЕРИЛ]
    метры = sorted(пол.норма[р][к] for р, к in зоны)
    print(f"Норма пола: {len(зоны)} зон из {len(tof.ОБРЫВ_РЯДЫ) * 8}, "
          f"медиана {метры[len(метры) // 2]:.2f} м "
          f"(от {метры[0]:.2f} до {метры[-1]:.2f}); "
          f"обрыв робот объявит от {порог_зон} зон")

    молчали = {з: 0 for з in зоны}
    ушли = {з: 0 for з in зоны}
    обрывов = подряд = дольше_всего = 0
    проверено = развёрнутые[tof.УЧИТЬ_КАДРОВ:]
    for сетка in проверено:
        сколько = пол.обрыв(сетка)
        if сколько >= порог_зон:
            обрывов += 1
            подряд += 1
            дольше_всего = max(дольше_всего, подряд)
        else:
            подряд = 0
        for р, к in зоны:
            замер = сетка[р][к]
            if замер <= tof.НЕ_ИЗМЕРИЛ:
                молчали[(р, к)] += 1
            elif замер > пол.норма[р][к] * tof.ОБРЫВ_ДАЛЬШЕ:
                ушли[(р, к)] += 1

    доля = 100 * обрывов / len(проверено)
    print(f"Обрыв (порог {порог_зон} зоны) в {обрывов} кадрах из "
          f"{len(проверено)} — {доля:.0f}%, подряд до {дольше_всего}")

    виноваты = [з for з in sorted(зоны, key=lambda з: -(молчали[з] + ушли[з]))
                if молчали[з] + ушли[з]][:5]
    if виноваты:
        print("\nЧаще всех кричат про обрыв:")
        for р, к in виноваты:
            print(f"  y{р} к{к}: норма {пол.норма[р][к]:.2f} м, "
                  f"молчит {100 * молчали[(р, к)] / len(проверено):3.0f}%, "
                  f"ушла дальше {100 * ушли[(р, к)] / len(проверено):3.0f}%")

    if доля < 5:
        print("\nЭто мало: на такой сцене робот бы ехал. Значит застревает он")
        print("НЕ ЗДЕСЬ — снимай карту там, где он встал, и не двигая его.")
    elif all(молчали[з] >= ушли[з] for з in виноваты):
        print("\nЗоны МОЛЧАТ, а не «видят дальше». Пропавший замер считается")
        print("обрывом отдельно, и порог ОБРЫВ_ДАЛЬШЕ его не смягчает: за")
        print("краем ступеньки луч тоже не возвращается. Значит дело не в")
        print("пороге, а в том, что эти зоны перестали ловить пол. Так бывает")
        print("от трёх причин: норма снята в другой позе (робот с тех пор")
        print("повернулся или наехал на порожек), под лучом тёмный ковёр, или")
        print("датчик наведён так полого, что луч скользит по полу.")
        print("Различить: сними карту ещё раз, не трогая робота. Повторится")
        print("тот же список зон — дело в наведении, другой — в позе.")
    else:
        print("\nЗоны видят пол ДАЛЬШЕ нормы. Это либо настоящая ступенька")
        print("перед роботом, либо тележка задрала нос — при базе 19.5 см")
        print("подъём передних колёс на 17 мм даёт крен в пять градусов.")


def карта_отказов(источник, секунд: float, порт_имя: str = "") -> int:
    """Доля кадров, где зона промолчала, — по каждой из 64 зон.

    Главный диагностический приём из разведки, и он отвечает на вопрос,
    который не решается разглядыванием отдельных кадров: молчащие зоны идут
    ПОЛОСАМИ или рассыпаны?

    Полосы по рядам — геометрия наклона: нижние ряды бьют в пол под
    скользящим углом и теряют сигнал, верхние уходят дальше предела дальности.
    Это не поломка, это физика, и чинится наклоном.

    Одни и те же одиночные зоны при любой сцене — дефект или паразитная
    засветка. Случайное мигание — на пределе сигнала: тёмная поверхность,
    солнце в окно, слишком мало времени накопления.

    Три разных ответа с тремя разными лечениями, и по одному кадру они
    неразличимы.
    """
    print(f"\nСнимаю {секунд:.0f} с. Стой смирно и ничем не маши: карта")
    print("должна показать сцену, а не твою руку.\n")
    промолчала = [[0] * 8 for _ in range(8)]
    # Кадры держим целиком, а не только счётчики молчания: по ним в конце
    # прогоняется настоящее правило обрыва. Триста кадров по 64 числа — это
    # полтораста килобайт, а ответ они дают тот, ради которого всё.
    снято: list = []
    кадров = 0
    срок = time.monotonic() + секунд
    молчит_до = time.monotonic() + 3.0
    while time.monotonic() < срок:
        if not кадров and time.monotonic() > молчит_до:
            пожаловаться_на_тишину(порт_имя, БЫЛО_СВОБОДНО[0])
            return 1
        сетка = источник.кадр()
        if сетка is None:
            continue
        кадров += 1
        снято.append([ряд[:] for ряд in сетка])
        for р in range(8):
            for к in range(8):
                if сетка[р][к] <= 0:
                    промолчала[р][к] += 1
    if not кадров:
        пожаловаться_на_тишину(порт_имя, БЫЛО_СВОБОДНО[0])
        return 1

    print(f"Кадров: {кадров}. Доля молчания по зонам, в процентах:\n")
    по_рядам = []
    for р in range(8):
        доли = [100 * промолчала[р][к] / кадров for к in range(8)]
        по_рядам.append(sum(доли) / 8)
        print(f"  y{р}: " + " ".join(f"{д:3.0f}" for д in доли)
              + f"   ряд в среднем {по_рядам[-1]:3.0f}%")
    по_колонкам = [sum(100 * промолчала[р][к] / кадров for р in range(8)) / 8
                   for к in range(8)]
    print("  ---  " + " ".join(f"{д:3.0f}" for д in по_колонкам)
          + "   колонка в среднем")

    # Читаем карту за человека: разброс по рядам против разброса по колонкам
    # говорит, полосатая она или нет.
    размах = lambda з: max(з) - min(з)          # noqa: E731 — короче некуда
    всего = sum(sum(р) for р in промолчала) / (64 * кадров) * 100
    print(f"\nМолчит в среднем {всего:.0f}% зон.")
    # СНАЧАЛА СМОТРИМ ПО ВЫСОТЕ, а не по размаху. Размах обманул на живых
    # данных: он был велик и по рядам (87), и по колонкам (72), ни одно
    # правило не сработало, и пробник объявил «отказы рассыпаны» там, где
    # картина была совершенно ясной:
    #
    #     y0  87%  █████████████████████
    #     y6  53%  █████████████
    #     y7   0%
    #
    # Нижний ряд отвечает полностью, верхний почти нет. Это не россыпь, это
    # наклон: ряды разложены по вертикали, нижние бьют в пол в полуметре и
    # получают отражение, верхние уходят в комнату, где до трёх метров
    # отражать нечему. Половина зон и ДОЛЖНА молчать.
    #
    # Различать надо не «есть ли полосы», а КУДА смотрит живая половина.
    # СЧИТАЕМ ПО ТЕМ ЖЕ РЯДАМ, ЧТО И РОБОТ, а не по половине сетки. Первая
    # редакция брала «нижнюю половину», ряды 4-7, и на живых данных выдала
    # «молчат 47%, наклони круче» — совет неверный и опасный.
    #
    # Неверный потому, что полом заняты не четыре ряда, а два. Ряд 5 смотрит
    # вниз всего на 7°, то есть в пол за метр, ряд 4 — вовсе горизонтально;
    # они молчат по делу, и подмешивать их в счёт значит портить число.
    #
    #     ряды 4-7: (59+77+51+0)/4 = 47%   «многовато»
    #     ряды 6-7: (51+ 0)/2      = 26%   совсем другой разговор
    #
    # А опасный потому, что по этому совету человек наклонит датчик круче, и
    # тогда пол уедет ещё ближе — робот перестанет видеть то, что перед ним,
    # ради зон, которые и так работали.
    полом_заняты = tuple(getattr(tof, "ОБРЫВ_РЯДЫ", (6, 7)))
    низ = sum(по_рядам[р] for р in полом_заняты) / len(полом_заняты)
    верх = sum(по_рядам[:4]) / 4
    if низ + 15 < верх:
        print("Молчит В ОСНОВНОМ ВЕРХ, низ отвечает — так и должно быть.")
        print(f"Нижние ряды молчат {низ:.0f}%, верхние {верх:.0f}%.")
        print("Датчик наклонён вниз: нижние ряды бьют в пол в полуметре и")
        print("получают отражение, верхние уходят в комнату, где до предела")
        print("дальности отражать нечему. Это геометрия, а не поломка, и")
        print("общий процент молчания тут ни о чём не говорит.")
        print()
        ряды_словом = ", ".join(f"y{р}" for р in полом_заняты)
        print(f"Смотреть надо на ряды {ряды_словом} — по ним робот ищет обрыв.")
        print(f"Сейчас они молчат {низ:.0f}% — "
              + ("это хорошо." if низ < 35 else
                 "многовато. Но прежде чем крутить кронштейн, посмотри "
                 "метры: --смотреть."))
        # ПОДОЗРИТЕЛЬНО РОВНЫЙ НИЖНИЙ РЯД — отдельный случай, и о нём надо
        # сказать. Ряд, который отвечает ВСЕГДА и во всех восьми зонах, чаще
        # видит не пол, а деталь самого робота: кронштейн, провод, край
        # платформы. Пол на краях сетки уходит вбок и хоть иногда молчит.
        самый_нижний = по_рядам[полом_заняты[-1]]
        if самый_нижний < 2 and низ > 20:
            print()
            print(f"Но ряд y{полом_заняты[-1]} отвечает ВСЕГДА, во всех восьми")
            print("зонах, а соседний молчит наполовину. Так себя ведёт не пол,")
            print("а близкая деталь: кронштейн, провод, край платформы. Пол на")
            print("краях сетки уходит вбок и хоть иногда пропадает.")
            print("Проверить: --смотреть. Если там 0.15-0.25 м и число не")
            print("меняется, когда робот едет, — это он сам. Лечится: --свои")
    elif верх + 15 < низ:
        print("Молчит В ОСНОВНОМ НИЗ, а верх отвечает — вот это плохо.")
        print(f"Нижние ряды молчат {низ:.0f}%, верхние {верх:.0f}%.")
        print("По нижним рядам робот ищет обрыв, и если они молчат, он либо")
        print("не увидит ступеньку, либо объявит обрыв на ровном полу.")
        print("Скорее всего датчик смотрит слишком горизонтально или вверх —")
        print("наклони его вниз на 15-20 градусов.")
    elif лесенкой(снято):
        # СПЕРВА СМОТРИМ, ЕСТЬ ЛИ ЛЕСЕНКА, и только потом подозреваем разворот
        # сетки. Прежняя редакция советовала «поперёк» первым делом — и на
        # живом кадре Игоря советовала зря: ряды у него шли идеальной
        # лесенкой (y7 — 0.35, y6 — 0.41, y3-5 — стена в метре), то есть
        # сетка читалась ровно правильно, а полосы по колонкам были дверным
        # проёмом справа. Совет крутить галку в этой ситуации — это совет
        # сломать то, что работает.
        print("Отказы лежат полосами по колонкам, но сетка читается ПРАВИЛЬНО.")
        print("Видно по рядам: нижние меряют пол ближе, соседние — дальше,")
        print("верхние уходят в комнату. Такая лесенка бывает только когда")
        print("ряды и правда ряды; будь сетка развёрнута поперёк, лесенка шла")
        print("бы по колонкам, а по рядам её бы не было вовсе.")
        print()
        print("Значит колонки молчат ПО ДЕЛУ: с той стороны дальше, чем видит")
        print("датчик. Дверной проём, конец коридора, окно. Проверяется")
        print("поворотом робота на месте: полоса должна уехать вместе со")
        print("сценой, а не остаться на тех же колонках.")
    elif размах(по_колонкам) > 40 and размах(по_колонкам) > 2 * размах(по_рядам):
        print("Отказы лежат ПОЛОСАМИ ПО КОЛОНКАМ, и это подозрительно.")
        print("Наклон датчика разложен по РЯДАМ: вниз смотрят нижние, вверх")
        print("верхние. Колонки же смотрят вбок, и повода отказывать полосой")
        print("у них нет. Два объяснения, и первое вероятнее:")
        print()
        print("  1. СЕТКА ЧИТАЕТСЯ ПОПЕРЁК. Плата подписывает строки «y0:…»,")
        print("     и что такое y — строка или колонка — нигде не сказано.")
        print("     Если колонка, то наши «колонки» на деле ряды, и полосы")
        print("     сразу становятся геометрией: живые — пол под роботом,")
        print("     молчащие — комната дальше предела дальности.")
        print("     Проверка: галка «поперёк» в пульте. Должно стать так, что")
        print("     нижние ряды меряют устойчиво, верхние молчат.")
        print()
        print("  2. Что-то сбоку: окно с солнцем, лампа, деталь робота.")
        print("     Проверка: тот же замер, зашторив окно.")
    else:
        print("Отказы рассыпаны, полос нет. Похоже на предел сигнала:")
        print("тёмные поверхности, засветка, мало времени накопления.")
        print("Проверяется темнотой: тот же замер ночью при выключенном свете.")

    объявил_бы_обрыв(снято)
    return 0


def сменить_режим(fd: int, разрешение: int) -> int:
    """Переключить сетку на 8×8 или 4×4 — кадром, взятым из кода вендора.

    Это НЕ слепой перебор, которым я однажды подвесил плату. Тот кадр был
    синтаксически неверен: длину я считал без команды, а разрешение слал
    первым аргументом вместо четвёртого. Прошивка дочитывала недостающие
    байты из начала следующего пакета. Здесь кадр совпадает с тем, что шлёт
    библиотека DFRobot, байт в байт.

    Зачем это может понадобиться: 8×8 делит один и тот же свет на вчетверо
    большее число зон, поэтому в трудных условиях 4×4 видит там, где 8×8
    молчит. И наоборот — если плата почему-то осталась в 4×4, половина
    сетки будет пустой всегда.
    """
    if tof is None:
        print("Нет модуля robot_voice.", file=sys.stderr)
        return 1
    кадр = tof._кадр(tof.CMD_CONFIG, tof.аргументы_режима(разрешение))
    print(f"\nШлю смену разрешения на {разрешение}×{разрешение}:")
    print(f"  {кадр.hex(' ')}")
    print("  (в точности то, что шлёт библиотека DFRobot)")
    os.write(fd, кадр)
    показать(почитать(fd, 1.0), "ответ")
    print(f"\nЖду {tof.ПОСЛЕ_СМЕНЫ_РЕЖИМА:.0f} с — столько плата "
          "перенастраивается и молчит.")
    time.sleep(tof.ПОСЛЕ_СМЕНЫ_РЕЖИМА)
    источник = ИзПорта(fd)
    кадры = кадры_подряд(источник, 10, срок=10.0)
    if not кадры:
        print("После смены плата молчит. Передёрни USB.")
        return 1
    живых = [sum(1 for ряд in к for м in ряд if м > 0) for к in кадры]
    print(f"Пришло {len(кадры)} кадров, живых зон: "
          f"{min(живых)}–{max(живых)} из 64.")
    сеткой(кадры[-1], "  ")
    return 0


def смотреть(источник, секунд: float, порт_имя: str = "") -> None:
    """Живой показ сетки: помаши рукой и увидишь, что он меряет.

    Ради этого режима пробник и стоит запускать второй раз. Дамп байтов
    отвечает на вопрос «каким протоколом плата говорит», а он был последним
    только до первого запуска. Теперь вопрос другой и куда важнее: КУДА
    ЭТА ПЛАТА СМОТРИТ, привинченная к роботу. На него не отвечает ни один
    протокол — только собственные глаза человека рядом с рукой перед
    датчиком.
    """
    print(f"\nсмотрю {секунд:.0f} с. Помаши рукой перед датчиком — цифры")
    print("должны падать. Ноль (—) значит «не измерил»: далеко, темно,")
    print("стекло. Выйти раньше — Ctrl+C.\n")
    срок = time.monotonic() + секунд
    # Жаловаться на тишину надо быстро. Двадцать секунд перед пустым экраном
    # человек тратит на догадки о железе, а причина обычно в другом.
    молчит_до = time.monotonic() + 3.0
    кадров = 0
    while time.monotonic() < срок:
        if not кадров and time.monotonic() > молчит_до:
            пожаловаться_на_тишину(порт_имя, БЫЛО_СВОБОДНО[0])
            return
        сетка = источник.кадр()
        if сетка is None:
            continue
        кадров += 1
        if кадров % 5:              # десять кадров в секунду глазами не читаются
            continue
        близко = sum(1 for р in range(2, 6) for к in range(8)
                     if 0 < сетка[р][к] < tof.СТОП_БЛИЖЕ)
        пусто = sum(1 for ряд in сетка for м in ряд if м <= 0)
        print(f"--- кадр {кадров}: зон ближе {tof.СТОП_БЛИЖЕ:.2f} м — "
              f"{близко}, не измерено — {пусто} из 64")
        сеткой(сетка, "  ")


def выбрать_порт(явный: str) -> str:
    if явный:
        return явный
    if tof is not None:
        найдено = tof.найти_устройство()
        if найдено:
            return найдено
    # Резервный поиск, если модуль робота не подключился.
    import glob
    for образец in ("*Raspberry_Pi_Pico*", "*RP2040*", "*DFRobot*"):
        нашлось = sorted(glob.glob(f"/dev/serial/by-id/usb-{образец}-if00"))
        if нашлось:
            return нашлось[0]
    return ""


def опасен(путь: str) -> bool:
    """Не приводы ли это. Слать в моторы случайные байты нельзя."""
    имя = os.path.realpath(путь).lower()
    ссылка = путь.lower()
    return any(плохо in ссылка or плохо in имя for плохо in ОПАСНЫЕ)


def главное() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--порт", default="", help="явный путь к устройству")
    р.add_argument("--слушать", action="store_true",
                   help="ничего не спрашивать, просто слушать три секунды")
    р.add_argument("--смотреть", nargs="?", type=float, const=20.0,
                   default=0.0, metavar="СЕКУНД",
                   help="живой показ сетки в метрах (по умолчанию 20 с)")
    р.add_argument("--команды", action="store_true",
                   help="ОПАСНО: слать плате двоичные команды вслепую. "
                        "Одна из них уже выключила плате автоотдачу, и "
                        "состояние пережило перезапуск сервиса.")
    р.add_argument("--карта", nargs="?", type=float, const=30.0,
                   default=0.0, metavar="СЕКУНД",
                   help="карта отказов: где сетка молчит чаще всего")
    р.add_argument("--режим", type=int, choices=(4, 8), default=0,
                   help="переключить сетку на 4×4 или 8×8 (кадр вендора)")
    р.add_argument("--свои", action="store_true",
                   help="запомнить зоны, смотрящие в сам робот "
                        "(освободи место перед ним)")
    аргс = р.parse_args()

    # Первым делом — не отнимать порт у робота. Раньше пробник открывал его
    # всегда, и при живом сервисе они делили байты пополам: проверка датчика
    # ПОРТИЛА датчик ровно в тот момент, когда его проверяют. Теперь, если
    # сервис жив и выкладывает сетку, смотрим её, а порт не трогаем вовсе.
    # Всё, что только СМОТРИТ, берём через окно робота и порт не трогаем.
    # Смена режима сюда не входит: она пишет в плату, а писать может только
    # владелец порта.
    if аргс.смотреть or аргс.свои or аргс.карта:
        файл = ИзФайла(Path.home() / ".robot-ai" / "tof_last.json")
        свежесть = файл.свежесть()
        путь = выбрать_порт(аргс.порт)
        держат = кто_держит(путь) if путь else []
        if держат and 0 <= свежесть <= ИзФайла.УСТАРЕЛ:
            кто = ", ".join(f"{имя} ({pid})" for pid, имя in держат)
            print(f"смотрю глазами самого робота: порт держит {кто}, "
                  f"сетке {свежесть:.1f} с.")
            if аргс.карта:
                return карта_отказов(файл, аргс.карта, "")
            if аргс.свои:
                return записать_своих(файл, "")
            try:
                смотреть(файл, аргс.смотреть, "")
            except KeyboardInterrupt:
                print("\nхватит.")
            return 0
        if держат:
            # Порт занят, а сетки нет. Открывать его всё равно нельзя: байты
            # разделятся пополам, и станет хуже обоим.
            кто = ", ".join(f"{имя} ({pid})" for pid, имя in держат)
            print(f"Порт держит {кто}, а сетку никто не выкладывает "
                  + ("(файла нет)." if свежесть < 0
                     else f"(последняя {свежесть:.0f} с назад)."))
            print("Похоже, служба старой версии. Обнови и перезапусти:")
            print(f"    git pull && sudo systemctl restart {СЕРВИС}")
            print("Что она сама говорит про дальномер:")
            print(f"    journalctl -u {СЕРВИС} -n 100 --no-pager | grep -i дальномер")
            return 1
        if соперник(""):
            # Служба запущена, но порт НЕ держит — значит дальномер внутри неё
            # не поднялся. Порт свободен, замерить можно, а вот роботу сейчас
            # датчик не служит, и сказать об этом важнее самого замера.
            print(f"Служба {СЕРВИС} запущена, но порт не держит — значит "
                  "дальномер у неё не поднялся.")
            print("Робот сейчас едет без датчика. Почему — здесь:")
            print(f"    journalctl -u {СЕРВИС} -n 100 --no-pager | grep -i дальномер")
            print("\nПорт свободен, поэтому смотрю напрямую.\n")
            БЫЛО_СВОБОДНО[0] = True

    порт = выбрать_порт(аргс.порт)
    if not порт:
        print("Дальномер не найден. Посмотри, что есть:", file=sys.stderr)
        print("    ls -l /dev/serial/by-id/", file=sys.stderr)
        print("и запусти с --порт /dev/serial/by-id/<то, что похоже на плату>",
              file=sys.stderr)
        return 1
    if опасен(порт) and not аргс.порт:
        print(f"{порт} похож на контроллер приводов — не трогаю.", file=sys.stderr)
        return 1

    print(f"порт: {порт}")
    print(f"      → {os.path.realpath(порт)}")
    try:
        fd = открыть(порт)
    except OSError as e:
        print(f"не открылся: {e}", file=sys.stderr)
        if e.errno == 13:
            print("Нет прав. Лечится: sudo usermod -aG dialout $USER "
                  "и перезаход в систему.", file=sys.stderr)
        return 1

    try:
        if аргс.карта:
            файл = ИзФайла(Path.home() / ".robot-ai" / "tof_last.json")
            if держат and 0 <= файл.свежесть() <= ИзФайла.УСТАРЕЛ:
                return карта_отказов(файл, аргс.карта, "")
        if аргс.режим:
            return сменить_режим(fd, аргс.режим)
        if аргс.карта:
            try:
                return карта_отказов(ИзПорта(fd), аргс.карта, порт)
            except KeyboardInterrupt:
                print("\nхватит.")
                return 0
        if аргс.свои:
            if tof is None:
                print("Нет модуля robot_voice — запусти из каталога репозитория.",
                      file=sys.stderr)
                return 1
            return записать_своих(ИзПорта(fd), порт)
        if аргс.смотреть:
            try:
                смотреть(ИзПорта(fd), аргс.смотреть, порт)
            except KeyboardInterrupt:
                print("\nхватит.")
            return 0
        if аргс.слушать:
            print("\nслушаю три секунды, ничего не спрашивая...")
            услышал = почитать(fd, 3.0)
            показать(услышал, "само пришло")
            if not услышал:
                пожаловаться_на_тишину(порт)
            return 0

        # Сначала просто послушаем: вдруг плата сыплет сама.
        print("\n1. молчим полсекунды — не сыплет ли сама")
        первое = почитать(fd, 0.5)
        показать(первое, "без запроса")
        if not первое:
            # Эта плата сыплет строки сама и без запроса молчать не должна.
            # Значит либо порт уже кем-то читается, либо плата не питается —
            # и перебирать после этого команды бессмысленно: ответа не будет
            # ни на одну, а человек проведёт минуту, глядя на семь «тишина»
            # подряд и думая, что сломался протокол.
            пожаловаться_на_тишину(порт)
            return 1

        if not аргс.команды:
            print("\nПлата отвечает. Команды вслепую не шлю — см. --команды.")
            return 0

        # Перебор команд. Оставлен, но по явной просьбе: см. предупреждение
        # в разборе аргументов.
        print("\n2. перебираю команды")
        for cmd, args, подпись in (
            (0x01, bytes([0x08]), "0x01 + 8 (настроить сетку 8×8)"),
            (0x01, bytes([0x04]), "0x01 + 4 (настроить сетку 4×4)"),
            (0x02, b"", "0x02 (все данные)"),
            (0x03, b"", "0x03"),
            (0x04, b"", "0x04"),
            (0x05, b"", "0x05"),
        ):
            os.write(fd, собрать(cmd, args))
            показать(почитать(fd, 0.3), подпись)

        # И ещё раз «все данные» — уже после настройки.
        print("\n3. ещё раз все данные, после настройки")
        os.write(fd, собрать(0x02))
        показать(почитать(fd, 0.5), "0x02 повторно")
    finally:
        os.close(fd)

    print("\nЧто дальше: пришли этот вывод целиком. Если хоть где-то написано")
    print("«РАЗОБРАЛОСЬ» и цифры похожи на расстояния в метрах — протокол")
    print("угадан и драйвер заработает как есть.")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
