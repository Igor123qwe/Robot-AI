#!/usr/bin/env python3
"""Пробник дальномера: показать, что плата отвечает на самом деле.

Зачем он нужен. Протокол SEN0628 собран по исходникам библиотеки DFRobot, а
не снят с живой платы: формат кадра там описан, а код команды переключения на
сетку 8×8 — нет. Догадка правдоподобная, но догадка. Проверять её вслепую,
правя драйвер и перезапуская робота, — долго и вслепую же.

Пробник ничего не чинит и никуда не встраивается. Он открывает порт, шлёт
несколько вариантов запроса и печатает ответ КАК ЕСТЬ, байтами. По этому
выводу протокол уточняется за пять минут.

ЗАПУСКАТЬ ИЗ КОРНЯ РЕПОЗИТОРИЯ И ПРИ ОСТАНОВЛЕННОЙ СЛУЖБЕ:

    sudo systemctl stop robot-voice
    cd ~/Robot-AI && python3 scripts/tof_probe.py --карта 30
    sudo systemctl start robot-voice

Обе строчки не для красоты. Из домашнего каталога скрипта просто нет —
«python3: can't open file '/home/wheeltec/scripts/tof_probe.py'». А порт
дальномера держит robot-voice, и второй читатель поделит байты пополам:
показания испортятся ровно в тот миг, когда их измеряют.

    python3 scripts/tof_probe.py --смотреть   # живая сетка в метрах
    python3 scripts/tof_probe.py --свои       # запомнить свои же детали
    python3 scripts/tof_probe.py              # найти сам, послушать
    python3 scripts/tof_probe.py --порт /dev/ttyACM0
    python3 scripts/tof_probe.py --слушать    # слушать три секунды

Команды плате БОЛЬШЕ НЕ ШЛЮТСЯ. Перебор 0x01…0x05 вслепую однажды уже
выключил плате автоотдачу — и состояние пережило перезапуск сервиса: драйвер
после этого решал «плата молчит», уходил в двоичный опрос и не получал
ничего. В журнале это выглядело как исправная служба, которая ничего не
видит. Слать команды, назначения которых не знаешь, устройству с собственной
памятью — так себе способ выяснять протокол, а протокол давно выяснен.
Осталось за флагом --команды, для другой прошивки.

Останавливать робота ради замера НЕ НАДО. Порт нельзя читать вдвоём — байты
делятся пополам, и проверка датчика портила бы датчик ровно в тот момент,
когда его проверяют. Поэтому владелец порта один, как и у камеры, а сетку он
выкладывает в ~/.robot-ai/tof_last.json. Режимы --смотреть и --свои читают
её оттуда, если сервис жив, и порт вообще не открывают.

Вопрос про протокол закрыт: эта плата сыплет строки «y0:…y7:» в миллиметрах
сама, без единой команды, и 4000 у неё означает «не измерил». Двоичный разбор
оставлен на случай другой прошивки.

Поэтому главный теперь режим — «--смотреть». Он отвечает на вопрос, на
который не отвечает ни один протокол: КУДА эта плата смотрит, привинченная к
роботу. Помаши рукой — цифры должны падать.

БЕЗОПАСНОСТЬ. На соседнем /dev/ttyACM* живёт контроллер приводов робота.
Слать в него байты нельзя: это команды моторам. Поэтому без --порт пробник
берёт устройство ТОЛЬКО по имени платы из /dev/serial/by-id и отказывается
работать, если имя не похоже на дальномер.
"""

