#!/usr/bin/env python3
"""Проверка достоверности САМОПРОВЕРКИ: ломаем защиту и смотрим, заметит ли она.

ЗАЧЕМ. Две тысячи проверок в voice/selftest.py говорят «Всё сошлось» — и это
приятно ровно до того мига, когда выясняется, что часть из них прошла бы и на
сломанном коде. Проверка, которую не видел падающей, не проверена.

Способ старый и простой: взять защитный механизм, СЛОМАТЬ его одной строкой и
прогнать самопроверку. Упала — механизм под присмотром. Прошла — механизм
работает молча и сломать его можно так же молча.

За одну ночь этот прогон нашёл четырнадцать таких мест, и вот несколько, чтобы
было видно, о чём речь:

  • вычитание своих зон дальномера из живого кадра (робот не должен видеть
    собственный кронштейн препятствием);
  • «на карту кладём только мебель» — предикат проверялся, послушание ему нет;
  • «стоп» гасил движителей только одним из двух путей;
  • условие «корпус низко» в стороже падений — без него робот кричал бы
    «человек упал» на всякого, кто прилёг с книжкой;
  • обе осторожности компаса, на котором держится вся карта.

КАК ПОЛЬЗОВАТЬСЯ

    python3 scripts/mutations.py              — весь список
    python3 scripts/mutations.py 3            — только третью цель
    python3 scripts/mutations.py --список     — что вообще проверяется

Один прогон самопроверки идёт около двух минут, так что весь список — это
полчаса. В CI он не стоит НАМЕРЕННО: там он съел бы время каждого коммита, а
пользы приносит не на каждом. Это инструмент для того, кто дописал защиту и
хочет знать, стережёт ли её кто-нибудь.

ЧЕСТНОСТЬ КАТАЛОГА. Мутации записаны кусками текста, и код под ними меняется.
Не нашёлся кусок — это НЕ «пропустим», это «каталог устарел», и прогон
сообщает об этом отдельной строкой и ненулевым кодом возврата. Молча
пропускать цель нельзя: список, половина которого не применяется, выглядит
работающим и не работает — то есть ровно та беда, ради которой он написан.
"""

