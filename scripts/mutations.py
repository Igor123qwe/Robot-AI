def чья_самопроверка(отн: str) -> str:
    """Какая самопроверка сторожит этот файл.

    Их две, и они не пересекаются: робот проверяется своей, ПК — своей. Пока
    здесь стояла одна, любая цель в pc/ выходила «мимо» — не потому, что
    защиты нет, а потому, что запускали не тот сторож. Та же история
    повторилась с face/scenes.py: файл лежит рядом с лицом робота, а
    исполняет его ПК, и сторожит его pc/selftest.py — шесть целей вышли
    «мимо» из-за одного этого выбора.
    """
    if отн.startswith("pc/") or отн in ("face/scenes.py", "face/lips.py",
                                        "face/director.py", "face/mood.py",
                                        "face/learn.py",
                                        "scripts/прогон_жизни.py"):
        # lips.py общий для робота и ПК; очередь фраз подробнее проверяет ПК.
        # director.py — режиссёр сценок, живёт на ПК: его сторож там же.
        # mood.py и learn.py — чистая арифметика настроения и обучения; их
        # числа гоняет pc/selftest.py вместе со сценками, которые они питают.
        return "pc/selftest.py"
    return "voice/selftest.py"


def прогнать_самопроверку(чем: str = "voice/selftest.py") -> tuple[list[str], bool]:
    """(упавшие проверки, рухнула ли целиком)."""
    вышло = subprocess.run([sys.executable, чем],
                           capture_output=True, text=True, cwd=КОРЕНЬ,
                           timeout=900)
    провалы = [с.strip() for с in вышло.stdout.splitlines()
               if с.strip().startswith("✗")]
    return провалы, вышло.returncode != 0 and not провалы


def проверить(номер: int) -> str:
    """Отдаёт «поймана», «мимо», «устарела» или «не тем»."""
    описание, отн, было, стало = ЦЕЛИ[номер][:4]
    # Пятым может стоять кусок имени проверки, которая ОБЯЗАНА упасть.
    # Необязательно, но там, где стоит, спрашивается строго: см. «не тем».
    ждём_проверку = ЦЕЛИ[номер][4] if len(ЦЕЛИ[номер]) > 4 else ""
    путь = КОРЕНЬ / отн
    исходное = путь.read_text(encoding="utf-8")
    if было not in исходное:
        print(f"  УСТАРЕЛА  {описание}\n"
              f"            в {отн} больше нет текста, который она ломает")
        return "устарела"
    # КУСОК ОБЯЗАН СОВПАДАТЬ РОВНО ОДИН РАЗ. Замена правит ПЕРВОЕ совпадение,
    # и цель с двусмысленным куском ломает не то, что написано в её названии.
    # Так «атлас: знакомые места берём и в стене» целый день ломала обход:
    # кусок совпадал и в `поле_до_неизведанного`, и тот шёл первым.
    сколько = исходное.count(было)
    if сколько > 1:
        print(f"  ДВУСМЫСЛЕННА  {описание}\n"
              f"            кусок встречается в {отн} {сколько} раза — "
              f"правится первое совпадение, а это может быть не та строка")
        return "устарела"
    # Подлинник — на диск ДО правки. finally ниже спасает от исключения и от
    # Ctrl-C, но не от SIGKILL и не от перезапуска машины: так уже осталась
    # мутация в рабочем дереве. См. ПОДЛИННИК.
    ПОДЛИННИК.write_text(json.dumps(
        {"файл": отн, "цель": описание, "текст": исходное},
        ensure_ascii=False), encoding="utf-8")
    try:
        путь.write_text(исходное.replace(было, стало, 1), encoding="utf-8")
        провалы, рухнула = прогнать_самопроверку(чья_самопроверка(отн))
    finally:
        # Восстанавливаем ВСЕГДА, даже если прогон рухнул или его прервали.
        путь.write_text(исходное, encoding="utf-8")
        ПОДЛИННИК.unlink(missing_ok=True)
    if провалы:
        # ПОЙМАНА — ЭТО МАЛО, НАДО «ПОЙМАНА ТЕМ, КЕМ ДОЛЖНА». Мутация ломает
        # одно, а падать могут соседи: «атлас: знакомые места берём и в стене»
        # роняла проверку про ПУСТУЮ карту, а названный сторож — «в занятое не
        # зовём» — молчал, потому что не мог сработать на той подделке в
        # принципе. Разница видна только по имени упавшей проверки.
        if ждём_проверку and not any(ждём_проверку in п for п in провалы):
            print(f"  НЕ ТЕМ    {описание}\n"
                  f"            упало {len(провалы)}, но среди них нет "
                  f"«{ждём_проверку}» — сторож, ради которого цель написана, "
                  f"промолчал")
            for п in провалы[:3]:
                print(f"            {п}")
            return "не тем"
        # ПЕЧАТАЕМ ПЯТЬ, А НЕ ДВЕ. Двух хватало, чтобы убедиться «поймана»,
        # но не хватало, чтобы понять КЕМ: разбирая прошлый прогон, я принял
        # за несовпадение то, что нужная проверка просто не влезла в вывод.
        # Судить о цели по обрезанному списку — это ровно та ошибка, которую
        # весь этот файл и ловит.
        print(f"  поймана   {описание}  ({len(провалы)})")
        for п in провалы[:5]:
            print(f"            {п}")
        if len(провалы) > 5:
            print(f"            ...и ещё {len(провалы) - 5}")
        return "поймана"
    if рухнула:
        # ПАДЕНИЕ — НЕ ПОИМКА. Оно говорит «стало плохо где-то», а не «сторож
        # заметил». Так целый день считалась пойманной цель, которая ломала
        # чужую функцию и валила прогон посторонним AttributeError.
        print(f"  УПАЛА     {описание}\n"
              f"            самопроверка не запустилась вовсе — это не поимка,"
              f" а поломка прогона: почини мутацию, чтобы она ломала защиту,"
              f" а не код вокруг")
        return "упала"
    print(f"  МИМО      {описание}\n"
          f"            защита сломана, а самопроверка этого не заметила")
    return "мимо"


def main() -> int:
    # ПЕРВЫМ ДЕЛОМ — прибрать за убитым прогоном. До перебора целей: иначе
    # первая же из них снимет «исходное» с уже сломанного файла и запишет
    # мутацию в подлинники.
    вернуть_недоделанное()
    доводы = sys.argv[1:]
    if "--список" in доводы or "--list" in доводы:
        for н, цель in enumerate(ЦЕЛИ):
            print(f"{н:3d}  {цель[0]}   ({цель[1]})")
        return 0
    # ВЫБОР ПО ИМЕНИ, А НЕ ТОЛЬКО ПО НОМЕРУ. Номера ползут от каждой вставки
    # в середину списка, и я уже гонял по ним не те цели: полчаса ушло на
    # проверку шести защит, которые и так были проверены.
    #
    #     python3 scripts/mutations.py --имя поиск:
    имена = [д for н, д in enumerate(доводы)
             if н and доводы[н - 1] in ("--имя", "--name")]
    номера = [н for н, цель in enumerate(ЦЕЛИ)
              if any(и.lower() in цель[0].lower() for и in имена)] if имена \
        else ([int(д) for д in доводы if д.isdigit()]
              or list(range(len(ЦЕЛИ))))
    if имена and not номера:
        print(f"по «{', '.join(имена)}» не нашлось ни одной цели")
        return 1
    print(f"Ломаю защиту {len(номера)} раз и смотрю, заметит ли самопроверка.")
    print("Один прогон — около двух минут.\n")
    итог = {"поймана": 0, "мимо": 0, "устарела": 0, "не тем": 0, "упала": 0}
    плохо: dict[str, list[str]] = {}
    for н in номера:
        исход = проверить(н)
        итог[исход] += 1
        if исход != "поймана":
            плохо.setdefault(исход, []).append(ЦЕЛИ[н][0])
    print(f"\nпоймано {итог['поймана']}, мимо {итог['мимо']}, "
          f"устарело {итог['устарела']}, не тем {итог['не тем']}, "
          f"упало {итог['упала']}")
    объяснения = {
        "мимо": "ЗАЩИТЫ БЕЗ СТРАЖА — их можно сломать, и никто не заметит:",
        "устарела": "УСТАРЕВШИЕ И ДВУСМЫСЛЕННЫЕ ЦЕЛИ — код под ними переписан\n"
                    "или кусок совпадает не в одном месте. Пока так, список\n"
                    "врёт о своём охвате:",
        "не тем": "ПОЙМАНЫ НЕ ТЕМ, КЕМ ДОЛЖНЫ — названный сторож промолчал,\n"
                  "а упали соседи. Либо подделка не даёт сторожу сработать,\n"
                  "либо цель ломает не то, что заявлено:",
        "упала": "ПРОГОН РУХНУЛ — мутация ломает код вокруг, а не защиту.\n"
                 "Падение не доказывает, что сторож есть:",
    }
    for исход, заголовок in объяснения.items():
        if плохо.get(исход):
            print(f"\n{заголовок}")
            for ц in плохо[исход]:
                print("   ", ц)
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
