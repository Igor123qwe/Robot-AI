# Куда кладём подлинник файла на время, пока он сломан.
#
# ЗАЧЕМ, ЕСЛИ ЕСТЬ finally. Потому что finally не выполняется, когда процесс
# убивают: SIGKILL, кончившаяся память, перезапуск машины. Это не выдумка для
# полноты — так и случилось: контейнер перезапустился ровно посреди прогона и
# оставил в `dog.py` применённую мутацию, то есть НАМЕРЕННО СЛОМАННЫЙ КОД в
# рабочем дереве. Заметить это можно было только по `git status`, а не заметив,
# легко закоммитить: правка выглядит как обычное удаление одной строки.
#
# Поэтому подлинник ложится на диск ДО правки и снимается ПОСЛЕ возврата. Файл
# на диске переживает то, чего не переживает finally, и следующий запуск
# начинается с проверки: лежит подлинник — значит прошлый прогон убили, чиним
# и говорим об этом вслух.
#
# И ОТМЕТКА СВОЯ У КАЖДОГО ПРОГОНА, что уже не педантизм.
#
# Была одна на всех, и вот что из этого вышло на живом дереве. Пока шёл прогон
# по десяти целям, я запустил рядом одиннадцатый — а тот первым делом чинит
# «недоделанное». Он увидел отметку ЖИВОГО соседа, вернул подлинник файла,
# который сосед в этот миг нарочно держал сломанным, и отметку стёр. Сосед
# доработал до конца и честно доложил, что защита поймана, — на файле, который
# ему починили посреди прогона.
#
# То есть один прогон молча портит результат другого, и оба выглядят
# исправными. Имя с номером процесса разводит их, а живого соседа видно по
# тому, что его номер ещё в системе.
ПОДЛИННИК = КОРЕНЬ / f".mutations-подлинник-{os.getpid()}.json"
ОТМЕТКИ = ".mutations-подлинник-*.json"


def _процесс_жив(номер: int) -> bool:
    """Работает ли ещё процесс с таким номером."""
    try:
        os.kill(номер, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True            # чужой, но живой
    return True


def вернуть_недоделанное() -> None:
    """Починить файлы, оставленные убитыми прогонами. Живых не трогаем."""
    for отметка in sorted(КОРЕНЬ.glob(ОТМЕТКИ)):
        номер = отметка.stem.rsplit("-", 1)[-1]
        if номер.isdigit() and номер != str(os.getpid()) \
                and _процесс_жив(int(номер)):
            # Сосед жив и работает — его мутация НАРОЧНАЯ, а не забытая.
            continue
        try:
            данные = json.loads(отметка.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            отметка.unlink(missing_ok=True)
            continue
        путь = КОРЕНЬ / данные["файл"]
        было = данные["текст"]
        try:
            если_сейчас = путь.read_text(encoding="utf-8")
        except OSError:
            если_сейчас = None
        if если_сейчас != было:
            путь.write_text(было, encoding="utf-8")
            print(f"ПРОШЛЫЙ ПРОГОН УБИЛИ: в {данные['файл']} осталась мутация "
                  f"«{данные['цель']}» — вернул подлинник.")
        отметка.unlink(missing_ok=True)

