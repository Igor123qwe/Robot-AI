def прогнать_самопроверку() -> tuple[list[str], bool]:
    """(упавшие проверки, рухнула ли целиком)."""
    вышло = subprocess.run([sys.executable, "voice/selftest.py"],
                           capture_output=True, text=True, cwd=КОРЕНЬ,
                           timeout=900)
    провалы = [с.strip() for с in вышло.stdout.splitlines()
               if с.strip().startswith("✗")]
    return провалы, вышло.returncode != 0 and not провалы


def проверить(номер: int) -> str:
    """Отдаёт «поймана», «мимо» или «устарела»."""
    описание, отн, было, стало = ЦЕЛИ[номер]
    путь = КОРЕНЬ / отн
    исходное = путь.read_text(encoding="utf-8")
    if было not in исходное:
        print(f"  УСТАРЕЛА  {описание}\n"
              f"            в {отн} больше нет текста, который она ломает")
        return "устарела"
    try:
        путь.write_text(исходное.replace(было, стало, 1), encoding="utf-8")
        провалы, рухнула = прогнать_самопроверку()
    finally:
        # Восстанавливаем ВСЕГДА, даже если прогон рухнул или его прервали.
        путь.write_text(исходное, encoding="utf-8")
    if провалы:
        print(f"  поймана   {описание}  ({len(провалы)})")
        for п in провалы[:2]:
            print(f"            {п}")
        return "поймана"
    if рухнула:
        print(f"  поймана   {описание}  (самопроверка не запустилась)")
        return "поймана"
    print(f"  МИМО      {описание}\n"
          f"            защита сломана, а самопроверка этого не заметила")
    return "мимо"


def main() -> int:
    доводы = sys.argv[1:]
    if "--список" in доводы or "--list" in доводы:
        for н, (описание, отн, _, _) in enumerate(ЦЕЛИ):
            print(f"{н:3d}  {описание}   ({отн})")
        return 0
    номера = ([int(д) for д in доводы if д.isdigit()]
              or list(range(len(ЦЕЛИ))))
    print(f"Ломаю защиту {len(номера)} раз и смотрю, заметит ли самопроверка.")
    print("Один прогон — около двух минут.\n")
    итог = {"поймана": 0, "мимо": 0, "устарела": 0}
    мимо: list[str] = []
    устарели: list[str] = []
    for н in номера:
        исход = проверить(н)
        итог[исход] += 1
        if исход == "мимо":
            мимо.append(ЦЕЛИ[н][0])
        elif исход == "устарела":
            устарели.append(ЦЕЛИ[н][0])
    print(f"\nпоймано {итог['поймана']}, мимо {итог['мимо']}, "
          f"устарело {итог['устарела']}")
    if мимо:
        print("\nЗАЩИТЫ БЕЗ СТРАЖА — их можно сломать, и никто не заметит:")
        for м in мимо:
            print("   ", м)
    if устарели:
        print("\nУСТАРЕВШИЕ ЦЕЛИ — код под ними переписан, каталог надо "
              "поправить.\nПока они не применяются, список врёт о своём "
              "охвате:")
        for у in устарели:
            print("   ", у)
    return 1 if (мимо or устарели) else 0


if __name__ == "__main__":
    sys.exit(main())
