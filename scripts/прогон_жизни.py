import argparse
import json
import math
import random
import sys
from collections import Counter
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "face"))

import character                                     # noqa: E402
import director                                      # noqa: E402
