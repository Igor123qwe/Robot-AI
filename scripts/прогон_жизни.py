#!/usr/bin/env python3
"""Линейка живости: сутки жизни персонажа за минуту, числами.

ЗАЧЕМ. «Человечек какой-то скучный» — самая частая и самая бесполезная
жалоба: под ней прячутся с полдюжины разных поломок, от молчащего детектора
до библиотеки в три сценки на повод. Глазами их не различить — все выглядят
одинаково. А числами различить можно, и они же не дают обмануть себя: после
каждой правки видно, стало лучше или только кажется.

ЧТО СЧИТАЕМ (docs/план-живости.md, раздел 5):

    неподвижность   доля времени, когда поза не меняется дольше двух секунд.
                    У живого это ноль: даже спящий дышит.
    предсказуемость максимум автокорреляции подскока на лагах 1–120 с. Мозг
                    ловит period-ичность быстрее, чем осознаёт, — и ровно с
                    этого мига существо становится механизмом.
    разнообразие    сколько разных сценок за час рядом с человеком, какая
                    доля у самой частой, сколько повторов подряд.
    покрытие        сколько поводов отыграно меньше чем четырьмя сценками.
                    Повод с одной сценкой человек выучивает за неделю.
    сутки           сколько сценок в час в разное время суток: днём и ночью
                    персонаж обязан вести себя по-разному.
    ночь            доля дневных сценок в два часа ночи. Должна быть нулевой.

ЧЕСТНОСТЬ — ГЛАВНОЕ ТРЕБОВАНИЕ К ЭТОМУ ФАЙЛУ. Линейка, которая показывает
хорошо всегда, не линейка, а украшение: инструмент обязан уметь сказать, что
всё плохо. Поэтому каждая метрика печатается с целью из плана и с пометкой,
достигнута она или нет, а в конце — общий вывод. Проверка в pc/selftest.py
(«измеритель не врёт») подсовывает заведомо мёртвого персонажа и требует,
чтобы он провалился по всем статьям.

ЗАПУСК:

    python3 scripts/прогон_жизни.py                 # сутки, обычный режим
    python3 scripts/прогон_жизни.py --сутки 7       # неделя
    python3 scripts/прогон_жизни.py --без-пк        # ПК выключен: режиссёра
                                                    # нет, живём своим
    python3 scripts/прогон_жизни.py --зерно 42      # другой жребий

Без pygame и без браузера: считается только то, что решает поведение, —
сценарист и тело. Картинка их не меняет, а тянуть сюда графику значит
сделать линейку непригодной для сборки, где экрана нет вовсе.
"""

from __future__ import annotations

import argparse
import math
import random
import sys
from collections import Counter
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "face"))

import character                                     # noqa: E402
import scenes                                        # noqa: E402

# Шаг модельного времени. Десятая доля секунды — тот же такт, которым живёт
# настоящее лицо (ПИШЕМ_РАЗ_В в voice/robot_voice/face.py).
ШАГ = 0.1
# Сколько неподвижности прощаем. Две секунды: самая длинная пауза между
# сценками бывает и дольше, но в паузе работают дыхание и блуждание взгляда,
# то есть поза всё равно меняется. Две секунды полной неподвижности — это уже
# не пауза, а стоп-кадр.
ЗАМЕР_ДОЛЬШЕ = 2.0
# На каких задержках ищем периодичность.
#
# НАЧИНАЕМ С ДЕСЯТИ СЕКУНД, И ЭТО НЕ ПОБЛАЖКА. Дыхание периодично у всего
# живого — период груди около трёх секунд, и он ОБЯЗАН быть виден в
# автокорреляции на малых лагах. Требовать её отсутствия значило бы требовать,
# чтобы персонаж не дышал. Механикой читается другое: повторение самого
# ПОВЕДЕНИЯ — когда одни и те же позы возвращаются каждые полминуты, и глаз
# начинает угадывать следующую. Вот это и ищем: от десяти секунд до двух
# минут. Внутри дыхательного окна периодичность — признак жизни, снаружи —
# признак механизма.
ЛАГИ = tuple(range(int(10.0 / ШАГ), int(120.0 / ШАГ), int(1.0 / ШАГ)))

# Цели из раздела 5 плана. Хранятся здесь, рядом с расчётом, чтобы не
# разъехались с ним: линейка, у которой цель написана в другом файле, однажды
# начнёт мерить одно, а сравнивать с другим.
ЦЕЛИ = {
    "неподвижность": (0.0, "не больше"),
    "предсказуемость": (0.5, "не больше"),
    "разных за час": (120, "не меньше"),
    "доля самой частой": (0.03, "не больше"),
    "повторов подряд": (0, "не больше"),
    "бедных поводов": (0, "не больше"),
    "сутки: во сколько раз день живее ночи": (1.6, "не меньше"),
    "ночь: доля дневных сценок": (0.0, "не больше"),
}


def _день_человека(секунда: float) -> dict:
    """Кто и когда рядом с роботом — обычные сутки обычного жителя.

    Ничего умного: человек уходит утром, возвращается вечером, ночью спит.
    Важно лишь, чтобы присутствие менялось — иначе мы померяем один режим и
    решим, что знаем про все.
    """
    час = (секунда / 3600.0) % 24.0
    дома = час < 8.0 or час >= 18.0
    рядом = дома and (int(секунда) // 300) % 3 == 0      # подходит к роботу
    говорит = рядом and (int(секунда) // 60) % 7 == 0
    return {
        "эмоция": "спокоен",
        "человек": рядом,
        "взгляд": 0.0 if рядом else None,
        "говорит": "фраза" if говорит else "",
        "музыка": {"играет": False},
        "ночь": час >= 23.0 or час < 7.0,
    }


def прогнать(суток: float = 1.0, зерно: int = 11, без_пк: bool = False) -> dict:
    """Прогон и все числа разом. Возвращает словарь метрик."""
    случай = random.Random(зерно)
    сцн = scenes.Сценарист(случай)
    тело = character.Питомец(1280, 800, тело_ширина=0.34, шаг_длина=0.05,
                             случай=random.Random(зерно + 1))

    имена: list[str] = []                 # имя сценки на каждом кадре
    при_человеке: list[tuple[float, str]] = []   # (время, имя) — только при нём
    подскоки: list[float] = []
    позы: list[tuple] = []
    по_часам: Counter = Counter()
    ночные_дневные = [0, 0]               # [дневных ночью, всего ночью]

    всего = int(суток * 24 * 3600 / ШАГ)
    for шаг in range(всего):
        t = шаг * ШАГ
        с = _день_человека(t)
        час = int((t / 3600.0) % 24.0)
        сутки_дн = int(t // 86400) + 1
        кадр = сцн.кадр(с, t, час=час, минута=int((t / 60.0) % 60),
                        день=сутки_дн, месяц=9, день_недели=(сутки_дн - 1) % 7)
        поза = тело.кадр(с, t)
        имя = кадр.get("имя") or ""
        имена.append(имя)
        if с["человек"]:
            при_человеке.append((t, имя))
        подскоки.append(float(поза.get("подскок", 0.0)))
        позы.append((round(поза.get("подскок", 0.0), 4),
                     round(поза.get("наклон", 0.0), 3),
                     round(поза.get("x", 0.0), 2),
                     round(поза.get("рассеян_x", 0.0), 3),
                     round(поза.get("рассеян_y", 0.0), 3),
                     round(поза.get("рот", 0.0), 2)))
        # СОН НЕ СЧИТАЕТСЯ ДЕЯТЕЛЬНОСТЬЮ. Сценки сна идут подряд без пауз —
        # «спит», сразу «сопит», снова «спит», — потому что это одна длящаяся
        # поза, разложенная на круги, а не череда событий. Для счёта «сколько
        # всего происходит» они давали шестьсот «сценок» за ночной час, и
        # выходило, что ночью персонаж активнее, чем днём. Спящий не делает
        # сценок, он спит.
        спит = имя and scenes.ПО_ИМЕНИ[имя].когда == "ночь_спит"
        if имя and not спит and (not имена[-2:-1] or имена[-2] != имя):
            по_часам[час] += 1
            if с["ночь"]:
                ночные_дневные[1] += 1
                повод = scenes.ПО_ИМЕНИ[имя].когда
                if повод in ("покой", "человек_рядом", "зовёт_внимание"):
                    ночные_дневные[0] += 1

    return {
        "неподвижность": _неподвижность(позы),
        "предсказуемость": _предсказуемость(подскоки),
        **_разнообразие(при_человеке),
        "бедных поводов": _бедные_поводы(),
        "сутки: во сколько раз день живее ночи": _суточная_разница(по_часам),
        "ночь: доля дневных сценок": (ночные_дневные[0] / ночные_дневные[1]
                                      if ночные_дневные[1] else 0.0),
        "_сценок всего": sum(по_часам.values()),
        "_по часам": dict(sorted(по_часам.items())),
        "_без пк": без_пк,
    }


def _неподвижность(позы: list[tuple]) -> float:
    """Доля времени в стоп-кадре. У живого — ноль: даже спящий дышит."""
    if not позы:
        return 1.0
    порог = int(ЗАМЕР_ДОЛЬШЕ / ШАГ)
    замерло = подряд = 0
    прошлая = None
    for поза in позы:
        подряд = подряд + 1 if поза == прошлая else 0
        прошлая = поза
        if подряд >= порог:
            замерло += 1
    return замерло / len(позы)


def _предсказуемость(ряд: list[float]) -> float:
    """Максимум автокорреляции: насколько движение похоже само на себя.

    Периодичность — самый быстрый способ выдать механизм. Человек не считает
    период сознательно, он просто перестаёт смотреть.
    """
    n = len(ряд)
    if n < max(ЛАГИ) + 10:
        return 0.0
    среднее = sum(ряд) / n
    отклонения = [з - среднее for з in ряд]
    знаменатель = sum(о * о for о in отклонения)
    if знаменатель <= 1e-12:
        return 1.0              # ничего не двигалось — это предел механичности
    пик = 0.0
    for лаг in ЛАГИ:
        числитель = sum(отклонения[и] * отклонения[и + лаг]
                        for и in range(0, n - лаг, 7))    # шаг 7 — ради скорости
        пик = max(пик, abs(числитель) / знаменатель * 7)
    return min(1.0, пик)


def _разнообразие(рядом: list[tuple[float, str]]) -> dict:
    """Что человек видит за ЧАС РЯДОМ: сколько разного и как часто повторы.

    Меряем скользящим окном в час и берём ЛУЧШЕЕ окно, а не среднее по суткам.
    Так честнее: человек не стоит у робота круглые сутки, он подходит на
    десять минут — и за эти минуты должен увидеть разное. Среднее по суткам
    размазало бы редкие встречи по всему дню и показало бы благополучие там,
    где его нет.

    Считаем только то, что сыграно ПРИ ЧЕЛОВЕКЕ: сценки пустой комнаты к делу
    не относятся, их всё равно никто не видел.
    """
    сыгранные = [(t, имя) for t, имя in рядом if имя]
    свежие: list[tuple[float, str]] = []
    for t, имя in сыгранные:
        if not свежие or свежие[-1][1] != имя:
            свежие.append((t, имя))
    if not свежие:
        return {"разных за час": 0, "доля самой частой": 1.0, "повторов подряд": 0}
    лучшее = 0
    начало = 0
    for конец in range(len(свежие)):
        while свежие[конец][0] - свежие[начало][0] > 3600.0:
            начало += 1
        лучшее = max(лучшее, len({и for _, и in свежие[начало:конец + 1]}))
    счёт = Counter(и for _, и in свежие)
    повторов = sum(1 for a, b in zip(свежие, свежие[1:]) if a[1] == b[1])
    return {
        "разных за час": лучшее,
        "доля самой частой": счёт.most_common(1)[0][1] / len(свежие),
        "повторов подряд": повторов,
    }


def _бедные_поводы() -> int:
    """Сколько поводов отыграно меньше чем четырьмя сценками."""
    счёт = Counter(с.когда for с in scenes.СЦЕНКИ)
    поводы = set(scenes.СОБЫТИЯ) | set(scenes.ФОНЫ)
    return sum(1 for п in поводы if счёт.get(п, 0) < 4)


def _суточная_разница(по_часам: Counter) -> float:
    """Во сколько раз днём живее, чем ночью. Одинаково — значит суток нет."""
    день = sum(по_часам.get(ч, 0) for ч in range(9, 22))
    ночь = sum(по_часам.get(ч, 0) for ч in list(range(0, 7)) + [23])
    if ночь <= 0:
        return float("inf") if день else 1.0
    return (день / 13.0) / (ночь / 8.0)


def напечатать(метрики: dict) -> bool:
    """Числа рядом с целями. Возвращает, всё ли достигнуто."""
    print(f"\nСценок всего: {метрики['_сценок всего']}"
          f"{'  (без ПК)' if метрики['_без пк'] else ''}")
    по_часам = метрики["_по часам"]
    if по_часам:
        строка = "  ".join(f"{ч:02d}:{n}" for ч, n in по_часам.items())
        print(f"По часам: {строка}")
    print()
    всё_хорошо = True
    for имя, (цель, как) in ЦЕЛИ.items():
        было = метрики.get(имя, 0)
        достигнуто = (было <= цель) if как == "не больше" else (было >= цель)
        всё_хорошо = всё_хорошо and достигнуто
        знак = "+" if достигнуто else "-"
        значение = f"{было:.3f}" if isinstance(было, float) else str(было)
        цель_с = f"{цель:.3f}" if isinstance(цель, float) else str(цель)
        print(f" {знак} {имя}: {значение}   (цель: {как} {цель_с})")
    print()
    print("Все цели достигнуты." if всё_хорошо else
          "Не всё достигнуто — смотри строки со знаком «-».")
    return всё_хорошо


def main() -> int:
    р = argparse.ArgumentParser(description="Линейка живости человечка")
    р.add_argument("--сутки", type=float, default=1.0, help="сколько суток прогнать")
    р.add_argument("--зерно", type=int, default=11, help="жребий")
    р.add_argument("--без-пк", action="store_true",
                   help="ПК выключен: режиссёра нет, персонаж живёт своим")
    а = р.parse_args()
    метрики = прогнать(суток=а.сутки, зерно=а.зерно, без_пк=а.без_пк)
    return 0 if напечатать(метрики) else 1


if __name__ == "__main__":
    sys.exit(main())
