def _numpy_жив() -> bool:
    """Можно ли импортировать numpy, не убив процесс. См. шапку про SIGILL.

    ROBOT_ORB_NUMPY=0/1 — решить руками (проверки, отладка без numpy).
    Проба считает маленький массив, а не только импортирует: битое ядро
    numpy в сентябре падало именно на первом вычислении в C-коде.
    """
    вручную = os.environ.get("ROBOT_ORB_NUMPY", "").strip()
    if вручную in ("0", "1"):
        return вручную == "1"
    try:
        проба = subprocess.run(
            [sys.executable, "-c",
             "import numpy as n; a = n.arange(64, dtype=n.float32); "
             "print(float(n.sin(a).sum() + (a @ a)))"],
            capture_output=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return False
    return проба.returncode == 0


