def _смешать(а, б, к):
    return tuple(int(round(x + (y - x) * к)) for x, y in zip(а, б))


def _ограничить(x, низ, верх):
    return низ if x < низ else верх if x > верх else x


def _число(з, по_умолч: float) -> float:
    """Число из сценки или состояния; мусор и пусто — значение по умолчанию."""
    try:
        return float(з) if з is not None else по_умолч
    except (TypeError, ValueError):
        return по_умолч


def _фаза(частота: float, t: float) -> float:
    """Угол частота·t, приведённый к одному обороту, — в float64.

    ЗАЧЕМ. t — секунды с запуска лица, а лицо живёт неделями. Сложи
    `1.6 * t` с массивом float32 — и через сутки мерцание замирает, кольцо сна
    собирается в четыреста позиций вместо полутора тысяч, вращение
    ступенчатое: у float32 семь значащих цифр, и 100 000 секунд съедают их
    все. Приводим угол к обороту здесь, в Python, где точности хватит на века.
    """
    return (частота * t) % (2.0 * math.pi)


def _hsv(h, s, v):
    """Цвет по тону 0..1 — для «радуги» и танца."""
    i = int(h * 6.0) % 6
    f = h * 6.0 - math.floor(h * 6.0)
    p, q, w = v * (1 - s), v * (1 - f * s), v * (1 - (1 - f) * s)
    r, g, b = [(v, w, p), (q, v, p), (p, v, w), (p, q, v), (w, p, v), (v, p, q)][i]
    return (int(r * 255), int(g * 255), int(b * 255))


def _перетекание(возраст: float, длится: float) -> float:
    """Ход превращения 0..1: туда за ПЕРЕТЕКАНИЕ, держим, обратно."""
    if возраст < 0 or возраст >= длится:
        return 0.0
    return max(0.0, min(1.0, возраст / ПЕРЕТЕКАНИЕ, (длится - возраст) / ПЕРЕТЕКАНИЕ))


class Шар:
    """Полторы тысячи точек на сфере и всё, что с ними происходит.

    `фон()` заливает холст и кладёт свечение, `кадр()` рисует точки. Всё
    остальное — состояние между кадрами: веса режимов, накопленный поворот,
    пружины разлёта, живые реакции на события.
    """

    def __init__(self, ширина: int, высота: int, *, случай: random.Random,
                 точек: int | None = None, без_numpy: bool = False) -> None:
        self.W, self.H = ширина, высота
        self.np = None if без_numpy else np
        if точек is None:
            точек = ТОЧЕК if self.np is not None else ТОЧЕК_БЕЗ_NUMPY
        self.точек = max(16, int(точек))
        self.случай = случай
        # Что видно снаружи — для касаний, пузыря реплики и проверок.
        self.центр = (ширина / 2.0, высота * ЦЕНТР_Y)
        self.радиус = РАДИУС * высота
        self.веса = {р: (1.0 if р == "покой" else 0.0) for р in РЕЖИМЫ}
        self.режим = "покой"
        self.эффекты: list[tuple[str, float, tuple]] = []
        # Свечение: можно выключить руками (ROBOT_ORB_GLOW=0) и гаснет само,
        # если кадр не успевает (`подстроить`). Без numpy его нет вовсе:
        # градиент считается массивом.
        self.свечение = СВЕЧЕНИЕ and self.np is not None
        # Текст для цифр из точек («пробил час»). Ставит кисть по часам,
        # которым верит; пусто — цифр не будет, будет кольцо.
        self.текст_часов = ""
        self._было_t: float | None = None
        self._поворот = 0.0          # накопленный угол рысканья, рад
        self._спин = РЕЖИМЫ["покой"]["спин"]
        self._первый_кадр = True
        self._взгляд_x = 0.0          # пружина взгляда: доля −1..1, x вправо
        self._взгляд_y = 0.0          # y вверх
        self.рот = 0.0                # открытость «рта» последнего кадра, 0..1
        self._голова = (0.0, 0.0)     # куда повёрнута «голова» сценкой, синусы
        # Фаза дыхания — СВОЯ, накопленная, а не sin(2π·f·t): частота
        # смешивается из весов режимов и меняется в каждом переходе, и
        # sin(f·t) прыгал бы на 2π·Δf·t — тем дальше, чем дольше лицо живёт
        # (кольцо сна дёргалось на 40 пикселей за кадр в миг засыпания).
        self._фаза_дыхания = 0.0
        # Облегчение (`подстроить`): сколько проверок подряд не успевали или
        # успевали с запасом, и сколько точек было задумано.
        self._плохо = self._хорошо = 0
        self._точек_задумано = self.точек
        self._cx = ширина / 2.0
        self._cy = высота * ЦЕНТР_Y
        self._сжатие = 1.0              # 1 → С_КАРТОЧКОЙ, пружиной вместе с центром
        self._сцена_была = ("", "")
        self._эмоция_была = "спокоен"
        self._цвет_свечения = (0, 0, 0)
        self._свечение_кэш: tuple | None = None    # цвет, в который перекрашено
        self._свечение_серое = None
        self._фигур_было = 0
        self.частей_нарисовано = 0
        self._сложить_точки()

    # --- точки -----------------------------------------------------------------
    def _сложить_точки(self) -> None:
        """Сфера Фибоначчи и всё, что про каждую точку постоянно.

        Постоянное — раз и навсегда: зерно (кому искриться, кому капать),
        фаза мерцания, место на кольце сна, в сердце и в каждой фигуре.
        Генератор свой, отделённый от общего жребия кисти: перестройка точек
        при подстройке числа не должна сдвигать сценки.
        """
        n = self.точек
        жребий = random.Random(self.случай.random())
        точки, зёрна, фазы = [], [], []
        # Мелкая дрожь против муара: на плотной решётке спираль Фибоначчи даёт
        # видимые полосы, крошечный постоянный сдвиг их прячет.
        муар = (1.0 - 1000.0 / n) * 1.6 / math.sqrt(n) if n > 1000 else 0.0
        for i in range(n):
            y = 1.0 - 2.0 * (i + 0.5) / n + (жребий.random() - 0.5) * муар
            y = _ограничить(y, -1.0, 1.0)
            r = math.sqrt(max(0.0, 1.0 - y * y))
            th = i * ЗОЛОТОЙ_УГОЛ + (жребий.random() - 0.5) * муар * 6
            точки.append((r * math.cos(th), y, r * math.sin(th)))
            зёрна.append(жребий.random())
            фазы.append(жребий.random() * 2 * math.pi)
        self._точки_список = точки
        self._зёрна_список = зёрна
        self._фазы_список = фазы
        # Кольцо сна — в плоскости экрана: его задача — обнимать часы, а не
        # вращаться вместе с глобусом.
        self._кольцо_список = [(2 * math.pi * (i + жребий.random() * 0.6) / n,
                                1.0 + (жребий.random() - 0.5) * 0.06) for i in range(n)]
        self._фигура_сдвиг = жребий.randrange(len(ФИГУРЫ))
        if self.np is None:
            return
        n_ = self.np
        f32 = n_.float32
        self._P = n_.asarray(точки, dtype=f32)
        self._s = n_.asarray(зёрна, dtype=f32)
        self._ф = n_.asarray(фазы, dtype=f32)
        self._кольцо_q = n_.asarray([к[0] for к in self._кольцо_список], dtype=f32)
        self._кольцо_т = n_.asarray([к[1] for к in self._кольцо_список], dtype=f32)
        self._индекс = n_.arange(n, dtype=f32)
        # Разброс: у каждой точки своё случайное направление — при разлёте
        # облако рвётся неровно, а не раздувается мыльным пузырём.
        разброс = n_.asarray([(жребий.gauss(0, 1), жребий.gauss(0, 1), жребий.gauss(0, 1))
                              for _ in range(n)], dtype=f32)
        разброс /= n_.maximum(1e-6, n_.linalg.norm(разброс, axis=1))[:, None]
        self._разброс = разброс
        self._сердце = self._форма_сердца(n, жребий)
        self._фигуры = {имя: self._форма(имя, n, жребий) for имя in ФИГУРЫ}
        self._цифры = None            # (текст, точки) — строятся по событию
        # Пружины разлёта: смещение и скорость каждой точки в координатах
        # взгляда. Пока все нули — пружины не считаются вовсе.
        self._O = n_.zeros((n, 3), dtype=f32)
        self._V = n_.zeros((n, 3), dtype=f32)
        self._пинок_когда = n_.full(n, n_.inf, dtype=f32)
        self._пинок_с = 0.0
        self._пинок = n_.zeros((n, 3), dtype=f32)
        self._пружины = False
        # Нормали точек в координатах ВЗГЛЯДА с прошлого кадра: толчки и
        # волны касаний живут там же, где их видит человек, а не там, куда
        # точку успел унести поворот глобуса.
        self._n_вид = self._P.copy()

    def _форма_сердца(self, n: int, жребий: random.Random):
        """Сердце: половина точек — плотный контур, половина — заливка.

        Одна заливка не читалась: две тысячи точек по большой площади — это
        розовое облако, а не сердце. Глаз узнаёт фигуру по КОНТУРУ, поэтому
        контур — плотной лентой. Заливка — честной выборкой внутри кривой
        (x² + y² − 1)³ − x²y³ ≤ 0: заливка по параметру кривой (точка на
        контуре, втянутая к центру) давала шов по оси.
        """
        n_ = self.np
        точки = []
        контур = n // 2
        for i in range(контур):
            т = 2 * math.pi * (i + жребий.random()) / контур
            x = 16 * math.sin(т) ** 3 / 17.0
            y = (13 * math.cos(т) - 5 * math.cos(2 * т) - 2 * math.cos(3 * т)
                 - math.cos(4 * т)) / 17.0
            точки.append((x + жребий.gauss(0, 0.012), y + 0.08 + жребий.gauss(0, 0.012),
                          жребий.gauss(0, 0.03)))
        while len(точки) < n:
            x = (жребий.random() * 2 - 1) * 1.15
            y = (жребий.random() * 2 - 1) * 1.15 + 0.1
            if (x * x + y * y - 1) ** 3 - x * x * y ** 3 <= 0:
                # Кривая с x²y³ — то же сердце, но крупнее параметрической в
                # 1.25 раза; подгоняем под контур.
                точки.append((x * 0.80, (y - 0.12) * 0.80 + 0.04, (жребий.random() - 0.5) * 0.22))
        return n_.asarray(точки, dtype=n_.float32)

    def _форма(self, имя: str, n: int, жребий: random.Random):
        """Точки фигуры в координатах шара (радиус шара — единица)."""
        n_ = self.np
        фи = 0.6180339887
        точки = []
        for i in range(n):
            if имя == "тор":
                u = 2 * math.pi * i / n
                v = 2 * math.pi * ((i * фи * 21) % 1.0)
                k = 0.80 + 0.30 * math.cos(v)
                точки.append((k * math.cos(u), 0.30 * math.sin(v), k * math.sin(u)))
            elif имя == "галактика":
                рукав = i % 2
                д = math.sqrt((i + 0.5) / n)
                угол = рукав * math.pi + д * 3.6 * math.pi
                разброс = 0.055 * (1.1 - д * 0.6)
                r = 0.10 + 1.05 * д
                точки.append((r * math.cos(угол) + жребий.gauss(0, разброс),
                              жребий.gauss(0, 0.035 * (1.2 - д)),
                              r * math.sin(угол) + жребий.gauss(0, разброс)))
            elif имя == "куб":
                грань = i % 6
                a = ((i // 6) * фи) % 1.0 * 2 - 1
                b = ((i // 6) * 0.7548776662) % 1.0 * 2 - 1
                с = 0.62
                ось, знак = грань // 2, (1 if грань % 2 else -1)
                p = [0.0, 0.0, 0.0]
                p[ось] = знак * с
                p[(ось + 1) % 3] = a * с
                p[(ось + 2) % 3] = b * с
                точки.append(tuple(p))
            elif имя == "облако":
                # Облако — это поверхность нескольких клубов с плоским дном, а
                # не пыль, насыпанная в эллипсоид: та на повороте в перспективе
                # выглядела шаром, который рассыпается в одну сторону. Точки
                # внутри соседнего клуба не берём — виден контур, а не каша.
                for _ in range(24):
                    cx_, cy_, r_ = жребий.choices(КЛУБЫ_ОБЛАКА, КЛУБЫ_ВЕСА)[0]
                    ux, uy, uz = (жребий.gauss(0, 1) for _ in range(3))
                    д = math.sqrt(ux * ux + uy * uy + uz * uz) or 1.0
                    x, y, z = cx_ + r_ * ux / д, max(cy_ + r_ * uy / д, -0.38), r_ * uz / д
                    if not any((x - a) ** 2 + (y - b) ** 2 + z * z < (rr * 0.97) ** 2
                               for a, b, rr in КЛУБЫ_ОБЛАКА if (a, b, rr) != (cx_, cy_, r_)):
                        break
                точки.append((x, y, z))
            else:                                        # спираль: двойная
                нить = i % 2
                h = 1.0 - 2.0 * (i + 0.5) / n
                угол = h * 3.0 * math.pi + нить * math.pi
                r = 0.42 + жребий.gauss(0, 0.03)
                if i % 7 == 0:                           # ступенька между нитями
                    r *= (жребий.random() * 2 - 1)
                точки.append((r * math.cos(угол) + жребий.gauss(0, 0.02),
                              1.05 * h + жребий.gauss(0, 0.02),
                              r * math.sin(угол) + жребий.gauss(0, 0.02)))
        return n_.asarray(точки, dtype=n_.float32)

    def _построить_цифры(self, текст: str):
        """Точки, складывающиеся в текст: шрифтом в маленькую картинку, из её
        светлых пикселей — цели. Ширина надписи — 2.4 радиуса шара."""
        n_ = self.np
        if not pygame.font.get_init():
            pygame.font.init()
        шрифт = pygame.font.Font(None, 120)
        картинка = шрифт.render(текст, False, (255, 255, 255), (0, 0, 0))
        w, h = картинка.get_size()
        светлые = n_.argwhere(pygame.surfarray.array_red(картинка) > 127)
        if len(светлые) == 0:
            return None
        жребий = random.Random(len(текст) * 7919 + sum(map(ord, текст)))
        выбор = [жребий.randrange(len(светлые)) for _ in range(self.точек)]
        xy = светлые[n_.asarray(выбор)].astype(n_.float32)
        xy += n_.asarray([(жребий.random() - 0.5, жребий.random() - 0.5)
                          for _ in range(self.точек)], dtype=n_.float32) * 0.9
        масштаб = 2.4 / max(1.0, w)
        цели = n_.zeros((self.точек, 3), dtype=n_.float32)
        цели[:, 0] = (xy[:, 0] - w / 2.0) * масштаб
        цели[:, 1] = -(xy[:, 1] - h / 2.0) * масштаб
        цели[:, 2] = 0.15
        # Слева направо — слева направо: точка с левого края шара летит в
        # левую цифру. Так полёт короткий, а надпись собирается, а не роится.
        по_точкам = n_.argsort(self._n_вид[:, 0], kind="stable")
        по_целям = n_.argsort(цели[:, 0], kind="stable")
        итог = n_.empty_like(цели)
        итог[по_точкам] = цели[по_целям]
        return итог

    def подстроить(self, мс_на_шар: float) -> bool:
        """Облегчиться, если шар не укладывается в свою долю кадра, — и
        вернуть красоту, когда снова укладывается.

        Зовёт только главный цикл, раз в окно, со средним временем шара за
        это окно. Проверки не зовут — иначе картинка зависела бы от скорости
        машины. Порог — ПОДСТРОЙКА_МС.

        Облегчаемся только после ДВУХ плохих окон подряд: одно может быть
        чужим всплеском (на тех же ядрах считают распознавание и синтез), и
        гасить из-за него свечение — значит наказывать шар за соседа.
        Сначала гаснет свечение (оно стоит целую заливку экрана, а без него
        шар остаётся шаром), потом уходят точки — по 15%, не ниже
        ТОЧЕК_НЕ_МЕНЬШЕ.

        Возвращаем назад после ШЕСТИ хороших окон подряд, когда шар укладывается
        в половину порога: сначала точки (по 15%, до задуманного числа), потом
        свечение. Без этого один тяжёлый час навсегда оставлял бы шар бедным.
        Возвращает, поменялось ли что-нибудь.
        """
        if мс_на_шар > ПОДСТРОЙКА_МС:
            self._плохо, self._хорошо = self._плохо + 1, 0
        elif мс_на_шар < 0.5 * ПОДСТРОЙКА_МС:
            self._плохо, self._хорошо = 0, self._хорошо + 1
        else:
            self._плохо = self._хорошо = 0
        if self._плохо >= 2:
            self._плохо = 0
            if self.свечение:
                self.свечение = False
                return True
            if self.точек <= ТОЧЕК_НЕ_МЕНЬШЕ:
                return False
            self.точек = max(ТОЧЕК_НЕ_МЕНЬШЕ, int(self.точек * 0.85))
            self._сложить_точки()
            return True
        if self._хорошо >= 6:
            self._хорошо = 0
            if self.точек < self._точек_задумано:
                self.точек = min(self._точек_задумано, int(self.точек / 0.85) + 1)
                self._сложить_точки()
                return True
            if not self.свечение and СВЕЧЕНИЕ and self.np is not None:
                self.свечение = True
                return True
        return False

    # --- события и касания -------------------------------------------------------
    def событие(self, вид: str, t: float, где: tuple = ()) -> None:
        """Завести реакцию. Повторная того же вида перезапускает её."""
        if вид not in ДЛИТСЯ:
            return
        if вид == "часы" and not self.текст_часов:
            # Часам не верим — цифр нет. Пробивший час всё равно отмечаем.
            вид = "кольцо"
        if вид == "фигура" and not где:
            где = (ФИГУРЫ[(self._фигур_было + self._фигура_сдвиг) % len(ФИГУРЫ)],)
            self._фигур_было += 1
        self.эффекты = [э for э in self.эффекты if э[0] != вид]
        self.эффекты.append((вид, t, где))
        if self.np is None:
            return
        n_ = self.np
        N = self._n_вид
        if вид == "сбор":
            # Разлёт волной: точки, обращённые к человеку, срываются первыми,
            # дальние — позже. Пинок наружу и вбок с разбросом силы: облако
            # рвётся неровно, как живое, и стягивается обратно пружиной.
            сила = (2.0 + 1.6 * self._s)[:, None]
            наружу = (N + 0.55 * self._разброс) * сила
            задержка = (1.0 - N[:, 2]) * 0.5 * 0.35
            self._пинок = наружу.astype(n_.float32)
            # Сроки пинков — от начала события, а не абсолютным t: в float32
            # абсолютная секунда недельной давности теряет миллисекунды.
            self._пинок_с = t
            self._пинок_когда = задержка.astype(n_.float32)
            self._пружины = True
        elif вид == "вздрог":
            сила = 2.2 + 1.5 * self._s[:, None]
            self._V += (N * сила).astype(n_.float32)
            self._пружины = True
        elif вид in ("тычок", "касание"):
            c = где if где else (0.0, -0.3, 0.95)
            близость = n_.maximum(0.0, N @ n_.asarray(c, dtype=n_.float32))
            self._V += (N * (близость ** 4 * -3.0)[:, None]).astype(n_.float32)
            self._пружины = True
        elif вид == "часы":
            self._цифры = (self.текст_часов, self._построить_цифры(self.текст_часов))

    def коснуться(self, x: float, y: float, t: float) -> None:
        """Палец на экране: волна по шару из того места, куда ткнули."""
        cx, cy = self.центр
        dx = (x - cx) / max(1.0, self.радиус)
        dy = -(y - cy) / max(1.0, self.радиус)
        d2 = dx * dx + dy * dy
        if d2 <= 1.0:
            c = (dx, dy, math.sqrt(1.0 - d2))
        else:
            d = math.sqrt(d2)
            c = (dx / d, dy / d, 0.0)
        self.событие("касание", t, c)

    def куда(self, x: float, y: float) -> str:
        """Куда пришлось касание: «голова» — верх шара, «тело» — низ, «мимо».

        Те же три слова, что ждёт сценарий (КАСАНИЕ_СОБЫТИЕ в scenes.py):
        верх шара гладят, в низ тычут, мимо — стучат по стеклу рядом. Запас в
        пятнадцать процентов радиуса: пальцем по краю точечного облака — это
        по шару, а не мимо.
        """
        cx, cy = self.центр
        R = self.радиус
        if self.веса["сон"] >= 0.5:
            # Во сне шар — широкое кольцо вокруг часов (КОЛЬЦО_СНА), и
            # палец по кольцу — это по нему, а не «мимо». Внутри кольца — часы,
            # но и тронуть часы спящего — тоже тронуть его: «погладили»,
            # мягкое пробуждение, а не тычок.
            ах, ау = КОЛЬЦО_СНА[0] + 0.1, КОЛЬЦО_СНА[1] + 0.1
            if ((x - cx) / (ах * R)) ** 2 + ((y - cy) / (ау * R)) ** 2 > 1.0:
                return "мимо"
            return "голова"
        if math.hypot(x - cx, y - cy) > R * 1.15:
            return "мимо"
        return "голова" if y <= cy else "тело"

    def _события_из_сцены(self, сцена: dict, состояние: dict, t: float) -> None:
        ключ = (сцена.get("имя") or "", сцена.get("когда") or "")
        if ключ != self._сцена_была and ключ[1] in СОБЫТИЯ:
            вид = СОБЫТИЯ[ключ[1]]
            где: tuple = ()
            if вид == "гладят":
                где = (0.0, 0.85, 0.53)
            elif вид == "тычок":
                где = (0.0, -0.45, 0.89)
            self.событие(вид, t, где)
            if ключ[1] == "праздник":
                self.событие("сбор", t)
        self._сцена_была = ключ
        эмоция = состояние.get("эмоция") or "спокоен"
        # Проснулся: из сна в любое бодрое состояние — шар собирается из
        # кольца с разлётом, а не просто перетекает.
        if self._эмоция_была == "сплю" and эмоция != "сплю":
            self.событие("сбор", t)
        self._эмоция_была = эмоция

    # --- режим -----------------------------------------------------------------
    режим_по = staticmethod(orb_rules.режим_по)

    def _сменить_веса(self, цель: str, dt: float) -> None:
        if dt <= 0:
            return
        τ = ПЕРЕХОД_В_СОН if цель == "сон" else ПЕРЕХОД
        k = 1.0 - math.exp(-dt / τ)
        for р in self.веса:
            self.веса[р] += ((1.0 if р == цель else 0.0) - self.веса[р]) * k
        self.режим = цель

    def _смесь(self, имя: str) -> float:
        return sum(в * РЕЖИМЫ[р][имя] for р, в in self.веса.items())

    def _палитра(self, t: float):
        а = [0.0, 0.0, 0.0]
        б = [0.0, 0.0, 0.0]
        for р, в in self.веса.items():
            if в < 1e-3:
                continue
            if р == "танец":
                # Танец переливается раз в двадцать секунд — но только по
                # холодной дуге (голубой → фиолетовый → малиновый): красный на
                # этом экране — аварийная остановка, янтарь — тревога, и песня
                # не должна раз в полминуты выглядеть как беда.
                ход = math.sin(_фаза(2 * math.pi * 0.05, t))
                ца = _hsv(0.45 + 0.47 * (0.5 + 0.5 * ход), 0.85, 1.0)
                ход = math.sin(_фаза(2 * math.pi * 0.05, t) + 2.0)
                цб = _hsv(0.45 + 0.47 * (0.5 + 0.5 * ход), 0.75, 1.0)
            else:
                ца, цб = ПАЛИТРЫ[р]
            for i in range(3):
                а[i] += ца[i] * в
                б[i] += цб[i] * в
        return tuple(а), tuple(б)

    @property
    def взгляд(self) -> tuple[float, float]:
        """Куда смотрит шар: доли −1..1, x вправо, y вверх (экранные оси)."""
        return self._взгляд_x, self._взгляд_y

    def _возраст(self, вид: str, t: float):
        for э in self.эффекты:
            if э[0] == вид:
                return t - э[1], э[2]
        return None, ()

    # --- фон и свечение --------------------------------------------------------
    def фон(self, холст, цвет, яркость: float) -> None:
        """Залить холст и положить мягкое свечение там, где шар.

        Свечение — готовая картинка, сложенная с фоном (BLEND_RGB_ADD). Её
        цвет и размер берутся с ПРОШЛОГО кадра шара: фон рисуется раньше
        точек, а на кадр опоздания глаз не видит. Картинка перестраивается,
        только когда цвет или размер заметно сдвинулись, — это раз в
        несколько секунд, а в переходе между режимами — каждый кадр, пока он
        идёт (доли миллисекунды).
        """
        холст.fill(цвет)
        if not self.свечение or self.np is None:
            return
        # Тусклый режим (грусть) — темнее и свечением, а не туманом поверх
        # потемневших точек.
        сила = (СВЕЧЕНИЕ_СИЛА * float(яркость) * self._смесь("яркость")
                * (1.0 - 0.6 * self.веса["сон"]))
        # Цвет — ступенями по три: в переходе между режимами картинка
        # перекрашивается раз в несколько кадров, а не каждый.
        цвет_св = tuple(int(c * сила) // 3 * 3 for c in self._цвет_свечения)
        if max(цвет_св) < 3:
            return
        if self._свечение_серое is None:
            self._свечение_серое = self._серое_свечение()
        размер, серое, цветное = self._свечение_серое
        if self._свечение_кэш != цвет_св:
            # Перекраска — палитрой: заготовка восьмибитная, её 256 оттенков
            # серого становятся 256 оттенками нужного цвета, и одна обычная
            # копия в 32 бита (SDL делает её таблицей, 0.2 мс на x86). Умножить
            # картинку на цвет средствами pygame стоило 4.4 мс, пересчитать
            # градиент заново — 9.
            серое.set_palette([(i * цвет_св[0] // 255, i * цвет_св[1] // 255,
                                i * цвет_св[2] // 255) for i in range(256)])
            цветное.blit(серое, (0, 0))
            self._свечение_кэш = цвет_св
        cx, cy = self.центр
        холст.blit(цветное, (int(cx) - размер, int(cy) - размер),
                   special_flags=pygame.BLEND_RGB_ADD)

    def _серое_свечение(self):
        """Заготовка свечения: серый градиент, ярче всего — белый. Один раз
        на жизнь кисти и по ОСНОВНОМУ радиусу, а не по текущему: свечение
        мягкое, и дышать вместе с шаром ему незачем."""
        n_ = self.np
        R = РАДИУС * self.H
        размер = int(R * СВЕЧЕНИЕ_ДО)
        сторона = 2 * размер
        ось = (n_.arange(сторона, dtype=n_.float32) - размер + 0.5) / max(1.0, R)
        r2 = ось[:, None] ** 2 + ось[None, :] ** 2
        # Мягкое ядро плюс светлый обод у края шара — как атмосфера у планеты.
        r = n_.sqrt(r2)
        сила = 0.65 * n_.exp(-r2 * 1.4) + 0.45 * n_.exp(-((r - 0.98) / 0.22) ** 2)
        сила *= n_.clip((СВЕЧЕНИЕ_ДО - r) / 0.25, 0.0, 1.0)
        сила /= max(1e-6, float(сила.max()))
        серое = pygame.Surface((сторона, сторона), 0, 8)
        серое.set_palette([(i, i, i) for i in range(256)])
        pygame.surfarray.blit_array(серое, n_.clip(сила * 255.0, 0, 255).astype(n_.uint8))
        return размер, серое, pygame.Surface((сторона, сторона), 0, 32)

    # --- кадр ------------------------------------------------------------------
    def кадр(self, холст, состояние: dict, сцена: dict, поза: dict, t: float,
             яркость: float, *, карточка_слева: bool = False) -> None:
        """Один кадр шара на холст. Фон уже залит (`фон`) — шар его не трогает."""
        dt = 0.0 if self._было_t is None else t - self._было_t
        if dt < 0:
            # Время пошло назад (перезапуск часов) — шагом считаем ноль, а
            # живые реакции сдвигаем вместе со временем: иначе их начало
            # оказалось бы в будущем, возраст — отрицательным, и экспоненты
            # от него переполнялись бы. Вперёд на сколько угодно — можно: все
            # пружины здесь точные (экспоненты), и большой шаг просто доводит
            # их до места, а не раскачивает.
            self.эффекты = [(в, t0 + dt, г) for в, t0, г in self.эффекты]
            if self.np is not None:
                self._пинок_с += dt
            dt = 0.0
        self._было_t = t
        сцена = сцена or {}
        # Сценарий кладёт сдвиг, поворот и масштаб картинки рядом с
        # параметрами, а не в них (scenes.py: «свои»). Шару удобнее одним
        # словарём — складываем, не трогая сценку.
        п = dict(сцена.get("параметры") or {})
        for к, по_умолч in (("масштаб", 1.0), ("поворот", 0.0), ("к", 0.0)):
            п[к] = _число(сцена.get(к), по_умолч)
        self._события_из_сцены(сцена, состояние, t)
        self.эффекты = [э for э in self.эффекты if t - э[1] < ДЛИТСЯ[э[0]]]
        self._сменить_веса(self.режим_по(состояние), dt)
        self._фаза_дыхания = (self._фаза_дыхания
                              + 2.0 * math.pi * self._смесь("дых_гц") * dt) % (2.0 * math.pi)

        # Вращение: скорость тянется к цели, угол копится — смена режима не
        # даёт рывка.
        цель_спина = self._смесь("спин")
        if self._первый_кадр:
            # Первый кадр: угол — от самого времени, чтобы картинка в данную
            # секунду не зависела от того, с какой секунды кисть запущена.
            self._поворот = t * цель_спина
            self._спин = цель_спина
            self._первый_кадр = False
        elif dt > 0:
            self._спин += (цель_спина - self._спин) * (1.0 - math.exp(-2.0 * dt))
            self._поворот += self._спин * dt

        # Взгляд: куда смотрит Питомец (на человека — по пеленгу камеры) плюс
        # саккады. Пружина, а не скачок: глаз не телепортируется.
        #
        # ЗНАКИ — экранные: x вправо, y вверх. У Питомца «взгляд» положителен
        # ВЛЕВО (пеленг камеры: человек слева — плюс), поэтому минус; его
        # «рассеян_y» положителен вниз (экранная ось) — тоже минус. У сценки
        # глаза по Cubism: +X вправо, +Y вверх; «к» — сторона движения, +1
        # справа.
        gx = -_число(поза.get("взгляд"), 0.0) + 0.35 * _число(поза.get("рассеян_x"), 0.0)
        gy = -0.25 * _число(поза.get("рассеян_y"), 0.0)
        gx += 0.6 * _число(п.get("ParamEyeBallX"), 0.0) + 0.5 * п["к"]
        gy += 0.4 * _число(п.get("ParamEyeBallY"), 0.0)
        k = 1.0 - math.exp(-dt / 0.15) if dt > 0 else 1.0
        self._взгляд_x += (_ограничить(gx, -1, 1) - self._взгляд_x) * k
        self._взгляд_y += (_ограничить(gy, -1, 1) - self._взгляд_y) * k

        # Где центр. Покачивается сам по себе; сценка двигает его как раньше
        # двигала персонажа; карточка слева отодвигает шар вправо — карточка
        # на экране важнее шара, и под неё он не лезет.
        # С карточкой шар ещё и меньше — пружиной, как центр, чтобы не прыгал.
        k = 1.0 - math.exp(-dt / 0.35) if dt > 0 else 1.0
        self._сжатие += ((С_КАРТОЧКОЙ if карточка_слева else 1.0) - self._сжатие) * k
        R = self.радиус = (РАДИУС * self.H * _ограничить(п["масштаб"], 0.6, 1.4)
                           * self._сжатие)
        сон = self.веса["сон"]
        cx = self.W / 2.0 + 0.012 * self.W * math.sin(t * 0.07)
        cy = self.H * (ЦЕНТР_Y + (ЦЕНТР_Y_ВО_СНЕ - ЦЕНТР_Y) * сон) \
            + 0.008 * self.H * math.sin(t * 0.11)
        cx += _число(сцена.get("x"), 0.0) * self.W * 0.35
        cy += _число(сцена.get("y"), 0.0) * self.H * 0.35
        if карточка_слева:
            # Под карточку не лезет ни сам, ни по сценке: «заглянул за край»
            # влево при карточке упирается в неё и остаётся справа.
            cx = max(cx, (0.06 + 0.30 + 0.02) * self.W + R * 1.08)
        cx = _ограничить(cx, R * 1.1 + 8, self.W - R * 1.1 - 8)
        self._cx += (cx - self._cx) * k
        self._cy += (cy - self._cy) * k

        if self.np is not None:
            self._кадр_numpy(холст, состояние, п, поза, t, dt, яркость)
        else:
            self._кадр_python(холст, состояние, п, поза, t, яркость)

    # --- вспомогательное для обоих путей ----------------------------------------
    def _общие(self, состояние: dict, п: dict, поза: dict, t: float):
        """Скаляры кадра, общие для numpy и без него."""
        дых_А = self._смесь("дыхание") + 0.04 * _число(п.get("ParamBreath"), 0.0)
        # Дыхание — своей накопленной фазой (см. _фаза_дыхания), а не фазой
        # Питомца: у того частота гуляет, а фаза считалась как t/период, и
        # через сутки работы «гуляние» умножалось на сутки — шар дрожал.
        дыхание = 1.0 + дых_А * math.sin(self._фаза_дыхания)
        радиус = self._смесь("радиус") * дыхание
        возраст, _ = self._возраст("выдох", t)
        if возраст is not None:
            радиус *= 1.0 - 0.08 * math.sin(math.pi * возраст / ДЛИТСЯ["выдох"])
        рот = 0.0
        if состояние.get("говорит"):
            звук = состояние.get("рот")
            if isinstance(звук, (int, float)) and not isinstance(звук, bool):
                # Рот по звуку из динамика — как есть, и ноль тоже: ноль — это
                # пауза между словами, а не «данных нет».
                рот = _ограничить(float(звук), 0.0, 1.0)
            else:
                # Рта по звуку нет (piper мимо, старый голос): дышим словами
                # сами, слогами по пять в секунду — шар не замирает посреди
                # фразы.
                рот = 0.35 + 0.35 * max(0.0, math.sin(t * 2 * math.pi * 5.0))
        рот = max(рот, _ограничить(_число(п.get("ParamMouthOpenY"), 0.0), 0.0, 1.0))
        self.рот = рот
        # Поворот головы из сценки — поворот шара. Углы сценок — градусы
        # Live2D (±30°); шару хватает их доли, иначе он кувыркается.
        голова_x = (math.radians(_число(п.get("ParamAngleX"), 0.0)) * 0.8
                    + math.radians(_число(п.get("ParamBodyAngleX"), 0.0)) * 0.4)
        голова_y = (math.radians(_число(п.get("ParamAngleY"), 0.0)) * 0.6
                    + math.radians(_число(п.get("ParamBodyAngleY"), 0.0)) * 0.3)
        # Поворот однородной сферы глазу почти не виден — поэтому голова ведёт
        # и яркое пятно «зрачка» (см. кадр): «посмотрел вверх» читается сразу.
        self._голова = (math.sin(голова_x), math.sin(голова_y))
        рыск = голова_x + self._взгляд_x * 0.35
        # Тангаж положительный наклоняет лицевую сторону ВНИЗ; у сценки +Y —
        # «посмотрел вверх», отсюда минус.
        тангаж = -(голова_y + self._взгляд_y * 0.25)
        крен = (math.radians(_число(п.get("ParamAngleZ"), 0.0)) * 0.8
                + math.radians(_число(п.get("ParamBodyAngleZ"), 0.0)) * 0.4
                + п["поворот"] + 0.05 * (
                    _число(п.get("ParamBrowLY"), 0.0)
                    - _число(п.get("ParamBrowRY"), 0.0)))
        качание = self._смесь("качание")
        крен += 0.15 * качание * math.sin(t * 2 * math.pi * 0.6)
        # Прищур: веки сценки (абсолютные, 1 — открыты) сплющивают шар; брови
        # вверх («удивился») вытягивают его, вниз («нахмурился») — приплющивают.
        веки = 0.5 * (_число(п.get("ParamEyeLOpen"), 1.0) + _число(п.get("ParamEyeROpen"), 1.0))
        брови = 0.5 * (_число(п.get("ParamBrowLY"), 0.0) + _число(п.get("ParamBrowRY"), 0.0))
        сплющ = (self._смесь("сплющ") * (0.78 + 0.22 * _ограничить(веки, 0.0, 1.0))
                 * (1.0 + 0.07 * _ограничить(брови, -1.0, 1.0)))
        return дыхание, радиус, рот, рыск, тангаж, крен, сплющ

    def _цвета_кадра(self, состояние: dict, п: dict, t: float):
        """Два цвета градиента с поправками: ночь, улыбка, румянец, праздник."""
        а, б = self._палитра(t)
        тепло = _ограничить(0.5 * _число(п.get("ParamMouthForm"), 0.0)
                            + 0.25 * (_число(п.get("ParamEyeLSmile"), 0.0)
                                      + _число(п.get("ParamEyeRSmile"), 0.0)),
                            -1.0, 1.0)
        if тепло > 0:
            а, б = _смешать(а, ТЕПЛО, тепло * 0.35), _смешать(б, ТЕПЛО, тепло * 0.35)
        elif тепло < 0:
            серый = (0x8A, 0x96, 0xA8)
            а, б = _смешать(а, серый, -тепло * 0.4), _смешать(б, серый, -тепло * 0.4)
        румянец = _число(п.get("ParamCheek"), 0.0)
        возраст, _ = self._возраст("гладят", t)
        if возраст is not None:
            румянец = max(румянец, math.exp(-возраст / 0.9))
        if румянец > 0:
            б = _смешать(б, РУМЯНЕЦ, _ограничить(румянец, 0, 1) * 0.5)
        if состояние.get("ночь"):
            # Сильно: при 0.45 голубой с сиреневым гасили друг друга в серый,
            # и ночной шар выглядел выключенным, а не тёплым.
            а, б = _смешать(а, НОЧНОЙ, 0.7), _смешать(б, НОЧНОЙ, 0.7)
        возраст, _ = self._возраст("радуга", t)
        if возраст is not None:
            # Праздник переливается, но по холодной дуге, как танец: красный
            # на этом экране — авария, янтарь — тревога.
            сила = math.sin(math.pi * возраст / ДЛИТСЯ["радуга"])
            ход = math.sin(_фаза(2 * math.pi * 0.4, t))
            а = _смешать(а, _hsv(0.45 + 0.47 * (0.5 + 0.5 * ход), 0.8, 1.0), сила)
            б = _смешать(б, _hsv(0.45 + 0.47 * (0.5 - 0.5 * ход), 0.8, 1.0), сила)
        возраст, _ = self._возраст("сердце", t)
        if возраст is not None:
            сила = math.sin(math.pi * возраст / ДЛИТСЯ["сердце"])
            б = _смешать(б, (0xFF, 0x4D, 0x8D), сила)
            а = _смешать(а, (0xFF, 0x8F, 0xAB), 0.6 * сила)
        возраст, _ = self._возраст("выдох", t)
        if возраст is not None:
            сила = 0.25 * math.sin(math.pi * возраст / ДЛИТСЯ["выдох"])
            а, б = _смешать(а, (0, 0, 0), сила), _смешать(б, (0, 0, 0), сила)
        self._цвет_свечения = tuple(int((x + y) / 2) for x, y in zip(а, б))
        return а, б

    def _сдвиги_центра(self, t: float) -> tuple[float, float, float, float]:
        """Сдвиг центра и сплющивание от реакций: прыжок, кивок, тряска."""
        R = self.радиус
        dx = dy = 0.0
        sx = sy = 1.0
        прыжок = self._смесь("прыжок")
        возраст, _ = self._возраст("прыжок", t)
        if возраст is not None:
            прыжок = max(прыжок, math.exp(-возраст / 0.9))
        if прыжок > 0.01:
            фаза = t * 2 * math.pi * 1.4
            dy -= 0.07 * R * abs(math.sin(фаза)) * прыжок
            а = 0.10 * math.cos(2 * фаза) * прыжок
            sy *= 1.0 + а
            sx *= 1.0 / math.sqrt(1.0 + а)
        возраст, _ = self._возраст("кивок", t)
        if возраст is not None:
            dy += 0.06 * R * math.sin(2 * math.pi * 2.5 * возраст) * math.exp(-возраст / 0.35)
        возраст, _ = self._возраст("тряска", t)
        if возраст is not None:
            dx += 0.07 * R * math.sin(2 * math.pi * 3.0 * возраст) * math.exp(-возраст / 0.4)
        dy += 0.06 * R * self._смесь("понурость")
        return dx, dy, sx, sy

    # --- путь numpy ------------------------------------------------------------
    def _кадр_numpy(self, холст, состояние, п, поза, t, dt, яркость) -> None:
        n_ = self.np
        P = self._P
        s = self._s
        f32 = n_.float32
        дыхание, радиус, рот, рыск, тангаж, крен, сплющ = self._общие(состояние, п, поза, t)
        R = self.радиус
        cx_d, cy_d, sx_d, sy_d = self._сдвиги_центра(t)
        cx, cy = self._cx + cx_d, self._cy + cy_d
        self.центр = (cx, cy)
        в = self.веса

        # 1. Поворот. Рысканье — своё у каждой широты, когда шар думает: верх
        # и низ крутятся с разной скоростью, как тянучка. Потом наклон оси,
        # тангаж и крен — одной матрицей на всех.
        твист = self._смесь("твист")
        # Накопленный угол — Python float64 и не ограничен; в массивы — уже
        # приведённым к обороту (см. _фаза).
        угол0 = (self._поворот + рыск) % (2.0 * math.pi)
        a = НАКЛОН_ОСИ + тангаж
        ca, sa = math.cos(a), math.sin(a)
        cr, sr = math.cos(крен), math.sin(крен)

        def повернуть(Q, угол):
            c, sn = n_.cos(угол), n_.sin(угол)
            x1 = Q[:, 0] * c + Q[:, 2] * sn
            z1 = -Q[:, 0] * sn + Q[:, 2] * c
            y2 = Q[:, 1] * ca - z1 * sa
            z2 = Q[:, 1] * sa + z1 * ca
            return x1 * cr - y2 * sr, x1 * sr + y2 * cr, z2

        nx, ny, nz = повернуть(P, угол0 + твист * 1.45 * P[:, 1] if твист > 1e-3 else угол0)
        self._n_вид = n_.stack((nx, ny, nz), axis=1).astype(f32)
        # Угол от точки, глядящей прямо на человека: от него расходятся волны
        # речи и к нему сходятся волны слушания. Считаем, только если нужен.
        от_центра = None

        def угол_от_центра():
            return n_.arccos(n_.clip(nz, -1.0, 1.0))

        # 2. Радиус каждой точки: дыхание, живая рябь, волны, касания, руки.
        r = n_.full(self.точек, радиус, dtype=f32)
        шум = self._смесь("шум")
        if шум > 0:
            # Сумма синусов вместо симплекс-шума: в двадцать раз дешевле и на
            # глаз не отличить — комки медленно ползут по поверхности.
            r += шум * (n_.sin(3 * P[:, 0] + _фаза(0.30, t)) * n_.cos(3 * P[:, 1] - _фаза(0.20, t))
                        * n_.sin(3 * P[:, 2] + _фаза(0.10, t))) / 0.35
        if в["речь"] > 1e-3 or рот > 0.01:
            # Речь: шар раздувается с громкостью, и от середины видимой стороны
            # бегут кольца — как волны от динамика.
            от_центра = угол_от_центра()
            кольца = n_.sin(11.0 * (1.0 - nz) - _фаза(7.5, t))
            r += (0.05 * рот + 0.10 * рот * n_.maximum(0.0, кольца)) * (0.6 + 0.4 * s)
            r += 0.03 * в["речь"] * n_.sin(12.0 * от_центра - _фаза(6.2, t))
        if в["слух"] > 1e-3:
            # Слушает: волны бегут ВНУТРЬ, к точке, смотрящей на человека, —
            # будто втягивает звук. Знак фазы обратный речи.
            if от_центра is None:
                от_центра = угол_от_центра()
            r += 0.022 * в["слух"] * n_.sin(13.0 * от_центра + _фаза(5.4, t))
        if в["танец"] > 1e-3:
            # Танец: удар на каждую долю (116 ударов в минуту) и полосы по
            # широтам, бегущие вверх.
            доля = (t * 116.0 / 60.0) % 2.0    # период полос — две доли
            удар = math.exp(-(доля - math.floor(доля)) * 5.0)
            r += в["танец"] * (0.07 * удар + 0.05 * n_.sin(2 * math.pi * (2.0 * P[:, 1] - доля * 0.5)))
        дрожь = self._смесь("дрожь")
        возраст, _ = self._возраст("вздрог", t)
        if возраст is not None:
            # Вздрогнул: сжался за 90 мс, распахнулся, улёгся — плюс мелкая дрожь.
            if возраст < 0.09:
                вздрог = -0.10 * возраст / 0.09
            elif возраст < 0.21:
                вздрог = -0.10 + 0.22 * (возраст - 0.09) / 0.12
            else:
                вздрог = 0.12 * math.exp(-(возраст - 0.21) / 0.18)
            r += вздрог
            дрожь = max(дрожь, math.exp(-возраст / 0.25))
        for вид in ("касание", "гладят", "тычок"):
            возраст, где = self._возраст(вид, t)
            if возраст is None:
                continue
            c3 = где if где else (0.0, 0.0, 1.0)
            # Волна по коже от точки касания: фронт идёт со скоростью
            # 2.5 рад/с, затухает за полсекунды. Тычок сначала вдавливает.
            гео = n_.arccos(n_.clip(nx * c3[0] + ny * c3[1] + nz * c3[2], -1.0, 1.0))
            d = гео - 2.5 * возраст
            r += 0.08 * math.exp(-возраст / 0.6) * n_.sin(18.0 * d) * n_.exp(-(d / 0.25) ** 2)
            if вид == "тычок" and возраст < 0.3:
                r -= 0.07 * n_.exp(-(гео ** 2) / 0.08) * math.exp(-возраст / 0.12)
        рука_п = _ограничить(_число(п.get("рука_п"), 0.0), 0.0, 60.0) / 60.0
        рука_л = _ограничить(_число(п.get("рука_л"), 0.0), 0.0, 60.0) / 60.0
        if рука_п > 0.01 or рука_л > 0.01:
            # «Помахал рукой» — лепесток точек тянется вбок. Сценки сами
            # качают угол руки, шару остаётся только вытянуть бок.
            r += 0.28 * рука_п * n_.maximum(0.0, nx - 0.35) ** 2 / 0.42
            r += 0.28 * рука_л * n_.maximum(0.0, -nx - 0.35) ** 2 / 0.42
        возраст, _ = self._возраст("кольцо", t)
        кольцо_яркость = None
        if возраст is not None:
            # Кольцо-волна от центра к краю: пробил час, сработал таймер.
            if от_центра is None:
                от_центра = угол_от_центра()
            полоса = n_.exp(-((от_центра - 2.2 * возраст) / 0.16) ** 2) * math.exp(-возраст / 0.9)
            r += 0.06 * полоса
            кольцо_яркость = полоса

        # 3. Форма. Сфера крутится, кольцо сна и сердце смотрят на человека.
        X = nx * r * sx_d * сплющ ** -0.5
        Y = ny * r * sy_d * сплющ
        Z = nz * r * sx_d
        понурость = self._смесь("понурость")
        if понурость > 0.01:
            # Грусть: низ провисает, как капля.
            Y = Y - 0.18 * понурость * n_.maximum(0.0, -ny) ** 2
        сон = в["сон"]
        if сон > 1e-3:
            # Кольцо вокруг спящих часов: широкий эллипс, медленно плывёт по
            # кругу, чуть волнуется.
            q = self._кольцо_q + _фаза(0.08, t)
            тк = self._кольцо_т * дыхание
            X = X * (1 - сон) + КОЛЬЦО_СНА[0] * тк * n_.cos(q) * сон
            Y = Y * (1 - сон) + КОЛЬЦО_СНА[1] * тк * n_.sin(q) * сон
            Z = Z * (1 - сон) + 0.06 * n_.sin(3 * q + _фаза(0.5, t)) * сон
        # Превращения: сердце, фигура, цифры. Каждая точка идёт к своей цели
        # со своей задержкой (до 40% хода) и по дуге — наружу и обратно, так
        # что видно полёт точек, а не растворение одной картинки в другой.
        цифры_вес = None
        for вид in ("сердце", "фигура", "часы"):
            возраст, где = self._возраст(вид, t)
            if возраст is None:
                continue
            ход = _перетекание(возраст, ДЛИТСЯ[вид])
            if ход <= 0:
                continue
            if вид == "сердце":
                удар = 1.0 + 0.08 * math.exp(-((t * 1.2) % 1.0) * 6.0)
                цель = self._сердце * n_.asarray((1.05 * удар, 1.05 * удар, 1.0), dtype=f32)
                tx, ty, tz = цель[:, 0], цель[:, 1], цель[:, 2]
            elif вид == "фигура":
                имя = где[0] if где else "тор"
                фигура = self._фигуры.get(имя)
                if фигура is None:
                    continue
                if имя == "галактика":
                    # Галактика крутится вокруг СВОЕЙ оси и смотрит на
                    # человека почти плашмя: с ребра рукавов не видно.
                    ug = ((self._поворот + рыск) * 1.6) % (2.0 * math.pi)
                    gx = фигура[:, 0] * math.cos(ug) - фигура[:, 2] * math.sin(ug)
                    gz = фигура[:, 0] * math.sin(ug) + фигура[:, 2] * math.cos(ug)
                    наклон = 0.6
                    tx = gx
                    ty = gz * math.cos(наклон) + фигура[:, 1]
                    tz = -gz * math.sin(наклон) + 0.2
                else:
                    tx, ty, tz = повернуть(фигура, ((self._поворот + рыск) * 0.7) % (2.0 * math.pi))
            else:
                if not self._цифры or self._цифры[1] is None:
                    continue
                цель = self._цифры[1]
                качнуть = 0.10 * math.sin(t * 1.3)
                tx = цель[:, 0] * math.cos(качнуть)
                ty = цель[:, 1]
                tz = цель[:, 2] + цель[:, 0] * math.sin(качнуть)
            w = n_.clip(ход * 1.6 - 0.6 * s, 0.0, 1.0)
            w = w * w * (3.0 - 2.0 * w)
            дуга = 0.5 * w * (1.0 - w)
            X = X * (1 - w) + tx * w + nx * дуга
            Y = Y * (1 - w) + ty * w + ny * дуга
            Z = Z * (1 - w) + tz * w + nz * дуга
            if вид == "часы":
                цифры_вес = w
        возраст, _ = self._возраст("капель", t)
        капли = None
        if возраст is not None:
            # Капель: нижние точки отрываются и падают, тая на лету.
            низ = ny < -0.80
            # Доля пути — сначала от времени в float64, потом к float32-массиву:
            # абсолютная секунда недельной давности в float32 теряет доли.
            путь = (((t * 0.45) % 1.0) + s * 3.0) % 1.0
            сила = math.sin(math.pi * возраст / ДЛИТСЯ["капель"])
            Y = n_.where(низ, Y - 0.55 * путь * сила, Y)
            капли = n_.where(низ, 1.0 - путь * сила, 1.0)

        # 4. Пружины разлёта: точно по закону критического затухания, так что
        # на любом шаге времени без раскачки.
        if self._пружины:
            пора = self._пинок_когда <= (t - self._пинок_с)
            if пора.any():
                self._V[пора] += self._пинок[пора]
                self._пинок_когда[пора] = n_.inf
            if dt > 0:
                полураспад = 0.30
                y_ = 2.0 * math.log(2.0) / полураспад
                e = math.exp(-y_ * dt)
                j1 = self._V + self._O * y_
                self._O = (e * (self._O + j1 * dt)).astype(f32)
                self._V = (e * (self._V - j1 * y_ * dt)).astype(f32)
            # Засыпают, когда сдвиг меньше полупикселя, а скорость — меньше
            # пикселя в секунду: дальше считать нечего, глаз разницы не видит.
            полпикселя = 0.5 / max(1.0, R)
            if (float(n_.abs(self._O).max()) < полпикселя
                    and float(n_.abs(self._V).max()) < 2 * полпикселя
                    and not n_.isfinite(self._пинок_когда).any()):
                self._O[:] = 0
                self._V[:] = 0
                self._пружины = False
            X = X + self._O[:, 0]
            Y = Y + self._O[:, 1]
            Z = Z + self._O[:, 2]
        if дрожь > 0.01:
            # Дрожь — из таблицы по номеру кадра, а не из случая: картинка
            # остаётся воспроизводимой.
            кадр25 = math.floor(t * 25.0)
            j = n_.sin(self._индекс * 12.9898 + (кадр25 % 997) * 78.233) * 43758.5453
            j = (j - n_.floor(j)) - 0.5
            X = X + 0.05 * дрожь * j
            Y = Y + 0.05 * дрожь * n_.roll(j, 7)

        # 5. Проекция и глубина.
        Zc = n_.minimum(Z, ПЕРСПЕКТИВА - 0.5)
        перспектива = ПЕРСПЕКТИВА / (ПЕРСПЕКТИВА - Zc)
        px = cx + X * R * перспектива
        py = cy - Y * R * перспектива
        глубина = n_.clip((Z + 1.0) * 0.5, 0.0, 1.0)

        # 6. Яркость: ближние ярче, край светится (как у мыльного пузыря),
        # пятно-«зрачок» смотрит на человека, пояса думающего шара, искры.
        яр = 0.45 + 0.75 * глубина ** 1.2
        сфера = 1.0 - сон
        яр += 0.30 * сфера * (1.0 - n_.abs(nz)) ** 2.2
        зрачок = self._смесь("зрачок")
        if состояние.get("человек"):
            зрачок = max(зрачок, 0.6 * сфера)
        if зрачок > 0.01:
            g = (self._взгляд_x * 0.7 + self._голова[0] * 0.9,
                 self._взгляд_y * 0.5 + self._голова[1] * 0.9)
            длина = math.hypot(*g)
            if длина > 0.95:
                g = (g[0] * 0.95 / длина, g[1] * 0.95 / длина)
            gz = math.sqrt(max(0.0, 1.0 - g[0] ** 2 - g[1] ** 2))
            скал = nx * g[0] + ny * g[1] + nz * gz
            яр += 1.1 * зрачок * n_.exp(-(1.0 - скал) / 0.07)
        if в["дума"] > 1e-3:
            пояса = n_.zeros(self.точек, dtype=f32)
            for ax, ay, az, cc in ((0.24, 0.83, 0.50, 0.13), (-0.71, 0.48, 0.39, -0.16),
                                   (0.69, 0.58, -0.41, 0.06)):
                норма = math.sqrt(ax * ax + ay * ay + az * az)
                пр = (nx * ax + ny * ay + nz * az) / норма - cc
                пояса += n_.exp(-(пр * 11.0) ** 2)
            головы = 0.6 + 0.4 * n_.sin(2.0 * n_.arctan2(ny, nx) - _фаза(2.3, t))
            яр += 1.2 * в["дума"] * n_.minimum(1.5, пояса) * головы
        возраст, _ = self._возраст("скан", t)
        if возраст is not None:
            # Скан: светлый меридиан проходит по видимой стороне слева
            # направо — дважды, по 1.2 с, как луч локатора.
            луч = -1.45 + 2.9 * ((возраст / 1.2) % 1.0)
            разн = n_.arctan2(nx, nz) - луч
            яр += 1.4 * n_.exp(-(разн / 0.12) ** 2) * (nz > -0.2) \
                * math.sin(math.pi * возраст / ДЛИТСЯ["скан"])
        # Мерцание: каждая точка чуть дышит своей фазой — шар живой и стоя.
        яр *= 0.86 + 0.14 * n_.sin(self._ф + _фаза(1.6, t))
        искры = self._смесь("искры")
        возраст, _ = self._возраст("прыжок", t)
        if возраст is not None:
            искры = max(искры, math.exp(-возраст / 1.0))
        искра = None
        if искры > 0.01:
            искра = n_.where(s > 0.9, n_.maximum(0.0, n_.sin(_фаза(8.0, t) + 149.0 * s)) ** 18, 0.0) * искры
            яр += 0.9 * искра
        if кольцо_яркость is not None:
            яр += 1.1 * кольцо_яркость
        возраст, _ = self._возраст("сбор", t)
        if возраст is not None:
            # Вспышка при сборе: свечение растёт вместе с тем, как точки
            # возвращаются, а не раньше — иначе свет приходит без шара.
            яр += 0.35 * math.exp(-возраст / 0.5)
        if цифры_вес is not None:
            # Цифры читаются, только если все точки в них одинаково светлые:
            # глубина и мерцание здесь — помеха.
            яр = яр * (1 - цифры_вес) + 1.15 * цифры_вес
        if капли is not None:
            яр *= капли
        яр *= self._смесь("яркость")
        if сон > 1e-3:
            # Кольцо сна ярче: поверх лица ложится ночная тень (55 %), а то и
            # программное притемнение, и без запаса кольцо пропадало совсем.
            яр = яр + 0.8 * сон

        # 7. Цвет: градиент между двумя цветами режима, бегущий по шару.
        а, б = self._цвета_кадра(состояние, п, t)
        дрейф = 0.65 * math.sin(t * 0.21)
        тон = 0.5 + 0.5 * n_.sin(2.1 * P[:, 1] + 1.6 * P[:, 0] + дрейф)
        ra = а[0] + (б[0] - а[0]) * тон
        ga = а[1] + (б[1] - а[1]) * тон
        ba = а[2] + (б[2] - а[2]) * тон
        # Ярче единицы — к белому: ближние и искрящиеся точки «раскаляются».
        перегрев = n_.clip(яр - 1.0, 0.0, 1.0) * (0.65 * float(яркость))
        база = n_.clip(яр, 0.0, 1.0) * float(яркость)
        r8 = ra * база + (255.0 - ra) * перегрев
        g8 = ga * база + (255.0 - ga) * перегрев
        b8 = ba * база + (255.0 - ba) * перегрев
        if искра is not None:
            бел = n_.clip(искра, 0.0, 1.0) * float(яркость)
            r8 = r8 + (ИСКРА[0] - r8) * бел
            g8 = g8 + (ИСКРА[1] - g8) * бел
            b8 = b8 + (ИСКРА[2] - b8) * бел

        # 8. Размер: дальние — точка в пиксель, средние — квадрат два на два,
        # ближние — кружок с мягким ореолом, искры — звёздочка.
        размер = 1 + (глубина > 0.25).astype(n_.int8) + (глубина > 0.62).astype(n_.int8)
        if цифры_вес is not None:
            размер = n_.where(цифры_вес > 0.5, 3, размер)
        if искра is not None:
            размер = n_.where(искра > 0.3, 4, размер)
        self._нарисовать(холст, px, py, глубина, размер, r8, g8, b8)

    # Ореол вокруг ядра два на два: восемь соседей по сторонам — кружок, а не
    # квадрат. Лучи звёздочки — ещё по пикселю дальше.
    _ОРЕОЛ = ((-1, 0), (-1, 1), (2, 0), (2, 1), (0, -1), (1, -1), (0, 2), (1, 2))
    _ЛУЧИ = ((-2, 0), (3, 1), (1, -2), (0, 3))

    def _нарисовать(self, холст, px, py, глубина, размер, r8, g8, b8) -> None:
        """Точки — прямо в пиксели, дальние раньше ближних.

        Без смешивания: ближняя точка закрывает дальнюю, как у настоящей
        сферы. Порядок — по глубине в 256 ступеней: сортировка целых в numpy
        поразрядная, линейная, а не n·log n. Сначала ореолы всех крупных
        точек (тусклые), потом ядра — так ядро соседа не теряется под чужим
        ореолом. Пишем через surfarray.pixels2d — блокировка поверхности и
        прямой доступ к её памяти, без копий; формат пикселя берём у самой
        поверхности, а не угадываем.
        """
        n_ = self.np
        W, H = холст.get_size()
        порядок = n_.argsort((глубина * 255.0).astype(n_.uint8), kind="stable")
        x = n_.round(px[порядок]).astype(n_.int32)
        y = n_.round(py[порядок]).astype(n_.int32)
        s = размер[порядок]
        rr = n_.clip(r8[порядок], 0, 255).astype(n_.uint32)
        gg = n_.clip(g8[порядок], 0, 255).astype(n_.uint32)
        bb = n_.clip(b8[порядок], 0, 255).astype(n_.uint32)
        видно = ((x >= 2) & (x < W - 3) & (y >= 2) & (y < int(НИЗ_ШАРА * H) - 3)
                 & ((rr + gg + bb) > 6))
        if not видно.any():
            self.частей_нарисовано = 0
            return
        x, y, s, rr, gg, bb = x[видно], y[видно], s[видно], rr[видно], gg[видно], bb[видно]
        рс, гс, бс, _ = холст.get_shifts()
        рп, гп, бп, _ = холст.get_losses()
        альфа = холст.get_masks()[3]

        def упаковать(r, g, b):
            return ((r >> рп) << рс) | ((g >> гп) << гс) | ((b >> бп) << бс) | альфа

        цвет = упаковать(rr, gg, bb)
        try:
            пиксели = pygame.surfarray.pixels2d(холст)
        except Exception:                                    # noqa: BLE001
            # Поверхность без прямого доступа (не 32/24 бита) — точками через
            # fill, медленнее, но шар всё равно есть.
            for xi, yi, si, ci in zip(x.tolist(), y.tolist(), s.tolist(), цвет.tolist()):
                холст.fill(холст.unmap_rgb(ci), (xi, yi, min(si, 2), min(si, 2)))
            self.частей_нарисовано = len(x)
            return
        try:
            тип = пиксели.dtype
            крупные = s >= 3
            if крупные.any():
                xк, yк = x[крупные], y[крупные]
                тускло = упаковать((rr[крупные] * 3) >> 3, (gg[крупные] * 3) >> 3,
                                   (bb[крупные] * 3) >> 3).astype(тип)
                for dx, dy in self._ОРЕОЛ:
                    пиксели[xк + dx, yк + dy] = тускло
                звёзды = s[крупные] >= 4
                if звёзды.any():
                    xз, yз, тз = xк[звёзды], yк[звёзды], тускло[звёзды]
                    for dx, dy in self._ЛУЧИ:
                        пиксели[xз + dx, yз + dy] = тз
            цвет = цвет.astype(тип)
            пиксели[x, y] = цвет
            два = s >= 2
            if два.any():
                x2, y2, c2 = x[два], y[два], цвет[два]
                пиксели[x2 + 1, y2] = c2
                пиксели[x2, y2 + 1] = c2
                пиксели[x2 + 1, y2 + 1] = c2
        finally:
            del пиксели
        self.частей_нарисовано = len(x)

    # --- путь без numpy ----------------------------------------------------------
    def _кадр_python(self, холст, состояние, п, поза, t, яркость) -> None:
        """Беднее, но живой: вращение, дыхание, речь, кольцо сна, цвета.

        Волны, пояса, пружины, фигуры и искры — только с numpy: каждая из
        них — несколько синусов на точку, а здесь точка стоит строки Python
        на A55.
        """
        дыхание, радиус, рот, рыск, тангаж, крен, сплющ = self._общие(состояние, п, поза, t)
        R = self.радиус
        cx_d, cy_d, sx_d, sy_d = self._сдвиги_центра(t)
        cx, cy = self._cx + cx_d, self._cy + cy_d
        self.центр = (cx, cy)
        радиус *= 1.0 + 0.10 * рот
        сон = self.веса["сон"]
        угол = self._поворот + рыск
        c, sn = math.cos(угол), math.sin(угол)
        a = НАКЛОН_ОСИ + тангаж
        ca, sa = math.cos(a), math.sin(a)
        cr, sr = math.cos(крен), math.sin(крен)
        а, б = self._цвета_кадра(состояние, п, t)
        множ = self._смесь("яркость") * float(яркость)
        W, H = холст.get_size()
        # Касание и без numpy отвечает сразу: точки вокруг пальца вспыхивают
        # и чуть проседают, гаснет за полсекунды. Беднее волны, но палец не
        # остаётся без ответа — а именно этот путь работает, когда numpy
        # сломан.
        тронут = None
        for вид in ("касание", "гладят", "тычок"):
            возраст, где = self._возраст(вид, t)
            if возраст is not None:
                c3 = где if где else (0.0, 0.0, 1.0)
                тронут = (c3, math.exp(-возраст / 0.5))
                break
        точки = []
        for i, (x, y, z) in enumerate(self._точки_список):
            x1 = x * c + z * sn
            z1 = -x * sn + z * c
            y2 = y * ca - z1 * sa
            z2 = y * sa + z1 * ca
            nx = x1 * cr - y2 * sr
            ny = x1 * sr + y2 * cr
            X, Y, Z = nx * радиус * sx_d, ny * радиус * sy_d * сплющ, z2 * радиус
            вспышка = 0.0
            if тронут is not None:
                (tx_, ty_, tz_), сила = тронут
                близко = max(0.0, nx * tx_ + ny * ty_ + z2 * tz_) ** 6 * сила
                X, Y, Z = X * (1 - 0.08 * близко), Y * (1 - 0.08 * близко), Z * (1 - 0.08 * близко)
                вспышка = близко
            if сон > 1e-3:
                q, тк = self._кольцо_список[i]
                q += _фаза(0.08, t)
                X = X * (1 - сон) + КОЛЬЦО_СНА[0] * тк * дыхание * math.cos(q) * сон
                Y = Y * (1 - сон) + КОЛЬЦО_СНА[1] * тк * дыхание * math.sin(q) * сон
                Z = Z * (1 - сон)
            пер = ПЕРСПЕКТИВА / (ПЕРСПЕКТИВА - min(Z, ПЕРСПЕКТИВА - 0.5))
            глубина = _ограничить((Z + 1.0) * 0.5, 0.0, 1.0)
            яр = (0.45 + 0.75 * глубина ** 1.2 + 0.9 * вспышка) * множ + 0.8 * сон
            тон = 0.5 + 0.5 * math.sin(2.1 * y + 1.6 * x)
            цвет = tuple(int(_ограничить((а[k] + (б[k] - а[k]) * тон) * яр, 0, 255))
                         for k in range(3))
            размер = 1 + (глубина > 0.25) + (глубина > 0.62)
            точки.append((глубина, int(cx + X * R * пер), int(cy - Y * R * пер), размер, цвет))
        точки.sort(key=lambda т: т[0])
        нарисовано = 0
        for _, px, py, размер, цвет in точки:
            if 0 <= px < W - 3 and 0 <= py < int(НИЗ_ШАРА * H) - 3 and sum(цвет) > 6:
                холст.fill(цвет, (px, py, размер, размер))
                нарисовано += 1
        self.частей_нарисовано = нарисовано
