"""Шар из точек — лицо робота. Рисует сам робот, без ПК и без видеокарты.

ЧТО ЭТО. Полторы тысячи точек на сфере, которые дышат, крутятся, слушают,
думают, говорят, рассыпаются и собираются обратно, складываются в сердце, в
тор, в галактику и в цифры часа. Тема известная: «шар» голосовых помощников
(ChatGPT Voice, Siri, Rabbit), вирусный шар из точек brushknight, десятки
three.js-примеров «Fibonacci sphere». Ни одной механики здесь не придумано с
потолка: формулы и числа взяты из открытых реализаций (Ship Notes voice-orb,
aria-voice, Engine-NEXUS, jarvis HUD, Home Assistant Voice PE, thinking-orbs)
и сведены под одно правило проекта — каждое состояние робота обязано читаться
ДВИЖЕНИЕМ, а не только цветом. Цвет люди замечают вторым.

ПОЧЕМУ ШАР, А НЕ ЧЕЛОВЕЧЕК. Решение хозяина: персонажей на экране не будет —
ни домовёнка, которого рисовал робот, ни Live2D-Марка с ПК. Шар рисует сам
робот, и ему не нужен ни ПК, ни сеть: выключенный компьютер больше не значит
пустой экран.

ЧТО ШАРОМ ДВИЖЕТ. То же, что двигало персонажа, — ничего своего:

  • состояние робота (face.json): эмоция, речь и громкость рта, музыка,
    ночь, взгляд на человека — это РЕЖИМЫ шара (`РЕЖИМЫ`);
  • сценки (face/scenes.py, 489 штук) — их ПОВОДЫ становятся событиями шара
    (`СОБЫТИЯ`: пришёл человек — шар собирается заново, погладили — по нему
    идёт волна, пробил час — точки складываются в цифры), а их ПАРАМЕТРЫ —
    позой шара: «повернул голову» поворачивает шар, «помахал рукой» выпускает
    лепесток точек вбок, «прищурился» сплющивает, «улыбнулся» теплит цвет.
    Движок жизни (настроение, привычка, обучение) остаётся главным — шар у
    него просто новое тело;
  • поза Питомца (face/character.py): взгляд, саккады, дыхание — «мозг тела»
    остаётся прежним и проверенным, меняется только то, во что он одет.

КАК РИСУЕТ. numpy считает всё сразу на массивах и пишет точки прямо в
пиксели (surfarray.pixels2d): замер — около 0.7 мс на кадр шара на x86, что
на A55 даёт порядка 5 мс. Нет numpy — шар всё равно есть, но беднее: 260
точек и только главные механики, через `Surface.fill` по точке. Не успевает
кадр — главный цикл зовёт `подстроить`: сначала гаснет свечение, потом
уходят точки.

numpy на роботе проверяется в ОТДЕЛЬНОМ процессе, прежде чем импортироваться
сюда. Это не перестраховка: в сентябре 2026 venv голоса падал на импорте numpy
от SIGILL, а такой сигнал не ловится никаким try — процесс просто умирает. Лицо
обязано подниматься всегда, поэтому сломанный numpy значит «рисую беднее», а
не «перезапускаюсь каждые три секунды».

ВОСПРОИЗВОДИМО. Время приходит снаружи (`t`), случай — из переданного
генератора. Одна и та же секунда при тех же входах — одна и та же картинка.
На этом держатся проверки.
"""

