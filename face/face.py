#!/usr/bin/env python3
"""Лицо робота на экране. Отдельная служба, рисует во фреймбуфер.

ЧТО ЭТА ПРОГРАММА ЗНАЕТ. Ничего про робота. Она умеет прочитать файл
`/run/robot-ai/face.json`, который выкладывает голосовая служба, и нарисовать
то, что там написано: глаза с эмоцией, строку состояния, последнюю
услышанную фразу, батарею, погоду и музыку. Всё знание о том, что робот
делает, живёт в голосовой службе (robot_voice/face.py) — здесь только кисть.

ПОЧЕМУ ОТДЕЛЬНЫМ ПРОЦЕССОМ И БЕЗ БРАУЗЕРА. Оба довода из docs/screen.md:
лицо не должно замирать, пока модель думает; и браузер на восьми A55 съест
то, что нужно BPU для зрения. Бюджет — не больше десятой доли одного ядра.
Поэтому pygame прямо в DRM/фреймбуфер, без X, и тридцать кадров в секунду.

ТРИ ЗАПРЕТА ИЗ ТЗ, и как они выполнены здесь:

  1. Замершее лицо запрещено. Файл старше секунды — лицо уходит в «сплю»:
     свежесть ПРОВЕРЯЕТСЯ, а не предполагается. А если умерла сама эта
     программа — в finally рисуется статичный кадр «экран отвалился», и
     systemd поднимает её заново. (От SIGKILL finally не спасает; это
     записано честно, а не спрятано.)
  2. Экран не показывает состояний, которых нет в коде. Эмоций здесь ровно
     столько, сколько присылает голосовая служба; ни одной своей.
  3. Тач — не единственный способ остановить. Тача сейчас нет вовсе.

ПРОПОРЦИИ — В ДОЛЯХ ВЫСОТЫ ЭКРАНА H, как в ТЗ: одна сетка на 8" и 7",
ничего не пересчитывать руками. Все числа ниже — из таблиц docs/screen.md §5.

ЗВУК НЕ ТРОГАЕМ. `pygame.init()` поднимает и микшер, а он полезет в ALSA —
на звуковую карту, которой владеют микрофон и голос робота. Поэтому
поднимаются только экран и шрифты, по отдельности.
"""

