# --- форма глаз ---------------------------------------------------------------
def форма_глаз(эмоция: str) -> dict:
    """Параметры пары глаз для эмоции, в долях H.

    высота, ширина, радиус — размеры; сдвиг_л/сдвиг_п — вертикальный сдвиг
    каждого глаза; наклон — градусы, положительный = внутрь; дуга_снизу —
    низ уходит дугой вверх (радость); дрожь — амплитуда в долях H;
    зрачки — глаза плавают влево-вправо (думаю); блик — яркость блика 0..1.

    Абсолютные числа ниже (не «×ГЛАЗ_ВЫСОТА», а сами по себе) считаны для
    старого, вдвое большего базового размера глаза (ТЗ §5: 0.34H). Когда
    глаза уменьшили под тело, эти числа пересчитаны в той же пропорции к
    новому базовому размеру — иначе, например, «рад» рисовал бы глаза
    БОЛЬШЕ обычных вместо чуть уже.
    """
    базовая = dict(высота=ГЛАЗ_ВЫСОТА, ширина=ГЛАЗ_ШИРИНА, радиус=ГЛАЗ_РАДИУС,
                   сдвиг_л=0.0, сдвиг_п=0.0, наклон=0.0, дуга_снизу=0.0,
                   дрожь=0.0, зрачки=0.0, блик=0.6)
    if эмоция == "рад":
        базовая.update(высота=0.16, дуга_снизу=1.0)
    elif эмоция == "слушаю":
        базовая.update(высота=ГЛАЗ_ВЫСОТА * 1.08, ширина=ГЛАЗ_ШИРИНА * 1.08,
                       блик=1.0)
    elif эмоция == "думаю":
        базовая.update(высота=0.145, зрачки=1.0)
    elif эмоция == "не_понял":
        базовая.update(сдвиг_л=-0.028, наклон=8.0)
    elif эмоция == "огорчён":
        базовая.update(наклон=12.0)
    elif эмоция == "встревожен":
        базовая.update(ширина=0.12, дрожь=2.0 / 800.0)   # ±2 px на 8", 6 Гц
    elif эмоция == "сплю":
        базовая.update(высота=0.034, блик=0.0)
    return базовая


def _смешать(а: dict, б: dict, доля: float) -> dict:
    """Линейно между двумя формами. доля 0 — а, 1 — б."""
    доля = max(0.0, min(1.0, доля))
    return {к: а[к] + (б[к] - а[к]) * доля for к in а}


def _цвет(ц: tuple, яркость: float) -> tuple:
    яркость = max(0.0, min(1.0, яркость))
    return tuple(int(round(c * яркость)) for c in ц)


# --- чтение состояния --------------------------------------------------------
def прочитать(файл: Path, сейчас: float | None = None) -> tuple[dict, str]:
    """(состояние, почему такое). Старый или битый файл — «сплю».

    Свежесть проверяется настенными часами: файл писал ДРУГОЙ процесс, и
    сравнивать его метку надо с тем же, чем он её ставил. Это единственное
    место, где настенные часы здесь законны.
    """
    сейчас = time.time() if сейчас is None else сейчас
    try:
        данные = json.loads(файл.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"эмоция": "сплю"}, "файла нет"
    if not isinstance(данные, dict):
        return {"эмоция": "сплю"}, "файл не тот"
    возраст = сейчас - float(данные.get("когда") or 0)
    if возраст > СТАРЕЕТ:
        # Старое лицо хуже спящего: человек думает, что робот работает.
        return {"эмоция": "сплю", "батарея": данные.get("батарея")}, \
            f"состоянию {возраст:.1f} с"
    if данные.get("эмоция") not in ЭМОЦИИ:
        данные["эмоция"] = "спокоен"
    return данные, "свежее"


# --- отрисовка ----------------------------------------------------------------
class Кисть:
    """Рисует один кадр по состоянию. Никакого чтения файлов и часов внутри.

    Всё время приходит снаружи (`t`), поэтому кадр воспроизводим: одна и та
    же секунда — один и тот же рисунок. На этом держится проверка.
    """

    def __init__(self, ширина: int, высота: int, *, шрифт: str = ШРИФТ,
                 жирный: str = ШРИФТ_ЖИРНЫЙ, случай=random.Random(7)) -> None:
        self.W, self.H = ширина, высота
        self.случай = случай
        self._шрифты: dict = {}
        self._шрифт_путь = шрифт if os.path.exists(шрифт) else None
        self._жирный_путь = жирный if os.path.exists(жирный) else None
        # Плавные переходы: откуда идём, куда и с какого момента.
        self._была = "спокоен"
        self._стала = "спокоен"
        self._переход_с = -1.0
        # Взгляд сглаживаем: пеленг с камеры дёргается, глаза — нет.
        self._взгляд = 0.0
        # Моргание.
        self._морг_в = 0.0
        self._следующий_морг = случай.uniform(*МОРГ_РАЗ_В)
        self.кадров = 0
        # Тело: где стоит, куда идёт, что делают руки и ноги. Отдельный
        # класс — своя логика, проверяемая без единого вызова pygame.
        #
        # Границы блуждания считаются от ширины — а самая широкая часть
        # персонажа не туловище, а уши: они торчат за его край. Отдать
        # Питомцу настоящую ширину силуэта, а не ширину одного туловища, —
        # иначе поля вокруг экрана считаются от того, чего на самом деле нет.
        ширина_силуэта = max(ТЕЛО_ШИРИНА, 2 * (УХО_ОТСТУП + УХО_РАДИУС))
        # И виджет погоды справа — тоже часть картины, а не только персонаж.
        # Он никуда не гаснет и не движется, пока идёт блуждание (музыка
        # занимает левый угол, но пока играет, сюда же и не заходят — см.
        # запас_справа в character.py), и на живом снимке персонаж однажды
        # дошёл и встал прямо под ним, уши поверх температуры. Считаем от
        # тех же чисел, что рисует _погода(), а не на глаз: левый край
        # температуры у «-15°» и «+5°» разный, меряем настоящим шрифтом.
        поле_виджета_px = ПОЛЯ * ширина
        r_виджета_px = 0.07 * высота
        # «+» шире «-» в этом жирном шрифте — «+99°» задаёт настоящий
        # наихудший случай, а не «-15°», который казался таким на глаз.
        температура_px = self._шрифт(0.09, True).size("+99°")[0]
        погода_левый_край_px = (ширина - поле_виджета_px - 2 * r_виджета_px
                                - 0.02 * ширина - температура_px)
        буфер_px = 0.02 * высота
        половина_силуэта_px = ширина_силуэта * высота / 2
        макс_x_нужен_px = погода_левый_край_px - половина_силуэта_px - буфер_px
        запас_справа = max(0.0, (ширина - character.ПОЛЯ * высота
                                 - половина_силуэта_px - макс_x_нужен_px) / высота)
        self.питомец = character.Питомец(
            ширина, высота, тело_ширина=ширина_силуэта, шаг_длина=НОГА_ШАГ_ДЛИНА,
            запас_справа=запас_справа, случай=random.Random(случай.random()))
        # Поза последнего кадра — наружу, для самопроверки: пиксели глаз и
        # тела сходятся туда, где персонаж стоит СЕЙЧАС, а не там, где он
        # стоял бы, если бы никогда не двигался.
        self.поза: dict = {"x": ширина / 2.0, "подскок": 0.0, "наклон": 0.0,
                           "рот": 0.0, "рука_л": 0.0, "рука_п": 0.0,
                           "нога": 0.0, "метка": "стоит"}

    # --- шрифты -------------------------------------------------------------
    def _шрифт(self, доля_H: float, жирный: bool = False):
        # Высота заглавной ≈ 0.72 кегля у DejaVu; кегль подбираем под H.
        кегль = max(8, int(round(доля_H * self.H / 0.72)))
        ключ = (кегль, жирный)
        if ключ not in self._шрифты:
            путь = self._жирный_путь if жирный else self._шрифт_путь
            try:
                ш = pygame.font.Font(путь, кегль) if путь else pygame.font.SysFont(
                    "dejavusans,freesans,sans", кегль, bold=жирный)
            except Exception:                   # noqa: BLE001
                ш = pygame.font.Font(None, кегль)
            self._шрифты[ключ] = ш
        return self._шрифты[ключ]

    def _текст(self, холст, текст: str, x: int, y: int, доля_H: float,
               цвет, *, жирный=False, справа=False, не_шире: int | None = None):
        if not текст:
            return 0
        ш = self._шрифт(доля_H, жирный)
        if не_шире is not None:
            while текст and ш.size(текст)[0] > не_шире:
                текст = текст[:-2] + "…" if len(текст) > 2 else ""
        картинка = ш.render(текст, True, цвет)
        if справа:
            x -= картинка.get_width()
        холст.blit(картинка, (x, y))
        return картинка.get_width()

    # --- эмоция с переходом ------------------------------------------------
    def _форма(self, эмоция: str, t: float) -> dict:
        if эмоция != self._стала:
            self._была, self._стала, self._переход_с = self._стала, эмоция, t
        доля = 1.0 if self._переход_с < 0 else (t - self._переход_с) / ПЕРЕХОД
        return _смешать(форма_глаз(self._была), форма_глаз(self._стала), доля)

    # --- моргание -------------------------------------------------------------
    def _моргание(self, t: float, спит: bool) -> float:
        """Доля высоты глаза 0..1 с учётом моргания. Спящий не моргает."""
        if спит:
            return 1.0
        if self._морг_в == 0.0 and t >= self._следующий_морг:
            self._морг_в = t
        if self._морг_в == 0.0:
            return 1.0
        прошло = t - self._морг_в
        if прошло < МОРГ_ЗАКРЫТЬ:
            return 1.0 - прошло / МОРГ_ЗАКРЫТЬ
        if прошло < МОРГ_ЗАКРЫТЬ + МОРГ_ДЕРЖАТЬ:
            return 0.0
        if прошло < МОРГ_ЗАКРЫТЬ + МОРГ_ДЕРЖАТЬ + МОРГ_ОТКРЫТЬ:
            return (прошло - МОРГ_ЗАКРЫТЬ - МОРГ_ДЕРЖАТЬ) / МОРГ_ОТКРЫТЬ
        self._морг_в = 0.0
        self._следующий_морг = t + self.случай.uniform(*МОРГ_РАЗ_В)
        return 1.0

    # --- глаза ----------------------------------------------------------------
    def _глаз(self, холст, cx: float, cy: float, ф: dict, открыт: float,
              наклон_знак: int, цвет, t: float) -> None:
        H = self.H
        w = ф["ширина"] * H
        h = max(МОРГ_ВЫСОТА * H, ф["высота"] * H * открыт)
        r = min(ф["радиус"] * H, h / 2, w / 2)
        if ф["дрожь"] > 0:
            cx += math.sin(t * 2 * math.pi * 6.0) * ф["дрожь"] * H
        # Рисуем в отдельной поверхности, чтобы наклонить и вырезать дугу.
        запас = int(h * 0.6) + 4
        пов = pygame.Surface((int(w) + 2 * запас, int(h) + 2 * запас), pygame.SRCALPHA)
        прям = pygame.Rect(запас, запас, int(w), int(h))
        pygame.draw.rect(пов, цвет, прям, border_radius=int(r))
        if ф["дуга_снизу"] > 0:
            # Радость: низ глаза уходит дугой вверх. Вырезаем эллипс фоном.
            # Не глубже 0.42 высоты: глубже — глаз превращается в две скобки,
            # и центр его исчезает. Улыбка читается уже при трети.
            выс_дуги = int(h * 0.42 * ф["дуга_снизу"])
            дуга = pygame.Rect(запас - int(w * 0.1), запас + int(h) - выс_дуги,
                               int(w * 1.2), выс_дуги * 2)
            pygame.draw.ellipse(пов, (0, 0, 0, 0), дуга)
        if ф["блик"] > 0 and открыт > 0.3:
            бл = _цвет(БЛИК, ф["блик"])
            rr = max(2, int(h * 0.12))
            pygame.draw.circle(пов, бл, (запас + int(w * 0.72), запас + int(h * 0.25)), rr)
        if ф["наклон"]:
            пов = pygame.transform.rotate(пов, -ф["наклон"] * наклон_знак)
        холст.blit(пов, пов.get_rect(center=(int(cx), int(cy))))

    def _глаза(self, холст, ф: dict, состояние: dict, t: float, яркость: float,
               спит: bool, x_центр: float, подскок: float) -> None:
        H = self.H
        цвет_глаз = ГЛАЗА_НОЧЬЮ if состояние.get("ночь") else ГЛАЗА
        if состояние.get("эмоция") == "встревожен":
            цвет_глаз = ТРЕВОГА
        цвет = _цвет(цвет_глаз, яркость)
        открыт = self._моргание(t, спит)
        # Взгляд: к человеку по пеленгу, влево — плюс. На экране влево — минус x.
        цель = 0.0
        if состояние.get("взгляд") is not None and not спит:
            угол = float(состояние["взгляд"])
            цель = -max(-1.0, min(1.0, угол / math.radians(45))) * ВЗГЛЯД_ДО * H
        self._взгляд += (цель - self._взгляд) * 0.2
        зрачки = math.sin(t * 2 * math.pi * 0.35) * ф["зрачки"] * ВЗГЛЯД_ДО * H * 0.6
        сдвиг_x = self._взгляд + зрачки

        # Голова сидит на теле: центр по x и подскок — от персонажа, а не от
        # середины экрана. Наклон тела на глаза намеренно не переносим — у
        # них своя, эмоциональная асимметрия (форма_глаз), и две причины
        # наклона в одном градусе только запутали бы.
        cy = ГЛАЗА_ЦЕНТР_ОТ_ВЕРХА * H - подскок
        пол_просвета = ПРОСВЕТ * H / 2
        пол_ширины = ф["ширина"] * H / 2
        cx_л = x_центр - пол_просвета - пол_ширины + сдвиг_x
        cx_п = x_центр + пол_просвета + пол_ширины + сдвиг_x
        self._глаз(холст, cx_л, cy + ф["сдвиг_л"] * H, ф, открыт, +1, цвет, t)
        self._глаз(холст, cx_п, cy + ф["сдвиг_п"] * H, ф, открыт, -1, цвет, t)

    # --- тело ------------------------------------------------------------------
    def _рот(self, холст, x: float, подскок: float, открыт: float, цвет) -> None:
        H = self.H
        w = РОТ_ШИРИНА * H
        h = max(1.0, (РОТ_ЗАКРЫТ + (РОТ_ОТКРЫТ - РОТ_ЗАКРЫТ) * открыт) * H)
        cy = РОТ_ОТ_ВЕРХА * H - подскок
        rect = pygame.Rect(0, 0, int(w), int(h))
        rect.center = (int(x), int(cy))
        pygame.draw.rect(холст, цвет, rect, border_radius=int(РОТ_РАДИУС * H))

    def _тело(self, холст, x: float, подскок: float, наклон: float,
              цвет, цвет_тени) -> None:
        H = self.H
        w, h = ТЕЛО_ШИРИНА * H, ТЕЛО_ВЫСОТА * H
        cy = (ТЕЛО_ОТ_ВЕРХА * H - подскок) + h / 2
        запас = 6
        пов = pygame.Surface((int(w) + 2 * запас, int(h) + 2 * запас), pygame.SRCALPHA)
        rect = pygame.Rect(запас, запас, int(w), int(h))
        pygame.draw.ellipse(пов, цвет, rect)
        # Пояс — полоса поперёк живота, а не техническая панель: рубаха, а
        # не приборный щиток. Без него живот читался как один плоский овал.
        пояс = pygame.Rect(запас, запас + int(h * ПОЯС_ОТ_ВЕРХА),
                           int(w), max(1, int(h * ПОЯС_ТОЛЩИНА)))
        pygame.draw.ellipse(пов, цвет_тени, пояс.inflate(-int(w * 0.04), 0))
        if наклон:
            пов = pygame.transform.rotate(пов, -наклон)
        холст.blit(пов, пов.get_rect(center=(int(x), int(cy))))

    def _чуб(self, холст, x: float, подскок: float, цвет) -> None:
        """Растрёпанный хохолок над глазами — без него силуэт лысый и никого
        не напоминает; с ним сразу видно, что это не робот, а домовой.
        """
        H = self.H
        верх = ЧУБ_ОТ_ВЕРХА * H - подскок
        for сдвиг, высота, наклон in ((-0.022, 1.0, -18), (0.0, 1.15, 0),
                                       (0.022, 0.85, 18)):
            cx = x + сдвиг * H
            h = ЧУБ_ВЫСОТА * H * высота
            w = ЧУБ_ШИРИНА * H
            пов = pygame.Surface((int(w) + 4, int(h) + 4), pygame.SRCALPHA)
            pygame.draw.polygon(пов, цвет, [(2, int(h) + 2), (int(w) + 2, int(h) + 2),
                                            (int(w / 2) + 2, 2)])
            пов = pygame.transform.rotate(пов, наклон)
            холст.blit(пов, пов.get_rect(midbottom=(int(cx), int(верх + h * высота))))

    def _уши(self, холст, x: float, подскок: float, цвет) -> None:
        H = self.H
        cy = ГЛАЗА_ЦЕНТР_ОТ_ВЕРХА * H - подскок
        r = int(УХО_РАДИУС * H)
        for бок in (-1, +1):
            pygame.draw.circle(холст, цвет, (int(x + бок * УХО_ОТСТУП * H), int(cy)), r)

    def _руки(self, холст, x: float, подскок: float,
              рука_л: float, рука_п: float, цвет) -> None:
        """Лапки висят от плеча и качаются вокруг НЕГО, а не вокруг своей
        середины: поворот вокруг центра превращает короткую фигуру в
        пропеллер, торчащий сквозь тело, — так и было до этой правки.

        Лапку с нулевым углом НЕ РИСУЕМ вовсе. Прижатая к боку фигурка у
        самого края туловища на живом экране читалась не как рука в покое,
        а как торчащий в сторону обломок — то самое «некрасиво» с первого же
        живого снимка. Руки нужны, чтобы что-то показать (танец, разговор),
        а не чтобы стоять молча — молча они только мешают.
        """
        H = self.H
        w, h = РУКА_ШИРИНА * H, РУКА_ВЫСОТА * H
        плечо_y = ТЕЛО_ОТ_ВЕРХА * H - подскок + h * 0.25
        отступ = ТЕЛО_ШИРИНА * H / 2 - w * 0.25
        запас = 6
        пов = pygame.Surface((int(w) + 2 * запас, int(h) + 2 * запас), pygame.SRCALPHA)
        rect = pygame.Rect(запас, запас, int(w), int(h))
        pygame.draw.ellipse(пов, цвет, rect)
        # Плечо сидит на верхнем крае фигуры, а не в её середине: смещение от
        # опоры до центра поверхности до поворота — вниз на h/2.
        смещение = pygame.Vector2(0.0, h / 2)
        for бок, угол in ((-1, рука_л), (+1, рука_п)):
            if abs(угол) < 0.5:
                continue
            опора = (x + бок * отступ, плечо_y)
            повёрнутая = pygame.transform.rotate(пов, угол)
            новое_смещение = смещение.rotate(-угол)
            холст.blit(повёрнутая, повёрнутая.get_rect(
                center=(опора[0] + новое_смещение.x, опора[1] + новое_смещение.y)))

    def _тень(self, холст, x: float, подскок: float, яркость: float) -> None:
        """Мягкое пятно под ногами. Без него тело будто висит в воздухе —
        особенно заметно на неподвижном снимке, где подпрыгивание не видно.
        Тень не двигается вместе с подскоком: она про то, где пол, а не про
        то, где сейчас персонаж, — иначе подпрыгнувший вверх вместе с тенью
        выглядел бы приклеенным к ней, а не оторвавшимся от земли.
        """
        H = self.H
        w = ТЕНЬ_ШИРИНА * H
        h = w * 0.16
        cy = (ТЕЛО_ОТ_ВЕРХА + ТЕЛО_ВЫСОТА) * H + НОГА_ВЫСОТА * H * 0.5
        пятно = pygame.Surface((int(w), int(h)), pygame.SRCALPHA)
        pygame.draw.ellipse(пятно, (*ФОН_ТЕНИ, int(90 * яркость)),
                            пятно.get_rect())
        холст.blit(пятно, пятно.get_rect(center=(int(x), int(cy))))

    def _ноги(self, холст, x: float, подскок: float, нога: float, цвет) -> None:
        """Две ступни переступают в противофазе, пока идёт; иначе стоят.

        «Нога» — фаза, растущая с пройденным путём (см. character.py), а не
        угол колеса: домовой ходит, а не катится.
        """
        H = self.H
        w, h = НОГА_ШИРИНА * H, НОГА_ВЫСОТА * H
        cy0 = (ТЕЛО_ОТ_ВЕРХА + ТЕЛО_ВЫСОТА) * H - подскок
        for бок, фазовый_сдвиг in ((-1, 0.0), (+1, math.pi)):
            cx = x + бок * НОГА_ОТСТУП * H
            подъём = max(0.0, math.sin(нога + фазовый_сдвиг)) * НОГА_ПОДЪЁМ * H
            rect = pygame.Rect(0, 0, int(w), int(h))
            rect.center = (int(cx), int(cy0 - подъём))
            pygame.draw.ellipse(холст, цвет, rect)

    def _зет(self, холст, x: float, подскок: float, t: float, цвет) -> None:
        """«z Z z», всплывающие над спящим — не глаза, а вежливое пояснение."""
        H = self.H
        буквы = (("z", 0.0, 0.055), ("Z", 0.35, 0.075), ("z", 0.7, 0.06))
        for буква, задержка, кегль in буквы:
            фаза = (t * 0.35 + задержка) % 1.0
            непр = int(255 * (1.0 - фаза) ** 1.5)
            if непр <= 0:
                continue
            картинка = self._шрифт(кегль, True).render(буква, True, цвет)
            картинка.set_alpha(непр)
            dx = (0.06 + фаза * 0.10) * H
            dy = -подскок - (ГЛАЗ_ВЫСОТА / 2 + 0.05 + фаза * 0.10) * H
            холст.blit(картинка, (int(x + dx), int(ГЛАЗА_ЦЕНТР_ОТ_ВЕРХА * H + dy)))

    def _зет(self, холст, x: float, подскок: float, t: float, цвет) -> None:
        """«z Z z», всплывающие над спящим — не глаза, а вежливое пояснение."""
        H = self.H
        буквы = (("z", 0.0, 0.055), ("Z", 0.35, 0.075), ("z", 0.7, 0.06))
        for буква, задержка, кегль in буквы:
            фаза = (t * 0.35 + задержка) % 1.0
            непр = int(255 * (1.0 - фаза) ** 1.5)
            if непр <= 0:
                continue
            картинка = self._шрифт(кегль, True).render(буква, True, цвет)
            картинка.set_alpha(непр)
            dx = (0.06 + фаза * 0.10) * H
            dy = -подскок - (ГЛАЗ_ВЫСОТА / 2 + 0.05 + фаза * 0.10) * H
            холст.blit(картинка, (int(x + dx), int(ГЛАЗА_ЦЕНТР_ОТ_ВЕРХА * H + dy)))

    # --- строка состояния ----------------------------------------------------
    def _строка(self, холст, состояние: dict, яркость: float) -> None:
        H, W = self.H, self.W
        верх = int(ЛИЦО_ДО * H)
        поле = int(ПОЛЯ * W)
        pygame.draw.line(холст, _цвет(ТЕКСТ_ТУСКЛЫЙ, яркость * 0.5),
                         (поле, верх), (W - поле, верх), 1)
        цвет = _цвет(ТЕКСТ, яркость)
        тускло = _цвет(ТЕКСТ_ТУСКЛЫЙ, яркость)
        # Слева — что делает. Справа — батарея.
        батарея = состояние.get("батарея")
        справа_текст = f"{батарея:.1f} В" if isinstance(батарея, (int, float)) else "— В"
        ш_справа = self._текст(холст, справа_текст, W - поле, верх + int(0.02 * H),
                               ТЕКСТ_ВЫСОТА, цвет if батарея is not None else тускло,
                               справа=True)
        строка = состояние.get("строка") or ""
        if состояние.get("эмоция") == "сплю":
            строка = "сплю"
        self._текст(холст, строка, поле, верх + int(0.02 * H), ТЕКСТ_ВЫСОТА, цвет,
                    жирный=True, не_шире=W - 2 * поле - ш_справа - поле)
        # Вторая строка — что именно услышал (или говорит). Это не украшение.
        говорит = состояние.get("говорит") or ""
        услышал = состояние.get("услышал") or ""
        подпись = f"› {говорит}" if говорит else (f"« {услышал} »" if услышал else "")
        self._текст(холст, подпись, поле, верх + int(0.095 * H), ПОДПИСЬ_ВЫСОТА,
                    тускло, не_шире=W - 2 * поле)

    # --- виджеты ---------------------------------------------------------------
    def _значок_погоды(self, холст, код: int, x: int, y: int, r: int, цвет, яркость):
        """Солнце / облако / дождь / снег / гроза — формами, без картинок."""
        ясно = код in (0, 1)
        облачно = код in (2, 3, 45, 48)
        дождь = код in (51, 53, 55, 56, 57, 61, 63, 65, 66, 67, 80, 81, 82)
        снег = код in (71, 73, 75, 77, 85, 86)
        гроза = код in (95, 96, 99)
        солнце = _цвет(ТРЕВОГА, яркость)
        if ясно or код == 2:
            pygame.draw.circle(холст, солнце, (x, y), int(r * 0.55))
            for i in range(8):
                a = i * math.pi / 4
                pygame.draw.line(холст, солнце,
                                 (x + math.cos(a) * r * 0.7, y + math.sin(a) * r * 0.7),
                                 (x + math.cos(a) * r * 0.95, y + math.sin(a) * r * 0.95),
                                 max(1, r // 12))
        if облачно or дождь or снег or гроза:
            for dx, dy, rr in ((-0.35, 0.15, 0.45), (0.05, -0.05, 0.55), (0.4, 0.2, 0.4)):
                pygame.draw.circle(холст, цвет, (int(x + dx * r), int(y + dy * r)), int(rr * r))
            pygame.draw.rect(холст, цвет, (int(x - 0.75 * r), int(y + 0.15 * r), int(1.5 * r), int(0.45 * r)))
        if дождь or гроза:
            for i in range(3):
                dx = (i - 1) * 0.35 * r
                pygame.draw.line(холст, _цвет(ГЛАЗА, яркость),
                                 (x + dx, y + 0.75 * r), (x + dx - 0.15 * r, y + 1.15 * r),
                                 max(1, r // 10))
        if снег:
            for i in range(3):
                dx = (i - 1) * 0.35 * r
                pygame.draw.circle(холст, _цвет(БЛИК, яркость), (int(x + dx), int(y + r)), max(1, r // 9))
        if гроза:
            pygame.draw.polygon(холст, солнце, [(x, y + 0.6 * r), (x - 0.2 * r, y + 1.05 * r),
                                                (x + 0.05 * r, y + 1.0 * r), (x - 0.1 * r, y + 1.4 * r),
                                                (x + 0.25 * r, y + 0.9 * r), (x, y + 0.95 * r)])

    def _погода(self, холст, погода: dict | None, яркость: float) -> None:
        if not погода or погода.get("t") is None:
            return
        H, W = self.H, self.W
        поле = int(ПОЛЯ * W)
        r = int(0.07 * H)
        x, y = W - поле - r, int(ПОЛЯ * H) + r
        цвет = _цвет(ТЕКСТ, яркость)
        тускло = _цвет(ТЕКСТ_ТУСКЛЫЙ, яркость)
        self._значок_погоды(холст, int(погода.get("код") or 0), x, y, r, тускло, яркость)
        t = int(погода["t"])
        self._текст(холст, f"{t:+d}°", x - r - int(0.02 * W), y - int(0.05 * H),
                    0.09, цвет, жирный=True, справа=True)
        мин, макс = погода.get("мин"), погода.get("макс")
        if мин is not None and макс is not None:
            self._текст(холст, f"{int(мин):+d}… {int(макс):+d}°", x - r - int(0.02 * W),
                        y + int(0.045 * H), ПОДПИСЬ_ВЫСОТА, тускло, справа=True)
        описание = погода.get("описание") or ""
        self._текст(холст, описание, W - поле, y + r + int(0.02 * H), ПОДПИСЬ_ВЫСОТА,
                    тускло, справа=True, не_шире=int(0.34 * W))

    def _музыка(self, холст, музыка: dict | None, яркость: float, t: float) -> None:
        if not музыка or not музыка.get("играет"):
            return
        H, W = self.H, self.W
        поле = int(ПОЛЯ * W)
        x, y = поле, int(ПОЛЯ * H)
        цвет = _цвет(ГЛАЗА, яркость)
        тускло = _цвет(ТЕКСТ_ТУСКЛЫЙ, яркость)
        # Три столбика, качаются: видно, что играет, а не висит.
        for i in range(3):
            выс = int((0.02 + 0.02 * (1 + math.sin(t * 5 + i * 1.3)) / 2) * H)
            pygame.draw.rect(холст, цвет, (x + i * int(0.012 * H), y + int(0.05 * H) - выс,
                                          int(0.008 * H), выс))
        self._текст(холст, музыка.get("название") or "музыка", x + int(0.05 * H),
                    y + int(0.005 * H), ПОДПИСЬ_ВЫСОТА, тускло, не_шире=int(0.4 * W))

    # --- кадр целиком ----------------------------------------------------------
    def кадр(self, холст, состояние: dict, t: float, яркость: float) -> None:
        """Нарисовать состояние на холст. Всё время — снаружи."""
        холст.fill(ФОН)
        эмоция = состояние.get("эмоция", "спокоен")
        спит = эмоция == "сплю"
        ф = self._форма(эмоция, t)
        self.поза = поза = self.питомец.кадр(состояние, t)
        x, подскок = поза["x"], поза["подскок"]
        цвет_тела = _цвет(ТЕЛО_ЦВЕТ, яркость)
        цвет_тени_тела = _цвет(ТЕЛО_ТЕНЬ, яркость)
        цвет_волос = _цвет(ВОЛОСЫ_ЦВЕТ, яркость)
        self._тень(холст, x, подскок, яркость)
        self._ноги(холст, x, подскок, поза["нога"], цвет_тени_тела)
        self._тело(холст, x, подскок, поза["наклон"], цвет_тела, цвет_тени_тела)
        self._уши(холст, x, подскок, цвет_тела)
        self._руки(холст, x, подскок, поза["рука_л"], поза["рука_п"], цвет_тела)
        self._глаза(холст, ф, состояние, t, яркость, спит, x, подскок)
        if not спит:
            self._чуб(холст, x, подскок, цвет_волос)
        if спит:
            # Ярче тела: на тусклом теле буквы не читались вовсе (проверено
            # по первому же кадру со «сплю» — z были практически не видны).
            self._зет(холст, x, подскок, t, _цвет(ТЕКСТ, min(1.0, яркость * 1.6)))
        else:
            self._рот(холст, x, подскок, поза["рот"], цвет_тела)
        self._строка(холст, состояние, яркость)
        if not спит:
            self._погода(холст, состояние.get("погода"), яркость)
            self._музыка(холст, состояние.get("музыка"), яркость, t)
        self.кадров += 1

    def кадр_отказа(self, холст) -> None:
        """Статичный кадр «экран отвалился». Не лицо: лицо тут было бы ложью."""
        холст.fill(ФОН)
        H, W = self.H, self.W
        цвет = _цвет(ТРЕВОГА, 0.7)
        pygame.draw.rect(холст, цвет, (int(W * 0.44), int(H * 0.30), int(W * 0.12), int(H * 0.22)), 3)
        pygame.draw.line(холст, цвет, (int(W * 0.44), int(H * 0.30)), (int(W * 0.56), int(H * 0.52)), 3)
        self._текст(холст, "экран отвалился", W // 2 - int(W * 0.14), int(H * 0.6),
                    ТЕКСТ_ВЫСОТА, цвет, жирный=True)
        self._текст(холст, "робот может работать; лицо перезапустится само",
                    W // 2 - int(W * 0.28), int(H * 0.7), ПОДПИСЬ_ВЫСОТА,
                    _цвет(ТЕКСТ_ТУСКЛЫЙ, 0.8))


# --- яркость: подсветка и экономия -------------------------------------------
class Яркость:
    """Сколько света: ТЗ §7. Видим человека или говорим — 100%; молчим и
    никого нет минуту — 30%; три минуты — гасим. Ночь — 15% и теплее.

    Аппаратную подсветку крутим через /sys/class/backlight, если она там есть;
    если нет — рисуем темнее. Второе хуже (панель светит фоном), но без
    первого лучше так, чем никак.
    """

    def __init__(self, часы=time.monotonic) -> None:
        self._часы = часы
        self._живо_с = часы()
        self._подсветка = self._найти_подсветку()
        self._выставлено = -1

    @staticmethod
    def _найти_подсветку() -> Path | None:
        for п in Path("/sys/class/backlight").glob("*"):
            if (п / "brightness").exists() and (п / "max_brightness").exists():
                return п
        return None

    def доля(self, состояние: dict) -> float:
        сейчас = self._часы()
        if состояние.get("человек") or состояние.get("говорит") or состояние.get("едет"):
            self._живо_с = сейчас
        основа = ЯРКОСТЬ_НОЧЬЮ if состояние.get("ночь") else ЯРКОСТЬ_ДНЁМ
        if состояние.get("эмоция") == "сплю":
            return основа * ТУСКЛО
        тихо = сейчас - self._живо_с
        if тихо > ГАСНУТЬ_ЧЕРЕЗ:
            return 0.0
        if тихо > ТУСКНЕТЬ_ЧЕРЕЗ:
            return основа * ТУСКЛО
        return основа

    def применить(self, доля: float) -> float:
        """Вернуть, какую яркость рисовать программно (после аппаратной)."""
        if self._подсветка is None:
            return доля
        try:
            макс = int((self._подсветка / "max_brightness").read_text())
            значение = int(round(макс * max(0.0, min(1.0, доля))))
            if значение != self._выставлено:
                (self._подсветка / "brightness").write_text(str(значение))
                self._выставлено = значение
            return 1.0 if доля > 0 else 0.0
        except OSError:
            self._подсветка = None
            return доля


# --- главный цикл -------------------------------------------------------------
class _ЧерезSDL:
    """Экран, который открыл SDL: рисуем прямо в него."""

    def __init__(self, экран, имя: str) -> None:
        self.поверхность = экран
        self.имя = имя

    def показать(self) -> None:
        pygame.display.flip()

    def закрыть(self) -> None:
        pygame.display.quit()


class _ЧерезDRM:
    """Экран через dumb-буферы DRM: рисуем в память, копируем в ядро."""

    def __init__(self, экран: drmout.ЭкранDRM) -> None:
        self._экран = экран
        self.поверхность = pygame.Surface((экран.width, экран.height), 0, 32,
                                          masks=drmout.МАСКИ)
        self.имя = "DRM dumb-буферы"

    def показать(self) -> None:
        self._экран.показать(self.поверхность)

    def закрыть(self) -> None:
        self._экран.закрыть()


def нужен_насос_событий(вывод) -> bool:
    """Очередь событий SDL жива, только если жива видеосистема SDL.

    На DRM-пути (_ЧерезDRM) display.quit() уже вызван до открытия экрана, и
    pygame.event.get() тут же упал бы с «video system not initialized». А
    слать нам QUIT в киоске всё равно некому — оконного менеджера нет ни на
    одном из путей, это чисто защита от падения. Отдельной функцией — чтобы
    проверить решение без запуска бесконечного главного цикла.
    """
    return isinstance(вывод, _ЧерезSDL)


# Драйверы SDL, которые открываются всегда и рисуют в никуда. Принять такой за
# экран — значит тридцать кадров в секунду в память и «30 к/с» в журнале при
# тёмной панели. Ровно так и было на роботе: «1024×768 через SDL по
# умолчанию» — а такого разрешения нет ни у одной из наших панелей.
ЗАГЛУШКИ = {"dummy", "offscreen"}


def _открыть_экран():
    """SDL (kmsdrm по каждой карте → fbcon → любой настоящий) → DRM напрямую.

    ОШИБКА, КОТОРАЯ ТУТ БЫЛА, ДВАЖДЫ. Первый `display.init()` стоял ДО цикла с
    запасными вариантами — он и падал, до перебора не доходило. А потом SDL
    «по умолчанию» открыл заглушку, и код объявил это экраном, не спросив у
    SDL, какой драйвер тот выбрал. Теперь спрашивает, и заглушки не считает.

    ПОЧЕМУ НУЖЕН DRM НАПРЯМУЮ. На RDK X5 DRM-драйвер — VeriSilicon vs-drm, и у
    Mesa для него нет модуля. SDL-овский kmsdrm без Mesa/GBM работать не
    может в принципе, /dev/fb* на этом ядре нет. Dumb-буферы DRM не нуждаются
    ни в том, ни в другом — так на этой панели рисовал X, пока мы его не
    выключили. См. drmout.py.
    """
    pygame.font.init()
    попытки: list[tuple[str, str | None]] = []
    хотели = os.environ.get("SDL_VIDEODRIVER", "kmsdrm")
    if хотели == "kmsdrm":
        карт = len(glob.glob("/dev/dri/card*")) or 1
        попытки += [("kmsdrm", str(i)) for i in range(карт)]
    else:
        попытки.append((хотели, None))
    попытки += [("fbcon", None), ("", None)]
    for драйвер, карта in попытки:
        try:
            if драйвер:
                os.environ["SDL_VIDEODRIVER"] = драйвер
            else:
                os.environ.pop("SDL_VIDEODRIVER", None)
            if карта is not None:
                os.environ["SDL_KMSDRM_DEVICE_INDEX"] = карта
            else:
                os.environ.pop("SDL_KMSDRM_DEVICE_INDEX", None)
            pygame.display.quit()
            pygame.display.init()
            выбрал = pygame.display.get_driver()
            if выбрал in ЗАГЛУШКИ:
                print(f"лицо: SDL выбрал «{выбрал}» — это не экран, а память",
                      flush=True)
                continue
            экран = pygame.display.set_mode((0, 0), pygame.FULLSCREEN)
            print(f"лицо: экран {экран.get_width()}×{экран.get_height()} через "
                  f"SDL/{выбрал}"
                  f"{f' (card{карта})' if карта is not None else ''}", flush=True)
            return _ЧерезSDL(экран, f"SDL/{выбрал}")
        except pygame.error as e:
            print(f"лицо: {драйвер or 'драйвер по умолчанию'}"
                  f"{f' card{карта}' if карта is not None else ''} не открылся: {e}",
                  flush=True)
    pygame.display.quit()
    try:
        экран = drmout.ЭкранDRM()
    except Exception as e:                      # noqa: BLE001
        raise SystemExit(f"лицо: экран не открылся ни через SDL, ни через DRM "
                         f"({e}). Разобраться: python3 face/diag.py")
    print(f"лицо: экран {экран.width}×{экран.height} ({экран.mm[0]}×{экран.mm[1]} мм, "
          f"{экран.mode.vrefresh} Гц) через DRM dumb-буферы, без SDL", flush=True)
    return _ЧерезDRM(экран)


def главный() -> int:
    файл = Path(ФАЙЛ)
    if not файл.parent.exists():
        файл = Path(ЗАПАСНОЙ_ФАЙЛ).expanduser()
    вывод = _открыть_экран()
    экран = вывод.поверхность
    try:
        pygame.mouse.set_visible(False)
    except pygame.error:
        pass                                    # без SDL-экрана мыши и нет
    кисть = Кисть(экран.get_width(), экран.get_height())
    яркость = Яркость()
    такт = pygame.time.Clock()
    начало = time.monotonic()
    последний_отчёт = начало
    кадров_за_отчёт = 0
    причина_была = ""
    из_sdl = нужен_насос_событий(вывод)
    try:
        while True:
            if из_sdl:
                for событие in pygame.event.get():
                    if событие.type == pygame.QUIT:
                        return 0
            состояние, почему = прочитать(файл)
            if почему != причина_была:
                print(f"лицо: {почему}", flush=True)
                причина_была = почему
            t = time.monotonic() - начало
            доля = яркость.применить(яркость.доля(состояние))
            кисть.кадр(экран, состояние, t, доля)
            вывод.показать()
            кадров_за_отчёт += 1
            if time.monotonic() - последний_отчёт >= 60.0:
                # Счётчик кадров — это проверка №1 из ТЗ §8, а не украшение.
                print(f"лицо: {кадров_за_отчёт / 60.0:.1f} к/с", flush=True)
                последний_отчёт, кадров_за_отчёт = time.monotonic(), 0
            такт.tick(КАДРОВ_В_СЕКУНДУ)
    except KeyboardInterrupt:
        return 0
    finally:
        # Запрет №1 из ТЗ: умерли — на экране не последнее живое лицо, а
        # честный кадр отказа. От SIGKILL это не спасает, и это записано.
        try:
            кисть.кадр_отказа(экран)
            вывод.показать()
        except Exception:                       # noqa: BLE001
            pass
        try:
            вывод.закрыть()
        except Exception:                       # noqa: BLE001
            pass


if __name__ == "__main__":
    sys.exit(главный())
