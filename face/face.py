ЗАПАСНОЙ_ФАЙЛ = "~/.robot-ai/face.json"
# Старше этого — лицо спит. Требование ТЗ: одна секунда.
СТАРЕЕТ = 1.0
КАДРОВ_В_СЕКУНДУ = 30
ШРИФТ = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
ШРИФТ_ЖИРНЫЙ = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

# --- цвета (docs/screen.md §5, «Цвета») --------------------------------------
ФОН = (0x0B, 0x0F, 0x14)            # тёмный, но не чёрный: на IPS чёрный пятнами
ГЛАЗА = (0x7F, 0xE3, 0xFF)
ГЛАЗА_НОЧЬЮ = (0xFF, 0xC9, 0x8A)
ТРЕВОГА = (0xFF, 0xB0, 0x20)        # янтарь; красный — только под аварийный стоп
ТЕКСТ = (0xC7, 0xD3, 0xDD)
ТЕКСТ_ТУСКЛЫЙ = (0x6E, 0x7B, 0x86)
БЛИК = (0xFF, 0xFF, 0xFF)
ЯРКОСТЬ_ДНЁМ = 0.85
ЯРКОСТЬ_НОЧЬЮ = 0.15

# --- пропорции, доли H (docs/screen.md §5) ------------------------------------
ЛИЦО_ДО = 0.84                       # ниже — строка состояния
ГЛАЗ_ВЫСОТА = 0.34
ГЛАЗ_ШИРИНА = 0.27
ГЛАЗ_РАДИУС = 0.10
ПРОСВЕТ = 0.24
ГЛАЗА_ЦЕНТР_ОТ_ВЕРХА = 0.36
ПОЛЯ = 0.06
ВЗГЛЯД_ДО = 0.10                     # ±0.10 H смещения к человеку
МОРГ_ВЫСОТА = 0.04
ТЕКСТ_ВЫСОТА = 0.06                  # заглавная строки состояния
ПОДПИСЬ_ВЫСОТА = 0.035               # услышанная фраза, виджеты

