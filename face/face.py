МОРГ_ЗАКРЫТЬ, МОРГ_ДЕРЖАТЬ, МОРГ_ОТКРЫТЬ = 0.090, 0.040, 0.110
МОРГ_РАЗ_В = (3.0, 7.0)
# Переход между эмоциями — 150 мс, плавно.
ПЕРЕХОД = 0.150

# --- яркость и расход (docs/screen.md §7) -------------------------------------
# Человека не видно и не говорим дольше минуты — 30%; дольше трёх — гасим.
ТУСКНЕТЬ_ЧЕРЕЗ = 60.0
ГАСНУТЬ_ЧЕРЕЗ = 180.0
ТУСКЛО = 0.30

# Эмоции — тем же списком, что у голосовой службы. Своих нет.
ЭМОЦИИ = ("спокоен", "рад", "слушаю", "думаю", "не_понял", "огорчён",
          "встревожен", "сплю")


# --- форма глаз ---------------------------------------------------------------
def форма_глаз(эмоция: str) -> dict:
    """Параметры пары глаз для эмоции, в долях H. Таблица из ТЗ §5.

    высота, ширина, радиус — размеры; сдвиг_л/сдвиг_п — вертикальный сдвиг
    каждого глаза; наклон — градусы, положительный = внутрь; дуга_снизу —
    низ уходит дугой вверх (радость); дрожь — амплитуда в долях H;
    зрачки — глаза плавают влево-вправо (думаю); блик — яркость блика 0..1.
    """
    базовая = dict(высота=ГЛАЗ_ВЫСОТА, ширина=ГЛАЗ_ШИРИНА, радиус=ГЛАЗ_РАДИУС,
                   сдвиг_л=0.0, сдвиг_п=0.0, наклон=0.0, дуга_снизу=0.0,
                   дрожь=0.0, зрачки=0.0, блик=0.6)
    if эмоция == "рад":
        базовая.update(высота=0.28, дуга_снизу=1.0)
    elif эмоция == "слушаю":
        базовая.update(высота=ГЛАЗ_ВЫСОТА * 1.08, ширина=ГЛАЗ_ШИРИНА * 1.08,
                       блик=1.0)
    elif эмоция == "думаю":
        базовая.update(высота=0.26, зрачки=1.0)
    elif эмоция == "не_понял":
        базовая.update(сдвиг_л=-0.05, наклон=8.0)
    elif эмоция == "огорчён":
        базовая.update(наклон=12.0)
    elif эмоция == "встревожен":
        базовая.update(ширина=0.22, дрожь=2.0 / 800.0)   # ±2 px на 8", 6 Гц
    elif эмоция == "сплю":
        базовая.update(высота=0.06, блик=0.0)
    return базовая


def _смешать(а: dict, б: dict, доля: float) -> dict:
    """Линейно между двумя формами. доля 0 — а, 1 — б."""
    доля = max(0.0, min(1.0, доля))
    return {к: а[к] + (б[к] - а[к]) * доля for к in а}


def _цвет(ц: tuple, яркость: float) -> tuple:
    яркость = max(0.0, min(1.0, яркость))
    return tuple(int(round(c * яркость)) for c in ц)


# --- чтение состояния --------------------------------------------------------
def прочитать(файл: Path, сейчас: float | None = None) -> tuple[dict, str]:
    """(состояние, почему такое). Старый или битый файл — «сплю».

    Свежесть проверяется настенными часами: файл писал ДРУГОЙ процесс, и
    сравнивать его метку надо с тем же, чем он её ставил. Это единственное
    место, где настенные часы здесь законны.
    """
    сейчас = time.time() if сейчас is None else сейчас
    try:
        данные = json.loads(файл.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"эмоция": "сплю"}, "файла нет"
    if not isinstance(данные, dict):
        return {"эмоция": "сплю"}, "файл не тот"
    возраст = сейчас - float(данные.get("когда") or 0)
    if возраст > СТАРЕЕТ:
        # Старое лицо хуже спящего: человек думает, что робот работает.
        return {"эмоция": "сплю", "батарея": данные.get("батарея")}, \
            f"состоянию {возраст:.1f} с"
    if данные.get("эмоция") not in ЭМОЦИИ:
        данные["эмоция"] = "спокоен"
    return данные, "свежее"


# --- отрисовка ----------------------------------------------------------------
class Кисть:
    """Рисует один кадр по состоянию. Никакого чтения файлов и часов внутри.

    Всё время приходит снаружи (`t`), поэтому кадр воспроизводим: одна и та
    же секунда — один и тот же рисунок. На этом держится проверка.
    """

    def __init__(self, ширина: int, высота: int, *, шрифт: str = ШРИФТ,
                 жирный: str = ШРИФТ_ЖИРНЫЙ, случай=random.Random(7)) -> None:
        self.W, self.H = ширина, высота
        self.случай = случай
        self._шрифты: dict = {}
        self._шрифт_путь = шрифт if os.path.exists(шрифт) else None
        self._жирный_путь = жирный if os.path.exists(жирный) else None
        # Плавные переходы: откуда идём, куда и с какого момента.
        self._была = "спокоен"
        self._стала = "спокоен"
        self._переход_с = -1.0
        # Взгляд сглаживаем: пеленг с камеры дёргается, глаза — нет.
        self._взгляд = 0.0
        # Моргание.
        self._морг_в = 0.0
        self._следующий_морг = случай.uniform(*МОРГ_РАЗ_В)
        self.кадров = 0

    # --- шрифты -------------------------------------------------------------
    def _шрифт(self, доля_H: float, жирный: bool = False):
        # Высота заглавной ≈ 0.72 кегля у DejaVu; кегль подбираем под H.
        кегль = max(8, int(round(доля_H * self.H / 0.72)))
        ключ = (кегль, жирный)
        if ключ not in self._шрифты:
            путь = self._жирный_путь if жирный else self._шрифт_путь
            try:
                ш = pygame.font.Font(путь, кегль) if путь else pygame.font.SysFont(
                    "dejavusans,freesans,sans", кегль, bold=жирный)
            except Exception:                   # noqa: BLE001
                ш = pygame.font.Font(None, кегль)
            self._шрифты[ключ] = ш
        return self._шрифты[ключ]

    def _текст(self, холст, текст: str, x: int, y: int, доля_H: float,
               цвет, *, жирный=False, справа=False, не_шире: int | None = None):
        if not текст:
            return 0
        ш = self._шрифт(доля_H, жирный)
        if не_шире is not None:
            while текст and ш.size(текст)[0] > не_шире:
                текст = текст[:-2] + "…" if len(текст) > 2 else ""
        картинка = ш.render(текст, True, цвет)
        if справа:
            x -= картинка.get_width()
        холст.blit(картинка, (x, y))
        return картинка.get_width()

    # --- эмоция с переходом ------------------------------------------------
    def _форма(self, эмоция: str, t: float) -> dict:
        if эмоция != self._стала:
            self._была, self._стала, self._переход_с = self._стала, эмоция, t
        доля = 1.0 if self._переход_с < 0 else (t - self._переход_с) / ПЕРЕХОД
        return _смешать(форма_глаз(self._была), форма_глаз(self._стала), доля)

    # --- моргание -------------------------------------------------------------
    def _моргание(self, t: float, спит: bool) -> float:
        """Доля высоты глаза 0..1 с учётом моргания. Спящий не моргает."""
        if спит:
            return 1.0
        if self._морг_в == 0.0 and t >= self._следующий_морг:
            self._морг_в = t
        if self._морг_в == 0.0:
            return 1.0
        прошло = t - self._морг_в
        if прошло < МОРГ_ЗАКРЫТЬ:
            return 1.0 - прошло / МОРГ_ЗАКРЫТЬ
        if прошло < МОРГ_ЗАКРЫТЬ + МОРГ_ДЕРЖАТЬ:
            return 0.0
        if прошло < МОРГ_ЗАКРЫТЬ + МОРГ_ДЕРЖАТЬ + МОРГ_ОТКРЫТЬ:
            return (прошло - МОРГ_ЗАКРЫТЬ - МОРГ_ДЕРЖАТЬ) / МОРГ_ОТКРЫТЬ
        self._морг_в = 0.0
        self._следующий_морг = t + self.случай.uniform(*МОРГ_РАЗ_В)
        return 1.0

    # --- глаза ----------------------------------------------------------------
    def _глаз(self, холст, cx: float, cy: float, ф: dict, открыт: float,
              наклон_знак: int, цвет, t: float) -> None:
        H = self.H
        w = ф["ширина"] * H
        h = max(МОРГ_ВЫСОТА * H, ф["высота"] * H * открыт)
        r = min(ф["радиус"] * H, h / 2, w / 2)
        if ф["дрожь"] > 0:
            cx += math.sin(t * 2 * math.pi * 6.0) * ф["дрожь"] * H
        # Рисуем в отдельной поверхности, чтобы наклонить и вырезать дугу.
        запас = int(h * 0.6) + 4
        пов = pygame.Surface((int(w) + 2 * запас, int(h) + 2 * запас), pygame.SRCALPHA)
        прям = pygame.Rect(запас, запас, int(w), int(h))
        pygame.draw.rect(пов, цвет, прям, border_radius=int(r))
        if ф["дуга_снизу"] > 0:
            # Радость: низ глаза уходит дугой вверх. Вырезаем эллипс фоном.
            # Не глубже 0.42 высоты: глубже — глаз превращается в две скобки,
            # и центр его исчезает. Улыбка читается уже при трети.
            выс_дуги = int(h * 0.42 * ф["дуга_снизу"])
            дуга = pygame.Rect(запас - int(w * 0.1), запас + int(h) - выс_дуги,
                               int(w * 1.2), выс_дуги * 2)
            pygame.draw.ellipse(пов, (0, 0, 0, 0), дуга)
        if ф["блик"] > 0 and открыт > 0.3:
            бл = _цвет(БЛИК, ф["блик"])
            rr = max(2, int(h * 0.12))
            pygame.draw.circle(пов, бл, (запас + int(w * 0.72), запас + int(h * 0.25)), rr)
        if ф["наклон"]:
            пов = pygame.transform.rotate(пов, -ф["наклон"] * наклон_знак)
        холст.blit(пов, пов.get_rect(center=(int(cx), int(cy))))

    def _глаза(self, холст, ф: dict, состояние: dict, t: float, яркость: float,
               спит: bool) -> None:
        H, W = self.H, self.W
        цвет_глаз = ГЛАЗА_НОЧЬЮ if состояние.get("ночь") else ГЛАЗА
        if состояние.get("эмоция") == "встревожен":
            цвет_глаз = ТРЕВОГА
        цвет = _цвет(цвет_глаз, яркость)
        открыт = self._моргание(t, спит)
        # Взгляд: к человеку по пеленгу, влево — плюс. На экране влево — минус x.
        цель = 0.0
        if состояние.get("взгляд") is not None and not спит:
            угол = float(состояние["взгляд"])
            цель = -max(-1.0, min(1.0, угол / math.radians(45))) * ВЗГЛЯД_ДО * H
        self._взгляд += (цель - self._взгляд) * 0.2
        зрачки = math.sin(t * 2 * math.pi * 0.35) * ф["зрачки"] * ВЗГЛЯД_ДО * H * 0.6
        сдвиг_x = self._взгляд + зрачки

        cy = ГЛАЗА_ЦЕНТР_ОТ_ВЕРХА * H
        пол_просвета = ПРОСВЕТ * H / 2
        пол_ширины = ф["ширина"] * H / 2
        cx_л = W / 2 - пол_просвета - пол_ширины + сдвиг_x
        cx_п = W / 2 + пол_просвета + пол_ширины + сдвиг_x
        self._глаз(холст, cx_л, cy + ф["сдвиг_л"] * H, ф, открыт, +1, цвет, t)
        self._глаз(холст, cx_п, cy + ф["сдвиг_п"] * H, ф, открыт, -1, цвет, t)

    # --- строка состояния ----------------------------------------------------
    def _строка(self, холст, состояние: dict, яркость: float) -> None:
        H, W = self.H, self.W
        верх = int(ЛИЦО_ДО * H)
        поле = int(ПОЛЯ * W)
        pygame.draw.line(холст, _цвет(ТЕКСТ_ТУСКЛЫЙ, яркость * 0.5),
                         (поле, верх), (W - поле, верх), 1)
        цвет = _цвет(ТЕКСТ, яркость)
        тускло = _цвет(ТЕКСТ_ТУСКЛЫЙ, яркость)
        # Слева — что делает. Справа — батарея.
        батарея = состояние.get("батарея")
        справа_текст = f"{батарея:.1f} В" if isinstance(батарея, (int, float)) else "— В"
        ш_справа = self._текст(холст, справа_текст, W - поле, верх + int(0.02 * H),
                               ТЕКСТ_ВЫСОТА, цвет if батарея is not None else тускло,
                               справа=True)
        строка = состояние.get("строка") or ""
        if состояние.get("эмоция") == "сплю":
            строка = "сплю"
        self._текст(холст, строка, поле, верх + int(0.02 * H), ТЕКСТ_ВЫСОТА, цвет,
                    жирный=True, не_шире=W - 2 * поле - ш_справа - поле)
        # Вторая строка — что именно услышал (или говорит). Это не украшение.
        говорит = состояние.get("говорит") or ""
        услышал = состояние.get("услышал") or ""
        подпись = f"› {говорит}" if говорит else (f"« {услышал} »" if услышал else "")
        self._текст(холст, подпись, поле, верх + int(0.095 * H), ПОДПИСЬ_ВЫСОТА,
                    тускло, не_шире=W - 2 * поле)

    # --- виджеты ---------------------------------------------------------------
    def _значок_погоды(self, холст, код: int, x: int, y: int, r: int, цвет, яркость):
        """Солнце / облако / дождь / снег / гроза — формами, без картинок."""
        ясно = код in (0, 1)
        облачно = код in (2, 3, 45, 48)
        дождь = код in (51, 53, 55, 56, 57, 61, 63, 65, 66, 67, 80, 81, 82)
        снег = код in (71, 73, 75, 77, 85, 86)
        гроза = код in (95, 96, 99)
        солнце = _цвет(ТРЕВОГА, яркость)
        if ясно or код == 2:
            pygame.draw.circle(холст, солнце, (x, y), int(r * 0.55))
            for i in range(8):
                a = i * math.pi / 4
                pygame.draw.line(холст, солнце,
                                 (x + math.cos(a) * r * 0.7, y + math.sin(a) * r * 0.7),
                                 (x + math.cos(a) * r * 0.95, y + math.sin(a) * r * 0.95),
                                 max(1, r // 12))
        if облачно or дождь or снег or гроза:
            for dx, dy, rr in ((-0.35, 0.15, 0.45), (0.05, -0.05, 0.55), (0.4, 0.2, 0.4)):
                pygame.draw.circle(холст, цвет, (int(x + dx * r), int(y + dy * r)), int(rr * r))
            pygame.draw.rect(холст, цвет, (int(x - 0.75 * r), int(y + 0.15 * r), int(1.5 * r), int(0.45 * r)))
        if дождь or гроза:
            for i in range(3):
                dx = (i - 1) * 0.35 * r
                pygame.draw.line(холст, _цвет(ГЛАЗА, яркость),
                                 (x + dx, y + 0.75 * r), (x + dx - 0.15 * r, y + 1.15 * r),
                                 max(1, r // 10))
        if снег:
            for i in range(3):
                dx = (i - 1) * 0.35 * r
                pygame.draw.circle(холст, _цвет(БЛИК, яркость), (int(x + dx), int(y + r)), max(1, r // 9))
        if гроза:
            pygame.draw.polygon(холст, солнце, [(x, y + 0.6 * r), (x - 0.2 * r, y + 1.05 * r),
                                                (x + 0.05 * r, y + 1.0 * r), (x - 0.1 * r, y + 1.4 * r),
                                                (x + 0.25 * r, y + 0.9 * r), (x, y + 0.95 * r)])

    def _погода(self, холст, погода: dict | None, яркость: float) -> None:
        if not погода or погода.get("t") is None:
            return
        H, W = self.H, self.W
        поле = int(ПОЛЯ * W)
        r = int(0.07 * H)
        x, y = W - поле - r, int(ПОЛЯ * H) + r
        цвет = _цвет(ТЕКСТ, яркость)
        тускло = _цвет(ТЕКСТ_ТУСКЛЫЙ, яркость)
        self._значок_погоды(холст, int(погода.get("код") or 0), x, y, r, тускло, яркость)
        t = int(погода["t"])
        self._текст(холст, f"{t:+d}°", x - r - int(0.02 * W), y - int(0.05 * H),
                    0.09, цвет, жирный=True, справа=True)
        мин, макс = погода.get("мин"), погода.get("макс")
        if мин is not None and макс is not None:
            self._текст(холст, f"{int(мин):+d}… {int(макс):+d}°", x - r - int(0.02 * W),
                        y + int(0.045 * H), ПОДПИСЬ_ВЫСОТА, тускло, справа=True)
        описание = погода.get("описание") or ""
        self._текст(холст, описание, W - поле, y + r + int(0.02 * H), ПОДПИСЬ_ВЫСОТА,
                    тускло, справа=True, не_шире=int(0.34 * W))

    def _музыка(self, холст, музыка: dict | None, яркость: float, t: float) -> None:
        if not музыка or not музыка.get("играет"):
            return
        H, W = self.H, self.W
        поле = int(ПОЛЯ * W)
        x, y = поле, int(ПОЛЯ * H)
        цвет = _цвет(ГЛАЗА, яркость)
        тускло = _цвет(ТЕКСТ_ТУСКЛЫЙ, яркость)
        # Три столбика, качаются: видно, что играет, а не висит.
        for i in range(3):
            выс = int((0.02 + 0.02 * (1 + math.sin(t * 5 + i * 1.3)) / 2) * H)
            pygame.draw.rect(холст, цвет, (x + i * int(0.012 * H), y + int(0.05 * H) - выс,
                                          int(0.008 * H), выс))
        self._текст(холст, музыка.get("название") or "музыка", x + int(0.05 * H),
                    y + int(0.005 * H), ПОДПИСЬ_ВЫСОТА, тускло, не_шире=int(0.4 * W))

    # --- кадр целиком ----------------------------------------------------------
    def кадр(self, холст, состояние: dict, t: float, яркость: float) -> None:
        """Нарисовать состояние на холст. Всё время — снаружи."""
        холст.fill(ФОН)
        эмоция = состояние.get("эмоция", "спокоен")
        спит = эмоция == "сплю"
        ф = self._форма(эмоция, t)
        self._глаза(холст, ф, состояние, t, яркость, спит)
        self._строка(холст, состояние, яркость)
        if not спит:
            self._погода(холст, состояние.get("погода"), яркость)
            self._музыка(холст, состояние.get("музыка"), яркость, t)
        self.кадров += 1

    def кадр_отказа(self, холст) -> None:
        """Статичный кадр «экран отвалился». Не лицо: лицо тут было бы ложью."""
        холст.fill(ФОН)
        H, W = self.H, self.W
        цвет = _цвет(ТРЕВОГА, 0.7)
        pygame.draw.rect(холст, цвет, (int(W * 0.44), int(H * 0.30), int(W * 0.12), int(H * 0.22)), 3)
        pygame.draw.line(холст, цвет, (int(W * 0.44), int(H * 0.30)), (int(W * 0.56), int(H * 0.52)), 3)
        self._текст(холст, "экран отвалился", W // 2 - int(W * 0.14), int(H * 0.6),
                    ТЕКСТ_ВЫСОТА, цвет, жирный=True)
        self._текст(холст, "робот может работать; лицо перезапустится само",
                    W // 2 - int(W * 0.28), int(H * 0.7), ПОДПИСЬ_ВЫСОТА,
                    _цвет(ТЕКСТ_ТУСКЛЫЙ, 0.8))


# --- яркость: подсветка и экономия -------------------------------------------
class Яркость:
    """Сколько света: ТЗ §7. Видим человека или говорим — 100%; молчим и
    никого нет минуту — 30%; три минуты — гасим. Ночь — 15% и теплее.

    Аппаратную подсветку крутим через /sys/class/backlight, если она там есть;
    если нет — рисуем темнее. Второе хуже (панель светит фоном), но без
    первого лучше так, чем никак.
    """

    def __init__(self, часы=time.monotonic) -> None:
        self._часы = часы
        self._живо_с = часы()
        self._подсветка = self._найти_подсветку()
        self._выставлено = -1

    @staticmethod
    def _найти_подсветку() -> Path | None:
        for п in Path("/sys/class/backlight").glob("*"):
            if (п / "brightness").exists() and (п / "max_brightness").exists():
                return п
        return None

    def доля(self, состояние: dict) -> float:
        сейчас = self._часы()
        if состояние.get("человек") or состояние.get("говорит") or состояние.get("едет"):
            self._живо_с = сейчас
        основа = ЯРКОСТЬ_НОЧЬЮ if состояние.get("ночь") else ЯРКОСТЬ_ДНЁМ
        if состояние.get("эмоция") == "сплю":
            return основа * ТУСКЛО
        тихо = сейчас - self._живо_с
        if тихо > ГАСНУТЬ_ЧЕРЕЗ:
            return 0.0
        if тихо > ТУСКНЕТЬ_ЧЕРЕЗ:
            return основа * ТУСКЛО
        return основа

    def применить(self, доля: float) -> float:
        """Вернуть, какую яркость рисовать программно (после аппаратной)."""
        if self._подсветка is None:
            return доля
        try:
            макс = int((self._подсветка / "max_brightness").read_text())
            значение = int(round(макс * max(0.0, min(1.0, доля))))
            if значение != self._выставлено:
                (self._подсветка / "brightness").write_text(str(значение))
                self._выставлено = значение
            return 1.0 if доля > 0 else 0.0
        except OSError:
            self._подсветка = None
            return доля


