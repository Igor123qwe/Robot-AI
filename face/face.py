def дата_числом(когда: float) -> list[int]:
    """[день, месяц, день недели (пн — 0)] — расписанию сценок."""
    м = time.localtime(когда)
    return [м.tm_mday, м.tm_mon, м.tm_wday]


def часы_и_дата(когда: float) -> tuple[str, str]:
    """«22:23», «сб, 5 сен» — по местному времени робота."""
    м = time.localtime(когда)
    return f"{м.tm_hour:02d}:{м.tm_min:02d}", f"{ДНИ[м.tm_wday]}, {м.tm_mday} {МЕСЯЦЫ[м.tm_mon - 1]}"


# --- главный цикл -------------------------------------------------------------
class _ЧерезSDL:
    """Экран, который открыл SDL: рисуем прямо в него."""

    def __init__(self, экран, имя: str) -> None:
        self.поверхность = экран
        self.имя = имя

    def показать(self) -> None:
        pygame.display.flip()

    def закрыть(self) -> None:
        pygame.display.quit()

    # mpv сам выбирает карту при --vo=drm — не обязательно ту же, где рисует
    # SDL; здесь это ему не мешало (см. drm_device в _ЧерезDRM).
    drm_device: str | None = None


class _ЧерезDRM:
    """Экран через dumb-буферы DRM: рисуем в память, копируем в ядро."""

    def __init__(self, экран: drmout.ЭкранDRM) -> None:
        self._экран = экран
        self.поверхность = pygame.Surface((экран.width, экран.height), 0, 32,
                                          masks=drmout.МАСКИ)
        self.имя = "DRM dumb-буферы"
        # У платы бывает несколько /dev/dri/card* — drmout перебрал их и
        # нашёл рабочий (см. drmout._открыть). mpv при --vo=drm без указания
        # устройства выбирает карту сам, и не обязательно ту же: тогда видео
        # рисуется в карту без подключённой панели — экран чёрный, а звук
        # идёт своим путём через ALSA и его никто не останавливает. Отсюда
        # и симптом «включил мультик — играет только звук».
        self.drm_device = экран.путь

    def показать(self) -> None:
        self._экран.показать(self.поверхность)

    def закрыть(self) -> None:
        self._экран.закрыть()


def нужен_насос_событий(вывод) -> bool:
    """Очередь событий SDL жива, только если жива видеосистема SDL.

    На DRM-пути (_ЧерезDRM) display.quit() уже вызван до открытия экрана, и
    pygame.event.get() тут же упал бы с «video system not initialized». А
    слать нам QUIT в киоске всё равно некому — оконного менеджера нет ни на
    одном из путей, это чисто защита от падения. Отдельной функцией — чтобы
    проверить решение без запуска бесконечного главного цикла.
    """
    return isinstance(вывод, _ЧерезSDL)


# Драйверы SDL, которые открываются всегда и рисуют в никуда. Принять такой за
# экран — значит тридцать кадров в секунду в память и «30 к/с» в журнале при
# тёмной панели. Ровно так и было на роботе: «1024×768 через SDL по
# умолчанию» — а такого разрешения нет ни у одной из наших панелей.
ЗАГЛУШКИ = {"dummy", "offscreen"}


def _открыть_экран():
    """SDL (kmsdrm по каждой карте → fbcon → любой настоящий) → DRM напрямую.

    ОШИБКА, КОТОРАЯ ТУТ БЫЛА, ДВАЖДЫ. Первый `display.init()` стоял ДО цикла с
    запасными вариантами — он и падал, до перебора не доходило. А потом SDL
    «по умолчанию» открыл заглушку, и код объявил это экраном, не спросив у
    SDL, какой драйвер тот выбрал. Теперь спрашивает, и заглушки не считает.

    ПОЧЕМУ НУЖЕН DRM НАПРЯМУЮ. На RDK X5 DRM-драйвер — VeriSilicon vs-drm, и у
    Mesa для него нет модуля. SDL-овский kmsdrm без Mesa/GBM работать не
    может в принципе, /dev/fb* на этом ядре нет. Dumb-буферы DRM не нуждаются
    ни в том, ни в другом — так на этой панели рисовал X, пока мы его не
    выключили. См. drmout.py.
    """
    pygame.font.init()
    попытки: list[tuple[str, str | None]] = []
    хотели = os.environ.get("SDL_VIDEODRIVER", "kmsdrm")
    if хотели == "kmsdrm":
        карт = len(glob.glob("/dev/dri/card*")) or 1
        попытки += [("kmsdrm", str(i)) for i in range(карт)]
    else:
        попытки.append((хотели, None))
    попытки += [("fbcon", None), ("", None)]
    for драйвер, карта in попытки:
        try:
            if драйвер:
                os.environ["SDL_VIDEODRIVER"] = драйвер
            else:
                os.environ.pop("SDL_VIDEODRIVER", None)
            if карта is not None:
                os.environ["SDL_KMSDRM_DEVICE_INDEX"] = карта
            else:
                os.environ.pop("SDL_KMSDRM_DEVICE_INDEX", None)
            pygame.display.quit()
            pygame.display.init()
            выбрал = pygame.display.get_driver()
            if выбрал in ЗАГЛУШКИ:
                print(f"лицо: SDL выбрал «{выбрал}» — это не экран, а память",
                      flush=True)
                continue
            экран = pygame.display.set_mode((0, 0), pygame.FULLSCREEN)
            print(f"лицо: экран {экран.get_width()}×{экран.get_height()} через "
                  f"SDL/{выбрал}"
                  f"{f' (card{карта})' if карта is not None else ''}", flush=True)
            return _ЧерезSDL(экран, f"SDL/{выбрал}")
        except pygame.error as e:
            print(f"лицо: {драйвер or 'драйвер по умолчанию'}"
                  f"{f' card{карта}' if карта is not None else ''} не открылся: {e}",
                  flush=True)
    pygame.display.quit()
    try:
        экран = drmout.ЭкранDRM()
    except Exception as e:                      # noqa: BLE001
        raise SystemExit(f"лицо: экран не открылся ни через SDL, ни через DRM "
                         f"({e}). Разобраться: python3 face/diag.py")
    print(f"лицо: экран {экран.width}×{экран.height} ({экран.mm[0]}×{экран.mm[1]} мм, "
          f"{экран.mode.vrefresh} Гц) через DRM dumb-буферы, без SDL", flush=True)
    return _ЧерезDRM(экран)


def _играть_видео(начальное: dict, файл: Path, drm_device: str | None = None) -> None:
    """Отдаём экран mpv на время ролика. DRM уже закрыт вызывающим.

    Опрашиваем face.json заметно реже, чем кадры лица: рисовать самим нечего
    — экран занят mpv, — а слишком частый опрос отнимает у него же процессор.
    Смена ролика («следующий мультик»), пауза и громкость идут через
    управляющий сокет mpv, без пересоздания процесса; отпускать и заново
    захватывать DRM нужно только один раз — на входе и на выходе.

    drm_device — та же карта /dev/dri/card*, что уже выбрал drmout для лица:
    без неё mpv выбирает карту сам, и на плате с несколькими картами это
    может быть карта без подключённой панели — тогда видео не видно, а звук
    всё равно идёт (см. _ЧерезDRM.drm_device).
    """
    проигрыватель = videoplayer.Проигрыватель(
        устройство=str(начальное.get("устройство") or ""), drm_device=drm_device)
    if not проигрыватель.запустить(str(начальное.get("url") or ""),
                                   int(_число(начальное.get("громкость"), 70))):
        print("лицо: видео не запустилось — возвращаю обычный экран", flush=True)
        return
    url_был = начальное.get("url")
    пауза_была = bool(начальное.get("пауза"))
    громкость_была = int(_число(начальное.get("громкость"), 70))
    try:
        while проигрыватель.жив():
            time.sleep(0.2)
            состояние, _ = прочитать(файл)
            видео = состояние.get("видео") or {}
            if not видео.get("играет") or not видео.get("url"):
                break
            if видео.get("url") != url_был:
                url_был = видео.get("url")
                проигрыватель.загрузить(url_был)
            пауза = bool(видео.get("пауза"))
            if пауза != пауза_была:
                пауза_была = пауза
                проигрыватель.пауза(пауза)
            громкость = int(_число(видео.get("громкость"), 70))
            if громкость != громкость_была:
                громкость_была = громкость
                проигрыватель.громкость(громкость)
    finally:
        проигрыватель.стоп()


def главный() -> int:
    файл = Path(ФАЙЛ)
    if not файл.parent.exists():
        файл = Path(ЗАПАСНОЙ_ФАЙЛ).expanduser()
    вывод = _открыть_экран()
    экран = вывод.поверхность
    try:
        pygame.mouse.set_visible(False)
    except pygame.error:
        pass                                    # без SDL-экрана мыши и нет
    кисть = Кисть(экран.get_width(), экран.get_height())
    яркость = Яркость()
    поток = Поток(ПК and ПК + "/avatar/stream", экран.get_size(), образец=экран)
    поток.запустить()
    print(f"лицо: аватар с ПК — {поток.почему}", flush=True)
    тач = Тач(экран.get_size())
    тач.запустить()
    кисть.тач_есть = тач.есть
    if not тач.есть:
        print("лицо: тач — не найден, кнопок на экране не будет (ищу дальше, "
              f"раз в {Тач.ИСКАТЬ_РАЗ_В:.0f} с)", flush=True)
    # Нажатия — голосовой службе, файлом в обратную сторону от face.json.
    файл_нажатий = файл.with_name("touch.json")
    нажатий = 0
    такт = pygame.time.Clock()
    начало = time.monotonic()
    последний_отчёт = начало
    кадров_за_отчёт = 0
    кадров_с_пк_было = 0
    причина_была = ""
    источник_был = ""
    из_sdl = нужен_насос_событий(вывод)
    try:
        while True:
            if из_sdl:
                for событие in pygame.event.get():
                    if событие.type == pygame.QUIT:
                        return 0
            состояние, почему = прочитать(файл)
            видео = состояние.get("видео") or {}
            if видео.get("играет") and видео.get("url"):
                # Экран целиком уходит mpv: своя отрисовка тут не нужна и
                # мешала бы — оба разом рисовать в DRM не могут (см.
                # videoplayer.py). Насос событий SDL, если он был, временно
                # не нужен — на DRM-пути его и так не было.
                drm_device = вывод.drm_device
                вывод.закрыть()
                _играть_видео(видео, файл, drm_device=drm_device)
                вывод = _открыть_экран()
                экран = вывод.поверхность
                из_sdl = нужен_насос_событий(вывод)
                причина_была = ""     # первая строка после видео — не «повтор»
                continue
            if почему != причина_была:
                print(f"лицо: {почему}", flush=True)
                причина_была = почему
            # Часы — своё: кисть часов не читает (её кадры воспроизводимы),
            # а голосовая служба во сне ничего не пишет — часы же нужны всегда.
            состояние["время"], состояние["дата"] = часы_и_дата(time.time())
            состояние["дата_числом"] = дата_числом(time.time())
            for tx, ty in тач.нажатия():
                действие = кисть.нажато(tx, ty)
                if not действие:
                    continue
                нажатий += 1
                try:
                    временный = файл_нажатий.with_suffix(".tmp")
                    временный.write_text(json.dumps({"когда": time.time(), "номер": нажатий,
                                                     "действие": действие}, ensure_ascii=False),
                                         encoding="utf-8")
                    os.replace(временный, файл_нажатий)
                    print(f"лицо: нажали «{действие}»", flush=True)
                except OSError as e:
                    print(f"лицо: нажатие не записалось ({e})", flush=True)
            t = time.monotonic() - начало
            доля = яркость.применить(яркость.доля(состояние))
            # Тач мог появиться или пропасть после старта — кнопки на
            # карточках рисуются только пока есть кому их нажать.
            кисть.тач_есть = тач.есть
            # Поток тушит кадры сам, в фоне, под ту яркость, что нужна сейчас.
            поток.яркость = доля
            картинка, запечено = поток.снять()
            if картинка is None:
                источник = "рисую сам" if СВОЁ_ЛИЦО else "пусто, ПК пропал"
            elif поток.свежий:
                источник = "аватар с ПК"
            else:
                источник = "ПК запнулся, держу последний кадр"
            if источник != источник_был:
                # Переходы — в журнал: «ПК пропал» без этой строки выглядит
                # как «персонаж вдруг сменился», и искать причину негде.
                print(f"лицо: {источник} ({поток.почему})", flush=True)
                источник_был = источник
            if картинка is not None:
                кисть.кадр_из_потока(экран, картинка, состояние, t, доля, запечено=запечено)
            elif СВОЁ_ЛИЦО:
                кисть.кадр(экран, состояние, t, доля)
            else:
                кисть.пусто(экран, состояние, t, доля)
            вывод.показать()
            кадров_за_отчёт += 1
            if time.monotonic() - последний_отчёт >= 60.0:
                # Счётчик кадров — это проверка №1 из ТЗ §8, а не украшение.
                с_пк = поток.кадров - кадров_с_пк_было
                кадров_с_пк_было = поток.кадров
                print(f"лицо: {кадров_за_отчёт / 60.0:.1f} к/с"
                      + (f", с ПК {с_пк / 60.0:.1f} к/с" if с_пк else ""), flush=True)
                последний_отчёт, кадров_за_отчёт = time.monotonic(), 0
            такт.tick(КАДРОВ_В_СЕКУНДУ)
    except KeyboardInterrupt:
        return 0
    finally:
        # Запрет №1 из ТЗ: умерли — на экране не последнее живое лицо, а
        # честный кадр отказа. От SIGKILL это не спасает, и это записано.
        try:
            кисть.кадр_отказа(экран)
            вывод.показать()
        except Exception:                       # noqa: BLE001
            pass
        try:
            вывод.закрыть()
        except Exception:                       # noqa: BLE001
            pass


if __name__ == "__main__":
    sys.exit(главный())
