def режим_по(состояние: dict) -> str:
    """Какой режим у шара сейчас. Порядок — по силе повода.

    Сон сильнее всего (экран и так приглушён), тревога сильнее речи,
    речь сильнее эмоций, эмоции сильнее музыки: «рад» под музыку — это
    прыжок, а не танец.
    """
    эмоция = состояние.get("эмоция") or "спокоен"
    музыка = состояние.get("музыка")
    if эмоция == "сплю":
        return "сон"
    if эмоция == "встревожен":
        return "тревога"
    if состояние.get("говорит"):
        return "речь"
    если = {"думаю": "дума", "слушаю": "слух", "рад": "радость",
            "огорчён": "грусть", "не_понял": "недоумение"}
    if эмоция in если:
        return если[эмоция]
    if isinstance(музыка, dict) and музыка.get("играет"):
        return "танец"
    return "покой"


# --- для страницы на ПК ---------------------------------------------------------


def _hex(ц: tuple) -> str:
    return "#%02x%02x%02x" % tuple(int(к) for к in ц)


