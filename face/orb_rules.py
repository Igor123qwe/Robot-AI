def _hex(ц: tuple) -> str:
    return "#%02x%02x%02x" % tuple(int(к) for к in ц)


def для_страницы() -> dict:
    """Всё то же — в виде, который отдаётся JSON'ом странице шара на ПК.

    Цвета — строками #rrggbb: так их читает и человек в инструментах
    браузера, и сама страница.
    """
    return {
        "режимы": РЕЖИМЫ,
        "палитры": {р: [_hex(а), _hex(б)] for р, (а, б) in ПАЛИТРЫ.items()},
        "ночной": _hex(НОЧНОЙ), "искра": _hex(ИСКРА), "румянец": _hex(РУМЯНЕЦ),
        "тепло": _hex(ТЕПЛО),
        "переход": ПЕРЕХОД, "переход_в_сон": ПЕРЕХОД_В_СОН,
        "события": СОБЫТИЯ, "длится": ДЛИТСЯ, "фигуры": list(ФИГУРЫ),
        "перетекание": ПЕРЕТЕКАНИЕ,
        "ход": ХОД, "итог_жест": ИТОГ_ЖЕСТ,
    }
