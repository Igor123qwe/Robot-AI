"""Часы: можно ли вообще верить тому, который час показывает эта плата.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ РАДИ ОДНОГО ВОПРОСА. У RDK X5 нет батарейки на часах.
Выключенный робот времени не считает вовсе, и при включении без сети система
ставит на часы что придётся — обычно момент сборки образа или дату последнего
файла, то есть месяцы назад. Полминуты спустя приходит NTP и всё чинит, но
эти полминуты лицо уже живёт: оно успевает решить, что сейчас глубокая ночь,
уйти в ночной фон, погасить экран и не поздороваться с человеком, который
стоит перед ним в обед. А если сети в доме нет вообще (дача, роутер
перезагружается, робот в дороге), то не полминуты, а весь день.

И беда не в самом числе на экране — часы можно не показывать. Беда в том, что
на час завязан ВЕСЬ суточный ритм персонажа: расписание («доброе утро»,
«спокойной ночи», пятница, обед), ночные фоны, сон, кривая бодрости. Врущий
час означает врущий характер, причём врущий убедительно: персонаж бодро
потягивается в два часа ночи и спит в полдень, и выглядит это не как
поломка часов, а как поломка персонажа.

Поэтому здесь один честный вопрос — `верно()` — и два ответа на него:

  1. **Сеть сверила.** systemd-timesync, сверив время, заводит файл-маркер
     `/run/systemd/timesync/synchronized`. Файл в tmpfs, после перезагрузки
     его нет, — то есть он означает ровно «в ЭТОЙ загрузке время сверено», а
     не «когда-то сверялось». Лучшего доказательства у нас всё равно нет.

  2. **Время идёт вперёд от того, что робот уже видел.** Приём известен как
     fake-hwclock: раз в пять минут кладём на диск «вот до этого мига мы
     точно дожили». При следующем включении сравниваем: часы показывают
     позже отметки — значит по крайней мере они не сброшены в прошлое, и
     суточному ритму можно верить. Показывают раньше — значит сброшены, и
     верить нечему.

ОТМЕТКА ТОЛЬКО РАСТЁТ И ТОЛЬКО ПРИ ВЕРНЫХ ЧАСАХ. Это главное правило файла, и
нарушить его — значит сломать всю защиту одним движением. Отметка — не «когда
мы последний раз писали», а «до какого мига мы ТОЧНО дожили». Разреши ей ехать
назад вместе со сбитыми часами — и первое же включение без сети запишет туда
позапрошлый год, после чего `верно()` будет говорить «верю» на любую чушь,
потому что любая чушь окажется больше позапрошлого года. Разреши писать её при
несверенных часах — и защита сама себя отключит через пять минут после первого
запуска. Защита при этом останется на месте и перестанет защищать — молча.

ЧЕГО ЭТА ПРОВЕРКА НЕ УМЕЕТ, и врать про это нельзя. Сравнение с отметкой
ОДНОСТОРОННЕЕ: оно ловит «часы сброшены в прошлое» и не ловит «часы отстают на
три часа». Мало того, ровно этот случай systemd устраивает сам: на машине без
батарейки он при загрузке поднимает часы из `/var/lib/systemd/timesync/clock`,
то есть ставит приблизительно момент прошлого выключения. Такие часы идут
ВПЕРЁД от нашей отметки — и наивное сравнение сказало бы «верю» именно там,
где верить нельзя больше всего.

Поэтому третьим стоит признак «часы подняты с диска»: настенное время момента
загрузки (`time.time() - time.monotonic()`) совпадает с меткой того самого
файла systemd. Совпало — значит сети не было ни разу за эту загрузку, что бы
ни показывал циферблат. Это не догадка по косвенным: это ровно то, что systemd
и делает, и признак держится всю загрузку, а не первые секунды.

ЕСЛИ МАШИНА СЧИТАЕТ ВРЕМЯ САМА (ноутбук разработчика с батарейкой и chrony
вместо systemd-timesyncd) — доказательств у нас не будет никаких, и лицо там
проживёт без суточного ритма. Лечится переменной `ROBOT_CLOCK_TRUSTED=1`: это
человек берёт на себя то, что мы проверить не можем.

Без pygame и без сети, как и вся папка face/ кроме самого экрана.
"""

from __future__ import annotations

import importlib.util
import math
import os
import sys
import time
from pathlib import Path

# Своего журнала у этого модуля нет НАРОЧНО. Единственная строка, которую тут
# стоит писать, — это `почему()`, и пишет её тот, кто заметил перемену (лицо:
# час сменился с «не знаю» на настоящий или обратно). Пиши её отсюда — и она
# уходила бы в журнал тридцать раз в секунду, потому что спрашивают часы
# каждый кадр.


def _соседний(имя: str):
    """Сосед по каталогу face/ — по точному пути, а не «что найдётся».

    В этот модуль ходят из двух процессов с разными привычками. Лицо
    (face/face.py) кладёт свой каталог в `sys.path` и зовёт соседей по имени.
    Голосовая служба, наоборот, каталог face/ в `sys.path` НЕ кладёт и грузит
    оттуда файлы по точному пути — нарочно: там лежит `face.py` с pygame и
    DRM, и любой `import face` в голосовом процессе получил бы экран вместо
    того, что искал (вся история — в комментарии
    `voice/robot_voice/face.py:_загрузить_губы`, а сторож этого правила — в
    самопроверке робота).

    Поэтому берём точный путь: он работает одинаково в обоих процессах. А
    если сосед уже поднят из ЭТОГО же файла — берём готовый, чтобы не держать
    в памяти две копии одного модуля с двумя разными кэшами.
    """
    путь = Path(__file__).resolve().parent / f"{имя}.py"
    готовый = sys.modules.get(имя)
    если_файл = getattr(готовый, "__file__", None)
    if готовый is not None and если_файл and Path(если_файл).resolve() == путь:
        return готовый
    спец = importlib.util.spec_from_file_location(f"robot_face_{имя}", путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


memory = _соседний("memory")

# Маркер systemd-timesync. Отдельным именем, а не строкой по месту: на
# машинах без systemd (и в проверках) его подменяют.
МАРКЕР = "/run/systemd/timesync/synchronized"
ФАЙЛ = "часы.json"
ВЕРСИЯ = 1

# Как часто отметка ложится на диск. Пять минут — цена потери при внезапном
# выключении: столько времени робот после включения без сети будет считать
# часы неверными, хотя они верны. Чаще писать незачем — это флеш-память, и
# запись раз в пять минут она переживёт, а раз в секунду нет.
ОТМЕЧАТЬ_РАЗ_В = 300.0

# Раньше этого мига кода, который вы читаете, не существовало. Значит, часы,
# показывающие такое, — сброшены, и никакие отметки этого не исправят.
# (1 января 2025, UTC.)
ПОЛ = 1735689600.0

# Откуда systemd поднимает часы на машине без батарейки. Метка этого файла —
# приблизительно момент прошлого выключения, и ровно её systemd ставит на
# часы при загрузке, если сеть ещё не ответила.
ВОССТАНОВЛЕНО_ИЗ = "/var/lib/systemd/timesync/clock"
# Насколько близко должны сойтись метка файла и настенное время загрузки,
# чтобы считать, что часы именно подняты с диска. Минуты хватает с запасом:
# systemd ставит время из файла за доли секунды до того, как мы начинаем
# считать монотонные, а разойтись на минуту эти два числа могут только если
# часы кто-то подвинул — то есть как раз тогда, когда признак не нужен.
ВОССТАНОВЛЕНО_ТОЧНОСТЬ = 60.0

# Разобранный файл отметки и ключ, по которому видно, что он не менялся.
# ЗАЧЕМ КЭШ. `верно()` зовут из главного цикла лица — тридцать раз в секунду,
# — а весь бюджет лица десятая доля ядра. Ключом стоит не время, а stat
# файла: так кэш не может отстать от жизни (`отметить()` меняет mtime, и
# следующий же вопрос читает заново), и в проверках не приходится ждать,
# пока он «протухнет».
_КЭШ: tuple | None = None
_ПАМЯТЬ: dict[str, object] = {}


def _забыть() -> None:
    """Выбросить всё, что закэшировано. Нужно, когда каталог сменился под нами.

    В бою это разовый случай (переменная окружения меняется до запуска), в
    проверках — каждый второй шаг: они гоняют часы по временным каталогам.
    """
    global _КЭШ
    _КЭШ = None
    _ПАМЯТЬ.clear()


def _память():
    """Файл отметки, один на процесс: в нём живёт дроссель «раз в пять минут»."""
    путь = str(memory.дом() / ФАЙЛ)
    если = _ПАМЯТЬ.get(путь)
    if если is None:
        если = memory.Память(путь, версия=ВЕРСИЯ, раз_в=ОТМЕЧАТЬ_РАЗ_В)
        _ПАМЯТЬ[путь] = если
    return если


def _отметка() -> float | None:
    """До какого мига робот точно дожил. None — отметок ещё нет.

    Отметку раньше `ПОЛ` считаем за её отсутствие: такое число в файл могли
    положить только руками или сбитые часы, и доверять ему нельзя ни в одну
    сторону.
    """
    global _КЭШ
    путь = memory.дом() / ФАЙЛ
    try:
        с = os.stat(путь)
        ключ = (str(путь), с.st_mtime_ns, с.st_size)
    except OSError:
        ключ = (str(путь), None, None)
    if _КЭШ is not None and _КЭШ[0] == ключ:
        return _КЭШ[1]
    видели = _память().прочитать().get("видели")
    if (isinstance(видели, bool) or not isinstance(видели, (int, float))
            or not math.isfinite(видели) or видели < ПОЛ):
        видели = None
    else:
        видели = float(видели)
    _КЭШ = (ключ, видели)
    return видели


def _сверены_по_сети() -> bool:
    """Есть ли прямое доказательство: systemd-timesync отчитался о сверке.

    `ROBOT_CLOCK_TRUSTED=1` — то же самое, но под ответственность человека:
    на машине с батарейкой и своим NTP доказательства взять больше неоткуда,
    а лишать её суточного ритма насовсем — хуже, чем поверить хозяину.
    """
    if os.environ.get("ROBOT_CLOCK_TRUSTED", "").strip() == "1":
        return True
    return os.path.exists(МАРКЕР)


def _часы_подняты_с_диска(сейчас: float) -> bool:
    """Похоже ли, что часы не сверены, а просто восстановлены из файла systemd.

    Считаем настенное время МОМЕНТА ЗАГРУЗКИ: `сейчас - time.monotonic()`.
    Если оно совпало с меткой файла, из которого systemd поднимает часы, —
    значит за всю эту загрузку часы никто не двигал, кроме самого systemd, и
    показывают они момент прошлого выключения. Ровно тот случай, ради
    которого весь модуль и написан: циферблат выглядит осмысленно, идёт
    вперёд, больше нашей отметки — и врёт на столько, сколько робот простоял
    выключенным.

    Нет файла (не systemd, другой дистрибутив) — признака нет, и это не
    «верно», а просто «нечего сказать»: решать будет отметка.
    """
    try:
        метка = os.path.getmtime(ВОССТАНОВЛЕНО_ИЗ)
    except OSError:
        return False
    включились = сейчас - time.monotonic()
    return abs(включились - метка) <= ВОССТАНОВЛЕНО_ТОЧНОСТЬ


def _словами(когда: float) -> str:
    """Метка времени так, как её прочтёт человек в журнале."""
    try:
        return time.strftime("%d.%m.%Y %H:%M", time.localtime(когда))
    except (OSError, OverflowError, ValueError):
        # Часы могут показывать такое, чего localtime не умеет вовсе, — а
        # строка эта нужна именно в тот миг, когда с часами беда.
        return f"{когда!r}"


def верно(сейчас: float | None = None) -> bool:
    """Можно ли верить настенным часам. Довод `сейчас` — только для проверок.

    Порядок важен: сначала сеть (прямое доказательство), потом отметка
    (косвенное). Без обоих — False, и это НЕ осторожность впрок, а самый
    обычный случай: свежий робот, впервые включённый там, где нет вайфая.
    Сказать в этот миг «верю» значит отдать сценаристу выдуманный час, и
    персонаж проживёт свой первый день в доме по чужому расписанию.
    """
    if _сверены_по_сети():
        return True
    сейчас = time.time() if сейчас is None else сейчас
    if _часы_подняты_с_диска(сейчас):
        return False
    видели = _отметка()
    return видели is not None and сейчас >= видели


def отметить(сейчас: float | None = None) -> None:
    """Записать «до этого мига дожили». Раз в пять минут, молча и не назад.

    Зовут это из главного цикла лица, то есть часто, — дроссель внутри
    `memory.Память`, чтобы вызывающему не приходилось помнить про флеш-память.

    ТРИ УСЛОВИЯ, И КАЖДОЕ ОБЯЗАТЕЛЬНО:
      • часам сейчас верим — иначе мы запишем в отметку выдумку;
      • новое время больше старого — отметка обязана только расти, иначе
        одно включение без сети опускает её в позапрошлый год и обнуляет
        всю защиту (см. шапку файла);
      • время не раньше `ПОЛ` — на случай часов, сброшенных в самое начало.
    """
    сейчас = time.time() if сейчас is None else сейчас
    if not верно(сейчас) or сейчас < ПОЛ:
        return
    видели = _отметка()
    if видели is not None and сейчас <= видели:
        return
    # Человекочитаемая копия — чтобы `cat ~/.robot-ai/часы.json` отвечал на
    # вопрос «с какого момента робот считает часы верными» без калькулятора.
    _память().писать({"видели": сейчас, "видели_строкой": _словами(сейчас)})


def почему(сейчас: float | None = None) -> str:
    """Одной строкой для журнала: почему часы верны или почему нет.

    Строка эта пишется в тот единственный миг, когда ответ МЕНЯЕТСЯ (так её
    зовёт лицо), и потому обязана быть самодостаточной: кто читает journalctl
    через неделю, не будет сопоставлять её с кодом. Отсюда и числа прямо в
    тексте — что показывают часы и до чего робот дожил.
    """
    if _сверены_по_сети():
        return f"сверены по сети (есть {МАРКЕР})"
    сейчас = time.time() if сейчас is None else сейчас
    if _часы_подняты_с_диска(сейчас):
        return (f"НЕ СВЕРЕНЫ: часы показывают {_словами(сейчас)}, но подняты "
                f"с диска ({ВОССТАНОВЛЕНО_ИЗ}) — это момент прошлого "
                f"выключения, а не сейчас. Сети за эту загрузку не было ни "
                f"разу. Суточный ритм отключаю (час = -1).")
    видели = _отметка()
    if видели is None:
        return (f"НЕ СВЕРЕНЫ: сети не было, отметок на диске тоже нет — часы "
                f"показывают {_словами(сейчас)}, но у платы нет батарейки, и "
                f"это может быть что угодно. Суточный ритм отключаю "
                f"(час = -1). Лечится: подключить робота к сети, поставить "
                f"время руками (timedatectl set-time) или, если у этой машины "
                f"часы с батарейкой, — ROBOT_CLOCK_TRUSTED=1.")
    if сейчас < ПОЛ:
        return (f"НЕ СВЕРЕНЫ: часы показывают {_словами(сейчас)} — это раньше, "
                f"чем написан этот код, значит они сброшены в ноль. "
                f"Суточный ритм отключаю (час = -1).")
    if сейчас < видели:
        return (f"НЕ СВЕРЕНЫ: часы показывают {_словами(сейчас)}, а робот уже "
                f"жил {_словами(видели)} — время пошло назад, сети не было. "
                f"Суточный ритм отключаю (час = -1).")
    return (f"верю без сети: часы ушли вперёд от отметки {_словами(видели)} "
            f"к {_словами(сейчас)}")
