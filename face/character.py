def _угол(значение) -> float | None:
    """Пеленг из состояния — число или None, если там не число.

    Состояние приходит из файла (робот) или по сети (ПК), и «взгляд»:
    «влево» там возможен. float() на нём падал внутри кадра — на роботе это
    роняло главный цикл лица и уводило службу в перезапуск по кругу.
    """
    try:
        угол = float(значение)
    except (TypeError, ValueError):
        return None
    return угол if math.isfinite(угол) else None


def _пустая_поза(x: float, нога: float, метка: str, **доп) -> dict:
    """Общая заготовка позы: то, что не меняется, задано один раз.

    «взгляд» — ОТДЕЛЬНОЕ поле от «наклона», и это принципиально. Наклон
    корпуса подкрашивается настроением (`_с_настроением`: озадаченный кренится
    на 3.5°, думающий на 1.5°), а взгляд обязан говорить ровно одно — где
    человек. На роботе это и так два разных канала: домовёнок берёт крен из
    «наклона», а глаза — из состояния напрямую. На ПК же «наклон» был
    ЕДИНСТВЕННЫМ каналом пеленга, и крен настроения уезжал прямо в поворот
    головы: думающий Марк косил на 7° мимо собеседника, а «не понял» без
    человека в кадре вовсе разворачивал голову на 17° в пустоту.
    """
    поза = dict(x=x, подскок=0.0, наклон=0.0, взгляд=0.0, рот=0.0,
                рука_л=0.0, рука_п=0.0, нога=нога, метка=метка,
                рассеян_x=0.0, рассеян_y=0.0)
    поза.update(доп)
    return поза


class Питомец:
    """Решает, где стоит персонаж и что делают его тело, руки и ноги.

    `тело_ширина`, `шаг_длина` — доли H, те же числа, которыми кисть рисует
    туловище и подбирает длину шага. Передаются снаружи, а не дублируются
    здесь: одно число, а не два, которые однажды разъедутся.
    """

    def __init__(self, ширина: int, высота: int, *, тело_ширина: float,
                 шаг_длина: float, запас_справа: float = 0.0,
                 занято_слева: float = 0.0, случай=random.Random(13)) -> None:
        self.W, self.H = ширина, высота
        self.случай = случай
        self._шаг_длина_px = max(1.0, шаг_длина * высота)

        поле_px = ПОЛЯ * высота
        половина_тела_px = тело_ширина * высота / 2
        self._мин_x = поле_px + половина_тела_px
        # запас_справа — если справа вверху что-то прибито (часы). Доли H.
        self._макс_x = max(self._мин_x,
                           ширина - поле_px - половина_тела_px - запас_справа * высота)
        # занято_слева — до какой доли H по горизонтали доходят карточки
        # (музыка, погода) слева вверху. Пока карточка на экране, левее
        # этого персонажу нельзя: он ОТХОДИТ, а не прячется под неё.
        self._мин_x_у_карточки = min(self._макс_x, max(
            self._мин_x, занято_слева * высота + половина_тела_px + 0.02 * высота))
        self._карточка = False

        # Середина экрана — это цель по умолчанию, но границы могли сделать
        # её недопустимой; зажимаем сразу, а не ждём первого решения _решить
        # — до него «стоит»/«медитирует» держат x на месте, и место должно
        # быть безопасным с самого первого кадра.
        self.x = max(self._мин_x, min(ширина / 2.0, self._макс_x))
        self._цель = self.x
        self._под = "стоит"
        self._решение_в = 0.0
        self._нога_фаза = 0.0
        self._t_прошлый: float | None = None
        # Откуда начался нынешний переход к _цель — чтобы _шагнуть знал, сколько
        # уже пройдено, и мог разогнаться/затормозить, а не идти одной скоростью.
        self._шаг_старт = self.x
        # БОДРОСТЬ И ВОЗБУЖДЕНИЕ — входы снаружи, 0..1. Пока их никто не
        # двигает, персонаж всегда полон сил, как и было. Дальше их будет
        # считать настроение: к вечеру бодрость падает, дыхание замедляется,
        # ходить хочется меньше. Это единственное внутреннее состояние,
        # которое зритель считывает без объяснений: усталый выглядит усталым.
        self.бодрость = 1.0
        self.возбуждение = 0.0

    @property
    def _мин_сейчас(self) -> float:
        return self._мин_x_у_карточки if self._карточка else self._мин_x

    # --- главный вход -------------------------------------------------------
    def кадр(self, состояние: dict, t: float) -> dict:
        """Поза персонажа для момента t. Всё время — снаружи, как и у кисти."""
        поза = self._поза(состояние, t)
        return self._с_настроением(поза, состояние.get("эмоция", "спокоен"))

    def _с_настроением(self, поза: dict, эмоция: str) -> dict:
        """Подкрасить любую позу настроением.

        Раньше `кадр` читал эмоцию ровно в двух ветках, и обе были заморозкой
        («сплю», «тревога»): из восьми настроений ТЕЛО не знало ни одного —
        обрадованный и огорчённый стояли и ходили совершенно одинаково. А
        поза — первое, по чему настроение читают у живых, задолго до лица:
        обрадованный подбирается и пружинит, огорчённый оседает и дышит
        реже, озадаченный кренится набок. Числа маленькие нарочно: это
        подкраска чужой позы, а не своя поза со своим характером.

        Заморозок («спит», «тревога») в таблице нет вовсе — они и есть эмоция
        целиком, и красить их нечем: `get` вернёт нули.
        """
        осадка, крен, бодрость = ЭМОЦИЯ_В_ТЕЛЕ.get(эмоция, (0.0, 0.0, 1.0))
        if бодрость != 1.0:
            поза["подскок"] *= бодрость
        поза["подскок"] += осадка * self.H
        поза["наклон"] += крен
        return поза

    def _поза(self, состояние: dict, t: float) -> dict:
        dt = 0.0 if self._t_прошлый is None else max(0.0, t - self._t_прошлый)
        self._t_прошлый = t

        музыка_поле = состояние.get("музыка")
        музыка = isinstance(музыка_поле, dict) and bool(музыка_поле.get("играет"))
        self._карточка = музыка or isinstance(состояние.get("погода"), dict)

        эмоция = состояние.get("эмоция", "спокоен")
        взгляд_сейчас = _угол(состояние.get("взгляд"))
        видит_сейчас = bool(состояние.get("человек")) and взгляд_сейчас is not None
        if эмоция == "сплю":
            # Взгляд НУЛЕВОЙ и это важно: спящий смотрит прямо, а не туда, где
            # человек был перед сном. На ПК поза замирает при потере связи с
            # роботом, и без обнуления Марк засыпал с головой, вывернутой в
            # сторону, — глаза закрыты, а шея скручена. У домовёнка это давно
            # так (face.py не читает «взгляд» во сне), у Марка не было.
            # СПЯЩИЙ ДЫШИТ — медленно и глубоко. Раньше эта ветка возвращала
            # ровные нули, то есть самый долгий кадр в сутках выглядел
            # выключенным прибором: восемь часов абсолютно неподвижной
            # картинки. Дыхание — единственное, что отличает спящего от
            # мёртвого, и стоит оно одной строки.
            return _пустая_поза(self.x, self._нога_фаза, "спит",
                                подскок=self._дыхание(t, СОН_ЧАСТОТА, СОН_СИЛА))
        if эмоция == "встревожен":
            # А вот встревоженный человека НЕ ТЕРЯЕТ. Здесь поза замирает — на
            # то она и тревога, — но смотреть персонаж продолжает туда же, где
            # человек. Иначе два экрана одного героя вели себя противоположно:
            # домовёнок при тревоге следил глазами, а Марк разворачивался прямо.
            # ВСТРЕВОЖЕННЫЙ ТОЖЕ ДЫШИТ — часто и мелко, и его слегка
            # потряхивает. Замереть от испуга живое существо может, но не
            # перестать дышать; ровные нули читались не как тревога, а как
            # «программа повисла». Дрожь мелкая (доли градуса) — её не видно
            # глазом отдельно, но неподвижность она снимает.
            дрожь = math.sin(t * 37.0) * ТРЕВОГА_ДРОЖЬ
            return _пустая_поза(self.x, self._нога_фаза, "тревога",
                                подскок=self._дыхание(t, ТРЕВОГА_ЧАСТОТА,
                                                      ТРЕВОГА_СИЛА),
                                наклон=дрожь,
                                взгляд=(self.доля_взгляда(взгляд_сейчас)
                                        if видит_сейчас else 0.0))
        # Карточка появилась, а персонаж стоит под ней — сначала отойти.
        # Это важнее и речи, и взгляда, и танца: карточку читают, а речь
        # длится секунды — шаг в сторону короче. Рот на ходу всё равно
        # открывается, если говорит.
        #
        # Продолжаем, ПОКА уже идём именно сюда, а не только «не дошли»: у
        # разгона/торможения (_скорость_множитель) шаг у цели может выйти
        # меньше прежнего запаса в полпикселя — ровно тот случай, когда x
        # оказывался чуть ближе _мин_сейчас, чем этот запас, но ещё не в
        # цели, а _карточка не пускала сюда снова через речь/взгляд/танец:
        # персонаж замирал в полупикселе от места навсегда. _шагнуть сам
        # снимает «идёт», как только дойдёт, — снаружи ему в этом мешать незачем.
        отходит = self._под == "идёт" and self._цель == self._мин_сейчас
        if self.x < self._мин_сейчас or отходит:
            if not отходит:
                self._шаг_старт = self.x
            self._цель, self._под = self._мин_сейчас, "идёт"
            self._решение_в = t + 3600.0
            шаг = self._шагнуть(t, dt)
            if шаг is not None:
                if состояние.get("говорит"):
                    шаг["рот"] = self._говорит(t)["рот"]
                # Отходит из-под карточки — но голову держит к человеку.
                # Иначе на все секунды ухода персонаж отворачивался от
                # собеседника: заиграла музыка, показали погоду — и он
                # разговаривает, глядя в сторону.
                if видит_сейчас:
                    шаг["взгляд"] = self.доля_взгляда(взгляд_сейчас)
                return self._с_рассеянным(шаг, t)
        # Контакт глаз: пока человек в кадре, персонаж повёрнут к нему — и
        # когда говорит тоже. Раньше речь перебивала взгляд, и на время
        # ответа персонаж смотрел прямо перед собой, мимо собеседника: со
        # стороны это читалось как «говорит не со мной».
        взгляд = _угол(состояние.get("взгляд"))
        видит = состояние.get("человек") and взгляд is not None
        if состояние.get("говорит"):
            поза = self._говорит(t)
            if видит:
                поза["наклон"] = self._наклон_к(взгляд)
                поза["взгляд"] = self.доля_взгляда(взгляд)
                # И на собеседника смотрят не в упор: тот же отвод взгляда.
                return self._с_рассеянным(поза, t, ВЗГЛЯД_ОТВОД)
            return self._с_рассеянным(поза, t)
        if видит:
            return self._смотрит(взгляд, t)
        if музыка:
            return self._танцует(t)
        return self._с_рассеянным(self._блуждает(t, dt), t)

    def _с_рассеянным(self, поза: dict, t: float, доля: float = 1.0) -> dict:
        """Дописать в позу блуждание взгляда — там, где глазам нечем занять-
        ся. НЕ зовётся при танце, сне и тревоге: спорить с настоящим поводом
        блуждание не должно — оно фон, а не поза.

        `доля` — вполсилы. На контакте глаз взгляд раньше замирал наглухо, и
        это ровно та мертвечина, ради которой всё и затевалось: НИ ОДИН
        живой не смотрит в чужие глаза неподвижно. Взгляд всё время чуть
        уходит и возвращается — это называется gaze aversion, и по
        исследованиям социальных роботов (Furhat и другие) именно
        неотрывный взгляд читается как жуткий, а не как внимательный.
        """
        сак_x, сак_y = self._рассеян(t)
        поза["рассеян_x"], поза["рассеян_y"] = сак_x * доля, сак_y * доля
        return поза

    # --- реакции на месте -----------------------------------------------------
    def _говорит(self, t: float) -> dict:
        # Дыхание есть и здесь. Раньше речь выключала жизнь тела целиком:
        # подскок ноль, руки ноль, двигался один рот — то есть ровно в те
        # секунды, когда на персонажа смотрят внимательнее всего, он
        # переставал быть живым и становился говорящей картинкой.
        рот = max(0.0, math.sin(t * 2 * math.pi * ГОВОРИТ_ЧАСТОТА))
        return _пустая_поза(self.x, self._нога_фаза, "говорит",
                            рот=рот, подскок=self._дыхание(t))

    @staticmethod
    def доля_взгляда(угол: float) -> float:
        """Пеленг в радианах → доля −1…1, где ±1 — край поля зрения камеры.

        Знак — как у глаз: пеленг влево положительный, поворот в ту же
        сторону, иначе персонаж отворачивается от человека, на которого якобы
        смотрит.

        Делим на ПОЛОВИНУ ПОЛЯ КАМЕРЫ, а не на условные 45°, как было раньше.
        Камера видит 130° — до ±65° от центра, — и всё, что дальше 45°,
        упиралось в единицу: человек отходит вбок, ещё прекрасно виден
        детектору, а персонаж перестаёт доворачиваться и смотрит мимо. Теперь
        край доли ровно совпадает с краем кадра.
        """
        доля = угол / (math.radians(ПОЛЕ_КАМЕРЫ) / 2.0)
        return max(-1.0, min(1.0, доля))

    @classmethod
    def _наклон_к(cls, угол: float) -> float:
        return cls.доля_взгляда(угол) * ЛЕАН_МАКС

    def _смотрит(self, угол: float, t: float) -> dict:
        поза = _пустая_поза(self.x, self._нога_фаза, "смотрит",
                            наклон=self._наклон_к(угол),
                            взгляд=self.доля_взгляда(угол),
                            подскок=self._дыхание(t))
        return self._с_рассеянным(поза, t, ВЗГЛЯД_ОТВОД)

    @staticmethod
    def _рассеян(t: float) -> tuple[float, float]:
        """Куда «сам собой» уплыл взгляд к моменту t: доли -1..1 по x и y.

        Между делами глаза, оставленные ровно там, где их бросил прошлый
        повод, читаются остекленевшими — персонаж «смотрит в одну точку»,
        даже когда дышит и переступает. Это тот же приём, которым живут
        VTuber-риги: медленное блуждание взгляда фоном.

        Здесь только ЧИСЛА, без амплитуд в пикселях и градусах: свои экраны
        (face.py у робота, страница Live2D у ПК) домножают их на своё — у
        одного глаза ездят по холсту, у другого крутятся параметры модели.
        Кто и когда его глушит — решает не эта функция, а тот, кто зовёт:
        поводов молчать у неё разное число на разных экранах (у страницы
        есть ещё и взгляд сценки, которого тело не знает).
        """
        def дрейф(частоты, фазы) -> float:
            низ, верх = частоты
            фн, фв = фазы
            return (math.sin(t * 2 * math.pi * низ + фн) * РАССЕЯН_ДОЛИ[0]
                    + math.sin(t * 2 * math.pi * верх + фв) * РАССЕЯН_ДОЛИ[1])
        сак_x, сак_y = Питомец._саккада(t)
        дрейф_x = дрейф(РАССЕЯН_ЧАСТОТЫ_X, РАССЕЯН_ФАЗЫ_X)
        дрейф_y = дрейф(РАССЕЯН_ЧАСТОТЫ_Y, РАССЕЯН_ФАЗЫ_Y)
        def смесь(д: float, с: float) -> float:
            return max(-1.0, min(1.0, д * (1 - СААКАДА_ДОЛЯ) + с * СААКАДА_ДОЛЯ))
        return (смесь(дрейф_x, сак_x), смесь(дрейф_y, сак_y))

    @staticmethod
    def _жребий(номер: int, соль: float) -> float:
        """Повторимое псевдослучайное 0..1 по номеру — без состояния.

        Именно без состояния: `_рассеян` обязан оставаться чистой функцией от
        времени. На неё смотрят три отрисовки, и робот со своим экраном может
        начать считать её на полчаса позже страницы на ПК — при общем t они
        обязаны дать одно и то же число, а не разойтись на своих генераторах.
        """
        х = math.sin(номер * 12.9898 + соль) * 43758.5453
        return х - math.floor(х)

    @staticmethod
    def _фиксация(номер: int) -> tuple[float, float]:
        """Точка, на которой стоит взгляд в этом слоте.

        Сетка слотов ровная, а фиксации выходят разной длины: слот с некоторой
        вероятностью не заводит свою точку, а остаётся на точке предыдущего.
        Так получается живой разброс «глянул-глянул-глянул… и долго смотрит
        в одну точку» без единой переменной состояния.
        """
        корень = номер
        for _ in range(СААКАДА_ДЕРЖИТ_ПОДРЯД):
            if корень <= 0 or Питомец._жребий(корень, 7.13) >= СААКАДА_ДЕРЖИТ:
                break
            корень -= 1
        return (Питомец._жребий(корень, 1.7) * 2 - 1,
                Питомец._жребий(корень, 4.2) * 2 - 1)

    @staticmethod
    def _саккада(t: float) -> tuple[float, float]:
        """Прыжок взгляда: стоим на точке, потом быстро перелетаем на другую."""
        слот = math.floor(t / СААКАДА_ШАГ)
        доля = min(1.0, max(0.0, (t - слот * СААКАДА_ШАГ) / СААКАДА_ПЕРЕЛЁТ))
        ш = 0.5 - 0.5 * math.cos(math.pi * доля)   # мягкий старт и стоп перелёта
        из_x, из_y = Питомец._фиксация(слот - 1)
        в_x, в_y = Питомец._фиксация(слот)
        return (из_x + (в_x - из_x) * ш, из_y + (в_y - из_y) * ш)

    def _дыхание(self, t: float, частота: float = 1.0, сила: float = 1.0) -> float:
        """Вдох-выдох, чтобы стоящий на месте не читался истуканом.

        Здесь две вещи, которые отличают дыхание живого от синусоиды.

        ПЕРВОЕ: ПЕРИОДЫ НЕ СОВПАДАЮТ. Грудь, корпус и голова качаются каждый
        своим сроком — 3.23, 15.53 и 6.53 секунды, — и вместе не повторяются
        почти никогда. Так устроено дыхание в Live2D (setupBreath), и не от
        красоты: ровный период глаз ловит быстрее, чем осознаёт, и с этого
        мига существо становится механизмом. Числа некруглые намеренно —
        круглые складываются в общий период слишком скоро.

        ВТОРОЕ: ВДОХ КОРОЧЕ ВЫДОХА. У живого вдох занимает примерно две пятых
        цикла, выдох — три пятых, и между ними есть крошечная пауза. Синус
        симметричен, и от этого дыхание выходит «механическое» даже при
        верной частоте.

        `частота` и `сила` — множители: спящий дышит вдвое медленнее и глубже,
        встревоженный — часто и мелко, усталый — медленнее бодрого. Раньше
        дыхание было одно на всех, а спящий и встревоженный не дышали вовсе.
        """
        частота = max(0.05, частота * (2.0 - max(0.0, min(1.0, self.бодрость))))
        # ДЫХАНИЕ ЖИВОГО НЕ ХОДИТ ПО МЕТРОНОМУ. Период всё время слегка гуляет
        # — это называется дыхательной вариабельностью, и она есть у всех, кто
        # дышит сам; строго ровный период бывает только у аппарата ИВЛ.
        # Ухо этого не замечает, а глаз замечает: ровная синусоида на груди
        # читается как механизм, даже когда частота верная. Гуляем медленно
        # (полминуты на цикл блуждания) и немного — на десятую часть.
        медленно = self._жребий(int(t / ДЫХАНИЕ_ГУЛЯЕТ), 7.77)
        следом = self._жребий(int(t / ДЫХАНИЕ_ГУЛЯЕТ) + 1, 7.77)
        доля = (t % ДЫХАНИЕ_ГУЛЯЕТ) / ДЫХАНИЕ_ГУЛЯЕТ
        плавно = медленно + (следом - медленно) * (0.5 - 0.5 * math.cos(доля * math.pi))
        частота *= 1.0 + (плавно - 0.5) * 2 * ДЫХАНИЕ_РАЗБРОС
        сила = сила * self.H * ДЫХАНИЕ_ПОДСКОК

        def волна(период: float, сдвиг: float) -> float:
            доля = ((t / max(0.001, период * частота)) + сдвиг) % 1.0
            if доля < ВДОХ_ДОЛЯ:                       # вдох: быстрее
                return math.sin(доля / ВДОХ_ДОЛЯ * math.pi / 2)
            выдох = (доля - ВДОХ_ДОЛЯ) / (1.0 - ВДОХ_ДОЛЯ)
            return math.cos(выдох * math.pi / 2)       # выдох: дольше и плавнее

        return сила * (0.62 * волна(ДЫХАНИЕ_ГРУДЬ, 0.0)
                       + 0.26 * волна(ДЫХАНИЕ_КОРПУС, 0.31)
                       + 0.12 * волна(ДЫХАНИЕ_ГОЛОВА, 0.67))

    def _танцует(self, t: float) -> dict:
        # Наклон тела здесь НАМЕРЕННО не участвует: он крутит весь корпус
        # вокруг его собственного центра (так рисует кисть), а руки — вокруг
        # плеча. Сложить оба поворота ещё и с раскачкой рук — верный способ
        # получить не танец, а падение; проверено на первом же кадре.
        фаза = t * 2 * math.pi * ТАНЕЦ_ЧАСТОТА
        подскок = abs(math.sin(фаза)) * ТАНЕЦ_ПОДСКОК * self.H
        # ОБЕ руки поднимаются НАРУЖУ вместе, а не крест-накрест: поворот
        # кисти (face.py._руки) считает положительный угол взмахом вправо
        # ОТ ПЛЕЧА, и для левого плеча это значит внутрь, под корпус — там
        # рука на первом же кадре и пряталась, проверено картинкой.
        рука = abs(math.sin(фаза)) * 30.0
        return _пустая_поза(self.x, self._нога_фаза, "танцует",
                            подскок=подскок, рука_л=-рука, рука_п=рука)

    # --- блуждание: единственное, что двигает x -----------------------------
    def _решить(self, t: float) -> None:
        """Что делать дальше — жребий. Идёт чаще, чем стоит или медитирует."""
        жребий = self.случай.random()
        if жребий < В_ИДЁТ:
            self._шаг_старт = self.x
            self._цель = self.случай.uniform(self._мин_сейчас, self._макс_x)
            self._под = "идёт"
            # Пока не дойдёт — новое решение не нужно; момент прихода сам
            # выставит следующий срок. Без этого срок наступил бы посреди
            # шага, и жребий бросали бы заново, не дав дойти.
            self._решение_в = t + 3600.0
        elif жребий < В_СТОИТ:
            self._под = "стоит"
            self._решение_в = t + self.случай.uniform(*ПАУЗА)
        else:
            self._под = "медитирует"
            self._решение_в = t + self.случай.uniform(*МЕДИТАЦИЯ)

    def _скорость_множитель(self) -> float:
        """Доля от полной скорости хода: разгон у старта, торможение у цели.

        Slow in/slow out — самый цитируемый из двенадцати принципов
        мультипликации (Disney) именно потому, что равномерная скорость
        читается как заводная игрушка, а не как что-то живое. Считаем от
        РАССТОЯНИЯ, не от времени: тогда работает и посреди перехода,
        прерванного речью или взглядом на много кадров, — а не только с
        начала до конца одного гладкого прогона."""
        весь_путь = abs(self._цель - self._шаг_старт)
        if весь_путь <= 1e-6:
            return 1.0
        пройдено = abs(self.x - self._шаг_старт)
        запас = max(1e-6, min(РАЗГОН_ДОЛЯ * весь_путь, весь_путь / 2))
        к_старту = пройдено / запас
        к_цели = (весь_путь - пройдено) / запас
        return max(МИН_СКОРОСТЬ_ДОЛЯ, min(1.0, к_старту, к_цели))

    def _шагнуть(self, t: float, dt: float) -> dict | None:
        """Один шаг к _цель. None — дошли (и уже стоим); поза — ещё идём."""
        множитель = self._скорость_множитель()
        шаг = СКОРОСТЬ_ХОДЬБЫ * self.H * dt * множитель
        осталось = self._цель - self.x
        if abs(осталось) <= шаг:
            self.x = self._цель
            self._под = "стоит"
            self._решение_в = t + self.случай.uniform(*ПАУЗА)
            return None
        направление = 1.0 if осталось > 0 else -1.0
        self.x += направление * шаг
        self._нога_фаза += шаг / self._шаг_длина_px
        подскок = (abs(math.sin(t * 2 * math.pi * ПОСТУПЬ_ЧАСТОТА))
                  * ПОСТУПЬ_ПОДСКОК * self.H * множитель)
        return _пустая_поза(self.x, self._нога_фаза, "идёт",
                            подскок=подскок, наклон=направление * 4.0)

    def _блуждает(self, t: float, dt: float) -> dict:
        if t >= self._решение_в:
            self._решить(t)

        if self._под == "идёт":
            поза = self._шагнуть(t, dt)
            if поза is not None:
                return поза
            # Дошли ровно в этом кадре — доигрываем как «стоит» ниже.

        if self._под == "медитирует":
            подскок = (math.sin(t * 2 * math.pi * МЕДИТАЦИЯ_ЧАСТОТА)
                      * МЕДИТАЦИЯ_ПОДСКОК * self.H)
            return _пустая_поза(self.x, self._нога_фаза, "медитирует",
                                подскок=подскок, рука_л=-20.0, рука_п=20.0)

        return _пустая_поза(self.x, self._нога_фаза, "стоит", подскок=self._дыхание(t))
