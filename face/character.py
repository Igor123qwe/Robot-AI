"""Тело персонажа: где стоит, куда идёт, что делают руки и ноги.

Отдельно от кисти (face.py), по той же причине, по которой издатель и кисть —
два разных файла: это не рисование, а решение «что делать сейчас», и его
можно проверить числами, без единого вызова pygame.

КТО ЭТО. Не робот на колёсах — домовёнок, тот же, чьим именем зовётся голос
(«Кузя»). У домовёнка нет колёс: он ходит, и «нога» ниже — это фаза шага для
переступания, а не угол вращения.

ОТКУДА БЕРЁТСЯ ПОВЕДЕНИЕ. Ни одного нового поля в face.json — только то, что
там уже есть: эмоция, говорит, человек, взгляд, музыка. Раньше эти поля
двигали только глаза; теперь по ним же решает, что делать, ещё и тело.

ПОРЯДОК ВАЖНЕЕ ВСЕГО ОСТАЛЬНОГО, и он ровно тот, каким уже руководствуется
voice/robot_voice/app.py для эмоций (говорю не перебивает тревогу):

    сплю > тревога > говорит > видит человека > играет музыка > блуждает

«Сплю» — самый верхний, хотя по смыслу это состояние никогда не совпадает с
остальными на живом роботе (сплю бывает только когда издатель встал или
файл протух). Он всё равно проверяется первым — потому что самопроверка
имеет право собрать любую комбинацию полей, а тело не должно врать позой
спящего, увидевшего человека.

x ДВИГАЮТ ДВЕ ВЕЩИ: блуждание и карточки. Разговор и взгляд на человека
держат персонажа на месте — вещи короткие и частые, и мотание по экрану во
время разговора выглядело бы суетой, а не вниманием. А вот когда слева
вверху появляется карточка (музыка играет, спросили погоду), персонаж
ОТХОДИТ ВПРАВО, освобождая ей место, — и там уже пляшет или стоит. Иначе
карточка ложилась бы ему на лицо: на живом экране так и было с погодой.
"""

from __future__ import annotations

import math
import random

# --- поведение: скорости, паузы, амплитуды -----------------------------------
СКОРОСТЬ_ХОДЬБЫ = 0.10        # доли H в секунду
ПОЛЯ = 0.10                   # доли H — не подходит к самому краю экрана
ПАУЗА = (2.0, 5.0)            # секунд, случайная стоянка между переходами
МЕДИТАЦИЯ = (6.0, 12.0)       # секунд, случайная более долгая стоянка
В_ИДЁТ, В_СТОИТ, В_МЕДИТИРУЕТ = 0.55, 0.85, 1.0   # границы жребия — см. _решить

ЛЕАН_МАКС = 6.0               # градусов — наклон корпуса к человеку
ГОВОРИТ_ЧАСТОТА = 3.2         # Гц — открывание-закрывание рта. Не липсинк:
                               # честная имитация, потому что настоящий разбор
                               # звука в реальном времени сюда пока не подключён.
ТАНЕЦ_ПОДСКОК = 0.02          # доли H
ТАНЕЦ_ЧАСТОТА = 2.2           # Гц
ПОСТУПЬ_ПОДСКОК = 0.010       # доли H — лёгкий подскок на ходу
ПОСТУПЬ_ЧАСТОТА = 2.0         # Гц
МЕДИТАЦИЯ_ПОДСКОК = 0.006     # доли H — дыхание
МЕДИТАЦИЯ_ЧАСТОТА = 0.15      # Гц


def _пустая_поза(x: float, нога: float, метка: str, **доп) -> dict:
    """Общая заготовка позы: то, что не меняется, задано один раз."""
    поза = dict(x=x, подскок=0.0, наклон=0.0, рот=0.0, рука_л=0.0, рука_п=0.0,
                нога=нога, метка=метка)
    поза.update(доп)
    return поза


class Питомец:
    """Решает, где стоит персонаж и что делают его тело, руки и ноги.

    `тело_ширина`, `шаг_длина` — доли H, те же числа, которыми кисть рисует
    туловище и подбирает длину шага. Передаются снаружи, а не дублируются
    здесь: одно число, а не два, которые однажды разъедутся.
    """

    def __init__(self, ширина: int, высота: int, *, тело_ширина: float,
                 шаг_длина: float, запас_справа: float = 0.0,
                 занято_слева: float = 0.0, случай=random.Random(13)) -> None:
        self.W, self.H = ширина, высота
        self.случай = случай
        self._шаг_длина_px = max(1.0, шаг_длина * высота)

        поле_px = ПОЛЯ * высота
        половина_тела_px = тело_ширина * высота / 2
        self._мин_x = поле_px + половина_тела_px
        # запас_справа — если справа вверху что-то прибито (часы). Доли H.
        self._макс_x = max(self._мин_x,
                           ширина - поле_px - половина_тела_px - запас_справа * высота)
        # занято_слева — до какой доли H по горизонтали доходят карточки
        # (музыка, погода) слева вверху. Пока карточка на экране, левее
        # этого персонажу нельзя: он ОТХОДИТ, а не прячется под неё.
        self._мин_x_у_карточки = min(self._макс_x, max(
            self._мин_x, занято_слева * высота + половина_тела_px + 0.02 * высота))
        self._карточка = False

        # Середина экрана — это цель по умолчанию, но границы могли сделать
        # её недопустимой; зажимаем сразу, а не ждём первого решения _решить
        # — до него «стоит»/«медитирует» держат x на месте, и место должно
        # быть безопасным с самого первого кадра.
        self.x = max(self._мин_x, min(ширина / 2.0, self._макс_x))
        self._цель = self.x
        self._под = "стоит"
        self._решение_в = 0.0
        self._нога_фаза = 0.0
        self._t_прошлый: float | None = None

    @property
    def _мин_сейчас(self) -> float:
        return self._мин_x_у_карточки if self._карточка else self._мин_x

    # --- главный вход -------------------------------------------------------
    def кадр(self, состояние: dict, t: float) -> dict:
        """Поза персонажа для момента t. Всё время — снаружи, как и у кисти."""
        dt = 0.0 if self._t_прошлый is None else max(0.0, t - self._t_прошлый)
        self._t_прошлый = t

        музыка = bool((состояние.get("музыка") or {}).get("играет"))
        self._карточка = музыка or bool(состояние.get("погода"))

        эмоция = состояние.get("эмоция", "спокоен")
        if эмоция == "сплю":
            return _пустая_поза(self.x, self._нога_фаза, "спит")
        if эмоция == "встревожен":
            return _пустая_поза(self.x, self._нога_фаза, "тревога")
        # Карточка появилась, а персонаж стоит под ней — сначала отойти.
        # Это важнее и речи, и взгляда, и танца: карточку читают, а речь
        # длится секунды — шаг в сторону короче. Рот на ходу всё равно
        # открывается, если говорит.
        if self.x < self._мин_сейчас - 0.5:
            self._цель, self._под = self._мин_сейчас, "идёт"
            self._решение_в = t + 3600.0
            шаг = self._шагнуть(t, dt)
            if шаг is not None:
                if состояние.get("говорит"):
                    шаг["рот"] = self._говорит(t)["рот"]
                return шаг
        # Контакт глаз: пока человек в кадре, персонаж повёрнут к нему — и
        # когда говорит тоже. Раньше речь перебивала взгляд, и на время
        # ответа персонаж смотрел прямо перед собой, мимо собеседника: со
        # стороны это читалось как «говорит не со мной».
        видит = состояние.get("человек") and состояние.get("взгляд") is not None
        if состояние.get("говорит"):
            поза = self._говорит(t)
            if видит:
                поза["наклон"] = self._наклон_к(float(состояние["взгляд"]))
            return поза
        if видит:
            return self._смотрит(float(состояние["взгляд"]))
        if музыка:
            return self._танцует(t)
        return self._блуждает(t, dt)

    # --- реакции на месте -----------------------------------------------------
    def _говорит(self, t: float) -> dict:
        рот = max(0.0, math.sin(t * 2 * math.pi * ГОВОРИТ_ЧАСТОТА))
        return _пустая_поза(self.x, self._нога_фаза, "говорит", рот=рот)

    @staticmethod
    def _наклон_к(угол: float) -> float:
        # Знак — как у глаз: пеленг влево положительный, наклон в ту же
        # сторону, что и взгляд, иначе персонаж отворачивается от человека,
        # на которого якобы смотрит.
        доля = max(-1.0, min(1.0, угол / math.radians(45)))
        return доля * ЛЕАН_МАКС

    def _смотрит(self, угол: float) -> dict:
        return _пустая_поза(self.x, self._нога_фаза, "смотрит",
                            наклон=self._наклон_к(угол))

    def _танцует(self, t: float) -> dict:
        # Наклон тела здесь НАМЕРЕННО не участвует: он крутит весь корпус
        # вокруг его собственного центра (так рисует кисть), а руки — вокруг
        # плеча. Сложить оба поворота ещё и с раскачкой рук — верный способ
        # получить не танец, а падение; проверено на первом же кадре.
        фаза = t * 2 * math.pi * ТАНЕЦ_ЧАСТОТА
        подскок = abs(math.sin(фаза)) * ТАНЕЦ_ПОДСКОК * self.H
        # ОБЕ руки поднимаются НАРУЖУ вместе, а не крест-накрест: поворот
        # кисти (face.py._руки) считает положительный угол взмахом вправо
        # ОТ ПЛЕЧА, и для левого плеча это значит внутрь, под корпус — там
        # рука на первом же кадре и пряталась, проверено картинкой.
        рука = abs(math.sin(фаза)) * 30.0
        return _пустая_поза(self.x, self._нога_фаза, "танцует",
                            подскок=подскок, рука_л=-рука, рука_п=рука)

    # --- блуждание: единственное, что двигает x -----------------------------
    def _решить(self, t: float) -> None:
        """Что делать дальше — жребий. Идёт чаще, чем стоит или медитирует."""
        жребий = self.случай.random()
        if жребий < В_ИДЁТ:
            self._цель = self.случай.uniform(self._мин_сейчас, self._макс_x)
            self._под = "идёт"
            # Пока не дойдёт — новое решение не нужно; момент прихода сам
            # выставит следующий срок. Без этого срок наступил бы посреди
            # шага, и жребий бросали бы заново, не дав дойти.
            self._решение_в = t + 3600.0
        elif жребий < В_СТОИТ:
            self._под = "стоит"
            self._решение_в = t + self.случай.uniform(*ПАУЗА)
        else:
            self._под = "медитирует"
            self._решение_в = t + self.случай.uniform(*МЕДИТАЦИЯ)

    def _шагнуть(self, t: float, dt: float) -> dict | None:
        """Один шаг к _цель. None — дошли (и уже стоим); поза — ещё идём."""
        шаг = СКОРОСТЬ_ХОДЬБЫ * self.H * dt
        осталось = self._цель - self.x
        if abs(осталось) <= шаг:
            self.x = self._цель
            self._под = "стоит"
            self._решение_в = t + self.случай.uniform(*ПАУЗА)
            return None
        направление = 1.0 if осталось > 0 else -1.0
        self.x += направление * шаг
        self._нога_фаза += шаг / self._шаг_длина_px
        подскок = abs(math.sin(t * 2 * math.pi * ПОСТУПЬ_ЧАСТОТА)
                     ) * ПОСТУПЬ_ПОДСКОК * self.H
        return _пустая_поза(self.x, self._нога_фаза, "идёт",
                            подскок=подскок, наклон=направление * 4.0)

    def _блуждает(self, t: float, dt: float) -> dict:
        if t >= self._решение_в:
            self._решить(t)

        if self._под == "идёт":
            поза = self._шагнуть(t, dt)
            if поза is not None:
                return поза
            # Дошли ровно в этом кадре — доигрываем как «стоит» ниже.

        if self._под == "медитирует":
            подскок = (math.sin(t * 2 * math.pi * МЕДИТАЦИЯ_ЧАСТОТА)
                      * МЕДИТАЦИЯ_ПОДСКОК * self.H)
            return _пустая_поза(self.x, self._нога_фаза, "медитирует",
                                подскок=подскок, рука_л=-20.0, рука_п=20.0)

        return _пустая_поза(self.x, self._нога_фаза, "стоит")
