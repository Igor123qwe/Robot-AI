ПО_ИМЕНИ = {с.имя: с for с in СЦЕНКИ}
ИЩЕТ = ("пошёл искать", "выглянул за край", "к другому краю", "никого",
        "пожал плечами", "вернулся на место")


class Сценарист:
    """Выбирает и ведёт сценки. Всё время снаружи; жребий — свой Random."""

    def __init__(self, случай=None) -> None:
        self.случай = случай or random.Random(11)
        self._было: dict | None = None            # прошлое состояние
        self._сцена: Сценка | None = None
        self._начало = 0.0
        self._следующая = 0.0                     # когда можно новую фоновую
        self._играли: dict[str, float] = {}       # имя → когда кончилась
        self._человек_ушёл_в = None               # None — человек есть
        self._покой_с = 0.0                       # с какого t ничего не происходит
        self._пеленг: list[tuple[float, float]] = []
        self._таймер_скоро_был: set[str] = set()
        self._батарея_жаловался = float("-inf")
        self._час_был = -1
        self._услышал_было = ""
        self._день_утра = -1
        self._куда = 0.0                          # куда было последнее движение

    # --- события: смена состояния ---------------------------------------------
    def _события(self, с: dict, t: float, час: int, минута: int) -> list[str]:
        было = self._было or {}
        соб: list[str] = []
        эмоция = с.get("эмоция", "спокоен")
        эмоция_была = было.get("эмоция", "спокоен")
        if эмоция != эмоция_была:
            if эмоция == "слушаю":
                соб.append("имя")
            elif эмоция == "думаю":
                соб.append("думает")
            elif эмоция in ("не_понял", "рад", "огорчён"):
                соб.append(эмоция)
            elif эмоция == "встревожен":
                соб.append("тревога")
        человек, был = bool(с.get("человек")), bool(было.get("человек"))
        if человек and not был:
            # Вернулся посреди поиска — это не «пришёл», это «нашёлся».
            ищет = self._сцена is not None and self._сцена.имя in ИЩЕТ
            соб.append("нашёлся" if ищет else "человек_пришёл")
        elif был and not человек:
            соб.append("человек_ушёл")
            # Искать — с той стороны, где его видели в последний раз.
            # Пеленг влево положительный, экранное «куда» — вправо.
            if self._пеленг:
                self._куда = -1.0 if self._пеленг[-1][1] > 0 else 1.0
        # Движение: пеленг человека скакнул за полсекунды — или камера
        # увидела, что что-то шевельнулось (motion.py: кошка, штора, свет).
        # Куда смотреть — запоминаем: −1 слева, +1 справа.
        if с.get("взгляд") is not None and человек:
            self._пеленг.append((t, float(с["взгляд"])))
            self._пеленг = [(тт, у) for тт, у in self._пеленг if t - тт <= 0.5]
            if len(self._пеленг) >= 2 and abs(self._пеленг[-1][1] - self._пеленг[0][1]) >= СКАЧОК_ПЕЛЕНГА:
                соб.append("движение")
                # Пеленг влево положительный; экранное «где» — вправо.
                self._куда = max(-1.0, min(1.0, -self._пеленг[-1][1] / 0.8))
                self._пеленг = []
        движение = с.get("движение") or {}
        было_движение = было.get("движение") or {}
        if движение.get("есть") and not было_движение.get("есть") and "движение" not in соб:
            соб.append("движение")
            self._куда = max(-1.0, min(1.0, float(движение.get("где") or 0.0)))
        играет = bool((с.get("музыка") or {}).get("играет"))
        играла = bool((было.get("музыка") or {}).get("играет"))
        if играет and not играла:
            соб.append("музыка_началась")
        elif играла and not играет:
            соб.append("музыка_кончилась")
        # Мозг позвал инструмент: сравниваем НОМЕР, а не имя, — два
        # «drive» подряд должны дать два жеста, а не один.
        делает = с.get("делает") or {}
        делал = было.get("делает") or {}
        if делает.get("номер") and делает.get("номер") != делал.get("номер"):
            соб.append(дело(str(делает.get("что") or "")))
        едет, ехал = bool(с.get("едет")), bool(было.get("едет"))
        if едет and not ехал:
            соб.append("поехали")
        elif ехал and not едет:
            соб.append("приехали")
        # Таймеры: скоро и кончился.
        имена = {з.get("имя"): int(з.get("осталось") or 0) for з in (с.get("таймеры") or [])}
        были_имена = {з.get("имя"): int(з.get("осталось") or 0) for з in (было.get("таймеры") or [])}
        for имя, осталось in имена.items():
            if осталось <= ТАЙМЕР_СКОРО and имя not in self._таймер_скоро_был:
                self._таймер_скоро_был.add(имя)
                соб.append("таймер_скоро")
        for имя, осталось in были_имена.items():
            if имя not in имена:
                self._таймер_скоро_был.discard(имя)
                if осталось <= 2:
                    соб.append("таймер_кончился")
        if минута == 0 and час != self._час_был:
            if self._час_был >= 0:
                соб.append("час_пробил")
            self._час_был = час
        elif минута != 0 and self._час_был != час:
            self._час_был = час              # запуск посреди часа — не «пробило»
        батарея = с.get("батарея")
        if (isinstance(батарея, (int, float)) and батарея <= БАТАРЕЯ_МАЛО
                and t - self._батарея_жаловался >= БАТАРЕЯ_НАПОМИНАТЬ):
            self._батарея_жаловался = t
            соб.append("батарея_мало")
        погода, была_погода = с.get("погода"), было.get("погода")
        if погода and not была_погода:
            код = int(погода.get("код") or 0)
            if код in (51, 53, 55, 56, 57, 61, 63, 65, 66, 67, 80, 81, 82, 95, 96, 99):
                соб.append("дождь")
            elif код in (71, 73, 75, 77, 85, 86):
                соб.append("снег")
            elif int(погода.get("t") or 0) >= 28:
                соб.append("жара")
        услышал = (с.get("услышал") or "").strip().lower()
        if услышал and услышал != self._услышал_было:
            self._услышал_было = услышал
            for слово, соб_имя in (("спасибо", "услышал_спасибо"), ("пока", "услышал_пока"),
                                   ("до свидания", "услышал_пока"), ("привет", "услышал_привет"),
                                   ("молодец", "услышал_молодец"), ("умница", "услышал_молодец"),
                                   ("ха-ха", "услышал_смех"), ("ахах", "услышал_смех"),
                                   ("люблю", "услышал_люблю")):
                if слово in услышал:
                    соб.append(соб_имя)
                    break
        return соб

    # --- фон: что уместно прямо сейчас ------------------------------------------
    def _фоны(self, с: dict, t: float, час: int) -> list[str]:
        эмоция = с.get("эмоция", "спокоен")
        # «Сплю» (голос молчит) сюда не доходит: это не «спокоен», и ниже
        # ему, как и любой эмоции, кроме спокойной, фонов не положено.
        if с.get("говорит"):
            return ["говорит"]
        if (с.get("музыка") or {}).get("играет"):
            return ["танец"]
        if с.get("едет"):
            return ["едет"]
        if эмоция != "спокоен":
            return []
        ночь = bool(с.get("ночь"))
        if ночь and t - self._покой_с >= НОЧЬ_СПИТ_ЧЕРЕЗ and not с.get("человек"):
            return ["ночь_спит"]
        if с.get("человек"):
            return ["человек_рядом", "покой"]
        фоны = ["покой_ночью"] if ночь else ["покой"]
        if 6 <= час < 11 and not ночь:
            фоны.append("покой_утром")
        if t - self._покой_с >= ДОЛГО_ОДИН:
            фоны.append("долго_один")
        return фоны

    def _выбрать(self, когда: list[str], t: float) -> Сценка | None:
        годные = [сц for сц in СЦЕНКИ if сц.когда in когда
                  and t - self._играли.get(сц.имя, float("-inf")) >= сц.отдых]
        if not годные:
            return None
        веса = [сц.вес for сц in годные]
        return self.случай.choices(годные, weights=веса, k=1)[0]

    def _начать(self, сц: Сценка, t: float) -> None:
        self._сцена, self._начало = сц, t

    # --- главный вход ---------------------------------------------------------
    def кадр(self, с: dict, t: float, час: int = 12, минута: int = 30) -> dict:
        """Сдвиги для этого кадра: {имя, текст, параметры, x, y, поворот, масштаб}."""
        события = self._события(с, t, час, минута)
        фоны = self._фоны(с, t, час)
        # Покой считается с момента, когда последний раз что-то было.
        if события or not фоны or фоны[0] not in ("покой", "покой_ночью", "долго_один", "ночь_спит"):
            self._покой_с = t
        self._было = dict(с)

        # Событие перебивает фон и события с меньшим приоритетом.
        for соб in события:
            новая = self._выбрать([соб], t)
            if новая and (self._сцена is None or новая.приоритет >= self._сцена.приоритет
                          or self._сцена.когда in ФОНЫ):
                self._начать(новая, t)
                break

        # Текущая сценка кончилась?
        if self._сцена is not None:
            прошло = t - self._начало
            if прошло >= self._сцена.длительность:
                if self._сцена.цикл and self._сцена.когда in фоны:
                    self._начало = t          # ещё круг: музыка всё играет
                elif self._сцена.следом and self._сцена.следом in ПО_ИМЕНИ:
                    # Цепочка: следующее звено сразу, без паузы и жребия.
                    self._играли[self._сцена.имя] = t
                    self._начать(ПО_ИМЕНИ[self._сцена.следом], t)
                else:
                    self._играли[self._сцена.имя] = t
                    self._сцена = None
                    if фоны and фоны[0] in ("танец", "ночь_спит"):
                        self._следующая = t   # музыка не ждёт: сразу в пляс
                    else:
                        пауза = (ПАУЗА_РЕЧИ if "говорит" in фоны
                                 else ПАУЗА_НОЧЬЮ if "покой_ночью" in фоны else ПАУЗА_ПОКОЯ)
                        self._следующая = t + self.случай.uniform(*пауза)
            elif self._сцена.когда in ФОНЫ and self._сцена.когда not in фоны:
                # Фон сменился (музыка кончилась посреди танца, заговорил
                # посреди зевка) — фоновую сценку бросаем, событийную доигрываем.
                self._играли[self._сцена.имя] = t
                self._сцена = None

        # Новая фоновая — когда пауза вышла.
        if self._сцена is None and фоны and t >= self._следующая:
            цикличные = фоны[0] in ("танец", "ночь_спит")
            новая = self._выбрать(фоны, t)
            if новая is not None:
                self._начать(новая, t)
            elif not цикличные:
                self._следующая = t + 1.0

        if self._сцена is None:
            return {"имя": "", "текст": "", "параметры": {}}
        доля = (t - self._начало) / max(1e-6, self._сцена.длительность)
        п = self._сцена.параметры(доля)
        if self._сцена.зеркало and self._куда < 0:
            # Сценка «в ту сторону»: влево — всё, что смотрит и идёт
            # вправо, переворачивается. Руки не трогаем: они наружу.
            for к in ЗЕРКАЛЬНЫЕ:
                if к in п:
                    п[к] = -п[к]
        свои = {к: п.pop(к, None) for к in (X, Y, ПОВОРОТ, МАСШТАБ)}
        итог = {"имя": self._сцена.имя, "текст": self._сцена.текст, "параметры": п}
        for к, з in свои.items():
            if з is not None:
                итог[к] = з
        if self._сцена.когда == "движение":
            # Сценка про движение — в ту сторону, где оно было: голова и
            # глаза туда (страница и домовёнок складывают это со своим).
            итог["к"] = self._куда
        return итог
