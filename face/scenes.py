def дело(инструмент: str) -> str:
    """Имя события для инструмента: точное имя, потом по началу (notes_*)."""
    имя = (инструмент or "").strip().lower()
    if имя in _ДЕЛО_ПО_ИНСТРУМЕНТУ:
        return _ДЕЛО_ПО_ИНСТРУМЕНТУ[имя]
    for кусок, событие in (("notes", "делает_записывает"), ("music", "делает_музыку"),
                           ("radio", "делает_музыку"), ("timer", "делает_таймер"),
                           ("alarm", "делает_таймер"), ("remember", "делает_записывает"),
                           ("drive", "делает_едет"), ("follow", "делает_едет"),
                           ("look", "делает_смотрит")):
        if кусок in имя:
            return событие
    return "делает_что_то"
