class Сценка:
    __slots__ = ("имя", "когда", "длительность", "кадры", "текст", "вес",
                 "цикл", "отдых", "приоритет", "следом", "зеркало")

    def __init__(self, имя: str, когда: str, длительность: float, кадры: list,
                 *, текст: str = "", вес: float = 1.0, цикл: bool = False,
                 отдых: float = 90.0, приоритет: int = 0, следом: str = "",
                 зеркало: bool = False) -> None:
        self.имя, self.когда, self.длительность = имя, когда, float(длительность)
        self.кадры = sorted(кадры, key=lambda к: к[0])
        self.текст, self.вес, self.цикл, self.отдых = текст, вес, цикл, отдых
        # Что играть сразу после этой сценки (цепочка), и идёт ли сценка «в
        # ту сторону», где было последнее событие (зеркалится по _куда).
        self.следом, self.зеркало = следом, зеркало
        # События важнее фонов; звено цепочки наследует вес события.
        self.приоритет = приоритет if приоритет else (
            2 if когда in СОБЫТИЯ or когда == ЦЕПОЧКА else 1)

    def параметры(self, доля: float) -> dict:
        """Параметры в точке 0..1 сценки — плавно между кадрами."""
        доля = max(0.0, min(1.0, доля))
        ключи = set()
        for _, п in self.кадры:
            ключи.update(п)
        итог = {}
        for к in ключи:
            # Ключа в кадре нет — покой: ноль сдвига, а у масштаба покой — единица.
            нейтраль = 1.0 if к == МАСШТАБ else 0.0
            точки = [(д, п.get(к, нейтраль)) for д, п in self.кадры]
            if доля <= точки[0][0]:
                итог[к] = точки[0][1] * (1.0 if точки[0][0] == 0 else доля / точки[0][0])
                continue
            if доля >= точки[-1][0]:
                итог[к] = точки[-1][1]
                continue
            for (д0, з0), (д1, з1) in zip(точки, точки[1:]):
                if д0 <= доля <= д1:
                    ш = 0.0 if д1 == д0 else (доля - д0) / (д1 - д0)
                    ш = 0.5 - 0.5 * math.cos(math.pi * ш)      # мягко в обе стороны
                    итог[к] = з0 + (з1 - з0) * ш
                    break
        return итог


def _с(имя, когда, длит, кадры, **доп) -> Сценка:
    return Сценка(имя, когда, длит, кадры, **доп)


