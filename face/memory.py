"""Память персонажа: файл, который переживает перезапуск, и время без вранья.

ЗАЧЕМ ВООБЩЕ ФАЙЛ. Пока биография персонажа живёт только в процессе,
перезапуск службы — это перерождение. «С добрым утром!» звучит второй раз за
одно утро; сценка, которую он показал минуту назад, снова числится
невиданной; привыкание к ней начинается с нуля. А служба лица
перезапускается чаще, чем кажется со стороны: обновление, вылет SDL,
выдернутый рубильник. Каждый такой раз домовёнок терял всё, что про этот дом
успел узнать, — и потому не узнавал ничего вообще.

ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: ЛИЦО ОБЯЗАНО ПОДНЯТЬСЯ ВСЕГДА. Битый,
недописанный, чужой или просто подсунутый руками файл — это повод начать с
авторских весов, а не повод не показать человеку лицо. Это не осторожность
впрок. Сегодня служба лица уже уходила в цикл перезапусков из-за одного
кривого поля в чужом файле: экран гас и загорался по кругу, а понять почему
можно было только через journalctl, и то зная, куда смотреть. Поэтому ни
одна дорога наружу отсюда не бросает исключений: `прочитать()` на любой беде
отдаёт `{}`, `писать()` на любой беде отдаёт False, и обе пишут о случившемся
в отладочный журнал, а не в лицо человеку.

ЗАПИСЬ АТОМАРНА, И ЭТО НЕ ПЕДАНТИЗМ. Питание у робота рубится рубильником, а
не командой; на выход рассчитывать нельзя. Пишем во временный файл рядом и
переименовываем поверх (`os.replace`) — ядро подменяет файл целиком, и
выдернутое посреди записи питание оставит на месте прошлый файл, а не
половину нового. Тот же приём и по тем же причинам — в
`voice/robot_voice/atlas.py` (карта квартиры копится месяцами, и потерять её
на половине записи было бы обиднее всего).

ВРЕМЯ ХРАНИМ НАСТЕННОЕ, А СЧИТАЕМ МОНОТОННОЕ. Внутри кадра всё живёт на
`time.monotonic()`: он не прыгает, когда сеть подводит часы, и только ему
можно верить в арифметике «сколько прошло». Но в файл монотонное класть
нельзя — после перезагрузки оно начинается заново, и вчерашняя отметка «1500»
означает уже не «полчаса назад», а «через двадцать пять минут после
включения». Поэтому на границе файла стоит пара `в_настенное`/`из_настенного`,
и она же выбрасывает всё, что старше суток или пришло из будущего: такие числа
рождаются не из жизни робота, а из сбитых часов.

Без pygame, без сети, всё время снаружи — как character.py, scenes.py и
lips.py. Значит, проверяется числами.
"""

from __future__ import annotations

import hashlib
import json
import logging
import math
import os
import time
import uuid
from pathlib import Path

log = logging.getLogger(__name__)

# Версия схемы. Меняется, когда меняется СМЫСЛ полей, а не когда добавилось
# новое поле: лишнее поле старый код просто не заметит, а вот поле, которое
# стало значить другое, — это как раз тот случай, когда честнее начать с
# авторских весов, чем притворяться, что мы файл поняли.
ВЕРСИЯ = 1

# Как часто память соглашается лечь на диск. Лицо зовёт `писать()` из главного
# цикла, то есть тридцать раз в секунду, а весь бюджет лица — десятая доля
# ядра (docs/screen.md). Дросселирование здесь, а не у зовущего, нарочно: так
# ни один будущий вызывающий не сможет случайно посадить карту флеш-памяти
# записью на каждый кадр.
ПИСАТЬ_РАЗ_В = 60.0

# Файл биографии. Имя одно на всех, кто её трогает: лицо (face/face.py),
# сценарист (face/scenes.py), ПК (pc/kuzya_pc.py) и разовые скрипты.
ФАЙЛ_СЦЕНАРИСТА = "сценарист.json"

# ЧУЖИЕ ПОЛЯ В ОБЩЕМ ФАЙЛЕ — их надо БЕРЕЧЬ при каждой записи. В файле
# биографии лежит не только снимок сценариста: рядом «зерно» (число, на
# котором стоят все кости ЭТОГО робота, `зерно_робота`) и «праздники»,
# которые хозяин пишет руками. Снимок сценариста про них ничего не знает и
# знать не должен — а запись поверх сносила бы их начисто.
#
# Это не предусмотрительность впрок, а починка. Ровно так и вышло, когда лицо
# начало сохраняться раз в минуту: зерно, рождённое при старте, стиралось
# первой же записью, на следующем запуске рождалось новое — и «характер этого
# домовёнка» менялся каждую минуту работы. То есть ровно то, против чего
# зерно и заведено.
БЕРЕЧЬ = ("зерно", "праздники")

СУТКИ = 24 * 60 * 60.0

# Пределы здравого смысла при чтении. Файл биографии — это килобайты (по
# расчёту волны 4: 295 сценок плюс люди плюс распорядок — меньше 64 КБ), и
# всё, что сильно больше, пришло не от нас. Разбирать мегабайтный JSON в
# момент, когда человек ждёт лица на экране, мы не станем.
ФАЙЛ_НЕ_БОЛЬШЕ = 1 << 20
ПОЛЕЙ_НЕ_БОЛЬШЕ = 100_000


def дом() -> Path:
    """Каталог состояния робота, `~/.robot-ai/`.

    СПРАШИВАЕМ КАЖДЫЙ РАЗ, а не запоминаем при импорте, — по тому же доводу,
    что и `face.py:где_состояние()`. Каталог могут завести после нашего
    старта, переменную окружения — выставить перед запуском службы, а в
    проверках она меняется по нескольку раз за прогон. Один вызов `os.environ`
    стоит меньше, чем один день разбирательства «почему память легла не туда».

    `/run` тут не годится принципиально: это tmpfs, она пуста после каждой
    перезагрузки. Память, которая теряется при выключении, — не память.
    """
    свой = os.environ.get("ROBOT_DATA_DIR") or (Path.home() / ".robot-ai")
    return Path(свой).expanduser()


def _число(что) -> float | None:
    """Конечное число или None. Всё, что пришло из файла, идёт через это.

    `bool` отсекается нарочно: `True` — это `1` для арифметики и «да» для
    человека, и молча посчитать галочку за секунду — ровно тот сорт ошибки,
    который потом ищут неделю.
    """
    if isinstance(что, bool) or not isinstance(что, (int, float)):
        return None
    значение = float(что)
    return значение if math.isfinite(значение) else None


def _числа_здоровы(данные) -> bool:
    """Нет ли в дереве NaN и бесконечностей и не слишком ли оно велико.

    NaN и Infinity — это НЕ мусор из ниоткуда: `json.dump` пишет их молча
    (нестандартным расширением), а `json.load` так же молча читает обратно.
    Одно такое число, попав в вес сценки, отравляет всю выборку: сравнение с
    NaN всегда ложно, и сценарист начинает выбирать не по весам, а по порядку
    в списке — то есть выглядит работающим и не работает.

    Обход стопкой, а не рекурсией: файл мог подсунуть кто угодно, а
    тысяча вложенных списков — это RecursionError в момент подъёма лица.
    """
    стопка = [данные]
    осмотрено = 0
    while стопка:
        узел = стопка.pop()
        осмотрено += 1
        if осмотрено > ПОЛЕЙ_НЕ_БОЛЬШЕ:
            return False
        if isinstance(узел, dict):
            стопка.extend(узел.values())
        elif isinstance(узел, (list, tuple)):
            стопка.extend(узел)
        elif isinstance(узел, float) and not math.isfinite(узел):
            return False
    return True


class Память:
    """Один файл состояния: прочитать целиком, писать не чаще раза в минуту.

    Хранит СЛОВАРЬ — что в нём лежит, знает тот, кто его положил. Здесь
    проверяется только то, что можно проверить, ничего не зная о смысле:
    файл читается, это словарь, схема наша, числа не бредовые. Разбор полей —
    дело `восстановить()` у сценариста, и он тоже обязан ничему не верить.

    ЧАСЫ ЗДЕСЬ МОНОТОННЫЕ и только для дросселирования: «прошла ли минута с
    прошлой записи» — вопрос про длительность, а на настенных часах робота без
    батарейки длительность считать нельзя (см. face/clock.py).
    """

    def __init__(self, файл, версия: int = ВЕРСИЯ,
                 раз_в: float = ПИСАТЬ_РАЗ_В, часы=time.monotonic) -> None:
        self.файл = str(файл)
        self.версия = int(версия)
        self.раз_в = float(раз_в)
        self._часы = часы
        # МИНУС БЕСКОНЕЧНОСТЬ, А НЕ НОЛЬ. Ноль означал бы «писали в момент
        # запуска машины», и на роботе, который поднялся десять секунд назад,
        # первая же попытка сохраниться была бы задушена дросселем: 10 < 60.
        # А первое сохранение — самое важное: до него в файле лежит вчерашнее.
        self._писали = float("-inf")

    # --- чтение ----------------------------------------------------------
    def прочитать(self) -> dict:
        """Что в файле. Любая беда — пустой словарь и ни одного исключения.

        Пустой словарь здесь — это не «ошибка», а «начинаем с авторских
        весов». Разница важна для того, кто зовёт: он НЕ должен разбираться,
        почему память пуста, он должен просто подняться и жить дальше. Лицо
        на экране человеку нужнее, чем вчерашние счётчики.
        """
        try:
            размер = os.path.getsize(self.файл)
            if размер > ФАЙЛ_НЕ_БОЛЬШЕ:
                log.debug("память: %s великоват (%d байт) — не мой",
                          self.файл, размер)
                return {}
            with open(self.файл, encoding="utf-8") as ф:
                данные = json.load(ф)
        except (OSError, ValueError, RecursionError, UnicodeDecodeError):
            # Файла нет (первый запуск), он недописан, в нём не UTF-8 или
            # вложенность на тысячу уровней. Всё это — одно и то же событие:
            # «прошлого нет», и оно штатное.
            log.debug("память: %s не прочитался", self.файл, exc_info=True)
            return {}
        if not isinstance(данные, dict):
            # Список вместо словаря — это чужой файл с тем же именем.
            return {}
        if данные.get("версия") != self.версия:
            # ЧУЖАЯ СХЕМА — НЕ НАША БИОГРАФИЯ. Прочитать её «как получится» и
            # разложить по полям значит поверить числам, которые означают
            # что-то другое: отдых сценки, посчитанный в долях, окажется
            # секундами, и персонаж замолчит на сутки. Молча начать заново
            # честнее — и ровно это спасает лицо от цикла перезапусков.
            log.debug("память: %s версии %r, а я понимаю %d — начну заново",
                      self.файл, данные.get("версия"), self.версия)
            return {}
        # Служебные поля — единственное, что мы тут понимаем сами, и потому
        # единственное, с чего можем спросить. Отрицательная отметка времени
        # записи означает либо испорченный файл, либо часы, ушедшие в минус,
        # — а на ней стоит всё состаривание счётчиков в волне 4.
        когда = _число(данные.get("когда"))
        if когда is None or когда < 0:
            log.debug("память: %s без внятной отметки времени записи", self.файл)
            return {}
        if not _числа_здоровы(данные):
            log.debug("память: %s содержит NaN/бесконечность — не беру", self.файл)
            return {}
        return данные

    # --- запись ----------------------------------------------------------
    def писать(self, данные: dict, принудительно: bool = False) -> bool:
        """Сохранить словарь. True — легло на диск, False — не в этот раз.

        ЗАЧЕМ ВРЕМЕННЫЙ ФАЙЛ И ПЕРЕИМЕНОВАНИЕ. Питание у робота рубится
        рубильником. Если писать прямо в боевой файл, то выдернутый посреди
        `json.dump` шнур оставляет на диске половину JSON — и следующий запуск
        читает её, не находит закрывающей скобки и остаётся без биографии.
        Переименование поверх ядро делает целиком: читатель видит либо старый
        файл, либо новый, и никогда — половину. Цена — один лишний файл на
        доли секунды.

        НОМЕР ПРОЦЕССА В ИМЕНИ ВРЕМЕННОГО. Один и тот же файл трогают лицо,
        прогон жизни и разовые скрипты. С общим именем временного два
        писателя пишут в один и тот же черновик, и первый успевший
        переименовывает ПОЛОВИНУ чужого — то есть ровно ту порчу, от которой
        мы и защищаемся. С номером процесса черновики разные.

        НИ ОДНОГО ИСКЛЮЧЕНИЯ НАРУЖУ. Зовут отсюда из главного цикла лица и из
        `finally` на выходе — мест, где ловить некому. Полный диск, каталог
        только на чтение, файл, подменённый каталогом, объект, который не
        умеет в JSON, — всё это обязано кончаться строкой в отладочном
        журнале и `False`, а не погасшим экраном.
        """
        сейчас = self._часы()
        if not принудительно and сейчас - self._писали < self.раз_в:
            return False
        # ОТМЕТКУ СТАВИМ ДО ПОПЫТКИ, А НЕ ПОСЛЕ УДАЧИ (так же в atlas.py).
        # Ставь её после удачи — и на полном диске каждая неудача открывала бы
        # дроссель заново: лицо пыталось бы сохраниться тридцать раз в секунду
        # и тридцать раз в секунду писало бы в журнал, что не вышло. Беда,
        # мешающая записи, обычно длится минуты, а не миллисекунды, — значит и
        # следующая попытка уместна через минуту.
        self._писали = сейчас
        врем = f"{self.файл}.новый-{os.getpid()}"
        try:
            # Штамп кладём в КОПИЮ: словарь пришёл от сценариста, и тихо
            # дописывать в чужую структуру свои поля — значит однажды
            # обнаружить «версию» среди сценок.
            наружу = dict(данные)
            # Чужие поля — из того, что уже лежит в файле. Читаем только
            # когда и правда пишем (раз в минуту), а не на каждый зов.
            было = self.сырое()
            для_бережения = БЕРЕЧЬ
            for ключ in для_бережения:
                if ключ not in наружу and ключ in было:
                    наружу[ключ] = было[ключ]
            наружу["версия"] = self.версия
            наружу["когда"] = time.time()
            os.makedirs(os.path.dirname(self.файл) or ".", exist_ok=True)
            with open(врем, "w", encoding="utf-8") as ф:
                # allow_nan=False — чтобы НЕ НАПИСАТЬ файл, который сами же
                # завтра откажемся читать. `json.dump` пишет NaN и Infinity
                # молча, нестандартным расширением; такой файл проходит
                # запись, а на следующем запуске бракуется целиком — и
                # биография пропадает без единого слова о причине. Пусть уж
                # запись честно сорвётся сейчас, оставив на месте вчерашнюю.
                json.dump(наружу, ф, ensure_ascii=False, allow_nan=False)
            os.replace(врем, self.файл)
            return True
        except Exception:                                   # noqa: BLE001
            log.debug("память: не смог сохранить %s", self.файл, exc_info=True)
            return False
        finally:
            # Черновик остался — значит запись сорвалась на полпути. Убираем
            # сами: иначе рядом с биографией копится по огрызку на каждую
            # неудачу, и однажды кто-нибудь примет огрызок за настоящий файл.
            # (От SIGKILL это не спасает, и врать про это не надо: один
            # черновик на одно убийство процесса на диске останется.)
            try:
                if os.path.exists(врем):
                    os.unlink(врем)
            except OSError:
                pass

    def сырое(self) -> dict:
        """Что в файле, БЕЗ проверки схемы. Только для того, что вне схемы.

        Единственный нынешний потребитель — `зерно_робота()`. Зерно не имеет
        отношения к смыслу полей: это личность робота, и она обязана пережить
        и смену версии схемы, и файл, написанный руками. Читать её через
        `прочитать()` значило бы при любом расхождении версий выдать роботу
        новые кости — то есть другой характер после обновления.
        """
        try:
            if os.path.getsize(self.файл) > ФАЙЛ_НЕ_БОЛЬШЕ:
                return {}
            with open(self.файл, encoding="utf-8") as ф:
                данные = json.load(ф)
        except (OSError, ValueError, RecursionError, UnicodeDecodeError):
            return {}
        return данные if isinstance(данные, dict) else {}


