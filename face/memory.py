# Зерно: чем этот робот отличается от соседнего
# --------------------------------------------------------------------------
def свои_праздники(файл=None) -> dict:
    """«праздники» хозяина из файла биографии: {"ДД-ММ": "что сказать"}.

    ЗАЧЕМ ОТДЕЛЬНО ОТ ПК. Праздники до сих пор жили только в
    `pc/config.local.json` и доезжали до персонажа через компьютер. Значит,
    в день рождения хозяина при выключенном ПК робот молчал — а это ровно тот
    день, когда молчать нельзя. Личное про этот дом обязано жить в самом доме.

    Формат ключа — «ДД-ММ», как на ПК: один формат на два места, чтобы хозяин
    не гадал, где какой. Любая дичь в файле — пустой словарь и ни одного
    исключения: расписание молчит, всё остальное живёт.
    """
    путь = Path(файл) if файл else дом() / ФАЙЛ_СЦЕНАРИСТА
    праздники = Память(путь).сырое().get("праздники")
    if not isinstance(праздники, dict):
        return {}
    свои = {}
    for ключ, текст in праздники.items():
        куски = str(ключ).split("-")
        if len(куски) != 2 or not all(к.strip().isdigit() for к in куски):
            continue
        д, м = int(куски[0]), int(куски[1])
        if 1 <= д <= 31 and 1 <= м <= 12 and str(текст).strip():
            свои[f"{д:02d}-{м:02d}"] = str(текст).strip()
    return свои


def зерно_робота(файл=None) -> int:
    """Число, на котором стоят все кости этого робота. Одно и то же всегда.

    ЗАЧЕМ. Умолчания вроде `random.Random(11)` (scenes.py) и `Random(13)`
    (character.py) держат проверки — их трогать нельзя (Р0.4 плана). Но если
    ИХ же оставить в бою, то все роботы этой сборки будут вести себя посекундно
    одинаково: одинаково моргать, в одном порядке доставать сценки, одинаково
    отводить взгляд. Домовёнок перестаёт быть ЭТИМ домовёнком.

    А если, наоборот, брать зерно из времени запуска, то характер меняется при
    каждом перезапуске службы — и всё, что персонаж делает «по своей привычке»,
    становится случайным шумом.

    Поэтому зерно рождается один раз и ложится в тот же файл, что и остальная
    биография: у одного робота оно одно на всю жизнь, у двух роботов из одного
    образа — разное. `/etc/machine-id` даёт разницу между машинами,
    `time.time_ns()` — между двумя роботами с КЛОНИРОВАННЫМ образом, где
    machine-id совпадает побайтно (а это не редкость: так и разворачивают).

    Зерно кладётся в общий словарь, а не в свой файлик: рядом лежат
    «праздники», которые хозяин пишет руками, и заводить второй файл ради
    одного числа значит однажды потерять их вместе.
    """
    путь = Path(файл) if файл else дом() / ФАЙЛ_СЦЕНАРИСТА
    было = Память(путь).сырое()
    зерно = было.get("зерно")
    if isinstance(зерно, int) and not isinstance(зерно, bool) and 0 < зерно < (1 << 64):
        return int(зерно)
    зерно = _новое_зерно()
    было["зерно"] = зерно
    # ВЕРСИЮ ЧУЖОГО ФАЙЛА СОХРАНЯЕМ, а не подменяем своей. Файл мог остаться
    # от сборки поновее (откатили обновление) — тогда его поля означают не то,
    # что мы думаем, и штамповать их своим номером значит подсунуть будущему
    # себе враньё. Мы дописываем в файл ОДНО поле, которое ни от какой схемы не
    # зависит, и оставляем всё остальное ровно таким, каким нашли.
    чужая = было.get("версия")
    своя = чужая if isinstance(чужая, int) and not isinstance(чужая, bool) else ВЕРСИЯ
    Память(путь, версия=своя).писать(было, принудительно=True)
    return зерно


def _новое_зерно() -> int:
    """64 бита из того, что отличает эту машину, и из того, что отличает миг."""
    сырьё = ""
    try:
        сырьё = Path("/etc/machine-id").read_text(encoding="utf-8").strip()
    except OSError:
        pass
    if not сырьё:
        # Не Linux или machine-id ещё не заведён (первая загрузка образа).
        # MAC-адрес хуже — он может смениться, — но он есть всегда.
        сырьё = str(uuid.getnode())
    смесь = f"{сырьё}:{time.time_ns()}"
    return int(hashlib.sha256(смесь.encode("utf-8")).hexdigest()[:16], 16)


