def в_настенное(t, значение, сейчас) -> float | None:
    """Монотонную отметку — в настенную, для записи в файл.

    `t` — монотонные часы ПРЯМО СЕЙЧАС, `значение` — монотонная отметка,
    которую хотим сохранить, `сейчас` — настенные часы прямо сейчас.

    Считаем не «сколько было на часах», а СКОЛЬКО ПРОШЛО: возраст отметки —
    единственное, что переживает перезагрузку. Отсюда и проверки: возраст
    меньше нуля означает отметку из будущего (её поставили не мы, а сбитые
    часы), больше суток — что она пережила ночь и уже ничего не значит ни для
    отдыха сценки, ни для привыкания. И то и другое честнее выбросить: None
    здесь читается как «этой отметки не было», и сценарист начнёт с чистого.
    """
    t, значение, сейчас = _число(t), _число(значение), _число(сейчас)
    if t is None or значение is None or сейчас is None:
        return None
    возраст = t - значение
    if возраст < 0 or возраст > СУТКИ:
        return None
    return сейчас - возраст


def из_настенного(настенное, t, сейчас) -> float | None:
    """Настенную отметку из файла — обратно в монотонную, для этого запуска.

    `настенное` — то, что лежало в файле, `t` и `сейчас` — монотонные и
    настенные часы этого запуска. Результат вполне может быть отрицательным:
    монотонные часы начинаются с нуля при загрузке, а отметка старше самого
    запуска — это норма, именно ради неё всё и затевалось. Считать
    отрицательное ошибкой и обнулять его значило бы сказать сценаристу
    «сценку показали только что», то есть соврать ровно наоборот.

    Те же две границы, что и на записи, и по той же причине: часы робота без
    батарейки после ночи без сети показывают что угодно (см. face/clock.py),
    и «отметка полугодовой давности» из такого файла — не память, а мусор.
    """
    настенное, t, сейчас = _число(настенное), _число(t), _число(сейчас)
    if настенное is None or t is None or сейчас is None:
        return None
    возраст = сейчас - настенное
    if возраст < 0 or возраст > СУТКИ:
        return None
    return t - возраст


def остыло(значение, было, сейчас, полураспад) -> float:
    """Экспоненциальное забывание: сколько осталось от `значение` к `сейчас`.

    Одна формула на весь проект, и это нарочно. Ею забывается привыкание к
    сценке (полураспад — часы), уровень ласки (минуты) и статистика обучения
    (недели): величины разные, закон один, и спорить о том, «как именно тает»
    в трёх местах по-разному, больше не придётся.

    ЧАСЫ, ПОШЕДШИЕ НАЗАД, НЕ ВОСКРЕШАЮТ. Если `сейчас` меньше `было` (а на
    роботе без батарейки это обычное утро), то формула дала бы множитель
    БОЛЬШЕ единицы — и привыкание, накопленное вчера, выросло бы само собой.
    Отрицательный возраст поэтому считается нулевым: «ничего не прошло».
    """
    значение = _число(значение)
    было, сейчас, полураспад = _число(было), _число(сейчас), _число(полураспад)
    if значение is None:
        return 0.0
    if было is None or сейчас is None or полураспад is None or полураспад <= 0:
        # Нечем считать возраст — отдаём как есть. Забыть то, про что неизвестно,
        # когда оно было, — это выдумать забывание, а не выполнить его.
        return значение
    возраст = max(0.0, сейчас - было)
    return значение * 0.5 ** (возраст / полураспад)
