"""Настроение персонажа: пять осей, два закона затухания и долг сна.

ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ. До сих пор «настроение» у персонажа было строкой:
модель на ПК отвечала словом («рад», «огорчён»), строка доезжала до лица,
лицо меняло брови. Живое существо устроено иначе: настроение — не ярлык, а
величина, которая КОПИТСЯ и ОСТЫВАЕТ, и остывает по-разному в зависимости
от того, где находится. Всплеск радости гаснет за минуту; доверие, которое
росло полгода, не гаснет вовсе; возбуждение из середины держится долго, а с
самого пика падает быстро — потому что на пике организм работает на износ.

Без этого получается прибор с двумя состояниями: либо ровно, либо ярко. А
человек читает как раз промежуточное: вчера тебя погладили, и сегодня он
чуть смелее; ты неделю на него не смотрел, и он присмирел. Ни одного из
этих оттенков строкой не выразить.

ПОЧЕМУ ДВА ЗАКОНА ЗАТУХАНИЯ, А НЕ ОДИН — И ПОЧЕМУ КАЖДОЙ ОСИ СВОЙ.

Оси бывают двух родов, и мерить их одной линейкой нельзя.

ЭПИЗОДЫ — радость, уверенность, общительность. Это вспышки: обрадовался,
побыл радостным, отпустило. Ими правит TimeRatio — «сколько прошло с
последнего толчка». Узлы (0,1) (10,1) (30,0.9) (75,0.6) (150,0): первые
десять секунд величина держится целиком, к двум с половиной минутам сходит
на нет.

УРОВНИ — возбуждение и доверие. Это не вспышка, а тонус: он не «проходит»,
он ПОЛЗЁТ, и скорость зависит от того, с какой высоты. У возбуждения на нуле
скорость 0.6 в минуту (низкое возбуждение неустойчиво, организм возвращается
к рабочему тонусу), на середине 0.12 (рабочий диапазон — самый стабильный),
выше 0.8 — 0.4 (пик держать дорого). У доверия скорость ноль: доверие не
тает от того, что время идёт. Его можно только потерять поступком.

Первая версия применяла ОБА закона ко всем осям сразу, перемножая их каждый
кадр. Получилось вот что: TimeRatio в точке 150 секунд равен нулю, и через
две с половиной минуты после толчка ЛЮБАЯ ось обнулялась начисто — вместе с
доверием, которое копилось полгода, и с возбуждением, которое должно ползти,
а не гаснуть. Прибор показал ноль там, где ожидалась середина. Каждой оси —
свой закон, и только свой.

ПОРОГ 0.05 В `добавить` — ПРЕДОХРАНИТЕЛЬ ОТ ВЕЧНОГО ВОЗБУЖДЕНИЯ. Толчки
приходят каждый кадр и почти все крошечные: человек шевельнулся, пеленг
дрогнул. Если каждый такой шум сбрасывает часы затухания, персонаж не
остынет НИКОГДА — он будет вечно «только что обрадовался». Поэтому часы
сбрасывает лишь заметный толчок (|delta| > 0.05) и лишь тот, который гонит
прочь от нуля: успокаивающий толчок ускоряет возврат, а не продлевает пик.

ЯРЛЫК ПРОВЕРЯЕТ «ТИХО» ПЕРВЫМ — и это тоже предохранитель. Персонаж с
низким возбуждением не должен считаться «живым» только потому, что у него
высокая радость: иначе он лезет к человеку, который его ни о чём не просил.

ДОЛГ СНА. Бодрствование копит долг впятеро быстрее, чем сон его гасит:
восемь часов сна закрывают сорок часов бодрствования, и это примерно
человеческая пропорция. Гистерезис обязателен: засыпать при долге больше
часа, просыпаться при долге меньше получаса. Без него существо на границе
дёргается — засыпает и просыпается каждые несколько секунд, и это худшее,
что можно показать человеку.

Без pygame, без сети, всё время снаружи — как character.py и scenes.py.
Значит, проверяется числами.
"""

from __future__ import annotations

import math
from collections import deque

# --- оси -------------------------------------------------------------------
# Пять осей. У радости, уверенности и общительности диапазон −1..+1: они
# бывают отрицательными (грустно, робко, замкнуто). У возбуждения и доверия —
# 0..1: «отрицательного возбуждения» не бывает, бывает низкое; «отрицательного
# доверия» тоже — бывает нулевое, и это уже очень плохо.
ОСИ = ("радость", "уверенность", "общительность", "возбуждение", "доверие")
ТОЛЬКО_ПОЛОЖИТЕЛЬНЫЕ = ("возбуждение", "доверие")

# Узлы TimeRatio: (секунд с толчка, какая доля величины остаётся).
ВРЕМЯ_УЗЛЫ = ((0.0, 1.0), (10.0, 1.0), (30.0, 0.9), (75.0, 0.6), (150.0, 0.0))

# ValueSlope: с какой скоростью (единиц в минуту) величина сама ползёт к нулю
# на разных высотах. Ключ — ось, значение — узлы (высота, скорость в минуту).
СКОРОСТЬ_УЗЛЫ = {
    "возбуждение": ((0.0, 0.6), (0.2, 0.12), (0.8, 0.12), (1.0, 0.4)),
    "доверие": ((0.0, 0.0), (1.0, 0.0)),
    # ОБЩИТЕЛЬНОСТЬ — ТОЖЕ УРОВЕНЬ, а не вспышка, и это выяснилось замером.
    # Сперва она была эпизодом, и сценарист капал ей вниз за каждую секунду
    # одиночества. За час пустой комнаты она приходила ровно к нулю: закон
    # эпизода возвращает к нулю быстрее, чем капает одиночество, и НИКАКОГО
    # «присмирел за день один» не получалось — величина была, эффекта не
    # было. Уровень с малой скоростью держит снос: капля побеждает возврат,
    # пока не упрётся в равновесие около половины шкалы.
    "общительность": ((0.0, 0.005), (0.5, 0.02), (1.0, 0.06)),
}
# Всем прочим осям — ровная умеренная скорость.
СКОРОСТЬ_ПО_УМОЛЧАНИЮ = 0.15

# Толчок меньше этого не сбрасывает часы затухания (см. шапку).
ЗАМЕТНЫЙ_ТОЛЧОК = 0.05

# Сколько отсчётов держим для `было()` — производная настроения («вдруг
# обрадовался», «сник») читается человеком лучше, чем сама величина.
ПАМЯТЬ_ОТСЧЁТОВ = 256

# --- долг сна --------------------------------------------------------------
ДОЛГ_КОПИТСЯ = 1.0            # часов долга за час бодрствования
ДОЛГ_ГАСНЕТ = 5.0             # часов долга за час сна
ДОЛГ_ПОТОЛОК = 20.0           # выше не растёт: бесконечно сонным не бывают
ЗАСЫПАТЬ_ПРИ = 1.0            # часов долга — порог «клонит в сон»
ПРОСЫПАТЬСЯ_ПРИ = 0.5         # часов долга — порог «выспался»
ЗАСНУВ_ДЕРЖИМ = 50.0 / 60.0   # при засыпании долг поднимаем минимум до этого
НЕ_ЗАСЫПАТЬ_СНОВА = 600.0     # секунд запрета на повторное засыпание

# Суточная кривая бодрости по часу: подъём к 9-11, провал 14-16, спад после
# 22. Узлы (час, множитель бодрости). Это не про сон, а про тонус: в три часа
# дня человек не спит, но и не бодр.
БОДРОСТЬ_ПО_ЧАСАМ = ((0, 0.25), (6, 0.45), (9, 1.0), (11, 1.0), (14, 0.7),
                     (16, 0.7), (19, 0.95), (22, 0.7), (24, 0.25))


def _по_узлам(узлы, x: float) -> float:
    """Кусочно-линейная кривая по узлам. За краями — крайние значения."""
    if x <= узлы[0][0]:
        return узлы[0][1]
    if x >= узлы[-1][0]:
        return узлы[-1][1]
    for (x1, y1), (x2, y2) in zip(узлы, узлы[1:]):
        if x1 <= x <= x2:
            если_ноль = x2 - x1
            if если_ноль <= 0:
                return y2
            доля = (x - x1) / если_ноль
            return y1 + (y2 - y1) * доля
    return узлы[-1][1]


class Настроение:
    """Пять осей, каждая со своими часами затухания.

    Всё время снаружи: `t` — монотонные секунды, как во всём проекте. Класс
    ничего не знает ни про экран, ни про файл; память кладёт его в снимок
    сама (`снимок`/`восстановить`).
    """

    def __init__(self) -> None:
        self._знач = {ось: 0.0 for ось in ОСИ}
        # Доверие начинается не с нуля: незнакомое существо всё-таки
        # подпускает к себе. С нуля начиналось бы «боится всех», а это не
        # исходное состояние, а результат плохой жизни.
        self._знач["доверие"] = 0.3
        self._знач["возбуждение"] = 0.3
        self._толчок_в = {ось: float("-inf") for ось in ОСИ}
        self._считано_до = None
        self._след: deque = deque(maxlen=ПАМЯТЬ_ОТСЧЁТОВ)
        # Долг сна в часах и когда персонаж последний раз заснул.
        self.долг_сна = 0.0
        self._спит = False
        self._заснул_в = float("-inf")

    # --- оси ---------------------------------------------------------------
    def значение(self, ось: str) -> float:
        return self._знач.get(ось, 0.0)

    def добавить(self, ось: str, дельта: float, t: float) -> float:
        """Толчок по оси. Часы затухания сбрасывает только заметный толчок.

        И только тот, что гонит ПРОЧЬ ОТ НУЛЯ: успокоение не должно продлевать
        пик. Иначе получается вечно возбуждённое существо — каждый чих
        начинает отсчёт заново, и остывание не наступает никогда.
        """
        if ось not in self._знач:
            return 0.0
        было = self._знач[ось]
        стало = было + float(дельта)
        низ = 0.0 if ось in ТОЛЬКО_ПОЛОЖИТЕЛЬНЫЕ else -1.0
        стало = max(низ, min(1.0, стало))
        self._знач[ось] = стало
        прочь = abs(стало) > abs(было)
        if abs(дельта) > ЗАМЕТНЫЙ_ТОЛЧОК and прочь:
            self._толчок_в[ось] = t
        return стало

    def остыть(self, t: float) -> None:
        """Прожить до момента t: применить оба закона затухания."""
        если_первый_раз = self._считано_до is None
        прошло = 0.0 if если_первый_раз else max(0.0, t - self._считано_до)
        self._считано_до = t
        для_справки = прошло
        for ось in ОСИ:
            знач = self._знач[ось]
            if знач == 0.0:
                continue
            узлы = СКОРОСТЬ_УЗЛЫ.get(ось)
            if узлы is not None:
                # УРОВЕНЬ (возбуждение, доверие): ValueSlope — ползём к нулю
                # со скоростью, зависящей от высоты.
                скорость = _по_узлам(узлы, abs(знач))
                шаг = скорость * для_справки / 60.0
                знач = max(0.0, знач - шаг) if знач > 0 else min(0.0, знач + шаг)
            else:
                # ЭПИЗОД (радость, уверенность, общительность): TimeRatio.
                # Доля берётся как ОТНОШЕНИЕ к прошлому кадру, а не как
                # множитель на текущее значение: иначе закон применяется по
                # разу за кадр и складывается сам с собой — на тридцати
                # кадрах в секунду эпизод умирает мгновенно, а не за минуту.
                с_толчка = t - self._толчок_в[ось]
                было_с_толчка = с_толчка - для_справки
                if math.isfinite(с_толчка):
                    сейчас_доля = _по_узлам(ВРЕМЯ_УЗЛЫ, с_толчка)
                    было_доля = _по_узлам(ВРЕМЯ_УЗЛЫ, max(0.0, было_с_толчка))
                    знач *= (сейчас_доля / было_доля) if было_доля > 1e-9 else 0.0
                else:
                    шаг = СКОРОСТЬ_ПО_УМОЛЧАНИЮ * для_справки / 60.0
                    знач = max(0.0, знач - шаг) if знач > 0 else min(0.0, знач + шаг)
            self._знач[ось] = знач
        self._след.append((t, dict(self._знач)))

    def было(self, секунд: float, ось: str) -> float | None:
        """Каким была ось столько-то секунд назад. None — не помним так далеко.

        Нужно для реакций на ПРОИЗВОДНУЮ: «вдруг обрадовался» читается
        человеком куда лучше, чем «радостен». Само значение он не видит, а
        перемену видит сразу.
        """
        if not self._след:
            return None
        сейчас = self._след[-1][0]
        цель = сейчас - секунд
        if self._след[0][0] > цель:
            return None
        подходящее = None
        for когда, снимок in self._след:
            if когда <= цель:
                подходящее = снимок
            else:
                break
        return None if подходящее is None else подходящее.get(ось, 0.0)

    def ярлык(self) -> str:
        """Одно слово для тех, кому число не нужно: сценарист, режиссёр, лог.

        «Тихо» проверяется ПЕРВЫМ, и это предохранитель от навязчивости: при
        низком возбуждении персонаж не лезет к человеку, какой бы радостный
        он ни был. Радость без возбуждения — это довольство, а не повод
        стучать по стеклу.
        """
        if self._знач["возбуждение"] <= 0.2:
            return "тихо"
        if self._знач["радость"] <= -0.3:
            return "расстроен"
        if self._знач["возбуждение"] >= 0.6:
            return "живо"
        return "средне"

    # --- сон ---------------------------------------------------------------
    def прожить_сон(self, спит: bool, t: float) -> None:
        """Копить или гасить долг сна. Вызывать раз в кадр."""
        прошло = 0.0 if self._считано_до is None else max(0.0, t - self._считано_до)
        часов = прошло / 3600.0
        if спит:
            self.долг_сна = max(0.0, self.долг_сна - ДОЛГ_ГАСНЕТ * часов)
        else:
            self.долг_сна = min(ДОЛГ_ПОТОЛОК, self.долг_сна + ДОЛГ_КОПИТСЯ * часов)

    def клонит_в_сон(self, t: float) -> bool:
        """Гистерезис: засыпать при долге > часа, просыпаться при < получаса.

        Без гистерезиса существо на границе дёргается — засыпает и
        просыпается каждые несколько секунд. Это худшее, что можно показать:
        не «живой», а «сломанный».
        """
        if self._спит:
            if self.долг_сна < ПРОСЫПАТЬСЯ_ПРИ:
                self._спит = False
            return self._спит
        if self.долг_сна <= ЗАСЫПАТЬ_ПРИ:
            return False
        if t - self._заснул_в < НЕ_ЗАСЫПАТЬ_СНОВА:
            return False
        self._спит = True
        self._заснул_в = t
        # Заснул — значит, поспит хотя бы сколько-то: поднимаем долг так,
        # чтобы порог пробуждения не был достигнут в ту же минуту.
        self.долг_сна = max(self.долг_сна, ЗАСНУВ_ДЕРЖИМ)
        return True

    def бодрость(self, час: int) -> float:
        """0..1: насколько персонаж сейчас в тонусе. Долг сна × суточная кривая."""
        от_долга = max(0.0, 1.0 - self.долг_сна / ДОЛГ_ПОТОЛОК)
        от_часа = _по_узлам(БОДРОСТЬ_ПО_ЧАСАМ, float(час % 24))
        return max(0.0, min(1.0, от_долга * от_часа))

    # --- память ------------------------------------------------------------
    def снимок(self) -> dict:
        """Что кладём в файл. Только числа — ни времени, ни следа."""
        снимок = {ось: round(self._знач[ось], 4) for ось in ОСИ}
        снимок["долг_сна"] = round(self.долг_сна, 4)
        return снимок

    def восстановить(self, д: dict) -> None:
        """Поднять из файла. Любая дичь в файле — не повод падать.

        Файл мог пережить смену версии, кривую правку руками или обрыв
        питания. Лицо обязано подняться всегда: битое поле просто не
        применяем, начиная эту ось с авторского значения.
        """
        if not isinstance(д, dict):
            return
        for ось in ОСИ:
            знач = д.get(ось)
            if isinstance(знач, (int, float)) and math.isfinite(знач):
                низ = 0.0 if ось in ТОЛЬКО_ПОЛОЖИТЕЛЬНЫЕ else -1.0
                self._знач[ось] = max(низ, min(1.0, float(знач)))
        долг = д.get("долг_сна")
        if isinstance(долг, (int, float)) and math.isfinite(долг):
            self.долг_сна = max(0.0, min(ДОЛГ_ПОТОЛОК, float(долг)))
