"""Режиссёр: модель на ПК сама решает, чем человечку заняться.

ЗАЧЕМ. Сценарист (scenes.py) выбирает сценки жребием по весам — честно, но
безразлично к обстановке: ему всё равно, что ребёнок стоит перед экраном
уже минуту и ждёт, что на улице дождь, а человечек только что три раза
подряд зевал. Модель на ПК (та же, что ведёт разговор, pc/kuzya_pc.py) в
покое простаивает — ей не тяжело раз в полминуты взглянуть на обстановку и
сказать, что дальше: «постучи по стеклу, потом помаши, потом спрячься, и
скажи „Иди сюда!“». Так человечек ведёт себя не случайно, а по ситуации
— и каждый раз немного иначе, как живой.

ЧТО МОДЕЛЬ МОЖЕТ, А ЧЕГО НЕТ. Она ВЫБИРАЕТ из готовых сценок и может
ДОБАВИТЬ короткую реплику в пузырь. Она не рисует новых движений и не
трогает параметры: сценки — данные, проверенные числами, и что бы модель
ни ответила, человечек сделает только то, что умеет. Выдуманное имя
выбрасывается, длинная реплика режется, мусор вместо JSON — просто нет
плана, и сценарист живёт жребием, как раньше. Ни одна ошибка модели не
доходит до экрана: это подсказка, не приказ (scenes.задать_план).

КОГДА СПРАШИВАТЬ. Только в покое (не во время речи, поездки, музыки —
там свои фоны), не чаще ПЛАН_РАЗ_В, и когда прошлый план кончился;
раньше — если обстановка переломилась (человек появился или ушёл).
Разговор с человеком важнее: пока модель отвечает роботу, режиссёр не
лезет в очередь (это решает Аватар на ПК, здесь — только «пора ли»).

Чистая логика, как scenes.py и character.py: ни сети, ни часов внутри.
Сеть — у kuzya_pc.py: он берёт запрос(), спрашивает Ollama и отдаёт ответ
в принять(). Значит, проверяется числами и строками.
"""

from __future__ import annotations

import json
import re

ПЛАН_РАЗ_В = 30.0            # секунд между вопросами модели в покое
ПОСЛЕ_ПЕРЕМЕНЫ = 3.0         # человек появился/ушёл — спросить раньше, но не чаще
ПЛАН_ДЛИНА = 4               # сценок в плане, не больше
РЕПЛИКА_НЕ_ДЛИННЕЕ = 28      # знаков в пузыре — длиннее не влезает и не читается
ИМЁН_В_СПИСКЕ = 40           # сколько уместных сценок показывать модели

# Что в пузыре допустимо: буквы, цифры, знаки препинания, нота. Всё прочее
# (смайлики, скобки JSON, кавычки) — вычищается.
_ДОПУСТИМО = re.compile(r"[^0-9A-Za-zА-Яа-яЁё ,.!?…:;\-–—♪]+")


def время_суток(час: int) -> str:
    if 5 <= час < 11:
        return "утро"
    if 11 <= час < 17:
        return "день"
    if 17 <= час < 23:
        return "вечер"
    return "ночь"


def обстановка(с: dict, сценарист, t: float, час: int = 12, минута: int = 0) -> list[str]:
    """Обстановка словами — строками, по одной на факт. Только то, что
    человечек и правда знает (те же поля, что рисует экран)."""
    строки = [f"время: {час:02d}:{минута:02d}, {время_суток(час)}"
              + (", тихие часы (ночь)" if с.get("ночь") else "")]
    if с.get("человек"):
        молчит = сценарист.молчит_рядом(t)
        строки.append("человек: в кадре, "
                      + (f"молчит уже {int(молчит)} с" if молчит >= 3 else "только что появился"))
    else:
        строки.append("человек: никого нет в кадре")
    робот = []
    погода = с.get("погода")
    if isinstance(погода, dict) and погода.get("t") is not None:
        try:
            робот.append(f"на экране карточка погоды: {int(float(погода['t'])):+d}°"
                         + (f", {погода['описание']}" if погода.get("описание") else ""))
        except (TypeError, ValueError):
            робот.append("на экране карточка погоды")
    таймеры = [з for з in (с.get("таймеры") or []) if isinstance(з, dict)]
    if таймеры:
        з = таймеры[0]
        try:
            ост = int(float(з.get("осталось") or 0))
            робот.append(f"идёт таймер «{з.get('имя') or 'таймер'}», осталось {ост // 60}:{ост % 60:02d}")
        except (TypeError, ValueError):
            робот.append("идёт таймер")
    батарея = с.get("батарея")
    if isinstance(батарея, (int, float)) and батарея <= 10.6:
        робот.append("батарея почти села")
    if с.get("подсказка"):
        робот.append(f"внизу подсказка «{с['подсказка']}»")
    строки.append("робот: " + ("; ".join(робот) if робот else "спокоен, ничего не делает"))
    недавние = сценарист.недавние(5)
    if недавние:
        строки.append("уже сыграно недавно (не повторяй): " + ", ".join(недавние))
    return строки


def запрос(с: dict, сценарист, t: float, час: int = 12, минута: int = 0) -> str:
    """Текст вопроса модели. Пусто — сейчас не время (нечего выбирать)."""
    годные = сценарист.годные(с, t, час)
    if not годные:
        return ""
    имена = годные[:ИМЁН_В_СПИСКЕ]
    return (
        "Ты — режиссёр человечка на экране домашнего робота Кузи. На него "
        "смотрят дети и взрослые. Человечек не говорит вслух: он показывает "
        "сценки и иногда пишет коротко в пузыре над головой.\n"
        "Обстановка сейчас:\n- " + "\n- ".join(обстановка(с, сценарист, t, час, минута)) + "\n"
        f"Выбери от 2 до {ПЛАН_ДЛИНА} сценок из списка — только эти имена, слово в "
        "слово, в порядке показа. Пусть выходит живо и по ситуации: если рядом "
        "человек молчит — привлекай его внимание и зови поговорить; если никого "
        "нет — займись своим.\n"
        "Сценки: " + "; ".join(имена) + ".\n"
        f"Можно добавить одну реплику для пузыря — до {РЕПЛИКА_НЕ_ДЛИННЕЕ} знаков, "
        "по-русски, понятную ребёнку, без смайликов и кавычек. Не нужна — оставь "
        "пустой.\n"
        'Ответь только JSON, без пояснений: {"сценки": ["имя", "имя"], "реплика": ""}'
    )


def причесать_реплику(текст) -> str:
    """Реплика в пузырь: без мусора, не длиннее РЕПЛИКА_НЕ_ДЛИННЕЕ, по слову."""
    т = str(текст or "")
    т = _ДОПУСТИМО.sub(" ", т)
    т = " ".join(т.split()).strip(" ,.;:-–—")
    if not т or not re.search(r"[А-Яа-яЁё]", т):
        return ""                                  # не по-русски — не в пузырь
    if len(т) > РЕПЛИКА_НЕ_ДЛИННЕЕ:
        обрез = т[:РЕПЛИКА_НЕ_ДЛИННЕЕ]
        if " " in обрез:
            обрез = обрез.rsplit(" ", 1)[0]
        т = обрез.rstrip(" ,;:-–—") + "…"
    return т


def разобрать(текст: str, годные) -> tuple[list[str], str]:
    """(имена сценок по порядку, реплика) из ответа модели.

    JSON — как просили; не JSON — ищем имена из списка прямо в тексте,
    по порядку появления, а реплике тогда не верим (не отличить от
    рассуждений). Чужих имён не бывает: только из «годные».
    """
    годные = [str(и) for и in (годные or ())]
    известные = set(годные)
    текст = str(текст or "")
    имена: list[str] = []
    реплика = ""
    начало, конец = текст.find("{"), текст.rfind("}")
    данные = None
    if 0 <= начало < конец:
        try:
            данные = json.loads(текст[начало:конец + 1])
        except ValueError:
            данные = None
    if isinstance(данные, dict):
        for имя in данные.get("сценки") or _список(данные.get("scenes")):
            имя = str(имя).strip().lower()
            if имя in известные and имя not in имена:
                имена.append(имя)
        реплика = причесать_реплику(данные.get("реплика") or данные.get("text") or "")
    if not имена:
        # Без JSON: имена, найденные в тексте, по месту первого появления.
        низ = текст.lower()
        найдено = [(низ.find(и), и) for и in годные if и in низ]
        имена = [и for _, и in sorted(найдено) if и not in имена]
        реплика = ""
    return имена[:ПЛАН_ДЛИНА], реплика


def _список(значение) -> list:
    return list(значение) if isinstance(значение, (list, tuple)) else []


class Режиссёр:
    """Когда спрашивать и что делать с ответом. Всё время — снаружи."""

    def __init__(self) -> None:
        self._спросил_в = float("-inf")
        self._человек_был: bool | None = None
        self.вопросов = 0
        self.планов = 0

    def пора(self, с: dict, сценарист, t: float) -> bool:
        """Покой, прошлый план кончился, и срок вышел (или обстановка
        переломилась: человек появился или ушёл)."""
        if (с.get("эмоция", "спокоен") != "спокоен" or с.get("говорит") or с.get("едет")
                or (с.get("музыка") or {}).get("играет")):
            return False
        if сценарист.план:
            return False
        человек = bool(с.get("человек"))
        перелом = self._человек_был is not None and человек != self._человек_был
        прошло = t - self._спросил_в
        return прошло >= ПЛАН_РАЗ_В or (перелом and прошло >= ПОСЛЕ_ПЕРЕМЕНЫ)

    def запрос(self, с: dict, сценарист, t: float, час: int = 12, минута: int = 0) -> str:
        """Вопрос модели; отмечает, что спросили (пусто — не отмечает)."""
        текст = запрос(с, сценарист, t, час, минута)
        if текст:
            self._спросил_в = t
            self._человек_был = bool(с.get("человек"))
            self.вопросов += 1
        return текст

    def принять(self, сценарист, ответ: str, годные=None) -> tuple[list[str], str]:
        """Ответ модели — в план сценариста. Возвращает, что принято."""
        имена, реплика = разобрать(ответ, годные if годные is not None else _все_имена())
        принято = сценарист.задать_план(имена, реплика)
        if принято:
            self.планов += 1
        return принято, (реплика if принято else "")


def _все_имена() -> list[str]:
    """Все имена сценок — когда список годных не передали."""
    import scenes
    return list(scenes.ПО_ИМЕНИ)
