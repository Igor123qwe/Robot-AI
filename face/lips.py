"""Рот по звуку: огибающая громкости речи — одна на робота и на ПК.

Синус вместо рта — честная имитация, но именно имитация: рот хлопает
ровно, пока звучит фраза, и не совпадает ни с одним слогом. Настоящий рот
идёт по громкости того звука, который слышно из динамика. Звук рождается
в двух местах: на ПК (/tts, silero) и на роботе (кэш готовых фраз, свой
piper через Python), — и оба кладут его сюда, в одну и ту же очередь.

ОЧЕРЕДЬ, А НЕ ОДНА ФРАЗА. Робот играет фразы друг за другом по
предложениям, как они синтезировались: начало следующей — не раньше конца
предыдущей. Сдвиг ЗАДЕРЖКА — на дорогу и буфер aplay; точнее без обратной
связи от динамика не выйдет, и сотня миллисекунд на глаз незаметна.

Без pygame, без сети, всё время снаружи — как character.py и scenes.py.
"""

from __future__ import annotations

import array
import math
import threading
import time


class Губы:
    """Очередь фраз со своими огибающими; `рот()` — открытие сейчас, 0..1."""

    ШАГ = 0.02              # секунд на отсчёт огибающей (50 Гц)
    ЗАДЕРЖКА = 0.25         # секунд от синтеза до динамика
    ХВОСТ = 2.0             # секунд — сколько помнить отзвучавшие фразы

    def __init__(self, часы=time.monotonic) -> None:
        self._часы = часы
        self._lock = threading.Lock()
        self._очередь: list[tuple[float, float, list[float]]] = []

    @classmethod
    def огибающая(cls, pcm: bytes, rate: int) -> list[float]:
        """Громкость по окнам, 0..1 относительно самого громкого места фразы.

        Относительно пика фразы, а не абсолютно: тихая фраза тоже должна
        открывать рот, иначе персонаж бормочет с закрытым ртом. Степень < 1
        поднимает тихие места: рот открыт и на безударных, а не только на
        пиках, — иначе речь выглядит как редкие щелчки.
        """
        отсчёты = array.array("h")
        отсчёты.frombytes(pcm[:len(pcm) // 2 * 2])
        окно = max(1, int(rate * cls.ШАГ))
        громкости = []
        try:
            import audioop                      # быстрее в разы; в 3.13 его нет
            for н in range(0, len(отсчёты), окно):
                громкости.append(float(audioop.rms(отсчёты[н:н + окно].tobytes(), 2)))
        except ImportError:
            for н in range(0, len(отсчёты), окно):
                кусок = отсчёты[н:н + окно]
                громкости.append(math.sqrt(sum(x * x for x in кусок) / len(кусок)))
        пик = max(громкости, default=0.0) or 1.0
        return [min(1.0, г / пик) ** 0.6 for г in громкости]

    def добавить(self, pcm: bytes, rate: int) -> None:
        огибающая = self.огибающая(pcm, rate)
        if not огибающая:
            return
        with self._lock:
            сейчас = self._часы()
            конец_прежней = max((к for _, к, _ in self._очередь), default=0.0)
            начало = max(сейчас + self.ЗАДЕРЖКА, конец_прежней)
            self._очередь.append((начало, начало + len(огибающая) * self.ШАГ, огибающая))
            self._очередь = [ф for ф in self._очередь if ф[1] > сейчас - self.ХВОСТ]

    def сбросить(self) -> None:
        """Перебили — всё, что стояло в очереди, уже не прозвучит."""
        with self._lock:
            self._очередь = []

    def рот(self) -> float | None:
        """Открытие рта сейчас, 0..1; None — звука нет, решать по-прежнему."""
        with self._lock:
            сейчас = self._часы()
            for начало, конец, огибающая in self._очередь:
                if начало <= сейчас < конец:
                    return огибающая[min(len(огибающая) - 1,
                                         int((сейчас - начало) / self.ШАГ))]
            if any(начало > сейчас for начало, _, _ in self._очередь):
                return 0.0          # звук уже синтезирован, но ещё не дошёл
            return None
